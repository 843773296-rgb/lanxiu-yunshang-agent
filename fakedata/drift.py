#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""方案漂移 —— **表结构变了,上一份方案里哪几条判断失效了。**

## 为什么要这一层

一份方案是**对着某一天的库**出的:这一列是枚举、那一列是金额、这两张表有关系。
而真实项目每两周就改一次表:加列、改名、拆表、把可空改成必填。

改完之后那份方案**不会报错**,它只是开始造错的数据:

    方案里有的列库里没了      → 灌入当场失败(这种还算好的,**它会吵**)
    库里新增了一个必填列       → 灌入当场失败
    列的类型变了(文本→整数)    → **灌得进去,但造出来的值毫无意义**
    可空改成必填              → 造出来的 NULL 全部违规
    新表新列没进方案           → 悄悄漏造,而「少造了什么」在结果里看不见

**最后三种不吵**,所以要专门去比。

## 比什么:方案里**假设过**的东西

方案没存「当时的 schema 长什么样」,它存的是**生成规则**
(这一列怎么造、断言怎么写、外键指向谁)。而每一条规则背后都有一个假设,
这里就是把这些假设拿出来,和现在的库对一遍。

## 分三档,因为它们要做的事不一样

    致命   灌不进去(列没了 / 表没了 / 新增必填列)          —— 必须改方案才能再灌
    警告   灌得进去但造出来不对(类型变了 / 可空变了 / 断言引用没了)
    提示   新表新列没进方案 —— **漏造不报错**,要人决定要不要补

## 改名只猜,不改

旧列消失 + 新列出现 + 类型一样 → 大概率是改名。但**也可能是删一列加一列**,
两者在 schema 上长得一模一样。所以标成猜,让人看一眼 ——
**自动把方案里的列名改掉,一旦猜错就是把数据造到另一列上去了。**

## 不做什么

- **不自动改方案。** 和行级保护、试灌一个原则:工具给证据,不替人拍板。
- **不比数据,只比结构。** 分布漂移(金额涨了十倍、枚举多了一档)是另一件事,
  那要拿两次的统计摘要比 —— 见 `census.py`。
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

致命, 警告, 提示 = "致命", "警告", "提示"


def _plan_cols(plan, t):
    return set((plan["tables"].get(t) or {}).get("columns") or {})


def _sql_标识符(sql):
    """断言 SQL 里被引号括起来的标识符 —— 方案生成的 SQL 一律加引号,所以抠得干净。"""
    return set(re.findall(r'"([^"]+)"', sql or "")) | set(re.findall(r"`([^`]+)`", sql or ""))


def 对比(plan, sc):
    """把方案里的假设和现在的 schema 对一遍。返回 [{档, 是什么, 在哪, 说明}]。"""
    出 = []
    方案表 = {t for t, tp in plan["tables"].items() if not tp.get("skip")}
    现表 = set(sc.tables)

    for t in sorted(方案表 - 现表):
        出.append({"档": 致命, "是什么": "表没了", "在哪": t,
                   "说明": "方案要往这张表灌,而库里已经没有它了 —— 灌入会当场失败"})

    for t in sorted(方案表 & 现表):
        tb = sc.tables[t]
        现列 = {c.name: c for c in tb.columns}
        方案列 = _plan_cols(plan, t)

        没了 = sorted(方案列 - set(现列))
        新增 = sorted(set(现列) - 方案列)
        for c in 没了:
            # 改名只猜:类型一样的新列里挑一个,标成猜
            g = (plan["tables"][t]["columns"].get(c) or {})
            同类 = [n for n in 新增 if 现列[n].kind == g.get("kind")]
            猜 = f";**疑似改名成 {同类[0]}**(类型一样 —— 但也可能是删一列加一列,两者长得一模一样)" \
                if 同类 else ""
            出.append({"档": 致命, "是什么": "列没了", "在哪": f"{t}.{c}",
                       "说明": f"方案里还在给这一列造值,而库里没有它了 —— 灌入会当场失败{猜}",
                       "猜": 同类[0] if 同类 else None})

        for n in 新增:
            col = 现列[n]
            if not col.nullable and col.default is None and not col.pk:
                出.append({"档": 致命, "是什么": "新增了必填列", "在哪": f"{t}.{n}",
                           "说明": "库里多了一个必填又没默认值的列,而方案不会给它造值 —— 灌入会当场失败"})
            else:
                出.append({"档": 提示, "是什么": "新列没进方案", "在哪": f"{t}.{n}",
                           "说明": "这一列会被留空。**漏造不报错** —— 要不要补由人定"})

        for c in sorted(方案列 & set(现列)):
            g = plan["tables"][t]["columns"].get(c) or {}
            col = 现列[c]
            if g.get("kind") and col.kind != g["kind"]:
                出.append({"档": 警告, "是什么": "类型变了", "在哪": f"{t}.{c}",
                           "说明": f"方案按 {g['kind']} 造,现在是 {col.kind} —— "
                                   f"**灌得进去,但造出来的值没有意义**"})
            if g.get("nullable") is True and not col.nullable:
                出.append({"档": 警告, "是什么": "可空改成了必填", "在哪": f"{t}.{c}",
                           "说明": "方案会按一定比例造 NULL,而现在这一列不许为空"})
            if col.unique and g.get("gen") not in ("pk",) and not g.get("unique"):
                出.append({"档": 警告, "是什么": "多了唯一约束", "在哪": f"{t}.{c}",
                           "说明": "方案不知道它唯一,可能造出重复值 —— 灌到一半失败"})

        现pk = list(tb.pk)
        if 现pk and plan["tables"][t].get("pk") and 现pk != list(plan["tables"][t]["pk"]):
            出.append({"档": 警告, "是什么": "主键变了", "在哪": t,
                       "说明": f"方案按 {plan['tables'][t]['pk']} 记回滚凭据,现在是 {现pk} —— "
                               f"**回滚可能删不干净**"})

    # ⚠️ 差集要拿**方案里提到过的全部表**,不是「没被跳过的那些」。
    # 方案会主动跳过没有主键的表(灌得进去但删不掉),那是**方案知道它、决定不灌**,
    # 不是「方案不知道有这张表」—— 两件事该做的动作完全不同。
    # 第一版拿错了集合,于是每次都把跳过的表报成「新表」,自测当场抓到。
    # 方案当时限定过表集的话,没进方案的表是**人主动没选**,不是漏造。
    # 老方案没记这个字段,就按比例兜底:方案覆盖不到一半的表 —— 那基本只能是限定过。
    # ⚠️ 折叠不是「不报」:仍然报一行,写清有多少张、为什么折叠。
    # **把 65 条噪音摊在人脸上,和不报一样糟** —— 报多了人就不看了。
    新表 = sorted(现表 - set(plan["tables"]))
    限定 = plan.get("限定表集") or (len(plan["tables"]) * 2 < len(现表) or None)
    if 新表 and 限定:
        出.append({"档": 提示, "是什么": "另有表不在方案里", "在哪": f"{len(新表)} 张",
                   "说明": f"这份方案**当时限定过表集**,所以它们是人主动没选的,不是漏造:"
                           f"{新表[:6]}{' …' if len(新表) > 6 else ''}"})
    else:
        for t in 新表:
            出.append({"档": 提示, "是什么": "新表没进方案", "在哪": t,
                       "说明": "方案里根本没有这张表,它不会被造。**漏造不报错**"})

    # 断言:SQL 里写死了表名列名,引用没了就等于这条断言**永远为 0** —— 那是最坏的一种
    for a in plan.get("assertions", []):
        t = a.get("表")
        标识 = _sql_标识符(a.get("sql", ""))
        坏 = []
        if t and t not in 现表:
            坏.append(f"表 {t}")
        else:
            现列名 = {c.name for c in sc.tables[t].columns} if t in 现表 else set()
            坏 += [f"列 {x}" for x in 标识 - 现表 - 现列名
                   if x not in 现列名 and x not in 现表 and re.match(r"^[\w一-龥]+$", x)]
        if 坏:
            出.append({"档": 警告, "是什么": "断言引用没了", "在哪": a.get("名"),
                       "说明": f"这条断言里的 {坏[:3]} 已经不存在 —— "
                               f"**跑起来会报错或恒为 0**,而恒为 0 看起来正好像「没问题」"})
    return 出


def 报告(漂移, log=print):
    """按档分组打印。**没有漂移也要说清楚验了什么** —— 「没扫到」和「没问题」长得一样。"""
    if not 漂移:
        log("✅ 方案和现在的表结构对得上(比的是:表/列是否还在、类型、可空、唯一、主键、断言引用;"
            "**方案主动跳过的表不算漂移**)")
        return 0
    分 = {致命: [], 警告: [], 提示: []}
    for x in 漂移:
        分[x["档"]].append(x)
    for 档 in (致命, 警告, 提示):
        if not 分[档]:
            continue
        记 = {致命: "❌", 警告: "⚠️", 提示: "ℹ️"}[档]
        log(f"\n{记} {档} {len(分[档])} 条")
        for x in 分[档]:
            log(f"   · {x['是什么']}:{x['在哪']}")
            log(f"     {x['说明']}")
    if 分[致命]:
        log("\n**致命那几条不改方案就灌不进去。** 重新出一份方案,或者手改方案里对应的那几列。")
    log("\n⚠️ **工具不自动改方案** —— 列改名和「删一列加一列」在结构上长得一模一样,"
        "猜错就是把数据造到另一列上去。")
    return len(分[致命])
