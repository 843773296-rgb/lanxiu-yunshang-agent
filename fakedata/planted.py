"""种下的规律 —— 造演示数据时**刻意放进去**的结构,登记在这里。

## 为什么要登记

造数据时为了「看起来像真的」,会往里放规律:轻薄丝类更容易坏、冬款冬天卖得好、
M 码卖得最多……这些规律**是假设,不是发现**。

而分析工具不知道这一点。版师的易损分析跑出「轻薄丝类维保率最高」,
这句话在演示时会被当成数据里挖出来的洞见讲出去 —— **而它只是我们自己种的**。
一张「种下的规律」的结论和一张「真的发现」的结论,在报表上长得一模一样。

所以:
  · 每条种下的规律登记在 `种下的` 里:种了什么、强度、在哪、哪种分析会看到它
  · 生成器里对应的代码旁边打标记 `〔种下 S1〕`
  · 分析工具出结论时调 `提醒(维度)`:命中了就带一句「这是演示数据里种下的」
  · 本文件的自检**双向**核对:登记了就得在代码里找得到标记,代码里标了就得登记 ——
    只查一边的话,改了生成器忘了改登记(或反过来),都会安静地漂走

## 强度是编的,方向是常识

登记里的倍数是造数据时拍的(轻薄 ×2.2、刺绣 ×1.6)。方向有依据(行业常识),
**大小没有**。分析跑出来的「轻薄丝类维保率是棉麻的 3.5 倍」里,3.5 这个数没有任何意义。
"""
