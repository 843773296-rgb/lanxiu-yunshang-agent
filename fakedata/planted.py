_标记 = re.compile(r"〔种下 (S\d+)〕")


def 提醒(维度):
    """分析结论命中了种下的规律时,返回要带上的提醒句(没命中返回 [])。

    维度:分析按什么切的,例如「面料」「刺绣」「月份」。随便传个词或一句话都行。
    """
    out = []
    for sid, 规律, 强度, _src, 词, 为什么 in 种下的:
        if any(w in str(维度) for w in 词):
            out.append(f"⚠️ 〔{sid}〕这条规律是**演示数据里种下的**,不是发现:{规律}({强度})。{为什么}")
    return out


def 核对():
    """双向核对:登记 ⇔ 代码里的标记。返回 (问题列表, 找到的标记数)。"""
    问题, 找到 = [], {}
    files = sorted({x[3] for x in 种下的} | {"tools/simulate_sales.py", "tools/order_mix.py",
                                              "tools/grow_customers.py"})
    for f in files:
        p = os.path.join(ROOT, f)
        if not os.path.exists(p):
            问题.append(f"登记里的出处 {f} 不存在")
            continue
        for sid in _标记.findall(open(p, encoding="utf-8").read()):
            找到.setdefault(sid, set()).add(f)
    登记 = {x[0]: x[3] for x in 种下的}
    for sid, f in 登记.items():
        if f not in 找到.get(sid, set()):
            问题.append(f"〔{sid}〕登记在 {f},但那个文件里找不到 `〔种下 {sid}〕` 标记 —— "
                      f"生成器改了而登记没跟上,或者标记被删了")
    for sid, fs in 找到.items():
        if sid not in 登记:
            问题.append(f"{sorted(fs)} 里标了 `〔种下 {sid}〕`,但登记里没有这一条 —— "
                      f"种了新规律没登记,分析工具会把它当成发现")
    return 问题, sum(len(v) for v in 找到.values())


