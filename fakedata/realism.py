"""像不像体检 —— **同一批数据,一个视角能信、另一个不能,而它们长得一模一样。**

## 为什么要这一层

给库存预警造模拟销量那次,数据灌完才发现:

    按**商品**看   4334 行订单摊到 471 个 SKU 上 —— 对的,可售天数算得出来了
    按**客户**看   同一批数据摊到 **27 个客户**上,人均 142 单 ——
                   RFM、生命周期、会员等级看了都会错

**同一批数据,两个出口,一个能信一个不能。** 而在库里,它们长得一模一样:
行数对、外键都指得到、检查全绿。

灌之前没人看得出来,灌之后也没有任何东西会报 —— 除非有人专门去算一下
「每个客户摊几单」。这个模块就是去算那一下。

## 判的是**扇出**,不是「数据真不真」

「像不像」没法笼统地判。能判的是一件很具体的事:
**每个父亲摊到几个孩子,灌完之后有没有变个数量级。**

    每个客户几单 · 每单几行 · 每个 SKU 几条流水 · 每个订单几条工单

一个数量级是**分水岭**:2 倍是数据多了,10 倍是这个视角的画像变了。
按它做的一切判断(分层、评分、生命周期)都会跟着变,而且不会有人发现。

## 期望值从**库里现算**,不从方案里读

方案里也有一份「形状」(哪种父亲带几个孩子),但**拿方案去验方案造出来的数,是同源谬误** ——
造错了,期望值跟着一起错。所以这里一律现算:灌之前拍一次,灌之后再拍一次。

## 不做什么

- **不拦。** 这是一份体检报告,不是闸门。数据像不像、够不够用,是人按用途判断的:
  同一批数据对库存预警足够,对会员分层就不够 —— **而工具不知道你要拿它干什么**。
- **不给「像不像」打总分。** 一个总分会把「商品维度对、客户维度错」抹成一个中间值,
  而那个中间值谁也不能用。报告按**维度**逐条给。
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

# 一个数量级 —— 不是拍脑袋:2 倍是「数据多了」,10 倍是「这个视角的画像变了」
数量级 = 10.0


def _中位(xs):
    if not xs:
        return 0
    s = sorted(xs)
    m = len(s) // 2
    return s[m] if len(s) % 2 else (s[m - 1] + s[m]) / 2


def 扇出(conn, 子表, 外键列, 父表, 父键, cap=200000):
    """每个父亲摊到几个孩子。返回 {父亲数, 有孩子的, 零孩子占比, 中位数, 最大, 平均}。

    **零孩子的那些必须算进去** —— 长尾的形状全在它们身上:
    「一半客户零订单」和「每人两单」的平均数可以一样,而它们完全是两回事。
    """
    try:
        n父 = conn.q(f"select count(*) from {conn.ident(父表)}")[0][0]
        rows = conn.q(f"select {conn.ident(外键列)}, count(*) from {conn.ident(子表)} "
                      f"where {conn.ident(外键列)} is not null "
                      f"group by {conn.ident(外键列)} limit {cap}")
    except Exception as e:
        return {"查不动": str(e)}
    counts = [r[1] for r in rows]
    有孩子 = len(counts)
    return {"父亲数": n父, "有孩子的": 有孩子,
            "零孩子占比": round(1 - 有孩子 / n父, 3) if n父 else None,
            "中位数": _中位(counts), "最大": max(counts) if counts else 0,
            "平均": round(sum(counts) / n父, 2) if n父 else 0}


def 边(plan):
    """方案里所有「子表 → 父表」的边。体检按边做,因为**视角就是边**。"""
    out = []
    for t, tp in plan["tables"].items():
        if tp.get("skip"):
            continue
        for cn, g in tp["columns"].items():
            if g.get("gen") == "fk" and g.get("table") and g.get("table") != t:
                out.append((t, cn, g["table"], g["column"]))
    return out


def 快照(conn, plan):
    """灌之前拍一张:每条边的扇出 + 每张表的行数。"""
    snap = {"边": {}, "行数": {}}
    for t in plan["tables"]:
        try:
            snap["行数"][t] = conn.q(f"select count(*) from {conn.ident(t)}")[0][0]
        except Exception:
            pass
    for 子, 列, 父, 父键 in 边(plan):
        snap["边"][f"{子}.{列} → {父}"] = 扇出(conn, 子, 列, 父, 父键)
    return snap


def _倍(a, b):
    """b 是 a 的几倍。两个都是 0 就算 1 倍(没变)。"""
    if not a:
        return float("inf") if b else 1.0
    return b / a


def 体检(前, 后):
    """对比两张快照,逐个视角给结论。**不给总分。**

    返回 {"维度": [...], "不能信的": [...]}——
    「不能信的」不是「数据错了」,是**这个视角上的画像变了个数量级**。
    """
    出 = {"维度": [], "不能信的": []}
    for k, b in 后["边"].items():
        a = 前["边"].get(k)
        if not a or "查不动" in a or "查不动" in b:
            continue
        倍 = _倍(a["平均"], b["平均"])
        零变化 = None
        if a["零孩子占比"] is not None and b["零孩子占比"] is not None:
            零变化 = round(b["零孩子占比"] - a["零孩子占比"], 3)
        项 = {"视角": k,
              "人均(前→后)": f'{a["平均"]} → {b["平均"]}',
              "倍数": round(倍, 1) if 倍 != float("inf") else "从 0 开始",
              "中位数(前→后)": f'{a["中位数"]} → {b["中位数"]}',
              "零孩子占比(前→后)": f'{a["零孩子占比"]} → {b["零孩子占比"]}'
                                   + (f"({零变化:+})" if 零变化 is not None else ""),
              "父亲数": b["父亲数"]}
        if 倍 == float("inf") or 倍 >= 数量级:
            项["结论"] = (f"⚠️ **这个视角不能信** —— 人均变了 "
                          f"{'一个数量级以上' if 倍 == float('inf') else f'{倍:.0f} 倍'}。"
                          f"按它做的分层/评分/生命周期都会跟着变,而且不会有人发现")
            出["不能信的"].append(项)
        elif 倍 <= 1 / 数量级:
            项["结论"] = "⚠️ 人均掉了一个数量级 —— 父亲多了而孩子没跟上,长尾被冲淡"
            出["不能信的"].append(项)
        else:
            项["结论"] = "看着还行(只说扇出没变数量级,**不代表内容像**)"
        出["维度"].append(项)
    return 出


def 报告(体检结果, log=print):
    log("\n像不像体检(按**视角**逐条给,不给总分 —— 总分会把「这个能用那个不能用」抹平)")
    for x in 体检结果["维度"]:
        log(f'  · {x["视角"]}:人均 {x["人均(前→后)"]}(×{x["倍数"]})· '
            f'中位数 {x["中位数(前→后)"]} · 零孩子 {x["零孩子占比(前→后)"]}')
        log(f'    {x["结论"]}')
    if not 体检结果["维度"]:
        # **空集合上一切成立。** 一个视角都没验到时打「都没变数量级」,
        # 和真的验过一遍长得一模一样 —— 这个项目为「样本量 0 算通过」栽过。
        log("  ❌ **一个视角都没验到** —— 这不叫「像」,这叫没扫到东西。\n"
            "     常见原因:方案限定了表集,父表被排除之后那一列**不再是外键**"
            "(退化成按编号格式造),于是没有边可验。")
        return 体检结果
    if 体检结果["不能信的"]:
        log(f'\n  ❌ **{len(体检结果["不能信的"])} 个视角不能信** —— '
            f'不是数据错了,是这些视角上的画像变了个数量级。'
            f'拿这批数据做那几件事之前,先想清楚。')
    else:
        log("\n  ✅ 每个视角的扇出都没变数量级 —— **但这只说明比例没塌,不说明内容像**")
    return 体检结果
