"""事件与台账 —— **一件事发生之后,另一件事才可能发生。**

## 为什么原来的工具做不了这个

工具原来是**一列一列**造:这一列像日期、那一列像状态、外键指得到。
造出来的每一行单看都正常,但它答不了这类问题:

    这单付款了吗?付了款库存该占住;取消了该释放;发货了在手要减
    这个 SKU 的流水链,最后一条的余额,和库存表上的数对得上吗

**凡是有流水的地方都是这个形状**:库存、积分、余额、押金、工时。
而这类数据错了最难发现 —— **每一行单看都正常**,只有把链接起来算一遍才看得出来。

## 两件事,分开做

    排时间线   先把一条实体的**全部**事件排完,再按「现在」截断 → 状态是**推出来的**
    台账       一个数随事件加加减减,每一行 after = before + 增减,而且接得上上一行

### 为什么顺序不能反

先抽状态、再补时间戳,会造出「付款早于下单」「完成时间在下个月」这种数据 ——
而**它们在单行上完全合法**:格式对、类型对、不早于创建时间。
这个项目为这两样各栽过一次(35/35 条付款早于下单长年没被发现;
量体记录落在 2026-09-17,只有和「今天」比才看得出来)。

先排完整时间线再截断,这两类错**造不出来**:
时间线本身是单调的,而截断点就是「现在」。

## 用在哪

这是给**写专用生成器的人**用的库,不是 plan/load 流程的一部分 ——
哪些事件改变哪个数,是业务语义,工具不替业务决定
(比如库存流水里「发货」不写一行,因为在手和占用各减一样多,可用没变)。

`tools/simulate_sales.py` 就是拿它写的:12 万行库存流水,链 0 处断。
"""
import datetime as dt


# ── 一、时间线 ────────────────────────────────────────────────────────
def 排时间线(起点, 步骤, r, 现在, 中断=None):
    """把一条实体的事件排完,再按「现在」截断。

    步骤:[(事件名, 最短小时, 最长小时), ...] —— 每一步的时长是**相对上一步**的。
    中断:(事件名, 概率, 最短小时, 最长小时) —— 比如「取消」,发生就不再往下走。

    返回 {"到哪一步": 事件名 或 None, "时间": {事件名: datetime}, "中断了": bool}。

    ⚠️ **状态是推出来的,不是先抽再补时间。** 截断点就是「现在」,
    所以「完成时间落在未来」这种数据在这里造不出来。
    """
    t, 时间 = 起点, {}
    if 中断:
        名, p, lo, hi = 中断
        if r.random() < p:
            tc = t + dt.timedelta(hours=r.uniform(lo, hi))
            if tc <= 现在:
                return {"到哪一步": 名, "时间": {名: tc}, "中断了": True}
            # 中断点在未来 → 这一刻它还停在起点那一步,**不是「中断了」**
            return {"到哪一步": None, "时间": {}, "中断了": False}
    到 = None
    for 名, lo, hi in 步骤:
        t = t + dt.timedelta(hours=r.uniform(lo, hi))
        if t > 现在:
            break
        时间[名] = t
        到 = 名
    return {"到哪一步": 到, "时间": 时间, "中断了": False}


def 查时间线(时间, 顺序):
    """时间戳必须按给定顺序单调不减。返回倒挂的那几对(空 = 没问题)。"""
    坏, 上一个 = [], None
    for 名 in 顺序:
        if 名 not in 时间:
            continue
        if 上一个 and 时间[名] < 时间[上一个]:
            坏.append((上一个, 时间[上一个], 名, 时间[名]))
        上一个 = 名
    return 坏


def 查未来(时间, 现在):
    """已经发生的事不能在未来。返回越界的那几个。

    **未来日期在单条记录上完全合法** —— 格式对、类型对、不早于创建时间,
    只有和「今天」比才看得出来。
    """
    return [(k, v) for k, v in 时间.items() if v > 现在]


# ── 二、台账 ──────────────────────────────────────────────────────────
class 台账:
    """一个数随事件加加减减,每一行都带前值和后值。

    **不许出现负数** —— 卖掉比库里还多的件数,是业务上不可能的事;
    真要造这种反例,显式调 `记(..., 允许为负=True)`,而不是让它悄悄发生。
    """

    def __init__(self, 键, 起始=0, 允许为负=False):
        self.键 = 键
        self.余额 = 起始
        self.行 = []
        self.允许为负 = 允许为负

    def 记(self, 时间, 类型, 增减, 凭据="", 备注="", 允许为负=None):
        """记一笔。够不够由调用方先判断 —— **不够时返回 None,不静默改数。**"""
        允许 = self.允许为负 if 允许为负 is None else 允许为负
        新 = self.余额 + 增减
        if 新 < 0 and not 允许:
            return None
        行 = {"键": self.键, "时间": 时间, "类型": 类型, "增减": 增减,
              "前": self.余额, "后": 新, "凭据": 凭据, "备注": 备注}
        self.余额 = 新
        self.行.append(行)
        return 行

    def 够吗(self, n):
        return self.余额 >= n


def 查链(行, 起始=None):
    """一条链的自检。**这是台账唯一真正值钱的东西** —— 每一行单看都正常,只有链起来才看得出。

    查三样:
      · 后 = 前 + 增减      (单行自洽)
      · 前 = 上一行的后     (接得上)
      · 起始对得上          (给了起始值才查)

    返回坏掉的那几行(空 = 这条链是连的)。
    """
    坏, 上一个 = [], 起始
    for i, x in enumerate(行):
        if x["后"] != x["前"] + x["增减"]:
            坏.append({"第几行": i, "毛病": "后 ≠ 前 + 增减", "行": x})
        if 上一个 is not None and x["前"] != 上一个:
            坏.append({"第几行": i, "毛病": f"接不上:上一行的后是 {上一个},这一行的前是 {x['前']}",
                       "行": x})
        上一个 = x["后"]
    return 坏


def 对账(链尾, 表上的数, 说明=""):
    """链尾和表上的数对不对得上。**对不上要说清差多少,不要只说「不一致」。**"""
    if 链尾 == 表上的数:
        return None
    return {"链尾": 链尾, "表上的数": 表上的数, "差": 表上的数 - 链尾,
            "说明": 说明 or "**流水不是这个数的唯一真相来源** —— 要么有事件没记,要么表被直接改过"}
