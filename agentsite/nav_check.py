#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""导航检查 —— **有页面没入口,不会报错,只会没人点得到。**

## 为什么有这条

2026-09-25 用户报「很多功能还缺入口」。查下来:17 个页面里只有 7 个带统一顶栏,
面板 / 任务 / 着装人 / AI 调控中心 / 调试后台 / 实验对比都有页面、导航上没有;
而导航第一项写着「值班台」,点进去却是**智能助手对话页** —— 名字和目标不是一回事。

根因:导航原来是**手写在 _shell.txt 里的一段 HTML**,而且 chat / scheme / workbench /
acceptance **各自又抄了一份**(四份都是 7 项的旧版)。加页面的人不会想起来去改它们,
**而漏改不报错**。

所以这条检查断言三件事:

  ① `PAGES` 里每一条路径,要么挂在顶栏上,要么在「不挂」里**写明为什么**
  ② 顶栏和「不挂」里的路径,都得真的是 `PAGES` 里有的(别囤积死链)
  ③ 导航**只有一个来源**:页面里不许再出现手写的 `<a ... data-p=` 导航项

⚠️ 第 ③ 条是这次的关键。前两条防的是「忘了加入口」,第三条防的是
**「加了入口但加在了第五份拷贝上」** —— 而那种错在本地点一点是发现不了的:
你点的那一页正好是你改过的那一份。
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

咬合 = [
    ("在 PAGES 里加一个页面但不登记进 nav", "每个页面要么挂顶栏、要么写明为什么不挂"),
    ("在某个页面里手写一份导航项(data-p)", "导航只有一个来源"),
    ("给一个已经有顶栏的页面再加一条 <nav class=\"sitenav\">", "每个页面最多一条顶栏"),
    ("在「不挂」里留一条 PAGES 里已经没有的路径", "登记表里没有死链"),
    ("把已经删掉的 /debug 加回顶栏(已移交表清空之后,这条判据差点变成空跑)",
     "工作台顶栏里没有 AI 调控页"),
    ("把一条还在 PAGES 里的路径同时登记进「不挂」和「已移交」",
     "一条路径不会同时在「不挂」和「已移交」两张表里"),
]

FAIL, N = [], [0]


def ck(名, 真, 补=""):
    N[0] += 1
    print(f"  {'✅' if 真 else '❌'} {名}{('  ' + str(补)[:200]) if 补 else ''}")
    if not 真: FAIL.append(名)


def 页面路径(src=None):
    s = src if src is not None else open(os.path.join(HERE, "app.py"), encoding="utf-8").read()
    出 = set(re.findall(r'"(/[a-z]*)":\s*"[\w./]+\.html"', s))
    # /ai/<模块> 那一批由一行 update 生成 —— 它们共用 ai.html,不是独立入口
    return {p for p in 出 if p}


def 导航条数(目录=None):
    """每个页面**恰好一条**顶栏。

    ⚠️ 2026-09-25 用户截图发现:面板页上叠了两条横栏 —— 我上一轮给它盲加了
    `<!--NAV-->`,而它**自带一条**(类名不同、用 `data-s=` 切页内视图),
    所以「手写导航」那条检查没抓到。**检查抓不到它没见过的形状。**
    数「有几条 sitenav」是形状无关的:不管那条是谁加的、长什么样,两条就是两条。
    """
    import os as _o
    d = 目录 or _o.path.join(HERE, "web")
    出 = {}
    for f in sorted(_o.listdir(d)):
        if not f.endswith(".html"): continue
        n = open(_o.path.join(d, f), encoding="utf-8").read().count('class="sitenav"')
        if n > 1: 出[f] = n
    return 出


def 手写导航的页面(目录=None):
    d = 目录 or os.path.join(HERE, "web")
    出 = {}
    for f in sorted(os.listdir(d)):
        if not f.endswith(".html"): continue
        t = open(os.path.join(d, f), encoding="utf-8").read()
        n = len(re.findall(r'<a\s[^>]*data-p=', t))
        if n: 出[f] = n
    return 出


def 跑(src=None, 目录=None):
    import nav
    页 = 页面路径(src)
    ck("扫到了页面清单", len(页) >= 10, f"{len(页)} 个:{' '.join(sorted(页))}")
    漏 = sorted(页 - nav.全部登记的())
    ck("每个页面要么挂顶栏、要么写明为什么不挂", not 漏,
       f"没登记的:{漏} —— **有页面没入口不会报错,只会没人点得到**" if 漏 else
       f"顶栏 {len(nav.顶栏)} 项、明确不挂 {len(nav.不挂)} 项")
    死 = sorted(nav.全部登记的() - 页)
    ck("登记表里没有死链", not 死, f"登记了但 PAGES 里没有:{死}" if 死 else "")
    # 顶栏项的名字不许和它指的页面对不上 —— 这次那个 bug 就是「值班台」指向对话页
    对 = dict((a, b) for a, b, _ in nav.顶栏)
    ck("顶栏第一项是对话页(而不是别的页顶着「值班台」的名字)",
       对.get("/") == "对话", 对.get("/"))
    多 = 导航条数(目录)
    ck("每个页面最多一条顶栏(别叠两条)", not 多,
       f"叠了两条的:{多} —— 用户 2026-09-25 截图发现的,而「手写导航」那条检查抓不到它"
       if 多 else "没有页面叠两条")
    手 = 手写导航的页面(目录)
    ck("导航只有一个来源(页面里没有手写的导航项)", not 手,
       f"这些页面里还有手写导航:{手} —— **加了入口却加在第五份拷贝上,本地点一点发现不了**"
       if 手 else "16 个页面共用 nav.py 那一份")
    for k in nav.不挂:
        if not (nav.不挂[k] or "").strip():
            ck(f"「不挂」{k} 写了理由", False, "不挂是决定,不是遗漏 —— 写下来才分得开")
    # ── 2026-09-27:**工作台不涉及 AI 调控** ────────────────────────
    #
    # 用户原话:「工作台改为只面向非开发工作人员,完成业务任务,不涉及 ai 调控」。
    # 手改一次顶栏挡不住下一次 —— 下周有人加一个调参页,他不会想起这条规矩。
    # 所以判据落在这儿:**已移交的路径不许再出现在顶栏上**。
    # ⚠️ **2026-09-28:这条判据差点在删页面那天变成空跑。**
    # 原来它只比 `已移交管理后台`,而那张表在六页删完之后**清空了** ——
    # 空集和任何集合的交集都是空,于是**这条守卫从此不可能红**,
    # 而它在清单上仍然是一行 ✅。
    #
    # > 空跑的守卫比没有守卫更糟:没有的时候人知道没有,
    # > 空跑的时候清单告诉你它在看着。
    #
    # 修法是把**删掉的**那张表也算进来:六页搬走之后,「不许回流」这件事
    # 没有随着删除而消失 —— 反而更要紧了(页面文件都没了,加回顶栏是条死链)。
    # 所以判据钉的是「**这些路径不许出现在顶栏上**」,而不是「某张表里的不许」。
    不许上顶栏 = set(nav.已移交管理后台) | set(nav.删掉的)
    顶 = {路 for 路, _, _ in nav.顶栏}
    回流 = sorted(顶 & 不许上顶栏)
    ck("**工作台顶栏里没有 AI 调控页**(已移交 / 已删掉的都不许回流)", not 回流,
       f"这几个又回到顶栏了:{回流} —— AI 调控在 `管理后台/`,"
       f"工作台只面向非开发人员(用户 2026-09-27)" if 回流 else
       f"顶栏 {len(顶)} 项全是业务;盯着 {len(不许上顶栏)} 条不许回流的路径"
       f"(已移交 {len(nav.已移交管理后台)} + 已删 {len(nav.删掉的)})")
    无理由 = [k for k, v in nav.已移交管理后台.items() if not (v or "").strip()]
    ck("每条已移交的都写了它是什么", not 无理由, 无理由 or
       "**这张表不空就说明搬家还没做完** —— 管理后台接完一件,这里删一条")
    # ⚠️ **一条路径只能有一个归属。** 2026-09-27 踩过:`/debug` `/experiments`
    # 待在 `不挂` 里,理由写的是「从 /ai 进」—— 而 /ai 已经搬走了。
    # 于是「`已移交管理后台` 清空 = 搬家做完」这句话是**假的**:
    # 表清空那天,这两页还留在工作台,而完成判据会宣布搬完了。
    # 光把它们挪过去只修了这一次;**同时在两张表里**这个形状本身要挡住,
    # 否则下一条漏项还是会以同样的方式漏 —— 两处理由各自演化,而漂了不报错。
    双登记 = sorted(set(nav.不挂) & set(nav.已移交管理后台))
    ck("一条路径不会同时在「不挂」和「已移交」两张表里", not 双登记,
       f"这几条两边都登记了:{双登记} —— **两处理由会各自演化**,"
       f"而「已移交清空 = 搬完」那个判据会漏掉它们" if 双登记 else
       f"不挂 {len(nav.不挂)} 项、已移交 {len(nav.已移交管理后台)} 项,不重叠")


def _自测():
    print("\n咬合:改坏了要红\n" + "-" * 80)
    import tempfile, nav
    过 = []
    def 咬(名, 跑法, 应红):
        FAIL.clear(); N[0] = 0
        跑法()
        中 = any(应红 in f for f in FAIL)
        过.append(中)
        print(f"  {'✅' if 中 else '❌'} 咬合「{名}」→ {FAIL or '全绿'}")

    # ① 多一个没登记的页面
    咬("PAGES 里多一个没登记的页面",
       lambda: 跑(src='PAGES = {"/": "station.html", "/zzz": "zzz.html"}\n' * 1 + 'x="/duty": "duty.html"'),
       "每个页面要么挂顶栏、要么写明为什么不挂")
    # ② 某个页面里手写导航
    d = tempfile.mkdtemp()
    open(os.path.join(d, "x.html"), "w", encoding="utf-8").write('<a href="/duty" data-p="/duty">值班台</a>')
    咬("某个页面里手写一份导航项", lambda: 跑(目录=d), "导航只有一个来源")
    # ③ 一条路径同时进两张表 —— **这正是 /debug 当时的形状**
    # ⚠️ 原来这条是往「不挂」里塞 `/ai`(那时它在「已移交」里)。2026-09-28
    # 六页删完、`已移交` 清空之后,这个改法红的**不再是点名那一条** ——
    # `/ai` 已经哪张表都不在了,塞进「不挂」只会变成一条死链。
    # **改坏了仍然红,但红的不是指定那一条 —— 这一关不算过。**
    # 换成拿一条**还在 PAGES 里**的路径(/tasks 本来就在「不挂」),
    # 把它也塞进「已移交」:两张表都在、而且不是死链,
    # 于是只有「同时在两张表里」那一条会红。
    原 = dict(nav.已移交管理后台)
    nav.已移交管理后台["/tasks"] = "任务列表 —— 假装它也移交了"
    咬("把 /tasks 同时登记进「不挂」和「已移交」", lambda: 跑(),
       "一条路径不会同时在「不挂」和「已移交」两张表里")
    nav.已移交管理后台.clear(); nav.已移交管理后台.update(原)
    # ④ **守卫别空跑**:把一条已删的路径加回顶栏,「不许回流」那条必须红。
    # 这一条是 09-28 新加的 —— 那天 `已移交` 清空,原来那条判据变成了恒真。
    原顶 = list(nav.顶栏)
    nav.顶栏.append(("/debug", "调试后台", "假装有人把它加回顶栏了"))
    咬("把已经删掉的 /debug 加回顶栏", lambda: 跑(),
       "工作台顶栏里没有 AI 调控页")
    nav.顶栏.clear(); nav.顶栏.extend(原顶)
    FAIL.clear()
    print(f"\n{'✅' if all(过) else '❌'} 咬合 {sum(过)}/{len(过)} 条如预期")
    return 0 if all(过) else 1


if __name__ == "__main__":
    print("导航 · 每个页面都有入口,而且入口只有一个来源")
    print("=" * 84)
    跑()
    坏 = list(FAIL)
    rc = _自测()
    print()
    if 坏 or rc:
        print(f"\033[31m❌ 导航 {len(坏)} 处不符合预期(验了 {N[0]} 条)\033[0m")
        for f in 坏: print(f"   · {f}")
        sys.exit(1)
    print(f"\033[32m✅ 导航全过\033[0m —— 页面都有入口,入口只有一份")
