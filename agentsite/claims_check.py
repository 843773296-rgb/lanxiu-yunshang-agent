    ("分组维度(门店号)也当记录键", "「6 条(本店 SH909)」—— 门店号落在每一条上,不当记录键,不判冲突"),
    ("串里的数不看单位", "「闲置 17 天」顶不上记录里的「17 个测量项」"),
    ("日期里的数字也算数", "「闲置 9 天」顶不上记录里日期「2026-09-20」的 09"),
