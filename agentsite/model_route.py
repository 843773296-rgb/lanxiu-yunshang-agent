# -*- coding: utf-8 -*-
"""聊天站的难题分流:**简单题 Haiku 5.5 答,难题才调 Opus 5.5**(用户 2026-10-25 拍;按事情类型那半已撤,见下)。

算法(纯函数,不碰模型、不碰库;app.py 的 /run 照着它接线,model_route_check.py 逐条真调它):
  ① 分流只在「用的是网站默认模型、而且页面没手动选过模型」时开 —— 手选的模型优先,原样跑,不分流。
  ※ 不按事情类型分(用户 10-25 改口:「先不做意图分类,所有意图分类交给 harness 统一调配」)——
     原来那份「判断类技能名单 → 直接上 Opus」就是一次手写的意图分类,已拆掉;这里只看**结果出没出问题**。
  ② 出问题就升级:Haiku 答完了,但交付前检查「未通过 / 不完整」、有工具报错且它自己没纠正过来(同一个工具到最后都没调成功)、或者整遍跑崩了 → 换 Opus 重答。
     **换模型救不了的不升级**:环境故障(锁库、库连不上)和撞了花费上限。
  ③ 只升级一次:Opus 那一遍不管结果如何都直接交,不再循环。
  ④ 每条回答记下谁答的、为什么升级(根 span 属性 lanxiu.route.* + 返回值 `路由`),页面元信息里显示。

成本按上线 API 实价:Haiku 5.5 一轮通常不到 1 美分,Opus 5.5 一轮约 0.3–0.6 美元;被升级的那轮两边都付。
"""

升级到 = "claude:claude-opus-5-5"


def 分流开着吗(用的模型, 手选了, 默认):
    """①:只有「用的就是网站默认、页面没手选过」才分流。默认本身就是 Opus 时没什么可升的。"""
    return (not 手选了) and 用的模型 == 默认 and 默认 != 升级到


def 没纠正的报错(失败, 成功):
    """报过错、而且这一轮**到最后都没调成功过**的工具(去重、按先后)。
    用户 10-25 拍「它没自己纠正才升级」:实测 Haiku 常在拿到工具说明之前先猜参数名(fabric / query),
    被拒后取了说明、重调成功、答案是对的 —— 按「有报错就升级」那一轮多花了 20 倍。
    判据是「同一个工具后来调成功过」,不看报错次数:次数说明不了它最后取没取到数。"""
    好 = {str(t).rsplit("__", 1)[-1] for t in (成功 or [])}
    out = []
    for t in 失败 or []:
        n = str(t).rsplit("__", 1)[-1]
        if n not in 好 and n not in out:
            out.append(n)
    return out


def 该升级吗(r=None, 异常=None):
    """②:看 Haiku 那一遍的结果,返回 (要不要升级, 理由)。r 是 sdk.run 的返回值。"""
    if 异常:
        return True, f"第一遍中途出错({str(异常)[:80]})"
    r = r or {}
    # 换模型救不了的:库锁了 / 连不上,Opus 来了照样取不到数;撞了花费上限,再跑一遍只会更贵
    if r.get("环境故障"):
        return False, None
    if r.get("budget_hit"):
        return False, None
    状态 = (r.get("交付检查") or {}).get("状态")
    if 状态 in ("未通过", "不完整"):
        return True, f"交付前检查{状态}"
    没纠正 = 没纠正的报错(r.get("工具失败"), r.get("工具成功"))
    if 没纠正:
        return True, f"工具 {'、'.join(没纠正)} 报错后一直没调成功"
    return False, None
