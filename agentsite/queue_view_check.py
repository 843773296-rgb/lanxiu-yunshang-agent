#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""研判队列那一页**不许把四件事压成一个「已销账」**。

    python3 agentsite/queue_view_check.py

库只读,不起服务。

## 这条检查在守什么

用户 2026-10-12 的原话(经转述):页面上不要把「AI 出了结论 / 有人采纳或改判 /
任务升级 / 业务办结」四件事混成一个「已销账」。

而查出来的真相是:**后端早就分开了,是页面把它压回去了。**
`backend/ops.py` 的 `queue()` 返回 `凭什么销账` / `研判有结论` / `工单已关闭`
三个字段(业务 2026-09-28 拍的),它的注释写着:压平之后
「研判过并采纳了」和「工单被关掉但一条研判都没走过」长得一模一样,而后者**要人看一眼**。
**而 `queue.html` 里这三个字段原来的出现次数是 0。**

> **后端把话说清楚了,页面又把它压回去了。**
> 而这种情况比「后端没做」更难发现:**两边分别看都是对的。**

实测库里那一档的构成(所以这不是假想的风险):

    只是关单、没走过研判   158 条   ← 占绝大多数
    研判采纳                36 条
    研判升级                 5 条

## 判据守三样

1. **后端还在分开报** —— `queue()` 的返回里那三个字段都在。
   少了哪个,页面就没得分;而页面会**退回显示「已销账」而不报错**。
2. **页面真的在用它们** —— 不只是「有那个字段」,而是 `queue.html` 里读得到。
3. **提示分成功 / 失败两种样式,而且有一条失败就不出成功样式** ——
   原来批量跑完那一句是「研判 3 条,失败 2 条」,两件事写在同一句里。
   > 一个「全跑成了」和一个「跑了一半」,**在那一句话里长得一模一样。**

## 不验的

**不验页面长什么样**(颜色、位置)—— 那要真起浏览器。
这里验的是「分类逻辑在真实数据上分得开」和「那几个字段真的被读了」。
⚠️ 所以它**挡不住**「字段读了但显示成同一个样子」—— 那一步要靠人看一眼页面。
"""
import io, json, os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path[:0] = [os.path.join(ROOT, "backend"), os.path.join(ROOT, "knowledge"), ROOT]
import ops

G, R, Y, D = "\033[32m", "\033[31m", "\033[33m", "\033[0m"
bad, n = [], 0

# ⚠️⚠️ **这三条里有两条,第一次咬合时「改坏了却没红」** —— 而那一次很有用:
# 它证明了我最初那两条判据只查「字符串在不在文件里」,
# 于是把分支改成走不到(`else if(false)`、第一行一律 return)之后,
# **字符串都还在,判据照样绿**。
# > 一个「写了但永远到不了」的分支,和一个真的分支,
# > **在「字符串在不在文件里」上长得一模一样。**
# 修法不是再加一个字符串匹配,是**把判定抽成纯函数、判据真的调它**(见 ⑤ 那一段)。
咬合 = [
    ("把 queue.html 的 销账标() 改成一律返回「已销账」(四件事又压成一个)",
     "它在真实数据上吐出 **≥3 种**不同的结果"),
    ("把 backend/ops.queue 里的 凭什么销账 那几个字段去掉",
     "后端还在把销账来源分开报"),
    ("把 批量提示文() 的失败分支改成走不到(有失败也返回成功那一句)",
     "**有 2 条失败 → bad,不是 ok**"),
]

页 = os.path.join(HERE, "web", "queue.html")


def ck(名, ok, 说明=""):
    global n
    n += 1
    print(f"  {G + '✅' + D if ok else R + '❌' + D} {名}" + ("" if ok else f"  —— {说明}"))
    if not ok:
        bad.append(名)


# ── 把 queue.html 里的**纯函数**抽出来,用 node 真跑一遍 ──────────────────
#
# ⚠️⚠️ **这是这条检查最要紧的一段,而它是被咬合逼出来的。**
# 第一版判据查的是「文件里有没有 `shut` / 有没有『全部跑出来了』这几个字」。
# 咬合把 `销账标()` 的第一行改成一律返回「已销账」、把失败那一支改成 `else if(false)`
# —— **两处字符串都还在,判据照样绿**。
# > 一个「写了但永远到不了」的分支,和一个真的分支,
# > **在「字符串在不在文件里」上长得一模一样。**
#
# 修法不是再加一个字符串匹配(那是「往词表里加第 N 个词」那条路),
# 是**真的调它** —— 抽出函数源码,拿真实数据 / 构造的入参跑,看它吐出什么。
def 跑JS(函数名们, 代码):
    """把 queue.html 里几个函数抽出来,接上 `代码` 用 node 跑,返回 stdout。"""
    片 = ['const esc=s=>(s??"").toString();']
    for 名 in 函数名们:
        m = re.search(r"function %s\(.*?\n\}" % re.escape(名), s, re.S)
        if not m:
            return None, f"抽不到函数 {名}"
        片.append(m.group(0))
    片.append(代码)
    f = os.path.join(tempfile.mkdtemp(prefix="qv-"), "t.js")
    io.open(f, "w", encoding="utf-8").write("\n".join(片))
    r = subprocess.run(["node", f], capture_output=True, text=True)
    return (r.stdout.strip(), r.stderr.strip())


print("研判队列那一页 · 不许把四件事压成一个「已销账」")
s = io.open(页, encoding="utf-8").read()

# ── ① 后端还在分开报 ───────────────────────────────────────────────────
print("\n① 后端还在把销账来源分开报(页面的分类全靠这几个字段)")
行们 = ops.queue(None)
ck(f"样本量:队列 {len(行们)} 条(0 条的话下面全是空集合上的真)", len(行们) >= 20,
   f"只有 {len(行们)} 条")
需要 = ("凭什么销账", "研判有结论", "工单已关闭", "done", "state")
缺 = [k for k in 需要 if 行们 and k not in 行们[0]]
ck("后端还在把销账来源分开报(" + " / ".join(需要) + ")", not 缺,
   f"少了 {缺} —— 少了哪个,页面就**退回显示「已销账」而不报错**")
已销 = [x for x in 行们 if x["done"]]
ck(f"样本量:已销账 {len(已销)} 条", len(已销) >= 10, f"只有 {len(已销)} 条")
来源 = {}
for x in 已销:
    来源[x["凭什么销账"]] = 来源.get(x["凭什么销账"], 0) + 1
for k in sorted(来源, key=lambda a: -来源[a]):
    print(f"    {k}:{来源[k]} 条")
ck("已销账里**至少两种来源**(只有一种的话「分开」这件事验不到)", len(来源) >= 2,
   f"只有 {len(来源)} 种:{list(来源)}")
只关单 = [x for x in 已销 if not x["研判有结论"]]
ck(f"「只是关单、没走过研判」确实有样本({len(只关单)} 条)—— 它是最该被看见的那一种",
   len(只关单) >= 1,
   "一条都没有的话,页面上那个警示色永远不出现,而它配得对不对验不到")

# ── ② 页面真的在用那几个字段 ───────────────────────────────────────────
print("\n② 页面真的在读它们(不是「后端有」就算)")
for k in ("研判有结论", "工单已关闭", "凭什么销账"):
    ck(f"queue.html 里读到了 `{k}`", k in s,
       "后端分开报了而页面没读 —— **两边分别看都是对的**,只有合起来才看出压平了")
ck("有一个专门把来源分开的函数(不是在模板里散着拼)", "function 销账标" in s)
ck(".tag.shut 这个样式类定义了(没定义的话那个警示色不存在)", ".tag.shut" in s)
ck("表头多了「怎么销的」这一列(光有逻辑没有列,页面上看不见)", "怎么销的" in s)

# ── ③ 分类逻辑在真实数据上分得开 ───────────────────────────────────────
print("\n③ 分类逻辑在真实数据上分得开")
# 不起浏览器 —— 把 `销账标` 的判定照抄一份是**第二份实现**(同源谬误的反面:
# 两份实现会各自漂)。所以这儿**按它依赖的那几个字段算分组**,
# 验的是「这几个字段足以把四种分开」,而不是「我的复制品算得对」。
组 = {}
for x in 行们:
    if not x["done"]:
        k = "还没销账"
    elif x["研判有结论"] and x["工单已关闭"]:
        k = "研判有结论·已关单"
    elif x["研判有结论"]:
        k = "研判有结论"
    else:
        k = "只是关单·没研判"
    组[k] = 组.get(k, 0) + 1
for k in sorted(组, key=lambda a: -组[a]):
    print(f"    {k}:{组[k]} 条")
ck("「只是关单、没走过研判」和「研判有结论」分得开(两边都有样本)",
   组.get("只是关单·没研判", 0) >= 1
   and (组.get("研判有结论", 0) + 组.get("研判有结论·已关单", 0)) >= 1,
   str(组))
ck("分出来的组数 ≥3(只分出一组等于没分)", len(组) >= 3, str(组))

# ── ④ 有一条失败就不出成功样式 ─────────────────────────────────────────
print("\n④ 提示:有一条失败就不出成功样式")
ck("有一个统一的提示函数(原来是三处各自 textContent)", "function 提示" in s)
ck("提示带级别(ok / bad),不是只有一段文字",
   '"bad"' in s and '"ok"' in s and ".note.bad" in s and ".note.ok" in s)
# 要害:批量那一路必须**按 failed 的条数**分支,不能把两件事写在同一句
# ⚠️ 这一条原来查的是 onclick 里那几行的写法(`挂 = (r.failed||[])`)——
# 而那段判定**后来抽成了纯函数**,写法一变这条判据就过期了,
# 它报的是「没按条数分支」,而实际上分支做得更好了。
# > **一条贴着实现写法的判据,会在实现变好的时候报红。**
# 现在只验一件结构上的事:**判定不许写在 onclick 里面** ——
# 写在里面的判定判据调不到它,而调不到就只能回去查字符串(上面那段的教训)。
ck("「出哪句提示」是一个纯函数,不写在 onclick 里面(写在里面判据调不到它)",
   "function 批量提示文" in s and "批量提示文(r, 跑了, state)" in s,
   "抽出来才验得到 —— 这是上面 ⑤ 那一段能成立的前提")
ck("有失败时点名是哪几条(光说「失败 2 条」没法查)",
   "task_id" in s and "没跑出来" in s)
# ── ⑤ **真的调那两个纯函数** —— 字符串在不在,证明不了分支走不走得到 ────
print("\n⑤ 真的调它们(字符串在不在,证明不了分支走不走得到)")
_行 = [{k: v for k, v in x.items()
        if k in ("done", "研判有结论", "工单已关闭", "state", "凭什么销账")}
       for x in 行们]
_out, _err = 跑JS(["销账标"], """
const 行 = %s;
const 计 = {};
for (const x of 行) { const t = 销账标(x); 计[t] = (计[t]||0)+1; }
console.log(JSON.stringify(计));
""" % json.dumps(_行, ensure_ascii=False))
ck("销账标() 跑得起来", bool(_out), _err[:160])
if _out:
    _计 = json.loads(_out)
    for k in sorted(_计, key=lambda a: -_计[a]):
        print(f"    {re.sub(r'<[^>]+>', '', k)}:{_计[k]} 条")
    ck("它在真实数据上吐出 **≥3 种**不同的结果(压成一个的话只有 1 种)",
       len(_计) >= 3, f"只有 {len(_计)} 种:{[re.sub(r'<[^>]+>', '', k) for k in _计]}")
    ck("「只是关单、没走过研判」那一类真的带 shut 样式(不是和研判类同色)",
       any("shut" in k for k in _计),
       "一种都没带 shut —— 那个警示色**永远不出现**,而它就是最该被看见的那一类")
    ck("研判有结论的那几类**不带** shut(不然全都是警示色,等于没分)",
       any(("shut" not in k) and ("研判" in k) for k in _计), str(list(_计)))

_out2, _err2 = 跑JS(["批量提示文"], """
const 全好 = 批量提示文({done:[1,2,3], failed:[], cost:0.01}, 3, "待复核");
const 有挂 = 批量提示文({done:[1], failed:[{task_id:"T-9"},{task_id:"T-8"}], cost:0.01}, 1, "待复核");
const 整挂 = 批量提示文({error:"连不上"}, 0, "待复核");
console.log(JSON.stringify({全好, 有挂, 整挂}));
""")
ck("批量提示文() 跑得起来", bool(_out2), _err2[:160])
if _out2:
    _r = json.loads(_out2)
    print(f"    全好 → [{_r['全好']['级']}] {_r['全好']['文'][:46]}")
    print(f"    有挂 → [{_r['有挂']['级']}] {_r['有挂']['文'][:46]}")
    print(f"    整挂 → [{_r['整挂']['级']}] {_r['整挂']['文'][:46]}")
    ck("全部成功 → ok", _r["全好"]["级"] == "ok", str(_r["全好"]))
    ck("**有 2 条失败 → bad,不是 ok**(这一条是整件事的要害)",
       _r["有挂"]["级"] == "bad", str(_r["有挂"]))
    ck("有失败时**不说**「全部跑出来了」",
       "全部跑出来了" not in _r["有挂"]["文"], _r["有挂"]["文"])
    ck("有失败时点名是哪几条(光说「失败 2 条」没法查)",
       "T-9" in _r["有挂"]["文"] or "T-8" in _r["有挂"]["文"], _r["有挂"]["文"])
    ck("整个请求挂了 → bad", _r["整挂"]["级"] == "bad", str(_r["整挂"]))

print()
print(f"{Y}📌 这条检查**不验**页面长什么样(颜色、位置)—— 那要真起浏览器。"
      f"所以它挡不住「字段读了但显示成同一个样子」,那一步要靠人看一眼。{D}")
if bad:
    print(f"{R}❌ {len(bad)} 条不过(验了 {n} 条){D}")
    for x in bad:
        print(f"   · {x}")
    sys.exit(1)
print(f"{G}✅ 四件事在页面上分得开,而且有失败不出成功样式(验了 {n} 条){D}")
