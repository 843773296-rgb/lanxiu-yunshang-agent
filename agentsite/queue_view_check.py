# ── 库况 ≠ 判据 ────────────────────────────────────────────────────────
#
# ⚠️⚠️ **2026-10-13 修:这条检查在 CI 上连红四次,而红的理由和任何人做的事都无关。**
#
# 原来有五条 `ck()` 问的其实是「**这个库里现在有几种销账来源**」——
# 而那个答案取决于 `triage` 表里有没有数据,不取决于页面代码对不对。
# CI 上 `tools/seed_triage_samples.py` 调不动模型(没有凭据,它自己明说了),
# 于是 `triage` 恒空 → 一条「研判有结论」的行都没有 → 页面只分得出一种 → 红。
#
# > **一条判据,如果它红不红取决于环境里碰巧有什么数据,那它不是在验代码。**
#
# 修法不是放宽那五条,是把混在一起的两件事拆开:
#   · **代码对不对** → 判据**自己造**那四种形状去调 `销账标()`(见 ⑤ 第一段)。
#     自造的样本永远在,所以这一组在 CI 和本机都真的验得到。
#   · **这个库上有几种** → 用 `库况()` 打印,**不判红**,并在输出里写明它不是判据。
#
# 而降级是安全的**只因为**自造那一组兜住了代码 —— 所以下面那条守卫是硬的:
# **自造形状必须真的分出四种**,否则红。少了它,这两样一起变成什么都不验。
def 库况(名, 实, 注=""):
    """打印这个库现在长什么样。**不判红** —— 它描述环境,不判定代码。"""
    print(f"  {Y}·{D} 库况(不判红):{名} —— {实}" + (f"  {注}" if 注 else ""))


# ── 把 queue.html 里的**纯函数**抽出来,用 node 真跑一遍 ──────────────────
#
# ⚠️⚠️ **这是这条检查最要紧的一段,而它是被咬合逼出来的。**
# 第一版判据查的是「文件里有没有 `shut` / 有没有『全部跑出来了』这几个字」。
# 咬合把 `销账标()` 的第一行改成一律返回「已销账」、把失败那一支改成 `else if(false)`
# —— **两处字符串都还在,判据照样绿**。
# > 一个「写了但永远到不了」的分支,和一个真的分支,
# > **在「字符串在不在文件里」上长得一模一样。**
#
# 修法不是再加一个字符串匹配(那是「往词表里加第 N 个词」那条路),
# 是**真的调它** —— 抽出函数源码,拿真实数据 / 构造的入参跑,看它吐出什么。
def 跑JS(函数名们, 代码):
    """把 queue.html 里几个函数抽出来,接上 `代码` 用 node 跑,返回 stdout。"""
    片 = ['const esc=s=>(s??"").toString();']
    for 名 in 函数名们:
        m = re.search(r"function %s\(.*?\n\}" % re.escape(名), s, re.S)
        if not m:
            return None, f"抽不到函数 {名}"
        片.append(m.group(0))
    片.append(代码)
    f = os.path.join(tempfile.mkdtemp(prefix="qv-"), "t.js")
    io.open(f, "w", encoding="utf-8").write("\n".join(片))
    r = subprocess.run(["node", f], capture_output=True, text=True)
    return (r.stdout.strip(), r.stderr.strip())


