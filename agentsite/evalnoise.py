"""**一次改动到底读不读得出效果** —— 纯函数,可离线测。

这一段同一天量错四次,四种坏法。其中两次是同一件事:
**把噪声读成了效果**。而我每一次犯的时候都「知道」这条 ——
所以它必须变成结构,不能停在觉悟。

判据只有一句:

    改动组的净变化,要**超过对照组的抖动量**,才谈得上效果。

对照组 = 这期间**一个字都没改**的那些技能的用例。
它们照样在动,那个动的量就是噪声底噪 —— 实测过:
文件没动的 growth-plan,两条用例一涨一跌。

## 为什么不用统计检验

样本太小(15 条用例、3 次重复),做 t 检验只是给一个粗糙判断套个精确的壳。
**用一个自己都不可信的数去算 p 值,比直接说「读不出」更有害** ——
后者会让人再跑几遍,前者会让人相信。
"""


def verdict(changed_fixed, changed_broke, control_fixed, control_broke,
            changed_n=0, control_n=0):
    """给一次对比下判断。

    返回 (能不能读出效果, 一句话)。
    """
    net = changed_fixed - changed_broke                  # 改动组的净变化
    noise = control_fixed + control_broke                # 对照组一共动了几条(不抵消)
    if control_n == 0:
        return None, ("**没有对照组** —— 这期间每份技能都改过,"
                      "分不清哪些变化是效果、哪些是抖动。"
                      "下次留一份不动的,或者先跑一遍 --noise 量底噪。")
    if changed_n == 0:
        return None, (f"改动组是空的(这期间改的技能没有对应用例),"
                      f"对照组动了 {noise} 条 —— 这个数是噪声参考,不是效果。")
    if net == 0:
        return False, (f"改动组净变化 0(修好 {changed_fixed}、变坏 {changed_broke}),"
                       f"**读不出效果**。不是「没用」,是「这次测不出来」——"
                       f"要么效果小于噪声,要么样本不够。")
    if abs(net) <= noise:
        return False, (f"改动组净变化 {net:+d},而对照组光噪声就动了 {noise} 条 —— "
                       f"**读不出效果**。改动组的变化不超过噪声,"
                       f"说它有用和说它没用一样没根据。想读出来:多跑几遍,或者加用例。")
    return True, (f"改动组净变化 {net:+d},对照组噪声 {noise} 条 —— "
                  f"**{'确实变好了' if net > 0 else '确实变差了'}**,变化超出噪声。")


def stability(runs):
    """一组重复结果的稳定性。runs 是每次的结果列表(可比较的值)。

    返回 (稳不稳, 一句话)。**不稳的尺子量不了别人** ——
    任何新评测的第一件事应该是量它自己,而不是拿它去量别人。
    """
    if not runs:
        return None, "没有数据"
    n, k = len(runs), len(set(map(str, runs)))
    if n < 3:
        return None, (f"只跑了 {n} 遍,**量不出自己稳不稳**。"
                      f"至少三遍 —— 两遍一致可能是巧合,两遍不一致不知道哪遍是常态。")
    if k == 1:
        return True, f"{n} 遍结果一致,这把尺子稳。"
    return False, (f"{n} 遍出现 {k} 种结果 {runs} —— **这把尺子自己就在抖**。"
                   f"拿它去量别人,量出来的差异分不清是别人的还是它的。")
