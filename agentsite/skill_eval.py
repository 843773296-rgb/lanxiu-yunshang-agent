    # 由店长问可以读成门店经营 —— **同一句话换个人问,标准答案就变了**,不换身份测不出那条边界。
    身份们 = {"店长": me,
             "顾问": {"no": "60000002", "name": "林岚", "role": "顾问", "shop": "SH001 静安旗舰店"}}
    _错身份 = [c["id"] for c in cases if (c.get("身份") or "店长") not in 身份们]
    if _错身份:   # 写错的身份不许落进「跑崩了」那一类 —— 那一类不进分母,题会安静地消失
        sys.exit(f"用例 {_错身份} 的「身份」认不出,只认 {list(身份们)}")

    _拒 = 模型闸(os.environ.get("ANTHROPIC_MODEL"))
    if _拒:
        sys.exit(_拒)
    import importlib as _il; _mid = _il.import_module("sdk").default_model_id()
    # 这一轮的**工作流接管状态**(用户 2026-10-27 拍「评测读接管状态,动态定真值」)。
    # 被接管的技能「应该走工作流,不走技能」—— 真值跟着它变,**而且要印出来**:
    # 只改真值不印口径,以后两版基线的接管状态不同时照样分不开。
    import sys as _sy, os as _os
    _sy.path.insert(0, _os.path.join(_os.path.dirname(_os.path.dirname(_os.path.abspath(__file__))), "agent"))
    import takeover_guard as _tg
    _接管开跑 = _tg.读状态()
    # 这一轮**真挂上去**的技能(用户 2026-10-28 拍「评测按放行状态动态定真值」)。
    # ⚠️ 这是 10-27 那三条漏触发的真正根因:own 档 10-23 起 = 「后台放行的」,
    # 而**第三方改造版默认待审查**(sdk.py:637)—— 那三个技能根本没挂,模型调不到。
    # > 一个「这个技能在仓库里」和一个「这一轮真的挂给了模型」,
    # > **在查目录的结果上长得一模一样**(目录 13 个、挂上去 10 个)。
    _挂了 = set(_il.import_module("sdk").skills_for(a.set))
    print(f"\n\033[1m技能触发评测 · {len(cases)} 条 · 模型 {_mid} · "
          f"技能档 {a.set}({len(_il.import_module('sdk').skills_for(a.set))} 个)\033[0m")
    print(f"  \033[33m{_tg.一句话(_接管开跑)}\033[0m")
    # 口径印出来 —— **只按放行状态改真值不印,分数就跟着后台配置走而看不出原因**。
    _要的 = sorted({c.get("expect") for c in cases if c.get("expect")})
    _没挂 = [x for x in _要的 if x not in _挂了]
    print(f"  \033[33m放行状态:这一轮挂了 {len(_挂了)} 个技能" +
          (f";**题里要的 {len(_没挂)} 个没挂**({'、'.join(_没挂)})—— "
           f"它们按设计就不该触发,这几题的真值已改成「不触发」"
           if _没挂 else ";题里要的技能全挂上了") + f"\033[0m")
    print("=" * 88)
    rows, t0 = [], time.time()
    # 每一遍就是一轮 —— 攒成 rounds.py 要的形状 `[{用例: 过没过}, ...]`。
    # 逐条重复和「跑两轮」量的是同一件事,只是交错着跑;
    # 攒起来就能直接问那个问题:**这个差会不会被抖动淹掉。**
    轮数 = max(1, a.repeat)
    多轮 = [{} for _ in range(轮数)]
    轮因 = [{} for _ in range(轮数)]
    for c in cases:
        want = 定真值(c.get("expect"), _接管开跑.get("接管中") or [], _挂了)
        # 跑 N 遍,**记下每一遍的结果** —— 稳定性本身是个要看的东西:
        # 一个「有时触发有时不触发」的技能,比稳定不触发更难查,
        # 因为它偶尔会给你一个「已经好了」的假象。
        got_all, 崩, 每遍 = [], [], []
        for _ in range(轮数):
            # ⚠️ **跑崩了不算答错了。** 2026-09-19 那次跑批暴露的:
            # 连着五条抛 ResultError(之后自己恢复,明显是瞬时故障),
            # 而它们被当成「触发结果」记进了准确率 ——
            # 期望不触发的记成**误触发**,期望触发的记成**漏触发**。
            # **「跑崩了」和「答错了」在准确率里长得一模一样。**
            #
            # 现在:崩了先重试;重试还崩就**单独记一类,不进准确率分母**,
            # 并在汇总里明说有几条没测到。**没测到不叫通过,也不叫失败。**
            g1 = None
            for _t in range(a.retry + 1):
                try:
                    g1, _r = asyncio.run(_run_with_identity(
                        sdk, c["prompt"], 身份们[c.get("身份") or "店长"], a.set))
                    break
                except Exception as e:
                    g1 = f"ERR:{type(e).__name__}"
            每遍.append(g1)
            (崩 if str(g1).startswith("ERR:") else got_all).append(g1)

        # ── 把这一条的每一遍记进对应那一轮 ────────────────────────────
        # ⚠️ 崩掉的那一遍在两个地方待遇**不同,而且都是对的**:
        #   准确率里 → **剔除**(不然把环境问题算成能力,2026-09-19 就是这么错的)
        #   抖动报告里 → **留着记成没过**,理由写「跑挂了」
        #     (rounds.py 有专门的「跑挂」一类)。剔掉的话,
        #     「这一轮根本没跑完」会从抖动视图里**安静消失**,
        #     那条用例看上去就成了「稳定地挂着」。
        #
        # 失败理由一律标 **轨迹类**,这不是偷懒 —— 是**结构上就只能是它**:
        # `_skill_of()` 读的是工具调用的入参,**这把尺子根本不看模型说了什么**。
        # 所以这里的翻面永远不可能是「判据太吃措辞」,只能是模型这次行为变了。
        # 该改的是**技能描述**,不是判据。
        for _i, _g in enumerate(每遍):
            if str(_g).startswith("ERR:"):
                多轮[_i][c["id"]] = False
                轮因[_i][c["id"]] = [f"跑挂了:{_g}"]
                continue
            多轮[_i][c["id"]] = (_g == want)
            if _g != want:
                轮因[_i][c["id"]] = [
                    f"轨迹:该触发 {want or '(不触发)'},实际 {_g or '(无)'}"]

        if not got_all:
            print(f"  {R}✗{D} #{c['id']:<3} {c['prompt'][:30]:<32} "
                  f"{R}{len(崩)} 遍全崩({崩[0]}),这条没测到{D}")
            rows.append(dict(id=c["id"], prompt=c["prompt"], want=want, got=崩[0],
                             ok=None, kind="没测到", hits=0, runs=0, wobbly=False,
                             崩=len(崩)))
            continue
        行 = 一行(c, want, got_all)
