    cases = [c for c in spec["cases"] if not a.only or c["id"] == a.only]

    import sdk
    # 身份:排班/团队类问法要店长才答得了,否则会因为「你没这个权限」而不触发 ——
    # **那种不触发是权限挡的,不是描述不好**,混在一起测就分不清谁的责任。
    sys.path.insert(0, os.path.join(ROOT, "backend"))
