def 一行(c, want, got_all):
    """把一道题这一轮的结果攒成**存盘的那一行**。

    ⚠️ **`逐轮` 这一栏必须存。** 2026-11-08 查实:`got_all`(这道题每一遍真实触发了什么)
    本来就在内存里躺着 —— 报告里那句「不稳定:['rating-repair', None, ...]」印的就是它 ——
    而写盘时只写了汇总 `hits/runs`,**把它丢了**。
    于是导出题集那边印不出「哪一遍错的」,我 11-08 差点为此设计一条「只报汇总」的路径。

    > 「这个数据没有」和「这个数据有、只是没存下来」,**在那个文件里长得一模一样** ——
    > 而前者要重新设计一条路径,后者只要把它写下来。

    项目里 `tools/export_evals.py` 那条判据「**多轮必须逐轮印出来**」讲的是同一件事:
    三个 ✅ 和「❌❌✅」在一个 ✅ 上分不开,而它们该触发的下一步动作相反
    (前者是能力稳,后者是要去查抖动)。
    ⚠️ v6 及更早的基线**没有这一栏**(11-08 之前存的)——
    读那几版时要按「只有汇总」处理,**别把缺这一栏当成「那一轮没抖」**。
    """
    hits = sum(1 for x in got_all if x == want)
    got = got_all[0] if len(set(got_all)) == 1 else f"{got_all[0]}?{len(set(got_all))}种"
    ok = (hits == len(got_all))
    wobbly = 0 < hits < len(got_all)
    # 两种错分开记 —— 后果不一样,不能揉成一个准确率
    g0 = got_all[0]
    kind = "对" if ok else ("不稳定" if wobbly else
                            ("漏触发" if want and not g0 else
                             ("误触发" if g0 and not want else "触发错了技能")))
    return dict(id=c["id"], prompt=c["prompt"], want=want, got=got, ok=ok,
                kind=kind, hits=hits, runs=len(got_all), wobbly=wobbly,
                逐轮=list(got_all))


def 定真值(写着的, 接管中, 挂了):
    """这一道题**这一轮**的真值 —— 按运行时的两样配置改写(用户 2026-10-27 / 10-28 拍)。

    题面里写着「应触发 X」,而 X 这一轮可能根本不该触发,有两种情形:

      · **X 被工作流接管** → `sdk.py` 的规矩是技能被拦、改走工作流 → 期望不触发
      · **X 没放行、没挂给模型** → 模型调不到它 → 期望不触发
        (own 档 10-23 起 = 「后台放行的」,而**第三方改造版默认待审查**)

    > 一个「模型漏了该走的技能」和一个「这件事本来就不该走技能」,
    > **在「漏触发」那一栏里长得一模一样** —— 而那一栏的标题是
    > 「用户拿到的是随口答的东西」,挂错了就完全反了。

    ⚠️ **抽成模块级函数是为了能单独验。** 内嵌在 `main()` 里的话,
    验它得跑一整轮模型调用(70 分钟)——
    **而一条要跑 70 分钟才能验的判据,等于没有判据。**
    判据:`agentsite/skill_eval_truth_check.py`。

    ⚠️ 期望**不触发**的题(`写着的` 为空)原样返回 —— 接管和放行都只会
    「让该触发的变成不该触发」,不会反过来。
    """
    if not 写着的:
        return 写着的
    if 写着的 in (接管中 or []):
        return None
    if 挂了 is not None and 写着的 not in 挂了:
        return None
    return 写着的


