#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""改造过的第三方技能 · **正文改了就红一次**(用户 2026-11-06 拍「做」)。

## 它守的是什么

`agentsite/.claude/skills/` 里有三份是从第三方技能包改造来的(`third_party_review.json`
里带 `改造自` 的那些)。它们的**全部价值压在一件事上:第三方的业务门槛已经删干净了** ——
保本投入产出比和「低于就砍」、各渠道目标倍数、预算上下 20% 的加减规则、花费进度线、
安全库存天数、周转红线。删它们的理由是:**这些数门店一次都没拍过板**,
留着就等于让一个海外投放的经验值替门店做决定。

而技能面原有的四条自查(`skills_check.py`)验的是:前言字段齐不齐、代码里声明的清单和
目录对不对、工具白名单和实际暴露的一致不一致、内置的写文件/执行命令工具封没封。
**没有一条去读技能正文。**

> 一份门槛删干净了的技能,和一份被谁又把门槛加回去的技能,
> **在门禁的绿勾上长得一模一样。**

而加回去是极自然的事:哪天有人觉得「总得有个线吧」,在正文里补一句
「低于保本就建议停」,门禁照旧全绿,而从那天起这个技能就开始拿一个
**没人拍过板的数**替门店做决定。

## 为什么不是禁某些词

门槛的中文写法接近无限,枚举必输 —— 这个项目为枚举词表栽过七次。
这里要的是另一种工具:

> **「不许变」和「变了就让证据过期」是两种不同的东西。**

所以这条**不禁止修改**:正文当然可以改。但改了**红一次**,红的时候要求
重新走一遍审查、并把指纹更新掉。理由是:「门槛删干净了」是一个**人的判断**,
机器没法重新验证它;机器能做的是**保证这个判断不会在没人看见的时候失效**。

## 判据跟着「改造自」走,不是写死三个名字

写死名字的清单会漂:第四份改造技能进来时,它**不会红**,而「没覆盖到」
和「覆盖了而且是干净的」在绿勾上长得一模一样。

跑:`python3 agentsite/skill_body_check.py`
"""
# 咬合 —— 改坏的是什么、该红的是哪一条。可执行规格在 `tools/bite_specs.json`。
咬合 = [
    ("往 stock-patrol-lanxiu 正文里加一句第三方的业务门槛(「低于保本投入产出比就建议停」)",
     "正文改了,而审查结论是对旧那一版下的"),
    ("把一份改造技能的指纹登记删掉 —— 于是它的正文从此没人盯着",
     "有目录、没登指纹"),
]

import hashlib
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
审查记录 = os.path.join(HERE, "third_party_review.json")
G, R, Y, D = "\033[32m", "\033[31m", "\033[33m", "\033[0m"


def 指纹(路径):
    """正文的指纹 = 文件字节的 sha256 前 12 位。

    ⚠️ 用**字节**,不是「去掉空白之后的文本」—— 后者会把「只改了排版」放过去,
    而一句门槛可以就写在被忽略的那一行里。这条判据宁可为排版改动红一次
    (红的时候只要确认一眼、更新指纹),也不要漏掉一句加回来的门槛。

    ⚠️ **写法故意和另外两处一字不差**(`skill_eval.py` 算评测来路、`sdk.py` 往轨迹里
    记 `lanxiu.skill.sha256`)—— 底下「指纹算法只有一种写法」那条判据扫的就是这个写法。
    """
    return hashlib.sha256(open(路径, "rb").read()).hexdigest()[:12]


# 仓库里算技能正文哈希的**全部**地方。三处算的必须是同一件事 ——
# 这个项目的教训:两份实现会漂,而漂了之后
# **「指纹对不上」和「两处算法不一样」长得一模一样**,人会去查前者。
算指纹的地方 = ("agentsite/skill_eval.py",      # 评测来路:哪一版技能考出了这个分
                "agentsite/sdk.py",             # 运行时:往轨迹里记 lanxiu.skill.sha256
                "agentsite/skill_body_check.py")  # 这条判据自己
# ⚠️ 这里**不写出完整的表达式**当样板 —— 写出来这个文件自己就匹配两次,
# 而「扫到的是真实现」和「扫到的是我举的例子」长得一模一样(项目为这个坑连踩三次)。
指纹写法 = re.compile(r"sha256\(\s*open\([^)]*\)\s*\.read\(\)\s*\)\.hexdigest\(\)\[:(\d+)\]")


def 技能正文(名):
    return os.path.join(HERE, ".claude", "skills", 名, "SKILL.md")


def 几条(坏, 上限=4):
    """截断要说**还有几条** —— 只显示前几条、照着修完再跑它「又冒出来」,
    人会编一个错解释(这个项目栽过一次,还照着错解释加了条会误报的门禁)。"""
    头 = "、".join(坏[:上限])
    return 头 + (f"  ……**还有 {len(坏) - 上限} 条**(共 {len(坏)})" if len(坏) > 上限 else "")


def main():
    print("改造过的第三方技能 · 正文改了就红一次")
    记录 = json.load(open(审查记录, encoding="utf-8"))
    改造的 = {k: v for k, v in 记录.items() if isinstance(v, dict) and v.get("改造自")}

    # ⑧ 「没东西可验」必须和「验过了」分开 —— 而这份记录是**仓库里的**,
    # 不是环境里碰巧有的东西:它一份都没有,只能是记录坏了或被清空了,不是「这台机器上没有」。
    if not 改造的:
        print(f"  {R}❌ `third_party_review.json` 里一份带「改造自」的条目都没有 —— "
              f"这条判据**读不到东西**,不算通过{D}")
        return 1
    print(f"  验了 {len(改造的)} 份改造过的技能(判据跟着「改造自」走,不是写死名字)")

    # ③ 失败**分类**报:三类的下一步动作完全不同
    #    改了   → 去重新走一遍审查,然后更新指纹
    #    没登   → 去补一条指纹登记(它现在没人盯着)
    #    没了   → 去把这条过期的登记删掉(⑥ 豁免 / 登记不许囤积)
    改了, 没登, 没了 = [], [], []
    for 名, v in sorted(改造的.items()):
        路 = 技能正文(名)
        记 = v.get("正文指纹")
        if not os.path.exists(路):
            if 记:
                没了.append(名)
            continue
        if not 记:
            没登.append(名)
        elif 记 != 指纹(路):
            改了.append(f"{名}(登记 {记} · 现在 {指纹(路)})")

    坏 = 0
    print(f"  {R + '❌' + D if 改了 else G + '✅' + D} 正文和审查时的那一版一致"
          + (f"  —— **正文改了,而审查结论是对旧那一版下的**:{几条(改了)}" if 改了 else ""))
    print(f"  {R + '❌' + D if 没登 else G + '✅' + D} 每份改造技能都有指纹登记"
          + (f"  —— **有目录、没登指纹**(它的正文现在没人盯着):{几条(没登)}" if 没登 else ""))
    # ⑥ 反向检查:登记不许囤积 —— 没有这一半,记录会慢慢攒满早就删掉的技能,
    #    而**囤积的登记和真登记长得一模一样**
    print(f"  {R + '❌' + D if 没了 else G + '✅' + D} 登了指纹的技能都还在"
          + (f"  —— **登记过期了,去把它删掉**:{几条(没了)}" if 没了 else ""))
    坏 = len(改了) + len(没登) + len(没了)

    # 三处算法必须一致。② 先报样本量:扫不到就是判据的视野漏了,不是「它们一致」
    取 = {}
    for 相 in 算指纹的地方:
        文 = open(os.path.join(ROOT, 相), encoding="utf-8").read()
        取[相] = sorted({int(x) for x in 指纹写法.findall(文)})
    缺 = [k for k, v in 取.items() if not v]
    长 = sorted({n for v in 取.values() for n in v})
    一致 = not 缺 and len(长) == 1
    print(f"  {G + '✅' + D if 一致 else R + '❌' + D} 指纹算法在仓库里只有一种写法"
          f"(扫了 {len(算指纹的地方)} 处)"
          + (f"  —— **这几处扫不到那个写法**(判据的视野漏了,不是它们一致):{几条(缺)}" if 缺
             else f"  —— **截断长度不止一种:{长}**,两处算出来的指纹不可比" if not 一致 else ""))
    坏 += 0 if 一致 else max(len(缺), 1)

    if 改了:
        print()
        print(f"  {Y}改了之后要做的**不是**把指纹改一改了事{D} —— 这条判据守的是"
              f"「门槛删干净了」这个**人的判断**不会在没人看见的时候失效。")
        print(f"  顺序是:① 读一遍改动,确认没有把第三方的业务门槛加回来"
              f"(保本投入产出比 / 低于就砍 / 目标倍数 / 预算±20% / 花费进度线 / "
              f"安全库存天数 / 周转红线这类**门店一次都没拍过板的数**)")
        print(f"  ② 把结论更新到 `澜绣云裳agent-第三方技能审查结论.md`"
              f"  ③ 跑 `python3 agentsite/skill_body_check.py --更新指纹`")
    print()
    if 坏:
        print(f"{R}❌ 不符合预期 {坏} 处{D}")
        return 1
    print(f"{G}✅ {len(改造的)} 份改造技能的正文都还是审查过的那一版{D}")
    return 0


def 更新指纹():
    """把现在的正文指纹写回审查记录。**单独一个口、要人显式去调** ——
    自动更新等于没有这条判据:它会在每次跑门禁时静静地把「改过了」变成「一致」。"""
    记录 = json.load(open(审查记录, encoding="utf-8"))
    动 = []
    for 名, v in sorted(记录.items()):
        if not (isinstance(v, dict) and v.get("改造自")):
            continue
        路 = 技能正文(名)
        if not os.path.exists(路):
            continue
        新 = 指纹(路)
        if v.get("正文指纹") != 新:
            动.append(f"{名}:{v.get('正文指纹') or '(原来没有)'} → {新}")
            v["正文指纹"] = 新
    if not 动:
        print("  指纹本来就是对的,一个字没改")
        return 0
    json.dump(记录, open(审查记录, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    open(审查记录, "a", encoding="utf-8").write("\n")
    for x in 动:
        print(f"  ✍️ {x}")
    print(f"  ⚠️ 更新了 {len(动)} 份的指纹 —— **这等于声明「我读过这次改动,门槛没被加回来」**。"
          f"没读就更新,这条判据就只是个摆设。")
    return 0


if __name__ == "__main__":
    sys.exit(更新指纹() if "--更新指纹" in sys.argv else main())
