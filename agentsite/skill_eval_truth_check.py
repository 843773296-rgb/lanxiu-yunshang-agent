#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""技能触发评测的**真值改写** · 检查 —— 这段逻辑会让分数虚高,所以必须单独验。

`skill_eval.定真值()` 按运行时的两样配置改写题面里的真值:

    技能被工作流接管   → 期望不触发(sdk.py 的规矩是技能被拦、改走工作流)
    技能没放行、没挂上 → 期望不触发(模型调不到它)

**为什么这段非验不可**:它改坏了,那几条会从「❌ 漏触发」变成「✅ 通过」、
分数凭空涨几分,而**没有任何东西会红**。

> 一个「这题通过了因为模型做对了」和一个「这题通过了因为我们不再期望它做什么」,
> **在那个 ✅ 上长得一模一样。**

⚠️ 这个检查**不调模型、不碰库**,毫秒级。
原来那段逻辑内嵌在 `main()` 的循环里,验它得跑一整轮(70 分钟)——
**而一条要跑 70 分钟才能验的判据,等于没有判据**,所以先把它抽成了模块级函数。
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

# ⚠️ 只取那一个函数,不跑 main ——
# `skill_eval` 顶上 import sdk 要 .venv 里的 claude_agent_sdk,
# 而这条检查在门禁里用系统 python 跑。所以用源码里那一段单独 exec。
import ast, io
_src = io.open(os.path.join(HERE, "skill_eval.py"), encoding="utf-8").read()
_树 = ast.parse(_src)
_节 = next((n for n in _树.body if isinstance(n, ast.FunctionDef) and n.name == "定真值"), None)
if _节 is None:
    print("\033[31m❌ skill_eval.py 里找不到 `定真值()` —— "
          "它被改名或内联回去了。**这条检查扫不到的东西不等于不存在问题**\033[0m")
    sys.exit(1)
_ns = {}
exec(compile(ast.Module(body=[_节], type_ignores=[]), "<定真值>", "exec"), _ns)
定真值 = _ns["定真值"]

# 咬合 —— 改坏的是什么、该红的是哪一条。
# (可执行的在 tools/bite_specs.json)
咬合 = [
    ("把「没挂上 → 期望不触发」那一支去掉", "没挂上 → 改成期望不触发"),
    ("把「被接管 → 期望不触发」那一支去掉", "被接管 → 改成期望不触发"),
    ("让「挂了传 None」也当成「没挂上」", "拿不到挂载清单(None)→ 真值不动"),
]

G, R, D = "\033[32m", "\033[31m", "\033[0m"
坏, n = [], 0


def ck(名, 得, 应):
    global n
    n += 1
    ok = (得 == 应)
    print(f"  {G + '✅' + D if ok else R + '❌' + D} {名}" + ("" if ok else f"  得到={得!r} 应={应!r}"))
    if not ok:
        坏.append(名)


挂全 = {"quote", "store-report", "exchange"}
print("真值改写 · 检查(不调模型、不碰库)")

# ── 正常情形:挂上了、没被接管 → 真值原样 ─────────────────────────
ck("挂上了且没被接管 → 真值不动", 定真值("quote", [], 挂全), "quote")
ck("期望不触发的题原样返回(None)", 定真值(None, [], 挂全), None)
ck("期望不触发的题,空字符串也原样", 定真值("", [], 挂全), "")

# ── 接管中 → 期望不触发 ───────────────────────────────────────────
ck("被接管 → 改成期望不触发", 定真值("store-report", ["store-report"], 挂全), None)
ck("别的技能被接管,不影响这一条", 定真值("quote", ["store-report"], 挂全), "quote")

# ── 没挂上 → 期望不触发 ──────────────────────────────────────────
ck("没挂上 → 改成期望不触发",
   定真值("metric-diagnostics-lanxiu", [], 挂全), None)
ck("挂了一部分:挂上的那条不动", 定真值("exchange", [], 挂全), "exchange")

# ── 两样同时:都指向不触发 ────────────────────────────────────────
ck("既被接管又没挂上 → 还是不触发",
   定真值("stock-patrol-lanxiu", ["stock-patrol-lanxiu"], 挂全), None)

# ── ⚠️ 只会把「该触发」变成「不该触发」,不会反过来 ────────────────
# 这个方向性是刻意的:接管和放行都只能**拿掉**一条路,不会凭空造出一条。
# 反过来写的话,一道「期望不触发」的题会被改成「期望触发某个技能」,
# 而那个技能的名字从哪来都说不清。
ck("不会把「期望不触发」改成「期望触发」(方向只有一个)",
   定真值(None, ["quote"], 挂全), None)

# ── 挂了传 None(拿不到挂载清单)→ 不乱改 ────────────────────────
# ⚠️ 「拿不到清单」和「清单里没有它」不是一回事:前者什么都不知道,
# 后者确凿知道它没挂。拿不到就别改真值 —— 瞎改会让分数虚高。
ck("拿不到挂载清单(None)→ 真值不动(不知道 ≠ 没挂)",
   定真值("quote", [], None), "quote")

print(f"  (验了 {n} 条)")
if n == 0:
    print(f"{R}❌ 一条都没验{D}"); sys.exit(1)
if 坏:
    print(f"{R}❌ 真值改写 {len(坏)} 条不过{D}"); sys.exit(1)
print(f"{G}✅ 真值改写:接管 / 没放行 → 期望不触发;方向只有一个;"
      f"拿不到清单时不乱改(**这段改坏了会让分数虚高,所以单独验**){D}")
