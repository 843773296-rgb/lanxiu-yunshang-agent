#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""技能触发评测的**真值改写** · 检查 —— 这段逻辑会让分数虚高,所以必须单独验。

`skill_eval.定真值()` 按运行时的两样配置改写题面里的真值:

    技能被工作流接管   → 期望不触发(sdk.py 的规矩是技能被拦、改走工作流)
    技能没放行、没挂上 → 期望不触发(模型调不到它)

**为什么这段非验不可**:它改坏了,那几条会从「❌ 漏触发」变成「✅ 通过」、
分数凭空涨几分,而**没有任何东西会红**。

> 一个「这题通过了因为模型做对了」和一个「这题通过了因为我们不再期望它做什么」,
> **在那个 ✅ 上长得一模一样。**

⚠️ 这个检查**不调模型、不碰库**,毫秒级。
原来那段逻辑内嵌在 `main()` 的循环里,验它得跑一整轮(70 分钟)——
**而一条要跑 70 分钟才能验的判据,等于没有判据**,所以先把它抽成了模块级函数。
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

# ⚠️ 只取那一个函数,不跑 main ——
# `skill_eval` 顶上 import sdk 要 .venv 里的 claude_agent_sdk,
# 而这条检查在门禁里用系统 python 跑。所以用源码里那一段单独 exec。
import ast, io
_src = io.open(os.path.join(HERE, "skill_eval.py"), encoding="utf-8").read()
_树 = ast.parse(_src)
_节 = next((n for n in _树.body if isinstance(n, ast.FunctionDef) and n.name == "定真值"), None)
if _节 is None:
    print("\033[31m❌ skill_eval.py 里找不到 `定真值()` —— "
          "它被改名或内联回去了。**这条检查扫不到的东西不等于不存在问题**\033[0m")
    sys.exit(1)
_要的 = ("定真值", "这一轮的口径", "_接管口径", "口径差异")
_节们 = [n for n in _树.body if isinstance(n, ast.FunctionDef) and n.name in _要的]
_缺 = [x for x in _要的 if x not in {n.name for n in _节们}]
if _缺:
    print(f"\033[31m❌ skill_eval.py 里找不到 {_缺} —— 被改名或内联回去了。"
          f"**这条检查扫不到的东西不等于不存在问题**\033[0m")
    sys.exit(1)
_ns = {}
exec(compile(ast.Module(body=_节们, type_ignores=[]), "<取出来的几个函数>", "exec"), _ns)
定真值, 这一轮的口径, 口径差异 = _ns["定真值"], _ns["这一轮的口径"], _ns["口径差异"]

# 咬合 —— 改坏的是什么、该红的是哪一条。
# (可执行的在 tools/bite_specs.json)
咬合 = [
    ("把「没挂上 → 期望不触发」那一支去掉", "没挂上 → 改成期望不触发"),
    ("把「被接管 → 期望不触发」那一支去掉", "被接管 → 改成期望不触发"),
    ("让「挂了传 None」也当成「没挂上」", "拿不到挂载清单(None)→ 真值不动"),
    ("把存基线那一处的 `**这一轮的口径(...)` 删掉(口径又只印在屏幕上)",
     "接线:存基线那一处真的把两个口径写进文件"),
    ("把「老基线没记这个字段」和「两版一致」合并成同一句话",
     "「不知道」和「一致」不是同一句话(含义相反)"),
    ("让接管口径把那句「说明」也算进去比", "说明的文案不同,不算口径变了"),
]

G, R, D = "\033[32m", "\033[31m", "\033[0m"
坏, n = [], 0


def ck(名, 得, 应):
    global n
    n += 1
    ok = (得 == 应)
    print(f"  {G + '✅' + D if ok else R + '❌' + D} {名}" + ("" if ok else f"  得到={得!r} 应={应!r}"))
    if not ok:
        坏.append(名)


挂全 = {"quote", "store-report", "exchange"}
print("真值改写 · 检查(不调模型、不碰库)")

# ── 正常情形:挂上了、没被接管 → 真值原样 ─────────────────────────
ck("挂上了且没被接管 → 真值不动", 定真值("quote", [], 挂全), "quote")
ck("期望不触发的题原样返回(None)", 定真值(None, [], 挂全), None)
ck("期望不触发的题,空字符串也原样", 定真值("", [], 挂全), "")

# ── 接管中 → 期望不触发 ───────────────────────────────────────────
ck("被接管 → 改成期望不触发", 定真值("store-report", ["store-report"], 挂全), None)
ck("别的技能被接管,不影响这一条", 定真值("quote", ["store-report"], 挂全), "quote")

# ── 没挂上 → 期望不触发 ──────────────────────────────────────────
ck("没挂上 → 改成期望不触发",
   定真值("metric-diagnostics-lanxiu", [], 挂全), None)
ck("挂了一部分:挂上的那条不动", 定真值("exchange", [], 挂全), "exchange")

# ── 两样同时:都指向不触发 ────────────────────────────────────────
ck("既被接管又没挂上 → 还是不触发",
   定真值("stock-patrol-lanxiu", ["stock-patrol-lanxiu"], 挂全), None)

# ── ⚠️ 只会把「该触发」变成「不该触发」,不会反过来 ────────────────
# 这个方向性是刻意的:接管和放行都只能**拿掉**一条路,不会凭空造出一条。
# 反过来写的话,一道「期望不触发」的题会被改成「期望触发某个技能」,
# 而那个技能的名字从哪来都说不清。
ck("不会把「期望不触发」改成「期望触发」(方向只有一个)",
   定真值(None, ["quote"], 挂全), None)

# ── 挂了传 None(拿不到挂载清单)→ 不乱改 ────────────────────────
# ⚠️ 「拿不到清单」和「清单里没有它」不是一回事:前者什么都不知道,
# 后者确凿知道它没挂。拿不到就别改真值 —— 瞎改会让分数虚高。
ck("拿不到挂载清单(None)→ 真值不动(不知道 ≠ 没挂)",
   定真值("quote", [], None), "quote")


# ════════════════════════════════════════════════════════════════════
# 口径要进基线文件 —— **屏幕上印过不算**
# ════════════════════════════════════════════════════════════════════
# 2026-10-27 拍的「评测读接管状态、动态定真值」做了两件:改真值 ✅、把口径
# 「印出来」—— 而印的是**终端**。终端明天就没了,基线文件要活很久。
# 于是 v1/v2/v3 三版基线里一个字都没记这一轮的接管和放行状态,
# **两版口径不同时照样分不开** —— 正是那条规矩想防的事。
print()
print("口径进文件 · 检查")

口径 = 这一轮的口径({"接管中": [], "连上了": True, "说明": "连上了,一个都没接管"},
                {"quote", "exchange"})
ck("存进基线的口径带「接管」", "接管" in 口径, True)
ck("存进基线的口径带「放行」", "放行" in 口径, True)
# ⚠️ 放行必须是**排过序的列表**,不是集合:集合的迭代顺序每次都可能不同,
# 那样两版基线文件 diff 出来全是顺序差,而内容一模一样。
ck("放行排过序(否则两版文件的差异全是顺序)", 口径["放行"], ["exchange", "quote"])

_接管开 = {"接管中": ["store-report"], "连上了": True, "说明": "接管中 1 个:store-report"}
_接管空 = {"接管中": [], "连上了": True, "说明": "连上了,一个都没接管"}
_没连上 = {"接管中": [], "连上了": False, "说明": "没连上管理后台"}

_老全 = dict(接管=_接管空, 放行=["exchange", "quote"])
_级 = lambda 老, 接, 挂: [x[0] for x in 口径差异(老, 接, 挂)]

ck("两版都记了且一样 → 两条都「一致」",
   _级(_老全, _接管空, {"quote", "exchange"}), ["一致", "一致"])
ck("老基线没记 → 两条都「不知道」(不是「一致」)",
   _级({}, _接管空, {"quote", "exchange"}), ["不知道", "不知道"])
ck("接管状态不同 → 「变了」", _级(_老全, _接管开, {"quote", "exchange"})[0], "变了")
ck("没连上后台 vs 连上了没接管 → 「变了」(两者含义相反)",
   _级(_老全, _没连上, {"quote", "exchange"})[0], "变了")
ck("这一轮多挂上一个技能 → 「变了」",
   _级(_老全, _接管空, {"quote", "exchange", "stock-patrol-lanxiu"})[1], "变了")
ck("多挂上的那个技能名要点出来(不然不知道该去看哪几道题)",
   "stock-patrol-lanxiu" in 口径差异(_老全, _接管空,
                                   {"quote", "exchange", "stock-patrol-lanxiu"})[1][1], True)

# ⚠️ **只有那句「说明」的文案不同,不算口径变了。**
# 口径要落在**结构**上(连上了 / 接管了哪几个),不落在那句中文怎么写 ——
# 不然我改一个字的措辞,所有基线当场全部「不可比」。
_文案不同 = dict(_接管空); _文案不同["说明"] = "换个说法:后台连上了,没有技能被接管"
ck("说明的文案不同,不算口径变了",
   _级(dict(接管=_文案不同, 放行=["exchange", "quote"]), _接管空, {"quote", "exchange"})[0],
   "一致")

# ⚠️ **「不知道」和「一致」不许输出同一句话** —— 两者的下一步动作相反:
# 一个是「这版做不了口径对照,换一版」,一个是「可以读差异」。
# (`takeover_guard` 里 `接管中: []` vs `连上了: False` 是同一个形状,那边也有一条钉它。)
_不知道句 = [x[1] for x in 口径差异({}, _接管空, {"quote"})]
_一致句 = [x[1] for x in 口径差异(dict(接管=_接管空, 放行=["quote"]), _接管空, {"quote"})]
ck("「不知道」和「一致」不是同一句话(含义相反)",
   all(a != b for a, b in zip(_不知道句, _一致句)), True)

# ════════════════════════════════════════════════════════════════════
# 接线 —— **函数写对了,而没人调它**,在绿勾上和守住了一模一样
# ════════════════════════════════════════════════════════════════════
# 项目里栽过(2026-11-04 `tools/impact.py`):四条用例全打在纯函数上,
# 把入口里调它那一支关掉,四条照旧全对、自测全绿。
# 所以除了验上面那些,还要验**存基线那一处真的在用它**。
_main = next((x for x in _树.body if isinstance(x, ast.FunctionDef) and x.name == "main"), None)
if _main is None:
    print("\033[31m❌ skill_eval.py 里找不到 main()\033[0m"); sys.exit(1)

_存基线用了 = False
for _n in ast.walk(_main):
    # json.dump(dict(...), ...) 那一处:它的实参里必须有 `**这一轮的口径(...)`
    if isinstance(_n, ast.Call) and isinstance(_n.func, ast.Attribute) and _n.func.attr == "dump":
        for _a in _n.args:
            if isinstance(_a, ast.Call):
                for _kw in _a.keywords:
                    if (_kw.arg is None and isinstance(_kw.value, ast.Call)
                            and isinstance(_kw.value.func, ast.Name)
                            and _kw.value.func.id == "这一轮的口径"):
                        _存基线用了 = True
ck("接线:存基线那一处真的把两个口径写进文件", _存基线用了, True)

_对比用了 = any(isinstance(_n, ast.Call) and isinstance(_n.func, ast.Name)
              and _n.func.id == "口径差异" for _n in ast.walk(_main))
ck("接线:对比两版那一处真的在比口径", _对比用了, True)

print()
print(f"  (验了 {n} 条)")
if n == 0:
    print(f"{R}❌ 一条都没验{D}"); sys.exit(1)
if 坏:
    print(f"{R}❌ 真值改写 {len(坏)} 条不过{D}"); sys.exit(1)
print(f"{G}✅ 真值改写:接管 / 没放行 → 期望不触发;方向只有一个;"
      f"拿不到清单时不乱改(**这段改坏了会让分数虚高,所以单独验**){D}")
