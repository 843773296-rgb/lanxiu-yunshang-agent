# ── 要害那一条:**先问「有没有资格比」,再比** ─────────────────────────
#
# ⚠️⚠️ 2026-10-14 改。原来这里直接比「重跑的号 == 库里的号」,而那个等式
# **只在「刚造完数那一瞬间」为真**:每日上新每天往库里加订单/评价
