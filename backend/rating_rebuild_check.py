# **实测:只动取行集一个元素,重合率从 100% 掉到 6%。**
#
# 所以原来那条判据把两件完全不同的事混成了一条:
#     ① 造数的代码改了                              ← **这才是要判红的**
#     ② 库里的数据被动过(按设计每天都会发生)      ← 不该判红
# 而它们**在「号不一样」这件事上长得一模一样**。
# 这和 2026-10-13 修的 `queue_view_check` 是同一个病,原话:
# > **一条判据,如果它红不红取决于环境里碰巧有什么数据,那它不是在验代码。**
#
# 修法(用户 2026-10-14 拍「只在刚造完、还没被动过时判红」):
# 拿**造数输入的指纹**当资格 —— 指纹是造数那一刻写进库的(`rating_rowset_fp`),
# 而它覆盖了全部影响随机序列的输入(取行集逐行、售后工号、店长们、月目标)。
#     指纹一致 → 输入没变而号变了 = **代码改了**,硬判红
#     指纹不同 → 输入被动过,这个等式本来就不成立,降级打印、**不判红**
# ⚠️ 用指纹而不是「哪天造的 + 那之后跑过每日上新没」:后者是个**会漂的时间推理**
# (同一天先造数后上新,日期分不出先后),而指纹直接比那个等式的前提本身。
