前缀 = "IT-"


def 是测试客户(cid):
    return isinstance(cid, str) and cid.startswith(前缀)


def 排除条件(别名=""):
    """WHERE 片段:不是测试客户。统计口子用。"""
    p = f"{别名}." if 别名 else ""
    return f"{p}id NOT LIKE '{前缀}%'"
