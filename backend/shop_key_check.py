import re as _re3


def _建表列清单(src, 表):
    """从源码里取 `CREATE TABLE … 表(…)` 的列清单。**手工配括号**,不用正则 ——
    `references staff(no)` 这种嵌套括号会把非贪婪正则截断在第一个 `)` 上。"""
    出 = []
    for m in _re3.finditer(rf"CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?[\"`\[]?{表}[\"`\]]?\s*\(",
                           src, _re3.I):
        i, 深 = m.end() - 1, 0
        for j in range(i, len(src)):
            if src[j] == "(": 深 += 1
            elif src[j] == ")":
                深 -= 1
                if 深 == 0:
                    出.append(src[i + 1:j])
                    break
    return 出


