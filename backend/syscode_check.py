#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""字典表的检查 —— **枚举表说的和数据里真有的,得是同一批。**

## 这条检查怎么来的

2026-09-16 从零重建库时,「渠道和活动共线」那条评测前提突然不成立。
查下去不是世界变了,是**一个空格**:

    ordr.source 里是   「门店 Pad」(有空格)
    run_journey 写的是 「门店Pad」(无空格)

于是同一个渠道在统计里被算成**两个**。

而这个笔误**不是随手打的** —— 写的人照着 `sys_code` 抄的,而那张表是这样的:

    sys_code 说:微信小程序 / **门店Pad** / 门店A / 门店B
    ordr 实际是:微信小程序 / **门店 Pad** / 官网 / 客服代下单

**四个里只有一个对得上。** 枚举表里有两个数据里根本不存在的(门店A、门店B),
数据里有两个枚举表没有的(官网、客服代下单)。

> **这是「同一个事实两个来源」的完整版** —— 而且两个来源都在,
> **写代码的人照哪一个都像是对的**。

## 它坏起来是什么样子

不是报错。是:

    · 页面上的筛选下拉列出「门店A」「门店B」,**筛出来 0 条**
    · 新写的代码照着枚举表填,**产出一个统计上独立的第五个渠道**
    · 而那个渠道在报表上**就是一行数据**,看不出它是重复的

## 钉的是上限,不是归零

对不上的条数记成上限,**只许降不许涨**。归零要业务确认
(「门店A / 门店B」是历史遗留还是将来要用的,我判不了)。
"""
import os, sys, sqlite3

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path[:0] = [HERE, ROOT]

咬合 = [
    ("把 run_journey 写的渠道改回硬编码「门店Pad」(无空格)",
     "订单来源:数据里的值都在枚举表里,或都记在账上"),
    ("把欠账上限改成 0",
     "订单来源:数据里的值都在枚举表里,或都记在账上"),
]

# ── 对不上的上限(2026-09-16 首次扫出来的账)────────────────────────────
#
#   枚举表有而数据里没有:门店A、门店B、**门店Pad**   —— 3 条
#   数据里有而枚举表没有:官网、客服代下单、**门店 Pad** —— 3 条
#
# ⚠️ 注意「门店Pad / 门店 Pad」**两边各算一条** —— 我第一版按「一条写法不一致」
# 填了 5,实扫是 6。**按实测填,不按估的填** ——
# 一个估出来的上限和一个量出来的上限,在代码里长得一模一样,
# 而前者会在第一次跑的时候就红,然后人会顺手把它改大。
#
# **只许降不许涨。** 归零要业务确认:
#   · 「门店A / 门店B」是历史遗留还是将来要用的
#   · 「官网 / 客服代下单」为什么不在枚举表里
#   · 「门店Pad」这一项该删掉还是该改成「门店 Pad」
对不上上限 = 6

FAIL = []


def ck(name, ok, n, msg=""):
    print(f"  {'✅' if ok else '❌'} {name}(验了 {n} 个){'  ' + msg if msg else ''}")
    if not ok: FAIL.append(name)
    if n == 0:
        print("     ⚠️ 样本量 0 —— **这不叫通过,这叫没扫到东西**")
        FAIL.append(name + "(样本量 0)")


def main():
    print("字典表 · 检查")
    print("=" * 84)
    c = sqlite3.connect(os.path.join(HERE, "lanxiu.db")); c.row_factory = sqlite3.Row

    枚举 = {r["name"] for r in c.execute(
        "SELECT name FROM sys_code WHERE category='订单来源'")}
    数据 = {r["source"] for r in c.execute(
        "SELECT DISTINCT source FROM ordr WHERE source IS NOT NULL AND source<>''")}

    # ── ① 同一个渠道不许有两种写法 ────────────────────────────────────
    # **这条是硬的,不进欠账** —— 它不是历史遗留,是笔误,而笔误该当场修。
    # 判法:把空格去掉之后重名的,就是同一个东西两种写法。
    去空 = {}
    for v in 数据:
        去空.setdefault(v.replace(" ", ""), []).append(v)
    重 = {k: v for k, v in 去空.items() if len(v) > 1}
    ck("同一个渠道不许有两种写法", not 重, len(数据),
       f"{重}" if 重 else
       "**一个空格就够** —— 同一个渠道被算成两个,而报表上它就是多出来的一行")

    # ── ② 枚举表和数据对不上的,不超过上限 ────────────────────────────
    只在表 = sorted(枚举 - 数据)
    只在数据 = sorted(数据 - 枚举)
    对不上 = len(只在表) + len(只在数据)
    ck("订单来源:数据里的值都在枚举表里,或都记在账上",
       对不上 <= 对不上上限, len(枚举 | 数据),
       f"对不上 {对不上} 条(上限 {对不上上限})—— "
       f"**枚举表有而数据没有**:{只在表 or '(无)'};"
       f"**数据有而枚举表没有**:{只在数据 or '(无)'}。"
       f"⚠️ 两个来源都在,**写代码的人照哪一个都像是对的**")

    # ── ③ 枚举表里的每一项,页面筛出来不该是 0 条 ──────────────────────
    # **一个筛出 0 条的选项,比没有这个选项更糟** —— 人会以为「这个渠道没单」。
    空筛 = [v for v in 只在表]
    ck("枚举表里筛出 0 条的选项要记在账上", len(空筛) <= 对不上上限, len(枚举),
       f"{空筛} 这几个在数据里一条都没有 —— "
       f"**筛出 0 条比没有这个选项更糟**:人会以为「这个渠道没单」,"
       f"而真相是「这个渠道不存在」" if 空筛 else "枚举表里每一项都有数据")

    print()
    if FAIL:
        print(f"\033[31m❌ 字典表 {len(FAIL)} 处不符合预期\033[0m")
        for f in FAIL: print(f"   · {f}")
        sys.exit(1)
    print("\033[32m✅ 字典表符合预期\033[0m")
    print(f"    订单来源:枚举表 {len(枚举)} 项、数据里 {len(数据)} 种,"
          f"**对不上 {对不上} 条记在账上**(上限 {对不上上限},只许降不许涨)。")


if __name__ == "__main__":
    main()
