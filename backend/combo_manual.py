#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""人工确认过的相容矩阵格子 —— **读写那份归档文件的唯一一份实现**。

归档文件:`knowledge/相容矩阵-人工确认.json`(手写源,进版本库)。
读的那一头在 `knowledge/derive_combo.py`(推导从它取 OVERRIDE),
写的那一头是后台的「核实回填」(`server.resolve_combo`)。

## 为什么要这份文件(2026-10-23,业务需求池 P3)

后台「核实回填」把打样结论写进库的 `craft_combo`,而那 16 格「人工确认」
原来**写死在 `derive_combo.py` 的 `OVERRIDE` 字典里**。
于是「人确认过的事实」有两个家,**而只有一个家被推导当真** ——
回填一格之后,落库对账报

    ❌ 落库漂移 1 格,md 改过但没重新 seed

**那是个错的诊断**(md 一个字没改),而照着它去跑 `seed.py` 会把那格人工确认
**抹掉** —— 那一格回到待核实队列,**而人已经打过样了**(打样是最贵的那种人工)。

> 它红了,所以不是静默的 —— 比静默好得多。
> 但**红错理由比不红更费事**,而这一条更糟:**照着它去做会造成损失。**

## ⚠️ 单向仍然成立

归档文件和 md 一样是**手写源、进版本库**,推导只读它;
库永远是推导的产物,不是真相源 —— **重建一次库,结论还在文件里**。
(业务需求池 P3 原话:「仍然单向:md → 表」。)

## ⚠️ 这里的日期是来路,而它**不在库里**

`核的日期` 记的是「谁哪天核的」,是来路,不是世界里发生的事。
它在 JSON 文件里,所以**每日平移碰不到它** —— 放在库的文本列里就会被挪
(2026-10-22 那件事:确认书正文里的条款版本被挪成了一个没发布过的版本)。
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
档 = os.path.join(HERE, "..", "knowledge", "相容矩阵-人工确认.json")
结论们 = ("可", "不可", "需评估")


def 读():
    """→ (说明, 格子列表)。文件不在就抛 —— **不许当成「0 格」**。

    当成 0 格的话,那些格子会被规则重新填一遍,
    **而那个结果看起来完全正常**(273 格全有判定)——
    只是人打样的判断被规则的猜测换掉了,而没有任何东西会说出来。
    """
    with open(档, encoding="utf-8") as f:
        d = json.load(f)
    return d.get("_说明", []), d.get("格子", [])


def 记一格(工艺, 材质, 结论, 理由, 核的人, 核的日期):
    """把一格核实结论写进归档文件(同一格覆盖,不追加第二条)。→ (动作, 这一格)。

    ⚠️ **同一格只许一条。** 两条的话谁赢取决于谁写在后面,
    而「覆盖过」和「写了两次」在那个文件里看不出来 —— `derive_combo` 读到重复会拒跑。
    """
    if 结论 not in 结论们:
        raise ValueError(f"结论只能是 {' / '.join(结论们)},收到「{结论}」")
    if not (理由 or "").strip():
        raise ValueError("理由必填 —— 没有理由的「人工确认」和默认放行没区别")
    说明, 格子 = 读()
    新 = {"工艺": 工艺, "材质": 材质, "结论": 结论, "理由": 理由.strip(),
          "核的人": 核的人, "核的日期": 核的日期, "来路": "打样核实"}
    动作 = "新增"
    出 = []
    for g in 格子:
        if (g["工艺"], g["材质"]) == (工艺, 材质):
            动作 = "覆盖"
            continue
        出.append(g)
    出.append(新)
    出.sort(key=lambda g: (g["工艺"], g["材质"]))
    with open(档, "w", encoding="utf-8") as f:
        json.dump({"_说明": 说明, "格子": 出}, f, ensure_ascii=False, indent=1)
        f.write("\n")
    return 动作, 新
