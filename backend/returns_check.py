#!/usr/bin/env python3
"""标品退货率 · 口径守得住(用户 2026-11-15 拍:观察期 / 精确可信范围 / 至少 3 件才判偏高 / 换货单列 / 申请与实际两个率)。

判据真调被测代码:knowledge/returns.py 的 `算()` / `范围()` 用夹具验性质,`api.return_rate` 在这台机器的库上真跑一遍。

    python3 backend/returns_check.py
"""
import datetime as dt
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "knowledge"))
import returns as R  # noqa: E402

G, Rd, D = "\033[32m", "\033[31m", "\033[0m"
坏 = []

咬合 = [
    ("让观察期失效(付款不满 14 天的件也算进分母)", "付款不满观察期的件分子分母一起不算"),
    ("把审批拒绝算进实际退货", "审批拒绝只算申请退货、不算实际退货"),
    ("去掉「至少退过 3 件」那道门槛", "退 1–2 件的不判偏高"),
    ("把换货并进退货", "换货单独一个率,不并进退货"),
]


def ck(名, ok, 话=""):
    print(f"  {G + '✅' if ok else Rd + '❌'}{D} {名}" + (f"  {话}" if 话 else ""))
    if not ok:
        坏.append(名)


今天 = dt.date(2026, 11, 15)
旧 = "2026-10-01"        # 满观察期
新 = "2026-11-10"        # 付款 5 天,还在观察期里


def 卖(档, n, 日=旧):
    return [dict(付款日=日, 件数=1, 档=档) for _ in range(n)]


def 售(档, kind, status="已完成", 日=旧, reason="尺寸不合适"):
    return dict(付款日=日, kind=kind, status=status, reason=reason, 档=档)


print("标品退货率 · 口径")
# ① 精确区间:对照公开表的 Clopper-Pearson 值(1/9 → 0.28%–48.25%;0/58 上界 6.16%)
r1, r0 = R.范围(1, 9), R.范围(0, 58)
ck("可信范围是精确区间(对照公开表:1/9 → 0.28%–48.25%、0/58 上界 6.16%)",
   abs(r1[0] - 0.0028) < 0.0002 and abs(r1[1] - 0.4825) < 0.0005 and r0[0] == 0 and abs(r0[1] - 0.0616) < 0.0005,
   f"1/9 = {r1}, 0/58 = {r0}")

# ② 观察期:新付款的件分子分母一起不算
x = R.算(卖("甲", 100) + 卖("甲", 50, 新), [售("甲", "退货退款"), 售("甲", "退货退款", 日=新)], 今天, lambda r: r["档"])
ck("付款不满观察期的件分子分母一起不算", x["全店"]["卖出件"] == 100 and x["全店"]["实际退货"] == 1
   and x["观察期"]["未满观察期的件"] == 50, f"{x['全店']} · 未满 {x['观察期']['未满观察期的件']}")

# ③ 审批拒绝 / 还在审:只进申请、不进实际;原因只数实际退了的
x = R.算(卖("甲", 100), [售("甲", "退货退款"), 售("甲", "退货退款", "审批拒绝", reason="质量问题"),
                         售("甲", "退货退款", "提交申请", reason="质量问题")], 今天, lambda r: r["档"])
ck("审批拒绝只算申请退货、不算实际退货", x["全店"]["申请退货"] == 3 and x["全店"]["实际退货"] == 1
   and x["全店"]["申请被拒"] == 1 and [o["原因"] for o in x["退货原因"]] == ["尺寸不合适"], f"{x['全店']}")

# ④ 换货单列
x = R.算(卖("甲", 100), [售("甲", "换货"), 售("甲", "换货")], 今天, lambda r: r["档"])
ck("换货单独一个率,不并进退货", x["全店"]["换货"] == 2 and x["全店"]["实际退货"] == 0 and x["全店"]["换货率"] == 2.0,
   f"{x['全店']}")

# ⑤ 至少 3 件才判偏高:大盘 1%,一个小档卖 2 件退 1 件 / 卖 9 件退 2 件 —— 范围都高于大盘,但件数不够
大 = 卖("大", 10000)
售大 = [售("大", "退货退款") for _ in range(100)]
x = R.算(大 + 卖("小1", 2) + 卖("小2", 9) + 卖("够", 20),
         售大 + [售("小1", "退货退款")] + [售("小2", "退货退款")] * 2 + [售("够", "退货退款")] * 3, 今天, lambda r: r["档"])
判 = {r["档"]: r["实际退货"]["判"] for r in x["各档"]}
ck("退 1–2 件的不判偏高", 判["小1"] == "说不清" and 判["小2"] == "说不清", f"{判}")
ck("退够 3 件、范围整体高于大盘的判偏高(门槛没把真信号一起挡掉)", 判["够"] == "偏高", f"{判}")

# ⑥ 0 退货:小样本说不清(不许读成「偏低 / 最不容易退」),大样本才可能偏低
x = R.算(大 + 卖("零小", 58) + 卖("零大", 5000), 售大, 今天, lambda r: r["档"])
判 = {r["档"]: r["实际退货"]["判"] for r in x["各档"]}
ck("0 退货的小样本判「说不清」,不是偏低", 判["零小"] == "说不清", f"{判}")
ck("提醒一直带着(造数种进去的率)", "种进去" in x["提醒"])

# ⑦ 真调工具:这台机器的库上跑一遍(只读)
try:
    import api
    r = api.return_rate()
    ok = "error" not in r and r["全店"]["卖出件"] > 0 and r["维度"] == "品类" and r["各档"]
    ck("api.return_rate 在这台机器的库上真跑得通(默认按品类)", ok,
       f"卖出 {r.get('全店', {}).get('卖出件')} 件 · {len(r.get('各档', []))} 档")
    e = api.return_rate(dim="颜色")
    ck("不认识的维度报错,不静默换成默认", "error" in e)
    m = api.return_rate(month="2026/10")
    ck("付款月格式不对报错", "error" in m)
except Exception as ex:   # noqa: BLE001
    ck("api.return_rate 在这台机器的库上真跑得通", False, f"{type(ex).__name__}: {ex}")

print()
print(f"{G}✅ 标品退货率口径全过{D}" if not 坏 else f"{Rd}❌ 标品退货率 {len(坏)} 条不过:{坏}{D}")
sys.exit(1 if 坏 else 0)
