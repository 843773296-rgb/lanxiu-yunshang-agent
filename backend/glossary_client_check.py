#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""聊天站取术语 · 检查(不调模型、不碰库、不发任何请求)

这条检查盯的是 `backend/glossary_client.py` 的四件事(为什么是这四件,见那个文件的文件头):

  ① 比**内容哈希**,不比版本号 —— 版本号没动而内容换了,必须重取
  ② **六种「空」不许说同一句话** —— 没配 / 没挂 / **后台没配这个角色的助手(404)** /
     字段还没上 / 取不到(有缓存)/ 取不到(没缓存)。六种都会让这一轮不带或少带术语,
     而含义和下一步**完全不同**。
     ⚠️ 那个 404 是 2026-11-06 **真跑一次才发现的第六种** —— 前五种的用例全是我自己摆的
     假响应,而我压根没想到还有这一种。所以多了一条:**404 不许打告警**
     (开发机本来就是 404,打多了就没人看,真的连不上那天也没人看)
  ③ 「当前该用哪一版」**字段缺失 ≠ 显式 null** —— 前者要去同步契约,后者是业务状态
  ④ **不另写一份匹配实现** —— 必须 import 后台那份纯函数

⚠️ 整条检查**把发请求那一处换成假的**,所以它在任何机器上都跑得出同一个结果,
   不依赖「这台机器上有没有管理后台」。这是刻意的:
   > 一条「红不红取决于环境里碰巧有什么」的判据,**不是在验代码**。
"""
import ast
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import glossary_client as GC                                   # noqa: E402

G, R, D = "\033[32m", "\033[31m", "\033[0m"
坏, n = [], 0


def ck(名, 得, 应):
    global n
    n += 1
    ok = (得 == 应)
    print(f"  {G + '✅' + D if ok else R + '❌' + D} {名}" + ("" if ok else f"\n       得到={得!r}\n       应={应!r}"))
    if not ok:
        坏.append(名)


# 咬合 —— 改坏的是什么、该红的是哪一条。(可执行的在 tools/bite_specs.json)
咬合 = [
    ("让「要不要重取」改成比版本号(版本号没动、内容换了就发现不了)", "内容哈希不一样就重取,哪怕版本号相同"),
    ("把「字段还没上」和「没挂」合并成同一个态", "字段缺失和显式 null 不是同一个态"),
    ("让「取不到后台但有缓存」那句话不提「可能不是最新」", "取不到后台而用缓存时,话里要说清它可能不是最新"),
    ("把 404 那一支关掉 —— 于是「后台没配这个角色的助手」被当成「连不上」并打告警",
     "404 是业务状态,不打告警"),
]


class 假curl:
    """把发请求那一处换成假的 —— 按路径返回预先摆好的 (码, 体)。"""

    def __init__(self, 表):
        self.表 = 表
        self.问过 = []

    def __call__(self, 方法, 路径, cfg, 体=None, 幂等键=None):
        self.问过.append(路径)
        for 键, 值 in self.表.items():
            if 键 in 路径:
                return 值
        return ("500", None)


def 摆(表, cfg=("后台", "proj", "60000008"), 缓存=None):
    """换掉 配置() / _curl() / 读缓存() / 写缓存(),返回那个假 curl 以便事后查它问过什么。"""
    f = 假curl(表)
    GC._tc.配置 = (lambda: dict(地址=cfg[0], 项目=cfg[1], 工号=cfg[2])) if cfg else (lambda: None)
    GC._tc._curl = f
    GC.读缓存 = lambda: 缓存
    GC.写缓存 = lambda x: True
    return f


print("聊天站取术语 · 检查(不发请求、不碰库)")
print("     验的是 6 种「空」各说一句不同的话 + 404 不告警 + 哈希比对 + 不另写匹配实现")

一版 = {"id": "v-1", "版本": "v3", "内容哈希": "abc123", "冻结于": "2026-11-06T17:00:00",
        "术语": [{"标准词": "到店转化率", "叫法": ["到店转化"], "定义": "预约里真的来店的比例"}]}

# ── ③ 字段缺失 ≠ 显式 null ──────────────────────────────────────────
摆({"/chat-assistants/": ("200", {"版": 7})})                    # 响应里没有 glossary_version_id
缺 = GC.同步("guide")
摆({"/chat-assistants/": ("200", {"版": 7, "glossary_version_id": None})})
空挂 = GC.同步("guide")
ck("字段缺失和显式 null 不是同一个态", (缺["态"], 空挂["态"]), ("字段还没上", "没挂"))
ck("两种都不带术语(但原因不同)", (缺["条数"], 空挂["条数"]), (0, 0))

# ── 第六种:后台没给这个角色配助手(404)—— 业务状态,不是连不上 ──────
# ⚠️ 真跑一次才发现的。开发机上这三个角色名全是 404,而代码当时把它当「连不上」打告警。
摆({"/chat-assistants/": ("404", {"code": "NOT_FOUND", "message": "没有角色 guide 的聊天助手"})})
没助手 = GC.同步("guide")
ck("后台没配这个角色的助手 → 单独一个态,不是「取不到」", 没助手["态"], "没配助手")
ck("404 是业务状态,不打告警", "⚠️" in GC.一句话(没助手), False)
# 而真的连不上**必须**打告警 —— 两条一起才钉得住,少了这一条就是把告警一刀切掉
摆({"/chat-assistants/": ("500", None)})
连不上 = GC.同步("guide")
ck("真的连不上 → 照旧打告警(别把告警一刀切掉)", "⚠️" in GC.一句话(连不上), True)

# ── 走真入口:没配地址 → 不带术语,而且**一个请求都不发** ─────────────
f = 摆({"/chat-assistants/": ("200", {"glossary_version_id": "v-1"})}, cfg=None)
没配 = GC.同步("guide")
ck("没配后台地址 → 态是「没配」", 没配["态"], "没配")
ck("没配时一个请求都不发(别对着空地址发 curl)", f.问过, [])

# ── 正常路:取到那一版 ──────────────────────────────────────────────
摆({"/chat-assistants/": ("200", {"glossary_version_id": "v-1"}),
    "/glossary-versions/": ("200", 一版)})
好 = GC.同步("guide")
ck("取到了 → 来源是「后台」", 好["来源"], "后台")
ck("取到了 → 条数和哈希都带出来", (好["条数"], 好["内容哈希"]), (1, "abc123"))

# ── 取不到后台:有缓存用缓存、没缓存不带 ─────────────────────────────
摆({"/chat-assistants/": ("200", {"glossary_version_id": "v-1"}),
    "/glossary-versions/": ("500", None)},
   缓存={"版本id": "v-1", "版本": "v3", "内容哈希": "abc123", "术语": 一版["术语"], "取到于": "2026-11-05T09:00:00"})
退缓存 = GC.同步("guide")
ck("取不到后台而本地有同一版 → 用缓存", (退缓存["来源"], 退缓存["条数"]), ("缓存", 1))
摆({"/chat-assistants/": ("200", {"glossary_version_id": "v-1"}),
    "/glossary-versions/": ("500", None)}, 缓存=None)
退空 = GC.同步("guide")
ck("取不到后台且没缓存 → 不带术语,而且话里说清这不是「没挂术语」",
   退空["来源"] == "没有" and "不是「没挂术语」" in 退空["说明"], True)

# ── ② 每一种「空」都不许说同一句话 ──────────────────────────────────────
# 五种都让这一轮不带或少带术语,而下一步完全不同:
# 没配 → 不用管;没挂 → 不用管;字段还没上 → 去同步契约;
# 取不到+有缓存 → 看它有多旧;取不到+没缓存 → 这一轮的回答没有术语兜底。
空们 = {名: GC.一句话(st) for 名, st in
        (("没配", 没配), ("没挂", 空挂), ("没配助手(404)", 没助手), ("字段还没上", 缺),
         ("取不到·有缓存", 退缓存), ("取不到·没缓存", 退空))}
print(f"     验了 {len(空们)} 种「空」各自那一句:")
for 名, 句 in 空们.items():
    print(f"       · {名}:{句}")
ck("每一种「空」两两都不是同一句话", len(set(空们.values())), len(空们))
ck("取不到后台而用缓存时,话里要说清它可能不是最新", "可能不是最新" in 空们["取不到·有缓存"], True)

# ── ① 比内容哈希,不比版本号 ────────────────────────────────────────
同 = {"版本id": "v-1", "版本": "v3", "内容哈希": "abc123", "术语": []}
ck("同一个内容哈希 → 不重取", GC.要不要重取(同, "abc123")[0], False)
ck("内容哈希不一样就重取,哪怕版本号相同", GC.要不要重取(同, "改过了")[0], True)
ck("缓存里没有内容哈希(老格式)→ 重取",
   GC.要不要重取({"版本id": "v-1", "版本": "v3", "术语": []}, "abc123")[0], True)
ck("本地压根没缓存 → 重取", GC.要不要重取(None, "abc123")[0], True)

# ── 缓存坏掉不许崩 ──────────────────────────────────────────────────
import importlib                                                             # noqa: E402
importlib.reload(GC)                     # 换回真的 读缓存
GC._落盘 = os.path.join(HERE, ".glossary_不存在的缓存.json")
ck("缓存文件不存在 → 当没有缓存,不崩", GC.读缓存(), None)
坏文件 = os.path.join(HERE, ".glossary_坏掉的缓存.json")
with open(坏文件, "w", encoding="utf-8") as _f:
    _f.write("{这不是 json")
GC._落盘 = 坏文件
ck("缓存文件坏掉 → 当没有缓存,不崩", GC.读缓存(), None)
os.remove(坏文件)

# ── ④ 不另写一份匹配实现 ────────────────────────────────────────────
# 后台那份纯函数就是「试一下」接口调的那一份。这里**只许 import,不许自己扫**。
# > 两边都在做最长匹配,和两边口径一样,是两件事 —— 而两边不一样时,谁都不会红。
ck("后台那份纯函数找得到(路径没漂)", os.path.exists(GC._纯函数), True)
_树 = ast.parse(io.open(os.path.join(HERE, "glossary_client.py"), encoding="utf-8").read())
_自己扫的 = [x.func.attr for x in ast.walk(_树)
            if isinstance(x, ast.Call) and isinstance(x.func, ast.Attribute)
            and x.func.attr in ("startswith", "find", "index") and not isinstance(x.func.value, ast.Name)]
ck("这个文件里没有自己的匹配扫描(该 import 后台那份)", _自己扫的, [])
_叫了 = {x.func.attr for x in ast.walk(_树)
        if isinstance(x, ast.Call) and isinstance(x.func, ast.Attribute)}
ck("真的在调后台那份的 匹配 / 上下文段", {"匹配", "上下文段"} <= _叫了, True)

print()
print(f"  (验了 {n} 条)")
if n == 0:
    print(f"{R}❌ 一条都没验{D}")
    sys.exit(1)
if 坏:
    print(f"{R}❌ 取术语 {len(坏)} 条不过{D}")
    sys.exit(1)
# ⚠️ **条数现数,不写在话里** —— 项目里一天抓到五处写死的条数漂了(2026-11-04)。
print(f"{G}✅ 取术语:{len(空们)} 种「空」各说一句不同的话(404 不告警、连不上要告警)、"
      f"比内容哈希不比版本号、"
      f"字段缺失≠显式 null、缓存坏掉不崩、匹配只有一份实现{D}")
