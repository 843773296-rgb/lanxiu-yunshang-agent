# -*- coding: utf-8 -*-
"""订单的**两套状态**必须真的分开 —— 定制品 6 步,标品 5 步。

## 这是业务 2026-09-18 明确要求的

> 「订单中,标品和定制品是两套不同的状态,要做好区分」

2026-09-18 通篇读了 Figma《澜绣云裳管理后台》的「门店购买」节,
两套流程在稿子里是**同一个组件的两个变体**:

    流程=线下下单(定制品)  买家付款 → 审核定制 → 生产 → 发货 → 签收 → 完成   6 步
    流程=app下单(标品)     买家付款 → 审核     →      发货 → 签收 → 完成   5 步

订单日志组件里有两条白纸黑字的印证:
「微信小程序订单**支付后自动审核通过**」、
「订单生产完成 …… **注意:小程序订单无生产环节**」。

## 为什么非得有程序守着

库里**一张 `ordr` 表、一套状态词**,`kind` 只是个标签 ——
也就是说**标品也存得下「待生产」**。库允许,业务不允许。
而存下去之后没有任何东西会报:列表页照样列,详情页照样渲染,
只有懂业务的人看见「一件标品在生产中」才会觉得不对。

2026-09-18 这天正在重建整个订单数据集(见 `intent/order-aftersale-dataset.md`),
**这条检查就是给那次重建当护栏的** —— 生成器要是把生产三档发给了标品,这里会红。

## 允许集是**手抄的**,故意不从库里现算

从库里现算「标品用过哪些状态」再拿去校验标品,那是拿被测数据当期望值 ——
这个项目管它叫**同源谬误**:数据漂了检查跟着漂,永远绿。

所以下面两个集合是**照着设计稿抄下来的常数**,和
`knowledge/pinned_check.py` 里那 8 个锚点是同一个做法。
稿子改了要手动改这里 —— 那正是想要的:**改口径应该是一件要动手的事。**
"""
import os
import sqlite3
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FAIL = []
DONE = []

# ── 照设计稿手抄的两套状态 ────────────────────────────────────────────
生产三档 = ("待生产", "生产中", "已生产")

# 「待确认」:业务 09-22 加的 —— 开了单、还没确认下单(每一件量完下单量体才许确认);只定制单有
定制品允许 = ("待确认", "待付款", "待审核") + 生产三档 + ("待发货", "已发货", "待完成", "完成", "取消")
标品允许 = ("待付款", "待审核", "待发货", "已发货", "待完成", "完成", "取消")

允许 = {"定制品订单": set(定制品允许), "标品订单": set(标品允许)}

# 到了这几档,生产**一定发生过** —— 必须有生产完成时间。
# 「取消」不在里面:一单可以在生产之前就取消。
过了生产 = ("已生产", "待发货", "已发货", "待完成", "完成")


def ck(name, ok, n, msg=""):
    DONE.append(name)
    print(f"  {'✅' if ok else '❌'} {name}(验了 {n} 个){'  ' + msg if msg else ''}")
    if not ok:
        FAIL.append(name)
    if n == 0:
        print("     ⚠️ 样本量 0 —— **这不叫通过,这叫没扫到东西**")
        FAIL.append(name + "(样本量 0)")


def main():
    print("订单状态 · 两套状态必须分开")
    print("=" * 80)
    c = sqlite3.connect(os.path.join(HERE, "lanxiu.db"))
    c.row_factory = sqlite3.Row
    单 = [dict(r) for r in c.execute(
        "SELECT id, kind, status, produced_at FROM ordr")]
    c.close()

    # ── ① 每个订单的状态,必须在它那一类的允许集里 ──────────────────
    #    这是**黑名单**性质:新加一档状态会立刻红,逼人来这里做决定,
    #    而不是悄悄多出一个没人定义过的状态。
    类型 = sorted({r["kind"] for r in 单})
    没定义的类型 = [k for k in 类型 if k not in 允许]
    越界 = [f"{r['id']} 是{r['kind']},状态「{r['status']}」不在允许集里"
           for r in 单 if r["kind"] in 允许 and r["status"] not in 允许[r["kind"]]]
    ck("① 订单状态在它那一类的允许集里", not (越界 or 没定义的类型), len(单),
       (f"没定义状态集的订单类型 {没定义的类型};" if 没定义的类型 else "")
       + (f"越界 {len(越界)} 单:{越界[:3]}" if 越界 else "")
       or f"定制品 {len(定制品允许)} 档 / 标品 {len(标品允许)} 档,各走各的")

    # ── ② 标品**不许**出现生产三档 ────────────────────────────────
    #    这是 ① 的子情况,但单独报:业务的要点就在这一条上,
    #    混在「状态越界」里报,读的人看不出破的是哪条业务规则。
    标品 = [r for r in 单 if r["kind"] == "标品订单"]
    犯 = [f"{r['id']}(「{r['status']}」)" for r in 标品 if r["status"] in 生产三档]
    ck("② 标品不出现生产三档(待生产/生产中/已生产)", not 犯, len(标品),
       f"违规 {len(犯)} 单:{犯[:4]}" if 犯 else
       "标品是现货,没有生产环节 —— 设计稿的 app 下单流程只有 5 步")

    # ── ③ 标品**不许**有生产完成时间 ──────────────────────────────
    #    状态分开了而时间戳还在,等于没分开:
    #    详情页照样渲染出一行「生产完成时间」,而那一单根本没生产过。
    有时间 = [r["id"] for r in 标品 if (r["produced_at"] or "").strip()]
    ck("③ 标品没有生产完成时间", not 有时间, len(标品),
       f"有值的 {len(有时间)} 单:{有时间[:3]}" if 有时间 else
       "**状态分开而时间戳不分开,等于没分开** —— 详情页会渲染出一行不存在的事实")

    # ── ④ 定制品过了生产阶段的,必须有生产完成时间 ──────────────────
    #    反向那一半:光有「标品不许有」不够,还得有「定制品必须有」,
    #    否则把生产完成时间整列清空,前三条全绿。
    定 = [r for r in 单 if r["kind"] == "定制品订单" and r["status"] in 过了生产]
    缺 = [r["id"] for r in 定 if not (r["produced_at"] or "").strip()]
    ck("④ 定制品已过生产阶段的,有生产完成时间", not 缺, len(定),
       f"缺的 {len(缺)} 单:{缺[:3]}" if 缺 else
       "到了已生产/待发货/已发货/待完成/完成,生产一定发生过")

    print("=" * 80)
    if FAIL:
        print(f"❌ {len(FAIL)} 条没过:{FAIL}")
        return 1
    print(f"✅ 两套状态分开 {len(DONE)} 条全过")
    return 0


# ── 咬合记录 ──────────────────────────────────────────────────────────
# **第四条是专门挑的破坏点**:只有前三条时,把 produced_at 整列清空会全绿 ——
# 「标品不许有」在空列上永远成立。**单边的规则是半条规则。**
咬合 = [
    ('把一单标品的状态改成「生产中」', '② 标品不出现生产三档'),
    ('给一单标品填上生产完成时间(状态不动)', '③ 标品没有生产完成时间'),
    ('把 produced_at 整列清空 —— 前三条会全绿', '④ 定制品已过生产阶段的,有生产完成时间'),
    ('把一单订单的状态改成一个谁也没定义过的词', '① 订单状态在它那一类的允许集里'),
]

if __name__ == "__main__":
    sys.exit(main())
