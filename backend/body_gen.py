# -*- coding: utf-8 -*-
"""**按人造尺寸** —— 演示数据里所有「造一套量体值」的地方都走这一个函数。

## 为什么要有它(2026-09-22)

原来三处造量体(seed.py / fix_order_measure.py 两处)抄的是同一张 BASE 表:
胸 86、腰 68、臀 92、肩 38 …… 只有长度按身高缩放。于是**男女老少围度一样**,
2014 年出生的女孩胸围 86;拿去比尺码表,约 65% 的定制单被判成「全定制」——
而真实门店大概一成多。白坯试衣新规(全定制必试)把这个失真直接放大成
「待生产 36 单只有 3 单开得了裁」,演示效果完全不像一家店。

## 怎么造

  围度  按性别 / 年龄 / 身高推(成人参照国标号型 160/84A、170/88A 的比例;
        儿童参照童装号型 110/56 → 140/68,约 0.4×身高+12),加个人差异
  长度  **长度类量的是「客户想要多长」**(10-版型库.md 第六节),所以给了
        「他下单那件衣服的尺码表」时,长度贴着那件的成衣长度 ±2cm;没给就按身高比例
  特体  约 12% 的人体型不标准(围度偏大一截),**让「全定制」有真实样本** ——
        全部造成标准身材,全定制那条判据就永远命中不了,和原来的毛病反过来而已

## 确定性

不用全局随机数:每个人用 `key`(着装人编号)派生自己的随机源 ——
重建多少次同一个人的尺寸都一样,和项目「重建可复现」的约定一致。

⚠️ 已知局限:一个人只存一套长度。买过两种衣长差很多的款式(褙子 90 / 长衫 118)的人,
只能贴其中一件 —— 另一件仍可能被判成全定制。重建后实测剩多少,报给业务。
"""
import hashlib, random

CODE = {"身高": "MI01", "体重": "MI02", "胸围": "MI03", "腰围": "MI04", "臀围": "MI05",
        "肩宽": "MI06", "袖长": "MI07", "衣长": "MI08", "裙长": "MI09", "领围": "MI10",
        "臂围": "MI11", "裤长": "MI12", "胸上围": "MI13", "通袖长": "MI14",
        "头围": "MI15", "腕围": "MI16", "脚长": "MI17"}
长度项 = ("衣长", "裙长", "裤长", "通袖长", "袖长")


def _rng(key):
    return random.Random(int(hashlib.sha256(("body:" + str(key)).encode()).hexdigest()[:12], 16))


def 造尺寸(sex, age, height, key, 款=None, 特体概率=0.12):
    """返回 {量体项名: 值}。

    sex     "女" / "男"(其余按女)
    age     周岁(整数即可)
    height  身高 cm;None 时按性别年龄给一个常见值
    key     着装人编号 —— 同一个人永远造出同一套
    款      可选:{部位: 成衣值},他下单那件衣服**最合身那个码**的尺码表。给了就让长度贴着它
    """
    r = _rng(key)
    男 = sex == "男"
    童 = age is not None and age < 14
    h = float(height or (125 if 童 else (171 if 男 else 160)))
    g = r.gauss
    if 童:
        胸 = 0.40 * h + 12 + g(0, 2.0)
        腰 = 胸 - 5 + g(0, 1.5)
        臀 = 胸 + 4 + g(0, 1.5)
        肩 = 0.225 * h + g(0, 0.8)
        领 = 0.20 * 胸 + 15 + g(0, 0.6)
        重 = (h / 100) ** 2 * (16 + g(0, 1.5))
    else:
        胸 = (0.518 if 男 else 0.525) * h + g(0, 3.0)
        腰 = 胸 - (13 if 男 else 15) + g(0, 2.5)
        臀 = 胸 + (2 if 男 else 6) + g(0, 2.5)
        肩 = (0.257 if 男 else 0.245) * h + g(0, 1.1)
        领 = (0.23 * 胸 + 16.8) if 男 else (0.21 * 胸 + 15.6)
        重 = (h / 100) ** 2 * ((23 if 男 else 21) + g(0, 2.2))
    特 = r.random() < 特体概率
    if 特:
        # 体型不标准:围度整体偏大一截(胸 / 腰 / 臀一起,腰更多)——
        # 真实门店里全定制多半是这个原因,而不是长度
        加 = 9 + r.random() * 8
        胸 += 加; 腰 += 加 * 1.3; 臀 += 加 * 0.9; 重 *= 1.18
    头 = (50 + 0.03 * h if 童 else (56.5 if 男 else 55)) + g(0, 0.8)
    out = {"身高": h, "体重": 重, "胸围": 胸, "腰围": 腰, "臀围": 臀, "肩宽": 肩,
           "头围": 头, "腕围": (0.095 * h if 童 else (16.8 if 男 else 15.5)) + g(0, 0.5),
           "脚长": 0.15 * h + g(0, 0.5),
           "领围": 领, "臂围": 0.30 * 胸 + g(0, 0.8), "胸上围": 胸 - (3 if 男 else 4) + g(0, 1.0),
           "袖长": 0.33 * h + g(0, 1.0),
           "衣长": 0.62 * h + g(0, 2.0), "裙长": 0.58 * h + g(0, 2.0),
           "裤长": 0.60 * h + g(0, 2.0), "通袖长": 1.02 * h + g(0, 3.0)}
    if 款:
        # 长度 = 「想要多长」—— 贴着他下单那件的成衣长度,个人偏好 ±2cm
        for 部位, 值 in 款.items():
            if 部位 in 长度项 and 值:
                out[部位] = float(值) + g(0, 1.5)
    return {k: round(v, 1) for k, v in out.items()}, 特


def 按编码(sex, age, height, key, 特体概率=0.12):
    """同 `造尺寸`,返回 {量体项编码: 值}(造数脚本按编码写 measure_rec)。
    马面宽度(MI18)不是人体尺寸,**不造** —— 模板里有这一项的,由调用方按原样处理。"""
    d, 特 = 造尺寸(sex, age, height, key, 特体概率=特体概率)
    return {CODE[k]: v for k, v in d.items() if k in CODE}, 特


def 周岁(birthday, on):
    """生日 + 某一天 → 周岁;生日缺就返回 None(按成人造)。"""
    try:
        b, o = str(birthday)[:10], str(on)[:10]
        a = int(o[:4]) - int(b[:4])
        return a - (1 if o[5:] < b[5:] else 0)
    except Exception:
        return None


if __name__ == "__main__":
    # 自测:确定性、男女有别、儿童不是成人围度、特体约一成
    a1, _ = 造尺寸("女", 30, 160, "W1"); a2, _ = 造尺寸("女", 30, 160, "W1")
    assert a1 == a2, "同一个人两次造出来不一样 —— 重建不可复现"
    m, _ = 造尺寸("男", 30, 172, "W2"); f, _ = 造尺寸("女", 30, 160, "W3")
    k, _ = 造尺寸("女", 8, 125, "W4")
    assert k["胸围"] < 70, f"8 岁孩子胸围 {k['胸围']} —— 又造成成人围度了"
    assert m["肩宽"] > f["肩宽"], "男女肩宽没拉开"
    特 = sum(造尺寸("女", 30, 160, f"K{i}")[1] for i in range(1000))
    assert 60 < 特 < 180, f"特体 {特}/1000,应在一成上下"
    print(f"✅ 按人造尺寸自测通过:确定性 / 男女有别 / 8 岁胸围 {k['胸围']} / 特体 {特}/1000")
