def 字段怎么打(字段名):
    """→ 打码函数 或 None(原样 / 不在清单里)。按清单里的常见字段名对,不分大小写。"""
    k = str(字段名 or "").strip().lower()
    for 项 in 清单():
        if k in {str(x).lower() for x in 项.get("常见字段名") or []}:
            return _打法.get(项.get("类型"))
    return None


def 给人看行(行, 跳过=()):
    """就地把一行(dict)里清单上要打码的字段打掉,回同一个 dict。`跳过` 里的键不动(比如页面另有 phone_mask、要把 phone 整个去掉的)。
    不是清单上的键一个字不碰;清单上「原样」的也不碰。"""
    if not isinstance(行, dict):
        return 行
    for k in list(行.keys()):
        if k in 跳过:
            continue
        f = 字段怎么打(k)
        if f and 行.get(k) not in (None, ""):
            行[k] = f(行[k])
    return 行


