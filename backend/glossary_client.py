def 实体识别哪一版(角色):
    """→ (版本id, 说明, 态)。和 `哪一版()` 同一套三态,读的是生产配置里的 entity_version_id。"""
    cfg = _tc.配置()
    if not cfg:
        return None, "没配管理后台地址 —— 用代码里的默认三本词典实体识别", "没配"
    码, 体 = _tc._curl("GET", f"/chat-assistants/by-role/{角色}/production", cfg)
    if 码 == "404":
        return None, f"后台没给角色「{角色}」配聊天助手 —— 用代码里的默认三本词典实体识别", "没配助手"
    if 码 != "200" or not isinstance(体, dict):
        return None, f"取生产聊天助手配置拿不到 200(码={码})—— 环境问题,不是「没挂实体识别」", "取不到"
