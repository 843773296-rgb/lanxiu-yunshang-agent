#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""聊天站拿术语:**本地存一版冻结的,启动时同步**(用户 2026-11-06 拍)。

## 为什么是这个形状(摆给用户的那张卡上的三条代价)

| 选法 | 代价 |
|---|---|
| **本地存一版冻结的**(选了这个) | 顾问聊天**不依赖管理后台** —— 后台挂了照样能聊;术语改了要等下一次同步才生效 |
| 每条消息都向后台要最新的 | 始终最新,但聊天站多一个外部依赖:后台不在时,要么不带术语照答(顾问看不出少了什么),要么停下来报错 |

用户拍了第一个,理由是「冻结版本不可变」正好适合缓存:**版本里的内容不会漂,
只会漂「用的是哪一版」** —— 而那个版本号印在回答的来源里,看得见。

## 四件这个模块必须做对的事(每一条都是项目里栽过的形状)

### ① 比**内容哈希**,不比版本号
版本号相同而内容换掉了,这种事必须发现得了。并行会话那边连接指纹吃过同一个坑:
「能力真变了」和「只是又探了一次」在同一个哈希上分不开。
> 一个「还是那一版」和一个「版本号没动、内容换了」,**在版本号上长得一模一样。**

### ② 六种「空」要分得开,**绝不能都返回空列表**
  · **没配后台地址** → 这台机器就没接(开发机、CI 都是这样)
  · **连上了,而这一版一条术语都没有** → 生产的真实状态,聊天站不带术语是对的
  · **后台没给这个角色配聊天助手**(404 NOT_FOUND)→ 业务状态,开发机本来就这样,
    **不该告警**。⚠️ 这一种是 2026-11-06 **真跑一次才发现的**:五种「空」的单测全是我
    自己摆的假响应,而我压根没想到还有这一种
  · **没连上 / 别的非 200** → 评测或生产环境和预期不一样,该用上一次缓存**并说出来**,
    不许静默照答

> 「后台没为这个角色配助手」和「后台连不上」,**在「不是 200」这件事上长得一模一样** ——
> 而前者不该告警,后者必须告警。
`takeover_guard` 把 `接管中: []` 和 `连上了: False` 拆成两个字段就是这个形状,照它拆。

### ③ 「当前该用哪一版」有三态,不是两态
它挂在聊天站本来就在调的 `/chat-assistants/by-role/{角色}/production` 响应里
(换术语版本 = 换聊天助手版本,发布那一步天然把关)。三态:
  · 字段**缺失** → 后台还没上那个字段,**是我该去同步契约**,不是业务状态
  · 显式 **null** → 这一版聊天助手**没挂术语**(业务状态)
  · 有值 → 用这一版
> 字段缺失和显式 null,**在 `.get()` 的结果上长得一模一样** —— 而下一步相反。

### ④ **不另写一份匹配实现**
匹配 / 拼给模型那段,一律 import `管理后台/services/api/app/runtime/术语.py` 里那两个纯函数
(后台的「试一下」接口调的也是它)。
> 两边都在做最长匹配,和两边口径一样,**是两件事** ——
> 而两边算出来不一样的时候,谁都不会红。
(判据在 `backend/glossary_client_check.py`:这个文件里不许出现自己的匹配循环。)

⚠️ **这个模块还没接进聊天站给模型读的那段。** 2026-11-06 傍晚正在跑技能触发评测的
新基线,而往那段里加任何东西都会让基线作废(10-27 吃过一次:给每个角色多挂一个
只读工具,49 道题每一道的上下文都变了,三条题同时翻面、整轮归不了因)。
基线存完再接。
"""
import json
import os
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
_纯函数 = os.path.join(ROOT, "管理后台", "services", "api", "app", "runtime", "术语.py")
_落盘 = os.path.join(HERE, ".glossary_last.json")

import takeover_client as _tc      # 地址 / 项目 / 服务账号工号和 curl 那一处共用


def 术语模块():
    """后台那份纯函数,**按路径 import,不复制** —— 复制出来的那份会和后台悄悄分叉。"""
    import importlib.util as u
    sp = u.spec_from_file_location("术语纯函数", _纯函数)
    m = u.module_from_spec(sp)
    sp.loader.exec_module(m)
    return m


def 哪一版(角色):
    """→ (版本id, 说明, 态)。态 ∈ {"有", "没挂", "字段还没上", "取不到", "没配"}。

    ⚠️ 三态见文件头 ③:**字段缺失 ≠ 显式 null**。"""
    cfg = _tc.配置()
    if not cfg:
        return None, "没配管理后台地址 —— 这台机器没接术语(开发机 / CI 都是这样)", "没配"
    码, 体 = _tc._curl("GET", f"/chat-assistants/by-role/{角色}/production", cfg)
    # ⚠️ **404 不是环境问题**:后台还没给这个角色配聊天助手(开发机本来就这样)。
    # 把它和「连不上」混成一个的后果是:开发机上每次启动都打一个假告警,
    # 而**打多了就没人看**,真的连不上那天也没人看。
    if 码 == "404":
        return (None, f"后台没给角色「{角色}」配聊天助手 —— 那它也就没挂术语版本;"
                      f"这是业务状态,**不是连不上**", "没配助手")
    if 码 != "200" or not isinstance(体, dict):
        return None, f"取生产聊天助手配置拿不到 200(码={码})—— 这是环境问题,不是「没挂术语」", "取不到"
    if "glossary_version_id" not in 体:
        return (None, "生产聊天助手配置里**没有 glossary_version_id 这个字段** —— "
                      "后台契约还没上这一项,要去同步契约,**不是「这一版没挂术语」**", "字段还没上")
    vid = 体.get("glossary_version_id")
    if vid is None:
        return None, "这一版聊天助手**没挂术语**(显式 null)—— 这是业务状态,聊天站不带术语是对的", "没挂"
    return vid, f"该用术语版本 {vid}", "有"


def 取一版(vid):
    """→ (那一版, 说明)。一次给全(项目 / key / 版本 / 冻结于 / 内容哈希 / 术语)。"""
    cfg = _tc.配置()
    if not cfg:
        return None, "没配管理后台地址"
    码, 体 = _tc._curl("GET", f"/glossary-versions/{vid}", cfg)
    if 码 != "200" or not isinstance(体, dict):
        return None, f"取术语版本 {vid} 拿不到 200(码={码})"
    return 体, f"取到 {体.get('版本')}({len(体.get('术语') or [])} 条,哈希 {体.get('内容哈希')})"


def 读缓存():
    try:
        with open(_落盘, encoding="utf-8") as f:
            d = json.load(f)
        return d if isinstance(d, dict) and d.get("版本id") else None
    except Exception:                                                        # noqa: BLE001
        return None          # 没有 / 坏掉 / 读不了 —— 都当「没有缓存」,**不崩**


def 写缓存(那一版):
    try:
        with open(_落盘, "w", encoding="utf-8") as f:
            json.dump({"版本id": 那一版.get("id"), "版本": 那一版.get("版本"),
                       "内容哈希": 那一版.get("内容哈希"), "冻结于": 那一版.get("冻结于"),
                       "术语": 那一版.get("术语") or [], "取到于": time.strftime("%Y-%m-%dT%H:%M:%S")},
                      f, ensure_ascii=False)
        return True
    except Exception:                                                        # noqa: BLE001
        return False         # 写不下去不影响这一轮能用,只是下次还得重取


def 要不要重取(缓存, 后台哈希):
    """⚠️ 见文件头 ①:**比内容哈希,不比版本号。**

    缓存里没有哈希(老格式)→ 重取;哈希不一样 → 重取,**哪怕版本号一模一样**。"""
    if not 缓存:
        return True, "本地没有缓存"
    if not 缓存.get("内容哈希"):
        return True, "本地缓存没有内容哈希(老格式)—— 不敢认它是同一版"
    if 后台哈希 and 缓存["内容哈希"] != 后台哈希:
        return True, (f"内容哈希不一样(本地 {缓存['内容哈希']} ≠ 后台 {后台哈希})—— "
                      f"**哪怕版本号相同也重取**")
    return False, "本地缓存和后台同一个内容哈希"


def 同步(角色):
    """启动时调一次。→ 状态 dict,字段都是给人看的,**每一种情形一句不同的话**。

    `来源` ∈ {"后台", "缓存", "没有"};`态` 原样带出 `哪一版()` 的那五种。
    """
    vid, 说, 态 = 哪一版(角色)
    缓存 = 读缓存()
    底 = dict(角色=角色, 态=态, 说明=说, 版本=None, 版本id=None, 内容哈希=None,
              术语=[], 条数=0, 来源="没有", 取到于=None)
    if 态 in ("没配", "没挂", "没配助手"):
        return 底                       # 三种都不该带术语、都不该告警,而 `态` 把它们分开了
    if 态 in ("取不到", "字段还没上"):
        if 缓存:
            底.update(版本=缓存.get("版本"), 版本id=缓存.get("版本id"), 内容哈希=缓存.get("内容哈希"),
                      术语=缓存.get("术语") or [], 条数=len(缓存.get("术语") or []), 来源="缓存",
                      取到于=缓存.get("取到于"),
                      说明=说 + f";**用上一次缓存的 {缓存.get('版本')}**(取到于 {缓存.get('取到于')})")
        return 底
    那一版, 说2 = 取一版(vid)
    if 那一版 is None:
        if 缓存 and 缓存.get("版本id") == vid:
            底.update(版本=缓存.get("版本"), 版本id=vid, 内容哈希=缓存.get("内容哈希"),
                      术语=缓存.get("术语") or [], 条数=len(缓存.get("术语") or []), 来源="缓存",
                      取到于=缓存.get("取到于"), 态="取不到",
                      说明=说2 + f";**用上一次缓存的同一版**(取到于 {缓存.get('取到于')})")
        else:
            底.update(态="取不到", 说明=说2 + ";本地也没有这一版的缓存 —— 这一轮不带术语,**而这不是「没挂术语」**")
        return 底
    要, 为什么 = 要不要重取(缓存 if (缓存 or {}).get("版本id") == vid else None, 那一版.get("内容哈希"))
    if 要:
        写缓存(那一版)
    底.update(版本=那一版.get("版本"), 版本id=那一版.get("id"), 内容哈希=那一版.get("内容哈希"),
              术语=那一版.get("术语") or [], 条数=len(那一版.get("术语") or []),
              来源="后台", 取到于=time.strftime("%Y-%m-%dT%H:%M:%S"),
              说明=说2 + ";" + 为什么)
    return 底


def 一句话(状态):
    """印在回答来源 / 日志里的那一行 —— **每种情形一句不同的话**(判据钉着这一点)。"""
    态 = 状态.get("态")
    if 态 == "没配":
        return "术语:这台机器没接管理后台 —— 这一轮**不带术语**(不是「没挂术语」)"
    if 态 == "没挂":
        return "术语:这一版聊天助手没挂术语表 —— 这一轮不带术语(生产的真实状态)"
    if 态 == "没配助手":
        return ("术语:后台还没给这个角色配聊天助手 —— 这一轮不带术语。"
                "**这不是连不上**,所以不报警(开发机本来就这样)")
    if 态 == "字段还没上":
        return ("⚠️ 术语:后台生产配置里还没有 glossary_version_id 这个字段 —— "
                "**要去同步契约**" + (f";这一轮用缓存的 {状态.get('版本')}" if 状态.get("来源") == "缓存" else ";这一轮不带术语"))
    if 态 == "取不到":
        return ("⚠️ 术语:取不到后台 —— "
                + (f"这一轮用缓存的 {状态.get('版本')}(取到于 {状态.get('取到于')}),**可能不是最新的**"
                   if 状态.get("来源") == "缓存" else "本地也没有缓存,这一轮不带术语"))
    return (f"术语:{状态.get('版本')} · {状态.get('条数')} 条 · 哈希 {状态.get('内容哈希')} "
            f"· 取自{状态.get('来源')}")


def 这一段(文本, 状态):
    """这次要塞给模型的那一段。**调后台那份纯函数**,不另写(见文件头 ④)。

    一条术语都没提到 → 空串(不带空壳)。"""
    T = 术语模块()
    术语们 = 状态.get("术语") or []
    命 = T.匹配(文本, 术语们)
    return T.上下文段(命, 术语们), 命


# ── 这一轮到底塞进去了什么:给评测的口径用 ────────────────────────────────
#
# 为什么要有这个登记,而不是让评测那边「传一个参数进来」:
# 接术语之后,如果装配那一处忘了改那个实参,基线会老实写「没接术语」——
# **而它和真的没接,在基线文件里长得一模一样。**
#
# 2026-10-27 那三条漏触发查了三轮实验、约四小时,根因正是同一个形状:
# 基线里只有「目录里有哪几份技能」,没有「真挂给了模型哪几个」。
#
# ⚠️ 登记**也会漏**(某一轮没走到那条路,表里却留着上一轮的值)。所以两件:
#   ① 每一轮装配前要 `清一轮()`,`这一轮塞了什么()` 只认本轮登记的
#   ② `agentsite/skill_eval_truth_check.py` 有一条**条件接线断言**:
#      装配代码里只要出现了 `这一段(` 的调用,就必须同时出现 `记一笔(`;
#      两个都没出现 = 这一版还没接,那时它明说「没东西可验」而不是「验过了」
_这一轮 = {}

# ⚠️ **「这个模块在」和「装配真的接上它了」是两回事。**
# 第一版我拿 `import` 成不成功去判断「接没接」—— 而 import 成功只说明**文件在**,
# 不说明**有人调它**:于是「模块在、装配没接」和「装配接了、这一轮没走到那条路」
# 返回了同一个结果,而两者下一步完全不同(一个是「还没做」,一个是「做了但接线断了」)。
#
# 这是这个项目最老那条教训的同一张脸:`allowed_tools` 不是排他白名单 ——
# **「模型没用」和「模型不能用」是两回事**。
# 所以接上它的那一侧必须**显式宣告一次**,别让人从 import 去推。
_接上了 = False


def 宣告接上了():
    """装配上下文的那个模块在**自己被 import 的时候**调一次。

    放在模块顶层(不是函数里)—— 它要回答的是「这一版代码接没接」,
    而不是「这一次调用有没有走到」。后者是 `记一笔()` 的事。
    """
    global _接上了
    _接上了 = True


def 接上了吗():
    return _接上了


def 记一笔(状态, 命中=None, 字数=None):
    """装配上下文时塞了术语,在这里登记一笔。**塞了多少就记多少,没塞也要记。**

    「没塞」要记成 `{"态": …, "条数": 0}` 这样的真值,**不是不记** ——
    不记和「这一版压根没接术语」在读的时候长得一样,而它们不是一回事:
    前者是这一轮没命中任何术语(正常),后者是整版代码里没有这段能力。
    """
    _这一轮.clear()
    _这一轮.update(态=状态.get("态"), 条数=len(命中 or []),
                   版本=状态.get("版本"), 内容哈希=状态.get("内容哈希"),
                   来源=状态.get("来源"), 塞了几个字=int(字数 or 0),
                   库里几条=int(状态.get("条数") or 0))


def 清一轮():
    """每一轮装配之前调 —— 不清的话,这一轮没走到装配那条路时,
    `这一轮塞了什么()` 会把**上一轮**的值当成本轮的。"""
    _这一轮.clear()


def 这一轮塞了什么():
    """→ dict(真的塞过)/ None(这一轮没走到装配那条路)。

    ⚠️ **None 和 `{"条数": 0}` 不是一回事**,下一步动作不同:
    前者是「这一轮压根没走装配那条路」(可能是评测没过那段、也可能是接线断了),
    后者是「走了,而这一轮一条术语都没命中」(完全正常)。
    """
    return dict(_这一轮) if _这一轮 else None


if __name__ == "__main__":
    import sys
    角色 = sys.argv[1] if len(sys.argv) > 1 else "guide"
    st = 同步(角色)
    print(一句话(st))
    if len(sys.argv) > 2:
        段, 命 = 这一段(sys.argv[2], st)
        print(f"命中 {len(命)} 条:" + "、".join(x["标准词"] for x in 命))
        print(段 or "(一条都没提到 → 什么都不带)")
