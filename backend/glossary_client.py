#   > 这里「没挂」和「取不到」落到同一个结果(都走默认),但**说明里分开写** —— 默认路由本来就是没挂时该有的样子,不像实体识别那样两者处置相反
_路由落盘 = os.path.join(HERE, ".route_last.json")


def 同步路由(角色):
    """启动时调一次。→ {态, 说明, 版本, 版本id, 内容哈希, 配置, 来源}。配置 = None 表示「全走默认路由」。"""
    底 = dict(态="没配", 说明="", 版本=None, 版本id=None, 内容哈希=None, 配置=None, 来源="默认路由")
    cfg = _tc.配置()
    if not cfg:
        return dict(底, 说明="没配管理后台地址 —— 全走默认路由")
    码, 体 = _tc._curl("GET", f"/chat-assistants/by-role/{角色}/production", cfg)
    try:
        with open(_路由落盘, encoding="utf-8") as f:
            缓存 = json.load(f)
    except Exception:                                                        # noqa: BLE001
        缓存 = None
    if 码 == "404":
        return dict(底, 态="没配助手", 说明=f"后台没给角色「{角色}」配聊天助手 —— 全走默认路由")
    if 码 != "200" or not isinstance(体, dict) or "route_version_id" not in 体:
        态 = "取不到" if 码 != "200" or not isinstance(体, dict) else "字段还没上"
        if 缓存 and 缓存.get("配置") is not None:
            return dict(底, 态=态, 版本=缓存.get("版本"), 版本id=缓存.get("版本id"), 内容哈希=缓存.get("内容哈希"),
                        配置=缓存["配置"], 来源="缓存", 说明=f"{态}(码={码});用上一次缓存的路由 {缓存.get('版本')}")
        return dict(底, 态=态, 说明=f"{态}(码={码});本地也没有缓存 —— 全走默认路由")
    vid = 体.get("route_version_id")
    if vid is None:
        return dict(底, 态="没挂", 说明="这一版聊天助手没挂路由(显式 null)—— 全走默认路由")
    码2, 版 = _tc._curl("GET", f"/route-versions/{vid}", cfg)
    if 码2 != "200" or not isinstance(版, dict) or not isinstance(版.get("配置"), dict):
        if 缓存 and 缓存.get("版本id") == vid:
            return dict(底, 态="取不到", 版本=缓存.get("版本"), 版本id=vid, 内容哈希=缓存.get("内容哈希"), 配置=缓存["配置"],
                        来源="缓存", 说明=f"取路由版本 {vid} 拿不到 200(码={码2});用上一次缓存的同一版")
        return dict(底, 态="取不到", 说明=f"取路由版本 {vid} 拿不到 200(码={码2});本地也没有缓存 —— 全走默认路由")
    if not 缓存 or 缓存.get("内容哈希") != 版.get("内容哈希"):     # 比内容哈希,不比版本号(文件头 ①)
        try:
            with open(_路由落盘, "w", encoding="utf-8") as f:
                json.dump({"版本id": 版.get("id"), "版本": 版.get("版本"), "内容哈希": 版.get("内容哈希"), "配置": 版.get("配置")},
                          f, ensure_ascii=False)
        except Exception:                                                    # noqa: BLE001
            pass
    return dict(底, 态="有", 版本=版.get("版本"), 版本id=版.get("id"), 内容哈希=版.get("内容哈希"), 配置=版.get("配置"),
                来源="后台", 说明=f"路由 {版.get('版本')}(哈希 {版.get('内容哈希')})")


def 这一段(文本, 状态, 名单表=None):
    """这次要塞给模型的那一段。**调后台那份纯函数**,不另写(见文件头 ④)。

    先实体识别(名字占掉的字不算术语),再只把术语那几段 + 「占位并提示」的提示拼给模型。
    一条都没有 → 空串(不带空壳)。拆法:名单表(测试用)> 状态["实体识别"](后台配置)> 代码默认三本。"""
    T = 术语模块()
    术语们 = 状态.get("术语") or []
    拆态 = 状态.get("实体识别")
    规则 = None
    if 名单表 is not None:
        名 = 名单表
    elif isinstance(拆态, dict):
        配 = 拆态.get("配置")
        名 = T.按配置的名单(配, 现取)[0] if 配 else None          # 配置 None = 这一版没挂实体识别,不拆
        规则 = (配 or {}).get("拿不准")
    else:
        名 = 名单()
    拆 = T.识别实体(文本, 术语们, 名, 规则)
    # 第二期:识别结果交给查询路由决定带哪些定义、给模型哪些提示(没挂路由 = 默认路由 = 第一期行为)
    路态 = 状态.get("路由")
    走 = T.应用路由(拆, (路态 or {}).get("配置") if isinstance(路态, dict) else None, None, (规则 or {}).get("提醒"))
    命 = 走["术语命中"]
    return T.上下文段(命, 术语们, 规则, 走["提示们"]), 命


# ── 这一轮到底塞进去了什么:给评测的口径用 ────────────────────────────────
#
# 为什么要有这个登记,而不是让评测那边「传一个参数进来」:
# 接术语之后,如果装配那一处忘了改那个实参,基线会老实写「没接术语」——
# **而它和真的没接,在基线文件里长得一模一样。**
#
# 2026-10-27 那三条漏触发查了三轮实验、约四小时,根因正是同一个形状:
# 基线里只有「目录里有哪几份技能」,没有「真挂给了模型哪几个」。
#
# ⚠️ 登记**也会漏**(某一轮没走到那条路,表里却留着上一轮的值)。所以两件:
#   ① 每一轮装配前要 `清一轮()`,`这一轮塞了什么()` 只认本轮登记的
#   ② `agentsite/skill_eval_truth_check.py` 有一条**条件接线断言**:
#      装配代码里只要出现了 `这一段(` 的调用,就必须同时出现 `记一笔(`;
#      两个都没出现 = 这一版还没接,那时它明说「没东西可验」而不是「验过了」
_这一轮 = {}

# ⚠️ **这张表是进程全局的一份,不是每轮一份 —— 并发会串台。**
#
# 现在的用法安全,是因为**评测是一条一条串着跑的**:装配一轮 → 立刻读一轮。
# 而聊天站本身跑在 asyncio 上,多个会话同时问的时候,A 的装配会覆盖 B 刚写的那一笔,
# 于是 `这一轮塞了什么()` 返回的实际是「**最后一个装配完的那一轮**」,不是调用者自己那轮。
#
# > 「这一轮塞了什么」和「最后一轮塞了什么」,**在返回的那个 dict 上长得一模一样** ——
# > 单线程下它俩恒等,所以压根不会露馅。
#
# 所以这个口**只给评测和自测用**,不许用来给某个具体会话做展示或计费。
# 要那种用途得换成「装配函数把这一笔当返回值交出去」,让调用方自己拿着。
#
# ⛔ **别改成 `contextvars`。** 看着是对症的修法,实际会把这个口彻底废掉:
# 评测是**从那个 asyncio 任务外面**读它的(`skill_eval.py` 跑完一轮再问),
# 换成 contextvars 之后外面读到的永远是默认值 —— 于是「接了但这一轮没走到」
# 和「压根没接」又会合并成同一张脸,正是上面那段注释要防的事。

# ⚠️ **「这个模块在」和「装配真的接上它了」是两回事。**
# 第一版我拿 `import` 成不成功去判断「接没接」—— 而 import 成功只说明**文件在**,
# 不说明**有人调它**:于是「模块在、装配没接」和「装配接了、这一轮没走到那条路」
# 返回了同一个结果,而两者下一步完全不同(一个是「还没做」,一个是「做了但接线断了」)。
#
# 这是这个项目最老那条教训的同一张脸:`allowed_tools` 不是排他白名单 ——
# **「模型没用」和「模型不能用」是两回事**。
# 所以接上它的那一侧必须**显式宣告一次**,别让人从 import 去推。
_接上了 = False


def 宣告接上了():
    """装配上下文的那个模块在**自己被 import 的时候**调一次。

    放在模块顶层(不是函数里)—— 它要回答的是「这一版代码接没接」,
    而不是「这一次调用有没有走到」。后者是 `记一笔()` 的事。
    """
    global _接上了
    _接上了 = True


def 接上了吗():
    return _接上了


def 记一笔(状态, 命中=None, 字数=None):
    """装配上下文时塞了术语,在这里登记一笔。**塞了多少就记多少,没塞也要记。**

    「没塞」要记成 `{"态": …, "条数": 0}` 这样的真值,**不是不记** ——
    不记和「这一版压根没接术语」在读的时候长得一样,而它们不是一回事:
    前者是这一轮没命中任何术语(正常),后者是整版代码里没有这段能力。
    """
    _这一轮.clear()
    _这一轮.update(态=状态.get("态"), 条数=len(命中 or []),
                   版本=状态.get("版本"), 内容哈希=状态.get("内容哈希"),
                   来源=状态.get("来源"), 塞了几个字=int(字数 or 0),
                   库里几条=int(状态.get("条数") or 0))


def 清一轮():
    """每一轮装配之前调 —— 不清的话,这一轮没走到装配那条路时,
    `这一轮塞了什么()` 会把**上一轮**的值当成本轮的。"""
    _这一轮.clear()


def 这一轮塞了什么():
    """→ dict(真的塞过)/ None(这一轮没走到装配那条路)。

    ⚠️ **None 和 `{"条数": 0}` 不是一回事**,下一步动作不同:
    前者是「这一轮压根没走装配那条路」(可能是评测没过那段、也可能是接线断了),
    后者是「走了,而这一轮一条术语都没命中」(完全正常)。
    """
    return dict(_这一轮) if _这一轮 else None


