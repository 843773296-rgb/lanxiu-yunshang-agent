# -*- coding: utf-8 -*-
"""商机判断的评测:24 条逐字稿,16 正 8 负,真值在 truth 表。

## ⚠️ 两个前提,不说清这组数字就是假的

**① 逐字稿是造的,不是真实通话的转写。**
造的对话里信号比真实通话清楚得多 —— 真人会绕、会跑题、会同时说三件事。
**「造的对话上的准确率」和「真实通话上的准确率」在报告上长得一模一样。**

**② 现在是纯规则版,没有调模型。**
规则能做的:客户提到了哪个维度(颜色/形制/纹样/场合)、店里现在有没有对得上的货。
规则做不了的:**客户是真的想要,还是随口一提。**

## 🔑 这个评测最有价值的地方:它量出了规则版的天花板

误报全部来自同一个形状:

> 客户说「齐胸襦裙听起来好像不错啊。但是呢,我先不急着定,想再想想。」

规则看到「齐胸襦裙」+ 店里有货 → 判成商机。**而他只是随口一提。**

要分开「想要」和「提到」,得判断**未满足的需求**,
而这件事**步骤枚举不出来** —— 同一个意思的中文写法接近无限
(CLAUDE.md 记着这个项目为「枚举中文短语」栽过七次)。

**所以这一层要上模型。** 按项目的判断标准:
「任务步骤能不能提前枚举 —— 能就停在 V2,不能才上 V3」——
维度识别停在规则,未满足判断得上模型。

## 欠账上限模式:只许升不许降

准确率写死一个下限。改判据把它改低了,这里会红 ——
**「我把判据放宽了所以分数掉了」和「代码写坏了」在分数上长得一模一样。**
"""
import os, sqlite3, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import opportunity as op

G, R, Y, D = "\033[32m", "\033[31m", "\033[33m", "\033[0m"
DB = os.path.join(HERE, "lanxiu.db")

# ── 咬合记录 ──────────────────────────────────────────────────────────
咬合 = [
    ('把「只看客户说的话」去掉(改成全文匹配,顾问说的也算)',
     '只看客户说的话'),
]

准确率下限 = 65      # 当前 67%。**只许升不许降**
# 2026-09-21:注释原来写着「当前 62%」,而实测是 67% —— **一个过期的注释,
# 和一个刚写下的注释长得一模一样**。顺手把下限从 60 往上锁一格:
# 这一层是纯规则、确定性的,67% 不会自己抖回去。


def main():
    c = sqlite3.connect(DB); c.row_factory = sqlite3.Row
    真值 = {r["case_id"]: r["root_cause"] == "是商机"
            for r in c.execute("select * from truth where src='造数据标注'")}
    条 = list(c.execute("select audio_id,text from call_transcript "
                        "where audio_id like 'TS-%' order by audio_id"))
    print("\n\033[1m▸ 商机判断 · 24 条逐字稿(⚠️ 造的对话,纯规则版)\033[0m")
    print("  " + "=" * 80)

    if not 条:
        print(f"  {R}❌{D} 一条逐字稿都没有 —— **空集合上什么都成立,这不叫通过**")
        return 1
    if len(条) < 10:
        print(f"  {R}❌{D} 只有 {len(条)} 条,样本太少,量不出东西")
        return 1
    正 = sum(1 for v in 真值.values() if v)
    负 = len(真值) - 正
    if 负 == 0:
        print(f"  {R}❌{D} 一条负例都没有 —— **只有正例的评测集,"
              f"会让「见什么都说是商机」的实现拿满分**")
        return 1

    对, 误报, 漏报 = 0, [], []
    for r in 条:
        应该 = 真值.get(r["audio_id"])
        if 应该 is None:
            continue
        判, 码, why = op.判断(r["text"])
        if 判 == 应该:
            对 += 1
        elif 判:
            误报.append((r["audio_id"], 码))
        else:
            漏报.append((r["audio_id"], 码))

    率 = 对 * 100 // len(条)
    print(f"  {len(条)} 条(正 {正} / 负 {负}):对 {对} 条 = **{率}%**")
    print(f"     误报 {len(误报)} 条(不是商机判成了商机)")
    print(f"     漏报 {len(漏报)} 条(是商机没判出来):" +
          "、".join(f"{a}({b})" for a, b in 漏报[:4]))

    # 这条是**只看客户说的话**那个判据的哨兵 —— 去掉它,误报会爆
    顾问话 = "顾问:我们这次进了一批红色的马面裙,还有缠枝纹的褙子。\n客户:哦,好的。"
    判, 码, _ = op.判断(顾问话)
    ok = not 判
    print(f"  {G+'✅'+D if ok else R+'❌'+D} 只看客户说的话" +
          (f"  ← 顾问介绍商品时一定会提到颜色和形制,"
           f"**全文匹配的话每通电话都是商机**" if ok else
           f"  ← 顾问说的被当成了客户的偏好"))
    if not ok:
        return 1

    if 率 < 准确率下限:
        print(f"\n  {R}❌{D} 准确率 {率}% 低于下限 {准确率下限}% —— "
              f"**判据放宽和代码写坏,在分数上长得一模一样**")
        return 1

    print(f"\n  {Y}⚠ 这组数字的两个前提{D}:")
    print(f"     ① 逐字稿是**造的**,不是真实通话 —— 造的对话信号清楚得多")
    print(f"     ② **纯规则版,没调模型** —— 误报全来自同一个形状:")
    print(f"        客户说「XX听起来不错,但我先不急」,规则看到维度词就判成商机。")
    print(f"        **分开「想要」和「提到」要判未满足的需求,而那件事枚举不出来** ——")
    print(f"        按项目标准(步骤能枚举就停在规则),**这一层要上模型**。")
    print(f"  {G}✅{D} 商机判断 {率}%(下限 {准确率下限}%,只许升不许降)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
