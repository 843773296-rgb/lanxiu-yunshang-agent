# -*- coding: utf-8 -*-
"""ASR 效果实测:行业词能不能转对,热词有没有用。

⚠️ **这一组数字的前提必须先说,否则它是假的:**

    喂进去的是 macOS `say` 合成的语音,**不是真实通话录音**。

合成语音吐字清楚、没有背景噪音、没有口音、不抢话、语速均匀。
**真实通话的识别率一定比这个低** —— 低多少不知道,因为现在库里一条真录音都没有。

**「合成语音的准确率」和「真实通话的准确率」在报告上长得一模一样**,
而前者会好看得离谱。所以每一处输出都盖着这个前提。
(并行会话在识图评测上踩过同一个形状:喂的是合成图不是真照片。)

## 量什么

不量整句的字准 —— 那个数会被「的了吗」这类虚词稀释,看不出真问题。
量的是 **行业词召回率**:真值里出现的那些汉服术语,有几个在转写里原样出现。

**错了不会报错,只会安静地转成别的字**,而且转出来往往很通顺:
「要明制的」→「要明智的」,不看真值根本发现不了。
"""
import os, sys, json, sqlite3, subprocess
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import asr

G, R, Y, D = "\033[32m", "\033[31m", "\033[33m", "\033[0m"

# (音频文件基名, 真值, 该转对的行业词)
语料 = [
    ("t1", "我想做一条马面裙,配齐胸襦裙那种上衣,要明制的。", ["马面裙", "齐胸襦裙", "明制"]),
    ("t2", "面料用妆花缎还是香云纱?缂丝的话工期要多久?", ["妆花", "香云纱", "缂丝"]),
    ("t3", "这件用的是盘金绣和打籽绣,领口做滚边,袖子要接襕。", ["盘金绣", "打籽绣", "滚边"]),
    ("t4", "上次那件我想要红色的,结果只有蓝色,最后买了藏青那条。", ["红色", "蓝色", "藏青"]),
    ("t5", "下个月要拍旅拍写真,想要一套正式点的,能穿去看戏的那种。", ["旅拍", "写真", "正式"]),
    ("t6", "好的那我下周三下午三点过去,到时候再联系您。", []),
]


# ⚠️ **简繁归一。** 实测踩过:关热词那组吐的是繁体(「紅色」「藍色」「寫真」),
# 而判据按简体比对,把三个**识别正确**的词判成了漏。
# 于是热词的收益被算成 +33 个百分点;加上简繁归一重跑是 **60% → 60%,+0**(09-20)。
# (这里原来写「真实 +13」,和提交记录、需求文档的 +0 对不上 —— 09-22 改正,以重跑结果为准)
#
# > **「识别成繁体」和「识别错了」,在召回率里长得一模一样。**
#
# 只在 prompt 里要求简体是不够的:**控制不了模型输出,就得在判据这头兜住。**
# 这里不引第三方库(项目底线是纯标准库),只映射测试词表会用到的那些字。
繁简表 = {"紅":"红","藍":"蓝","寫":"写","絲":"丝","繡":"绣","錦":"锦","襴":"襕",
         "緞":"缎","紗":"纱","雲":"云","製":"制","點":"点","齊":"齐","襖":"袄",
         "結":"结","買":"买","條":"条","個":"个","後":"后","戲":"戏","種":"种",
         "點":"点","還":"还","們":"们","來":"来","時":"时","應":"应","樣":"样"}


def 简体(s):
    return "".join(繁简表.get(ch, ch) for ch in s)


def 召回(转写文本, 词表):
    """真值里的行业词,有几个在转写里出现(简繁归一后比)。"""
    if not 词表:
        return None, []
    t = 简体(转写文本)
    漏 = [w for w in 词表 if 简体(w) not in t]
    return (len(词表) - len(漏)) / len(词表), 漏


def main(wav目录=None, 入库=False):
    ok, 缺 = asr.可用()
    if not ok:
        print(f"{Y}⏭  跳过:{';'.join(缺)}{D}")
        print("   **跳过不是通过** —— 这一节什么都没验到。")
        return 0

    wav目录 = wav目录 or os.environ.get("ASR_WAV_DIR", "")
    if not wav目录 or not os.path.isdir(wav目录):
        print(f"{Y}⏭  跳过:没有测试音频目录(设 ASR_WAV_DIR){D}")
        print("   **跳过不是通过。** 造音频:见本文件末尾的 造音频() ")
        return 0

    print(f"\n\033[1m▸ ASR 实测 · 行业词召回(⚠️ 合成语音,不是真实通话)\033[0m")
    print("  " + "=" * 84)
    结果 = []
    for 组, 用热词 in (("关热词", False), ("开热词", True)):
        命中, 总数, 用时合计 = 0, 0, 0.0
        细 = []
        for 基名, 真值, 词表 in 语料:
            wav = os.path.join(wav目录, 基名 + ".wav")
            if not os.path.exists(wav):
                continue
            try:
                文本, 用时, model = asr.转写(wav, 用热词=用热词)
            except Exception as e:
                print(f"  {R}❌{D} {基名} 转写失败:{e}"); continue
            用时合计 += 用时
            r, 漏 = 召回(文本, 词表)
            if r is not None:
                命中 += len(词表) - len(漏); 总数 += len(词表)
            细.append((基名, 文本, 漏, 词表))
            if 入库:
                asr.入库(f"TEST-{基名}-{'hw' if 用热词 else 'nohw'}", None, wav, 文本,
                        model, 用时, "合成(测试用)", 用热词)
        率 = 命中 / 总数 if 总数 else 0
        结果.append((组, 率, 命中, 总数, 用时合计, 细))
        print(f"\n  【{组}】行业词召回 {命中}/{总数} = {率*100:.0f}%   用时合计 {用时合计:.1f}s")
        for 基名, 文本, 漏, 词表 in 细:
            标 = f"{R}漏 {'、'.join(漏)}{D}" if 漏 else (f"{G}全中{D}" if 词表 else "—")
            print(f"     {基名}  {标}")
            if 漏:
                print(f"           转成了:{文本}")

    if len(结果) == 2:
        关, 开 = 结果[0][1], 结果[1][1]
        差 = (开 - 关) * 100
        print(f"\n  " + "=" * 84)
        print(f"  热词的效果:{关*100:.0f}% → {开*100:.0f}%  ({'+' if 差>=0 else ''}{差:.0f} 个百分点)")
        if abs(差) < 1:
            print(f"  {Y}⚠{D} **几乎没差** —— 「加了热词」这件事本身不说明任何问题,要量出来才算数")

    print(f"\n  {Y}⚠ 这组数字的前提{D}:喂的是 `say` 合成的语音,**不是真实通话**。")
    print(f"     合成语音吐字清楚、无噪音、无口音、不抢话 —— **真实通话一定更低**,")
    print(f"     低多少不知道,因为库里一条真录音都没有。")
    print(f"     **「合成语音的准确率」和「真实通话的准确率」在报告上长得一模一样。**")
    return 0


def 造音频(目录):
    """用 macOS 自带 TTS 造测试音频(16kHz 单声道 wav,whisper 直接吃)。"""
    os.makedirs(目录, exist_ok=True)
    for 基名, 真值, _ in 语料:
        wav = os.path.join(目录, 基名 + ".wav")
        for 声音 in ("Tingting", "Flo", "Eddy"):
            subprocess.run(["say", "-v", 声音, "-o", wav, "--data-format=LEI16@16000", 真值],
                           check=False, capture_output=True)
            if os.path.exists(wav):
                break
    return 目录


if __name__ == "__main__":
    if "--造音频" in sys.argv:
        print("已造:", 造音频(sys.argv[sys.argv.index("--造音频") + 1]))
    else:
        sys.exit(main(入库="--入库" in sys.argv))
