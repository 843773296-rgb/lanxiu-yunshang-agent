# -*- coding: utf-8 -*-
"""简体闸:业务数据一律简体,外来文本(ASR/导入)进来前先查。

## 为什么要这一条

业务 2026-09-20 定:**商品必须都是简体字。**

库里现在是干净的(扫 15 个表的文本列,一处繁体都没有)。
**风险不在存量,在入口** —— 尤其是 ASR:whisper 转中文时会吐繁体。

后果很具体:

    ASR 转出「紅色」,而库里写的是「红色」
    → 商机判断查「这位客户提到过红色吗」→ **匹配不到**
    → 而查询不会报错,它只是返回空

> **「客户没提过红色」和「提过但简繁对不上」,在查询结果里长得一模一样。**

## ⚠️ 这个字表是**检测用**的,不是转换用的

检测只要知道「这个字是繁体」,转换还要知道「对应的简体是哪个」——
后者需要一张完整的对应表(上千组),而这个项目的底线是纯标准库,不引 opencc。

**所以这里只检测、不转换**:发现繁体就报出来,让人处理。
宁可挡住,也不要自己猜一个转换结果 ——
**猜错的转换和正确的转换,在库里长得一模一样。**

## ⚠️ 字表只收「繁体专用字」

第一版我手写字表时混进了一堆**简繁同形**的字(裙、面、白、工、衣、料、扣、裁、短、嵌),
扫出 367 处「繁体」**全是误报**,差点让我去改一批本来就对的商品名。

> **误报的检查比没有检查更糟** —— 它会让人去改对的东西。

所以这里只收**简体中文里不会出现**的字。宁可漏,不可错。
漏了的后果是少报一个;错了的后果是让人去改对的数据。
"""
import os, sqlite3, sys

DB = os.path.join(os.path.dirname(os.path.abspath(__file__)), "lanxiu.db")

# ── 咬合记录 ──────────────────────────────────────────────────────────
# 左边「改坏了什么」,右边「预期红的那一条」。规格在 tools/bite_specs.json,
# `python3 tools/bite_run.py` 能重放:对照绿 → 改坏 → 红的必须是右边这条。
咬合 = [
    ('往繁体字表里混进一个简繁同形的字(「面」)',
     '字表里混进了简繁同形的字'),
]

# 繁体专用字 —— 简体中文里不会出现的。宁可漏,不可错(见上面的警告)。
繁体专用 = set(
    "紅藍綠黃銀錦繡綉絲緞紗襖製織線針飾寶貴華麗優質標準規範類號碼價錢庫訂單發貨運輸"
    "選確認撤銷開關閉業務處間寬圓領對盤帶鑲紋圖顏風傳統現經設計師藝術裡襯內層級檔"
    "檢驗測證買賣個後戲還們來時應樣寫點齊襴雲種條結"
    "東車馬鳥魚龍鳳麥產業義樂學習書畫筆硯詩詞語說話聽見聞問對錯"
    "無為體積極線長遠親"
    "兒麼會過沒與並將當從給讓"
)
# ⚠️ 后三行是第二次才写对的。第一次写的时候混进了
# **墨、言、答、有、面、短、高、低、近、疏、被、把** —— 全是简繁同形字。
# 下面 main() 里的自检当场抓住了,所以它们没进库。
# **一个会误报的字表,比没有这张表更糟** —— 它会让人去改本来就对的商品名。

# 要守的表和列(业务数据,不含日志/原始文本)
守的列 = [("product", "name"), ("product", "remark"), ("sku", "color"), ("sku", "spec"),
          ("category", "name"), ("xingzhi", "name"), ("craft", "name"), ("material", "name"),
          ("pattern", "name"), ("sys_code", "name"), ("sys_code", "note"),
          ("activity", "name"), ("measure_tpl", "name"), ("measure_item", "name")]


def 繁体字(s):
    """这段文本里的繁体字(去重,保序)。空列表 = 全简体。"""
    seen, out = set(), []
    for ch in str(s or ""):
        if ch in 繁体专用 and ch not in seen:
            seen.add(ch); out.append(ch)
    return out


def 扫库(db=DB):
    问题 = []
    with sqlite3.connect(db) as c:
        for 表, 列 in 守的列:
            try:
                for (v,) in c.execute(f"select distinct {列} from {表} "
                                      f"where {列} is not null and {列}<>''"):
                    ch = 繁体字(v)
                    if ch:
                        问题.append((f"{表}.{列}", v, "".join(ch)))
            except sqlite3.Error:
                pass          # 表/列不存在就跳过 —— 库是演进的
    return 问题


def main():
    G, R = "\033[32m", "\033[31m"
    D = "\033[0m"
    print("\n\033[1m▸ 简体闸 · 业务数据一律简体\033[0m")
    print("  " + "=" * 76)

    # 自检:字表里**不许有简繁同形的字**。混进去会误报,而
    # **误报的检查比没有检查更糟 —— 它会让人去改对的东西。**
    # 这串是**踩过的**同形字,两次误报的来源都在里面
    同形 = [ch for ch in "裙面白工衣料扣裁短嵌襟案傅那和的是在了"
                        "墨言答有高低近疏被把" if ch in 繁体专用]
    if 同形:
        print(f"  {R}❌{D} 字表里混进了简繁同形的字:{''.join(同形)} —— 这会误报")
        return 1

    问题 = 扫库()
    if 问题:
        print(f"  {R}❌{D} {len(问题)} 处业务数据含繁体字:")
        for 位置, v, ch in 问题[:10]:
            print(f"      {位置}: 「{v}」 ← {ch}")
        print(f"\n      **查询不会因此报错,它只会返回空** ——")
        print(f"      「客户没提过红色」和「提过但简繁对不上」,在结果里长得一模一样。")
        return 1

    print(f"  {G}✅{D} 扫了 {len(守的列)} 个表的文本列,一处繁体字都没有")
    print(f"      字表只收**繁体专用字**(简体里不会出现的)—— 宁可漏,不可错:")
    print(f"      漏了少报一个;错了会让人去改本来就对的商品名(第一版踩过,367 处全是误报)。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
