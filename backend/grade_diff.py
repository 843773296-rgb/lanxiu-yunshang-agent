"""版师核过档差的**登记表**,只有建表。口径在 `knowledge/grading.py`。

## 这张表记什么,不记什么

**记**:哪一条档差、谁核的、什么时候、凭什么(理由)、**核的时候那个值是多少**。
**不记、也不能记**:档差本身的值。

⚠️⚠️ **档差不在库里** —— 它在 `knowledge/10-版型库.md` 的「四、档差规则」那张表里,
`grading.档差()` 从 md 现读,`derive_pattern.py` 再推出 1237 条尺码。
所以**改档差是人的活**(改 md → 重跑推导),而这张表只记「核过这件事」。
在库里再存一份档差值的话,它就成了第二份真相 ——
而两份不一致时**没人知道哪个是真的**,这个项目为这句话栽过很多次
(相容矩阵文档写 273 格而库里 2025 格、提示词里的比例写着 6% 而实际 100%)。

## 为什么要存「核的时候那个值」

光记「核过了」会造出一个假象:**md 里那个数以后被改了,
那条「核过」会漂到一个没人核过的新值上。**

> **「核过的档差」和「核过时是另一个数、后来被改了的档差」,
> 在那条记录上长得一模一样。**

所以存下当时那个值,读的时候拿它和现在的 md 比(`grading.核过还算数吗`),
不一样就报**失效**,并且说出「核的是 X,现在是 Y」。
同一个形状:`order_contract.terms_ver` —— 正是那一列没被平移挪,
才看出确认书正文里的条款版本被挪歪了(2026-10-22)。

## 为什么 DDL 单独放在 backend

两个检查各自要求一件事,而要求的位置不一样(同影子台账那张表的 DDL 模块):
· `tools/ensure_tables.py` —— 「用到时才建」的表要在重建流水线里显式建出来。
  **本地建过就一直在,CI 每次从零。**
· `tools/table_origin_check.py` —— 「库里有一张表,谁也建不出它」要红,
  而它跟进 import 时**只看 `backend` / `tools` / `knowledge` 三个目录**。
"""

表名 = "grade_diff_check"


def 确保表(c):
    """建档差核过登记表。

    ⚠️ 表名在 DDL 里**写死,不用 f-string** —— `table_origin_check` 按正则从源码里
    找 `CREATE TABLE ... <表名>`,而 `{表名}` 里的 `{` 不是字母,
    **它看不见这张表叫什么**,于是这张表在它眼里是「谁也建不出来」。
    (闸四影子台账那张表的 DDL 第一版就是这么红的。)
    """
    c.execute("""CREATE TABLE IF NOT EXISTS grade_diff_check(
        item TEXT PRIMARY KEY,          -- 档差的部位名(胸围 / 肩宽 / 上襦衣长……)
                                        -- **一条档差一行**:档差是全局的,不分版型
        verdict TEXT NOT NULL,          -- 核过 / 不对(枚举,写口拦;见 grading.档差结论)
        -- ⚠️ **核的时候那个值**。这一列是这张表存在的理由的一半 ——
        -- 少了它,md 改过之后「核过」会漂到一个没人核过的新值上。
        value_at_check REAL,
        -- 版师认为该改成多少。**只有 verdict='不对' 时才有**,而且它是**提案不是事实**:
        -- 改 md 是人的活。工具返回里明说「这个工具不改 md」。
        propose REAL,
        why TEXT NOT NULL,              -- 凭什么(量的 / 照老版比的 / 按国标)。写口要求必填
        checked_by TEXT NOT NULL,       -- 工号,从登录会话取,**不收身份参数**
        -- 世界时钟(整列日期,跟着平移挪)。
        -- ⚠️ 这一处栽了两次,都和「检查器说 OK」有关,记在这儿:
        --  ① 第一版把这句注释写在了三引号**外面** —— 而 `ast.parse` 说语法 OK,
        --     因为两个减号在 Python 里是**合法表达式**(两个一元负号作用在一个调用上),
        --     所以语法检查看不见它,只在运行时炸成 NameError。
        --  ② 第二版把注释挪进来了,可注释里**写了三个双引号那个字面量** ——
        --     它把这个三引号字符串**提前关掉**,后面整段变回 Python 代码。
        -- > **语法检查器通过,不等于它是对的。**
        -- > 同一天早上 `bash -n` 也对一个非 ASCII 变量名说过「语法 OK」。
        checked_at TEXT NOT NULL)""")
    c.execute("CREATE INDEX IF NOT EXISTS ix_grade_diff_check_v "
              "ON grade_diff_check(verdict)")
