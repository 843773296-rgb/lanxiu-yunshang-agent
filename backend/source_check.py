    ck(f"话术里 demo 的段数不超过 {话术demo上限}(只许降不许涨)",
       len(演) <= 话术demo上限, len(段),
       f"现在 {len(演)} 段 —— " + ("**涨了**:新加的说法该等业务给,不该再现编" if len(演) > 话术demo上限
                                   else "业务替换一段就把上限改小"))
    ck("话术里没有留空的「______」(空栏会被模型读成「这里随你说」)",
       "______" not in 话, 1)
    sec = next(l[3:].strip() for l in 话.split("\n")
               if l.startswith("## ") and "`demo`" in l)
    r = api.kb_read("13", sec)
    ck("话术的 demo 口径是「思路不是台词」(不是通用的「对客户:不能」)",
       "不照念" in str(r.get("对客户")), 1,
       f"{sec[:12]}… → {str(r.get('对客户'))[:40]} —— "
       "给通用口径的话,模型会把整节话术当禁区,回头又自己现编")

    print()
    if FAIL:
        print(f"\033[31m❌ 来源等级 {len(FAIL)} 处不符合预期\033[0m")
        for f in FAIL: print(f"   · {f}")
        sys.exit(1)
    print("\033[32m✅ 来源等级全部符合预期\033[0m")
    print(f"    溯不了源的 {len(欠)}/{n3} 条 —— **它们会自己说出来**,"
          f"不会被当成有出处的知识往外说。")


