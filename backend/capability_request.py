# -*- coding: utf-8 -*-
"""能力申请单 —— 助手缺工具时,和用户一起把需求问清楚、起草一份申请(用户 2026-11-11 拍)。

用户原话:「加新工具这件事,可以由用户自行填写,也可以由智能体和用户进行讨论后,由智能体生成更细致的需求。
因为用户可能不懂需求该如何填写,如果更详细描述需求,这生成需求申请单可以让智能体代劳。」

缘起:版师问「怎么才能调出商品照片」,助手答「找管理员或系统的维护方确认」—— 而系统里没有人知道管理员是谁、
走什么流程。现在的路:员工在「意见与建议」提「新增能力」→ 管理后台「意见」待受理 → 开发实现 → 上架。
缺的是**第一步写不清**:员工不知道要写什么,写一句「想要看图」处理的人只能回头再问。

## 这里只**起草**,不提交

起草是只读的(不写任何东西)。提交由用户在页面上点「确认提交」,走「意见与建议」原有的通道
(answer_feedback.转给后台,提问人只从登录身份取)—— 用户那一下就是确认,不需要另开一个写口。

## 六栏(对外描述的六要素:场景 / 谁用 / 痛点 / 怎么解决 / 输入 / 输出)

前五栏必填才算「写清了」;没问清的栏**照实空着、列进「还缺」**,不替用户编。
"""
栏 = (("场景", "在什么情况下需要它(哪个环节、多久遇到一次)"),
      ("谁用", "哪个岗位用(顾问 / 店长 / 版师 / 工坊 / 总部运营…)"),
      ("现在卡在哪", "现在没有它时怎么办、麻烦在哪"),
      ("想让它做什么", "要它查什么 / 算什么 / 做什么"),
      ("给它什么", "用的时候会提供什么(款号、订单号、照片…)"),
      ("希望得到什么", "希望它给出什么(一张图、一个数、一份清单…)"))
必填 = ("场景", "谁用", "现在卡在哪", "想让它做什么", "希望得到什么")
每栏最长 = 400


def 起草(字段, 标题=None):
    """→ {申请单: {标题, 六栏…}, 还缺: [栏名], 写清了吗, 提交载荷: {问题类型, 说明, 期望结果}}。纯函数。
    字段 = {栏名: 文字};不认识的键忽略(不把模型多塞的东西带进申请单)。"""
    字段 = 字段 if isinstance(字段, dict) else {}
    单 = {}
    for 名, _ in 栏:
        v = str(字段.get(名) or "").strip()
        单[名] = v[:每栏最长]
    缺 = [名 for 名 in 必填 if not 单[名]]
    题 = (str(标题 or "").strip() or 单["想让它做什么"][:30] or "新增能力申请")[:60]
    # 管理后台那张表只有「说明 / 期望结果」两段 —— 六栏拼进去,每栏一行带栏名,处理的人一眼看得懂
    说明 = "\n".join([f"【能力申请】{题}"] + [f"· {名}:{单[名] or '(没问清)'}" for 名, _ in 栏 if 名 != "希望得到什么"])
    return {"申请单": {"标题": 题, **单}, "还缺": 缺, "写清了吗": not 缺,
            "提交载荷": {"问题类型": "新增能力", "说明": 说明[:2000], "期望结果": 单["希望得到什么"] or ""},
            "下一步": ("申请单已写清 —— 请用户在下方申请单上核对后点「确认提交」(助手不能替用户提交)"
                       if not 缺 else f"还缺:{'、'.join(缺)} —— 先问用户这几栏,问清了再起草一次;用户说不清的栏可以空着提交")}


def 给模型的说明():
    """工具描述里用:六栏各问什么。"""
    return ";".join(f"{名}({问})" for 名, 问 in 栏)
