# -*- coding: utf-8 -*-
"""流失预警取数的对账 + 覆盖报告。

判定口径的逐例真值在 `knowledge/churn.py` 的 68 条自测里,**这里不重复**。
这里只验**取数层特有的四类错** —— 它们都有同一个性质:
**错了不报错,只是名单全歪**。

## ① 列名写错一个字,名单照样跑得出来

`revive.py` 2026-09-20 真栽过:订单状态按「已完成」写而库里是「完成」,
23499 张完成单被判成「在做」。
> 「状态值写错了」和「这个客户真的有单在做」,**在判断结果里长得一模一样**。

而这边更隐蔽:口径吃的键**逐字就是表的列名**,读错一个键
`sqlite3.Row` 不会报错 —— 2026-10-05 就是这么栽的:
读成另一个键名、静静返回 None,**23216 条历史的档位全成了字符串 "None"**,
而当时所有检查都是绿的。

## ② 参数抄了一份而不是转发

> 一句写在注释里的「要共用」,和一处真共用了的,**在那段注释上长得一模一样**。

所以这里用 `is` 断言,不比值 —— 比值的话抄一份出来也相等。

## ③ 连接其实是可写的

> 一个只读连接和一个可写连接,**在查询结果上长得一模一样** ——
> 直到某天有人往取数层加了一行 UPDATE。

所以这里真往那个连接上写一次,**写得进去就是错**。

## ④ 一条永远不触发的分支

> 一条永远不触发的分支,和一条正确的分支,**在通过率上长得一模一样**。

所以报**每个码在当前库上有几个样本** —— **没有样本不叫通过,叫没测到**。
⚠️ 这一段**只报不拦**:库里有没有样本是造数的事,不是代码错误。
"""
import os
import sqlite3
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "knowledge"))
import slipping
import churn

G, R, Y, D = "\033[32m", "\033[31m", "\033[33m", "\033[0m"
坏 = []


# ── 咬合记录 ──────────────────────────────────────────────────────────
# 左边「改坏了什么」,右边「预期红的那一条」。三关缺一关这条记录就不算数:
# 对照先绿 / 改坏要红 / **红的必须是点名那一条**。
咬合 = [
    ("把要查的列名写成库里不存在的(比如 idle 写成 idle_day)",
     "要查的每一列都真实存在"),
    ("把活跃度轴在取数层抄一份,而不是从口径模块转发",
     "参数是转发的,不是抄的"),
    ("把只读连接换成普通连接(取数层就能写库了)",
     "取数用的连接是只读的"),
]


def ck(说, 得, want, 附=""):
    if 得 != want:
        坏.append(f"{说}:要 {want!r},得 {得!r}")
    print(f"  {G + '✅' + D if 得 == want else R + '❌' + D} {说:46s} {得!r}{附}")


def main():
    print("\033[1m▸ 流失预警取数 · 对账\033[0m")
    print("  " + "=" * 76)

    # ① 列名:**拿库里的实际列对账**,不是看代码里写了什么
    真列 = {r[1] for r in sqlite3.connect(slipping.DB)
            .execute("PRAGMA table_info(lifecycle_history)")}
    缺 = [c for c in slipping.列 if c not in 真列]
    ck("要查的每一列都真实存在", 缺, [],
       f"  ← 表里有 {len(真列)} 列,要查 {len(slipping.列)} 列")

    # 反向也验一次:**库里多出来的列要被看见**。
    # 新加一列判定依据而取数层没跟上,名单照样跑得出来 ——
    # 口径会拿一个 None 去判,而那个 None 不报错。
    没取的 = sorted(真列 - set(slipping.列) - {"source", "note", "created"})
    ck("没有漏掉新加的判定依据列", 没取的, [],
       "  ← 新加一列而取数层没跟上,口径会拿 None 去判而不报错")

    # ② 参数:**用 is**,比值的话抄一份出来也相等
    ck("参数是转发的,不是抄的",
       all(getattr(slipping, k) is getattr(churn, k)
           for k in ("活跃度轴", "价值标签", "严重", "下一步")), True,
       "  ← 比的是同一个对象,不是同一个值")

    # ③ 连接真的是只读的 —— **往它上面写一次**
    con = slipping._只读()
    try:
        con.execute("CREATE TABLE _写得进去吗(x INT)")
        写进去了 = True
    except sqlite3.OperationalError:
        写进去了 = False
    finally:
        con.close()
    ck("取数用的连接是只读的", 写进去了, False, "  ← 真往它上面写了一次")

    # ④ 取数和判定接得上:自己拼一遍 == 一个人的判断()
    有历史 = next(iter(slipping.查历史()), None)
    if 有历史 is None:
        print(f"  {Y}⏸{D} 库里一条档位历史都没有 —— **不适用,不是通过**")
    else:
        手拼 = churn.判(slipping.查历史([有历史])[有历史])
        ck("一个人的判断() 和手拼的一样",
           slipping.一个人的判断(有历史)["码"], 手拼["码"],
           f"  ← 样本 {有历史}")
        ck("查不到历史的客户不在返回值里",
           slipping.查历史(["这个客户号不存在"]), {},
           "  ← 「查不到」和「没在流失」是两件事")
        ck("而单独问他时给的是 NO_HISTORY",
           slipping.一个人的判断("这个客户号不存在")["码"], "NO_HISTORY")
        ck("给空名单不等于给 None(不许退化成查全部)",
           slipping.查历史([]), {})

    # ── 覆盖报告:**没有样本不叫通过,叫没测到** ────────────────────
    print()
    print("\033[1m▸ 流失预警 · 覆盖报告(没有样本不叫通过,叫没测到)\033[0m")
    print("  " + "=" * 76)
    from collections import Counter
    数 = Counter()
    严重数 = Counter()
    for cid, hs in slipping.查历史().items():
        w = churn.判(hs)
        数[w["码"]] += 1
        if w["要不要预警"]:
            严重数[w["严重程度"]] += 1
    总 = sum(数.values())
    if not 总:
        # ⚠️⚠️ **这里原来以退出码 0 收场** —— 门禁会把它算成通过,
        # 也就是说一个没有档位历史的库上,下面这整段覆盖报告**一个字都没验**而全绿。
        # 按 CLAUDE.md 第 8 节的规矩(「检查必须声明验了多少个,样本量为 0 要红」),
        # 这一条是反的:
        # > 一个「验过了没问题」和一个「没有东西可验」,
        # > **在那个绿勾上长得一模一样。**
        #
        # 2026-10-09 之前**不能翻**,而且理由不是「怕红」:
        # `tools/rebuild.sh` 的配方里**一步都没有造 `lifecycle_history`**
        # (原来只有 `fakedata/mkt_sop_seed.py` 顺带造,而它不在配方里)——
        # 所以 CI 的库里这张表永远是空的。那时候翻成非零,CI 会立刻红,
        # 而**红的原因是「配方缺一步」,不是「判据发现了问题」**。
        # > 一条「判据发现了真问题」的红,和一条「配方缺一步」的红,
        # > **在 CI 的红叉上长得一模一样。**
        #
        # 现在可以翻了:`tools/lifecycle_history_seed.py` 已经进配方(69057b3),
        # 而且**在 CI 的从零构建上真跑过并打出「✅ 档位历史造好了」**(run 37896159692)——
        # 是去日志里确认的,不是只看绿勾。
        坏.append("库里没有档位历史 —— C 方案的前提不在,**下面那份覆盖报告一个字都没验**。"
                  "`tools/rebuild.sh` 里有 `lifecycle_history_seed.py --做` 这一步,"
                  "单独跑:python3 tools/lifecycle_history_seed.py --做")
        print(f"  {R}❌{D} {坏[-1]}")
    else:
        print(f"  {总} 个有历史的客户 → 要预警 {sum(严重数.values())} 人 "
              f"(高 {严重数['高']} / 中 {严重数['中']} / 低 {严重数['低']})")
        缺 = [k for k in churn.下一步 if 数[k] == 0]
        for k in churn.下一步:
            mark = f"{Y}⚠ 库里没有样本{D}" if 数[k] == 0 else ""
            print(f"     {k:14s} {数[k]:>6}  {mark}")
        if 缺:
            print(f"\n  {Y}⚠{D} 这几支在当前库上**一次都没触发**:{'、'.join(缺)}")
            print("     它们在 churn.py 的 68 条自测里是对的,"
                  "但**库里没有真实样本** ——")
            print("     **一条永远不触发的分支,和一条正确的分支,"
                  "在通过率上长得一模一样。**")
            print("     NO_HISTORY 恒空是因为造数给每个客户都造了 5 条历史;")
            print("     NEVER_BOUGHT 恒空是因为只给有单的客户造了历史。")

        # ── 「有多可惜」那三支分别有几个样本 ──────────────────
        # ⚠️ **这一段是 2026-10-05 真跑工具时才想到要加的。**
        # 当时全库 2649 条预警里,「曾经是忠诚而现在这个标签没了」是 **0 条** ——
        # 而 `MKT-10-03` 整节讲的就是那个情形,自测里也有一条(用的是 fixture)。
        # > 一支「fixture 里验过」的分支,和一支「真数据上跑过」的,
        # > **在自测的通过数上长得一模一样。**
        # ⚠️ **根因在 2026-10-09 被重新量过一次,上面那句诊断已经作废。**
        # 原来写的是「造出来的历史里这两个数每条都一样,只有闲置天数在变」——
        # 那是 10-05 的事实。后来 `lifecycle_history_seed` 改成逐时点调
        # `order_mix.某天的事实` 现算,这两个数**已经在变**:
        #     amount_12m 变过的 3648 人 / orders_12m 变过的 3487 人(全库 7930 人有历史)
        # 但同一次量出了真正的那条:
        #     **「末值低于自己峰值」的人是 0 个 —— 金额只涨不落。**
        # 因为 `某天的事实` 算的是「截至该时点往前 365 天」,
        # 只要一个人的订单都堆在近期,越晚的时点金额就越高。
        # 要让它落下来,得有人**老订单已经滚出窗口而新单没补上**,而库里一个都没有。
        #
        # > 一个「数字在变」的历史,和一个「数字会衰减」的历史,
        # > **在「变过的人数」这个指标上长得一模一样。**
        #
        # 所以缺口不在算法而在**样本形状**:要造的是「大单落在 12 个月窗口外 +
        # 小单落在窗口内」的客户(算出来的参数:大单 今−400 天、小单 今−200 天)。
        # 改算法改不出这一支 —— 它只会把别人的金额也一起算错。
        可惜 = Counter()
        for cid, hs in slipping.查历史().items():
            w = churn.判(hs)
            if w["要不要预警"]:
                可惜["现在仍然是" if w["现在还是"] else
                     "曾经是但现在没了" if w["曾经是"] else "没有价值标签"] += 1
        print()
        print("  「有多可惜」这三支:")
        for k in ("现在仍然是", "曾经是但现在没了", "没有价值标签"):
            print(f"     {k:16s} {可惜[k]:>6}  "
                  f"{Y + '⚠ 库里没有样本' + D if not 可惜[k] else ''}")
        if not 可惜["曾经是但现在没了"]:
            # ⚠️ 这段提示 2026-10-09 重写过一次。原来写的是「造数没模拟金额衰减,
            # 交数据工坊」—— 那件事**已经做完了**(`tools/seed_churned.py` 的 C 组),
            # 当天这一支从 0 变成 3。一条指向已完成任务的提示比没有提示更糟:
            # 它会让下一个人去改一个已经对了的地方。
            print("     ⚠️ **「曾经是但现在没了」是 MKT-10-03 整节在讲的那个情形** ——")
            print("        这一支 2026-10-09 之前一直是 0,靠 `tools/seed_churned.py`")
            print("        的 **C 组**才有样本(大单落在 12 个月窗口外 + 小单落在窗口内)。")
            print("        现在又变 0,先查这两件事,**顺序别颠倒**:")
            print("        ① C5* 那批人还在不在(`seed_churned.py --回滚` 会把他们连历史一起删);")
            print("        ② 他们的末态还在不在「潜在流失」—— 世界每天往前走一天,")
            print("           闲置过了 365 天就变「流失」→ 码变 GONE → **不预警** →")
            print("           数据还是对的,可这个计数器只收预警中的,于是又成 0。")
            print("           那就是该调 C 单日期了(见 seed_churned.py 文件头)。")

        # ⚠️ 这一条**只报不拦**,理由写在下面
        #
        # ⚠️⚠️ 2026-10-09 修了一处**从写下那天起就没跑过**的代码:
        # 这里原来写 `r["customer_id"]`,而这个连接**没有设 row_factory**,
        # 行是元组 —— 按字符串取下标会 `TypeError`。
        # 它一直没炸,是因为这个查询**以前返回 0 行**:列表推导式一行都不迭代,
        # 那个错的下标永远不会被求值。
        # 当天档位重算之后它开始返回 2732 行,**当场崩**(而崩溃不打印 ❌,
        # 整条检查显示成「没验过」)。
        # > 一行「下标写错了」的代码和一行写对的,**在查询返回 0 行时长得一模一样。**
        不符 = [r[0] for r in sqlite3.connect(slipping.DB).execute(
            """select h.customer_id from lifecycle_history h
               join customer c on c.id = h.customer_id
               where h.as_of = (select max(as_of) from lifecycle_history
                                 where customer_id = h.customer_id)
                 and h.lifecycle <> c.lifecycle""")]
        # ⚠️⚠️ **这里要守的是另一个 0。**
        #
        # 上面那个查询**返回 0 行就是通过**(没有一个对不上),所以不能给它加
        # 「0 行算没验到」—— 那会让一条正确的不变量永远红。真正分不开的是:
        # > 一个「一条都没对不上」和一个「**一条都没比过**」,
        # > **在那个 0 上长得一模一样。**
        # 所以数一下「到底比了多少对」。这张表空了 / join 写坏了 /
        # 子查询选不出最后一条 —— 比的对数就是 0,而那时上面那个 0 什么都不代表。
        # **空集合上所有性质都成立。**
        比了 = sqlite3.connect(slipping.DB).execute(
            """select count(*) from lifecycle_history h
                 join customer cu on cu.id = h.customer_id
                where h.as_of = (select max(as_of) from lifecycle_history
                                  where customer_id = h.customer_id)""").fetchone()[0]
        print()
        if 比了 < 100:
            坏.append(f"只比了 {比了} 对「历史最后一条 vs 现在的档位」——"
                      f" **这不叫通过,叫没比过**(库里 5804 个客户有档位历史)")
            print(f"  {R}❌{D} {坏[-1]}")
        if 不符:
            print(f"  {Y}⚠{D} 历史最后一条和 `customer.lifecycle` "
                  f"对不上的有 {len(不符)} 个")
            print("     **不拦** —— 人工调整(`manual_lc`)本来就会让当前档位"
                  "偏离重算值,所以不等 ≠ 错。要查的是**有没有对应的 manual 记录**。")
        else:
            print("  ✅ 历史最后一条都等于 `customer.lifecycle`(0 个对不上)")

    print()
    if 坏:
        print(f"{R}❌ 流失预警取数 {len(坏)} 处不符合预期{D}")
        for b in 坏:
            print(f"    ❌ {b}")
        return 1
    print(f"{G}✅ 流失预警取数全部符合预期{D}")
    print("    判定口径的逐例真值在 knowledge/churn.py 的 74 条自测里 —— "
          "这里只验取数层特有的那四类错。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
