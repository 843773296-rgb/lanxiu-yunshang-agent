"""世界时钟 —— **演示世界的「现在」只有这一份来源**。

## 为什么要单独一个文件

2026-09-26 踩到:`backend/booking.py` 的 `_now()` 是 `datetime.datetime.now()` ——
**机器时钟**。于是它写出来的 `schedule.assigned_at` 落在机器的今天,
而演示世界当时停在前一天。然后每日平移把这条记录**跟着往后挪了一天**,
它就落到了世界的未来。

> **这个 bug 不会自愈:平移每跑一次,它就往未来多推一天。**

C4(「已经发生的事,时间不能在未来」)抓到了症状,而根因是
「世界的今天」在这个仓库里有两处表示:`seed.TODAY`(库里读的)和
各个文件里的 `datetime.now()`。**一份数据两处表示,这是第八次。**

## 两个口径,别混

    今天()   世界的日期(从 world_meta 读,不从时钟读)
    当下()   世界的日期 + **机器的时刻** —— 世界按天平移,一天之内的钟点是真的

为什么当下() 用机器的时刻:世界平移的粒度是天,时刻没有被平移过。
硬造一个固定时刻(比如都当成 12:00)会让同一天内的先后顺序全错,
而那种错在单条记录上看完全正常。

⚠️ **不是所有 `datetime.now()` 都该换成这个。** 会话过期、审计时间戳、
监控指标记的是**真实世界**发生的事,它们本来就该用机器时钟。
该换的是**写演示业务数据**的地方 —— 判据是:这一列会不会被
`tools/shift_world.py` 平移。会被平移的,就必须用世界时钟写。
"""
import datetime as _dt
import os as _os
import sys as _sys

_HERE = _os.path.dirname(_os.path.abspath(__file__))
if _HERE not in _sys.path:
    _sys.path.insert(0, _HERE)


def 今天():
    """世界的日期(date)。**从库里读,不从时钟读。**"""
    import seed
    v = seed.TODAY
    return v if isinstance(v, _dt.date) else _dt.date.fromisoformat(str(v))


def 当下():
    """世界的日期 + 机器的时刻(datetime)。"""
    now = _dt.datetime.now()
    return _dt.datetime.combine(今天(), now.time())


def 差几天(d):
    """某一天距离「世界的今天」几天(正数=过去)。"""
    d = d if isinstance(d, _dt.date) else _dt.date.fromisoformat(str(d)[:10])
    return (今天() - d).days


# ── 「已经发生的事」的时间列 —— **唯一来源** ─────────────────────────
#
# 这份清单原来只长在 `backend/spec_check.py` 的 C4 里(叫 `_FUTURE`)。
# 2026-09-26 平移要用同一份知识(平移前得知道「有没有记录已经在未来」),
# 于是挪到这里:**一份数据,两个读者**。
#
# 抄一份给平移的话,两份会各自漂 —— 而漂的表现是「C4 红着但平移放行」
# 或者反过来,两种都看不出是清单不同步。
#
# ⚠️ 只列**已经发生**的事实(互动过了、量过了、付过了、派过了)。
# **计划类字段本来就该在未来**(预约开始、任务截止、承诺交期),不在这份清单里 ——
# 把它们混进来的后果是每天的平移都会被自己拦住。
#
# 每条是 (表, 列, 说明, **主键列**)。
# ⚠️ 主键列必须写出来:第一版是三元组、查询里写死 `SELECT id`,
# 而 `pkg` 的主键叫 `pkg_id`、`order_event` 压根没有单列主键 ——
# 加进来之后 C4 报「查不了:no such column: id」。
# 那次**没有静默通过**(C4 的「不许 pass」救了一次),但如果它当时是 `except: pass`,
# 这两列就会悄悄进入清单却从来没被查过 —— 而清单看起来是齐的。
已发生的时间列 = [
    ("customer", "last_interact", "最近互动", "id"),
    ("measure_rec", "measured_at", "量体时间", "id"),
    ("ordr", "paid_at", "付款时间", "id"),
    ("ordr", "finished_at", "订单完成", "id"),
    ("schedule", "assigned_at", "派单时间", "id"),
    ("followup", "ts", "跟进时间", "id"),
    ("fitting", "ts", "白坯试衣时间", "id"),
    ("fitting", "signed_at", "试衣签字时间", "id"),
    ("ordr", "cut_at", "开裁时间", "id"),
    # 2026-09-26 补进来的两列 —— **并行会话指出来的,而它指对了**:
    # `pkg.created` 在正常行里等于 `shipped_at`(包裹发出那一刻建的档),
    # 是**已经发生的事**。它当时不在这份清单里,所以:
    #   · spec_check 的 C4 查不到它
    #   · shift_world 的平移前置闸也看不见它
    # 12 条 `created=2026-10-22` 是靠**假数据工厂的基线断言**
    # (`pkg.arrived_at 不该早于 created`)才照出来的 ——
    # **一条清单漏掉的列,就是两道闸同时的盲区。**
    ("pkg", "created", "包裹建档", "pkg_id"),
    ("ordr", "updated", "订单最后更新", "id"),
    # order_event 没有单列主键 —— 用 rowid(SQLite 每张表都有)
    ("order_event", "at", "订单事件发生时间", "rowid"),
]


def 未来记录(conn, 基准=None, 每列上限=3):
    """哪些「已经发生的事」落在了世界的未来。返回清单(空=干净)。

    ⚠️ **查不了的列要报出来,不许 `pass`** —— 被吞掉的异常和「查过了没问题」
    在输出上完全一样。spec_check 的 C4 为这一条栽过一次
    (`followup.created` 这一列根本不存在,于是那一项从加进来那天起没查过一次)。

    ⚠️ 但**「这张表不存在」和「这一列写错了」是两回事**,要分开:
    前者是合成夹具/还没建全的库(正常),后者是清单和库对不上(该红)。
    第一版把两者混成一条,结果 shift_world 的自测(夹具只有两张表)
    被自己的闸拦住了 —— **判据把「没这张表」当成了「有未来记录」**。
    分开之后见 `分类()`。
    """
    return 分类(conn, 基准, 每列上限)["未来行"]


def 分类(conn, 基准=None, 每列上限=3):
    """返回 {未来行, 缺表, 查不了} —— 三种情况**分开报**。

      未来行  真的有「已经发生的事」落在未来 → **该拦**
      缺表    这张表不存在 → 合成夹具或还没建全的库,**不该拦**,但要说出来
      查不了  表在、查询却失败(列名写错、类型不对)→ **该拦**:
              清单和库对不上,而它的表现是「这一项从来没查过」
    """
    基准 = str(基准 or 今天())[:10]
    未来行, 缺表, 查不了 = [], [], []
    for t, col, cn, pk in 已发生的时间列:
        try:
            for r in conn.execute(
                    f"SELECT {pk},{col} FROM {t} WHERE {col} IS NOT NULL "
                    f"AND substr({col},1,10) > ? LIMIT {int(每列上限)}", (基准,)):
                未来行.append(dict(表=f"{t}.{col}", 说明=cn, id=r[0], 时间=r[1]))
        except Exception as e:
            msg = str(e)
            if "no such table" in msg:
                缺表.append(dict(表=f"{t}.{col}", 说明=cn, 原因=msg))
            else:
                查不了.append(dict(表=f"{t}.{col}", 说明=cn, 原因=f"{type(e).__name__}: {msg}"))
    return dict(未来行=未来行, 缺表=缺表, 查不了=查不了)


# ── 「要和业务时刻比先后」的列 —— **第四类错的唯一来源** ──────────────
#
# ## 这一类和上面那份清单**不是一回事**
#
# `已发生的时间列` 防的是「这一列不该落在世界的未来」,判据是**日期**。
# 这一份防的是另一件事:
#
# > **`当下()` 的日期那一半修对了,时刻那一半仍然会和业务时刻打架。**
#
# 业务时刻(包裹到店 15:00、发货 12:00)是造数**按剧本排的**;
# 而 `当下()` = 世界日期 + **机器时刻**,机器时刻是跑脚本那一刻的真实钟点。
# **同一天之内,这两种时刻没有可比的先后。**
#
# 09-26 实测:重建时真实时间 20:55,于是 `pkg.created 20:55` 晚于同一条包裹的
# `arrived_at 15:00` —— 「包裹建档晚于包裹到店」。
# 而 `worldclock_check.py` 的**三条判据全都放行**:它们问的是
# 「这个写口用的是不是机器时钟」,而那一行用的**确实是**世界时钟。
# **判据的盲区这次不是漏了某种写法,是漏了某种「错」。**
#
# ## 一份登记,两个读者(以及为什么还需要第三个不读它的对照)
#
# · 数据层:`查序关系()` 直接在库里查「早的列是不是真的不晚于晚的列」;
# · 代码层:`worldclock_check.py` 第四条判据查「这些列的写口有没有取『现在』」。
#
# ⚠️ **两个读者共用一份真相源,那么「不在清单里的那一对」会同时躲过两边。**
# 这正是 `pkg.created` 上一次躲过 C4 和平移闸的方式(它们读同一份清单)。
# 所以**必须保留一个不读这份清单的对照** —— 假数据工厂里那条
# 「arrived_at 不该早于 created」的基线断言就是它,**它不针对任何特定的列**,
# 而照出这一次的正是它。**那条断言不许被这份登记替换掉。**
#
# 每条是 (表, 早的列, 晚的列, 说明)。
序关系 = [
    ("pkg", "created", "shipped_at", "包裹要先建档再发出"),
    ("pkg", "shipped_at", "arrived_at", "先发出才能到店"),
    ("ordr", "created", "paid_at", "先下单才能付款"),
    ("ordr", "paid_at", "cut_at", "先付款才开裁"),
    ("ordr", "cut_at", "finished_at", "先开裁才完工"),
    ("fitting", "ts", "signed_at", "先试衣才签字"),
]

# 这些列**不许用「现在」写**(它们要和业务时刻比先后)。
# 从 序关系 派生 —— 两头的列都算,因为任何一头取了「现在」都会让比较失去意义。
def 不许取现在的列():
    出 = set()
    for t, 早, 晚, _ in 序关系:
        出.add((t, 早))
        出.add((t, 晚))
    return sorted(出)


def 查序关系(conn, 每对上限=3):
    """在库里查每一对的先后。返回 {倒挂=[...], 缺表=[...], 查不了=[...]}。

    ⚠️ 判据是 **`早 > 晚` 才算倒挂**,相等放行 —— 同一时刻发生的事是正常的
    (批量造数经常把两件事排在同一分钟)。判成「必须严格早于」会一直误报,
    而误报久了人就开始无视它。
    """
    倒挂, 缺表, 查不了 = [], [], []
    for t, 早, 晚, 说明 in 序关系:
        try:
            for r in conn.execute(
                    f"SELECT rowid,{早},{晚} FROM {t} "
                    f"WHERE {早} IS NOT NULL AND {晚} IS NOT NULL "
                    f"AND {早} > {晚} LIMIT {int(每对上限)}"):
                倒挂.append(dict(表=t, 早=f"{早}={r[1]}", 晚=f"{晚}={r[2]}",
                                说明=说明, rowid=r[0]))
        except Exception as e:
            msg = str(e)
            (缺表 if "no such table" in msg else 查不了).append(
                dict(表=f"{t}.{早}→{晚}", 说明=说明,
                     原因=f"{type(e).__name__}: {msg}"))
    return dict(倒挂=倒挂, 缺表=缺表, 查不了=查不了)
