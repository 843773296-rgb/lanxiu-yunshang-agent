#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""渠道流水号 —— **对账时唯一能把两边对起来的那个号,不许重复。**

来路:只读审计 2026-10-23 第 1 条(`澜绣云裳Agent_数据库只读检查结论_20261023.md`)。

## 这条判据守的那句话

`payment_flow.channel_serial` 是**渠道那边给的单号**。它的用处只有一个:
拿它去和渠道的账单对。所以同一个渠道、同一个方向上,它必须唯一 ——
**两笔不同的钱共用一个号,对账就对不起来了,而且对不起来的时候不报错**。

> 一个「两笔不同的钱共用一个渠道流水号」的库,和一个正常的库,
> **在任何一张页面上长得一模一样** —— 按押金查流水照样一条不多一条不少,
> 因为所有页面都是**按 `deposit_id` 查**的,**没人按流水号反查**。

2026-10-23 查到的两条就是这么来的:造数里流水号拼的是「常量 + `i`」,
而 `i` 是**这次循环的第几条**、`did` 是**全局递增**的押金号 ——
重跑一次 `i` 归零、`did` 接着走,同一个号就配到了另一笔押金上。
(修在 `tools/seed_triage_tasks.py`:改成绑 `did`。)

## ⚠️ 为什么只验「不重复」,**不建唯一索引**

审计自己写着:「真实支付流水的唯一约束应依据**渠道事件语义**确定,
不能直接按当前猜测加索引或删除重复行。」这话是对的 ——
真实世界里同一个渠道单号**可能**合法地出现两次(重试、对账补录、部分退款分笔),
而那取决于渠道的事件语义,不是我能替业务定的。

所以这条判据的位置很明确:**它守的是「我们自己造的数据别自相矛盾」**,
不是「数据库层面强制唯一」。后者要业务拍板(已登记进只读审计待办第 6 条)。
> **一条「业务上允许重复」和一条「造数把号拼错了」,在那两行数据上长得一模一样** ——
> 分开它们的是**那个号是怎么生成的**,所以这条判据连生成方式一起验。

## 验三件

  ① 同渠道 + 同流水号 + 同方向,**不许重复**(样本量要报出来)
  ② 造数那两处**不许再拿循环下标拼号** —— 查结构,不查某个具体常量
  ③ 判据**自己造**一对重复去调同一个判断
     (库里现在是干净的,不自己造的话这条分支永远走不到,
      而「没走到」和「验过了」在绿勾上长得一模一样)
"""
import os
import re
import sqlite3
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DB = os.path.join(HERE, "lanxiu.db")

G, Rd, Y, D = "\033[32m", "\033[31m", "\033[33m", "\033[0m"

咬合 = [
    # ⚠️ 第一条的攻击打在**造数**上(被检查的那个东西),不是打在判据上 ——
    # **削弱一条检查永远不会让它红**(2026-10-23 为这个重写过一条规格:
    # 当时我去改判据自己的 ck 标题和条件,咬合报「改坏了却没红」)。
    # ⚠️ 攻击必须落在**这条判据真正看的那一段**上:它查的是
    # INSERT 参数元组里有没有 `+ 裸循环变量}`。第一版我去改算号函数内部
    # (`序` 钉成 0)—— 行为确实坏了,但**那个形状没出现在元组里**,判据看不见,
    # 咬合当场报「改坏了却没红」。
    # > **注入要落在判据真正看的那一段上,差几个字就等于没注入。**
    ("把一处 INSERT 的流水号改回「常量 + 这次循环的第几条」",
     "没有一处拿裸循环下标拼流水号"),
    # 第二条是**反向**的:它让判据变**松**(不看方向),而松了之后
    # 「同一笔押金一进一出共用一个号」会被误报成重复 ——
    # 所以预期红的是「方向不同不算重复」那条自造用例,不是真库那条。
    # > 一条「守得住」的判据和一条「在正常数据上误报」的判据,
    # > 在真库全绿这件事上长得一模一样 —— 真库里碰巧没有这种形状。
    # ⚠️ 预期红的是「只逮那一对」那条,不是「方向不同不算重复」那条:
    # 自造用例里 A/B/C 三行同号,去掉方向之后它们塌成一组 3 条,
    # **条数那一条先触发**。第一版写成后者,咬合报「红了但红的不是那一条」。
    ("让重复判定不看 direction(一进一出同号是正常的,会被误报成重复)",
     "判据真的逮得到**(而且只逮那一对)"),
]

坏, n = [], 0


def ck(名, ok, 说明=""):
    global n
    n += 1
    print(f"  {G + '✅' + D if ok else Rd + '❌' + D} {名}" + ("" if ok else f"  —— {说明}"))
    if not ok:
        坏.append(名)


def 重复的(c):
    """返回 [(渠道, 流水号, 方向, 条数, 都挂在哪几笔押金上)] —— 空表示干净。"""
    out = []
    for ch, se, di, cnt in c.execute(
            "SELECT channel, channel_serial, direction, COUNT(*) FROM payment_flow "
            "WHERE channel_serial IS NOT NULL AND TRIM(channel_serial) <> '' "
            "GROUP BY channel, channel_serial, direction HAVING COUNT(*) > 1"):
        挂 = [r[0] for r in c.execute(
            "SELECT deposit_id FROM payment_flow WHERE channel=? AND channel_serial=? "
            "AND direction=? ORDER BY deposit_id", (ch, se, di))]
        out.append((ch, se, di, cnt, 挂))
    return out


print(f"\n\033[1m▸ 渠道流水号 · 对账时唯一能把两边对起来的那个号不许重复\033[0m")
print("  " + "=" * 80)

# ── ① 真库上 ────────────────────────────────────────────────────────────
if not os.path.exists(DB):
    print(f"  {Y}⏭{D} 库不在,跳过 —— **跳过不是通过**")
    sys.exit(0)

with sqlite3.connect(f"file:{DB}?mode=ro", uri=True) as c:
    总 = c.execute("SELECT COUNT(*) FROM payment_flow "
                   "WHERE channel_serial IS NOT NULL AND TRIM(channel_serial) <> ''"
                   ).fetchone()[0]
    种 = c.execute("SELECT COUNT(DISTINCT channel || '|' || channel_serial || '|' || direction) "
                   "FROM payment_flow WHERE channel_serial IS NOT NULL "
                   "AND TRIM(channel_serial) <> ''").fetchone()[0]
    重 = 重复的(c)

# **样本量为 0 要红** —— 空集合上所有性质都成立,
# 而「一条流水都没有」和「流水都不重复」在这条判据上长得一模一样。
#
# ⚠️ 这个下限守的是「**没扫到东西**」,不是「该有多少条」——
# 所以它定得比现状低一截,而真实条数**印出来**让人看。
# 第一版我拍了 50,而真库当时是 36 条,**那条红说的是「样本不够」而真相是我拍高了**:
# > 一条「库里没数据」的红,和一条「我把下限拍高了」的红,在那句话上长得一模一样。
# 写死一个贴着现状的数就是夹具写死会漂的东西(押金一多它就跟着涨)。
ck(f"有流水可验(带流水号的 {总} 条 · {种} 个不同的「渠道+号+方向」)",
   总 >= 10, f"只有 {总} 条 —— **这不是通过,是没扫到东西**"
             f"(下限 10 只防「空扫」,不是说该有多少条)")
ck(f"同渠道 + 同流水号 + 同方向**不重复**(验了 {总} 条)",
   not 重,
   f"{[(ch, se, di, f'{cnt} 条', 挂) for ch, se, di, cnt, 挂 in 重][:4]} —— "
   f"**两笔不同的钱共用一个渠道流水号,对账就对不起来,而且不报错**。"
   f"多半是造数拿循环下标拼的号(见下一条);"
   f"⚠️ 别直接删重复行 —— 先看它们挂在哪几笔押金上,确认哪一条是假的")

# ── ② 造数不许再拿循环下标拼号(查结构)────────────────────────────────
#
# ⚠️ 查的是**结构**:「`channel_serial` 这一列的值里出现了循环变量」。
# 不查某个具体常量(`9000000000` 那种会漂),也不查某个具体文件名之外的东西。
造 = os.path.join(ROOT, "tools", "seed_triage_tasks.py")
if not os.path.exists(造):
    ck("造数脚本在", False, f"{造} 不在了 —— 这条判据点名的文件消失了,**不是通过**")
else:
    src = open(造, encoding="utf-8").read()
    # 取 INSERT INTO payment_flow(...) 那几个 execute 的参数元组,看里面有没有
    # 「拿裸循环变量参与算号」的写法。判据盯的是 `+ i`(以及 i2/idx 这类)这个形状。
    片 = []
    # ⚠️ 这个正则**故意写成 `INSERT\\s+INTO`**,不写那个连在一起的字面串 ——
    # 否则 `tools/insert_shape_check.py` 会把**我这一行正则**当成一处
    # 「写了表名却看不出列名」的 INSERT,然后判我欠一笔位置参数的债。
    # 2026-10-23 真撞了一次,门禁当场红在 `backend/payment_serial_check.py → payment_flow`。
    # > **判据的源码会被别的判据扫到**,而那时红的理由指向一处根本不存在的问题。
    # 同 CLAUDE.md §5 那条:被扫描的文件里要举例就**描述**它,别照抄
    # (那一条为密钥扫描连踩三次:规则写进文档 → 文档匹配自己;挪进规则文件 →
    #  规则文件匹配自己;写在脚本注释里 → 脚本匹配自己)。
    for m in re.finditer(r"INSERT\s+INTO\s+payment_flow\s*\(", src):
        # 从这个 INSERT 往后取到下一个 `))` 收尾 —— 参数元组就在这一段里
        尾 = src.find("))", m.end())
        片.append(src[m.end():尾 if 尾 > 0 else m.end() + 600])
    # 盯的形状:参数元组里出现「`+ <裸循环变量>}`」—— 那就是拿「这次循环的第几条」算号。
    # 查结构而不查具体常量:`9000000000` 那种数会漂,而「加一个循环下标」这个形状不会。
    裸下标 = re.compile(r"\+\s*(?:i|j|k|n|idx)\s*\}")
    嫌 = [p for p in 片 if 裸下标.search(p)]
    ck(f"造数里 {len(片)} 处写支付流水,**没有一处拿裸循环下标拼流水号**",
       not 嫌 and len(片) >= 2,
       f"{len(嫌)} 处还在拿循环下标拼号(片段 {[p[:70] for p in 嫌][:2]})—— "
       f"**循环下标每次重跑都归零,而押金号全局递增** → 同一个号配到另一笔押金上。"
       f"绑押金号(或别的全局唯一标识),别绑「这次循环的第几条」"
       if 嫌 else f"只找到 {len(片)} 处写流水的地方(该有 2 处:收款 + 退款)—— "
                  f"**找不到就不是通过**,多半是这条判据的正则跟不上代码改动了")

# ── ③ 判据自己造一对重复去调同一个判断 ────────────────────────────────
#
# 库里现在是干净的,所以上面那条 `重复的()` 永远走的是「没有重复」那一支。
# 不自己造的话,**这条判据守不守得住根本不可观测**。
import tempfile
tmp = tempfile.mkdtemp()
假 = os.path.join(tmp, "t.db")
c2 = sqlite3.connect(假)
c2.execute("CREATE TABLE payment_flow(id TEXT PRIMARY KEY, deposit_id TEXT, "
           "direction TEXT, amount REAL, channel TEXT, channel_serial TEXT, "
           "status TEXT, ts TEXT)")
# ⚠️ 点名列,不用位置参数(门禁有一条专门盯这个:列数相等而顺序错了不报错)
c2.executemany(
    "INSERT INTO payment_flow(id, deposit_id, direction, channel, channel_serial) "
    "VALUES(?,?,?,?,?)",
    [("A", "DQ9001", "in", "微信支付", "WX9000000000"),
     ("B", "DQ9002", "in", "微信支付", "WX9000000000"),     # ← 同渠道同号同方向
     ("C", "DQ9003", "out", "微信支付", "WX9000000000"),    # ← 同号但**方向不同**,不算重复
     ("D", "DQ9004", "in", "支付宝", "WX9000000000"),       # ← 同号但**渠道不同**,不算重复
     ("E", "DQ9005", "in", "微信支付", None),               # ← 空号不参与
     ("F", "DQ9006", "in", "微信支付", "   ")])             # ← 空白号不参与
c2.commit()
造出来的 = 重复的(c2)
ck("自己造一对「同渠道+同号+同方向」→ **判据真的逮得到**(而且只逮那一对)",
   len(造出来的) == 1 and 造出来的[0][:3] == ("微信支付", "WX9000000000", "in")
   and 造出来的[0][3] == 2,
   f"逮到的是 {造出来的} —— 该只有一对;逮不到的话上面那条判据是个摆设")
ck("同一个号但**方向不同 / 渠道不同**,不算重复(那是两笔真·不同的渠道事件)",
   all(not (x[0] == "支付宝" or x[2] == "out") for x in 造出来的),
   f"{造出来的} —— 把它们也判成重复的话,这条判据会在正常数据上误报")
ck("流水号是空的 / 只有空白,**不参与重复判定**(没有号就谈不上号重复)",
   all(x[1] and x[1].strip() for x in 造出来的),
   f"{造出来的} —— 空号被凑成一组的话,一堆没号的流水会被判成互相重复")
c2.close()
import shutil
shutil.rmtree(tmp, ignore_errors=True)

print("  " + "=" * 80)
if 坏:
    print(f"  {Rd}❌ {len(坏)} 条没过:{坏}{D}")
    sys.exit(1)
print(f"  {G}✅ 渠道流水号对得起账(验了 {n} 条){D}")
print(f"      ⚠️ 这条判据**不建唯一索引** —— 真实世界里同一个渠道单号可能合法地出现两次"
      f"(重试 / 对账补录 / 部分退款分笔),而那取决于渠道的事件语义,不是这里能定的。"
      f"它守的是「我们自己造的数据别自相矛盾」;数据库层面要不要强制唯一,"
      f"归只读审计待办第 6 条,等业务拍板。")
sys.exit(0)

