#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""受欢迎程度与易损率 · 性质检查 —— 口径在 `knowledge/popularity.py`。

## 为什么验的是**性质**,不是逐例真值

项目第 9 节定的分流准入标准第 ③ 条:

    绝对判定  逐例标真值(生命周期八档:第 90 天就是活跃)
    相对指标  验性质(RFM 五分位:分数随人群变)

「这个月谁最受欢迎」是**相对指标** —— 它随订单变,今天第一名明天就不是。
逐例标真值的话,**第二天就会过期,而且过期时不报错,只会开始误报**。

所以验的是这些**不管数据怎么变都该成立**的事:

  1. 取消单不进榜(口径说不算,那就一件都不能漏进来)
  2. 两张榜的总件数一致 —— 同一批数据换个排序,总量不该变
  3. 件数榜和金额榜**可以不同**,而且**通常应该不同** ——
     完全相同说明要么数据太少,要么口径塌成了一个
  4. 维保率 = 分子 / 分母,且分母 < 下限时**必须是 None 不是 0**
  5. 维度分布各档之和 **≥** 总件数(一件商品可以挂多个面料,会重复计)
  6. 排序是确定的 —— 同样的输入跑两次,名次一模一样

第 3 条是这里面最有意思的:它**故意允许两张榜不一致**,
反过来把「一致」当成可疑信号。因为那正是「用一个合成分数把两个口径揉成一个」
之后会出现的样子 —— 而口径里明写着不合成。
"""
import importlib.util
import os
import sqlite3
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
_s = importlib.util.spec_from_file_location(
    "popularity", os.path.join(ROOT, "knowledge", "popularity.py"))
pop = importlib.util.module_from_spec(_s)
_s.loader.exec_module(pop)

FAIL = []
DONE = []


def ck(name, ok, n, msg=""):
    DONE.append(name)
    print(f"  {'✅' if ok else '❌'} {name}(验了 {n} 个){'  ' + msg if msg else ''}")
    if not ok:
        FAIL.append(name)
    if n == 0:
        print("     ⚠️ 样本量 0 —— **这不叫通过,这叫没扫到东西**")
        FAIL.append(name + "(样本量 0)")


def 取数(c, 月=None):
    where = "WHERE 1=1"
    a = []
    if 月:
        where += " AND substr(o.created,1,7)=?"
        a.append(月)
    行 = [dict(r) for r in c.execute(
        f"SELECT i.spu, i.name, i.qty, i.total, o.status, o.created"
        f" FROM ordr_item i JOIN ordr o ON o.id=i.order_id {where}", a)]
    # 商品 → 形制 / 面料 / 工艺
    维 = {}
    for r in c.execute("SELECT spu,xz,mt_opts,kf_opts FROM product_custom"):
        维[r[0]] = {
            "形制": [x.strip() for x in (r[1] or "").split(",") if x.strip()],
            "面料": [x.strip() for x in (r[2] or "").split(",") if x.strip()],
            "工艺": [x.strip() for x in (r[3] or "").split(",") if x.strip()],
        }
    return 行, 维


def main():
    print("受欢迎程度与易损率 · 性质检查")
    print("=" * 80)
    c = sqlite3.connect(os.path.join(HERE, "lanxiu.db"))
    c.row_factory = sqlite3.Row
    行, 维 = 取数(c)

    # 维保 → spu(经 order_item 反查,**不按商品名**)
    维保行 = [dict(r) for r in c.execute(
        "SELECT i.spu FROM maintain m JOIN ordr_item i ON i.id=m.order_item_id")]
    c.close()

    取形制 = lambda r: 维.get(r.get("spu"), {}).get("形制", [])
    取面料 = lambda r: 维.get(r.get("spu"), {}).get("面料", [])

    榜 = pop.受欢迎(行)

    # ── ① 取消单一件都不许进榜 ────────────────────────────────────
    取消件 = sum(int(r["qty"] or 0) for r in 行 if r["status"] == "取消")
    全部件 = sum(int(r["qty"] or 0) for r in 行)
    ck("① 取消单不进榜", 榜["总件数"] == 全部件 - 取消件, len(行),
       f"榜内 {榜['总件数']} = 全部 {全部件} − 取消 {取消件}"
       if 榜["总件数"] == 全部件 - 取消件 else
       f"榜内 {榜['总件数']},而应该是 {全部件 - 取消件}")

    # ── ② 换个排序,总量不该变 ────────────────────────────────────
    a = sum(x["件数"] for x in 榜["按件数"])
    b = sum(x["件数"] for x in 榜["按金额"])
    ck("② 两张榜是同一批数据的两种排法", a == b == 榜["总件数"], len(榜["按件数"]),
       f"件数榜合计 {a} / 金额榜合计 {b} / 口径总件数 {榜['总件数']}")

    # ── ③ 两张榜**应该**不一样 ───────────────────────────────────
    #    完全一致是可疑信号:要么数据太少,要么两个口径塌成了一个。
    前十件 = [x["spu"] for x in 榜["按件数"][:10]]
    前十金 = [x["spu"] for x in 榜["按金额"][:10]]
    ck("③ 件数榜和金额榜的前十名不完全相同", 前十件 != 前十金, len(前十件),
       "**故意允许两张榜不一致,反过来把「一致」当可疑信号** —— "
       "一件卖 3 件的重工和一件卖 30 件的常服,按件数和按金额本来就该排出不同的结果"
       if 前十件 != 前十金 else
       "两张榜前十完全相同 —— 要么样本太少,要么口径塌成了一个,查一下")

    # ── ④ 维保率:分子分母都在,分母不足时是 None 不是 0 ──────────
    率 = pop.易损率(行, [{"spu": r["spu"]} for r in 维保行], 取面料)

    # ⚠️ **下限这个数在这里手抄一份,不从 pop 读。**
    #    第一版写的是 `pop.易损分母下限` —— 拿被测模块的常数当期望值,
    #    于是把口径里的下限改成 0 时,**两边一起变,检查照样全绿**。
    #    咬合当场抓到:「改坏了却没红 —— 检查看不见这处破坏」。
    #    这就是这个项目里那条「同源谬误」,我在给它写检查的时候又犯了一次。
    # ⚠️ **这里有两个数,别混。**
    #    `最低可接受下限` 是这道检查独立手抄的**底线**:口径把下限调到这个数以下就红。
    #    它**不是**口径当前用的那个值 —— 口径可以比它严,不能比它松。
    #    (2026-09-19 业务把口径下限从 10 提到 30,这里的底线仍是 10:
    #     底线管的是「不许松到荒唐」,不是「必须等于某个数」。
    #     写成相等的话,每次业务调下限这道检查都要跟着改,
    #     而**跟着改的检查,等于没有独立判断**。)
    最低可接受下限 = 10
    坏 = []
    if pop.易损分母下限 < 最低可接受下限:
        坏.append(f"口径里的分母下限是 {pop.易损分母下限},低于底线 {最低可接受下限} —— "
                 f"下限一松,「卖 2 件修 1 件 = 50%」就会排在第一名")
    for x in 率:
        if x["维保率"] is None:
            # 给不给率,按**口径当前的下限**判(它可以比底线严);
            # 底线那一条上面单独判过了。
            if x["销售件数"] >= pop.易损分母下限:
                坏.append(f"{x['值']} 分母 {x['销售件数']} 够却没给率")
        else:
            if x["销售件数"] < pop.易损分母下限:
                坏.append(f"{x['值']} 分母 {x['销售件数']} 不足却给了率")
            if abs(x["维保率"] - round(x["维保单数"] / x["销售件数"], 4)) > 1e-9:
                坏.append(f"{x['值']} 率和分子分母对不上")
    ck("④ 维保率 = 分子/分母,分母不足时不给结论", not 坏, len(率),
       f"{坏[:3]}" if 坏 else
       f"下限 {pop.易损分母下限} 件(检查这边独立手抄 {最低可接受下限} 做底线);"
       f"**不给 0% 而给「样本不足」** —— "
       f"0% 会被读成「这个面料不容易坏」,而真相是「没卖几件,看不出来」")

    # ── ⑤ 维度分布:覆盖得到的那部分,各档之和 ≥ 它的件数 ────────────
    #
    # ⚠️ **第一版这里写的是 `和 >= 0` —— 永远成立,等于没验。**
    #    我当时以为「各档之和 ≥ 总件数」(一件可挂多个面料会重复计),
    #    跑出来 8800 < 30748,于是随手把断言放松成了一个恒真式。
    #    真相是:**只有定制品有面料映射,标品没有** ——
    #    所以该比的不是全库总件数,是**有映射的那部分**。
    #    把断言放松到恒真,和删掉这条检查是一回事,而前者看起来还在守着。
    # 精确等式:各档之和 == Σ(件数 × 这一行挂了几个面料)。
    # ⚠️ 第一版写的是「和 ≥ 有映射件数」—— 太松:把「一件挂多个面料各计一次」
    #    改成「只计第一个」之后,和变小了但仍然 ≥,**咬合当场抓到它没红**。
    #    **不等式判不出「少算了一部分」,等式才判得出。**
    应等于 = sum(int(r.get("qty") or 0) * len(取面料(r) or [])
               for r in 行 if pop.算数的单(r.get("status")))
    分布 = pop.维度分布(行, 取面料)
    和 = sum(x["件数"] for x in 分布)
    ck("⑤ 各档之和 == Σ(件数 × 该行挂了几个面料)", 和 == 应等于, len(分布),
       f"各档之和 {和},而应该是 {应等于}" if 和 != 应等于 else
       f"{和} = Σ(件数 × 面料个数);全库 {榜['总件数']} 件,"
       f"其余是没有面料映射的标品 —— **大于总件数是对的**(重复计),"
       f"但必须说明,否则会被当成占比去算百分比")

    # ── ⑥ 排序确定 ──────────────────────────────────────────────
    #    同样的输入跑两次,名次必须一模一样。并列时不靠字典序兜底的话,
    #    榜单会在两次刷新之间无理由地跳动 —— 而那种跳动**没人查得出原因**。
    再 = pop.受欢迎(行)
    ck("⑥ 同样的输入跑两次,名次一模一样",
       [x["spu"] for x in 再["按件数"]] == [x["spu"] for x in 榜["按件数"]],
       len(榜["按件数"]),
       "并列时按 spu 兜底定序 —— 否则榜单会在两次刷新之间无理由跳动,而那种跳动没人查得出原因")

    # ── ⑦ 显著性判断本身要可信:突出的那几档,必须真的越过了两倍噪声 ──
    #    这条防的是「判显著的那段逻辑写歪了」——
    #    它一歪,输出仍然是一张漂亮的榜,只是「值得注意」那几档变成了随机的。
    显 = pop.差异显著吗(率)
    歪 = []
    if 显.get("显著"):
        p0 = 显["合并率"]
        for x in 显["突出的"]:
            n = [y for y in 率 if y["值"] == x["值"]][0]["销售件数"]
            噪 = 2 * (p0 * (1 - p0) / n) ** 0.5
            if abs(x["率"] - p0) <= 噪:
                歪.append(f"{x['值']} 被判成突出,实际没越过两倍噪声")
    ck("⑦ 判成「值得注意」的档,确实越过了两倍噪声",
       not 歪, len(显.get("突出的", [])) or 1,
       f"{歪[:3]}" if 歪 else
       (f"合并率 {显.get('合并率', 0):.1%},突出 {len(显.get('突出的', []))} 档"
        if 显.get("显著") else
        "**这批数据判为不显著** —— 那也是一个结论,而且是更该报出来的那个:"
        "排行榜排得出来,但第一名和最后一名的差可能只是噪声"))

    print("=" * 80)
    if FAIL:
        print(f"❌ {len(FAIL)} 条没过:{FAIL}")
        return 1
    print(f"✅ 受欢迎与易损 {len(DONE)} 条性质全过")
    return 0


咬合 = [
    ('把「取消单不算数」那一支关掉(取消的也计进榜)', '① 取消单不进榜'),
    ('把口径里的分母下限改成 0(样本 2 件也给率)', '④ 维保率 = 分子/分母'),
    ('把排序里的 spu 兜底去掉(并列时名次随机)', '⑥ 同样的输入跑两次'),
    ('把维度分布里「一件挂多个面料各计一次」改成只计第一个', '⑤ 各档之和'),
    ('把显著性判据里的「两倍噪声」改成「零」(所有档都算突出)', '⑦ 判成「值得注意」的档'),
]

if __name__ == "__main__":
    sys.exit(main())
