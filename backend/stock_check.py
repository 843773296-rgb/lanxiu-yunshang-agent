#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""库存预警的检查 —— **算不出的,不许算出一个数来。**

`intent/stock-alert.md` 立项时就写死了一条,而做的时候差点没守住:

> **算不出可售天数的,要明说「算不出」,不许退回成件数阈值假装算得出**
> —— 这个项目为「抓不到 ≠ 零」栽过好几次。

第一版口径只判了「卖过几件 > 0」就放行,于是**在文档里写着「不许凑数」的
同一个模块,自己凑了一个数**:一个卖过 1 件、跨 18 天的 SKU,
被算出「还能卖 18 天」。

那个 18 天是假的,**而且假得看不出来** —— 它有单位、有小数点、排得进表格。
它区分不了「每 18 天稳定卖 1 件」和「那 18 天里碰巧卖了 1 件」,
**而这两件事对补货的含义完全相反**。

所以这套检查钉的是三样东西:

    **算不出就说算不出**   笔数不够的 SKU,那一栏必须是话,不许是数
    **在手 ≠ 可用**        可用 = 在手 − 已占用,两个数要同时报
    **不许编阈值**         补货点是 None,而且带着「为什么是空的」

## 为什么「最少两笔」不算编阈值

这个项目的规矩是**不许替业务猜数**(积分门槛、特体修版量、超时天数……)。
「两笔」不在那一类:它不是商业判断,是算术 —— **一个点画不出一条斜率**。
换谁来做这门生意,一笔销售都推不出销售速度。

而「低于 10 件就预警」是**纯粹的业务判断**,所以它不许在代码里出现。
这套检查会去源码里找那种写死的件数线。
"""
import os, sys, re, sqlite3

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path[:0] = [HERE, ROOT, os.path.join(ROOT, "knowledge")]

# ── 咬合记录 ────────────────────────────────────────────────────────────
# 每一条都手动改坏过一次,确认对应那条检查**真的会红**。
# 一条从没红过的检查,和没有这条检查是一样的。
咬合 = [
    ("把 可售天数() 里的「笔数不够」那道闸删掉(退回成只判件数 > 0)",
     "卖过不到两笔的 SKU,可售天数必须是「算不出」"),
    ("把 补货点 从 None 改成 10",
     "口径里不许写死补货件数阈值"),
    ("把 可用() 改成直接返回 在手(不减已占用)",
     "可用 = 在手 − 已占用"),
    ("把「发不出」那一档并进「断货」",
     "「断货」档里不许有在手 > 0 的(**并进去数字全对得上,"
     "只是 20 个催一下就能发货的 SKU 被说成了要补货**)"),
    ("把停用的 SKU 也算进预警",
     "停用的 SKU 不进预警"),
    ("把 TL29 从 TASK_RULES 挪进 KB_RULES(工具在任务助手那边)",
     "TL29 和 stock_alert 要在同一个角色身上"),
]

FAIL = []


def ck(name, ok, n, msg=""):
    print(f"  {'✅' if ok else '❌'} {name}(验了 {n} 个){'  ' + msg if msg else ''}")
    if not ok: FAIL.append(name)
    if n == 0:
        print("     ⚠️ 样本量 0 —— **这不叫通过,这叫没扫到东西**")
        FAIL.append(name + "(样本量 0)")


def main():
    print("库存预警 · 检查")
    print("=" * 84)
    import stockalert as SA, api, prompts

    # ── ① 口径:不许编阈值 ────────────────────────────────────────────
    ck("口径里不许写死补货件数阈值",
       SA.补货点 is None and bool(SA.补货点_为什么是空的), 1,
       "补货点 = 补货周期内的销量 + 安全库存,**两样都要业务和数据撑着**")

    src = open(os.path.join(ROOT, "knowledge", "stockalert.py"),
               encoding="utf-8").read()
    # 把注释和文档串里的数字排除掉,只看真正参与判断的代码
    代码 = "\n".join(l.split("#")[0] for l in src.splitlines())
    代码 = re.sub(r'"""[\s\S]*?"""', "", 代码)
    野线 = re.findall(r'(?:在手|库存|stock|可用)\s*[<>]=?\s*(\d+)', 代码)
    ck("源码里没有写死的库存件数预警线",
       not [x for x in 野线 if int(x) > 4], len(代码.splitlines()),
       f"找到 {野线}" if 野线 else "**「低于 10 件预警」是业务判断,不是代码能定的**")

    # ── ② 算不出就说算不出 ────────────────────────────────────────────
    # **这条是 intent 点名要的那一条。**
    for 笔, 件, 说 in ((0, 0, "一件没卖过"), (1, 1, "只卖过一笔"), (1, 9, "一笔卖了 9 件")):
        天, 为什么 = SA.可售天数(10, 0, 笔, 件, 18)
        ck(f"卖过不到两笔的 SKU,可售天数必须是「算不出」({说})",
           天 is None and "算不出" in (为什么 or ""), 1,
           (为什么 or "")[:46])
    天, _ = SA.可售天数(10, 0, 6, 9, 18)
    ck("笔数够了就该算得出来(**不是一律不给数**)",
       isinstance(天, float), 1,
       f"{天} 天 —— 一律不给数的检查,咬合测试测不出它是不是真在判")

    # ── ③ 工具出口也守着同一条 ────────────────────────────────────────
    r = api.stock_alert()
    档 = ["发不出", "断货", "快没了", "卖不动"]
    ck("四档齐全,而且「发不出」单独成一档",
       all(k in r for k in 档), len(档),
       "**在手有货但全被占用**是唯一一种「在库存表上看起来没问题」的缺货")

    行 = [x for k in 档 for x in (r[k].get("明细") or [])]
    坏 = [x for x in 行 if (x.get("卖过几笔") or 0) < SA.最少笔数
          and not isinstance(x.get("可售天数"), str)]
    ck("工具出口:笔数不够的,那一栏是话不是数", not 坏, len(行),
       f"{len(坏)} 行给出了编造的天数:{[x['SKU'] for x in 坏[:3]]}" if 坏
       else f"{len(行)} 行,**没有一个编出来的天数**")

    零 = [x for x in 行 if x.get("可售天数") == 0 or x.get("可售天数") == 0.0]
    ck("「算不出」不许写成 0 天", not 零, len(行),
       "0 天会被读成「今天就断」—— **和「不知道」是两回事**")

    # ── ④ 在手 ≠ 可用 ─────────────────────────────────────────────────
    错 = [x for x in 行
          if x.get("可用") != (x.get("在手") or 0) - (x.get("已占用") or 0)]
    ck("可用 = 在手 − 已占用", not 错, len(行),
       f"{len(错)} 行对不上" if 错 else "客户问「还有货吗」要的是**可用**")

    # **「断货」档里不许出现在手 > 0 的。** 这条和上面那条是一对:
    # 把「发不出」并进「断货」不会让任何一栏变空 —— 数字对得上、总数也没变,
    # **只是 20 个「催订单释放就能发货」的 SKU 被说成了「要补货」**。
    # 只查「发不出这一档是不是空的」防不住它反过来的情形,所以两头都钉。
    误 = [x for x in (r["断货"].get("明细") or []) if (x.get("在手") or 0) > 0]
    ck("「断货」档里不许有在手 > 0 的", not 误, len(r["断货"].get("明细") or []),
       f"{len(误)} 行在手有货却被说成断货:{[x['SKU'] for x in 误[:3]]}" if 误
       else "**在手有货但被占用**该催订单释放,**在手是 0** 才该补货 —— 两个动作不一样")

    有货却发不出 = r["发不出"]["明细"]
    ck("「发不出」这一档里的,在手都 > 0 而可用都 = 0",
       all((x.get("在手") or 0) > 0 and x.get("可用") == 0 for x in 有货却发不出),
       len(有货却发不出),
       "在手是 0 的属于「断货」,**两者该做的事不一样**:"
       "一个是催订单释放,一个是补货")

    # ── ⑤ 停用的不进预警 ──────────────────────────────────────────────
    c = sqlite3.connect(os.path.join(HERE, "lanxiu.db"))
    停 = {x[0] for x in c.execute("SELECT code FROM sku WHERE status='停用'")}
    混 = [x["SKU"] for x in 行 if x["SKU"] in 停]
    ck("停用的 SKU 不进预警", not 混, len(停),
       f"混进来 {混[:3]}" if 混 else
       "停用的本来就不该有货可卖,库存 0 是正常状态 —— "
       "**误报比漏报贵**,一条误报会让采购去补一个已经下架的款")

    # ── ⑥ 规矩和工具在同一个角色身上 ──────────────────────────────────
    # TL28 栽过这个坑:规矩写进 KB_RULES 而工具挂在任务助手,
    # 模型拿到了工具拿不到规矩。
    tl29 = [x for x in prompts.TASK_RULES if x.id == "TL29"]
    ck("TL29 和 stock_alert 要在同一个角色身上",
       bool(tl29) and "stock_alert" in (tl29[0].needs if tl29 else ()),
       len(prompts.TASK_RULES),
       "**「工具给了,规矩没给」比「工具没给」更危险**:模型会用,而且没人告诉它用错了")

    文 = tl29[0].text if tl29 else ""
    for 词, 为什么 in (("可用", "在手和可用是两个数"),
                      ("算不出", "算不出要明说"),
                      ("采购", "补货是采购的决定")):
        ck(f"TL29 里说到「{词}」", 词 in 文, 1, 为什么)

    # ── ⑦ 工具描述里也得带着这几条 ────────────────────────────────────
    # 模型先读到的是 schema 描述,规矩在后面。描述里不提,它可能已经错了。
    d = [x for x in api.SHOP_SCHEMAS if x["name"] == "stock_alert"][0]["description"]
    for 词 in ("可用", "算不出", "不补货"):
        ck(f"工具描述里说到「{词}」", 词 in d, 1)

    print()
    if FAIL:
        print(f"\033[31m❌ 库存预警 {len(FAIL)} 处不符合预期\033[0m")
        for f in FAIL: print(f"   · {f}")
        sys.exit(1)
    print("\033[32m✅ 库存预警全部符合预期\033[0m")
    能算的 = [x for x in 行 if not isinstance(x.get("可售天数"), str)]
    print(f"    {len(行)} 行预警里,**{len(能算的)} 行算得出可售天数** —— "
          f"其余的老老实实说「算不出」,而不是给一个编出来的数。")


if __name__ == "__main__":
    main()
