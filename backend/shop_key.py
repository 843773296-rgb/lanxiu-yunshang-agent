"""**门店关联键的唯一来源** —— 哪一行归哪家门店,只认编码,不认名字。

来路:只读审计 2026-10-23 第 3 条,用户 2026-10-24 拍「根治:加 shop_code 列,
读写都改成按编码」。

## 这一条修的病

库里**本来就有**一张正规的门店表(`shop`:`code` 主键 SH001/SH002/SH003,
`name` 另存)。而 11 张表、**5.1 万行**存的却是**拼起来的显示串**
`"SH001 静安旗舰店"`,并且拿它当关联键:

    ordr.shop 26596 · appointment.shop 14639 · customer.shop 8083 ·
    aftersale 376 · maintain 376 · fitting 340 · roster 280 ·
    schedule 212 · staff 33 · activity 6 · store_report_doc 2

于是只要有人在后台把「静安旗舰店」改个名:
`report_template.门店表()`(第 341 行)是**从 shop 表现拼** `f"{code} {name}"` 的,
它拼出来的是**新串**,而那 5.1 万行、以及早先存下的试运行门店范围装的还是**老串**。
两边对不上 → 店长看到的是「我不在试运行范围里」「我店里没有这些单」——

> **不报错,只少几行。** 而「这家店今天确实没单」和「关联键对不上了」
> 在页面上长得一模一样。

## ⚠️ 摸出来的第二件事,它决定了整个设计

这一列**不只装门店**。`staff.shop` 里有 **12 个工坊名**(上海工坊 / 苏州绣坊 /
顺德晒莨场……,来自 `seed.py` 匠人表的第七列),`activity.shop` 里有「**全渠道**」。

> **「这一行归哪家门店」和「这个人在哪儿上班」,在同一列里长得一模一样。**

所以 `shop_code` 的语义收成**一个**:**这一行归哪家门店(`shop.code`),
不是门店的留空**。而「留空」必须和「不知道」分开 ——
要是工坊和「全渠道」都填空,那「**全渠道 = 所有门店**」和「**不知道是哪家**」
就塌成同一个值,又是两个该触发相反动作的状态长得一样。

**分开它们的办法是下面这张明写名单 + 一条棘轮**:`shop_code` 为空的行,
它的 `shop` 必须落在这张名单里 —— 于是「空」的意思变成
「**不归门店,而且我们知道它是哪一类不归**」,而冒出一个没登记的值会当场红。

⚠️ 名单**不从库里现读** —— 那就是同源谬误(拿被测的东西算期望值),
新冒出来的脏值会被当成合法。它只许**人**来改,改的时候才会想一想这是什么。
"""
import os
import sqlite3

HERE = os.path.dirname(os.path.abspath(__file__))
DB = os.path.join(HERE, "lanxiu.db")

# ⚠️ **明写名单,不许从库里现读。** 新加一个要人手写一行 ——
# 那一行就是「我知道它不是门店,它是什么」。
# 两类的下一步完全不同:工坊是**工作地**(匠人在哪儿干活),
# 「全渠道」是**投放范围**(不是一个地方)。混成一类就没法分别处理。
不是门店的 = {
    # ── 工坊:匠人的工作地。来源是 seed.py 匠人表的第七列 ──────────────
    "上海工坊": "工坊", "苏州绣坊": "工坊", "苏州工坊": "工坊",
    "顺德晒莨场": "工坊", "长沙绣坊": "工坊", "贵州蜡染坊": "工坊",
    "苏州缂丝坊": "工坊", "苏州织造坊": "工坊", "浙南染坊": "工坊",
    "成都绣坊": "工坊", "广州绣坊": "工坊", "南京云锦坊": "工坊",
    # ── 投放范围:不是一个地方 ───────────────────────────────────────
    "全渠道": "范围",
}

# 装着门店键的那几处(表, 列)。**明写**,不靠扫 ——
# 扫出来的清单会把新表悄悄纳进来而没人看过它,也会在列改名时安静地少一处。
带门店键的 = [
    ("ordr", "shop"), ("appointment", "shop"), ("customer", "shop"),
    ("aftersale", "shop"), ("maintain", "shop"), ("fitting", "shop"),
    ("roster", "shop"), ("schedule", "shop"), ("staff", "shop"),
    ("activity", "shop"), ("store_report_doc", "shop"),
]


def 门店表(c):
    """→ {显示串: code}。显示串就是业务数据里的写法「SH001 静安旗舰店」。"""
    return {f"{r[0]} {r[1]}": r[0] for r in c.execute("SELECT code, name FROM shop")}


def 认得出(值, 门店):
    """一个 shop 值到底是什么。返回 (类别, code) ——
    类别是 "门店" / "工坊" / "范围" / "空" / **"不认识"**。

    ⚠️ 「不认识」要单独一类,**不能归进「不是门店」** ——
    一个新开的工坊和一个打错的字,在「对不上 shop 表」这件事上长得一模一样,
    而前者该登记一行、后者该改数据。
    """
    if 值 is None or not str(值).strip():
        return ("空", None)
    值 = str(值)
    if 值 in 门店:
        return ("门店", 门店[值])
    if 值 in 不是门店的:
        return (不是门店的[值], None)
    return ("不认识", None)


def 该填的码(值, 门店):
    """这一行的 shop_code 该是什么 —— 门店给 code,其余一律 None(留空)。"""
    类, code = 认得出(值, 门店)
    return code if 类 == "门店" else None


def 有列(c, 表, 列="shop_code"):
    return 列 in [r[1] for r in c.execute(f"PRAGMA table_info({表})")]


def 码(c, 串):
    """给**写口**用:显示串 → 门店码(不是门店就 None)。

    ⚠️ 写口一律调这个,别在各处自己拆串 —— `shop` 串的写法哪天变了,
    拆法有几份就有几份会漂,而**漂了不报错,只是某几行的码填空**。
    (CLAUDE.md §7-2 同源谬误那一族:让那段逻辑只剩一份。)
    """
    return 该填的码(串, 门店表(c))
