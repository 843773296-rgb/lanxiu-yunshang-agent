#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""研判队列「没走正门关的」· 检查 —— 库副本上自造形状 + 真库只读棘轮。

用户 2026-10-14 拍:队列里那批「工单关了、没走过研判」的按「**没走正门关的**」收起,**计数亮着不藏成 0**。
(原话是「把 166 条清掉」;核过之后定的是按事实判 —— 有没有一条**真实的**正门关单记录 —— 而不是按形状或时间。)

要守的:
  · 凭据要**真实**:走正门清理演示数据的那种(reason 带演示清理标记)**不算**复核 ——
    「有人复核了这条」和「有人清理了这条」在「有审计记录」上长得一模一样;
  · 研判过的、真走正门关的,不进这一档;
  · **一条关掉的工单要说得出是谁关的**:造数直接写库关的那批在 `seed_direct_closed` 里登记着,
    剩下「说不出是谁关的」必须是 0。
    ⚠️ 这里原来是「总数 ≤ 基线 166」,2026-10-17 换掉了 —— **那个总数随世界日期漂**:
    同一个提交、只把世界日期分别钉在 10-16 / 10-17 各从零重建一次 → 160 和 166,
    而且不是「多了 6 条」,是差评那批**整批换了**(只在 10-17 有的 153 条、
    只在 10-16 有的 147 条,全是差评)。哪些包裹收到差评、造数按年龄概率关了哪些,
    都跟着世界今天走。
    > **一条「正门又被绕过了」和一条「换了一天重建」,在「这个数涨了」上长得一模一样。**
    换成「说不出是谁关的 = 0」之后,既更严(基线底下那 166 条换一条就红)
    又更稳(不随日期漂)。**禁区:别把基线抬成 167,换一天还会漂。**
"""
import os, shutil, sqlite3, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path[:0] = [HERE, os.path.join(ROOT, "knowledge")]
G, R, D = "\033[32m", "\033[31m", "\033[0m"
bad, n = [], 0
咬合 = [
    ("正门凭据不看 reason(演示清理也算复核)", "走正门清理演示数据的那种不算(reason 带演示清理标记)"),
    ("没走正门不查正门凭据", "真走正门关的不进这一档"),
    ("往库里塞一条没登记来源的「已关闭差评」(模拟有人绕过正门关单)", "说不出是谁关的"),
    # 2026-10-17:CI 上这一条红在「1 条」,而那一条是哪个号日志里一个字都没有。
    ("把 `ops.说不出谁关的号` 改成只返回空列表(判据报得出数、报不出号)", "号里真有那条自造的"),
]


def ck(名, ok, 附=""):
    global n
    n += 1
    if not ok:
        bad.append(名)
    print(f"  {'✅' if ok else '❌'} {名}" + (f"  {str(附)[:160]}" if 附 and not ok else ""))


print("研判队列「没走正门关的」· 检查")
print("=" * 80)

# ── 真库(只读):棘轮 + 计数亮着 ─────────────────────────────────────
import ops, oplog, rating as RT
_b = ops.backlog()
真, 在册, 说不出 = _b["没走正门关的"], _b["没走正门_登记在册"], _b["没走正门_说不出谁关的"]
# 总数**只打印不判红** —— 它按设计随世界日期漂(见文件头)。
# 这是这个项目反复用的那个拆法:「代码对不对」判红,「这个库上碰巧有几条」只报数。
print(f"     ℹ️ 真库里「没走正门关的」现在 {真} 条"
      + (f":造数登记在册 {在册} 条(按设计会漂,不判红)· **说不出是谁关的 {说不出} 条**"
         if 说不出 is not None else " —— 还没有来源登记表"))
if 说不出 is None:
    ck("造数直关的工单有来源登记(没登记表的话,「正门被绕过」和「换了一天重建」分不开)",
       False, "`seed_direct_closed` 表不在 —— 跑一次 `python3 tools/backfill_rating.py --只登记`")
else:
    # ⚠️ **报数不报号,下一个人没法查。** 2026-10-17 CI 上这一条红在「1 条」,
    # 而那一条是哪个号、什么形状,日志里一个字都没有 ——
    # 一条要求别人「说得出是谁关的」的判据,自己得先说得出是**哪一条**。
    号 = ops.说不出谁关的号()
    ck(f"没有一条关掉的工单说不出是谁关的(现在 {说不出} 条;登记在册的 {在册} 条不算)",
       说不出 == 0, ("、".join(号) + (" …" if 说不出 > len(号) else "")) if 号 else 说不出)
    # ⚠️ 号和计数对不对得上,**不在这里验** —— 真库上「说不出」恒为 0,
    #    `len([]) == min(0, 10)` 永远成立,**破坏进不了它的视野**。
    #    那一条挪到下面「库副本自造形状」那段:那里才会真有一条说不出来历的。

# ── 库副本:自造四种形状 ──────────────────────────────────────────────
tmp = tempfile.mkdtemp(prefix="qclosed-")
db = os.path.join(tmp, "lanxiu.db")
shutil.copy(os.path.join(HERE, "lanxiu.db"), db)
ops.DB = oplog.DB = db
c = sqlite3.connect(db)
造 = {}
for 名 in ("无凭据", "真正门", "清理正门", "研判过"):
    tid = f"T-检查-{名}"
    c.execute("INSERT INTO task(id,type,ref_id,status,created,summary) VALUES(?,?,?,?,?,?)",
              (tid, "评价差评", f"P-检查-{名}", "已关闭", "2026-01-01 10:00:00", "检查"))
    造[名] = tid
c.commit(); c.close()
from oplog import log_op
log_op("检查", "task", 造["真正门"], "待处理", "已关闭", True, "BAD_RATING_CLOSED", "只回访:电话回访过,顾客接受", {})
log_op("检查", "task", 造["清理正门"], "待处理", "已关闭", True, "BAD_RATING_CLOSED",
       f"只回访:{RT.演示清理标记}(检查造的),非真实复核", {})
ops.save_triage(造["研判过"], "BP-差评", "检查", "根因:检查", [])
行 = {x["task_id"]: x for x in ops.queue() if x["task_id"] in 造.values()}
ck("没研判、也查不到正门凭据 → 没走正门", 行[造["无凭据"]]["没走正门"] is True)
ck("真走正门关的不进这一档", 行[造["真正门"]]["没走正门"] is False)
ck("走正门清理演示数据的那种不算(reason 带演示清理标记)", 行[造["清理正门"]]["没走正门"] is True)
ck("研判过的不进这一档", 行[造["研判过"]]["没走正门"] is False)
ck("计数和逐行标记对得上", ops.backlog()["没走正门关的"] == sum(1 for x in ops.queue() if x.get("没走正门")))
# 「说不出是谁关的」那一条必须**说得出是哪一条** —— 在副本里验,因为真库上那个数恒为 0。
# 副本的库是从真库拷的,所以登记表在(166 条),而刚造的 `T-检查-无凭据` 不在登记里。
号副 = ops.说不出谁关的号() or []
ck("说不出谁关的:号里真有那条自造的(报数不报号,下一个人只能从零重建一个库去找它)",
   造["无凭据"] in 号副, 号副[:5])
_说 = ops.backlog()["没走正门_说不出谁关的"]
ck("说不出谁关的:号的条数和计数对得上(两条路径,漂开了别躺着)",
   len(号副) == min(_说, 10), f"号 {len(号副)} 个 / 计数 {_说}")
shutil.rmtree(tmp, ignore_errors=True)

print()
if bad:
    print(f"{R}❌ {len(bad)} 条不过(验了 {n} 条){D}")
    sys.exit(1)
print(f"{G}✅ 没走正门关的:凭据要真实、关掉的说得出是谁关的(验了 {n} 条){D}")
