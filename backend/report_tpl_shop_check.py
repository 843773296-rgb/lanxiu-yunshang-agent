#!/usr/bin/env python3
# -*- coding: utf-8 -*-
r"""报告模板的门店标识 —— 存的是编码,比较前一律归一,页面上仍显示店名。

来路:只读审计第 3 条的最后一块,用户 2026-10-24 拍「根治:加 shop_code 列,读写都改成按编码」。

## 这一处为什么要单独一道判据

试点门店和适用门店存在 **JSON 数组**里。`backend/shop_key_check.py` 那套棘轮扫的是
SQL 字符串里的 `shop=?`,**扫不到 JSON** —— 所以门店键那条线在这里有个洞。

而改一个门店名之后,**读路径看起来是好的**(存的和传进来的都是老串,照旧命中),
坏的是另外两处:

  · `改状态` 把老串判成「不是门店」—— 功能当场卡住,这个看得见
  · **「一家店同一时刻只试一版」那条互斥拿字符串比** —— 老串和新串被当成两家店,
    于是同一家店能同时试两版,**而且不报错**

> **两个指同一家店的标识,在字符串比较上长得不一样。**

## 这道判据分三层,而三层验的不是一件事

  ① **纯函数**:`_归一` / `_显示` 喂一张假门店表,五种形状逐个标真值 ——
     不连库,所以两个环境都真验得到
  ② **库副本上真跑一遍**:存草稿 → 试运行 → 生效 → **改门店名** → 再生效。
     ⚠️ 这一层是主角:**改名之后仍命中,才是这一笔买到的东西**;
     而①②都绿、改名那一步却失配,是完全可能的(①验的是归一函数,②验的是调用方用了它)
  ③ **结构**:那四个关键函数体里必须真的调着 `_归一` ——
     ②是行为断言,它在「这个库里碰巧只有一家店有模板」时可能验不到;
     ③盯的是「有人把归一拿掉了」,和数据无关

⚠️ 不在这儿验的:门店编码本身对不对(那是 `shop_key_check` 的事)。
"""
import ast
import json
import os
import sqlite3
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "backend"))
import report_template as RT          # noqa: E402
import shop_key as SK                 # noqa: E402

# ── 咬合记录(规格在 `tools/bite_specs.json`,`--only report_tpl_shop_check` 可重放)──
# **没红过的检查等于没有。** 三条分别打存、读、显示三层:
咬合 = [
    # 第一条打的是**根**:存入那一步不归一,就又回到存显示串。
    # ⚠️ 攻击点选在 `保存` 的入口而不是 `校验` / `改状态` 里 —— 后两处的归一在
    # 「全部走新写路径」时是**冗余的**(进门那一步已经归一过),攻掉它们什么都不会变,
    # 那就是个空操作,会显示成「改坏了却没红」。
    ("把存入那一步的归一去掉(改回原样存页面传来的显示串)",
     "库里存下来的是**编码**,不是显示串"),
    # 第二条打读路径:存的是编码、传进来的是显示串,不归一就永远比不上 ——
    # 而表现不是报错,是「这家店没有试运行的模板」,**和真的没有长得一模一样**。
    ("把 `生效()` 里试运行那一支的归一去掉(拿字符串直接比)",
     "**改名之后**按新串问,仍命中那一版"),
    # 第三条打展示:存法改了,而人看到的东西不许跟着变。
    ("把版本记录里「编码转回显示串」那一步去掉(页面上会出现 SH001)",
     "页面上看到的是店名,不是编码"),
]

G, Rd, Y, D = "\033[32m", "\033[31m", "\033[33m", "\033[0m"
坏, n = [], 0


def ck(名, ok, 说明=""):
    global n
    n += 1
    print(f"  {G + '✅' + D if ok else Rd + '❌' + D} {名}" + ("" if ok else f"  —— {说明}"))
    if not ok:
        坏.append(名)


print(f"\n  报告模板 · 门店标识按编码")
print("  " + "=" * 80)

# ── ① 纯函数:五种形状逐个标真值(不连库)────────────────────────────────
假店表 = {"SH001 静安旗舰店": "SH001", "SH002 徐汇店": "SH002"}
五种 = [
    ("显示串",            "SH001 静安旗舰店", "SH001"),
    ("已经是编码",        "SH001",            "SH001"),
    ("「全部」这个常量",   RT.全部门店,         RT.全部门店),
    ("工坊(不是门店)",   "上海工坊",          "上海工坊"),
    ("改过名的老串",       "SH001 静安老店",    "SH001 静安老店"),
]
错了 = [(名, 值, RT._归一(假店表, 值), 该) for 名, 值, 该 in 五种 if RT._归一(假店表, 值) != 该]
ck(f"归一:五种形状都归到该归的地方(验了 {len(五种)} 种)", not 错了,
   f"这几种不对:{错了} —— 认不出的**必须原样返回**,不能瞎猜一个码出来")
ck("归一:认不出的原样返回,不会凭空造一个码",
   RT._归一(假店表, "根本不存在的店") == "根本不存在的店",
   "认不出却返回了别的值 —— **「这不是门店」和「这是某家店」该触发相反的动作**")
ck("显示:编码转回显示串", RT._显示(假店表, "SH001") == "SH001 静安旗舰店",
   f"转出来是「{RT._显示(假店表, 'SH001')}」—— 存的是编码而页面要给人看店名,少了这一步页面上会出现 SH001")
ck("显示:认不出的原样返回", RT._显示(假店表, "全部") == "全部")
ck("归一和显示是一对(编码 → 串 → 编码,回到原点)",
   RT._归一(假店表, RT._显示(假店表, "SH002")) == "SH002")
# **空门店表**:别拿空口径去改数据 / 判人
ck("门店表是空的时候,归一什么都不改(空口径不许当口径用)",
   RT._归一({}, "SH001 静安旗舰店") == "SH001 静安旗舰店",
   "空表时把值改掉了 —— 那会在「shop 表还没建好」的库上把好数据洗坏")

# ── ③ 结构:那四个函数体里必须真的调着归一 ───────────────────────────
# ②是行为断言,它在「这个库里碰巧没有两家店都有模板」时可能验不到;
# 这一条和数据无关,盯的是「有人把归一拿掉了」。
源 = open(os.path.join(ROOT, "backend", "report_template.py"), encoding="utf-8").read()
树 = ast.parse(源)
函数体 = {}
for node in ast.walk(树):
    if isinstance(node, ast.FunctionDef):
        函数体[node.name] = {m.func.id for m in ast.walk(node)
                           if isinstance(m, ast.Call) and isinstance(m.func, ast.Name)}
该调归一 = ["生效", "校验", "改状态", "保存"]
缺 = [f for f in 该调归一 if "_归一" not in 函数体.get(f, set())]
ck(f"这几个函数体里真的调着 `_归一`(验了 {len(该调归一)} 个)", not 缺,
   f"{缺} 里没有调 `_归一` —— 门店标识没归一就比,**改个门店名那条互斥就会漏判**"
   f"(函数在不在都查:{[f for f in 该调归一 if f not in 函数体]} 找不到)")
找不到 = [f for f in 该调归一 if f not in 函数体]
ck("上面那几个函数名都还在(改名了就不是「没调」而是「没查」)", not 找不到,
   f"{找不到} 这几个函数找不到了 —— **「没调归一」和「这个函数不存在了」在上面那条上长得一样**")

# ── ② 库副本上真跑一遍(含改门店名)──────────────────────────────────
# **自造一个最小库**,不拿真库的副本 —— 真库被门禁 / 别的会话占着时副本建不出来,
# 那一层就会「跳过」,而跳过不是通过。自造的库两个环境都在,永远真验得到。
# (真库里这张表现在一行都没有,所以也没有「真实数据」可验 —— 要验的是**行为**。)
import tempfile
副本 = os.path.join(tempfile.mkdtemp(prefix="rpt-tpl-"), "lanxiu.db")
_z = sqlite3.connect(副本)
_z.execute("CREATE TABLE shop(code TEXT PRIMARY KEY, name TEXT)")
# 具名列 —— `tools/insert_shape_check.py` 的棘轮逮过:列数恰好相等而顺序错了**不报错**,值整体挪一格
_z.executemany("INSERT INTO shop(code, name) VALUES(?,?)",
               [("ZZ001", "自造一店"), ("ZZ002", "自造二店")])
_z.commit()
_z.close()

if 副本:
    # ⚠️ **把操作台账也指到这个副本上。** `保存` / `改状态` 会写一条 op_log,
    # 而 oplog 默认写**真库** —— 门禁里有一条专门抓这件事的检查(已经拦下过我两笔)。
    # 一条在跑的时候会改真库数据的判据,比没有这条判据更糟。
    import oplog as _ol
    _ol.DB = 副本
    运营 = {"no": "ZZ0030", "name": "(自造总部运营)", "role": "总部运营"}
    c = sqlite3.connect(副本)
    c.row_factory = sqlite3.Row
    店表 = SK.门店表(c)
    if len(店表) < 2:
        ck("库副本上至少有两家门店(少于两家就验不到互斥)", False,
           f"只有 {len(店表)} 家 —— 这不是「都通过」,是没东西可验")
    else:
        码1 = sorted(店表.values())[0]
        串1 = next(k for k, v in 店表.items() if v == 码1)
        内容 = RT.默认内容()
        内容["名称"] = "自造专用模板"
        内容["适用门店"] = [串1]              # 页面传的是**显示串**
        r = RT.保存("自造专用模板", 内容, "判据自造:验门店标识按编码", 运营, db=副本)
        ck("存一版(适用门店传的是显示串)", r.get("ok"), r)
        行 = c.execute("SELECT payload FROM report_template_ver WHERE name='自造专用模板' "
                       "ORDER BY version DESC LIMIT 1").fetchone()
        适用 = json.loads(行["payload"]).get("适用门店") if 行 else None
        ck("库里存下来的是**编码**,不是显示串", 适用 == [码1],
           f"存的是 {适用},该是 {[码1]} —— 存显示串的话,门店一改名那一版就对不上了")

        r2 = RT.改状态("自造专用模板", r.get("版本"), "试运行", "判据自造", 运营, 试点门店=[串1], db=副本)
        ck("改状态 → 试运行(试点传的是显示串)", r2.get("ok"), r2)
        t = c.execute("SELECT trial_shops FROM report_template_ver WHERE name='自造专用模板' "
                      "ORDER BY version DESC LIMIT 1").fetchone()
        ck("试点门店也存成编码", json.loads(t["trial_shops"] or "[]") == [码1], f"存的是 {t['trial_shops']}")

        g = RT.生效(串1, db=副本)
        ck("改名前:这家店生效的是试运行那一版",
           g["模板"] == "自造专用模板" and g["状态"] == "试运行", g)

        # ── 要害:把门店改个名 ──────────────────────────────────────
        c.execute("UPDATE shop SET name=name || '(改过名)' WHERE code=?", (码1,))
        c.commit()
        店表2 = SK.门店表(c)
        新串 = next(k for k, v in 店表2.items() if v == 码1)
        g3 = RT.生效(新串, db=副本)
        ck(f"**改名之后**按新串问,仍命中那一版(这就是这一笔买到的东西)",
           g3["模板"] == "自造专用模板" and g3["状态"] == "试运行",
           f"{g3} —— 存编码就是为了这一下;存显示串的话这里会掉回「默认」,**而且不报错**")
        # ⚠️ **改名之后,拿老串来问是命中不了的** —— 名字已经对不上 `shop` 表,
        # 从那个串算不出码。这不是漏网,是这条路的**边界**:
        #   · 传编码            → 命中(调用方该走这条;`staff.shop_code` 第一阶段回填过了)
        #   · 传**当前**显示串   → 命中(页面上选门店走这条)
        #   · 传**改过名的老串** → 命中不了,走默认模板
        # 所以 `api.store_report` 取模板时拿的是 `staff.shop_code`,不是 `staff.shop`。
        # 下面两条分别钉住「传码能命中」和「老串命中不了是已知的」。
        g4 = RT.生效(码1, db=副本)
        ck("改名之后传**门店码**仍命中(调用方该走这条)",
           g4["模板"] == "自造专用模板" and g4["状态"] == "试运行", g4)
        g5 = RT.生效(串1, db=副本)
        ck("改名之后传改过名的老串 → 走默认,这是**已知边界**不是意外",
           g5["模板"] == RT.默认模板名 and g5["状态"] == "代码默认",
           f"{g5} —— 这一条是**反向**断言:它绿表示那条路确实走不通。"
           f"要是哪天它红了(老串也命中了),说明有人给归一加了猜的逻辑,得去看那是不是真对")
        # 调用方真的在用码:**这一条和数据无关**,盯的是「有人把它改回 me['shop'] 了」
        _api源 = open(os.path.join(ROOT, "backend", "api.py"), encoding="utf-8").read()
        ck("`store_report` 取模板时拿的是 staff.shop_code,不是显示串",
           "SELECT shop_code FROM staff WHERE no=?" in _api源 and "_rt.冻结用(_本店" in _api源,
           "它又在拿 `me['shop']` 当门店标识了 —— 改名之后那是个算不出码的老串,"
           "**那家店的专用模板会静默掉回「默认」**")

        # 互斥:另一个专用模板想认领同一家店(这次用**新串**)
        内容2 = RT.默认内容()
        内容2["名称"] = "自造二号模板"
        内容2["适用门店"] = [新串]
        r3 = RT.保存("自造二号模板", 内容2, "判据自造:验互斥", 运营, db=副本)
        ck("一家店被两个专用模板认领 → 存不进去(一边老串一边新串也要拦住)",
           not r3.get("ok"),
           f"{r3} —— **这条互斥是拿字符串比的**,不归一的话老串和新串会被当成两家店,"
           f"于是同一家店同时试两版而不报错")

        # 展示:页面上看到的该是店名
        d = RT.详情("自造专用模板", db=副本)
        试行 = [v for v in d["版本记录"] if v["状态"] == "试运行"]
        ck("页面上看到的是店名,不是编码",
           bool(试行) and 试行[0]["试点门店"] == [新串],
           f"页面显示 {试行[0]['试点门店'] if 试行 else '(没有试运行那一版)'} —— "
           f"存编码之后要转回显示串,不然后台页面上门店变成了 {码1}")
        ov = RT.概览(db=副本)
        这个 = [m for m in ov["模板们"] if m["名称"] == "自造专用模板"]
        ck("概览里的适用门店也是店名",
           bool(这个) and 这个[0].get("适用门店") == [新串],
           f"概览显示 {这个[0].get('适用门店') if 这个 else '(没有这一行)'}")

        # 幂等迁移:把一行改回显示串,再走一次写路径,它该被迁成编码
        c.execute("UPDATE report_template_ver SET trial_shops=? WHERE name='自造专用模板'",
                  (json.dumps([新串], ensure_ascii=False),))
        c.commit()
        RT.确保表(c)        # 迁移挂在这儿 —— 跟建表 / 补列同一处,不新开流水线步骤
        回 = c.execute("SELECT trial_shops FROM report_template_ver WHERE name='自造专用模板'").fetchone()
        ck("幂等迁移:已经存成显示串的,走一次写路径就被迁成编码",
           json.loads(回["trial_shops"] or "[]") == [码1],
           f"迁完是 {回['trial_shops']},该是 {[码1]} —— 这一步是给「别的环境真有老数据」准备的")
    c.close()

print("  " + "=" * 80)
if 坏:
    print(f"  {Rd}❌ {len(坏)} 条没过:{坏}{D}")
    sys.exit(1)
print(f"  {G}✅ 报告模板门店标识:存编码、比较归一、页面仍显示店名(验了 {n} 条){D}")
sys.exit(0)
