#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""边界夹具还是不是原来那个夹具(2026-10-09 装的,因为它们已经被打穿了两处)。

`E-*` 那批客户是**手工摆在门槛上的反例**:第 90 天 / 第 91 天、实付 14999 / 15000、
人工调档窗口内 / 已超窗。它们存在的全部意义是「档位判定准不准」有个能对账的靶子。
`backend/seed.py` 的 EDGE 表是它们的真相源,`backend/member_check.py` 拿它们逐例对账。

> **夹具坏了的时候,评测照样是绿的** —— 那是它最贵的地方。
> 一个「第 91 天」的夹具和一个「被补成第 2 天」的,**在那张表上长得一模一样**:
> 字段齐、格式对、档位列也填着值,只有「它还测不测得到那条边」这一点泄露了它。

2026-10-09 实际抓到的两处(都不是档位算错,是夹具自己被改了):

  ① **5 张订单落在 E- 夹具上**(E-A3-06 / E-A3-02 / E-A3-08 / E-A2-03 / E-A2-01),
     全是「待确认」,`op_log` 显示**在同一秒**被开出来(三个不同顾问)—— 是脚本,不是人点的。
     而 `E-A3-02` 是「互动第 91 天」那个边界夹具:一张 10-07 的待确认单
     就把它的「最近互动」从 91 天前拉到 2 天前。
     ⚠️ 口径是「**下了单就算互动**,待确认 / 没付款 / 后来取消的都算」(用户 2026-10-09 拍),
     所以算法没错 —— **错在订单表没护住**。`customer` 行护住了,
     而**夹具是从另一张表被打穿的**。
  ② **两个夹具的名字被匿名化了**:`E-A3-04` 和 `E-A3-07` 在库里都叫「已注销用户」,
     而 seed.py 写的是「互动第 181 天」和「实付 14,999 元」——
     某个「注销」流程挑到了夹具。档位和闲置天数还对得上,**所以只看档位的检查抓不到它**。

## 这里判三件,各自抓的是不同的坏法

  **① 名下 0 单 0 触点。** seed.py 对这批的约定是「名下 0 单是故意的」
     (`tools/order_mix.受保护客户` 的注释也这么写)。闲置天数是直接写进列里的,
     任何一张单 / 一条跟进 / 一个预约 / 一条日程都会让重算结果偏离那条边。
  **② 名字对得上 seed.py。** 这一条专抓 ②那种坏法 —— 字段值全对、只有名字没了。
     名字就是这个夹具的判据(「互动第 91 天」说的就是它该测什么)。
  **③ 档位和闲置天数对得上 seed.py 的 EDGE 表。**
     ⚠️ 这一条只盖得住 `E-A2/A3/A4`(EDGE 表里位置已知的那 14 条);
     `E-M1-01` 在 seed.py 的另一段、列的位置不一样,**所以它只过 ①②**。
     这是**明写的盲区**,不是漏掉 —— 它的真相源是 `level` 列,由 member_check 对账。

⚠️ **为什么不写成「受保护客户名下不许有单」**(第一版就想这么写):
`tools/order_mix.受保护客户()` 扫出来的 45 个里有一类是**普通客户** ——
它们不是夹具,只是某条评测真值依赖它们身上的某个事实(`C10017` 的量体记录那种)。
**那些客户本来就该有订单**,禁掉会把一条对的数据判成错。
> 一条「护住夹具」的判据和一条「禁掉一切受保护客户的订单」的,在今天这批数据上
> 长得一模一样(今天落在受保护客户身上的单**正好全在 E- 上**)——
> 而后者会在下一次有人给 C10017 补一张合法的单时红,**而且红得理直气壮**。
"""
import os
import re
import sys
import sqlite3

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

G, R, D = "\033[32m", "\033[31m", "\033[0m"
# ⚠️ 可以指定库(`--db 某个副本`)—— 咬合测试要在**工作区副本**上重放,
# 别像这个仓库栽过的那次一样去动真库/真工作区。
DB = os.path.join(HERE, "lanxiu.db")
for _i, _a in enumerate(sys.argv):
    if _a == "--db" and _i + 1 < len(sys.argv):
        DB = sys.argv[_i + 1]
SEED = os.path.join(HERE, "seed.py")

# EDGE 表的元组形状:(id, 名字, 闲置, 单数, 实付, 12月单数, 季度, 首单, 人工档, 人工日, 档位, 说明)
# 只认 id / 名字 / 闲置 / 档位 这四个位置 —— 其余列这里不判(member_check 管)。
#
# ⚠️ 第一版写的是 `[^()]*?` 去跨中间那几列 —— 而第 8 列是 `ago(300)`,**它自己带括号**,
# 于是正则在那里停住,解析出 0 条。当场被下面 ⓪ 那条样本量判据逮住。
# > 一个「正则挂了」和一个「库里真的没有夹具」,**在「0 条」这个数上长得一模一样** ——
# > 要不是 ⓪ 先红,这个检查会一直显示绿的。
# 现在的写法:一条夹具的首行**以 `,"档位",` 收尾**,所以锚在行尾上拿最后那个带引号的词
# (`[^\n]` 不跨行,说明那一行在下一行,拿不到它)。
_EDGE = re.compile(r'\("(E-A[234]-\d\d)","([^"]*)",(\d+),[^\n]*?"([^"]*)",\s*$', re.M)
# 所有 E- 夹具的「名字」(不限 EDGE 那一段)——②用它
_任意夹具 = re.compile(r'\(\s*"(E-[A-Z0-9-]+)"\s*,\s*"([^"]*)"')

触点表 = (("followup", "ts"), ("appointment", "start_ts"), ("schedule", "start_ts"))


def 读种子():
    """从 seed.py 里读夹具的约定值。**不从库里读** —— 期望值和被测的东西同源就什么都抓不到。"""
    src = open(SEED, encoding="utf-8").read()
    名 = dict(_任意夹具.findall(src))
    边 = {m[0]: {"名字": m[1], "闲置": int(m[2]), "档位": m[3]}
          for m in _EDGE.findall(src)}
    return 名, 边


def main():
    if not os.path.exists(DB):
        print(f"  {R}❌{D} 没有库 {DB} —— 先跑 python3 backend/seed.py")
        return 1
    名, 边 = 读种子()
    c = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
    c.row_factory = sqlite3.Row
    库里 = {r["id"]: dict(r) for r in c.execute(
        "SELECT id, name, phone, birthday, lifecycle, idle_days"
        " FROM customer WHERE id LIKE 'E-%'")}

    print("边界夹具还是不是原来那个夹具")
    print("=" * 76)
    坏 = 0

    # ── ⓪ 样本量 —— **空集合上三条判据全成立** ────────────────────────
    # 「一个也没扫到」和「全都没问题」在输出上长得一模一样,所以这一条必须先红。
    if len(名) < 14 or len(边) < 14:
        print(f"  {R}❌{D} 从 seed.py 只解析出 {len(名)} 个夹具 / {len(边)} 条 EDGE"
              f" —— **解析挂了,不是「没有夹具」**(应 ≥ 14)")
        return 1
    if not 库里:
        print(f"  {R}❌{D} 库里一个 E- 夹具都没有 —— 这不叫过,叫没扫到")
        return 1
    缺 = sorted(set(名) - set(库里))
    if 缺:
        坏 += 1
        print(f"  {R}❌{D} seed.py 有而库里没有的夹具:{缺}")
    print(f"  {G}✅{D} 样本量:seed.py {len(名)} 个夹具(EDGE {len(边)} 条)· 库里 {len(库里)} 个")

    # ── ① 名下 0 单 0 触点 ────────────────────────────────────────────
    脏 = []
    for cid in sorted(库里):
        单 = [tuple(r) for r in c.execute(
            "SELECT id, substr(created,1,16), status FROM ordr WHERE customer_id=?"
            " ORDER BY created", (cid,))]
        for 表, 列 in 触点表:
            try:
                n = c.execute(f"SELECT count(*) FROM {表} WHERE customer_id=?", (cid,)).fetchone()[0]
            except sqlite3.OperationalError:
                continue                       # 这张表还不存在:不当成「干净」,但也没法判
            if n:
                脏.append((cid, f"{表} {n} 条"))
        for 单号, 时, 态 in 单:
            脏.append((cid, f"订单 {单号} {时} {态}"))
    if 脏:
        坏 += 1
        print(f"  {R}❌{D} 夹具名下有订单 / 触点({len(脏)} 处)—— "
              f"闲置天数是写死在列里的,任何一条都会让重算偏离那条边")
        for cid, 说 in 脏[:12]:
            print(f"      {cid}  {说}  (seed 说这批「名下 0 单是故意的」)")
        print(f"      怎么查是谁加的:op_log 里按 target 搜那个单号;"
              f"同一秒出现多条 = 脚本,不是人点的")
    else:
        print(f"  {G}✅{D} {len(库里)} 个夹具名下都是 0 单 0 触点")

    # ── ② 名字对得上 seed.py ──────────────────────────────────────────
    # ⚠️⚠️⚠️ **期望值必须是种子的「最终产物」,不是源码里的 EDGE 字面量。**
    #
    # 2026-10-09 我第一版就是拿 EDGE 里那个名字当期望值,于是这条判据红在
    # `E-A3-04` / `E-A3-07` 上(「seed 说互动第 181 天 / 库里是已注销用户」)。
    # 我据此报了「夹具被注销流程打穿了」,**用户还照着拍了「整行从种子复原」**。
    # 然后我在一个临时库里从零跑了一遍 `seed.py` —— **它造出来的就是「已注销用户」**。
    # 那两行**从来没被破坏过**:seed.py 自己做了一段「账户注销 → 门店档案去标识化」的
    # 演示(删量体 / 着装人 / 同意,再把姓名手机地址生日清掉),这两个夹具正好在里面。
    #
    # > **一条「夹具被人改名了」的红,和一条「我的期望值取错了地方」的红,
    # > 在这条判据上长得一模一样。** 而后者还会让人去修一个没坏的东西。
    #
    # seed.py 那段自己的注释写着一句正好打中这个错:
    #   「**真值必须是最终数据的函数** —— 数据后来变了,真值没跟着变,
    #     评测就会去要一个数据里根本不存在的答案,而报错会指向规则,不指向真值过期。」
    #
    # 所以这里认那个注销形状,但**要求整形状都对得上**(名字 + `DELETED-<id>` + 生日为空)——
    # 随便改一个名字匹配不上这三样,照样会红。**不是「见到已注销就放过」。**
    # ⚠️ 名单**钉死成这两个,而且双向判**。第一版写的是「谁长着注销的样子就放过」——
    # 那会留一个洞:哪天注销流程**真的**打中另一个夹具,它也会凑出同一个形状被放过。
    # > 一个「seed 自己造的注销夹具」和一个「被注销流程打中的夹具」,
    # > **在那三个字段上长得一模一样** —— 分开它们的只有「是哪个 id」。
    # 这两个 id 是 2026-10-09 在临时库里**从零跑一遍 seed.py** 核出来的,不是猜的。
    种子注销的 = {"E-A3-04", "E-A3-07"}

    def 是注销形状(cid, d):
        return (d["name"] == "已注销用户" and d["phone"] == f"DELETED-{cid}"
                and d["birthday"] is None)

    免, 怪 = [], []
    for cid in sorted(库里):
        形 = 是注销形状(cid, 库里[cid])
        if cid in 种子注销的 and 形:
            免.append(cid)
        elif cid in 种子注销的 and not 形:
            怪.append((cid, "seed 把它造成注销夹具,而库里**不是注销的样子了**"))
        elif 形:
            怪.append((cid, "**它被注销流程打中了** —— seed 没把它造成注销夹具"))
    改名 = [(cid, 名[cid], 库里[cid]["name"]) for cid in sorted(库里)
            if cid in 名 and 库里[cid]["name"] != 名[cid] and cid not in 免]
    for cid, 说 in 怪:
        改名.append((cid, 名.get(cid, "(不在 seed 里)"), f"{库里[cid]['name']} ← {说}"))
    if 改名:
        坏 += 1
        print(f"  {R}❌{D} {len(改名)} 个夹具的名字被改了 —— "
              f"**名字就是它的判据**(「互动第 91 天」说的就是它该测什么)")
        for cid, 应, 实 in 改名:
            print(f"      {cid}  seed「{应}」/ 库「{实}」")
    else:
        print(f"  {G}✅{D} 夹具名字都对得上 seed.py(验了 {len(库里) - len(免)} 个)")
    # ⚠️ **放过的要明写出来,不许静默跳过。**
    # 静默跳过的话这份名单会慢慢变成一个没人记得的洞 ——
    # 而「它被放过了」和「它从来没被扫到」在输出上长得一模一样。
    if 免:
        print(f"      ↳ 放过 {len(免)} 个:{免} —— seed.py 自己把它们做成了"
              f"「账户注销 → 门店档案去标识化」的演示夹具(姓名 + DELETED-<id> + 生日为空,"
              f"三样都对才放过)")

    # ── ③ 档位 / 闲置对得上 EDGE 表(只盖 E-A2/A3/A4) ───────────────────
    歪 = []
    for cid, 应 in sorted(边.items()):
        if cid not in 库里:
            continue
        实 = 库里[cid]
        if 实["lifecycle"] != 应["档位"]:
            歪.append((cid, "档位", 应["档位"], 实["lifecycle"]))
        if (实["idle_days"] or -1) != 应["闲置"]:
            歪.append((cid, "闲置天数", 应["闲置"], 实["idle_days"]))
    if 歪:
        坏 += 1
        print(f"  {R}❌{D} {len(歪)} 处和 seed.py 的 EDGE 表对不上")
        for cid, 列, 应, 实 in 歪[:10]:
            print(f"      {cid}.{列}  seed {应!r} / 库 {实!r}")
    else:
        print(f"  {G}✅{D} 档位 / 闲置都对得上 EDGE 表(验了 {len(边)} 条)")
    print(f"      ⚠️ 明写的盲区:E-M1-01 不在 EDGE 表里(列的位置不同),它只过 ①②")

    print("=" * 76)
    if 坏:
        print(f"{R}❌ 夹具被动过 {坏} 类{D} —— 修它之前跑出来的档位评测**不作数**")
        return 1
    print(f"{G}✅ 边界夹具完好{D}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
