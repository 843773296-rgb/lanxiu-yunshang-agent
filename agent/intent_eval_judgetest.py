#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""意图评测判分器 · 人造对照 —— 离线、一秒钟,抓逻辑错。

CLAUDE.md 第 9 节第 ⑤ 条是**纪律不是建议**:判分器写完先跑人造对照,
真跑之后再把每一句真实说法钉回来。这个文件是第一段。
(第二段要等真跑过一轮,把真实的误判钉回这里。**真跑之前这个文件就只覆盖得到
我想得出来的情形** —— 这句话留着,是为了别把「对照全过」读成「判分器对了」。)

## 这里守的是什么

意图评测有三件要触发**相反动作**的事,它们很容易被合成一个「没判对」:

    判错     → 改意图说明 / 加例句(模型选了另一个意图)
    判不出   → 调分类阈值、看缺不缺一个意图(模型没法决定)
    调用失败 → 查网络 / 额度,**不进任何分母**(那是环境,不是能力)

还有两条门槛相关的:**两个门槛都要过**、**两轮都要过**。
「平均过了」和「两轮都过」是两件事 —— 前者会被一轮的好运气抬上去。
"""
import io
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import intent_eval as E                                     # noqa: E402

G, R, D = "\033[32m", "\033[31m", "\033[0m"
坏, n = [], 0

# 咬合 —— 改坏的是什么、该红的是哪一条(可执行的在 tools/bite_specs.json)
咬合 = [
    ("让「调用失败」回 False 而不是 None(环境问题被算进分母当成答错)",
     "调用失败回 None(不是 False)"),
    ("把两个门槛改成「任一满足即达标」(判不出率超标也能上线)",
     "判对够了但判不出超了 → 不达标"),
    ("一道都没真跑到时也照样算一个率",
     "一道都没真跑到时不许算率"),
    ("把「判不出」算成判对(模型没法决定被当成答对了)",
     "判不出不算判对"),
    # ⚠️ 下面两件**没有单独的规格,刻意的**:它们的破坏点和上面那几条撞在同一处,
    #    单独配会变成两条一模一样的攻击(而全库查重只查 (script, 破坏点) 这一对,
    #    查不出「换个说法的同一个攻击」)。
    #    · 「调用失败也算进分母」= 上面「调用失败回 False」那条的同一处;
    #    · 「两轮都达标改成平均」= 上面那条门槛的同一处(都在 `达标()`),
    #      它由对照用例 `all(达标(x) for x in [...])` 钉着,那条用例在门禁里跑。
]


def ck(名, 得, 应):
    global n
    n += 1
    ok = (得 == 应)
    print(f"  {G+'✅'+D if ok else R+'❌'+D} {名}" + ("" if ok else f"  得到={得!r} 应={应!r}"))
    if not ok:
        坏.append(名)


print("意图评测判分器 · 人造对照(不调模型、不碰库)")

# ── 一、判一道:四种结果必须分得开 ─────────────────────────────────
ck("判对", E.判一道("报价", {"意图": "报价", "态": "判出"}), (True, "判对"))
ck("判错(选了另一个意图)", E.判一道("报价", {"意图": "问一个数", "态": "判出"}),
   (False, "判错"))
ck("判不出不算判对", E.判一道("报价", {"意图": None, "态": "判不出"}), (False, "判不出"))
# ⚠️ 调用失败回的是 `None` 而**不是 False** —— `False` 会让它进分母算成答错,
#    而那是环境问题。两者在「没判对」上长得一模一样。
ck("调用失败回 None(不是 False)—— 它不进分母",
   E.判一道("报价", {"意图": None, "态": "调用失败"}), (None, "调用失败"))
ck("结果为 None 也不崩", E.判一道("报价", None)[1], "判错")

# ── 二、报一轮:每个数都连分母,三类分开 ────────────────────────────
def 行(id, 期望, 实际, 类别, 混=None):
    return dict(id=id, 问="x", 期望=期望, 实际=实际, 类别=类别, 容易混成=混)

_行 = [行("A", "报价", "报价", "判对"), 行("B", "报价", "问一个数", "判错"),
       行("C", "报价", None, "判不出"), 行("D", "报价", None, "调用失败")]
_出 = []
_r = E.报一轮(_行, 日志=_出.append)
ck("调用失败不进任何分母(真跑到 3 道,不是 4 道)", _r["真跑到"], 3)
ck("判对率按真跑到算(1/3)", round(_r["判对率"], 4), round(1/3, 4))
ck("判不出率单独一个数(1/3)", round(_r["判不出率"], 4), round(1/3, 4))
ck("输出里明说调用失败不进分母",
   any("不进任何分母" in l for l in _出), True)
# ⚠️ 空集合那条:一道都没跑到时**不许印一个率**。
#    「判对率 0%」和「一道都没测到」要触发的动作完全不同。
_出2 = []
ck("一道都没真跑到时不许算率(返回 None)",
   E.报一轮([行("D", "报价", None, "调用失败")], 日志=_出2.append), None)
ck("而且要明说「这不叫 0%,这叫没测到」",
   any("没测到" in l for l in _出2), True)

# ── 三、门槛:两个都要过;两轮都要过 ───────────────────────────────
ck("两个门槛都过 → 达标",
   E.达标({"判对率": 0.95, "判不出率": 0.02}), True)
ck("判对够了但判不出超了 → 不达标(**两个门槛都要过,缺一个不算达标**)",
   E.达标({"判对率": 0.95, "判不出率": 0.20}), False)
ck("判不出很低但判对不够 → 不达标",
   E.达标({"判对率": 0.70, "判不出率": 0.00}), False)
ck("刚好贴线算达标(≥ 和 ≤,不是 > 和 <)",
   E.达标({"判对率": E.判对线, "判不出率": E.判不出线}), True)
ck("没测到(None)不算达标", E.达标(None), False)
# 两轮都要过 —— 这一条在 main 里是 `all(...)`,这里把那个语义钉死
ck("一轮达标一轮不达标 → 不算达标(不是看平均)",
   all(E.达标(x) for x in [{"判对率": 1.0, "判不出率": 0.0},
                           {"判对率": 0.5, "判不出率": 0.3}]), False)

# ── 四、题集本身:独立题的几条硬性质 ───────────────────────────────
_spec = E.读(E.题集)
_cs = _spec["cases"]
_cfg = E.读(E.配置文件)
_名 = {x["名称"] for x in _cfg["意图"]}
ck("题集和配置的标签空间完全一致(少一个意图就有题永远判不对)",
   sorted({c["意图"] for c in _cs}), sorted(_名))
ck("题面没有重复(重复题会让某个意图的权重悄悄变大)",
   len({c["问"] for c in _cs}), len(_cs))
ck("每个意图至少 3 道新说法(用户 11-08 拍的是 3–5 句)",
   min(sum(1 for c in _cs if c["意图"] == x) for x in _名) >= 3, True)
# ⚠️ **没有任何一道题的期望是「判不出」** —— 它是失败,不是答案。
ck("没有一道题把「判不出」当期望",
   [c["id"] for c in _cs if c["意图"] == "判不出"], [])
# ⚠️ 独立题的那条不可逆规矩,必须写在题集里(而不是只在谁的脑子里)
ck("题集里写着「跑过就不许再拿它调东西」",
   "不许再拿它调任何东西" in io.open(E.题集, encoding="utf-8").read(), True)
ck("题集里写着不进夜跑 / 不进快照 / 不进 check.sh",
   "不进夜跑" in io.open(E.题集, encoding="utf-8").read(), True)
# 和老 50 题**一句都不许撞** —— 独立题贵就贵在「没见过」
_老 = os.path.join(os.path.dirname(HERE), "agentsite", "evals", "skill_trigger.json")
if os.path.isfile(_老):
    _o = json.load(io.open(_老, encoding="utf-8"))
    _老面 = {str(c.get("prompt") or "").strip() for c in _o.get("cases", _o)}
    ck("独立题的题面和老 50 题一句都不撞(撞了就不叫「没见过」)",
       sorted(_老面 & {c["问"].strip() for c in _cs}), [])
else:
    ck("找得到老 50 题(找不到就验不了「不撞」)", False, True)
# 配置指纹:同一份配置算两次要一样,改一个字就要变
ck("配置指纹稳定(同一份算两次一样)",
   E.配置指纹(_cfg) == E.配置指纹(_cfg), True)
_改 = json.loads(json.dumps(_cfg, ensure_ascii=False))
_改["意图"][0]["说明"] += "。"
ck("配置改一个字,指纹就变(否则「用哪份配置跑的」查不出来)",
   E.配置指纹(_改) != E.配置指纹(_cfg), True)

print()
print(f"  (验了 {n} 条)")
if n == 0:
    print(f"{R}❌ 一条都没验{D}"); sys.exit(1)
if 坏:
    print(f"{R}❌ 意图判分器对照 {len(坏)} 条不过{D}")
    for x in 坏: print(f"   · {x}")
    sys.exit(1)
print(f"{G}✅ 意图判分器:判错 / 判不出 / 调用失败三类分得开;"
      f"调用失败不进分母;两个门槛都要过、两轮都要过;"
      f"题集和配置标签空间一致、和老 50 题不撞{D}")
print(f"  {R}⚠ 这些全是人造对照 —— 真跑一轮之后,把真实的误判钉回这里{D}")
