import datetime, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))


def 供应商():
    return (os.environ.get("LANXIU_PROVIDER", "") or "claude").lower()


def 代码():
    """跑这一轮时的提交号。

    ⚠️ **同一天 ≠ 同一份代码。** `tools/eval_compare.py` 原来只比日期,
    于是两轮之间改过判据也照样说「可以当结论」——
    它防住了「差两天」,却放过了「差三次提交」。
    而这个漏洞**只在结论那一行显形**:表照样出,只是那句话变成了假话。

    脏工作区标 `+dirty` —— **改了没提交,那这一轮的代码谁也复现不了。**
    """
    import subprocess
    try:
        h = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=HERE,
                           capture_output=True, text=True, timeout=5).stdout.strip()
        d = subprocess.run(["git", "status", "--porcelain"], cwd=HERE,
                           capture_output=True, text=True, timeout=5).stdout.strip()
        return (h or "?") + ("+dirty" if d else "")
    except Exception:
        return "?"


def 模型():
    p = 供应商()
    if p == "deepseek":
        return os.environ.get("DEEPSEEK_MODEL", "deepseek-v4-pro")
    return os.environ.get("ANTHROPIC_MODEL", "claude(CLI 登录态)")


def 盖章(记录=None):
    """一条结果的来路:谁跑的、哪个模型、什么时候、**哪一版代码**。

    抽出来是因为**有人抄过一份**:`agent/tool_eval.py` 写的是 json 不是 jsonl,
    于是它自己拼了 `供应商/模型/跑于` —— 注释还写着「所以自己盖,不走 dump」。
    2026-09-21 给 `dump()` 加代码指纹时,那一套**拿不到**,
    两份实现当场分家,而分家时两边都看着很正常。

    给了 `记录` 就返回盖好章的副本,不给就返回章本身。
    """
    章 = {"供应商": 供应商(), "模型": 模型(),
          # 真实时钟:记的就是「这一轮什么时候跑的」
          "跑于": datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
          "代码": 代码()}
    return dict(记录, **章) if 记录 is not None else 章


def dump(path, recs):
    """把一轮结果写进 jsonl,**每条都盖上是谁跑的**。

    盖在每一条上而不是文件头:文件头会被下一次覆盖写掉,
    而**部分覆盖**(跑了一半停掉)的时候,文件头说的和内容里的就对不上了 ——
    这一天正好就是跑到一半被停的。
    """
    章 = 盖章()
    with open(path, "w", encoding="utf-8") as fh:
        for r in recs:
            # ⚠️ **代码版本也要盖上。** 2026-09-21 发现:`代码()` 上面算出来了
            # (`c`),而它**一个字都没写进记录** —— 一个「写好了但没接上」的防护,
            # 和没有这个防护,在文件上长得一模一样。
            # 当天就撞上了它本该防住的那件事:一轮用**旧判据**跑出来的结果
            # 覆盖了基线,而文件上只有供应商/模型/日期,分不出判据换过。
            # 同一天 ≠ 同一份代码(见 `代码()` 的注释)。
            r = dict(r, **章)
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")
    return path


