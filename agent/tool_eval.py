def judge(cid, text, traj, guard_violations=None):
    """三轴打分。纯函数,离线可测。"""
    c = next(x for x in CASES if x[0] == cid)
    _, q, need, must, forbid = c
    bad = []
    names = " ".join(t.split("__")[-1] for t in traj)
    if need and not any(n in names for n in need):
        bad.append(f"轨迹:该调 {need} 里的工具,实际调了 [{names or '无'}]")
    if not need and traj:
        pass                       # 不要求工具的题,调了也不扣分(可能是为了确认)
    for g in must:
        # **判据可以是一个函数,不只是一组同义词。**
        # 2026-09-15 加。逐条看完 11 条失败之后发现:**10 条是尺子的问题**,
        # 而其中一半是「同义词表差那么一点点」——
        # 答案写「只有 **M、L、XL**」而词表里是「只有 M」(被 markdown 加粗打断)、
        # 写「只有**罗一机一个人**」而词表里是「只有一位」、写「**物料费**」而词表里是「物料成本」。
        # **同一个意思的中文写法接近无限,枚举必输** —— 这是项目写在 CLAUDE.md 里的话,
        # 而这套判分器一直在枚举。
        if callable(g):
            e = g(text, traj)
            if e: bad.append(f"内容:{e}")
            continue
        # ⚠️ **真值为空时不许生成期望。**
        # T03 的期望来自 `(fit.get("体型特征") or [""])[0]` —— 这位客户
        # 没有体型特征,真值是 `''`,而用例照样造了一条「回答里必须出现 ''」。
        # 空期望有两种坏法,都得防:
        #   **永远失败** —— T03 就是这样,一条内容分白扣
        #   **静默变成永远通过** —— 那更糟,一条判据消失了而成绩单还是满分
        # 所以这里**不是悄悄跳过**,是当场报出来:期望该修,不该假装它不存在。
        # (「分母为零不给比率,给一句话」——期望值也一样。)
        if not [x for x in g if (x or "").strip()]:
            bad.append(f"用例本身有问题:这条期望是**空的**"
                       f"(真值取出来是空串)—— 空期望要么永远失败、"
                       f"要么静默变成永远通过,**两种都不该留着**")
            continue
        if not hit(text, g):
            bad.append(f"内容:没提到 {g[0]}(同义:{'/'.join(g[1:]) or '无'})")
    for w in forbid:
        # **禁止项可以带主语:`("有现货", "云锦")` 表示「说云锦有现货」才算违规。**
        #
        # 不带主语的下场刚发生过两次:T20 禁「可以」,命中的是
        # 「我们**可以**推别的工艺」;T11 禁「有现货」,命中的是
        # 「可以看看**有现货**且相容的**其他面料**」——
        # 两句都在说**替代方案**,而答案第一行明明白白是「不可以」「没有现货」。
        # **禁的该是一个主张,不是一个字。**
        主语 = ()
        if isinstance(w, (tuple, list)): w, 主语 = w[0], tuple(w[1:])
        命中 = hit(text, (w,), negation=True)
        if not 命中: continue
        if 主语:
            import re as _re2
            贴着 = False
            for m in _re2.finditer(_re2.escape(w), text):
                if tm.negated(text, m.start()): continue
                窗 = text[max(0, m.start() - 36):m.start() + 36]
                if any(x in 窗 for x in 主语): 贴着 = True; break
            if not 贴着: continue
        bad.append(f"内容:出现了禁止说法「{w}」"
                   + (f"(而且是贴着{list(主语)}说的)" if 主语 else ""))
    for v in (guard_violations or []):
        bad.append(f"体检:{v['check']} {v['msg'][:40]}")
    return (not bad), bad


