# -*- coding: utf-8 -*-
"""标点不变量 —— **同一句话换个逗号,判定必须不变。**

## 这个文件为什么存在(2026-11-11)

`textmatch.STOP`(小句边界字符表)里**没有全角逗号** —— 中文里最常用的那个标点。
于是否定的作用域跨过逗号,把前一小句的否定算到后一小句上:

    「我没有发短信的权限，这一步需要人来确认」里的「人」被前半句的「没」否定了。
     ↑ 这句原话里的逗号是**全角**的。改注释时留意别把它变成半角,
       那样这个例子就复现不出来了,而注释看起来一点问题都没有。

线上守卫因此**漏拦了 6 类**软性让价和围度口径,而守卫那 175 条用例**一直全绿** ——

> **因为它们的逗号全是半角的。** 全文全角逗号 0 个。
> 守卫在一种真实数据里根本不会出现的标点形态上验过,然后所有人以为它守住了。

量过:31 份 judgetest 的字符串字面量里,半角逗号 **2052** 个、全角 **18** 个(0.9%),
其中 **11 份一个全角逗号都没有**。**判分规则在真实数据标点上的行为,从来没被对照集验过。**

## 为什么是一份公共的,而不是各家写一份

各家各写一份「把逗号换掉再跑一遍」的话,那就是 **N 份手抄件** ——
而这个项目反复栽在手抄件上(判据要真调被测代码,别在夹具里重实现一份)。
全角化的过滤条件一旦各家不一致,「这一套验过了」和「这一套的过滤把用例全挡掉了」
**在那个 ✅ 上长得一模一样**。所以 `全角化()` 全项目只有这一份。

## ⚠️⚠️ 为什么 `判定` 不许返回布尔

**这是 11-11 当天用血换的一条。** 那天先做了一次一次性测量,比的是
「**用例有没有通过**」,结论是「救回 5 条」。后来换成比**完整的判定结果**,
立刻多出第 6 条:

    说了围度却没说它只是区间、要复量
      半角 → ['g11_girth_point', 'g24_growth_not_statistical']
      全角 → ['g24_growth_not_statistical']

那条用例在两种标点下**都通过** —— 它的期望只要求某一个判据命中,而那个还在。

> **一条用例通过了**,和**它要验的每一闸都还在**,是两件事。

所以 `查()` **拒收**返回 `bool` 的 `判定`:让各家传「通过没通过」,
等于把那次测量的盲点复制到每一套上。
"""

import re

_中文字 = re.compile(r"[一-鿿]")

# ⚠️ 咬合:每条改坏一处,**红的必须是指定那一条**(不是「反正红了」)。
咬合 = [
    ("把 `查()` 里样本量 0 时的 `+ (1 if 空 else 0)` 去掉(0 条也算过)",
     "一条都没换到时必须算不过(样本量 0 不是通过)"),
    ("把 `查()` 里 `isinstance(v, bool)` 那一段删掉(让各家能传「通过没通过」)",
     "`判定` 返回 bool 时必须抛 判定不许是布尔 —— 比「通过没通过」会漏掉丢闸"),
    ("把 `查()` 报不一致那一行改成只印一句「不一样」,不印两边各自的判定",
     "报不一致时要印**两边各自的完整判定**,不只说「不一样」"),
    ("把 `查()` 结尾那个 `if len(变了) > 最多印` 的补印删掉(截断不说总数)",
     "超过 最多印 时必须说出**一共几条**(截断不说总数就是在骗人)"),
    ("把 `查()` 里 `缩水` 的判断关掉 —— 接线少换一个字段时样本量会从 N 掉到 M,"
     "**而两种都是绿的**",
     "样本量掉到下限以下要算不过"),
]

# 像代码的记号 —— 命中就不动这个串(工具名列表、正则、格式化模板、字典字面量)
_像代码 = re.compile(r"[{}\[\]<>=|\\]|__|\bmcp\b|^\s*$")


def 全角化(s):
    """把**看着像中文句子**的文本里的半角逗号换成全角。别的原样返回。

    条件:有中文、够长(≥8)、含半角逗号、不含像代码的记号。

    ⚠️ **别全文换。** 11-11 第一次做这个测量时把所有字符串里的逗号都换了,
    连工具名列表和正则里的也换 —— 整个脚本崩了,输出是「红 0 条」,
    **而那和「换了标点也没差别」长得一模一样**,差一点就读成「零影响」。
    """
    if not isinstance(s, str):
        return s
    if "," not in s or len(s) < 8 or not _中文字.search(s):
        return s
    if _像代码.search(s):
        return s
    return s.replace(",", "，")


def 换过吗(文本们):
    """这组文本里有没有哪一个真的被换过 —— 用来决定这条用例算不算进样本量。"""
    return any(全角化(x) != x for x in 文本们)


class 判定不许是布尔(TypeError):
    """见本文件开头那一段:比「通过没通过」会漏掉「某一道闸悄悄丢了」。"""


def 查(用例们, 取文本, 判定, 日志=print, 名="标点不变量", 最多印=8, 最少=0):
    """对每条用例把文本的半角逗号换成全角,**判定必须不变**。→ 不过的条数(0 = 过)。

    · `取文本(用例)` → `str` 或 `tuple[str, ...]`:这条用例里要换标点的那些文本。
    · `判定(用例, 新文本们)` → **可比较且信息完整**的东西(建议 `sorted([...命中的判据名])`)。
      传 `bool` 会抛 `判定不许是布尔` —— 理由见本文件开头。
      `新文本们` 的顺序和 `取文本` 返回的一致;原样那一遍传的就是原文本。
    · `名` 只用来印那一行。

    · `最少` 是**样本量下限**(实测值,写死在调用点)。验到的条数掉到它以下就算不过。
      ⚠️⚠️ **这不是锦上添花,它守的是「接线退化」。**
      有些用例的回答文本嵌在**好几个字段**里(负向那一套在 `finding` 的
      `suggested_action` / `evidence` / `note` 里)。重构时少换一个字段,
      样本量会从 7 掉到 3 —— 而**两种都是绿的**:
      > **「验了 7 条」和「验了 3 条」在那个 ✅ 上长得一模一样。**
      「样本量 0」和「样本量缩水」是同一个病的两个程度,所以一起守。

    ## ⚠️ 判定的理由里回显了原文时,**判定结果也要归一化**

    很多判据的理由会把命中的原文片段抄进去:
        「开头就顺着这个前提往下答了(「对,」)」
    那个 `「对,」` 是**原文片段** —— 换了标点它当然跟着变,而那**不是判定变了**。

    > 要比的是**判定的语义**(命中了哪些判据、每条的判断),不是理由字符串的字节。

    接入点这么写:
        判定=lambda c, t: sorted(全角化(x) for x in map(str, 真判据(...) or []))
    ⚠️ 归一化**不会掩盖真实差异**:命中集不同的话,归一化后照旧不同。
    (2026-11-11 接经营报告那一套时撞上的。)

    印出来的东西遵守两条项目铁律:
      ① **样本量 0 印 ❌ 不印 ✅** —— 「验过了,都一样」和「一条都没验到」长得一样;
      ② **截断说总数** —— 只印前几条会让人以为就这么几条(11-11 刚修过同一个病)。
    """
    def _组(用例):
        x = 取文本(用例)
        return (x,) if isinstance(x, str) else tuple(x)

    变了, 验了 = [], 0
    for 用例 in 用例们:
        原 = _组(用例)
        新 = tuple(全角化(x) for x in 原)
        if 新 == 原:
            continue                      # 没有可换的半角逗号 —— 不算进样本量
        验了 += 1
        a, b = 判定(用例, 原), 判定(用例, 新)
        for v in (a, b):
            if isinstance(v, bool):
                raise 判定不许是布尔(
                    f"{名}:`判定` 返回了 bool。要返回**完整的判定结果**"
                    f"(比如命中了哪些判据的有序列表)—— 比「通过没通过」会漏掉"
                    f"「某一道闸悄悄丢了」,见 agent/punct_invariant.py 开头那一段。")
        if a != b:
            变了.append((用例, a, b))

    空 = (验了 == 0)
    缩水 = (not 空 and 验了 < 最少)
    日志(f"  {'✅' if (not 变了 and not 空 and not 缩水) else '❌'} "
         f"{名}:半角逗号换成全角,判定不变(验了 {验了} 条"
         f"{f',下限 {最少}' if 最少 else ''})")
    if 空:
        日志("     ⚠️ **一条都没换到 —— 这不叫通过,这叫没测到东西**"
             "(先查 `取文本` 取对了没、用例文本里是不是本来就没有半角逗号)")
    if 缩水:
        日志(f"     ⚠️ **样本量从 {最少} 掉到了 {验了} —— 接线退化了**"
             f"(多半是 `取文本` 少取了一个字段)。**「验了 {最少} 条」和「验了 {验了} 条」"
             f"在那个 ✅ 上长得一模一样**,所以这里要红")
    for 用例, a, b in 变了[:最多印]:
        日志(f"       · 半角→{a}  全角→{b}")
    if len(变了) > 最多印:
        日志(f"       …… 上面只印了 {最多印} 条,**一共 {len(变了)} 条**")
    return len(变了) + (1 if 空 else 0) + (1 if 缩水 else 0)


def 自测():
    """咬合:三种情形各自都要说对话。→ 坏掉的条数。"""
    坏 = []

    # ① 全角化只动中文句子,不动像代码的串
    for 原, 期 in (("我没有权限,这一步需要人来确认。", "我没有权限，这一步需要人来确认。"),
                   ("get_stock,stock_alert", "get_stock,stock_alert"),      # 没中文
                   ("查库存,报数", "查库存,报数"),                          # 太短(<8 字)
                   # ⚠️ 这一条第一版写的是「查库存,然后报数」—— 那是**正好 8 字**,
                   #    不低于门槛,所以它该被换。自测当场红了,**红的是我的期望值**,
                   #    不是实现。边界用例要自己数一遍长度。
                   ('{"a":1,"b":2}', '{"a":1,"b":2}'),                      # 像代码
                   ("mcp__lanxiu__get_stock,别动它啊啊", "mcp__lanxiu__get_stock,别动它啊啊")):
        if 全角化(原) != 期:
            坏.append(f"全角化({原!r}) 得到 {全角化(原)!r},该是 {期!r}")

    # ② 判定返回 bool → 必须抛,**不许静默放过**
    try:
        查([1], lambda c: "这句有中文,也有逗号在里面", lambda c, t: True, 日志=lambda *a: None)
        坏.append("`判定` 返回 bool 时必须抛 判定不许是布尔 —— 比「通过没通过」会漏掉丢闸")
    except 判定不许是布尔:
        pass

    # ③ 样本量 0 → 印 ❌ 且算**不过**(这不叫通过,这叫没测到东西)
    出 = []
    n = 查([1, 2], lambda c: "nocomma", lambda c, t: ["x"], 日志=出.append)
    if n == 0:
        坏.append("一条都没换到时必须算不过(样本量 0 不是通过)")
    if not any("没测到东西" in x for x in 出):
        坏.append("样本量 0 时要明说「这不叫通过,这叫没测到东西」")

    # ④ 判定真的变了 → 要报出来,而且印的是两边各自的完整结果
    出 = []
    n = 查([1], lambda c: "这一句有中文,还带着逗号",
          lambda c, t: ["闸A", "闸B"] if "," in t[0] else ["闸B"], 日志=出.append)
    if n != 1:
        坏.append("判定变了要算不过")
    if not any("闸A" in x and "闸B" in x for x in 出):
        坏.append("报不一致时要印**两边各自的完整判定**,不只说「不一样」")

    # ⑤ 截断要说总数(11-11 栽过:只印前几条,读的人以为就这么几条)
    出 = []
    查(list(range(20)), lambda c: f"第{c}句话有中文,也有逗号",
      lambda c, t: ["闸"] if "，" in t[0] else [], 日志=出.append, 最多印=3)
    if not any("一共 20 条" in x for x in 出):
        坏.append("超过 最多印 时必须说出**一共几条**(截断不说总数就是在骗人)")

    # ⑥ 样本量**缩水**也要算不过(接线退化:少换一个字段,从 N 掉到 M,两种都是绿的)
    出 = []
    n = 查([1, 2], lambda c: f"第{c}句话有中文,也有逗号",
          lambda c, t: ["闸"], 日志=出.append, 最少=5)
    if n == 0:
        坏.append("样本量掉到下限以下要算不过(接线退化和「验过了」长得一样)")
    if not any("接线退化" in x for x in 出):
        坏.append("样本量缩水时要明说**接线退化了**,并把下限和实得都印出来")
    # 反向:够了就不许报缩水(**一条爱误报的检查会被拆掉**)
    出 = []
    查([1, 2], lambda c: f"第{c}句话有中文,也有逗号",
      lambda c, t: ["闸"], 日志=出.append, 最少=2)
    if any("接线退化" in x for x in 出):
        坏.append("样本量刚好够下限时不许报缩水 —— 误报比漏报贵")

    return 坏


if __name__ == "__main__":
    import sys
    print("标点不变量 · 咬合")
    坏 = 自测()
    for x in 坏:
        print(f"  ✗ {x}")
    print(f"{'❌ ' + str(len(坏)) + ' 条不过' if 坏 else '✅ 每一条都咬得动'}")
    sys.exit(1 if 坏 else 0)
