#!/usr/bin/env python3
"""销售话术判官的**校准集** —— 拿真跑过的答案量判官自己的准头。

## 为什么单独一个脚本

判官是模型,所以它**要花钱、要联网、结果会波动** —— 按这个项目的规矩,
这种东西不进 `check.sh`(门禁里放一条随机拦路的检查,比没有更糟)。
判分器那 32 条离线对照在 `talk_eval_judgetest.py` 里,验的是**接线**;
这一份验的是**准头**。

## 标签是我标的,这一点必须说清

下面的 `软性让价` 是**我逐条读原话标的**,不是业务给的真值。
理由:这一层没有第二套实现可以对账 —— 业务给的是「什么算让价」的规矩,
而「这一段具体的话算不算」只能有人读。所以:

  · 这些标签**只用来校准判官**,不参与评测的通过与否
  · 评测的真值仍然是**业务原话**(见 talk_eval.py 每题的「出处」)

## 怎么来的

2026-09-25「规矩没送到」那一轮的 12 条存档答案(`talk-eval-规矩没送到-20260925.jsonl`)。
判官改了两轮,这个脚本就是那把尺子:

    第一版(要求原样抄回原话)   这一轴**全空转** —— 12 题一条没抓到。
                              判官答的是 `**有**` / `第一行:有`,而解析写的是
                              `行[0].startswith("有")`,一条都对不上;
                              而且它「抄回」的句子是自己改写过的,于是每个「有」都被判成抄不回来
    第二版(报编号 + 改准说明书) **9/12**,但有**两处误报** ——
                              把「我理解价格差异,咱们先确认是不是同款」和
                              「改衣工费按实际算」判成了留希望
    第三版(加规则复核)         **9/12,误报归零**,漏报 3 条(T1 / T11 / T12)。
                              复核这一步:判官指的那一句里必须真有一个**没被否定的**让价信号,
                              信号表直接用那道闸的(guards.折扣词 / 许诺 / 以后)

⚠️ **判官是模型,同一条答案两次跑可能指不同的句子** —— 上面的 9/12 是一次的数,
不是一个稳定指标。这个脚本的用处是**看误报有没有回来**,不是刷准确率。

    ./agentsite/.venv/bin/python agent/talk_judge_cal.py
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path[:0] = [HERE, os.path.join(ROOT, "backend"), os.path.join(ROOT, "agentsite")]
os.environ.setdefault("LANXIU_PROVIDER", "claude")
import talk_eval as E

存档 = os.path.join(HERE, "talk-eval-规矩没送到-20260925.jsonl")

# 我读原话标的:这一段**建议对顾客说的话**里,有没有在价格上留希望
标签 = {
    "T1":  (True,  "「我们确实有调整空间,就看您重视哪个部分」"),
    "T2":  (False, "只追问在比什么、让顾问先弄清配置,没对顾客许任何价格上的话"),
    "T3":  (True,  "「我先帮你问一下店长,回头看能不能给你配」—— 赠品也是让步"),
    "T4":  (True,  "「由他看一下老客户有没有优惠空间」"),
    "T5":  (True,  "「如果双十一期间有整店活动,到时候我再帮您确认」"),
    "T6":  (False, "「先问店长有没有这条规定」是**对顾问的交代**,顾客听不到"),
    "T7":  (False, "只讲判责口径,没碰价格"),
    "T8":  (False, "报的是**要收的**改衣工费 —— 收钱不是让钱"),
    "T9":  (False, "讲料和工日,报的是成本"),
    "T10": (False, "讲加人无效、工期改不了"),
    "T11": (True,  "「我们的定价空间确实有限」—— 有限不等于没有,仍在暗示有空间"),
    "T12": (True,  "「返现的政策我这边不太清楚,得帮你问一下」—— 返现是折扣的另一个名字"),
}

if __name__ == "__main__":
    rows = [json.loads(l) for l in open(存档, encoding="utf-8") if l.strip()]
    print(f"判官校准 · {len(rows)} 条真跑过的答案(标签是人读原话标的,不是业务真值)")
    print("=" * 100)
    对, 误报, 漏报 = 0, [], []
    for r in rows:
        want, why = 标签[r["case"]]
        got, 句 = E.判官(r["text"])
        if got == want: 对 += 1
        elif got and not want: 误报.append(r["case"])
        else: 漏报.append(r["case"])
        print(f"  {'✅' if got == want else '❌'} {r['case']:4s} "
              f"该判「{'有' if want else '没有'}」判官说「{'有' if got else '没有'}」"
              f"  {(句 or '')[:40]}")
        if got != want: print(f"        人的判断:{why}")
    print("=" * 100)
    print(f"判官准头 {对}/{len(rows)} · 误报 {误报 or '无'} · 漏报 {漏报 or '无'}")
    # **误报比漏报贵**:误报会把一个本来正确的答复判成挂,照着它去改提示词就是改坏。
    print("⚠️ 误报比漏报贵 —— 漏报只是少抓到,误报会让人去改本来正确的提示词")
    sys.exit(0 if not 误报 else 1)
