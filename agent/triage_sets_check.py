台账上限 = 2        # 只许降 —— 连跑两轮算一次验收;要跑第三轮是用户的决定,不是我的


def ck(名, ok, 说明=""):
    global n
    n += 1
    print(f"  {G + '✅' + D if ok else Rd + '❌' + D} {名}" + ("" if ok else f"  —— {说明}"))
    if not ok:
        bad.append(名)


