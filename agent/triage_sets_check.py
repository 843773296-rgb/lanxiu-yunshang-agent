冻 = T.读冻结()
ck("冻结文件在(没有的话先跑 `python3 agent/triage_sets.py --冻`)", bool(冻),
   f"找不到 {T.冻结文件}")
if not 冻:
    print(f"\n{Rd}❌ 1 条不过(验了 {n} 条){D}")
    sys.exit(1)

套 = 冻["套"]
号 = {k: [t["包裹"] for t in v] for k, v in 套.items()}

# ── ① 不重叠 ───────────────────────────────────────────────────────────
print("\n① 三套之间不重叠")
ck("三套的套名就是登记的那三个(少一套会让下面的判据静默少验)",
   set(套) == set(T.套名), f"{sorted(套)} / {sorted(T.套名)}")
交 = []
for i, a in enumerate(T.套名):
    for b in T.套名[i + 1:]:
        重 = set(号.get(a, ())) & set(号.get(b, ()))
        if 重:
            交.append(f"{a}∩{b}={sorted(重)[:3]}")
