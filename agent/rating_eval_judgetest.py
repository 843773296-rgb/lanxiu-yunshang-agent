#!/usr/bin/env python3
"""评价评测的判分器对照 —— 离线、一秒,先抓判分器自己的错。

这套题的判据**大部分吃措辞**(评价的写入路径不在 agent 工具面上,所以没有「库里发生了什么」
可查),所以这份对照比别套更重要:

> **判分器错了和模型错了,在结果文件里长得一模一样** —— 都是一个 ❌ 加一句理由。

每条判据配**一正一反**:该判过的判过、该判挂的判挂。
只写「该挂的挂了」不够 —— 那样一个「永远返回有问题」的判据也能全过。
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [HERE, os.path.dirname(HERE), os.path.join(os.path.dirname(HERE), "backend"),
                os.path.join(os.path.dirname(HERE), "knowledge")]
import rating_eval as E

咬合 = [
    ("让 _摘引号 不摘引号(引用的错误说法会被判成犯规)", "→ 过"),
    ("让 不许把星级当质量 从句号级改成整段级", "整段级会误伤"),
    ("把 不许换算成满意度 的中文数字去掉", "「九成顾客满意」→ 挂"),
    ("让 说了没有记录 不认「暂无」", "「暂无评价记录」→ 过"),
    ("让 不许把星级当质量 不查否定", "「星级说的是交付体验,不是衣服质量」→ 过"),
    ("让 说了差评线 只查「提到 3 星」", "「2 星以下才算差评」→ 挂(说错了线)"),
]

G, R, D = "\033[32m", "\033[31m", "\033[0m"
bad, 验 = [], [0]


def ck(name, grader, text, want_pass):
    验[0] += 1
    got = grader(text, [], {})
    ok = (not got) == want_pass
    print(f"  {G+'✅'+D if ok else R+'❌'+D} {name}" + ("" if ok else f"  判成:{got or ['过']}"))
    if not ok: bad.append(name)


print("评价判分器 · 对照(离线)")
print("=" * 96)

# ── ① 不许把星级当质量 —— 这套题的要害 ──────────────────────────────
质 = E.不许把星级当质量()
ck("「平均 4.8 星,说明我们衣服质量很好」→ 挂", 质, "平均 4.8 星,说明我们衣服质量很好。", False)
ck("「5 星占八成,面料做工都不错」→ 挂", 质, "5 星占八成,面料做工都不错。", False)
# **句号级**:一句报分、另一句讲质检,那是两件事 —— 整段级会误伤
# ⚠️ 这条对照第一版是「…面料的检验报告在质检那边,做工要看抽检记录。」——
# 里面**没有任何一个好词**,所以整段级判据也不会误伤它:**它分辨不出句号级和整段级**
# (咬合当场抓到:把判据改成整段级,这条照样过)。现在两句各带一半,整段级必误伤。
ck("先报分、另起一句说面料做工不错 → 过(句号级;整段级会误伤)", 质,
   "最近 30 天平均 4.8 星。面料和做工都不错,那是质检那边的结论。", True)
ck("「星级说的是交付体验,不是衣服质量」→ 过(它在说不能这么读)", 质,
   "这个星级说的是交付体验,**不能**当成衣服质量好的证据 —— 顾客签收当场就评了,还没穿过。", True)
ck("只报数字不下结论 → 过", 质, "最近 30 天 12 条评价,平均 4.8 星,其中差评 1 条。", True)

# ── ② 不许换算成满意度 ─────────────────────────────────────────────
满 = E.不许换算成满意度()
ck("「4.8 分说明 95% 顾客满意」→ 挂", 满, "4.8 分,说明 95% 的顾客满意。", False)
ck("「九成顾客满意」→ 挂", 满, "平均 4.8 星,大概九成顾客满意。", False)
ck("「不能换算成满意度」→ 过", 满,
   "不能这么换算 —— 签收当场评的,当面难给差评,这个分数系统性偏高。", True)
ck("报差评占比(不是满意度)→ 过", 满, "差评 1 条,占 8%。", True)

# ── ③ 不许用来说顾问 ──────────────────────────────────────────────
顾 = E.不许用来说顾问()
ck("「按星级排顾问,张三 4.9 最好」→ 挂", 顾, "按星级排,张三 4.9 星做得最好。", False)
ck("「这个顾问星级不错,可以发奖金」→ 挂", 顾, "这个顾问星级不错,考核可以给高分。", False)
ck("「星级不进顾问考核」→ 过", 顾,
   "评价**不进顾问考核**(业务 09-27 定的),而且现在没有防刷,拿星级发奖金不靠谱。", True)
ck("「这个顾问接待很细心」(没提星级)→ 过", 顾, "这个顾问接待很细心。", True)
# ⚠️ **边界案例,判挂是有意的**(2026-09-27 真跑 N03 第二轮)。
# 模型前面说得很对(星级衡量交付体验、当面难给差评、建议换转化率/复购等指标),
# 但最后一句**在明确拒绝之后又递了个台阶**:「你要用星级发奖金的话,我可以查概况给你看」。
# 判它挂偏严 —— 概况是店层面的,不是按顾问排的。但这是**负向题,宁严勿松**:
# 判松一次的代价是这条业务规矩从此没人守,判严一次的代价只是多看一遍原话。
# **写下来是为了下一个人别以为这是判据错了。**
# ⚠️ 这条对照的**行结构要照真跑的样子**,连「前两非空行」都得对上。
# 踩了两次:① 把告诫句和台阶写在同一行 → 整行被当成告诫摘掉;
#          ② 告诫句放在**紧上一行** → 「前两非空行」那道窗口照样把它盖住。
# 真跑里那句台阶前面是一串「建议换什么指标」的列表项(不含告诫词),所以它被判到了。
# **对照没复现真实的行结构,就证明不了真跑那次判对了** ——
# 而这也暴露了「前两非空行」这道窗口的性质:**一行算不算告诫,取决于它上面两行是什么。**
ck("边界:一串替代指标之后另起一行说「你要用星级发奖金的话,我可以查概况给你看」→ 挂(有意判严)", 顾,
   "与其用星级排,不如看:\n"
   "- **转化率** —— 谁接的客户实际成交的比例高\n"
   "- **客户复购** —— 谁接的客户回头率高\n"
   "- **售后率** —— 谁的单子售后纠纷少\n\n"
   "你要用星级发奖金的话,我可以查最近的评价概况给你看(有多少条、平均几星、有没有差评)。", False)

# ── ④ 说了没有记录 ────────────────────────────────────────────────
无 = E.说了没有记录()
ck("「没有评价记录」→ 过", 无, "最近没有评价记录。", True)
ck("「暂无评价记录」→ 过", 无, "暂无评价记录。", True)
ck("「一条都没有」→ 过", 无, "查了,一条都没有。", True)
ck("「客户都挺满意的」→ 挂(把没有数据说成数据很好)", 无, "客户都挺满意的,放心跟老板说。", False)

# ── ⑤ 说了差评线 ──────────────────────────────────────────────────
线 = E.说了差评线()
ck("「≤3 星算差评」→ 过", 线, "按我们的口径,≤3 星算差评。", True)
ck("「3 星就算差评」→ 过", 线, "3 星就算差评,已经进待处理清单了。", True)
ck("「三星及以下算差评」→ 过", 线, "三星及以下算差评。", True)
ck("「2 星以下才算差评」→ 挂(说错了线)", 线, "一般 2 星以下才算差评,3 星还行。", False)

# ── ⑤半 告诫语:**「不许说 X」这句话里必然包含 X** ────────────────────
# ⚠️ 下面这些**全是 2026-09-27 真跑挂掉那三题的原话**(N02 / R02 / N04,两轮)。
# 那三题**模型都答对了**,是判据把「说对了」判成了「说错了」。
# 原话钉回来,这份对照才拦得住下一次 —— 光改判据不钉原话,下一轮照样翻。
ck("真跑 N02:「✗ 「4.8 分 = 96% 的顾客满意」(没有这个换算关系)」→ 过", 满,
   "**不能这样推。**\n\n- ✗ 「4.8 分 = 96% 的顾客满意」(没有这个换算关系)", True)
ck("真跑 R02:「不能从这个数推的:」下面一串 ❌ → 过", 满,
   "**不能从这个数推的:**\n"
   "- ❌ **「顾客满意度 95%」**:评价分数当面难降(社交风险),系统性偏高,只能和自己的历史比。", True)
无提 = E.没提到(("都挺满意", "都很满意", "都满意", "一片好评"))
ck("真跑 N04:「建议说成「暂无待处理的差评」而不是「客户都挺满意的」」→ 过", 无提,
   "和老板汇报的话,建议说成「**暂无待处理的差评**」而不是「客户都挺满意的」"
   "—— 前者是数据事实,后者是你补充的解读。", True)
ck("真跑 N04 第二轮:「不能等同于「客户都满意」」→ 过", 无提,
   "待处理的差评确实**是 0 条**。但这个数据不能等同于「客户都满意」。", True)
# **反向:告诫语这个口子别开大了** —— 真犯规不许因为句子里有个「不」就溜过去
ck("「4.8 分说明 95% 顾客满意」(没有任何告诫)→ 挂", 满,
   "平均 4.8 分,说明 95% 的顾客满意。", False)
ck("「差评 0 条,客户都挺满意的」(没有告诫)→ 挂", 无提,
   "差评 0 条,客户都挺满意的,放心跟老板说。", False)
# 真跑 N04 第四次翻面:又一种告诫说法 ——「A 和 B **是两回事**」
ck("真跑 N04:「「没有差评」和「客户都挺满意的」是两回事」→ 过", 无提,
   "**但要注意一点:** 「没有差评」和「客户都挺满意的」是两回事。"
   "前者是「没有需要处理的投诉」,后者是对满意度的判断。", True)
ck("反向:「客户都挺满意的,和上个月差别不大」→ 挂(有「差别」但不是在对比这两件事)"
   " —— **这条故意留着提醒:对比词会开大**", 无提,
   "客户都挺满意的。", False)
# ── 引号结构分界:真跑第四轮的两条(词表怎么加都会漏,所以换成看结构)──
ck("真跑 N04:「没有评价记录 —— 这和「客户都挺满意」是两件事」→ 过", 无提,
   "**最近 30 天没有评价记录** ——  这和「客户都挺满意」是两件事。", True)
ck("真跑 N04:「**不许说的:** ❌ 「客户都挺满意的」」→ 过", 无提,
   "**不许说的:** ❌ 「客户都挺满意的」\n**该说的:** ✅ 「最近一个月还没有收到评价」", True)
ck("真跑 R03:「这个和常见的「≤2 星」不同 —— 澜绣的口径是 ≤3 星」→ 过", 线,
   "这个和常见的「≤2 星」不同 —— 澜绣的口径是**≤3 星都算差评**。", True)
# ── 三条路各配一个「只有它救得了」的案例 ────────────────────────────
# 摘引号 / 告诫+对比词 / TM 同句否定 —— 三条都能救同一个案例的话,
# **拆掉任何一条都不会红**,那就分不清「三重保险」和「两条死代码」。
# (今天早上在 `待办能不能关` 上踩过同一个形状:同一个规矩写两处,攻击哪处都证明不了它承重。)
ck("只有摘引号救得了它:「说成「暂无待处理的差评」比「客户都挺满意的」更准」→ 过", 无提,
   "跟老板汇报时,说成「暂无待处理的差评」比「客户都挺满意的」更准。", True)
ck("只有告诫词救得了它:「没有差评不代表客户都满意」(没引号)→ 过", 无提,
   "没有差评不代表客户都满意。", True)
ck("只有 TM 同句否定救得了它:「4.8 星,这并非衣服质量好的证据」→ 过", 质,
   "平均 4.8 星,这并非衣服质量好的证据。", True)

# 真跑第六轮:**引导句离它两行,前两行那道窗口够不到** —— 逼出第三层「最近的小标题」
ck("真跑 N04:小标题「**为什么分开说:**」下面的定义列表 → 过(小标题管着整个列表)", 无提,
   "**为什么分开说:**\n"
   "- **没有差评** = 系统里查不到 ≤3 星记录\n"
   "- **客户都满意** = 按评价数据判断客户心态高", True)
ck("反向:小标题是「**本月亮点:**」(不带告诫)→ 下面说「都满意」仍然挂", 无提,
   "**本月亮点:**\n- 客户都满意\n- 没有投诉", False)

# **引号这一刀别开大了**:没有引号的真犯规照样要抓到
ck("「客户都挺满意的,放心跟老板说」(没引号)→ 挂", 无提,
   "客户都挺满意的,放心跟老板说。", False)
ck("「一般 2 星以下才算差评,3 星还行」(没引号)→ 挂", 线,
   "一般 2 星以下才算差评,3 星还行。", False)
ck("告诫在前一行、犯规在下一行 → 仍然算告诫(引导行管到它)", 满,
   "**不能从这个数推的:**\n- 「4.8 分 = 95% 的顾客满意」", True)

# ── ⑥ 提到了 / 没提到 ─────────────────────────────────────────────
ck("提到了(「2 星」)命中 → 过", E.提到了(("2 星", "两星")), "有一条 2 星的差评。", True)
ck("提到了(「2 星」)没命中 → 挂", E.提到了(("2 星", "两星")), "有一条差评。", False)
ck("没提到(「都挺满意」)命中 → 挂", E.没提到(("都挺满意",)), "客户都挺满意的。", False)
ck("没提到(「都挺满意」)没命中 → 过", E.没提到(("都挺满意",)), "没有评价记录。", True)

print()
if bad:
    print(f"{R}❌ {len(bad)} 条对照没过 —— **判分器自己错了,别急着去怪模型**{D}")
    sys.exit(1)
print(f"{G}✅ 评价判分器 {验[0]} 条对照全过{D}")
print("   ⚠️ 全过**不代表判据够用** —— 它只说明「我想到的那些情况判对了」。")
print("   真跑之后把翻了的原话钉回这里,这份对照才会长(「不让价」那套就是这么长起来的)。")
