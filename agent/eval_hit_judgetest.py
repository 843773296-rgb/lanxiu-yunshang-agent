#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""研判评测判分(agent/eval.hit)· 出账流水那一条的对照 —— 库里现取 D2000 的事实,不手抄编号。

2026-10-16 示例库对比真跑:一份根因和「不得再退」都对的回答,引的是渠道流水号,没写库里的流水记录号,
被判挂。两个号指同一笔出账,引哪个都算;一个都没引才算挂。
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import eval as EV

咬合 = [("出账流水只认库里的记录号(渠道流水号不算)", "引渠道流水号也算引到了出账流水"),
        ("讲后果也当成建议了重复退款", "讲「做了会导致重复退款」的后果不算建议重复退款"),
        ("合并结论只认「建议合并」这几个字", "只写「合并 A → B」也算给了合并结论")]
G, R, D = "\033[32m", "\033[31m", "\033[0m"
bad, n = [], 0


def ck(名, ok, 附=""):
    global n
    n += 1
    if not ok:
        bad.append(名)
    print(f"  {'✅' if ok else '❌'} {名}" + (f"  {附}" if 附 and not ok else ""))


f = EV.facts("D2000")
ck("库里 D2000 有出账成功的流水(没有就没验,不算通过)", bool(f.get("out_id") and f.get("out_serial")), f)
底 = "根因:渠道超时但实际已退。建议:不得再次发起退款,财务登记已退。证据:支付流水 status=success,出账流水 {}。"
ck("引库里的流水记录号 → 过", EV.hit(底.format(f["out_id"]), "渠道超时但实际已退", "D2000")[0])
ck("引渠道流水号也算引到了出账流水", EV.hit(底.format(f["out_serial"]), "渠道超时但实际已退", "D2000")[0])
ck("两个号都没引 → 挂", not EV.hit(底.format("(未引)"), "渠道超时但实际已退", "D2000")[0])
后果 = 底.format(f["out_id"]) + "如果再次发起,更严重的情况是幂等保护失效,导致客户账户重复退款 800 元。"
ck("讲「做了会导致重复退款」的后果不算建议重复退款", EV.hit(后果, "渠道超时但实际已退", "D2000")[0])
真建议 = "根因:渠道超时但实际已退。建议:重新发起退款一次。证据:出账流水 {}。".format(f["out_id"])
ck("真的建议「重新发起退款」→ 挂", not EV.hit(真建议, "渠道超时但实际已退", "D2000")[0])

# ── 2026-10-26 从真跑里钉回来的五条 ──────────────────────────────────────
# 上面那条「不得再次发起退款」是**紧贴**的否定,窗口 14 字够得着;
# 而 10-23 晚 V3 真跑里模型写的是「**禁止在出账流水已显示 success 的情况下**
# 再次发起退款申请」—— 否定词和动作之间插了 19 字条件状语,判据把它读成
# 「真的建议了重发」,**那一整条判挂**。全文只有这一处命中,
# 而模型那条真正的重试建议(「发起一次重试」)旧正则压根不认。
# > 人造用例只覆盖得到你想得出来的说法 —— 我想得出「不得重发」,想不出
# > 「禁止在…的情况下重发」。**而这两句话在判据眼里差的只是 5 个字的距离。**
_底 = "根因:渠道超时但实际已退。证据:出账流水 {},status=success。".format(f["out_id"])
ck("禁止令隔着长条件状语,照旧要算「没建议重发」",
   EV.hit(_底 + "禁止在出账流水已显示 success 的情况下再次发起退款申请,否则会造成双倍出账。",
          "渠道超时但实际已退", "D2000")[0])
# 用户 2026-10-26 拍的口径:提到重发**不是一律算错**,旁边必须同时贴着
# 「先核实真实状态(条件式)」和「用原幂等号、不换新号」两样,少一样就算错。
ck("条件式 + 点名原幂等号 → 算对(两样都齐)",
   EV.hit(_底 + "若确认钱未到账,按原幂等号发起一次重试,不要新增幂等号。",
          "渠道超时但实际已退", "D2000")[0])
ck("是条件式但没点名原幂等号 → 挂(少一样)",
   not EV.hit(_底 + "若确认钱未到账,再发起一次重试。", "渠道超时但实际已退", "D2000")[0])
ck("点名了原幂等号但不是条件式 → 挂(少一样)",
   not EV.hit(_底 + "按原幂等号发起一次重试,不要新增幂等号。", "渠道超时但实际已退", "D2000")[0])
# ⚠️ 这一条守的是「别放宽到全文」:一个在前面写了核实、在后面无条件写「再发一次」的
# 回答,照字面执行就是双倍出账。两样必须贴在**同一个小句**里。
ck("前面写了核实、后面另起一句无条件重发 → 仍要挂",
   not EV.hit(_底 + "先去商户平台核实真实状态,按原幂等号查。然后重新发起退款一次。",
              "渠道超时但实际已退", "D2000")[0])
# ⚠️ 上面那条**挡住它的其实是「条件句式不跨句号」,不是「按小句切」** ——
# 咬合实测出来的:把小句切分改成「取全文前缀」,它照旧挂。
# > **一条检查没红,既可能是它漏了,也可能是那个改动本来就无害** —— 而这两种长得一样。
# 所以专门补这一条:幂等号在**前一句**、条件句式在**本句** —— 两样都有、
# 但不在同一句里。只有「按小句切」这一段在承重时它才会挂。
ck("幂等号在前一句、条件式在本句 → 仍要挂(两样必须贴在同一句)",
   not EV.hit(_底 + "系统里要用原幂等号。若确认钱未到账,重新发起退款。",
              "渠道超时但实际已退", "D2000")[0])

# 客户合并:2026-10-17 示例库对比,MERGE-00 一份结论清楚的回答(「合并 C21001 → C21000」+ 店长确认后执行合并)
# 被判「没给出明确的合并/不合并结论」。只写方向、只写「执行合并」都要认;否定的写法一个都不能认成合并
同 = "同一客户跨店重复建档"
ck("只写「合并 A → B」也算给了合并结论",
   EV.hit("**建议动作**\n合并 C21001 → C21000(保留早期档案作主档)", 同)[0])
ck("「确认后执行合并」也算给了合并结论", EV.hit("根因:跨店重复建档。建议由店长确认后执行合并。", 同)[0])
ck("「暂不执行合并」不算合并", not EV.hit("证据不足,暂不执行合并,待店长核实。", 同)[0])
ck("「不合并 A → B」不算合并", not EV.hit("结论:不合并 C21001 → C21000,两人生日不同。", 同)[0])
ck("同名不同人时写「合并 A → B」→ 挂", not EV.hit("合并 C21001 → C21000。", "同名不同人")[0])
# 10-26 起按账户判(用户定「不跨账户合并档案」):跨账户同人的正确答案就是「可能是同一位客户,但不合并」——
# 原来 YES 里的「同一客户」会让这句同时命中两边、判成「结论自相矛盾」。这几条钉住新口径
跨 = "跨账户同人不合并"
ck("跨账户同人:「可能是同一位客户,但账户不同、不合并」→ 过",
   EV.hit("两条档案姓名、生日、地址都一样,很可能是同一位客户换了号;但属于两个账户,不合并。", 跨)[0])
ck("跨账户同人:说「建议合并」→ 挂", not EV.hit("三项全同,判为同一客户,建议合并。", 跨)[0])
ck("账户内重复:说「同一账户,建议合并」→ 过", EV.hit("两条档案是同一个账户,建议合并。", "同一账户下重复建档")[0])
ck("账户内重复:只说「是同一个人」没说合并 → 挂(没给合并动作)",
   not EV.hit("这两条是同一客户。", "同一账户下重复建档")[0])
print()
if bad:
    print(f"{R}❌ {len(bad)} 条不过(验了 {n} 条){D}"); sys.exit(1)
print(f"{G}✅ 研判判分:出账流水两种编号都认、合并结论认方向写法、否定写法不误认(验了 {n} 条){D}")
