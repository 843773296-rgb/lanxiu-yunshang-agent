# ── 跑挂重试(2026-11-11 用户拍)────────────────────────────────────────
#
# **不花一分钱:传一个假的「怎么跑一道」进去。** 真调 `ops_eval.跑一道带重试` ——
# 在夹具里手抄一份重试逻辑的话,把真代码改回去它照样绿(11-10 刚栽过)。
def _重试自测():
    坏 = []
    oe = __import__("ops_eval")
    原睡 = oe.time.sleep
    oe.time.sleep = lambda *_: None          # 别真睡 5 秒
    try:
        题 = {"id": "X1"}

        # ① 第一次就成 → 不该重试
        n = [0]
        def 一次就成(c):
            n[0] += 1
            return "答了", ["t"], {}
        t, _, _, 重 = oe.跑一道带重试(一次就成, 题, [0], 日志=lambda *_: None)
        if 重 or n[0] != 1:
            坏.append(f"第一次就成的不该重试(跑了 {n[0]} 次、重试过={重})")

        # ② 第一次挂、第二次成 → 该重试且该标记**重试过**
        n = [0]
        def 先挂后成(c):
            n[0] += 1
            return ("", [], {"error": "ResultError"}) if n[0] == 1 else ("答了", ["t"], {})
        t, _, _, 重 = oe.跑一道带重试(先挂后成, 题, [0], 日志=lambda *_: None)
        if not (t == "答了" and 重 and n[0] == 2):
            坏.append(f"挂一次该重试一次并标记(跑了 {n[0]} 次、text={t!r}、重试过={重})")

        # ③ 两次都挂 → 照实返回空,**不许再试第三次**
        n = [0]
        def 都挂(c):
            n[0] += 1
            return "", [], {"error": "ResultError"}
        t, _, _, 重 = oe.跑一道带重试(都挂, 题, [0], 日志=lambda *_: None)
        if t or n[0] != 2:
            坏.append(f"两次都挂就该认挂,只许跑两次(跑了 {n[0]} 次、text={t!r})")

        # ④ ⚠️ **整轮上限:撞了要抛,不许接着烧。**
        #    「偶发重试一次」和「持续故障把每道题都重试一遍」在单道题上分不出来
        计 = [3]                               # 已经重试 3 次(上限 3)
        try:
            oe.跑一道带重试(都挂, 题, 计, 上限=3, 日志=lambda *_: None)
            坏.append("整轮重试撞上限必须抛 像是环境坏了 —— "
                      "不抛的话一次持续故障会把每道题都重试一遍")
        except oe.像是环境坏了 as e:
            if "环境" not in str(e):
                坏.append("撞上限那句话要说清**是环境问题**,别让人去查模型")

        # ⑤ 上限之内照旧重试(别把上限写成「一轮只许重试一次」)
        计 = [1]
        n = [0]
        oe.跑一道带重试(先挂后成, 题, 计, 上限=3, 日志=lambda *_: None)
        if 计[0] != 2:
            坏.append(f"整轮重试数该累加到 2,实际 {计[0]}")
    finally:
        oe.time.sleep = 原睡
    return 坏


