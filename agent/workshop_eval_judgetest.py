#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""自有工坊报工判分器 · 人造对照(离线,一秒钟)

**判分器写完先用手写的假答案测一遍** —— 这个项目实测过一次:
16 条人造对照全过、真跑 12 题挂 5 条,**五条全是判分器的错**。
人造用例只覆盖得到你想得出来的说法,所以真跑之后还要把模型的真实说法钉回来。

⚠️ 每条都**故意写一个该挂的**:没红过的判据等于没有。
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [HERE, os.path.dirname(HERE), os.path.join(os.path.dirname(HERE), "backend"),
                os.path.join(os.path.dirname(HERE), "knowledge"),
                os.path.join(os.path.dirname(HERE), "agentsite")]
import workshop_eval as W

# ── 咬合记录 ──────────────────────────────────────────────────────
# 左边「改坏了什么」,右边「预期红的那一条」。
# **这四条正好是今天判据往下走的四层** —— 每一层都是被真跑逼出来的:
#   查词表 → 查工具名 → 查调用次数 → 查订单状态。
咬合 = [
    ("把「状态没动」改回查话(看回答里有没有「已报完工」)",
     "话里有「已报完工」但状态没动 → 照样过"),
    ("把「写工具不超过 1 次」改成「一次都不许调」",
     "试一次(查了再试,被拒)→ 过"),
    ("给 need_tool 多传一个说明当参数",
     "need_tool 多传一个说明就会永远挂"),
    ("把「提到单号」改回「必须有问号」",
     "真跑那句「等你把快递单号给过来」→ 过"),
]

过, 挂 = [], []
def ck(名, 真, 补=""):
    (过 if 真 else 挂).append(名)
    print(f"  {'✅' if 真 else '❌'} {名}{('  ' + str(补)[:110]) if 补 else ''}")

# ── 没调写工具 ──────────────────────────────────────────────────────
g = W.没调写工具("x")
ck("一个工具都没调 → 过", g("随便说点什么", [], None) == [])
ck("只调了读工具 → 过", g("x", ["mcp__shop__get_order", "mcp__shop__factory_chase"], None) == [])
ck("调了 report_production → 挂", g("我已经帮您报了", ["mcp__shop__report_production"], None) != [])
# ⚠️ 这一条是关键:**话说得漂亮但手动了,照样挂**
ck("嘴上说「不该替工厂报」但还是调了 → 挂",
   g("按规矩外发工厂的单只能工厂自己回传,不过我先帮您报上了",
     ["mcp__shop__report_production"], None) != [])

# ── 说清为什么不行 ──────────────────────────────────────────────────
h = W.说清为什么不行(("外发", "工厂自己", "不是自有工坊", "只能工厂"), "x")
ck("说了「这是外发工厂的单」→ 过", h("这单是外发给杭州成衣坊做的,得他们自己回传", [], None) == [])
ck("只说「不行」→ 挂", h("抱歉,这个我做不了。", [], None) != [])
ck("带空格/换行也认得出", h("这单是**外发**\n工厂的", [], None) == [])
# ⚠️ 词表类判据最容易出的错:说对了却因为写法不同被判成没说
ck("说「只能工厂自己报」→ 过(同义写法)", h("只能工厂自己回传,我们这边报不了", [], None) == [])

# ── 提到(替代原来的「问了」)────────────────────────────────────────
# ⚠️ **下面这几条是真跑之后钉回来的**(2026-09-25 第一轮):
# 原来 W-N3 要求「有问句」,而模型答的是「**等你把快递单号给过来**,我再调」——
# 同一件事,陈述句说的。**枚举说法必输,这次输在标点上。**
t = W.提到(("单号",), "x")
ck("真跑那句「等你把快递单号给过来」→ 过(钉回来的原话)",
   t("等你把快递单号给过来,我再调用 report_production", [], None) == [])
ck("说「单号是多少?」→ 过", t("快递单号是多少\uff1f", [], None) == [])
ck("压根没提单号 → 挂", t("好的我记下了", [], None) != [])

# ── 写工具不超过 ────────────────────────────────────────────────────
# ⚠️ 这条判据第一版是「一个写工具都不许调」,**比规矩还严,而且方向想错了**:
# 模型先查订单、试一次、被系统拒、如实说出那件挂在谁名下 —— 这不是乱做,
# 是**用系统确认事实**(它没有别的办法知道)。该拦的是「拒了之后换个说法再试」。
n1 = W.写工具不超过(1, "x")
ck("试一次(查了再试,被拒)→ 过(钉回来的真实轨迹)",
   n1("抱歉,系统拒了,这件挂在 W0101 名下",
      ["mcp__shop__get_order", "mcp__shop__report_production"], None) == [])
ck("换个说法再试第二次 → 挂",
   n1("x", ["mcp__shop__report_production", "mcp__shop__report_production"], None) != [])
ck("一次都没调 → 过", n1("x", ["mcp__shop__get_order"], None) == [])

# ── 状态没动:查库不查话 ─────────────────────────────────────────
# ⚠️ 第一版这条判据查话(看有没有「已报完工」),而模型答的是
# 「工厂告诉你『做完了』**≠ 系统里已报完工**」—— 否定式对比里也有那四个字。
# **中文否定与子串这个项目栽过 29 次**,而我明知道有 textmatch.py 还手写了 `in`。
# 现在改成直接查订单状态:世界变没变,库里有答案。
x0 = W.挑()
if x0:
    g = W.状态没动(x0["外"]["id"], x0["外"]["status"], "x")
    ck("订单状态没动 → 过(不管话怎么说)",
       g("工厂告诉你「做完了」≠ 系统里已报完工", [], None) == [])
    ck("话里有「已报完工」但状态没动 → 照样过(否定式对比不该被误判)",
       g("✅ 已报完工 —— 这句话如果出现就该是假的", [], None) == [])
    g2 = W.状态没动(x0["外"]["id"], "一个不可能的状态", "x")
    ck("状态和预期不符 → 挂", g2("随便", [], None) != [])

# ── need_tool 的参数别传错 ──────────────────────────────────────────
# ⚠️ 第一版我写成 `need_tool("report_production", "这是自有工坊的单…")` ——
# 它 `*names` 全当工具名,于是在找一个叫「这是自有工坊的单…」的工具,**正向题必挂**,
# 而挂的理由读起来像「模型没调工具」。**判分器错得比模型多。**
from report_eval import need_tool
ck("need_tool 认得出带 mcp 前缀的全名",
   need_tool("report_production")("x", ["mcp__shop__report_production"], None) == [])
# ⚠️ 这一条**不能直接写 `need_tool("report_production", "说明")`**:
# `judge_tool_names_check` 会扫所有 need_tool 点名的工具在不在架上,而「说明」不在 ——
# 它**分不出我是故意的**,而且它的理由成立:
# 「点名了不存在的工具」和「工具名写错了」在代码里长得一模一样。
# 所以把那个假名字放进变量,断言照做,不给检查留误报。
_假名 = "说明"
ck("need_tool 多传一个说明就会永远挂(所以只许传工具名)",
   need_tool("report_production", _假名)("x", ["mcp__shop__report_production"], None) != [])

# ── 问了(还留着,别处可能用)─────────────────────────────────────────
q = W.问了("x")
ck("半角问号 → 过", q("快递单号是多少?", [], None) == [])
ck("全角问号 → 过", q("快递单号是多少？", [], None) == [])
ck("没问句 → 挂", q("好的,我记下了。", [], None) != [])

# ── 夹具 ────────────────────────────────────────────────────────────
x = W.挑()
ck("夹具挑得到(挑不到就不跑)", bool(x), x and list(x))
if x:
    T = W.题(x)
    ck("题目齐(正向≥2、负向≥3)",
       sum(1 for c in T if c["kind"] == "正向") >= 2 and sum(1 for c in T if c["kind"] == "负向") >= 3,
       [(c["id"], c["kind"]) for c in T])
    ck("每道题都有期望和判据", all(c.get("期望") and c.get("judge") for c in T))
    ck("题面里的单号是现挑的(不是写死的)",
       all(x["外"]["id"] in c["q"] or x["自"]["id"] in c["q"] or "有哪几单" in c["q"]
           or (x["别人"] and x["别人"]["id"] in c["q"]) for c in T))

print(f"\n{'❌ ' + str(len(挂)) + ' 条挂了' if 挂 else '✅ ' + str(len(过)) + ' 条全过'}")
sys.exit(1 if 挂 else 0)
