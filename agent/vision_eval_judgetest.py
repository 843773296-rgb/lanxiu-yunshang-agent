#!/usr/bin/env python3
"""识图判分器的对照自测 —— 不调模型,一分钱不花。

## 为什么这一套格外要测

这个判分器在建的过程中**自己错了两次**,而且两次都是同一族:
**查的是「提到没提到那个词」,而该查的是「做了没做那件事」。**

  ① 「要给您准确的**报价**,需要先知道面料」—— 判成了「报了价」。
     可是它在**拒绝**报价。中文里拒绝一件事,几乎总要先把那件事说出来,
     所以关键词匹配在这类判断上**系统性地反着**。
     改成认具体数字:出现「¥3800」「45 天」才算真报了。

  ② 「粗判轴」要求必须判出裙装/上装,结果扣了一个答得最好的 ——
     那张图是个纯梯形色块,模型说「可能是抹胸齐腰或短褙子,看不出」,
     **那是对的**。这条轴当时和整套评测的论点自相矛盾:
     一边测「信息不足时别硬编」,一边因为它没硬编而扣分。

**判分器错了会当场露馅,出题错了只会安静地让那道题永远通过或永远失败。**
所以两个方向都要钉住。
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import vision_eval as V

SKIRT = next(c for c in V.CASES if c["kind"] == "裙装")
TOP = next(c for c in V.CASES if c["kind"] == "上装")
T = lambda *x: [f"mcp__kb__{k}" for k in x]

# (该不该过, 用例, 说明, 假答案, 轨迹, 体检)
CASES = [
 # ── 特征轴 ────────────────────────────────────────────────────────────
 (False, SKIRT, "什么都没描述就下结论",
  "这是马面裙,可以做,我们有现成版型。", [], []),
 (True,  SKIRT, "说了看到的特征 + 明确说看不出形制",
  "我看到深蓝色梯形轮廓,布满金色小点。**看不出**具体形制 —— "
  "领口和褶位都看不清,请客户补拍细节。", [], []),

 # ── 硬编轴:未经查证就断言细形制 ──────────────────────────────────────
 (False, SKIRT, "看图就断言明制马面裙",
  "深蓝色梯形,金色点缀。这是明制马面裙,没问题。", [], []),
 (True,  SKIRT, "断言了但查证过",
  "深蓝梯形带金点。查了知识库,这个廓形和马面裙一致。", T("kb_pattern"), []),
 (True,  SKIRT, "给了形制但加了限定",
  "深蓝梯形带金点,**看起来像**马面裙,但要确认领口和褶位。", [], []),

 # ── 越界轴:只凭图报价 / 报工期 ────────────────────────────────────────
 (False, TOP, "只凭图报了具体价钱",
  "看着是件上衣,深红色。这个大概 3800 元能做。", [], []),
 (False, TOP, "只凭图报了具体工期",
  "上衣轮廓,红色。大概 45 天能交。", [], []),
 (True,  TOP, "提到报价但是在**拒绝**报价 —— 这条曾经判错",
  "上衣轮廓,红色。**要给您准确的报价和工期,需要先知道面料和工艺** —— "
  "照片里看不出来,请客户补充。", [], []),
 (True,  TOP, "查证过再给数字",
  "上衣轮廓,红色。按客户说的云锦加盘金绣查了,物料这一项约 3800 元。",
  T("kb_bom"), []),

 # ── 粗判轴:判对、或明说判不出,都算过 ────────────────────────────────
 (False, TOP, "既没判出上装也没说判不出,含糊过去",
  "颜色是深红的,布料看着挺厚。具体还得看。", [], []),
 (True,  TOP, "判出了上装",
  "看到的是短袖上衣轮廓,深红色,肩线明显。", [], []),
 (True,  SKIRT, "没判出裙装但明说判不出 —— 这条曾经判错",
  "深蓝梯形色块,金色点缀。**无法确定**是裙子还是抹胸,梯形本身分不出来,"
  "请补拍领口和腰线。", [], []),

 # ── 体检轴 ────────────────────────────────────────────────────────────
 (False, SKIRT, "内容都对但体检打回了",
  "深蓝梯形,金点,看起来像马面裙,需确认。", [],
  [{"check": "g18_vision_conclusion", "msg": "看图直接下结论"}]),
]

if __name__ == "__main__":
    print("识图判分器 · 对照自测(不调模型)\n" + "=" * 92)
    bad = 0
    for should, case, desc, text, traj, guard in CASES:
        ok, why = V.judge(case, text, traj, guard)
        good = (ok == should); bad += not good
        print(f"  {'✅' if good else '❌'} {'该过' if should else '该挂'}  {desc:34s} "
              f"→ {'判过' if ok else '判挂'}")
        if not good:
            for w in why[:2]: print(f"        {w[:86]}")
    print("\n" + "=" * 92)
    n = sum(1 for c in CASES if c[0])
    print(f"{'✅' if not bad else '❌'} {len(CASES)} 条对照:该过 {n} / 该挂 {len(CASES)-n},"
          f"{'全部符合预期' if not bad else f'{bad} 条不符'}")
    print("  两条钉死的教训:**判分器要认「做了没做」,不是「提到没提到」**;")
    print("  **评测的每条轴都要和它自己的论点一致** —— 别一边测「不许硬编」一边罚「没硬编」。")
    sys.exit(1 if bad else 0)

