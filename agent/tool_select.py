#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""工具筛选的**准入判断** —— 这个角色该不该开筛选,以及退回时退到哪。

## 为什么是一个文件,不是一句 if

业务 10-03 定了「只开路由器」。而队友(管理后台那条线)量出来一件事:

> **路由器那一次调用是固定成本,而筛选的收益随工具数缩** —— 所以小角色必亏。

那不是调参能救的,是算术。代入现在那六个角色:

    all       77 → ✅ 每条净省 $0.00118
    task      61 → ✅ +$0.00073
    kb        43 → ✅ +$0.00028    ← 刚过线,余量很小
    pattern    9 → ❌ 净亏 $0.00090
    workshop   7 → ❌ 净亏 $0.00093
    finance    5 → ❌ 净亏 $0.00104

## ⚠️ 这条线**不许写死**,所以它必须是代码

线 = 路由器一次的钱 / (每个工具平均 token × 单价) + 路由器平均留几个

它随**三个数**漂:路由器单价、每个工具平均 token、**走不走缓存**。
而最后那个最要紧:

> 省下来的按**缓存读**单价算。**不走缓存单价高 10 倍**,
> 那时线降到 ≈ 5 —— **几乎所有角色都该开**。

也就是说:
> **在缓存命中率高的系统里,筛选只对大角色划得来;
> 而缓存一旦失效,筛选立刻对所有角色都划得来。**

(本项目实测缓存命中占输入的 **97.9%**,所以默认按缓存读那一档算。)

**写死 38 的那天模型降价它就错了,而错的时候不报错** ——
一个用过期的线算出来的「这个角色不该开筛选」,和一个算对了的,在日志上长得一模一样。

## 三条边界(都是队友定的,我原来漏了)

**① 筛选结果必须和角色工具集取交集,只许收窄。**
角色的工具集是**权限边界**(财务不给量体/版型),而规格明写
「筛选得分高**不**授予权限」。路由器选出一个角色本来没有的写工具就是越权。
(`knobs.校验` 对「工具」旋钮就是这个规矩 —— 同一条规矩两处都要落。)

**② 交集为空 → 退回角色原名单 + 当场记一条。**
记录里要带**路由器原本选了什么**和**角色集是什么** ——
不然事后查不出是路由器选歪还是角色集太窄。

**③ 兜底组也要取交集**,而且交集太小要报:
`finance` 和兜底组的交集只剩 **1 个** —— **退回它等于退回一个空壳**。

## 这个文件不调模型、不碰库

纯算术 + 集合运算,所以它的自测(`tool_select_judgetest.py`)离线一秒钟跑完。
"""
import os

# ── 这几个数**从哪来**,一个都不许填 ────────────────────────────────
#
# ⚠️ 全是实测或从价目表取的。缺了就**抛**,不给默认值 ——
# 一个用默认值算出来的准入线,和一个用实测算出来的,在那个布尔值上长得一模一样。

路由探针结果 = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       "..", ".feynman", "router-probe.json")


class 算不了(Exception):
    """缺数据就抛。**不猜** —— 猜出来的线会在它过期那天静默给出错的答案。"""


def 单价(模型, 走缓存=True):
    """从 `agent/v1.py::PRICE` 取单价(百万 token 美元)。**不抄一份价目表。**

    `走缓存=True` 取缓存读那一档 —— 本项目实测缓存命中占输入 97.9%。
    ⚠️ 这个开关是**这条线最敏感的一个** :走不走缓存差 10 倍,线差 7 倍。
    """
    import sys
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import v1
    pr = v1.PRICE.get(模型) or v1.DEEPSEEK_PRICE.get(模型)
    if not pr:
        raise 算不了(f"价目表里没有 {模型} —— **拒绝用猜的单价算**"
                  f"(这个项目在这上面栽过两次)")
    键 = "cache" if 走缓存 else "inp"
    if 键 not in pr:
        raise 算不了(f"{模型} 的价目表里没有 `{键}` 这一档")
    return pr[键] / 1e6


def 路由器实测(结果文件=None):
    """读探针结果 → (单条成本, 平均留几个工具, 哪一版探针)。

    ⚠️ **核探针版本** —— 一个用上一版探针的数算出来的线,
    和一个用当前版本算的,在那个数上长得一模一样。
    """
    import hashlib
    import json
    p = 结果文件 or 路由探针结果
    if not os.path.exists(p):
        raise 算不了("没有路由器探针结果 —— 先跑 `agent/router_probe.py`。"
                  "**不给默认成本**:筛选该不该开取决于它到底多贵")
    d = json.load(open(p, encoding="utf-8"))
    if "配置" not in d or "探针版本" not in d:
        raise 算不了("探针结果没盖版本章 —— 跑一次 "
                  "`agent/router_probe.py --模型 … --重算`(不会重新调模型)")
    行 = [x for x in d["配置"].get("开", []) if not x.get("挂了")]
    钱 = [x.get("成本USD") for x in 行 if x.get("成本USD") is not None]
    选 = [x.get("给的") or [] for x in 行]
    if not 钱:
        raise 算不了("探针结果里没有算好的成本 —— 跑 `--重算` 补上。"
                  "**这边不自己算** :`sdk.cost_of` 修过一次「少算三成」")
    if not 选:
        raise 算不了("探针结果里没有「路由器选了什么」")
    return (sum(钱) / len(钱),
            sum(len(x) for x in 选) / len(选),
            d["探针版本"])


def 每个工具平均token(工具面):
    """`工具面`:{工具名: (说明, 入参schema的JSON字符串)}。

    中文按 1 字 ≈ 1 token、其余按 3 字 ≈ 1 token 粗估。
    ⚠️ **这是粗估** —— 真实 token 要问 tokenizer,而各模型不一样。
    所以这条线算出来的是**量级**,不是一个能较真的数;
    它只用来分「值得开 / 不值得开」,不许拿它算钱。
    """
    if not 工具面:
        raise 算不了("工具面是空的 —— **空集合上这个平均值没有意义**"
                  "(而它会让线变成无穷大,于是所有角色都「不该开」)")
    共 = 0
    for 名, (说明, 入参) in 工具面.items():
        s = (说明 or "") + (入参 or "")
        中 = sum(1 for ch in s if "一" <= ch <= "鿿")
        共 += 中 + (len(s) - 中) // 3
    return 共 / len(工具面)


def 准入线(工具面, 模型, 走缓存=True, 结果文件=None):
    """→ (线, 怎么算出来的一张明细表)。**现算,不写死。**

    线的含义:**角色的工具数 ≥ 线,开筛选才是净省。**
    """
    路由钱, 均留, 探针版 = 路由器实测(结果文件)
    均每个 = 每个工具平均token(工具面)
    价 = 单价(模型, 走缓存)
    线 = 路由钱 / (均每个 * 价) + 均留
    return 线, {
        "路由器单条成本": 路由钱, "路由器平均留几个": 均留,
        "每个工具平均token": round(均每个, 1),
        "单价每token": 价, "按哪一档单价": ("缓存读" if 走缓存 else "未缓存输入"),
        "模型": 模型, "探针版本": 探针版,
        "⚠️": ("这条线随这三个数漂:路由器单价、每个工具平均 token、走不走缓存。"
              "**走不走缓存差 10 倍,线差约 7 倍** —— "
              "不走缓存时线降到 ≈ 5,几乎所有角色都该开"),
    }


def 该开筛选吗(角色工具数, 工具面, 模型, 走缓存=True, 结果文件=None):
    """→ (该不该开, 一句人话, 明细)。

    ⚠️ **算不了就抛,不默认「开」也不默认「不开」** ——
    两个方向错的代价都真:默认开会让小角色白花钱+白等 1.6 秒;
    默认不开会让大角色一直省不下来。而**「算不了」本身是要被看见的**。
    """
    线, 细 = 准入线(工具面, 模型, 走缓存, 结果文件)
    开 = 角色工具数 >= 线
    省 = (角色工具数 - 细["路由器平均留几个"]) * 细["每个工具平均token"] \
        * 细["单价每token"]
    净 = 省 - 细["路由器单条成本"]
    话 = (f"这个角色有 {角色工具数} 个工具,线是 {线:.1f} → "
          f"{'开' if 开 else '**不开**'}:每条净"
          f"{'省' if 净 >= 0 else '亏'} ${abs(净):.5f}")
    if not 开:
        话 += ("。原因是结构性的:**路由器那一次调用是固定成本,"
               "而筛选的收益随工具数缩** —— 小角色必亏,不是调参能救的")
    return 开, 话, dict(细, 角色工具数=角色工具数, 线=round(线, 1),
                      每条净省=净, 开吗=开)


# ── 三条边界(队友定的)────────────────────────────────────────────────

def 收窄到角色内(路由器选的, 角色名单):
    """筛选结果 ∩ 角色工具集。**只许收窄不许放宽。**

    → (能用的, 被挡掉的, 空集了吗)

    ⚠️ **角色的工具集是权限边界**(财务不给量体/版型),
    而规格 §3 明写「筛选得分高**不**授予权限」。
    路由器选出一个角色本来没有的工具就是越权 ——
    > 一个没取交集的工具面,和一个合法的工具面,**在运行时长得一模一样** ——
    > 直到某个角色调到了它本来不该有的工具。
    """
    角 = set(角色名单)
    能 = [t for t in 路由器选的 if t in 角]
    挡 = [t for t in 路由器选的 if t not in 角]
    return 能, 挡, (not 能)


def 空集退回记一条(角色, 路由器选的, 角色名单, 被挡掉的):
    """交集为空时要记的那一条。**带上两边原本是什么。**

    ⚠️ 不带的话事后**查不出是路由器选歪还是角色集太窄** ——
    而这两种的修法完全相反:前者改路由器的目录或提示,后者改角色的工具集。
    """
    return {
        "这一轮筛选没生效": "空集退回",
        "角色": 角色,
        "退回到": "该角色原本的工具集(_ROLE_TOOLS)",
        "路由器原本选了": list(路由器选的),
        "角色集里有": sorted(角色名单)[:12],
        "角色集共几个": len(set(角色名单)),
        "被挡掉的": list(被挡掉的),
        "怎么读": ("路由器选的全被挡掉了。看「被挡掉的」里那几个在不在角色集里:"
                "全不在 → 路由器选歪了(改它的目录或提示);"
                "角色集只有几个 → 角色集太窄(那这个角色本来也不该开筛选)"),
    }


def 兜底够用吗(兜底组, 角色名单, 下限=5):
    """兜底组 ∩ 角色工具集 够不够。→ (够不够, 交集, 一句话)

    ⚠️ 实测:`finance` 和那 20 个只读兜底组的交集**只剩 1 个** ——
    > 一个退回到空壳兜底组的筛选,和一个正常退回的,
    > 在「退回了」这个事实上长得一模一样。

    好消息是那两个交集太小的角色**正好也不过准入线**(不开筛选就用不到兜底组),
    两件事互相对上。这道闸是**防将来**:哪天线动了、某个小角色过线了,
    而它的兜底是个空壳。
    """
    交 = sorted(set(兜底组) & set(角色名单))
    够 = len(交) >= 下限
    话 = (f"兜底组和这个角色的交集 {len(交)} 个"
          + ("" if 够 else f" —— **少于 {下限} 个,退回它等于退回一个空壳**"))
    return 够, 交, 话
