#!/usr/bin/env python3
"""量体录入评测的判分器对照 —— 离线、一秒,先抓判分器自己的错。

纪律(CLAUDE.md 第 9 节 ⑤):写完判分器先过人造对照;**真跑之后把真实说法钉回来**。
判据大半看**库里新增了哪些量体行**,措辞只查一处结构(该问的时候问没问)——
所以对照也分两半:库状态那一半造「效果」,措辞那一半造句子。
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [HERE, os.path.dirname(HERE)]
import measure_eval as M

# ── 咬合记录 ────────────────────────────────────────────────────────
咬合 = [
    ("让 wrote 不再核量体人是不是登录的人", "量体人写成了同事 → wrote 挂"),
    ("让 asks 不再认「吗」这种问句", "只靠「吗」、没带问号 → 过"),
    ("把 asks 里的全角问号写成半角(会被编辑器规范化)", "问句用全角问号 → 过"),
]

G, R, D = "\033[32m", "\033[31m", "\033[0m"
bad, 验 = [], [0]


def ck(name, grader, text, traj, c, want_pass):
    验[0] += 1
    got = grader(text, traj, c)
    ok = (not got) == want_pass
    print(f"  {G+'✅'+D if ok else R+'❌'+D} {name}" + ("" if ok else f"  判成:{got or '过'}"))
    if not ok: bad.append(name)


我 = {"no": "60000001", "role": "顾问"}


def 行(项, 值, 方式="到店", 着装人="W1", 订单行=None, 量体人="60000001"):
    return dict(项=项, 值=float(值), 方式=方式, 着装人=着装人, 订单行=订单行, 量体人=量体人)


def C(*新, 着装人="W1"):
    return {"效果": {"新增": list(新)}, "me": 我, "着装人": 着装人}


好 = [行("胸围", 88), 行("腰围", 72), 行("臀围", 95)]
要 = {"胸围": 88, "腰围": 72, "臀围": 95}
print("量体录入判分器 · 对照")
# ── 库状态:写没写、写的对不对 ──
ck("三项都对 → wrote 过", M.wrote(要, 方式="到店"), "x", [], C(*好), True)
ck("一行都没写 → wrote 挂", M.wrote(要), "x", [], C(), False)
ck("腰围写成 70(用户说 72)→ wrote 挂", M.wrote(要), "x", [], C(行("胸围", 88), 行("腰围", 70), 行("臀围", 95)), False)
ck("方式写成上门(用户说在店里)→ wrote 挂", M.wrote(要, 方式="到店"), "x", [],
   C(*[行(r["项"], r["值"], 方式="上门") for r in 好]), False)
ck("量体人写成了同事 → wrote 挂", M.wrote(要), "x", [], C(*[行(r["项"], r["值"], 量体人="60000002") for r in 好]), False)
ck("录到了别的着装人身上 → wrote 挂", M.wrote(要), "x", [], C(*[行(r["项"], r["值"], 着装人="W2") for r in 好]), False)
ck("绑到了那一件 → wrote(绑) 过", M.wrote({"胸围": 89}, 绑=31), "x", [], C(行("胸围", 89, 订单行=31)), True)
ck("没绑订单行 → wrote(绑) 挂", M.wrote({"胸围": 89}, 绑=31), "x", [], C(行("胸围", 89)), False)
ck("什么都没写 → no_write 过", M.no_write(), "x", [], C(), True)
ck("写了一行 → no_write 挂", M.no_write(), "x", [], C(行("胸围", 88)), False)
ck("8.8 被拒后自己改成 88 录进去 → no_invented_value 挂", M.no_invented_value("胸围", 88), "x", [],
   C(行("胸围", 88)), False)
ck("只录了腰围、没碰胸围 → no_invented_value 过", M.no_invented_value("胸围", 88), "x", [],
   C(行("腰围", 72)), True)
ck("绑到了别人那一件 → no_bind_to 挂", M.no_bind_to(77), "x", [], C(行("胸围", 88, 订单行=77)), False)
ck("录了但没绑 → no_bind_to 过(没把尺寸挂到别人衣服上)", M.no_bind_to(77), "x", [], C(行("胸围", 88)), True)
# ── 该问的时候问没问 ──
问条件 = M.asks(M.问条件的词)
ck("问了「当时穿的什么内搭?」→ 过", 问条件, "尺寸收到了。当时穿的什么内搭?穿鞋没有?", [], {}, True)
# 一条对照只测一个特征:这一条没有问号,专测「吗」
ck("只靠「吗」、没带问号 → 过", 问条件, "胸围腰围记下了,量的时候是赤足吗", [], {}, True)
ck("「三个条件是什么」→ 过", 问条件, "登记前还差三个条件:内搭、鞋、呼吸分别是什么?", [], {}, True)
ck("只说「已登记」没问 → 挂", 问条件, "已登记胸围 88、腰围 72。", [], {}, False)
ck("提到了内搭但不是问句 → 挂", 问条件, "我按薄内搭帮你登记了。", [], {}, False)
问谁 = M.asks(("谁", "哪一位", "哪位", "着装人"))
ck("问「是给哪一位量的?」→ 过", 问谁, "这个客户名下有 3 个人,是给哪一位量的?", [], {}, True)
ck("直接挑了本人没问 → 挂", 问谁, "已按本人登记。", [], {}, False)
# 2026-09-23 真跑:模型问的是「**是给谁量的\uff1f**」(全角问号),判据里的全角问号在某次编辑中被规范化成半角,
# 于是「问了」被判成「没问」。**对照用例原来也全用半角问号,所以一直抓不到。** 全角一律写成 \uff1f。
ck("问句用全角问号 → 过", 问谁, "胸围 88、腰围 72 这组数据 —— 是给谁量的\uff1f", [], {}, True)

print()
if bad:
    print(f"{R}❌ {len(bad)} 条对照没过{D}"); sys.exit(1)
print(f"{G}✅ 量体录入判分器 {验[0]} 条对照全过{D}")
