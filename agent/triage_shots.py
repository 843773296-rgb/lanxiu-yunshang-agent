"""独立测试集的**开枪台账** —— 「这一枪算不算已经用掉」只许由证据决定,不许事后商量。

台账文件就是 `triage_sets.台账文件`(`agent/triage-sets-ledger.json`),**进版本库** ——
这个演示世界的库每天从零重建,台账得活得过重建(同
`knowledge/相容矩阵-人工确认.json` 那条:手写源 / 归档文件进版本库)。

## 用户 2026-10-23 拍的那条规则

> **崩了不算用过,但要留痕。**

选项原文:「凭据失效、库被锁、超时这类**不是模型答错**的崩,不算用掉那一枪,可以重跑;
但每次崩都写进归档(哪天、崩在哪、重跑了第几次)。这样『不算』是有记录的决定,
而不是事后商量出来的。」

## ⚠️ 为什么台账不能只是一个数

原来的台账是 `{"测试集": {"跑过几轮": N}}` —— **一个计数器装不下这条规则**。
「这一枪崩了所以不算」在计数器上的表现就是**没有加一**,
而「跑了但没人登记」也是**没有加一**。

> **一次「崩了所以没加一」和一次「跑了却没登记」,在那个数字上长得一模一样。**

(这句话不是我推的 —— `triage_sets_check.py` 第 409 行自己就写着
「它和『跑过了而没人登记』在这条判据上长得一样」,而当时没有东西去堵。)

所以台账改成**一条条记录**,而 `跑过几轮` **由记录推出来**,不是另存一个数:

    跑过几轮 = 算用过 为真的记录条数

⚠️ 推出来的和另存的差别要紧:另存一个数就等于**允许它和记录对不上**,
而对不上的时候没人知道哪个是真的。判据那头也改成**现算**,不读存的那个
(存的那个只为了让人读文件时一眼看见,判据不信它)。

## 三道闸(这条规则靠它们成立,不靠记性)

### ① 「不算用过」必须带崩的证据,而证据是**捕获来的**

没有证据的「不算」直接拒收。因为:

> **一条「真崩了所以不算」和一条「分数不好所以说它崩了」,在台账上长得一模一样。**

所以 `崩因` 不许人填一句话了事 —— 要带 `崩证据`(异常类型 + 输出尾部),
而那两样只能从**捕获到的异常和输出**里来。判据会验「不算用过的记录必须有证据」。

### ② 拿不准就算用过

白名单只收**明确不是模型造成的**那几种。偏错的代价是不对称的:

    把真开过的一枪记成「没开」  →  可以无限重摇,这套题的价值归零
    把一次真崩记成「开过了」    →  白费一套题,而题可以重新冻

所以不在白名单里的一律 `算用过`,包括 `说不清`。

⚠️ **超时要分两种,而这是我按「偏错朝安全那边」定的**:
  · `整轮超时`(墙上时钟)—— **不算用过**。这仓库见过一次 8599 秒的异常,
    整轮 10009 秒,**是电脑睡了**;那和模型能力无关。
  · `单次调用超时` —— **算用过**。模型自己绕圈也会把单次调用拖超时,**那是能力问题**,
    而「绕圈绕超时」和「机器卡了」在那条超时异常上长得一模一样 —— 分不出来就算用过。

### ③ 连着三次「崩了不算」就红

那不是运气差,是**环境根本没准备好**。红在这里逼人去修环境,
而不是一直重摇一套只能用一次的题。

## ⚠️ 没做、但想清楚了的一件(留给下一个人)

`判据崩了`(模型答完、判分器炸了)现在归 `说不清` → **算用过**,这是安全那边。
而它其实**可以证明是安全的**:答案已经落盘,重跑只需要**重判**,不必再问模型 ——
也就是说重试拿不到新的模型输出,摇不出更好的分。
要把它放进白名单的话,得同时要求记下**那一轮模型答案的指纹**,
并且重跑那条路只许重判、不许重问模型。**那两样都没有,所以现在不放。**
"""
