#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""三条退款题的判分器 · **人造对照** —— 判分器自己先过一遍,才有资格去判模型。

用户要求 2 明写:「判分器**先过人造对照**,真跑后把真实说法钉回对照用例」。
这个顺序不是流程洁癖 —— 一个判错的判分器跑出来的分,和一个真实的分,
**在那个数上长得一模一样**,而它会被写进 PRD。

## 对照里有一条是**实录**,不是我编的

`DQ9001` 第一次被真跑时,AI 的回答是:
> 「渠道在 12:46 连续超时导致三次重试失败,是系统级渠道故障」,置信度**高**。

它漏掉的是 `payment_flow` 里那条 `out` + `success` —— **钱已经出去了**。
按「渠道故障」处理就会重发,**钱出去两次**。这条进对照,**必须判不过**;
而且没过的理由要**正好是**「查过支付流水」和「说出了钱实际已退」这两条 ——
> 一个「判对了」和一个「碰巧也红了,但红在别的地方」,**在那个 ❌ 上长得一模一样。**

## 四种边界,每一种对着一个真实的误判方向

    查了但没用上   调过 get_payment_flow、却仍然只说渠道故障 → **不过**
                   (「查了」和「看懂了」是两件事,而轨迹那一关分不开它们)
    被否定的重发   「**不要**重新发起」→ **算过**(中文里拒绝一件事总要先把它说出来)
    该重发的那道   `DQ9003` 补足余额后重新发起是**对的** —— 同一个词在不同题里不同性质
    两侧都提到     「不是客户的问题,是商户余额不足」→ **算过**(问的是在说谁,不是提没提)
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import refund_sets as S                                       # noqa: E402

R, G = "\033[31m", "\033[32m"
D = "\033[0m"
坏 = []
题 = {t["押金单"]: t for t in S.题们()}


def ck(名, 取):
    try:
        ok = bool(取()); 说 = ""
    except Exception as e:
        ok, 说 = False, f"  ← **崩了**:{type(e).__name__}: {e}"
    print(f"  {'✅' if ok else '❌'} {名}{说}")
    if not ok:
        坏.append(名)


def 判(单, 文, 工具=()):
    return S.判一题(题[单], 文, [f"mcp__task__{x}" for x in 工具])


print("三条退款题的判分器 · 人造对照\n" + "=" * 74)
流水号 = (题["DQ9001"]["出账流水号"] or ["(库里没有出账流水)"])[0]

# ── DQ9001:考「查不查支付流水」────────────────────────────────────────
print("① DQ9001 渠道超时但实际已退")
实录 = ("根因:微信支付渠道在 2026-10-16 12:46 连续响应超时,导致三次自动重试均失败。"
        "该时间点出现的系统级渠道故障是主要原因。建议动作:建议重新发起退款。置信度:高")
r = 判("DQ9001", 实录, ("get_deposit", "get_refund_trace"))
ck("**实录的那条错答案**判不过", lambda: not r["过"])
ck("而且没过的正好是「查过支付流水」和「说出了钱实际已退」这两条"
   f"(实际:{r['没过的']})",
   lambda: set(r["没过的"]) >= {"查过支付流水", "说出了钱实际已退(引了那条出账流水)"})
ck("它建议了重发,所以第三条也该红", lambda: "没建议重发(提到也行,只要是被否定的)" in r["没过的"])

好 = (f"根因:退款轨迹三次 TIMEOUT,但支付流水里有一条 direction=out、status=success 的记录"
      f"(渠道流水号 {流水号}),说明这笔钱实际已经退出。"
      f"建议动作:**不要**重新发起退款,由财务向渠道核实后登记已退。证据:支付流水那条 out 记录。置信度:中")
ck("好答案判过(引了那条出账流水 + 否定了重发)",
   lambda: 判("DQ9001", 好, ("get_deposit", "get_refund_trace", "get_payment_flow"))["过"])

查了没用上 = ("根因:渠道连续超时导致三次重试失败,属渠道故障。建议动作:重新发起退款。置信度:高")
r2 = 判("DQ9001", 查了没用上, ("get_refund_trace", "get_payment_flow"))
ck("**查了但没用上**:轨迹那一关过了,内容那两关要红 ——"
   "「查了」和「看懂了」是两件事",
   lambda: (not r2["过"]) and "查过支付流水" not in r2["没过的"]
   and "说出了钱实际已退(引了那条出账流水)" in r2["没过的"])

# ── DQ9002:考「别建议重试」──────────────────────────────────────────
print("\n② DQ9002 原支付渠道已注销")
码2 = 题["DQ9002"]["返回码"][0]
好2 = (f"根因:渠道返回 {码2},收款账户已注销,原路退回不可能成功。"
       f"建议动作:**不要**再重试原渠道,改走线下转账退款,退完登记已退。置信度:中")
ck("好答案判过", lambda: 判("DQ9002", 好2, ("get_refund_trace",))["过"])
坏2 = f"根因:渠道返回 {码2}。建议动作:建议重新发起一次退款试试。置信度:中"
r3 = 判("DQ9002", 坏2, ("get_refund_trace",))
ck("建议重试的判不过(账户已注销,重试一定再失败)", lambda: not r3["过"])
ck("而且红的是重试那一条,不是「认出原因」那一条"
   f"(实际:{r3['没过的']})",
   lambda: r3["没过的"] == ["没建议重试(账户已注销,重试一定再失败)"])
ck("连渠道给的那个原因都没认出来的,红在「认出原因」那一条",
   lambda: "认出了渠道给回来的那个原因" in
   判("DQ9002", "根因:退款失败,原因待查。建议动作:转人工核实。", ("get_refund_trace",))["没过的"])

# ── DQ9003:考「商户侧还是客户侧」──────────────────────────────────────
print("\n③ DQ9003 商户账户余额不足")
码3 = 题["DQ9003"]["返回码"][0]
好3 = (f"根因:渠道返回 {码3} —— **商户**账户余额不足,是我方账户的问题。"
       f"建议动作:财务补足商户账户余额后重新发起退款。置信度:中")
ck("好答案判过 —— 注意**这道题里「重新发起」是对的**,同一个词在不同题里性质不同",
   lambda: 判("DQ9003", 好3, ("get_refund_trace",))["过"])
坏3 = f"根因:渠道返回 {码3},客户账户余额不足。建议动作:建议联系客户核实其账户。置信度:中"
r4 = 判("DQ9003", 坏3, ("get_refund_trace",))
ck("说成客户侧的判不过", lambda: not r4["过"])
ck("而且两条都红(「算在商户侧」没立 + 「说成客户侧」犯了)"
   f"(实际:{r4['没过的']})",
   lambda: len(r4["没过的"]) == 2)
两侧 = (f"根因:{码3}。这**不是客户**的问题,是**商户**账户余额不足。"
        f"建议动作:补足商户余额后重发。置信度:中")
ck("两侧都提到、但说清了是商户 → 算过(问的是「在说谁」,不是「提没提」)",
   lambda: 判("DQ9003", 两侧, ("get_refund_trace",))["过"])

# ── 两轮那一层 ──────────────────────────────────────────────────────
print("\n④ 两轮怎么报")
全过 = [判("DQ9001", 好, ("get_payment_flow",)), 判("DQ9002", 好2, ()), 判("DQ9003", 好3, ())]
全挂 = [判("DQ9001", 实录, ()), 判("DQ9002", 坏2, ()), 判("DQ9003", 坏3, ())]
ck("两轮都全过 → 说「两轮都全过」", lambda: S.判两轮(全过, 全过)["两轮都全过"])
ck("两轮挂的是同一批 → 说「像是稳定的能力缺口」",
   lambda: "稳定" in S.判两轮(全挂, 全挂)["一句话"])
ck("两轮挂的**不是**同一批 → 说「这是抖动,单轮的数不许用来下结论」",
   lambda: "抖动" in S.判两轮(全挂, [全挂[0], 全过[1], 全过[2]])["一句话"])

# ── 真值那一层 ──────────────────────────────────────────────────────
print("\n⑤ 真值来路")
ck("三道题的真值都是**认**出来的,不是按单号顺序猜的"
   "(改了发号顺序也不会整体挪一位)",
   lambda: all(t["真因"] and t["真值来路"].startswith("tools/seed_triage_tasks") for t in 题.values()))
ck("三道题的真因**互不相同**(三条考的是三件事,塌成一条就白考了)",
   lambda: len({t["真因"] for t in 题.values()}) == 3)

# ── 咬合记录 ──────────────────────────────────────────────────────────
# 左边「改坏了什么」,右边「预期红的那一条」。规格在 `tools/bite_specs.json` 里可重放:
# 对照要先绿,改坏之后要红,而且红的必须是右边这一条。
#
# 咬的是判分器里**唯一手写的那个词表**该怎么用:判定靠的是**否定结构**
# (「出现了但被否定」= 它在说「不要重发」),不是「出现了就算」。
# 中文里拒绝一件事几乎总要先把那件事说出来 —— 退回朴素包含判断的话,
# 一个写着「**不要**再重试原渠道」的**好**答案会被判成建议了重发。
#
# ⚠️ 这条咬合第一版挑错了下手处:我原想去掉别名表里的「重试」,结果**改坏了却没红** ——
# 因为那三条对照的坏答案写的都是主词「重新发起」,一条都没用到那个别名。
# 也就是说,那个别名**本来就没有任何人造对照覆盖**(它是为真跑准备的)。
# > 一处「改坏了检查会红」和一处「改坏了根本没人看着」,在咬合跑之前长得一模一样。
咬合 = [
    ('让判分器退回「出现了就算」:认重发时不再看它有没有被否定',
     '好答案判过(引了那条出账流水 + 否定了重发)'),
]

print()
if 坏:
    print(f"{R}❌ {len(坏)} 条对照没过{D}")
    for x in 坏:
        print(f"   · {x}")
    raise SystemExit(1)
print(f"{G}✅ 判分器过了人造对照(含一条实录的错答案){D}")
