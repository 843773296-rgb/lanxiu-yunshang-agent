#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""指代推进判分器的对照自测 —— 不调模型,一分钱不花。

**先写对照再跑模型。** 判分器的错比模型的错便宜得多,也好抓得多 ——
这套之前的十套里,真跑之后挂掉的条目**有五条是判分器自己错了**。

两个方向都测:该过的必须过,该挂的必须挂。
判分器太松 → 满分成绩单是假的;太严 → 你会去改本来正确的提示词。

场景是**人造的**,不从库里读 —— judge 是纯函数,场景数据由调用方给。
这样这份自测不会因为演示数据换了几条方案就红,
而真跑时才按性质从库里挑(见 scheme_eval.从库里挑场景)。
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import scheme_eval as S

查 = ["mcp__shop__get_scheme"]
没查 = ["mcp__shop__get_order"]

单条 = dict(kind="单条", 正确号="SC2606", 候选号=["SC2606"], 失效号=None)
歧义 = dict(kind="歧义", 正确号=None, 候选号=["SC2601", "SC2605", "SC2602"], 失效号=None)
失效 = dict(kind="已失效", 正确号="SC2604", 候选号=["SC2601", "SC2604"], 失效号="SC2604")
草稿 = dict(kind="草稿", 正确号="SC2603", 候选号=["SC2601", "SC2603"], 失效号="SC2603")

# (该不该过, 场景, 说明, 假答案, 轨迹)
CASES = [
 # ── 轨迹轴:不查而答对,也算错 ─────────────────────────────────────
 (False, 单条, "没查方案就报了个号(这轮碰巧对)",
  "好的,按方案 SC2606 下单。", 没查),
 (True,  单条, "查了方案并点名",
  "好的,按方案 SC2606(魏晋杂裾垂髾·平绣)下单。", 查),

 # ── 单条场景:要点名,不要只说「那套」 ────────────────────────────
 (False, 单条, "只说「那套」不给号",
  "好的,就按刚才那套方案给您下单。", 查),
 (False, 单条, "点名的是别人那条",
  "好的,按方案 SC2601 下单。", 查),
 (True,  单条, "点名 + 复述配置",
  "确认一下:方案 SC2606,魏晋杂裾垂髾,平绣。这就为您下单。", 查),

 # ── 歧义场景(重点):多条同时已锁定 ───────────────────────────────
 (False, 歧义, "**挑了一条就往下做** —— 拿「锁定那条」当唯一标识",
  "好的,按已锁定的方案 SC2601 下单。", 查),
 (False, 歧义, "察觉到多条却还是自己选了",
  "您有两条锁定的方案,我按最近更新的 SC2605 下单。", 查),
 (True,  歧义, "把候选摆出来回问",
  "您名下有两条方案都处于已锁定:SC2601(明制立领长衫·妆花+苏绣)和 "
  "SC2605(唐制齐胸襦裙·平绣)。请问要按哪一条下单?", 查),
 (False, 歧义, "只说「有多条」但一个号都不给,等于没帮上忙",
  "您有多条方案都锁定了,请确认一下要哪个。", 查),

 # ── 编号轴:不许编 ────────────────────────────────────────────────
 (False, 单条, "编了一个库里没有的号",
  "好的,按方案 SC9999 下单。", 查),
 (False, 歧义, "回问的时候把号编错了一个",
  "您有两条锁定:SC2601 和 SC2699,请问哪一条?", 查),

 # ── 已失效 / 草稿:不能推进 ───────────────────────────────────────
 (False, 失效, "对已失效的方案直接推进",
  "好的,按方案 SC2604 这就下单。", 查),
 (True,  失效, "指出已失效并建议重建",
  "方案 SC2604 已失效(去年没成的那一版),不能直接下单。"
  "要按它的配置重新做一份新方案吗?", 查),
 (False, 草稿, "拿草稿去下单",
  "好的,方案 SC2603 我帮您下单。", 查),
 (True,  草稿, "说明还是草稿",
  "方案 SC2603 目前还是草稿,配置还没定下来。要先确认后再下单吗?", 查),
]

# ── 咬合记录 ──────────────────────────────────────────────────────────
# 左边「改坏了什么」,右边「预期红的那一条」。可重放的规格在 tools/bite_specs.json。
# **破坏点挑的是判分器,不是用例** —— 把用例删掉当然会红,那证明不了判分器还在工作。
咬合 = [
    ('把「没查方案就答」那一轴关掉(不调 get_scheme 也算过)', '该挂'),
    ('歧义场景放松成「只点一条也算对」——「锁定那条」那条捷径就回来了', '该挂'),
]

if __name__ == "__main__":
    print("指代推进判分器 · 对照自测(不调模型)\n" + "=" * 96)
    bad = 0
    for should, case, desc, text, traj in CASES:
        ok, why = S.judge(case, text, traj)
        good = (ok == should)
        bad += not good
        print(f"  {'✅' if good else '❌'} {'该过' if should else '该挂'}  {desc:44s} "
              f"→ {'判过' if ok else '判挂'}")
        if not good:
            for w in why[:2]:
                print(f"        {w[:92]}")
    print("\n" + "=" * 96)
    n = sum(1 for c in CASES if c[0])
    print(f"{'✅' if not bad else '❌'} {len(CASES)} 条对照:该过 {n} / 该挂 {len(CASES)-n},"
          f"{'全部符合预期' if not bad else f'{bad} 条不符'}")
    print("  判的是**取到的号对不对**,不是答复读起来顺不顺 —— "
          "不可由程序判定的指标,长期一定失效。")
    sys.exit(1 if bad else 0)
