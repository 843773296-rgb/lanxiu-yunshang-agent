# 这儿漏掉了它:`档("免运费")` 返回 None,而 None 的意思是「它说了个枚举外的词」。
# > **一条写着「我现读」的注释,和一份真的现读的代码,在那一行上长得一模一样。**
# 现在 1 档 = 枚举里**既不是「只回访」、又不出钱**的那几种 —— 加一种自动跟上。
def _给东西那一族():
    return tuple(x for x in R.处理方式
                 if x != "只回访" and x not in R.出钱的处理方式)


def 档(方式):
    """这个处理方式在代价上排第几档。不认识的返回 None(算答错,不算 0)。"""
    方式 = str(方式 or "").strip()
    if 方式 == "只回访":
        return 0
    if 方式 in _给东西那一族():
        return 1
    if 方式 == "部分退款":
        return 2
    if 方式 == "全额退款":
        return 3
    return None


