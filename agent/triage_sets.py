def 边界(今天=None):
    """返回 (训练止, 验证止),两个 ISO 日期字符串。

    ⚠️ **口径模块不自己取当前日期**那条规矩在这儿不适用,
    因为这不是口径判定,是**夹具的切点**;而且它取的是**世界的今天**
    (`worldclock.今天()`,从库里读、不从时钟读),不是机器时钟。
    """
    import datetime as _dt
    if 今天 is None:
        import worldclock
        今天 = worldclock.今天()
    if not isinstance(今天, _dt.date):
        今天 = _dt.date.fromisoformat(str(今天)[:10])
    return (str(今天 - _dt.timedelta(days=训练止偏移)),
            str(今天 - _dt.timedelta(days=验证止偏移)))

