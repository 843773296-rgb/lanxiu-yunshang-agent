#        套        题数   人工小额档   上限(×1.5)
#        训练集     67       48         72    ← 比题数还大
#        验证集     46       32         48    ← 比题数还大
#        测试集     38       27         40    ← 比题数还大
#
#    测试集只有 38 道题而上限是 40 —— **模型把每道题都答「送保养」也过得了**。
#    > **一条不可能违反的线,和一条没有线,效果一样。**
#    > 这和「漏报 ≤5% 量不出来」是同一个毛病的**镜像**:那条达不到,这条碰不到。
#    根因不是裁定错了:1.5 这个倍数是在「小额档 = 优惠券」(19/151,一成多)
#    的时候定的,**倍数没动,而它乘的那个底数大了 5 倍**(小额档现在占七成)。
# ③ **2026-10-12 换成逐条判**(裁定采纳了开发的建议,并给了一个硬数)。
#
# ⚠️ **①② 那两条线已经退场,不和新线并存。** 退场原因要留着:
# 小额档改成「送保养 + 免次改衣」之后底数占到七成,乘 1.5 就顶穿了总题数。
#
# ## 现在的线(逐条判,和漏报那条同一个形状)
#
# **人工判「只回访」,而 AI 建议送东西(送保养 / 免次改衣 / 免运费)—— ≤ 2 道。**
#
# 📌 **来路,逐条分清:**
# · **换成逐条判 + 上限 2 道** —— 并行会话 2026-10-12 **转述**用户的裁定
#   (原话「同意,最多 2 道」)。依据:测试集里人工判「只回访」的有 7 道,
#   2 道约等于三分之一;小额补偿成本不高,偶尔多给能接受,
#   **而超过一半就说明 AI 偏大方,不能上线**。
#   ✅ **2026-10-12 用户本人亲口确认过**(先经并行会话转述,等本人点头才改这行标注)。
# · **「只看测试集」** —— 裁定里说的:这个 2 是对着独立测试集那 7 道说的。
#   训练集 / 验证集是用来调方案的,**报这个数可以,不拿它判过不过**。
#   (按比例套到各套题上是**另一个口径** —— 那会是**开发建议**,不是裁定的内容,
#    所以这儿不做。)
#
# ## 为什么这个形状量得动,而上一个量不动
#
# 上一个的分母是**整套题**(38 道),所以上限天然接近总数;
# 这一个的分母是**「人工判只回访」那几道**(测试集 7 道)——
# 一个模型只要在那 7 道里多给 3 次就破线。**逐条可判、不依赖样本量**,
# 和漏报那条零容忍用的是同一个手法。
小额档上限 = 2            # 道。**用户 2026-10-12 亲口拍的数**;只对测试集
小额档样本下限 = 3        # 「人工判只回访」的题少于这么多 → 报「验不动」,不报通过
验收看哪一套 = "测试集"


def 小额档吗(方式):
    """这个处理方式算不算小额档。口径在 `knowledge/rating`,这儿不抄。"""
    import rating as _R
    return str(方式 or "").strip() in _R.小额档处理方式


def 判一题(题, 模型档, 模型文本=""):
    """一道题的判定。返回 dict,**每一项都说出是哪条线**。

    模型档   模型建议的处理方式(字符串)。认不出来的档算 None ——
             **不算 0 档**:「它说了个枚举外的词」和「它建议只回访」是两件事。
    """
    人 = 题["人工档位"]
    机 = 档(模型档)
    出 = dict(包裹=题["包裹"], 题型=题["题型"], 人工=题["人工档"], 模型=模型档,
              人工档位=人, 模型档位=机, 枚举外=(机 is None))
    # ① 跨档漏报:人工落在退款档,而模型给得比它轻
    #    两句业务原话(「人工出钱 vs AI 不出钱」+「人工全额 vs AI 部分」)
    #    在优惠券去掉之后**正好塌成这一句** —— 原来那两句之间有个夹缝:
    #    「人工部分退款、AI 建议优惠券」两句都不管(优惠券出钱,第一句不算;
    #    人工不是全额,第二句不算)。优惠券一去,夹缝自己没了。
    出["跨档漏报"] = bool(人 is not None and 人 >= 退款档 and (机 is None or 机 < 人))
    # ② 误报 · 出钱档:人工没退款,而模型建议退款
    出["出钱档误报"] = bool(人 is not None and 人 < 退款档 and 机 is not None and 机 >= 退款档)
    # ③ 诱导题另判「有没有顺着那个错前提滑下去」—— 真值相同,但多这一条
    出["顺着诱导滑了"] = bool(题["题型"] != "正向" and (出["跨档漏报"] or 出["出钱档误报"]))
    # ⚠️ **还有一个夹缝,业务两条线都没覆盖它** ——
    # 「人工给部分退款,而模型建议全额退款」:
    # · 漏报那条线只管**给得更轻**的方向,这一条是给得更重;
    # · 误报那条线的原话是「**人工没退款**而 AI 建议退款」,而人工已经退款了。
    # 于是它**从两条线之间漏下去**,一条都不算。
    # 而启用闸文档自己写过「**全额和部分金额同样差得大**」—— 那句话是用来
    # 把漏报方向的 部分↔全额 算进跨档的,照同一个理由,反方向也该算。
    #
    # **但这是业务该拍的,不是我该自己补的。** 所以这儿只做一件事:
    # **把它数出来、报出来**,不计入任何过关线。
    # > 一个「业务定了不算」的分歧,和一个「没人想到过」的分歧,
    # > **在一份只报两条线的成绩单上长得一模一样** —— 分开它们的只有这一列。
    出["出钱档内往上跨"] = bool(人 is not None and 机 is not None
                                and 人 >= 退款档 and 机 > 人)
    出["判对了档"] = bool(机 is not None and 人 is not None and 机 == 人)
    return 出


def _小额档线(判们, 套=None):
    """**人工判「只回访」而 AI 建议送东西的条数 ≤ 上限**(逐条判)。

    ⚠️ 两种情况**不报「过」**,报 None 带一句状态 —— 和当初报「悬空」同一个处理:
    · 不是测试集(验收只看测试集,其余只报数);
    · 「人工判只回访」的题太少 —— **样本太少这条线验不动**,
      而「验不动」和「通过」在一个 ✅ 上长得一模一样。
    """
    只回访的 = [x for x in 判们 if x["人工"] == "只回访"]
    犯 = [x for x in 只回访的 if 小额档吗(x["模型"])]
    出 = dict(线=f"人工判「只回访」而 AI 建议送东西 ≤ {小额档上限} 道",
              这条线在几条题上判的=len(只回访的), 条数=len(犯),
              明细=[x["包裹"] for x in 犯],
              谁定的=f"逐条判 + 上限 {小额档上限} 道:**用户 2026-10-12 拍**"
                     f"(先经并行会话转述,**用户本人确认过**);"
                     f"只看{验收看哪一套} —— 裁定里说的",
              退场的旧线="「AI 建议小额的条数 ≤ 人工 × 1.5」—— 小额档改成送保养加免次改衣"
                         "之后底数占到七成,乘 1.5 顶穿了总题数,**一条都不可能违反**")
    if 套 is not None and 套 != 验收看哪一套:
        出.update(过=None, 状态=f"只报数,不判过不过 —— 验收只看{验收看哪一套}"
                                f"(训练集 / 验证集是用来调方案的)")
        return 出
    if len(只回访的) < 小额档样本下限:
        出.update(过=None,
                  状态=f"**样本太少,这条线验不动** —— 「人工判只回访」只有 "
                       f"{len(只回访的)} 道,下限 {小额档样本下限} 道。"
                       f"不报通过:空集合上所有性质都成立")
        return 出
    出.update(过=(len(犯) <= 小额档上限))
    return 出


def 判一轮(判们, 套=None):
    """一轮的汇总。返回 (过没过, 一份逐条说清的报告)。

    `套` 给了而且不是测试集时,小额档那条线**只报数、不判过不过**(验收只看测试集)。
    """
    漏 = [x for x in 判们 if x["跨档漏报"]]
    误 = [x for x in 判们 if x["出钱档误报"]]
    退款题 = [x for x in 判们 if x["人工档位"] is not None and x["人工档位"] >= 退款档]
    报 = {
        "题数": len(判们),
        "退款类题数": len(退款题),
        "① 跨档漏报零容忍": dict(过=not 漏, 条数=len(漏), 明细=[x["包裹"] for x in 漏],
                                 线="人工落在退款档而模型给得更轻 —— 一条都不许有",
                                 这条线在几条题上判的=len(退款题)),
        "② 误报·出钱档零容忍": dict(过=not 误, 条数=len(误), 明细=[x["包裹"] for x in 误],
                                     线="人工没退款而模型建议退款 —— 一条都不许有(用户 2026-10-12 拍)"),
        "③ 误报·小额档(逐条判)": _小额档线(判们, 套),
        # 不是一条线,是**一列登记** —— 见 `判一题` 里那段注释
        "⚠️ 登记·出钱档内往上跨(业务两条线都没覆盖)": dict(
            条数=sum(1 for x in 判们 if x["出钱档内往上跨"]),
            明细=[x["包裹"] for x in 判们 if x["出钱档内往上跨"]],
            是什么="人工给部分退款而模型建议全额退款。漏报线只管给得更轻的方向,"
                   "误报线的原话是「人工没退款」—— 两条都不管。**不计入过关,等业务拍**"),
        "判对档位": sum(1 for x in 判们 if x["判对了档"]),
        "枚举外的答案": [x["包裹"] for x in 判们 if x["枚举外"]],
    }
    三 = 报["③ 误报·小额档(逐条判)"]
    return (not 漏 and not 误 and 三.get("过") is not False), 报


def 判两轮(轮一, 轮二, 套=None):
    """**同一批至少跑两轮,两轮都 0 条跨档漏报**(用户 2026-10-12 批的补充条件)。

    为什么要两轮:这个项目实测过 —— 同一个提交、同一个模型、同一批工单连跑两轮,
    两代架构**各掉了一题,而且掉的不是同一题**。
    > **一个「真的稳」和一个「这一轮恰好对」,在单轮成绩单上长得一模一样。**
    """
    过一, 报一 = 判一轮(轮一, 套)
    过二, 报二 = 判一轮(轮二, 套)
    同 = {x["包裹"] for x in 轮一 if x["跨档漏报"]} == {x["包裹"] for x in 轮二 if x["跨档漏报"]}
    return (过一 and 过二), dict(第一轮=报一, 第二轮=报二, 两轮都过=(过一 and 过二),
                                 两轮漏的是不是同一批=同)


