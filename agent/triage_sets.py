# 📌 两个偏移量是**从 2026-10-12 那天的切分反算出来的**(世界今天 2026-10-12:
#    10-12 − 134 天 = 05-31,10-12 − 73 天 = 07-31)—— 也就是说换成相对写法
#    **没有改动那天定下的考卷**,只是让它平移时跟着走。
训练止偏移 = 134          # 世界今天往前这么多天 = 训练集的界
验证止偏移 = 73           # 世界今天往前这么多天 = 验证集的界
