def 报(记):
    n = len(记)
    print(f"\n{'=' * 72}")
    print(f"产线路跑了 {n} 道(训练集)")
    if not n:
        return
    轮总 = sum(x["跑了几轮"] for x in 记)
    取总 = sum(x["取了几轮"] for x in 记)
    每轮都取 = [x for x in 记 if x["取了几轮"] == x["跑了几轮"]]
    print(f"\n  ① **模型自己去取材料了吗**(产线和探针唯一的差别)")
    print(f"     按轮算:{取总}/{轮总} = {取总/轮总:.0%} 的调用里调了 `service_records`")
    print(f"     按题算:{len(每轮都取)}/{n} = {len(每轮都取)/n:.0%} 的题**每一轮都去取了**")
    if 取总 < 轮总:
        print(f"     {Rd}⚠️ 有 {轮总 - 取总} 轮**没去取材料就判了** ——"
              f"而那条建议和「看了材料才这么判」在页面上长得一模一样{D}")

    # ── ①甲 交付前检查扣下了几轮 —— **产线路独有的指标** ──────────────────
    # 探针测不到它(探针不走产线、不过这道检查),所以这个数只有这条路报得出来。
    # ⚠️⚠️ **旧数据没记这件事,那就明说没记,别回落成一个默认值。**
    # 第一版我写的是 `x.get("交出来几轮", x["跑了几轮"])` —— 字段缺失时
    # 回落成「全都交出来了」,于是拿 11:52 那一轮(它没记这个字段)重报,
    # 报出「**扣下 0 轮 = 0%**」,而我**亲眼在原文里看到 3 轮被扣下**。
    # > 一个「这一轮没有被扣下」和一个「这一轮的数据里没记这件事」,
    # > **在那个 0% 上长得一模一样。**
    # 而方向是最坏的那一种:默认值让旧数据看起来是**好的**。
    # (CLAUDE.md 第 7 节第 8 项原话:不符合预期的数会被查,符合预期的数会被信。)
    记了交付 = all("交出来几轮" in x for x in 记)
    if not 记了交付:
        print(f"\n  ①甲 {Y}这一轮的数据里**没记交付状态**"
              f"(2026-10-14 11:52 之前跑的)—— 这一项**报不了**,"
              f"而不是「扣下 0 轮」{D}")
        print(f"     {Y}   要这个数就重跑一轮;那一轮的原文里确实有 3 轮是"
              f"「没有作为正式答复给出」,只是当时没落成字段{D}")
    else:
        交总 = sum(x["交出来几轮"] for x in 记)
        扣了 = 轮总 - 交总
        print(f"\n  ①甲 **交付前检查扣下了几轮**(产线路独有 —— 探针不走这道检查)")
        print(f"     交出来 {交总}/{轮总};**扣下 {扣了} 轮 = {扣了/轮总:.0%}**")
    if 记了交付 and 轮总 - sum(x["交出来几轮"] for x in 记):
        状 = {}
        for x in 记:
            for st in x.get("被扣下的状态") or []:
                状[st] = 状.get(st, 0) + 1
        print(f"     扣下那几轮的最终状态:"
              f"{' / '.join(f'{k} {v}' for k, v in sorted(状.items()))}")
        _违 = {}
        for x in 记:
            for r in x["轮们"]:
                if r.get("交出来了"):
                    continue
                for c in ((r.get("为什么被扣") or {}).get("最终违规") or ["(没落这个字段)"]):
                    _违[c] = _违.get(c, 0) + 1
        print(f"     **违的是哪几条**:"
              f"{' / '.join(f'{k} {v} 次' for k, v in sorted(_违.items(), key=lambda kv: -kv[1]))}")
        print(f"     {Y}  这一项答的是「扣下率为什么两轮不一样」—— "
              f"内容类的规矩天然就抖,格式/结构类的更像是中间变了什么{D}")
        print(f"     {Y}⚠️ 被扣下的轮**没有回答可读**,所以它不进下面「判定读得出」"
              f"的分母 —— 把它算成「读不出」会让「模型定不下来」虚高{D}")

    读出 = [x for x in 记 if x["方式众数"]]
    层计 = {}
    for x in 记:
        for lv in x["读的层们"]:
            层计[str(lv)] = 层计.get(str(lv), 0) + 1
    有效题 = [x for x in 记 if x["交出来几轮"] > 0] if 记了交付 else 记
    m = len(有效题) or 1
    读出 = [x for x in 有效题 if x["方式众数"]]
    print(f"\n  ② 判定读得出来吗(**有众数**才算读得出):{len(读出)}/{len(有效题)} "
          f"= {len(读出)/m:.0%}")
    if 记了交付:
        print(f"     分母是**至少交出来一轮**的题({len(有效题)}/{n})—— "
              f"三轮全被扣下的题没有答案可读,不该算成「模型读不出」")
    else:
        print(f"     {Y}⚠️ 这一轮没记交付状态,所以分母是全部 {n} 道 ——"
              f"**里面混着「被守卫扣下」的轮**,这个数偏低,不许当成"
              f"「模型读不出的比例」{D}")
    print(f"     靠哪一层读到的(按轮):"
          f"{' / '.join(f'{k} {v}' for k, v in sorted(层计.items()))}")
    print(f"     {Y}靠「全文」那一层救回来的可信度本来就低 —— 不许和「段首」混成一个数{D}")

    print(f"\n  ③ **抖动**:同一条题跑 {记[0]['跑了几轮']} 轮,答案稳不稳")
    for 名, 键 in (("方式级(字面答案)", "方式确定度"), ("档位级(实质分歧)", "档确定度")):
        计 = {}
        for x in 记:
            计[x[键]] = 计.get(x[键], 0) + 1
        print(f"     {名}:"
              f"{' / '.join(f'{k} {计.get(k, 0)}' for k in 确定度档 if 计.get(k))}")
    同档内 = [x for x in 记 if x["方式确定度"] != "全一致" and x["档确定度"] == "全一致"]
    if 同档内:
        print(f"     {Y}其中 {len(同档内)} 道是**同档内抖动**(字面换了个说法,代价档没变)"
              f" —— 只报方式级会把它算成分歧{D}")

    print(f"\n  ④ 遮蔽:每道都独立核过,遮了几处 "
          f"{sorted({x['遮了几处'] for x in 记})}(为 0 的已跳过,不进这个分母)")
    print(f"\n  ⚠️ **不许拿这一轮算「判得对不对」** —— 这批数据的真值是**随机填的标注**"
          f"(库里有「外箱破了个角 → 全额退款」这种)。")
