#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""`select_eval` 判分器的人造对照 —— **离线、一秒钟、不花钱**。

CLAUDE.md §9⑤ 是纪律不是建议:**写完判分器先跑人造对照**。
它抓的是逻辑错(判据方向反了、恒真、恒假),抓不到词汇错 ——
那要等真跑之后把真实说法钉回来。

## 这一份要钉死的那几件

| 要钉的 | 不钉的下场 |
|---|---|
| 必需工具**全部**都要在(不是至少一个) | 和 `tool_eval` 的 `any` 语义混成一套,而两者在判分器里长得一样 |
| **禁调不参与第一层判定** | 第一版拿它当判据,19/20 全红 —— 那不是基线差,是没有分辨力 |
| 候选集给全了 → 召回必过 | 一个恒为假的判据,和一个正确算出假的,在返回值上长得一样 |
| 候选集给空了 → 召回必挂 | **空集合上所有性质都成立** —— 要确认它不是「扫不到就通过」 |
| 短名/全名都认 | 候选集可能带 `mcp__xx__` 前缀,认不出等于全漏 |

## 咬合过的

把 `量一题` 里的 `漏 = [t for t in 必需 if t not in 短]` 改成
`any(t in 短 for t in 必需)`(也就是退回 `tool_eval` 那种「至少一个」),
下面第 2 条当场红 —— **这一份确实在量「全部」这个语义**。
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "backend"))
import select_eval as SE

过, 挂 = [], []


def ck(名, 真, 补=""):
    print(f"  {'✅' if 真 else '❌'} {名}{('  ' + str(补)[:120]) if 补 else ''}")
    (过 if 真 else 挂).append(名)


def main():
    print("select_eval 判分器 · 人造对照(离线,不花钱)")
    print("=" * 84)

    # 挑一道**必需有两个**的题 —— 「全部 vs 至少一个」只在这种题上分得开
    两个 = [c for c in SE.案 if len(c[3]) >= 2]
    if not 两个:
        print("❌ 题集里没有一道「必需 ≥ 2 个工具」的题 —— "
              "那么「全部都要在」这个语义**无法被验证**,"
              "而它和「至少一个」在判分器里长得一模一样")
        return 1
    双, 单 = 两个[0], next(c for c in SE.案 if len(c[3]) == 1)
    print(f"  (拿 {双[0]} 验「全部」语义:必需 {双[3]};拿 {单[0]} 验单个)")

    # ① 候选集给全 → 过
    ok, bad = SE.量一题(双[0], 双[3] + 双[4] + ["无关工具"])
    ck("① 必需全给 → 召回过(对照:这个判据不是恒为假)", ok, bad)

    # ② **只给一个必需 → 必须挂**。这一条钉的是「全部」语义
    ok, bad = SE.量一题(双[0], [双[3][0]])
    ck("② 只给一个必需 → 挂(**全部都要在**,不是至少一个)",
       (not ok) and any("召回" in x for x in bad), bad)

    # ③ 候选集给空 → 必须挂(**空集合上所有性质都成立**)
    ok, bad = SE.量一题(单[0], [])
    ck("③ 候选集为空 → 挂(扫不到不是通过)", not ok, bad)

    # ④ 禁调也在候选集里 → **第一层照样过**
    ok, bad = SE.量一题(单[0], 单[3] + 单[4])
    ck("④ 禁调也在候选集里,第一层**照样过**(它量的是模型,不是筛选器)", ok, bad)
    混 = SE.混进来的(单[0], 单[3] + 单[4])
    ck("④ 而「混进来的」这个**辅助数**确实数到了", set(混) == set(单[4]), 混)

    # ⑤ 全名/短名都认
    ok, _ = SE.量一题(单[0], [f"mcp__shop__{单[3][0]}"])
    ck("⑤ 带 mcp__ 前缀的全名也认得(认不出等于全漏)", ok)

    # ⑥ 一组的汇总:分子分母都要有,而且比例不自己算
    r = SE.量一组(lambda 角色, q: [], "空筛选器")
    ck("⑥ 空筛选器 → 召回 0/全部(不是「没扫到所以通过」)",
       r["召回过"] == 0 and r["共"] == len(SE.案), f"{r['召回过']}/{r['共']}")
    ck("⑥ 候选集大小一起报(一个比例不带分母,和算错的比例长得一样)",
       r["候选均"] == 0 and r["候选最大"] == 0, (r["候选均"], r["候选最大"]))

    r2 = SE.量一组(lambda 角色, q: [c for x in SE.案 for c in x[3]], "全给筛选器")
    ck("⑥ 全给筛选器 → 召回全过(对照:这条判据两个方向都动)",
       r2["召回过"] == r2["共"], f"{r2['召回过']}/{r2['共']}")

    # ⑦ 动态筛选**不许有默认值** —— 静默回落是这个项目栽过的坑
    try:
        SE.筛选器_动态()
        ck("⑦ 动态筛选未实现时当场抛(不静默回落到按角色)", False, "它没抛!")
    except NotImplementedError as e:
        ck("⑦ 动态筛选未实现时当场抛(不静默回落)", "还没做" in str(e))
    except Exception as e:
        ck("⑦ 动态筛选未实现时当场抛", False, f"抛的是 {type(e).__name__}")

    # ⑧ 题集自己的性质:每一对都要有两个方向
    必需过的 = {}
    for cid, q, 角色, 必需, 禁调, _w in SE.案:
        for t in 必需: 必需过的.setdefault(t, []).append(cid)
    双向 = [t for t, cs in 必需过的.items()
            if any(t in c[4] for c in SE.案)]
    ck("⑧ 至少 8 个工具既当过「必需」也当过「禁调」(= 真的是双向出题)",
       len(双向) >= 8, f"{len(双向)} 个:{sorted(双向)[:6]}…")

    print("\n" + "=" * 84)
    print(f"过 {len(过)} · 挂 {len(挂)}")
    for x in 挂: print("   ❌", x)
    return 1 if 挂 else 0


if __name__ == "__main__":
    sys.exit(main())
