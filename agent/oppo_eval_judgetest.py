 (True, None, "「不给成单概率」这句话本身 —— 「不许说 X」里必然含 X,没有数字就不挂",
  答("这里不给成单概率,只给依据:她两次提到月白。", 商机()), 逐字稿, True),
 # ── 该挂的 ──────────────────────────────────────────────────────────
 (False, "格式", "没交 JSON —— 不从正文里抠", "客户想要月白色的,是商机,下一步推白色马面裙。", 逐字稿, True),
