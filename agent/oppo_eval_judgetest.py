坏 = 0
print("商机研判判分器 · 对照(不调模型)\n" + "-" * 96)
for 该过, 类, 说明, 回答, 稿, 标注 in CASES:
    why = E.判(回答, 稿, 客户, 标注)
    if 该过:
        对 = not why
    else:
        # 挂了还不够,**得挂在对的那一类上** —— 挂错类说明判据串了,成绩单上看不出来
        对 = any(w.startswith(类 + ":") for w in why)
    坏 += 0 if 对 else 1
    print(f"  {'✅' if 对 else '❌'} {'该过' if 该过 else '该挂'} {说明[:60]}")
    if not 对:
        for w in why or ["(判分器什么都没说)"]:
            print(f"        理由:{w[:88]}")

