def 跑挂了的(行们, 理由="why"):
    """挑出「**跑挂了**」的那些行 —— 调用本身失败(认证、网络、超时),一道题都没真答。

    ⚠️⚠️ **跑挂了 ≠ 答错了,而它们在 `passed=False` 上长得一模一样。**
    `check.sh` 早就把这两件事分开了(「崩了」和「判定不过」,还写着
    「崩了的那几条一条都没验过,先修崩的」)—— **门禁分得开,评测一直分不开。**

    代价有实测:10-16 和 10-17 两晚凭据失败(403),18 套评测每一套都 100% 全挂,
    **而每一题都被写成 `passed=False`**。夜跑基线里 98 轮有 38 轮是整轮全挂、
    525 题次是跑挂、只有 86 题次是真答错 —— **失败里 86% 其实是跑挂了**。
    """
    出 = []
    for r in 行们:
        v = r.get(理由)
        for w in (v if isinstance(v, (list, tuple)) else [v]):
            if w and "跑挂了" in str(w):
                出.append(r)
                break
    return 出


