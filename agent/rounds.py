def 跑(一轮, 轮数=2, 确定性=False, 日志=print):
    """跑 `轮数` 轮,每轮返回 `{用例名: 过没过}`。

    `确定性=True` 时只跑一轮并注明原因 —— 纯规则的东西跑两轮是白跑。
    """
    if 确定性:
        日志("  (确定性,跑一轮就够 —— 结果不会变,跑两轮是白跑)")
        return [一轮()]
    出 = []
    for i in range(1, 轮数 + 1):
        日志(f"  【第 {i} 轮】")
        出.append(一轮())
    return 出


def 抖动(多轮):
    """哪几个用例在轮与轮之间翻了面。返回 (翻了的用例名, 每轮通过数)。"""
    if not 多轮:
        return [], []
    键 = set().union(*(set(x) for x in 多轮))
    翻 = [k for k in sorted(键, key=str)
          if len({r.get(k) for r in 多轮 if k in r}) > 1]
    return 翻, [sum(1 for v in r.values() if v) for r in 多轮]


# 失败原因分几类 —— **因为下一步动作完全不同**(见 make-a-check-that-holds ③)。
# 2026-09-21 实测:`growth_eval` 两轮里 G01/G03/G04 三题翻面,而原因是两类:
#   G01/G04  挂在「没提到 统计(同义:分布/个体差/±/平均)」这种**同义词表**上
#            → 判据太吃措辞,**该改判据**
#   G03      `轨迹:实际调了 [无]` —— 模型**一个工具都没调**,14.6 秒答完
#            (别轮要 50 秒、调 2 个)。这不是答得不好,是这一次没查数据就答了
#            → 判据是对的,抓到了真问题,**该改提示词**
# 两边方向相反,而「抖动 3 题」这一个数字看不出区别。
类别 = [
    ("轨迹", "轨迹", "**模型这一次的行为变了**(该调的工具没调 / 多调了)—— "
                     "这类翻面是**真信号**,判据没问题,要看的是提示词和工具描述"),
    ("跑挂", "跑挂了", "这一轮根本没跑完(异常)—— 先看是不是环境问题,别当能力波动"),
    ("内容", "内容", "挂在**说法**上(没提到某个同义词)—— 这类翻面**多半是判据太吃措辞**,"
                     "中文同义写法接近无限,枚举必输(CLAUDE.md 栽过十次)"),
]


def 分类(理由们):
    """一条失败属于哪一类。**认不出来就说认不出来**,不硬塞进某一类。"""
    文 = " ".join(理由们 or [])
    for 名, 词, _说 in 类别:
        if 词 in 文:
            return 名
    return "认不出"


def 报(多轮, 基线通过数=None, 名="", 日志=print, 原因=None,
       基线来路=None, 本轮来路=None):
    """把「跑了几轮、抖了几题、能不能下结论」一次说清。

    `基线通过数` 给了才比得了 —— 没有基线时只报抖动,**不编一个结论出来**。

    ## 为什么 `基线来路` 是必需的,而且是**拒收**不是提醒

    2026-09-22 查出来:`agent/evalrec.py` 里的来路章(供应商/模型/代码)
    **每条记录都忠实地盖上了**,而判定函数也写全了 ——
    **全仓库没有一处比较读过它们**。一个「写好了但没接上」的防护,
    和没有这个防护,在文件上长得一模一样。

    所以这里不加提醒(提醒会被忽略,而且忽略了看不出来),改成:
    **给了分数却不说来路,这个基线就不用。** 想用就得把来路一起递进来 ——
    递不出来,本身就说明那份基线不知道是谁跑的。
    """
    翻, 各轮 = 抖动(多轮)
    n = len(多轮[0]) if 多轮 else 0
    头 = f"{名} · " if 名 else ""

    if len(多轮) < 2:
        日志(f"  {Y}⚠ {头}**只跑了一轮,不能下结论**{D} —— "
             f"{各轮[0] if 各轮 else 0}/{n}。"
             f"这个项目为「拿单轮结果下结论」栽过五次,最近一次是同一天两轮之间"
             f"自己翻了面。要下结论请跑两轮。")
        return False

    日志(f"  {头}各轮通过:{' / '.join(f'{x}/{n}' for x in 各轮)}")
    if 翻:
        日志(f"  ⚠️ **{len(翻)} 题在轮与轮之间翻了面**:{'、'.join(map(str, 翻))} —— "
             f"这几题的结果本身就是抽样,别拿它们下结论")
    else:
        日志(f"  ✅ 各轮逐题一致(0 题翻面)—— 这一批的结果是稳的")

    # 翻面的按原因分开数 —— 一边该改判据、一边该改提示词,方向相反
    if 翻 and 原因:
        桶 = {}
        for k in 翻:
            # 取它**失败那几轮**的理由
            理由 = [w for i, r in enumerate(多轮) if not r.get(k)
                    for w in ((原因[i] if i < len(原因) else {}) or {}).get(k, [])]
            桶.setdefault(分类(理由), []).append(k)
        日志(f"  翻面的 {len(翻)} 题按原因分:")
        for 名类, _词, 说 in 类别 + [("认不出", "", "理由里认不出类型 —— 去看原始输出")]:
            if 名类 in 桶:
                ks = 桶[名类]
                日志(f"     · **{名类}类** {len(ks)} 题({'、'.join(map(str, ks[:6]))}"
                     + (f" ……还有 {len(ks)-6} 题(共 {len(ks)})" if len(ks) > 6 else "")
                     + f"):{说}")
        if "轨迹" in 桶:
            日志(f"  {Y}⚠ 有**轨迹类**翻面 —— 那不是判据的问题,是模型这几次行为不一致。"
                 f"改判据修不了它{D}")

    if 基线通过数 is None:
        日志(f"  ℹ️ 没给基线,只报抖动 —— **不比就不编结论**")
        return not 翻

    # ── 基线的来路:不说清就不用 ────────────────────────────────────
    if 基线来路 is None:
        日志(f"  {Y}⚠ 给了基线 {基线通过数},却**没说这个基线是谁跑的** —— 不拿它比。{D}\n"
             f"     供应商 / 模型换了,分数照样能相减,而**两者在文件里长得一模一样**"
             f"(那次 DeepSeek 的数覆盖了 Claude 的六套基线)。"
             f"要比就把那条记录的来路一起递进来:`基线来路={{供应商,模型,代码}}`")
        return not 翻
    try:
        import evalrec
        能比, 说 = evalrec.基线能不能比(基线来路, 本轮来路)
    except Exception as e:                       # evalrec 拿不到时**不假装判过**
        能比, 说 = False, f"判不了基线可不可比({type(e).__name__}: {e})—— **这不叫可比**"
    日志(f"  基线来路:{说}")
    if not 能比:
        return not 翻

    版本差 = abs(各轮[-1] - 基线通过数)
    轮间差 = len(翻)
    日志(f"  轮间抖动 {轮间差} 题;和基线差 {版本差} 题")
    # ⚠️ **「没抖也没变」和「差别被抖动淹掉了」是两件事,而它们都满足 `轮间差 >= 版本差`。**
    # 2026-09-21 识图评测接上多轮时当场撞到:两轮 6/6、基线 6/6,
    # 于是打印「这个对比说明不了任何事」—— 而那一跑其实是这套评测最干净的一次。
    # 两边的下一步动作正好相反:一边是「加题、多跑几轮」,一边是「没变化,往下用」。
    # (这正是本项目反复栽的那个形状:两个要触发相反动作的状态,表示上长得一模一样。)
    if 轮间差 == 0 and 版本差 == 0:
        日志(f"  {G}✅ 两轮逐题一致,且和基线一模一样 —— **没有变化可报**{D}"
             f"(n={n}:这是「**没测出差别**」,不是「证明了没差别」——"
             f"要那个结论得加题)")
        return True
    if 轮间差 >= 版本差:
        日志(f"  {Y}⚠ **轮间抖动不小于版本差 —— 这个对比说明不了任何事。**{D} "
             f"想分辨出这么小的差,要么加题,要么多跑几轮")
        return False
    日志(f"  {G}✅ 版本差大于轮间抖动,这个对比有意义{D}(但 n={n},只能说方向)")
    return True


# ── 共用收尾:跑几轮 → 取基线并判来路 → 报告 → 部分不写 ────────────────
#
# 2026-09-22 抽出来。这一段在 growth / vision / liability / skill 四个评测里
# **各抄了一遍**,而每抄一遍都漏过东西:
#   · growth 挡了「部分覆盖」的写,却没挡「部分比较」的比
#   · vision / liability 当初都没挡部分覆盖(三处各修一次,见 partial_write_check)
#   · 四处取基线,**没有一处判过来路**,直到 `报()` 开始拒收
# 剩下十个评测要是再各抄一遍,就是第十四份 —— **修一处不等于修一类**,
# 而一段逻辑有十四份拷贝,就注定有一份是漏的。
#
# 各评测只交出「跑一轮」:返回这一轮的明细行(每行有用例键、过没过、理由)。
# 其余的 —— 几轮、基线、来路、部分不写、报告 —— 都在这里,**只写一次,咬合一次**。

def _取基线(结果文件, 键, 过, 本轮键, 全集数, 本轮数, 日志=print):
    """从 git 里上一版结果文件取基线。**不可比就不交出去**,并说清哪一样不可比。

    返回 (基线通过数, 基线来路);不可比时两个都是 None。
    """
    import json, subprocess
    根 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    相对 = os.path.relpath(os.path.abspath(结果文件), 根)
    try:
        t = subprocess.run(["git", "show", f"HEAD:{相对}"], capture_output=True,
                           text=True, cwd=根).stdout
    except Exception:
        return None, None
    # 两种格式都认:jsonl(一行一条)和整份 JSON 数组(agent/tool_eval 写的是后者)。
    # ⚠️ 只按行解析的话,JSON 数组**一行都读不出来**,于是安静地报「没给基线」——
    # 而「这份评测没有基线」和「这份基线我读不懂」,在报告上长得一模一样。
    try:
        整份 = json.loads(t) if t.strip() else None
    except Exception:
        整份 = None
    候选 = 整份 if isinstance(整份, list) else []
    if not 候选:
        for l in t.splitlines():
            try:
                候选.append(json.loads(l))
            except Exception:
                continue
    行 = [x for x in 候选 if isinstance(x, dict) and 键 in x]   # 跳过指纹头之类没有用例键的行
    if not 行:
        return None, None
    if 本轮数 < 全集数:
        日志(f"  ℹ️ 这次只跑了 {本轮数}/{全集数} 题 —— **不拿基线比**(分母都不一样)")
        return None, None
    量过 = {x[键] for x in 行}
    缺, 多 = set(本轮键) - 量过, 量过 - set(本轮键)
    if 缺 or 多:
        # 比的是**哪几道**不是**几道**:删一道又加一道会正好对上
        日志(f"  ℹ️ 基线和现在的题对不上,**不拿它比** —— "
             + (f"它没量过 {sorted(map(str, 缺))[:6]}" if 缺 else "")
             + ("；" if 缺 and 多 else "")
             + (f"它量过但现在没有的 {sorted(map(str, 多))[:6]}" if 多 else ""))
        return None, None
    n = sum(1 for x in 行 if x.get(过))
    日志(f"  (基线取自 git 里上一版结果:{n}/{len(行)})")
    return n, {k: 行[0].get(k) for k in ("供应商", "模型", "代码")}


def 跑并收尾(一轮, *, 名, 结果文件, 全集数, 本轮数, 键="id", 过="passed", 理由="why",
             写=None, 轮数=None, 日志=print):
    """跑 `轮数` 轮(默认 2;设了 `LANXIU_一轮` 就 1),然后把收尾一次做完。

    `一轮()` 返回这一轮的明细行列表。`写(结果文件, 行们)` 默认走 `evalrec.dump`;
    带指纹头之类的评测传自己的写法进来。

    返回 (最后一轮的明细, 每轮 {键: 过没过})。
    """
    if 轮数 is None:
        轮数 = 1 if os.environ.get("LANXIU_一轮") else 2
    多, 因, 最后 = [], [], []
    for i in range(轮数):
        if 轮数 > 1:
            日志(f"  【第 {i + 1} 轮】")
        行们 = 一轮() or []
        多.append({r[键]: bool(r.get(过)) for r in 行们})
        # 理由有的评测是列表、有的是一句字符串(chat_eval 的 `judge`)——
        # 字符串直接 list() 会被拆成一个个字,分类就全认不出了
        因.append({r[键]: ([r[理由]] if isinstance(r.get(理由), str)
                           else list(r.get(理由) or [])) for r in 行们})
        最后 = 行们
    基线, 来路 = _取基线(结果文件, 键, 过, [r[键] for r in 最后], 全集数, 本轮数, 日志)
    报(多, 基线通过数=基线, 名=名, 原因=因, 基线来路=来路, 日志=日志)
    # ⚠️ **只跑了一部分时不许覆盖结果文件** —— 「跑一部分」和「跑全部」
    # 写的是同一个文件,而文件上一点看不出区别。
    if 本轮数 < 全集数:
        日志(f"  ⚠️ 这次只跑了 {本轮数}/{全集数} 题,**不写结果文件** —— "
             f"部分结果覆盖完整基线之后,文件上看不出来。要更新基线请跑全部。")
    else:
        if 写 is None:
            import evalrec
            写 = evalrec.dump
        写(结果文件, 最后)
        日志(f"  明细写到 {结果文件}")
    return 最后, 多


def 自测():
    """咬合:三种情形各自都要说对话。"""
    import io, contextlib
    坏 = []

    # 对照用例用的来路:同供应商同模型、代码不同(**版本对比的常态**)
    _来 = {"供应商": "claude", "模型": "haiku", "代码": "aaa"}
    _本 = {"供应商": "claude", "模型": "haiku", "代码": "bbb"}

    def 抓(f):
        b = io.StringIO()
        with contextlib.redirect_stdout(b):
            r = f()
        return r, b.getvalue()

    # ① 只跑一轮 → 必须明说不能下结论
    _, out = 抓(lambda: 报([{"A": True, "B": True}]))
    if "不能下结论" not in out:
        坏.append("只跑了一轮要明说不能下结论")
    # ② 抖动 ≥ 版本差 → 必须明说比不了
    _, out = 抓(lambda: 报([{"A": True, "B": False}, {"A": False, "B": False}],
                           基线通过数=1, 基线来路=_来, 本轮来路=_本))
    if "说明不了任何事" not in out:
        坏.append("抖动大于版本差时要明说比不了")
    # ③ 稳定且版本差大 → 可以说有意义
    _, out = 抓(lambda: 报([{"A": True, "B": True, "C": True}] * 2, 基线通过数=0,
                           基线来路=_来, 本轮来路=_本))
    if "这个对比有意义" not in out:
        坏.append("稳定且版本差大时该说有意义")
    if "0 题翻面" not in out:
        坏.append("没翻面时要明说 0 题翻面(不然看不出是稳的还是没比)")
    # ⑤ 翻面按原因分类:轨迹类和内容类要分开说
