"""跑几轮、抖多少 —— **单轮的数和能下结论的数,在报告上长得一模一样。**

    import rounds
    多 = rounds.跑(lambda: 跑一轮(), 轮数=2)     # 返回每轮的 [{case: 过没过}]
    print(rounds.报(多))                          # 打印抖动,并说清能不能下结论

## 这条是怎么来的

这个项目为「拿单轮结果下结论」栽过**五次**:

  1. 评测跑的模型和产品不一致
  2. 单跑一次就断定描述改坏了
  3. 13/15 就说装 236 个技能没影响
  4. 三代对比表写单轮的 6/6/6 —— 而那是三次抛硬币都正面
  5. 2026-09-21 成长评测:基线 7/8 → 第 1 轮 5/8(看着退两题)→ 第 2 轮 6/8,
     **G04 在同一天的两轮之间自己翻了面**

第五次差一点就报出一个不存在的退步,然后去查一个不存在的退化。

> **轮间抖动 ≥ 版本差,这个对比就说明不了任何事。**
> 这句话是 `backend/opportunity_eval.py` 先写出来的,这里把它抽出来给大家用。

## 一条容易做过头的:不是所有东西都要跑两轮

`opportunity_eval` 做对了一件事 —— **规则版跑一轮就够,因为它是确定性的**。
一刀切跑两轮,会让确定性的那一半白白翻倍。判据是「**这一轮的结果会不会变**」:
调模型的会变,纯规则的不会。

## 为什么两轮就够(以及它不够在哪)

两轮只能回答一个问题:**这个差,会不会被抖动淹掉**。
它**不能**给出「真实通过率是多少」——那要几十轮。
所以 `报()` 只说「能不能比」,不说「到底是多少」,**这是故意的**:
一个报了置信区间的两轮结果,比一个只说「比不了」的更危险。
"""
import os

G, R, Y, D = "\033[32m", "\033[31m", "\033[33m", "\033[0m"

咬合 = [
    ("把「轮间抖动 ≥ 版本差 → 说明不了任何事」那一支去掉", "抖动大于版本差时要明说比不了"),
    ("把轮数改成 1 而报告照样下结论", "只跑了一轮要明说不能下结论"),
]


def 跑(一轮, 轮数=2, 确定性=False, 日志=print):
    """跑 `轮数` 轮,每轮返回 `{用例名: 过没过}`。

    `确定性=True` 时只跑一轮并注明原因 —— 纯规则的东西跑两轮是白跑。
    """
    if 确定性:
        日志("  (确定性,跑一轮就够 —— 结果不会变,跑两轮是白跑)")
        return [一轮()]
    出 = []
    for i in range(1, 轮数 + 1):
        日志(f"  【第 {i} 轮】")
        出.append(一轮())
    return 出


def 抖动(多轮):
    """哪几个用例在轮与轮之间翻了面。返回 (翻了的用例名, 每轮通过数)。"""
    if not 多轮:
        return [], []
    键 = set().union(*(set(x) for x in 多轮))
    翻 = [k for k in sorted(键)
          if len({r.get(k) for r in 多轮 if k in r}) > 1]
    return 翻, [sum(1 for v in r.values() if v) for r in 多轮]


def 报(多轮, 基线通过数=None, 名="", 日志=print):
    """把「跑了几轮、抖了几题、能不能下结论」一次说清。

    `基线通过数` 给了才比得了 —— 没有基线时只报抖动,**不编一个结论出来**。
    """
    翻, 各轮 = 抖动(多轮)
    n = len(多轮[0]) if 多轮 else 0
    头 = f"{名} · " if 名 else ""

    if len(多轮) < 2:
        日志(f"  {Y}⚠ {头}**只跑了一轮,不能下结论**{D} —— "
             f"{各轮[0] if 各轮 else 0}/{n}。"
             f"这个项目为「拿单轮结果下结论」栽过五次,最近一次是同一天两轮之间"
             f"自己翻了面。要下结论请跑两轮。")
        return False

    日志(f"  {头}各轮通过:{' / '.join(f'{x}/{n}' for x in 各轮)}")
    if 翻:
        日志(f"  ⚠️ **{len(翻)} 题在轮与轮之间翻了面**:{'、'.join(翻)} —— "
             f"这几题的结果本身就是抽样,别拿它们下结论")
    else:
        日志(f"  ✅ 各轮逐题一致(0 题翻面)—— 这一批的结果是稳的")

    if 基线通过数 is None:
        日志(f"  ℹ️ 没给基线,只报抖动 —— **不比就不编结论**")
        return not 翻

    版本差 = abs(各轮[-1] - 基线通过数)
    轮间差 = len(翻)
    日志(f"  轮间抖动 {轮间差} 题;和基线差 {版本差} 题")
    if 轮间差 >= 版本差:
        日志(f"  {Y}⚠ **轮间抖动不小于版本差 —— 这个对比说明不了任何事。**{D} "
             f"想分辨出这么小的差,要么加题,要么多跑几轮")
        return False
    日志(f"  {G}✅ 版本差大于轮间抖动,这个对比有意义{D}(但 n={n},只能说方向)")
    return True


def 自测():
    """咬合:三种情形各自都要说对话。"""
    import io, contextlib
    坏 = []

    def 抓(f):
        b = io.StringIO()
        with contextlib.redirect_stdout(b):
            r = f()
        return r, b.getvalue()

    # ① 只跑一轮 → 必须明说不能下结论
    _, out = 抓(lambda: 报([{"A": True, "B": True}]))
    if "不能下结论" not in out:
        坏.append("只跑了一轮要明说不能下结论")
    # ② 抖动 ≥ 版本差 → 必须明说比不了
    _, out = 抓(lambda: 报([{"A": True, "B": False}, {"A": False, "B": False}],
                           基线通过数=1))
    if "说明不了任何事" not in out:
        坏.append("抖动大于版本差时要明说比不了")
    # ③ 稳定且版本差大 → 可以说有意义
    _, out = 抓(lambda: 报([{"A": True, "B": True, "C": True}] * 2, 基线通过数=0))
    if "这个对比有意义" not in out:
        坏.append("稳定且版本差大时该说有意义")
    if "0 题翻面" not in out:
        坏.append("没翻面时要明说 0 题翻面(不然看不出是稳的还是没比)")
    # ④ 没给基线 → 不许编结论
    _, out = 抓(lambda: 报([{"A": True}] * 2))
    if "不比就不编结论" not in out:
        坏.append("没给基线时不许编结论")

    print("跑几轮、抖多少 · 咬合")
    for x in 坏:
        print(f"  ✗ {x}")
    if not 坏:
        print("  ✓ 单轮 / 抖动≥版本差 / 稳定可比 / 无基线,四种情形都说对了话")
    print((f"{R}❌ 轮次咬合 {len(坏)} 条不过{D}") if 坏 else f"{G}✅ 轮次咬合:四种情形都咬得动{D}")
    return 1 if 坏 else 0


if __name__ == "__main__":
    import sys
    sys.exit(自测())
