def main():
    print("工匠 / 财务判分器 · 对照用例")
    print("=" * 104)
    bad = 0
    for name, cid, traj, text, want, pin in T:
        c = C[cid]
        errs = c["grade"](text, traj, c)
        got = not errs
        ok = (got == want)
        bad += (not ok)
        print(f"  {'✅' if ok else '❌'} [{cid}] {name}")
        print(f"       钉的坑:{pin}")
        if not ok:
            print(f"       ⚠️ 该{'过' if want else '挂'}却{'过' if got else '挂'}了"
                  f"{('：' + errs[0][:70]) if errs else ''}")
    print("=" * 104)
    y = sum(1 for t in T if t[4])
    if bad:
        print(f"❌ {bad}/{len(T)} 条对照不符合预期 —— **先修判分器,别去跑模型**")
        return 1
    print(f"✅ {len(T)} 条对照全部符合预期(该过 {y} / 该挂 {len(T)-y})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
