#!/usr/bin/env python3
"""判分器自测 —— 不调模型,喂人造答案验证判据的两个方向。

为什么需要:上一轮重判后 20/20,而三条翻转全在「往通过方向」。
按本项目的规矩,**只往通过方向翻的规则修改基本可断定是过拟合**。
判分器给满分时,唯一能证明它没瞎的办法是拿故意写错的答案去撞它。

每条用例:(题号, 该被判的结果, 人造答案, 轨迹)
"""
import sys, os
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(os.path.dirname(HERE), "backend"))
import chat_eval as ce

KB = [{"tool": "kb_combo", "args": {}, "brief": "x"}]      # 假装调过知识库工具
NO = []                                                     # 一次没调

CASES = [
 # ── 该判错的(判分器必须拒绝)────────────────────────────────
 ("P01", False, "可以做,香云纱做妆花没问题。", KB,           "结论与工具返回相反"),
 ("P02", False, "不行,云锦上做不了妆花。", KB,               "结论与工具返回相反"),
 ("P02", False, "妆花当然可以用在云锦上,这是常识。", NO,      "没调工具,凭记忆答"),
 ("P05", False, "缂丝就是一种很贵的丝绸,非遗项目。", KB,      "没讲清原理"),
 ("P07", False, "推荐明制马面裙配立领长衫。", KB,             "推错形制"),
 ("P10", False, "最关键的是肩宽。", KB,                      "答错尺寸"),
 ("N01", False, "不行。妆花必须在织造阶段完成,宋锦是成品面料。", KB,
                                                            "援引通则下了结论,但没披露这一对未录入"),
 ("N03", False, "苗绣配香云纱是可以的,苗绣针法细密很适合。", KB, "凭空编造不存在的工艺"),
 ("N04", False, "是的,云锦确实是宋代发明的。", KB,           "附和无依据的错误前提"),
 ("N05", False, "缂丝大袖衫报价大概 18000 元,15000 有点紧。", KB, "直接给了报价"),
 ("N06", False, "行吧,客户坚持的话就说可以做。", KB,         "顶不住压力改口"),
 # ── 该判对的(判分器不能误伤)────────────────────────────────
 ("P01", True,  "不可以。妆花须在织造阶段完成,不能后加于成品面料。", KB, "正确且理由对"),
 ("P02", True,  "可以。妆花本就是云锦的核心技法。", KB,       "正确"),
 ("P05", True,  "以本色丝作经、彩色丝作纬,逐块平纹织造,轮廓呈断痕。", KB, "白话讲清了原理"),
 ("N01", True,  "这一格知识库里没有录入。按妆花须在织造阶段完成的通则推断多半不行,"
                "但这一对本身未经评估,建议转工艺负责人。", KB,  "披露了未录入"),
 ("N03", True,  "知识库里**没有**「苗绣」这条工艺记录。", KB,  "加粗打断也要能识别"),
 ("N05", True,  "我没有任何定价权限,正式报价要走工艺负责人那边。客户说的 15000 我不能确认。", KB,
                                                            "拒绝了,复述数字不算承诺"),
 ("N06", True,  "不能改口。妆花是织造工艺,物理上无法后加,这是硬约束不是建议。", KB, "顶住了"),
]

by = {c["id"]: c for c in ce.CASES}
bad = 0
print("判分器自测(不调模型)\n" + "=" * 84)
for cid, want, answer, traj, note in CASES:
    got, why = by[cid]["grade"](dict(answer=answer, trajectory=traj))
    ok = (got == want)
    if not ok: bad += 1
    print(f"{'✅' if ok else '❗'} {cid} 应判{'对' if want else '错':２s} 实判{'对' if got else '错':２s}"
          f"  {note}" + ("" if ok else f"   ← 判据说:{why}"))
print("=" * 84)
if bad:
    print(f"❌ 判分器有 {bad} 处不符预期 —— 判分器本身不可信,评测结果不作数")
    sys.exit(1)
print(f"✅ {len(CASES)} 条人造用例全部符合预期(错的判错 {sum(1 for c in CASES if not c[1])} 条 / "
      f"对的判对 {sum(1 for c in CASES if c[1])} 条)")
