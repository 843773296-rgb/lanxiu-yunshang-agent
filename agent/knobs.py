#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""调参旋钮 —— **「这个 agent 上有哪些东西可以拧」的唯一来源。**

## 为什么要有这个文件(2026-09-25)

原来这套系统只有**一个**能拧的地方:提示词文字。其余全是函数默认值和写死的常量 ——
`effort="medium"`、`max_turns=12`、工具按角色全给。它们**在代码里是参数,在产品上不存在**。

后果不是「少个功能」,是**调优这件事没法被演示,也没法被归因**:
改完提示词分数动了,你说不清是那几个字起的作用,还是那一轮恰好想得深一点。
**变量不可控,实验就不成立。**

## 一条硬规矩:每个旋钮必须声明「落点」

`落点` 写的是**改了它之后,哪个文件的哪个参数会读到这个值**。
`knobs_check.py` 会去那个文件里验这个名字真的被读 —— 验不到就红。

这条不是洁癖。`sdk.py` 里写过一段更狠的:**这条路径根本不传 temperature,
所以页面上不许放温度滑块** —— 放了它会是个「假旋钮」,拖动它什么都不会变,
而人会以为自己在调,于是往错的方向查问题。

> **「配置写了」和「配置生效了」是两回事,而它们在界面上长得一模一样。**

这个项目在 `allowed_tools` 上栽过同一个形状的跟头(以为封住了,其实没封)。
落点声明 + 落点检查,是把那次教训做成结构。

## 一条边界:只许收窄,不许放宽

`工具` 这个旋钮**只接受现有白名单的子集**,给了名单外的工具**当场抛**。

收窄是调优(少给它两个工具,看它还答不答得对 —— 这正是该测的);
放宽是**拆安全边界**,那不是调参能干的事,得走改代码 + 过 check.sh 那条路。

`体检` 关掉是**放松**(交付前的回答体检 hook 不挂了)。它允许,因为「没有 hook 会怎样」
本身就是该测的问题 —— 但方案会被打上 `松` 标记,而**带 `松` 标记的方案不许采纳**:
可以拿它做实验,不能拿它当新默认。

## 怎么用

    方案里加一段 "旋钮": {"effort": "high", "工具": [...], "体检": false}
    LANXIU_PROMPT_CANDIDATE=<号> 跑评测 → 旋钮和提示词改动一起生效

**旋钮和提示词共用同一个方案、同一个开关。** 因为要比的那件事是
「我改了 X,分数从 A 到 B」—— X 是提示词还是旋钮,比分机制不该有两套。
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
目录 = os.path.join(ROOT, ".feynman", "prompt_candidates")

EFFORT = ("low", "medium", "high", "xhigh", "max")


def _短(t):
    """`mcp__shop__get_order` → `get_order`。

    ⚠️ 工具名在这个系统里**有两种写法**:页面和方案文件存短名(人看得懂),
    sdk 的白名单是全名(SDK 要的)。**方案里一律存短名,比较一律按短名** ——
    不统一的话,方案存下来能过,一真跑就会被判成「放宽白名单」当场抛,
    而报错读起来像是你配错了工具。
    这个项目为「一份数据两处表示、改一处没改另一处」栽过六次,这是第七次的预防。
    """
    return (t or "").rsplit("__", 1)[-1]

# ── 旋钮表 ────────────────────────────────────────────────────────────
# 落点格式:"<相对路径>::<在那个文件里能搜到的名字>"。
# 松=True 表示这个旋钮往「放松约束」的方向拧 —— 可以试,不可以采纳。
旋钮表 = [
    dict(名="effort", 中文="想多深", 类型="枚举", 取值=list(EFFORT), 默认="medium",
         落点="agentsite/sdk.py::effort",
         说明="low→max 五档。管的是**想多深,不是多随机** —— 这条路径不暴露 temperature。"
              "定制业务要的是稳,不是花样,所以能调的恰好是对的那个。"),
    dict(名="max_turns", 中文="最多来回几轮", 类型="整数", 取值=[1, 24], 默认=12,
         落点="agentsite/sdk.py::max_turns",
         说明="模型和工具最多来回几次。调小是**逼它少绕**(也是成本闸);"
              "调太小它会在查到一半时被掐断,答案会残 —— 这正是值得亲手撞一次的边界。"),
    dict(名="model", 中文="用哪个模型", 类型="字符串", 取值=None, 默认=None,
         落点="agentsite/sdk.py::model_name",
         说明="留空=按凭证走默认。⚠️ 换了模型的两张成绩单**不可比**(成本能差一个量级),"
              "比分时会因为「换了模型」直接拒绝比较,不会静默给你一个假结论。"),
    dict(名="工具", 中文="挂哪些工具", 类型="工具子集", 取值=None, 默认=None,
         落点="agentsite/sdk.py::_tools_for",
         说明="**只许是现有白名单的子集**。收掉两个工具看它还答不答得对,是最能说明问题的一类实验:"
              "每多挂一个工具,此后**每一次调用**都要把它的定义带上(这个项目实测过,"
              "工具从 26 涨到 59,单条成本涨了 38%,而功能测试里完全看不见)。"),
    dict(名="体检", 中文="交付前体检", 类型="开关", 取值=[True, False], 默认=True, 松=True,
         落点="agentsite/sdk.py::guard",
         说明="关掉=不挂回答体检 hook,模型说什么就交付什么。"
              "**提示词里的「铁律」原本只是祈使句,挂上 hook 才是强制** —— "
              "关掉它跑一轮,就能看见这句话到底值多少分。"),
    dict(名="注日期", 中文="注入今天日期", 类型="开关", 取值=[True, False], 默认=True, 松=True,
         落点="agentsite/guards.py::注入原文",
         说明="关掉=不告诉模型今天几号。工期倒推会开始算错 —— "
              "这是**「上下文注入到底有没有用」的对照组**,也是这套系统里最便宜的一个消融实验。"),
]
_按名 = {k["名"]: k for k in 旋钮表}


def 默认():
    return {k["名"]: k["默认"] for k in 旋钮表}


def 校验(旋钮, 可用工具=None):
    """返回 (干净的旋钮, 松不松, [人话说明])。**认不出的键当场抛** —— 不静默忽略。

    静默忽略一个拼错的旋钮名,和「假旋钮」是同一个病:
    你以为自己在调,实际上那一轮跑的是默认值,而两轮的分数差会被归因到别处。
    """
    旋钮 = dict(旋钮 or {})
    生 = [k for k in 旋钮 if k not in _按名]
    if 生:
        raise ValueError(f"认不出这几个旋钮:{生} —— 现有的是 {list(_按名)}。"
                         f"**不忽略**:拼错一个名字就等于那一轮跑的是默认值,而分数差会被归到别处")
    出, 松, 话 = {}, False, []
    for 名, 值 in 旋钮.items():
        k = _按名[名]
        if 值 is None or 值 == k["默认"]:
            continue                      # 和默认一样就不记 —— 方案里只留「真的动过的」
        if k["类型"] == "枚举" and 值 not in k["取值"]:
            raise ValueError(f"{名} 只认 {k['取值']},给的是 {值!r}")
        if k["类型"] == "整数":
            try: 值 = int(值)
            except Exception: raise ValueError(f"{名} 要整数,给的是 {值!r}")
            lo, hi = k["取值"]
            if not (lo <= 值 <= hi): raise ValueError(f"{名} 要在 {lo}–{hi} 之间,给的是 {值}")
        if k["类型"] == "开关":
            if 值 not in (True, False): raise ValueError(f"{名} 只认 true/false,给的是 {值!r}")
        if k["类型"] == "工具子集":
            值 = [_短(t) for t in (值 or [])]
            if 可用工具 is not None:
                可用短 = {_短(t) for t in 可用工具}
                # ⚠️ **只许收窄。** 白名单外的工具在这里当场抛,不是过滤掉 ——
                # 过滤掉的话,跑出来的那一轮和你以为自己配的那一轮不是同一件事。
                外 = [t for t in 值 if t not in 可用短]
                if 外:
                    raise ValueError(
                        f"这几个工具不在当前角色的白名单里:{外[:5]}{'…' if len(外) > 5 else ''} —— "
                        f"**旋钮只许收窄不许放宽**。收窄是调优,放宽是拆安全边界,"
                        f"那得走改代码 + 过 check.sh 那条路。")
            if not 值:
                raise ValueError("工具收窄成空集了 —— 一个工具都不给,它只能靠编,这一轮说明不了任何事")
        出[名] = 值
        if k.get("松"): 松 = True
        话.append(f"{k['中文']}:{k['默认']} → {值 if k['类型'] != '工具子集' else f'收窄到 {len(值)} 个'}")
    return 出, 松, 话


def 读(号=None):
    """从方案文件里取旋钮。没指定方案返回空 —— **默认永远是源头那一份**。"""
    号 = (号 if 号 is not None else os.environ.get("LANXIU_PROMPT_CANDIDATE", "")).strip()
    if not 号: return {}
    f = os.path.join(目录, f"{号}.json")
    if not os.path.exists(f):
        # 和 prompts.候选覆盖() 同一个态度:**不退回源头**。
        # 套没套上方案,跑出来的分数含义完全不同。
        raise RuntimeError(f"指定了方案 {号},但找不到 {f}")
    return json.load(open(f, encoding="utf-8")).get("旋钮") or {}


def 应用(参数, 号=None, 可用工具=None):
    """把方案里的旋钮盖到 run() 的参数上,返回 (新参数, 人话说明)。

    **只盖方案里明确写了的那几个** —— 没写的保持调用方传进来的值,
    不要用旋钮表的默认去覆盖(那会把调用方的显式传参吃掉,是一类很难查的 bug)。
    """
    旋 = 读(号)
    if not 旋: return dict(参数), []
    干净, _松, 话 = 校验(旋, 可用工具)
    新 = dict(参数)
    if "effort" in 干净:    新["effort"] = 干净["effort"]
    if "max_turns" in 干净: 新["max_turns"] = 干净["max_turns"]
    if "model" in 干净:     新["model_name"] = 干净["model"]
    if "体检" in 干净:      新["guard"] = 干净["体检"]
    if "工具" in 干净:
        # **存的是短名,传给 SDK 的必须是全名** —— 在这里换回去,
        # 而不是让调用方自己记得换(记得换 = 迟早有一处忘了)
        留 = {_短(t) for t in 干净["工具"]}
        新["_工具收窄"] = [t for t in (可用工具 or []) if _短(t) in 留] or None
    if "注日期" in 干净:    新["_注日期"] = 干净["注日期"]
    return 新, 话


# ── 落点自检 ──────────────────────────────────────────────────────────
def 落点核对():
    """每个旋钮声明的落点,在那个文件里必须真的搜得到那个名字。

    **这是防假旋钮的那道闸。** 一个旋钮如果只存在于这张表和页面上,
    它就是个滑块 —— 拖动它什么都不会变,而人会以为自己在调。
    """
    坏 = []
    for k in 旋钮表:
        路, _, 名 = k["落点"].partition("::")
        p = os.path.join(ROOT, 路)
        if not os.path.exists(p):
            坏.append(f"{k['名']}:落点文件不存在 {路}"); continue
        if not re.search(re.escape(名), open(p, encoding="utf-8").read()):
            坏.append(f"{k['名']}:在 {路} 里搜不到「{名}」—— 这个旋钮可能没接上")
    return 坏
