#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""`tool_select.py` 的自测 —— **离线、一秒钟、不调模型、不碰库**。

## 为什么必须有这一份

`tool_select.py` 里全是闸(准入线、取交集、空集退回、兜底够不够)。
而这个项目的规矩是:**新加一条检查,必须做咬合测试** ——
故意把被检查的东西改坏,确认检查真的会红。

> **没红过的检查等于没有。**

而我昨天写完那个模块**直接提交了,没写自测** ——
那正是我一整天在批评的形状:声称装了闸,而没撞过它。

## 这一份要钉死的几件

| 要钉的 | 不钉的下场 |
|---|---|
| 缺数据就**抛**,不给默认值 | 一个用默认成本算出来的线,和一个用实测算的,在那个布尔值上长得一样 |
| **空工具面要抛** | 空集合上这个平均值没有意义,而它会让线变成无穷大 → 所有角色都「不该开」 |
| 取交集**只许收窄** | 一个没取交集的工具面,和一个合法的,在运行时长得一样 |
| 空集退回**要带两边原本是什么** | 不带就查不出是路由器选歪还是角色集太窄 |
| 兜底交集太小**要报** | 退回到空壳兜底组,和正常退回,在「退回了」这个事实上长得一样 |
| **线随「走不走缓存」漂** | 写死的那天模型降价它就错了,而错的时候不报错 |
"""
import json
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "backend"))
import tool_select as TS

过, 挂 = [], []


def ck(名, 真, 补=""):
    print(f"  {'✅' if 真 else '❌'} {名}{('  ' + str(补)[:120]) if 补 else ''}")
    (过 if 真 else 挂).append(名)


def 假探针(单条=0.001, 选=(("a", "b"),), 版本="router_probe@假的"):
    """造一份探针结果文件。**自测不读真结果** —— 真结果会变,而断言不该跟着它漂。"""
    f = tempfile.NamedTemporaryFile("w", suffix=".json", delete=False,
                                    encoding="utf-8")
    json.dump({"探针版本": 版本, "模型": "claude-haiku-4-5",
               "配置": {"开": [{"题": f"T{i}", "给的": list(g), "成本USD": 单条}
                            for i, g in enumerate(选)]}},
              f, ensure_ascii=False)
    f.close()
    return f.name


def 假工具面(n, 每个字数=300):
    """n 个工具,每个说明 `每个字数` 个汉字(≈ 同样多 token)。"""
    return {f"t{i}": ("工" * 每个字数, "{}") for i in range(n)}


def main():
    print("tool_select 自测(离线,不调模型不碰库)")
    print("=" * 84)

    # ── ① 缺数据就抛,不给默认值 ────────────────────────────────
    print("\n▸ ① 缺数据就抛 —— **不给默认值**")
    try:
        TS.路由器实测("/tmp/根本不存在的探针结果.json")
        ck("没有探针结果 → 抛", False, "它没抛!")
    except TS.算不了 as e:
        ck("没有探针结果 → 抛(不给默认成本)", "不给默认成本" in str(e))

    没章 = tempfile.NamedTemporaryFile("w", suffix=".json", delete=False,
                                      encoding="utf-8")
    json.dump({"开": []}, 没章, ensure_ascii=False); 没章.close()
    try:
        TS.路由器实测(没章.name)
        ck("探针结果没盖版本章 → 抛", False, "它没抛!")
    except TS.算不了 as e:
        ck("探针结果没盖版本章 → 抛(**不然用的是上一版探针的数**)",
           "没盖版本章" in str(e))

    无钱 = tempfile.NamedTemporaryFile("w", suffix=".json", delete=False,
                                      encoding="utf-8")
    json.dump({"探针版本": "x", "配置": {"开": [{"题": "T1", "给的": ["a"]}]}},
              无钱, ensure_ascii=False); 无钱.close()
    try:
        TS.路由器实测(无钱.name)
        ck("探针结果里没算好的成本 → 抛", False, "它没抛!")
    except TS.算不了 as e:
        ck("探针结果里没算好的成本 → 抛(**这边不自己算**:cost_of 修过「少算三成」)",
           "不算" in str(e) or "重算" in str(e))

    # ── ② 空工具面要抛(空集合上所有性质都成立)────────────────
    print("\n▸ ② 空工具面 —— **空集合上这个平均值没有意义**")
    try:
        TS.每个工具平均token({})
        ck("空工具面 → 抛", False, "它没抛!")
    except TS.算不了 as e:
        ck("空工具面 → 抛(不抛的话线变成无穷大 → **所有角色都「不该开」**)",
           "空" in str(e))

    try:
        TS.单价("根本没有这个模型")
        ck("价目表里没有这个模型 → 抛", False, "它没抛!")
    except TS.算不了 as e:
        ck("价目表里没有这个模型 → 抛(**拒绝用猜的单价算**)", "猜的单价" in str(e))

    # ── ③ 线真的随「走不走缓存」漂(这是它不能写死的理由)──────
    print("\n▸ ③ 线随「走不走缓存」漂 —— **这是它不许写死的理由**")
    探 = 假探针(单条=0.001, 选=(("a",),) * 10)
    面 = 假工具面(50, 每个字数=300)
    线缓, _ = TS.准入线(面, "claude-haiku-4-5", 走缓存=True, 结果文件=探)
    线不缓, _ = TS.准入线(面, "claude-haiku-4-5", 走缓存=False, 结果文件=探)
    ck("走缓存的线 **比不走缓存高一个量级**(缓存读便宜 10 倍 → 省得少 → 线更高)",
       线缓 > 线不缓 * 5, f"走缓存 {线缓:.1f} vs 不走 {线不缓:.1f}")
    ck("两条线都是**算出来的**,而且不等(= 它真的随那个开关漂)",
       abs(线缓 - 线不缓) > 1, f"差 {线缓-线不缓:.1f}")

    # ── ④ 准入判断两个方向都动(不是恒真也不是恒假)──────────
    print("\n▸ ④ 准入判断**两个方向都动** —— 恒真/恒假的判断和正确的长得一样")
    开大, 话大, 细大 = TS.该开筛选吗(int(线缓) + 20, 面, "claude-haiku-4-5",
                                结果文件=探)
    开小, 话小, 细小 = TS.该开筛选吗(max(int(线缓) - 20, 1), 面,
                                "claude-haiku-4-5", 结果文件=探)
    ck("工具数远超线 → 开", 开大 is True, 话大[:70])
    ck("工具数远低于线 → **不开**", 开小 is False, 话小[:70])
    ck("不开那一档说清了**原因是结构性的**(不是调参能救的)",
       "固定成本" in 话小, 话小[-50:])
    ck("明细里带着「怎么算出来的」那几个数(事后查得出是哪个数让它不开)",
       all(k in 细小 for k in ("路由器单条成本", "每个工具平均token",
                              "按哪一档单价", "探针版本")),
       sorted(细小)[:5])

    # ── ⑤ 取交集:只许收窄 ────────────────────────────────────
    print("\n▸ ⑤ 取交集 —— **只许收窄不许放宽**(角色工具集是权限边界)")
    能, 挡, 空 = TS.收窄到角色内(["a", "b", "越权的写工具"], ["a", "b", "c"])
    ck("角色集外的被挡掉", 挡 == ["越权的写工具"], (能, 挡))
    ck("角色集内的留下", 能 == ["a", "b"], 能)
    ck("没空集", 空 is False)
    能2, 挡2, 空2 = TS.收窄到角色内(["越权1", "越权2"], ["a", "b"])
    ck("全被挡掉 → **报空集**(而不是悄悄给全部)", 空2 is True and 能2 == [],
       (能2, 挡2))
    能3, 挡3, 空3 = TS.收窄到角色内([], ["a", "b"])
    ck("路由器一个都没给 → 也是空集", 空3 is True)

    # ── ⑥ 空集退回的记录:**带两边原本是什么** ───────────────
    print("\n▸ ⑥ 空集退回的记录 —— 不带两边原本是什么就**查不出是谁的错**")
    记 = TS.空集退回记一条("finance", ["kb_fit", "kb_size"],
                       ["get_deposit", "get_refund_trace"], ["kb_fit", "kb_size"])
    ck("记了「路由器原本选了什么」", 记["路由器原本选了"] == ["kb_fit", "kb_size"])
    ck("记了「角色集里有什么」和它共几个",
       "角色集里有" in 记 and 记["角色集共几个"] == 2)
    ck("记了「怎么读这条记录」(**分得开是路由器选歪还是角色集太窄**)",
       "路由器选歪" in 记["怎么读"] and "角色集太窄" in 记["怎么读"])
    ck("明说退回到哪", "ROLE_TOOLS" in 记["退回到"])

    # ── ⑦ 兜底够不够 ────────────────────────────────────────
    print("\n▸ ⑦ 兜底组交集太小要报 —— **退回空壳和正常退回长得一样**")
    够, 交, 话 = TS.兜底够用吗(["a", "b", "c", "d", "e", "f"],
                          ["a", "b", "c", "d", "e"], 下限=5)
    ck("交集 5 个(到下限)→ 够", 够 is True, 话)
    够2, 交2, 话2 = TS.兜底够用吗(["a", "b", "c"], ["a"], 下限=5)
    ck("交集 1 个 → **不够,而且明说「退回它等于退回一个空壳」**",
        够2 is False and "空壳" in 话2, 话2)
    够3, 交3, _ = TS.兜底够用吗([], ["a", "b"], 下限=1)
    ck("兜底组是空的 → 交集空 → 不够", 够3 is False and 交3 == [])

    for f in (探, 没章.name, 无钱.name):
        try: os.remove(f)
        except OSError: pass

    print("\n" + "=" * 84)
    print(f"过 {len(过)} · 挂 {len(挂)}")
    for x in 挂: print("   ❌", x)
    return 1 if 挂 else 0


if __name__ == "__main__":
    sys.exit(main())
