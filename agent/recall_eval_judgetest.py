def _挑个算得对的日子():
    """挑一个「上次」的日子,让「写出日期、天数算对了不算编数」那条用例**真的靠日期规则才过**。

    ⚠️⚠️ **日子不能写死。** 这里原来写死 `2026-09-13`,2026-11-08 当场栽:
       那天距今正好 **56** 天,而回答里有 728(金额)和 13(「9 月 13 日」里的 13)——
       **728 ÷ 13 = 56**,于是这个天数「不靠日期也算得出来」,
       **那条用例当天验不到日期规则**(把日期规则整段删掉它照旧通过),而绿勾一模一样。

       > 一条**今天恰好验不到**的判据,和一条**守得住**的判据,
       > **在那个 ✅ 上长得一模一样** —— 除非它自己去试一把。

       这和隔壁 `_挑个编出来的天数()` 是同一个病的两半:那边挑**错的**天数、
       这边挑**对的**天数,而两边撞车的方式一模一样(恰好能从回答里两个数算出来)。
       **而且 11-05 那次撞的就是 56 这个数** —— 同一个数隔三天从另一头又撞了一次,
       所以写死哪个日子都只是把撞车推到以后,而撞车那天没有东西会说「是夹具的事」。

    ⚠️ **咬合不能用「把条件①整段删掉」去攻** —— 2026-11-08 实测:删掉之后它照旧挑中
       同一天(31 天),因为**那天第一个「判据放过」的日子恰好也是「算不出来」的那一天**,
       两个条件碰巧重合,于是退出码 0。
       > 一个「检查漏了」和一个「这个改动今天本来就无害」,**在「没红」上长得一模一样。**
       所以攻它要换一刀:把下面那个 `None` 换成传今天(= 开着日期规则去问「算不算得出」)——
       那样每一天都会被判成「算得出来」,一个都挑不出来,`main` 里那条断言当场红。
       (这和老规格 1238 攻 `main` 的那一刀是同一个错,只是打在挑日子这一侧。)

    两个条件缺一不可:
      ① `距今` **不靠日期规则算不出来** —— 不然这条用例什么都没守住(用 `None` 去核,
         就是「不开日期规则」那一档;这里别传今天,传了日期规则就把它算出来了);
      ② 判据**完全放过**这段回答 —— 挂了说明是夹具没立起来(比如写出的月、日本身被当成编的数),
         那是换夹具的事,不是判据的事。
    「算不算得出」**调判据自己那个函数**(`E._算得出`),不在这儿重写一份 —— 重写就是同源谬误。
    回 (天数, 那天, 那段回答);一个都挑不出来就回 (None, None, None),由 main 报红。
    """
    今 = _dt.date.fromisoformat(E._今天())
