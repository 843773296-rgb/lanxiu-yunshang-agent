def main():
    坏 = []
    # ⚠️ 先把夹具自己验一遍 —— 一条**夹具没立起来**的用例,和一条**判据守住了**的用例,
    #    在那个 ✅ 上长得一模一样。
    if _距今 is None:
        print("  ❌ 挑不出一个「算得对的日子」—— 20…199 天里没有一天能让这条用例既"
              "**不靠日期也算不出天数**、又被判据完全放过,**要人来换夹具**(别以为是判据的事)")
        坏.append("挑不出算得对的日子")
    if _错偏差 is None:
        print("  ❌ 挑不出一个「编出来的天数」—— 回答里的数把 +1…+14 整片都盖住了,"
              "这条用例立不起来,**要人来换夹具**(别以为是判据的事)")
        坏.append("挑不出编出来的天数")
    else:
        说 = f"(今天 {E._今天()}:距今 {_距今} 天,错写成 {_距今 + _错偏差} 天)"
        print(f"  ℹ️ 「写错的天数」这次挑的是 +{_错偏差} {说}"
              + ("" if _错偏差 == 1 else " —— 更小的偏差**恰好能从回答里两个数算出来**,"
                                        "那种数判据放过是对的,不是漏")
              )
    # ⚠️ 「算对了不算编数」那条,必须是**靠日期算出来**才过的。万一 `_距今` 恰好也能
    #    由回答里两个数算出来,那条用例就会在日期规则被删掉之后**照旧通过** ——
    #    那时它什么都没守住,而绿勾一模一样。
    靠算术 = str(_距今) in E._算得出(set(E._数们(日期算对)) & set(事实["池数"]), 日期算对, None)
    if 靠算术:
        print(f"  ❌ 距今 {_距今} 天这个数**不靠日期也算得出来** —— 「写出日期、天数算对了不算编数」"
              "那条用例今天验不到日期规则(删掉日期规则它照旧通过)。**要人来换夹具**")
        坏.append("算对那条被算术巧合顶掉了")
    for 说, 答, 轨, 期望, *夹 in 例:
        why = E.判(答, 轨, 夹[0] if 夹 else 事实)
        类 = {w.split(":", 1)[0] for w in why}
        ok = (not why) if 期望 is None else (期望 in 类)
        print(f"  {'✅' if ok else '❌'} {说}" + ("" if ok else f" —— 期望 {期望 or '过'},得 {why}"))
        if not ok:
            坏.append(说)

    # 第五次真跑钉回:模型查了着装人档案再引里面的数 —— 那次调用也得重放进「工具给了什么」
    try:
        f2 = E.取事实(两个都过 + [{"tool": "mcp__customer__get_wearer", "args": {"customer": "C10001"}}], E.顾问)
        f1 = E.取事实(两个都过, E.顾问)
        多 = len(f2["池文"]) > len(f1["池文"])
        写口不重放 = not E._该重放("assign_task")
        ok = 多 and 写口不重放
        print(f"  {'✅' if ok else '❌'} 轨迹里别的只读调用也重放进事实池(着装人档案)、写口不重放"
              + ("" if ok else f" —— 多出来了吗 {多} · 写口不重放 {写口不重放}"))
        if not ok:
            坏.append("别的只读调用也重放")
    except Exception as e:
        print(f"  ❌ 别的只读调用也重放 —— 崩了:{type(e).__name__}: {e}")
        坏.append("别的只读调用也重放")

    # 现读库:用顾问身份重放两个名单工具,事实不能是空的
    try:
        f = E.取事实(两个都过, E.顾问)
        n名单, n客户 = len(f["名单"]), len(f["客户"])
        ok = n名单 > 0 and n客户 > 0 and any(v.get("档位") for v in f["客户"].values())
        print(f"  {'✅' if ok else '❌'} 现读库:顾问 {E.顾问['name']} 名单 {n名单} 人、取到档位的客户 {n客户} 个"
              + ("" if ok else " —— **没扫到东西,不算通过**"))
        if not ok:
            坏.append("现读库")
    except Exception as e:
        print(f"  ❌ 现读库崩了:{type(e).__name__}: {e}")
        坏.append("现读库")

    print(f"\n{'✅' if not 坏 else '❌'} 客户召回判分器对照 {len(例) + 2 - len(坏)}/{len(例) + 2}")
    return 1 if 坏 else 0


if __name__ == "__main__":
    sys.exit(main())
