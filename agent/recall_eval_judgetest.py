def main():
    坏 = []
    for 说, 答, 轨, 期望, *夹 in 例:
        why = E.判(答, 轨, 夹[0] if 夹 else 事实)
        类 = {w.split(":", 1)[0] for w in why}
        ok = (not why) if 期望 is None else (期望 in 类)
        print(f"  {'✅' if ok else '❌'} {说}" + ("" if ok else f" —— 期望 {期望 or '过'},得 {why}"))
        if not ok:
            坏.append(说)

    # 第五次真跑钉回:模型查了着装人档案再引里面的数 —— 那次调用也得重放进「工具给了什么」
    try:
        f2 = E.取事实(两个都过 + [{"tool": "mcp__customer__get_wearer", "args": {"customer": "C10001"}}], E.顾问)
        f1 = E.取事实(两个都过, E.顾问)
        多 = len(f2["池文"]) > len(f1["池文"])
        写口不重放 = not E._该重放("assign_task")
        ok = 多 and 写口不重放
        print(f"  {'✅' if ok else '❌'} 轨迹里别的只读调用也重放进事实池(着装人档案)、写口不重放"
              + ("" if ok else f" —— 多出来了吗 {多} · 写口不重放 {写口不重放}"))
        if not ok:
            坏.append("别的只读调用也重放")
    except Exception as e:
        print(f"  ❌ 别的只读调用也重放 —— 崩了:{type(e).__name__}: {e}")
        坏.append("别的只读调用也重放")

    # 现读库:用顾问身份重放两个名单工具,事实不能是空的
    try:
        f = E.取事实(两个都过, E.顾问)
        n名单, n客户 = len(f["名单"]), len(f["客户"])
        ok = n名单 > 0 and n客户 > 0 and any(v.get("档位") for v in f["客户"].values())
        print(f"  {'✅' if ok else '❌'} 现读库:顾问 {E.顾问['name']} 名单 {n名单} 人、取到档位的客户 {n客户} 个"
              + ("" if ok else " —— **没扫到东西,不算通过**"))
        if not ok:
            坏.append("现读库")
    except Exception as e:
        print(f"  ❌ 现读库崩了:{type(e).__name__}: {e}")
        坏.append("现读库")

    print(f"\n{'✅' if not 坏 else '❌'} 客户召回判分器对照 {len(例) + 2 - len(坏)}/{len(例) + 2}")
    return 1 if 坏 else 0


if __name__ == "__main__":
    sys.exit(main())
