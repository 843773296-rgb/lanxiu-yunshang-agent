# -*- coding: utf-8 -*-
"""**探针:配对出题这个法子,到底量不量得出东西。**

    python3 agent/triage_lure_probe.py --看        # 只印要问哪几道,不调模型
    python3 agent/triage_lure_probe.py --做 [-n 12]

**不进 `check.sh`** —— 它调模型、要几分钟、结果有波动。门禁里放这种会变成随机拦路。

## 它回答的是哪个问题

用户 2026-10-13 拍的:**先拿一小批题试,再决定全套改不改。**

背景(用户 10-13 在会话里原话确认的那道选型):差评 AI 的三条过关线里,
**两条建在「随机填的标注」上** —— 演示数据里某条差评标着「全额退款」,
不是因为它该全额退款,是因为造数脚本掷了个骰子。拿它当答案算「漏报了几条」,
**算出来的数量的是 AI 和骰子像不像**。

只有「**顶不顶得住诱导**」那条不需要正确答案:它不问「判得对不对」,
只问「同一条差评,我在问题里加一句挑唆的话,它的判断会不会跟着变」——
**只跟模型自己比**。

所以这支探针验的不是模型,是**尺子**:这个法子分辨得出东西吗?

## 🔺 为什么是**三问**,不是两问 —— 这一条决定结论站不站得住

「干净问一次、带诱导问一次,变了就算被诱导」听着干净,**而它是错的**:

> **模型自己就会抖。** 而「被诱导改了主意」和「这一轮恰好抽到另一个答案」,
> **在「两次答案不一样」这个事实上长得一模一样。**

这个项目为它栽过四次(CLAUDE.md 第 3 节):同一个提交、同一批工单连跑两轮,
V1 和 V3 各掉一题,**而且掉的不是同一题**。那张表原来写的单轮 6/6/6
读起来像「三代能力持平」,而那是三次抛硬币都正面。

所以问三次:**干净 ×2 + 带诱导 ×1**。两次干净问之间的差异就是**抖动基线**,
而「诱导后的变化」要减掉它才算数。

**而这恰好就是小批试验真正该回答的问题**:如果抖动本身就有三成,
那这条线不管怎么出卷都量不出东西 —— **那才是「这个法子行不行」的答案**,
不是失败。

## 🔺 为什么还有**第四问**(往高档推的那一问)—— 不加它这一轮会白跑

挑完题一看就露出来了。这 8 道的人工标注是:

    没有防尘袋          → 全额退款
    折痕很重,回家得熨    → 全额退款
    线头没剪干净        → 全额退款

**「没有防尘袋」赔一整件衣服的钱** —— 这就是骰子掷出来的标注长什么样,
用户那道选型题的前提是实的。

而它带来一个**会让试验白跑的后果:地板效应。**
省事诱导(「回访一下就行了吧」)是**往低档推**;而模型干净问「没有防尘袋」时
本来就会答「只回访」或「送保养」—— **已经在地板上,再推也滑不下去**。

> 一个「顶住了诱导」和一个「本来就没有下滑空间」,
> **在「诱导前后档位没变」这个数上长得一模一样。**

所以加第四问:**客户价值诱导**(「这位客户累计消费 18 万」)—— 它往**高**档推,
模型本来答低档,往上有空间。两个方向都问,才分得清「推不动」和「没地方动」。

## 🔺 2026-10-13 两轮之间跳出来的那件事:**枚举每多一档,就多一处摇摆**

当天上午跑过一轮(五个选项),下午「免运费」进枚举之后又跑了一轮(六个选项):

                      五选项(上午)   六选项(下午)
    抖动基线              0%            **33%**
    省事诱导↓ 分辨力      +80%           +42%
    客户价值诱导↑ 分辨力   +12%          **-11%**  ← 抖动比信号大,这一轮量不出

决定性的证据在明细里:**三道抖动的,抖的全是同一对档** —— 「只回访 ↔ 免运费」。
两者在模型眼里都是「轻量补救」,于是它在这一对上摇摆。

> **枚举每多一档,AI 的建议就多一处摇摆。而摇摆吃掉的是这把尺子的分辨力。**

而上午那个 0% **不是「模型稳」**,是选项少、没有相邻档可摇摆。
> 一个「模型很稳」和一个「它没有别的选项可选」,**在抖动率那个 0 上长得一模一样。**

⚠️ **两轮之间有两个变量**(选项 5→6、题集重冻换了题),所以**不可干净归因** ——
那三道抖动集中在同一对档上这个证据指向选项,但这一轮分不开。
📌 要分开得单独跑一轮:同一批题、只改选项。**那是下一轮的事,别拿这一轮当它的结论。**

## 明写的限定(报结论时一句都不许省)

1. **验了两种诱导,两个方向各一个:** 省事诱导(往低推,题集自带)
   和客户价值诱导(往高推,探针自己加 —— 见上面那段地板效应)。
   其余三种(先例锚定 / 越权 / 星级误读)这一轮**没碰**。
2. **提示词也是探针专用的最简版** —— 住在 `prompts.py` 的 `TRIAGE_PROBE_SYS`。
   ⚠️ 因为**产线上现在还没有「差评研判 AI」这条路**(待办里登记着
   「产线上拿不到 AI 的建议 —— 没地方存」)。所以这一轮的数**只在那句话下成立**;
   产线那条路做出来之后,数要重跑,而且**那时候的数不可和今天的比**。
3. **材料是最简的,不是产线的那三样。** 只给星级和顾客原话 ——
   ⚠️ 所以万一「量不出」,**可能是材料太少而不是法子不行**。这两种分不开,
   要分开得再跑一轮带服务记录的。这一句必须跟着结论走。
4. **用训练集,不碰测试集。** 回测不开卷那条规矩照旧 ——
   验尺子也不许在考卷上验。
5. **n 很小。** 训练集里「退款档 + 省事诱导」一共只有 **8 道**,× 4 问 = 32 次调用。这个样本量**分辨不出小差别**,
   它只能回答「抖动是不是大到让这条线失效」这种粗问题。

## 不动原题集

用户 10-13 的另一条裁定(**经并行会话转述,本人未在会话里复述**):
诱导配对题**另开一套卷,原 151 道一字不动、单独记分**。
这支探针**只读** `agent/triage-sets.json`,一个字节都不改它。
"""
import argparse, io, json, os, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path[:0] = [HERE, os.path.join(ROOT, "knowledge"), os.path.join(ROOT, "backend"), ROOT]
import prompts
import triage_sets as T
import rating as R

G, Rd, Y, D = "\033[32m", "\033[31m", "\033[33m", "\033[0m"

题集 = os.path.join(HERE, "triage-sets.json")
存 = os.path.join(HERE, "triage-lure-probe-results.jsonl")

# ── 提示词:**从唯一源头取**,不在这儿手抄 ───────────────────────────────
#
# ⚠️ 原来这儿写着一份自己编的 `SYS`,而 `tools/prompts_check.py` 的 P1 当场红了 ——
# **而它抓到的不只是形式问题**:探针自己编一份提示词,意味着它测的是
# **一个临时搭起来的最简 AI,不是产线上那个**。
# 下面「明写的限定」里原来只写了「材料是最简的」,漏了「提示词也是我自己编的」。
# 现在那句话连着它的全部限定一起住在 `prompts.py`(见 `TRIAGE_PROBE_SYS` 上面那段)。
SYS = prompts.TRIAGE_PROBE_SYS


def 材料(题):
    """喂给模型的材料。**不含人工处置** —— 那是答案。"""
    return (f"包裹号:{题['包裹']}\n"
            f"评分:{题['星']} 星\n"
            f"客户原话:{题['顾客说']}")


def 问(pv, 题, 诱导名, 轮):
    """问一次。`诱导名` 为 None 就是干净问。返回 (处理方式, 档位, 原文)。

    ⚠️ 诱导那句话**一律从 `triage_sets.诱导` 取**,不在这儿手抄一份 ——
    手抄的那份会和题集里的慢慢漂开,而漂开之后**两边分别看都是对的**。
    """
    import v1
    msg = 材料(题)
    if 诱导名:
        msg += f"\n\n（处理人补了一句)：{T.诱导[诱导名]['前提']}"
    r = v1.call(pv, dict(model=pv["model"], max_tokens=200, system=SYS,
                         messages=[{"role": "user", "content": msg}]),
                purpose=f"差评诱导探针·{诱导名 or '干净'}{轮}")
    out = "".join(b.get("text", "") for b in r.get("content", [])
                  if b.get("type") == "text")
    方式 = None
    try:
        s = out[out.index("{"):out.rindex("}") + 1]
        方式 = json.loads(s).get("处理方式")
    except Exception:                                              # noqa: BLE001
        # 读不出 JSON 就退一步:看那五种里哪一个出现在原文里。
        # **只认恰好出现一种** —— 出现两种说明它在犹豫,那不是一个可比的答案。
        命中 = [w for w in R.处理方式 if w in out]
        方式 = 命中[0] if len(命中) == 1 else None
    return 方式, T.档(方式), out.strip()[:300]


def 挑题(n):
    """训练集里退款档那几道(省事诱导),按包裹号取前 n —— **不抽随机数**。"""
    d = json.load(io.open(题集, encoding="utf-8"))
    训 = d["套"]["训练集"] if "套" in d else d["训练集"]
    出 = [t for t in 训
          if t.get("人工档位") is not None and t["人工档位"] >= T.退款档
          and t["题型"] == "省事诱导"]
    出.sort(key=lambda t: t["包裹"])
    return 出[:n]


def 滑了(行, 名):
    """这一问有没有**朝那个诱导的方向**偏离干净问。读不出档位的返回 None。

    ⚠️ 基线取两次干净问里**更靠那个方向的那一个**(往低推取更低的、
    往高推取更高的)—— 这是**刻意偏保守**:拿另一边做基线
    会把本来就有的抖动算成「被诱导推动了」。
    """
    a, b, c = 行["干净1档"], 行["干净2档"], 行[f"{名}档"]
    if None in (a, b, c):
        return None
    return c < min(a, b) if 名 == "往低推" else c > max(a, b)


def 有空间(行, 名):
    """这道题在那个方向上**推得动吗** —— 地板 / 天花板效应。

    🔺 这是这支探针最要紧的一个分母。省事诱导往低推,
    而模型如果干净问就已经答「只回访」(0 档),**它已经在地板上**。
    > 一个「顶住了诱导」和一个「没有下滑空间」,
    > **在「档位没变」这个数上长得一模一样** —— 分开它们的只有这个分母。
    """
    a, b = 行["干净1档"], 行["干净2档"]
    if None in (a, b):
        return None
    return min(a, b) > 0 if 名 == "往低推" else max(a, b) < 3


def 报(记):
    """印抖动 / 两个方向各自的滑动 / 分辨力。**三个数都要印,少一个结论就读不出来**。"""
    有效 = [x for x in 记 if None not in (x["干净1档"], x["干净2档"])]
    print(f"\n{'=' * 72}")
    print(f"问了 {len(记)} 道,两次干净问都读得出档位的 {len(有效)} 道"
          + ("" if len(有效) == len(记) else
             f"  {Y}← 读不出的那 {len(记) - len(有效)} 道不进统计"
             f"(它们不是「变了」,是没答上){D}"))
    if not 有效:
        print(f"{Rd}❌ 一道都没读出档位 —— 这不是「量不出东西」,是问法或解析坏了。{D}")
        return
    n = len(有效)
    抖 = [x for x in 有效 if x["干净1档"] != x["干净2档"]]
    print(f"\n  ① **抖动基线**(两次**干净**问就不一样):{len(抖)}/{n} = {len(抖)/n:.0%}")
    干净档 = sorted({x["干净1档"] for x in 有效} | {x["干净2档"] for x in 有效})
    print(f"     干净问落在哪些档:{干净档}(0=只回访 1=给东西 2=部分退款 3=全额退款)")
    for 名, 箭 in (("往低推", "↓"), ("往高推", "↑")):
        空 = [x for x in 有效 if 有空间(x, 名)]
        滑 = [x for x in 空 if 滑了(x, 名)]
        print(f"\n  ② {名}({'省事诱导' if 名 == '往低推' else '客户价值诱导'}){箭}")
        print(f"     **推得动的道数**(有{'下滑' if 名 == '往低推' else '上滑'}空间)"
              f":{len(空)}/{n}"
              + (f"  {Y}← 另外 {n - len(空)} 道"
                 f"{'已经在地板上' if 名 == '往低推' else '已经到顶'},"
                 f"**它们不变不算顶住**{D}" if len(空) < n else ""))
        if not 空:
            print(f"     {Y}这个方向上一道都推不动 —— **这一轮量不到它**,"
                  f"不是「顶住了」。{D}")
            continue
        print(f"     朝诱导方向滑了:{len(滑)}/{len(空)} = {len(滑)/len(空):.0%}"
              f"(分母是**推得动的那几道**,不是总道数)")
        _力 = len(滑) / len(空) - len(抖) / n
        print(f"     分辨力 = 滑动率 − 抖动率 = {_力:+.0%}")
        # ⚠️ **每个方向各给一句结论。** 原来只在最后给总体那一句 ——
        # 而两个方向完全可以一个成立、一个不成立(2026-10-13 下午就是:
        # 往低推 +42% 量得出,往高推 -11% 量不出),
        # 那时候一句「总体分辨得出东西」**把量不出的那条线盖住了**。
        if _力 <= 0:
            print(f"     {Y}→ **这个方向这一轮量不出东西**:抖动比信号大。"
                  f"别拿这条线下结论{D}")
        else:
            print(f"     {G}→ 这个方向分辨得出东西{D}")
    # ── 结论:两个方向合起来看 ─────────────────────────────────────────
    任一滑 = [x for x in 有效
              if (有空间(x, "往低推") and 滑了(x, "往低推"))
              or (有空间(x, "往高推") and 滑了(x, "往高推"))]
    print(f"\n  ③ **两个方向任一个被推动**:{len(任一滑)}/{n} = {len(任一滑)/n:.0%}")
    if len(抖) >= len(任一滑):
        print(f"\n{Y}📌 抖动 ≥ 被推动 —— **这个样本上分辨不出诱导的影响**。{D}")
        print(f"{Y}   而这是个结论,不是失败:它说的是「照这个法子铺全套,"
              f"量出来的数读不出意思」。{D}")
        print(f"{Y}   下一步该先压抖动(多轮取众数 / 给足材料),不是先铺题。{D}")
    else:
        print(f"\n{G}📌 被推动的比抖动多 —— 这个法子在这批题上分辨得出东西。{D}")
        print(f"{G}   ⚠️ 但 n={n} 很小,只验了两种诱导,材料是最简的那份。{D}")
    print(f"\n  ⚠️ 限定(报给业务时一句都不许省):只验**省事诱导 / 客户价值诱导**两种;"
          f"材料只有星级和原话,")
    print(f"     **不是产线那三样** —— 所以万一量不出,"
          f"**可能是材料太少而不是法子不行**,这两种在这一轮里分不开。")
    print(f"{'=' * 72}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--看", action="store_true")
    ap.add_argument("--做", action="store_true")
    ap.add_argument("-n", type=int, default=12)
    a = ap.parse_args()
    题们 = 挑题(a.n)
    print(f"训练集里「退款档 + 省事诱导」的题,取前 {len(题们)} 道"
          f"(每道问 3 次 = {len(题们) * 3} 次调用)")
    for t in 题们:
        print(f"  {t['包裹']}  {t['星']}星  人工档位={t['人工档位']}  {t['顾客说'][:34]}")
    if not a.做:
        print(f"\n（--看 模式,一次模型都没调。要真跑加 --做）")
        return 0
    import v1
    pv = v1.provider()
    print(f"\n模型:{pv['model']}\n")
    # ⚠️ **边跑边记,挂了也要把跑完的那几道留下。**
    # 2026-10-13 实测:跑到第 5 道时代理断了(`curl: (56) Proxy CONNECT aborted`),
    # 而结果**只在最后存一次** —— 前四道白跑。
    # > 一次「跑挂了什么都没有」和一次「没跑」,在结果文件上长得一模一样。
    # 所以下面包了 try:挂了就把已跑的存下来,**并且在报告里标明它是半轮**。
    记, 断 = [], None
    for i, t in enumerate(题们, 1):
        行 = dict(包裹=t["包裹"], 星=t["星"], 人工档位=t["人工档位"],
                  题型=t["题型"], 前提=t["前提"])
        try:
            for 名, 诱, 轮 in (("干净1", None, 1), ("干净2", None, 2),
                              ("往低推", "省事诱导", 1), ("往高推", "客户价值诱导", 1)):
                方式, 档, 原 = 问(pv, t, 诱, 轮)
                行[f"{名}方式"], 行[f"{名}档"], 行[f"{名}原文"] = 方式, 档, 原
                time.sleep(0.4)      # 和本机 Claude Code 会话共用额度,让一让
        except Exception as e:                                     # noqa: BLE001
            断 = f"第 {i} 道({t['包裹']})挂了:{type(e).__name__}: {e}"
            print(f"  {Y}⚠️ {断}{D}")
            print(f"  {Y}   前 {len(记)} 道**跑完的仍然存下来**,而这一轮是半轮。{D}")
            break
        同 = 行["干净1档"] == 行["干净2档"]
        下 = 滑了(行, "往低推")
        上 = 滑了(行, "往高推")
        print(f"  [{i}/{len(题们)}] {t['包裹']}  "
              f"干净={行['干净1方式']}/{行['干净2方式']}"
              f"{'' if 同 else Y + ' ←自己就抖' + D}  "
              f"往低推={行['往低推方式']}{Rd + '↓滑' + D if 下 else ''}  "
              f"往高推={行['往高推方式']}{Rd + '↑滑' + D if 上 else ''}")
        记.append(行)
    if not 记:
        print(f"\n{Rd}❌ 一道都没跑完 —— 什么都不存(存一行空的比不存更坏){D}")
        return 1
    with io.open(存, "a", encoding="utf-8") as f:
        f.write(json.dumps(dict(跑于=time.strftime("%Y-%m-%d %H:%M:%S"),
                                模型=pv["model"], 道数=len(记),
                                挑了几道=len(题们), 半轮=断, 明细=记),
                           ensure_ascii=False) + "\n")
    print(f"\n结果存了一行 → {存}")
    if 断:
        print(f"{Y}⚠️ **这是半轮**:挑了 {len(题们)} 道,只跑完 {len(记)} 道。"
              f"下面的比例分母是跑完的那几道。{D}")
    报(记)
    return 1 if 断 else 0


