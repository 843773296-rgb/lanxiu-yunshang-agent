#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""评测期间的**接管状态**:开跑时记一次、收尾时核一次,变了就不许写结果。

## 为什么要这个(2026-10-27 真撞上的)

技能被工作流接管之后,`agentsite/sdk.py` 的规矩是「**技能被拦**,改走工作流」。
所以同一道题,接管开着和关着,**正确行为是相反的**:

    接管关着 → 应该触发技能
    接管开着 → 技能被拦,应该走工作流

而评测的真值只写了「应触发 store-report」。于是接管一开,评测把它记成**漏触发**,
而那一栏的标题是「用户拿到的是随口答的东西」—— 完全反了,那是接管生效,是设计。

> 一个「模型漏了该走的技能」和一个「这件事现在由工作流接管、本来就不该走技能」,
> **在「漏触发」那一栏里长得一模一样。**

**更要紧的是第二层**:`LANXIU_USAGE_URL` 没配时 `takeover_client.配置()` 返回 None,
接管当**全关**。而生产的 store-report 是**开着**的。所以:

> 一个「评测通过了」和一个「评测跑在一个接管全关的环境里,而生产是开着的」,
> **在分数上长得一模一样。**

那三道周报题在评测里测的那条路(走 store-report 技能)**生产根本不走**,
而且测得很好,2/2 全对。

## 这个模块管两件,第二件是新的

① **把这一轮的接管状态记下来**,让成绩单印出来 —— 口径跟着数走
   (「每个数带口径」那条规矩在这里的样子)。**只改真值不印口径,
   以后两版基线的接管状态不同时照样分不开。**
② **评测期间接管状态不许变**。它是运行时配置,`git log` 里看不见 ——
   2026-10-27 并行会话在我跑评测的中间切了一次生产版本,我是从它的消息里
   才知道的,不是从代码里。变了就**拒绝写结果**,和「环境故障就不盖章」同一个形状:
   **一份跑在两种配置上的成绩单,和一份跑在一种配置上的,在分数上长得一样。**
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))


def 读状态():
    """→ {"接管中": [技能名…], "连上了": bool, "说明": str}。**读不到不抛**,如实说读不到。

    ⚠️ 「一个技能都没被接管」和「根本没连上管理后台」**不是一回事** ——
    前者是生产的真实状态,后者是评测环境和生产不一样。两个都返回空列表的话
    就分不开了,所以 `连上了` 单独记一个。
    """
    try:
        sys.path.insert(0, os.path.join(os.path.dirname(HERE), "backend"))
        import takeover_client as tc
    except Exception as e:
        return {"接管中": [], "连上了": False, "说明": f"读不到 takeover_client({e})"}
    cfg = None
    try:
        cfg = tc.配置()
    except Exception as e:
        return {"接管中": [], "连上了": False, "说明": f"配置读失败({e})"}
    if not cfg:
        return {"接管中": [], "连上了": False,
                "说明": "没配 LANXIU_USAGE_URL —— **接管当全关**,"
                        "而生产可能是开着的:这一轮测的不是生产的那条路"}
    try:
        items = tc.清单(强制=True) or []
    except Exception as e:
        return {"接管中": [], "连上了": True, "说明": f"连上了但清单读失败({e})"}
    名 = sorted({(x.get("skill") or x.get("技能") or str(x)) for x in items}) if items else []
    return {"接管中": 名, "连上了": True,
            "说明": (f"接管中 {len(名)} 个:{'、'.join(名)}" if 名 else "连上了,一个都没接管")}


def 一句话(状态):
    """印在成绩单上的那一行 —— 口径跟着数走。"""
    if not 状态.get("连上了"):
        return ("⚠️ **工作流接管:没连上管理后台,这一轮按「全关」跑** —— "
                "生产若有技能被接管,那几题测的路生产不走,分数和生产不可比")
    名 = 状态.get("接管中") or []
    return (f"工作流接管:{len(名)} 个技能被接管({'、'.join(名)})—— 它们**应该走工作流,不走技能**"
            if 名 else "工作流接管:连上了,一个技能都没被接管(这一轮的真值按「走技能」算)")


def 变了吗(开跑, 收尾):
    """→ (变了吗, 一句话)。**变了就该拒绝写结果。**"""
    if 开跑.get("连上了") != 收尾.get("连上了"):
        return True, (f"⚠️ **这一轮中间管理后台的连接状态变了**"
                      f"(开跑 连上了={开跑.get('连上了')} → 收尾 {收尾.get('连上了')})—— "
                      f"**不写结果**:前后两半跑在不同配置上,而那种污染在成绩单上看不出来")
    a, b = set(开跑.get("接管中") or []), set(收尾.get("接管中") or [])
    if a != b:
        return True, (f"⚠️ **这一轮中间接管状态变了**(多了 {sorted(b - a) or '无'}、"
                      f"少了 {sorted(a - b) or '无'})—— **不写结果**:"
                      f"被接管的技能「应该走工作流」,没被接管的「应该走技能」,"
                      f"真值前后不一致,这份成绩单没有主语")
    return False, "接管状态全程没变"


def 自测():
    坏 = []
    A = {"接管中": ["store-report"], "连上了": True}
    B = {"接管中": ["store-report"], "连上了": True}
    C = {"接管中": ["store-report", "quote"], "连上了": True}
    D = {"接管中": [], "连上了": False}
    if 变了吗(A, B)[0]: 坏.append("状态没变不该拦")
    if not 变了吗(A, C)[0]: 坏.append("接管的技能变了要拦")
    if not 变了吗(A, D)[0]: 坏.append("连接状态变了要拦")
    # ⚠️ 「一个都没接管」和「没连上」不许说同一句话
    if 一句话({"接管中": [], "连上了": True}) == 一句话(D):
        坏.append("「一个都没接管」和「没连上」要说不同的话(前者是生产状态,后者是环境不一样)")
    if "全关" not in 一句话(D):
        坏.append("没连上时要明说按全关跑、和生产不可比")
    真 = 读状态()
    if not isinstance(真, dict) or "连上了" not in 真:
        坏.append("读状态要返回带「连上了」的字典")
    print("接管状态守卫 · 自测")
    for x in 坏: print(f"  ✗ {x}")
    print(f"  这台机器实测:{一句话(真)}")
    if 坏:
        print(f"\033[31m❌ {len(坏)} 条不过\033[0m"); return 1
    print("\033[32m✅ 五条都对:状态没变不拦 / 技能变了拦 / 连接变了拦 / "
          "「没接管」≠「没连上」/ 没连上要明说不可比\033[0m")
    return 0


if __name__ == "__main__":
    sys.exit(自测())
