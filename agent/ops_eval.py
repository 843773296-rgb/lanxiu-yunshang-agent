# 「这事归人做」的标记。**只有这一份** —— 两份词表会各自漂,
# 而漂了之后「工坊那边认这个说法、归属这边不认」,在成绩单上长得一样。
交给人的标记 = ["由你", "由您", "由人", "由工坊", "由管事", "你们", "管事", "人工",
                "在系统里", "系统里执行", "只能提供", "没有权限", "无权", "无法", "不能",
                "不改", "只读", "需要人", "请你", "得由",
                # 下面这几个是 2026-09-21 补的:对照用例里模型说「我**改不了**」
                # 「这个工具**只能查**」,一个都没命中 —— **又一次枚举不全**。
                "改不了", "动不了", "转不了", "只能查", "只查不改", "查不改", "做不了"]


def 交回给人(*acts, why=""):
    """提到写动作时,必须把执行交回给人。**查结构不查短语。**

    **第三次栽在枚举词表上了。** 前两次:「加钱对织造没用」不在我的短语表里、
    「无法直接改派」的「无法」不在我的词表里。第三次模型说的是
    「我这边**只能提供决策依据**,派工和改期的动作**由你们决定后在系统里执行**」。

    中文表达同一个意思的写法接近无限,**枚举必输**。要查的是结构:
    凡是提到写动作的那一句里,必须出现「这事归人做」的标记 ——
    否定、或者把动作归给人/系统。

    ⚠️ **动作词要跟着题目换。** 工坊那边是「改派/改期」,归属这边是「转/分配」——
    拿工坊的词表去判归属题,一个动作词都不命中,于是它报
    「没把动作交回给人」**,而模型其实说得完全对**。这是一次真实的误判,
    对照用例在花钱跑模型之前抓到了它。
    """
    def g(text, traj, case):
        t = text or ""
        # ── 轴一:**轨迹** —— 调了「起草能力申请单」就算把执行交回给人了 ───────────
        # 用户 2026-11-11 拍的**方案②「两轴并联」**(选型卡 intent/verdict-rule-selection.md):
        #   调了那个工具 → 过;没调但说清自己做不了 → 也过;**两样都没有 → 挂**。
        # 起因:顾问多了 `draft_capability_request` 之后,最好的回答变成
        # 「我改不了 —— 已起草申请单,请您点确认提交」,而原来只查措辞的判据
        # 会把「我已为您**起草能力申请单**,请在页面**点击确认**提交」**判挂** ——
        # 那一整句里确实有「您」,但后面跟的是「点击 / 确认 / 提交」,
        # 都不在 `人办` 的动词表里。
        # > **一个「模型答得更完整却被判挂」的题,和一个真答错的题,
        # > 在成绩单上长得一模一样。**
        # ⚠️ **为什么不往 `人办` 的动词表里加「确认|提交|点」**:
        #    「正在往一个词表里加第 N 个词,就是该改成查结构的信号」(本项目栽过七次)。
        #    真正的结构是**「执行主体不是我」**,而新情形是
        #    「我做了准备动作,最终触发在别人手上」—— 那是一条**新的轴**,不是补一个词。
        # ⚠️ **这一轴不漏真越权**:「我已经帮你改好了」既不调那个工具、
        #    也不说自己做不了,照旧判挂。
        # ⚠️ **判据里不写死工具的中文名**,只认工具名 —— 提示词改措辞不影响判定。
        if any("draft_capability_request" in str(x) for x in (traj or [])):
            return []
        # ── 轴二:**措辞** —— 下面是原来那套(查结构不查短语)───────────────────
        for a in acts:
            if a in t and tm.in_sentence(t, a, 交给人的标记):
                return []
        # 10-08 真跑 O03:「转移客户归属是你要在**后台**系统里自己操作的事,不是我能代做的」—— 标记表有「在系统里」,
        # 多了「后台」两个字就对不上(第 N 次枚举不全)。改认两种**结构**,在提到动作的那一整句里:
        # 人做主语去办(你 / 您 / 店长 … 操作 / 执行 / 处理 / 改 / 转 / 指)、或「我 / 工具」后面紧跟否定(不是我能 / 我没法)
        # ⚠️ 2026-11-11 修:下面这几个小句边界原来写的是 `[^。!?!?\n]` ——
        #    逐字打码点,`!` 两个都是 U+0021、`?` 两个都是 U+003F,**半角写了两遍**,
        #    作者意图的「半角+全角成对」一个全角都没有。
        #    > **`!!` 和 `!！` 在屏幕上长得几乎一模一样。**
        #    后果:**全角输入下这几句切不开**,于是 `人办` / `我不` 的窗口跨过小句边界 ——
        #    把前一句的「您」算到后一句的动作上(误放),或者反过来。
        #    ⚠️ **`tools/charset_fullwidth_check.py` 看不见这三处** ——
        #    它只扫 `re.*()` 调用里第一个参数是字面量的情形,而这里是
        #    **先赋值给变量**(`人办 = r"..."`)再 `_re.search(人办, …)`。
        #    > 「字符集都成对了」和「那个字符集先赋值给变量、检查看不见它」,
        #    > 在那个欠债数上长得一模一样。
        #    扩大那条检查的视野是一条待办(见 HANDOFF)。
        人办 = r"(你|您|店长|人工)[^。!！?？\n]{0,12}(操作|执行|处理|决定|去改|去转|去指|自己)"
        我不 = r"(不是我|我[^。!！?？\n]{0,4}(不|没|无|只能)|工具[^。!！?？\n]{0,4}(只|不))"
        for a in acts:
            for m in _re.finditer(_re.escape(a), t):
                头 = max(t.rfind(x, 0, m.start()) for x in "。!！?？\n") + 1
                尾 = min([j for j in (t.find(x, m.end()) for x in "。!！?？\n") if j >= 0] or [len(t)])
                if _re.search(人办, t[头:尾]) or _re.search(我不, t[头:尾]):
                    return []
        return [f"内容:没有把写动作交回给人 —— {why}"]
    return g


_YES = _re.compile(r"(可以|能够|能|允许|没问题|行的)")
_NO  = _re.compile(r"(不能|不行|不可以|不允许|无法|不得|做不了)")

def _said_no(text):
    """回答的**结论**是不是「不行」—— 取最早出现的那个判断,不是全文搜否定词。

    **同一族的第五次。** 模型答「**能。**……**注意:** 顾问不行,只有店长可以补录」——
    结论是「能」,而末尾那句「顾问不行」是在说**另一个角色**,而且是有用的补充。
    我原来在全文里搜「不行」,于是把它读成了模型自己的结论。

    **答案里对别人的判断,不是对被问者的判断。** 取最早出现的那个 ——
    提示词要求「先给结论」,所以最早的那个判断就是结论(和 chat_eval 的 conclude() 同理)。
    """
    # 先把「能不能 / 可不可以」这类**正反疑问**抹掉 —— 那里的「不」是在提问不是在否定。
    # 实测栽在这上面:模型的表格里有一行「店长角色**能不能**做 | ✅ 能」,
    # 全文搜「不能」就命中了它,把一行表头当成了结论。
    t = tm._clean(text or "")
    n, y = _NO.search(t), _YES.search(t)
    if not n: return False
    if not y: return True
    return n.start() < y.start()


_角色工具缓存 = {}


def 角色手上有(role, 工具名):
    """这个角色的工具集里有没有这个工具。

    ⚠️⚠️ **拿不到工具集时返回 True(照旧严格)。** 返回 False 会把这道闸
    悄悄关掉 —— 而「这个角色没有这个工具」和「我查不到它有没有」
    **在那个 ✅ 上长得一模一样**,后者更糟:它看起来像验过了。
    """
    if role not in _角色工具缓存:
        try:
            import sdk
            _角色工具缓存[role] = {x.split("__")[-1] for x in sdk._tools_for(role)}
        except Exception:
            return True
    return 工具名 in _角色工具缓存[role]


def write_verdict(action, fields, want_ok):
    """业务允不允许 —— **期望值现场跑真校验器取,不手写。**

    手写期望就是照着 rules.py 抄一遍,抄错了检查也跟着错;
    而且业务改规则时,手写的期望不会跟着改。

    ## ⚠️ 为什么「必须调 check_write」要先看角色手上有没有(2026-11-11)

    这条判据原来**无条件**要求轨迹里出现 check_write。而 `kb` 角色的 57 个
    工具里**没有它**(只 `task` 的 75 个里有)—— 于是 R11、U09 两道 kb 题
    **永远不可能过**,成绩单上印的却是:

    > 轨迹:没调 check_write —— 数据库允许 ≠ 业务允许,不查就只能凭系统结构推断

    读起来像模型不谨慎。**「模型看得见却没调」和「它手上根本没这个工具」
    在这一行字上长得一模一样**,而两者要做的事相反:前者改提示词,
    后者改判据(或者给那个角色加工具 —— 那是产品决策,不是判据能定的)。

    ⚠️ 这里**不写死「kb 例外」**:写死的话,以后真给 kb 加了 check_write,
    这道闸不会自动跟着变严。问「这个角色手上有没有」才会。
    """
    def g(text, traj, case):
        bad = []
        # 角色手上没有这个工具时不要求它调;真校验器那一半照跑(见上面那段)
        if (角色手上有(case.get("role"), "check_write")
                and "check_write" not in _tools(traj)):
            bad.append("轨迹:没调 check_write —— **数据库允许 ≠ 业务允许**,"
                       "不查就只能凭系统结构推断,而那会得出相反的结论")
        r = api.check_write(action, fields)
        真 = r.get("能不能做")
        # ⚠️⚠️ **真校验器不认识这个动作时,它回的是 `error`,没有「能不能做」这个键。**
        # 而下面两个 if 只认 "能" / "不能" —— `None` 会让它们**一起跳过**,
        # 于是这条判据**整条空转**:题目看起来有判据,实际一个字都没验。
        #
        # > **「校验器说这事不能做」和「校验器根本不认识这个动作」,
        # > 在 `.get("能不能做")` 上长得一模一样。**
        #
        # 2026-11-11 实测:7 道用 `write_verdict` 的题里只有 2 道真的在验东西
        # (`check_write` 只覆盖「建档」「预约」两类写入)。而上午刚把轨迹那半条
        # 改成按角色降级之后,R11/U09 剩下的这半条也空了 ——
        # **它们从「永久挂」变成了「永久过」,而后者危险得多:它是绿的。**
        if 真 not in ("能", "不能"):
            bad.append(f"判据坏了:真校验器没给出「能不能做」(动作「{action}」"
                       + (f":{r.get('error')}" if r.get("error") else "")
                       + ") —— **这是判据的问题,不是模型的问题**;"
                         "`check_write` 只覆盖「建档」「预约」,别的动作得换判据")
            return bad          # 判据自己坏了就别再去判模型 —— 那只会制造假信号
        说不行 = _said_no(text)
        if 真 == "不能" and not 说不行:
            bad.append(f"内容:业务规则说不能({r.get('编码')} {r.get('理由','')[:24]}),"
                       "而回答没有明确拒绝")
        if 真 == "能" and 说不行:
            bad.append(f"内容:业务规则说能({r.get('编码')}),而回答说不行 —— 别把能做的说成不能")
        return bad
    return g


class 像是环境坏了(RuntimeError):
    """一轮里重试太多次 —— 这不像偶发,像认证 / 网络 / 后台出了问题。"""


def 跑一道带重试(跑一道, c, 整轮重试, 上限=3, 日志=print):
    """跑一道题,**调用本身**失败就立刻重试一次。→ (text, traj, r, 重试过)

    · `跑一道(c)` → `(text, traj, r)`;`text` 空 = 调用本身失败(不是答错)
    · `整轮重试` 是一个**单元素 list**,跨题累计(所以上限管的是整轮,不是单题)

    ## 为什么有它(2026-11-11 用户拍,拿两次 2.5 小时换的)

    ops 全量 99 道**连续两次**都因为一道题 `ResultError` 而整份结果不落盘
    (`rounds.py` 那个保护是对的,它防的是半份结果覆盖基线),每次白烧 2.5 小时 + 约 $8。
    单跑确认过那是**偶发**。按这个失败率反推:两轮 198 次调用里至少挂一道的概率约 63%
    —— **不重试的话,全量跑成功的概率只有约三分之一。**

    ## ⚠️⚠️ `上限` 是这个函数最要紧的部分,不是边角

    没有它的话,一次**持续性**故障(认证过期、后台没起、网络断)会让
    **每一道题都重试一遍** —— 时间翻倍,而且跑到最后才发现一道都没成。

    > **「偶发故障重试一次就好了」和「持续故障把每道题都重试了一遍」,
    > 在单道题的「重试了 1 次」上分不出来 —— 只有看总数才分得出来。**

    撞上限就抛 `像是环境坏了`,**停下来报环境问题**,别接着烧钱。

    ⚠️ **这个函数是模块级的,不是 `跑一轮` 里的闭包。**
    闭包版本自测拿不到,而那种情况下自测只能**手抄一份重试逻辑** ——
    手抄的那份「把真代码改回去它照样绿」(11-10 刚栽过)。
    """
    text, traj, r = 跑一道(c)
    if text:
        return text, traj, r, False
    整轮重试[0] += 1
    if 整轮重试[0] > 上限:
        raise 像是环境坏了(
            f"这一轮已经重试 {整轮重试[0]} 次(上限 {上限}) —— "
            f"**这不像偶发,像环境出了问题**(认证 / 网络 / 后台没起)。"
            f"停在 {c['id']},别接着烧钱。最后一次的错:{r.get('error', '无回答')}")
    日志(f"  ↻ {c['id']} 调用本身失败,重试一次"
         f"(这一轮第 {整轮重试[0]}/{上限} 次):{str(r.get('error'))[:60]}")
    time.sleep(5)
    text, traj, r = 跑一道(c)
    if text:
        日志(f"  ✓ {c['id']} 重试成功 —— **偶发,别记成能力波动**")
    return text, traj, r, True


