def 调用次数不超过(name, n, why=""):
    """某个工具最多调几次。**这条按轨迹判,不按说法判。**

    要测的是「别对整张清单逐个深判」——而这件事在**说法**上枚不完
    (「我先确认第一个」「要不要我逐个查」「这会调 5 次模型」……),
    在**轨迹**上却只有一个数:它调了几次。
    **能在轨迹上判的,就不要放到词表里判。**
    """
    def g(text, traj, case):
        c = sum(1 for t in traj if t.split("__")[-1] == name)
        return [] if c <= n else [f"轨迹:{name} 调了 {c} 次(最多 {n} 次)—— {why}"]
    return g


