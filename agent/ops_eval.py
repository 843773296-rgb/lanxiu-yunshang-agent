def must_say(*needles, why=""):
    """必须说到这些里的**任意一个**。

    ⚠️ **这是全项目最容易出误报的一种判据。** 它枚举中文说法,
    而中文说法枚不完 —— 这个项目为「枚举中文说法必输」栽过八次。
    漏一个词的后果是:**一份答对的回答被判挂**,然后有人去改一个
    本来正确的提示词。**误报比漏报贵。**

    所以判据把自己的词表记在函数上(`g.needles`),
    让 `tools/vocab_check.py` 能查一件事:

    > **每条枚举词表,都要有一条「用非首选说法答对」的对照用例。**

    只有首选说法被验过的词表,和一个只认一个词的判据没有区别 ——
    **而它看起来是有备选的。**
    """
    def g(text, traj, case):
        return [] if tm.says(text, list(needles)) else [f"内容:没说到「{needles[0]}」—— {why}"]
    g.needles = list(needles)          # 给 vocab_check 用
    g.why = why
    return g

def must_not_promise(*needles, why=""):
    """**未被否定地**出现才算违规 —— 「不代表能挽回」不该判成承诺了挽回。"""
    def g(text, traj, case):
        hit = tm.says(text, list(needles))
        return [f"内容:**{why}**(未加否定地说了「{hit}」)"] if hit else []
    return g


_NUM_NEAR = _re.compile(r"(\d+\s*%|\d+\s*(个|位|人|成))")

# 引号:模型举「我不会说的话」当例子时,内容都在引号里
_QOPEN, _QCLOSE = "「\u201c\"『", "」\u201d\"』"
_DENY = ["不能", "不会", "不该", "不得", "别", "不要", "勿", "不应", "禁止", "不可"]

def _quoted_example(text, i, look=18):
    """位置 i 是不是落在一段**被否定的引文**里 —— 那是举例,不是断言。

    第四次栽在同一族上了。前三次是枚举词表,这次更细:
    模型写的是「但**不能说「打完能挽回 60%」这样的数字**」——
    它在举一个自己**不会说**的例子,而例子里有数字。

    而 textmatch.negated 的作用域到 `「` 就停了(引号被当成标点边界),
    所以看不见前面的「不能说」。**引号切断了否定的作用域,而否定管的正是整段引文。**

    判法:找到包住 i 的那对引号,看**开引号之前**有没有否定词。
    「复述用户的问题不是承诺」和「举反面例子不是承诺」是同一条:**引用不是断言。**
    """
    a = max((text.rfind(q, 0, i) for q in _QOPEN), default=-1)
    if a < 0: return False
    b = min((x for x in (text.find(q, i) for q in _QCLOSE) if x >= 0), default=-1)
    if b < 0: return False
    before = text[max(0, a - look):a]
    return any(d in before for d in _DENY)

def must_not_quantify(*needles, why=""):
    """不许**给出数字**。只说词不算,给了数才算。

    P03 原来用 must_not_promise("能挽回"),被模型**复述用户问题**的那句
    「还是你已经有现成的名单,想问我能挽回多少?」判成了承诺 ——
    而它紧接着就说「按优先级打完也没法预测挽回率」。
    **复述问题不是承诺。** 承诺的标志是给出数字,所以判据改成查数字。
    """
    def g(text, traj, case):
        t = text or ""
        for n in needles:
            i = t.find(n)
            while i >= 0:
                seg = t[max(0, i - 40): i + 40]
                m = _NUM_NEAR.search(seg)
                if m and not tm.negated(t, i) and not _quoted_example(t, i):
                    return [f"内容:**{why}**(「{n}」附近给了数:{m.group()})"]
                i = t.find(n, i + 1)
        return []
    return g

# 结论位置的标记词。判「哪一档」时,档位名必须出现在**下结论的那个小句**里,
# 而不是随便出现在文中某处。
_CONCL = ["是", "属于", "判", "应为", "算", "归", "档"]
_STOP = "。,,、;;::!!??\n\r"

def _concl_pos(text, word):
    """word 是不是出现在**下结论**的位置。返回位置,不是则 None。

    结论标记(是 / 属于 / 判为)出现在档位名**之前**:「C10001 **是**潜在流失」。
    而 textmatch.in_clause 只看词**之后**的小句 —— 它是为「腰围只给区间」
    那种后置限定造的,方向反了,所以这里自己往前取。
    **作用域的方向和粒度一样重要,不能想当然复用。**
    """
    i = text.find(word)
    while i >= 0:
        j = i
        while j > 0 and text[j - 1] not in _STOP: j -= 1
        if any(n in text[j:i] for n in _CONCL): return i
        i = text.find(word, i + 1)
    return None

def lifecycle_is(cust):
    """期望值**从库里读**,不手写 —— 手写就是照着实现抄期望。

    ⚠️ 第一版写成 `tm.mentions(text, [want])`,被判分器对照当场抓到:
    答案「C10001 是**高价值**客户,同时命中忠诚和**潜在流失**」判成了过 ——
    因为「潜在流失」确实出现在文本里,出现在**命中列表**里,不是结论位置。
    **这是「提到没提到」而不是「做了没做」,这个项目栽过六次,我又写了一次。**

    改法:八个档位里,取**最早出现在结论小句**的那一个当作它的结论,
    再和库里的值比。命中列表里的档位不在结论小句里,不会被误当成结论。
    """
    import lifecycle as _lc
    def g(text, traj, case):
        r = api.get_lifecycle(customer=cust)
        want = (r.get("rows") or [{}])[0].get("生命周期")
        if not want: return ["判分器:库里查不到这个客户,夹具不成立"]
        said, pos = None, 10 ** 9
        for lc in _lc.PRIORITY:
            i = _concl_pos(text or "", lc)
            if i is not None and i < pos: said, pos = lc, i
        if said == want: return []
        return [f"内容:结论说的是「{said or '(没说出档位)'}」,库里是「{want}」"]
    return g

def must_list_matched(cust):
    """多条命中时必须把命中列表说出来 —— 只报结论运营无从判断算得对不对。"""
    def g(text, traj, case):
        r = api.get_lifecycle(customer=cust)
        m = (r.get("rows") or [{}])[0].get("命中") or []
        if len(m) < 2: return []
        got = [x for x in m if tm.mentions(text, [x])]
        return [] if len(got) >= len(m) - 0 else \
               [f"内容:命中 {len(m)} 条({'/'.join(m)}),只说了 {len(got)} 条 —— "
                "只报结论,运营无从判断算得对不对"]
    return g

# ── 库存预警专用:**不许给出一个可售天数** ──────────────────────────────
# 为什么要专门写一个,而不是 must_not_quantify("天"):
# 「订单只跨 18 天」「18 天里只卖过一笔」这些是**该说的事实**,它们也带着「天」。
# 要挡的只有一种句子:**把一个数当成「这些货还能卖几天」说出来**。
#
# ⚠️ 这里**故意枚举了说法**,而枚举中文说法这个项目栽过八次 ——
# 区别在于**偏错的方向**:这是 forbid 侧,枚举漏一个只会**放过**一条违规(漏报),
# 而 must_say 侧枚举漏一个会**冤枉一个答对的**(误报)。
# **误报比漏报贵** —— 一条误报会让人去改一个本来正确的答案。
_卖几天 = _re.compile(
    r"(可售|还能卖|还能撑|能卖|够卖|撑得|卖得完|库存天数|周转天数)"
    r"[^。;,\n]{0,12}?(\d+(?:\.\d+)?)\s*天")

# 「这个 SKU 没有销量」的说法。**只用在 forbid 侧** ——
# 枚举漏一个只会放过一条违规(漏报),不会冤枉一个答对的(误报)。
_没销量 = ("零销量", "没卖过", "没有销量", "无销量", "一笔都没", "一件都没",
           "0 销量", "零销售", "未产生销量", "没有成交")


def 不许给零销量的编天数(why=""):
    """**只有「给没卖过的那些编了个天数」才算违规。**

    ⚠️ **这条判据 2026-09-16 收窄过一次,而原来那版把正确答案判成了违规。**

    原来是一刀切:**文本里任何地方出现「还能卖 N 天」就算编**。
    写它的时候全库**一个 SKU 都算不出可售天数**(71/805 有销量、每个只有一笔),
    所以那个一刀切是成立的 —— 任何天数必然是编的。

    当天下午模拟销量灌进来,**292 个 SKU 算得出了**。于是一份
    标准答案(开口就是「我不能给这个数」,只给真有销量那些的天数)
    被判成了违规 —— **因为它在别处引用了一个合法的天数**。

    > **一条判据可以把「当时的数据长什么样」悄悄编进去**,
    > 而数据一变,它开始冤枉正确的答案,**而且红得理直气壮**。

    收窄成:**天数出现在一句同时说着「没卖过」的话里**才算编。
    这条不随数据变 —— 没销量就是算不出,什么时候都成立。
    """
    def g(text, traj, case):
        t = text or ""
        for m in _卖几天.finditer(t):
            if _quoted_example(t, m.start()):
                continue          # 举「我不会说的话」当例子,不算
            if tm.negated(t, m.start()):
                continue          # 「算不出还能卖几天」不算
            # **只看这一句** —— 同一句里说着「没卖过」又给了天数,才是编的
            seg = tm.in_sentence(t, m.group(0), list(_没销量))
            if seg:
                return [f"内容:**{why}**(在一句说着「没销量」的话里给了"
                        f"「{m.group(0)}」)"]
        return []
    return g


def all_of(*gs):
    """把几条判据串起来。**子判据的词表要透出来** ——
    套一层 all_of 就查不到 needles 的话,`vocab_check` 会以为这道题没有枚举词表,
    **而全项目的 must_say 几乎都套在 all_of 里**。"""
    def g(text, traj, case):
        out = []
        for x in gs: out += x(text, traj, case)
        return out
    g.parts = list(gs)
    return g

