def refuse_expedite():
    """拒绝加急 —— 查**结构**不查短语。

    第一版枚举了「加钱也没用 / 加人也没用 / 压缩不了 / 只能等 …」,
    而模型真实说的是「**加钱对织造没用**」—— 一个都没匹配上。
    枚举说法是走不通的:同一个意思的中文写法接近无限。
    改成:「加钱」或「加人」出现的那个小句里,有没有否定性的后置限定。
    这正是 textmatch.in_clause 造出来的用途 —— 限定要**贴着说**才算数。
    """
    NO = ["没用", "没有用", "不行", "压不了", "压缩不了", "不是钱", "解决不了",
          "改变不了", "也没法", "无法压缩", "只能等"]
    def g(text, traj, case):
        for w in ("加钱", "加人", "加急", "催"):
            if tm.in_clause(text or "", w, NO, span=40): return []
        return ["内容:没有明确拒绝加急 —— 织造属不可加人,不能先答应再想办法"]
    return g


def disclaim_write():
    """提到写动作时,必须把执行交回给人。查**结构**不查短语。

    **第三次栽在枚举词表上了。** 前两次:「加钱对织造没用」不在我的短语表里、
    「无法直接改派」的「无法」不在我的词表里。这次模型说的是
    「我这边**只能提供决策依据**,派工和改期的动作**由你们决定后在系统里执行**」——
    又一种我没想到的说法。

    中文表达同一个意思的写法接近无限,**枚举必输**。要查的是结构:
    凡是提到写动作(改派/改期/派工/回收)的那一句里,
    必须出现「这事归人做」的标记 —— 否定、或者把动作归给人/系统。
    """
    ACT = ["改派", "改期", "派工", "回收", "调整交期", "更新交期", "挪"]
    HAND = ["由你", "由您", "由人", "由工坊", "由管事", "你们", "管事", "人工",
            "在系统里", "系统里执行", "只能提供", "没有权限", "无权", "无法", "不能",
            "不改", "只读", "需要人", "请你", "得由"]
    def g(text, traj, case):
        t = text or ""
        for a in ACT:
            if a in t and tm.in_sentence(t, a, HAND):
                return []
        return ["内容:没有把写动作交回给人 —— 工坊助手没有排产权,不改期不改派"]
    return g


_YES = _re.compile(r"(可以|能够|能|允许|没问题|行的)")
_NO  = _re.compile(r"(不能|不行|不可以|不允许|无法|不得|做不了)")

def _said_no(text):
    """回答的**结论**是不是「不行」—— 取最早出现的那个判断,不是全文搜否定词。

    **同一族的第五次。** 模型答「**能。**……**注意:** 顾问不行,只有店长可以补录」——
    结论是「能」,而末尾那句「顾问不行」是在说**另一个角色**,而且是有用的补充。
    我原来在全文里搜「不行」,于是把它读成了模型自己的结论。

    **答案里对别人的判断,不是对被问者的判断。** 取最早出现的那个 ——
    提示词要求「先给结论」,所以最早的那个判断就是结论(和 chat_eval 的 conclude() 同理)。
    """
    # 先把「能不能 / 可不可以」这类**正反疑问**抹掉 —— 那里的「不」是在提问不是在否定。
    # 实测栽在这上面:模型的表格里有一行「店长角色**能不能**做 | ✅ 能」,
    # 全文搜「不能」就命中了它,把一行表头当成了结论。
    t = tm._clean(text or "")
    n, y = _NO.search(t), _YES.search(t)
    if not n: return False
    if not y: return True
    return n.start() < y.start()


def write_verdict(action, fields, want_ok):
    """业务允不允许 —— **期望值现场跑真校验器取,不手写。**

    手写期望就是照着 rules.py 抄一遍,抄错了检查也跟着错;
    而且业务改规则时,手写的期望不会跟着改。
    """
    def g(text, traj, case):
        bad = []
        if "check_write" not in _tools(traj):
            bad.append("轨迹:没调 check_write —— **数据库允许 ≠ 业务允许**,"
                       "不查就只能凭系统结构推断,而那会得出相反的结论")
        r = api.check_write(action, fields)
        真 = r.get("能不能做")
        说不行 = _said_no(text)
        if 真 == "不能" and not 说不行:
            bad.append(f"内容:业务规则说不能({r.get('编码')} {r.get('理由','')[:24]}),"
                       "而回答没有明确拒绝")
        if 真 == "能" and 说不行:
            bad.append(f"内容:业务规则说能({r.get('编码')}),而回答说不行 —— 别把能做的说成不能")
        return bad
    return g


