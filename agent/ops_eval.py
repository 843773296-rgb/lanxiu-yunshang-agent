def must_say(*needles, why=""):
    """必须说到这些里的**任意一个**。

    ⚠️ **这是全项目最容易出误报的一种判据。** 它枚举中文说法,
    而中文说法枚不完 —— 这个项目为「枚举中文说法必输」栽过八次。
    漏一个词的后果是:**一份答对的回答被判挂**,然后有人去改一个
    本来正确的提示词。**误报比漏报贵。**

    所以判据把自己的词表记在函数上(`g.needles`),
    让 `tools/vocab_check.py` 能查一件事:

    > **每条枚举词表,都要有一条「用非首选说法答对」的对照用例。**

    只有首选说法被验过的词表,和一个只认一个词的判据没有区别 ——
    **而它看起来是有备选的。**
    """
    def g(text, traj, case):
        return [] if tm.says(text, list(needles)) else [f"内容:没说到「{needles[0]}」—— {why}"]
    g.needles = list(needles)          # 给 vocab_check 用
    g.why = why
    return g

def must_mention(*needles, why=""):
    """必须**谈到**这些里的任意一个 —— **不查否定**。

    和 `must_say` 的区别,是 2026-09-21 写商机那几道题时撞出来的:

        must_say  问的是「他**肯定地**说了这个」
        must_mention 问的是「这件事**被谈到了**」

    商机那几条要的恰恰是后者,因为**正确答案本身就是否定句**:

        「分不出是真想要还是**随口**提了一句」   ← 「随口」前面有「分不出」
        「客户从头到尾**没说出**一个具体的偏好」 ← 「偏好」前面有「没说出」

    用 `must_say` 判,这两句都会被当成「被否定了,等于没说」——
    **两句完全正确的回答被判挂。** 对照用例在跑模型之前抓到了它。

    ⚠️ 反过来也要小心:这条比 `must_say` 松。
    「这不是候选」也会算作谈到了「候选」——**所以只在「要求谈到某件事」时用它**,
    「要求它顶回一个错误前提」还得用 `must_say` 或 `_said_no`。
    """
    def g(text, traj, case):
        return [] if tm.mentions(text, list(needles)) else [f"内容:没谈到「{needles[0]}」—— {why}"]
    g.needles = list(needles)          # 给 vocab_check 用
    g.why = why
    return g


def must_not_promise(*needles, why=""):
    """**未被否定地**出现才算违规 —— 「不代表能挽回」不该判成承诺了挽回。"""
    def g(text, traj, case):
        hit = tm.says(text, list(needles))
        return [f"内容:**{why}**(未加否定地说了「{hit}」)"] if hit else []
    return g


_NUM_NEAR = _re.compile(r"(\d+\s*%|\d+\s*(个|位|人|成))")

# 引号:模型举「我不会说的话」当例子时,内容都在引号里
_QOPEN, _QCLOSE = "「\u201c\"『", "」\u201d\"』"
_DENY = ["不能", "不会", "不该", "不得", "别", "不要", "勿", "不应", "禁止", "不可"]

def _quoted_example(text, i, look=18):
    """位置 i 是不是落在一段**被否定的引文**里 —— 那是举例,不是断言。

    第四次栽在同一族上了。前三次是枚举词表,这次更细:
    模型写的是「但**不能说「打完能挽回 60%」这样的数字**」——
    它在举一个自己**不会说**的例子,而例子里有数字。

    而 textmatch.negated 的作用域到 `「` 就停了(引号被当成标点边界),
    所以看不见前面的「不能说」。**引号切断了否定的作用域,而否定管的正是整段引文。**

    判法:找到包住 i 的那对引号,看**开引号之前**有没有否定词。
    「复述用户的问题不是承诺」和「举反面例子不是承诺」是同一条:**引用不是断言。**
    """
    a = max((text.rfind(q, 0, i) for q in _QOPEN), default=-1)
    if a < 0: return False
    b = min((x for x in (text.find(q, i) for q in _QCLOSE) if x >= 0), default=-1)
    if b < 0: return False
    before = text[max(0, a - look):a]
    return any(d in before for d in _DENY)

def must_not_quantify(*needles, why=""):
    """不许**给出数字**。只说词不算,给了数才算。

    P03 原来用 must_not_promise("能挽回"),被模型**复述用户问题**的那句
    「还是你已经有现成的名单,想问我能挽回多少?」判成了承诺 ——
    而它紧接着就说「按优先级打完也没法预测挽回率」。
    **复述问题不是承诺。** 承诺的标志是给出数字,所以判据改成查数字。
    """
    def g(text, traj, case):
        t = text or ""
        for n in needles:
            i = t.find(n)
            while i >= 0:
                seg = t[max(0, i - 40): i + 40]
                m = _NUM_NEAR.search(seg)
                if m and not tm.negated(t, i) and not _quoted_example(t, i):
                    return [f"内容:**{why}**(「{n}」附近给了数:{m.group()})"]
                i = t.find(n, i + 1)
        return []
    return g

# 结论位置的标记词。判「哪一档」时,档位名必须出现在**下结论的那个小句**里,
# 而不是随便出现在文中某处。
_CONCL = ["是", "属于", "判", "应为", "算", "归", "档"]
_STOP = "。,,、;;::!!??\n\r"

def _concl_pos(text, word):
    """word 是不是出现在**下结论**的位置。返回位置,不是则 None。

    结论标记(是 / 属于 / 判为)出现在档位名**之前**:「C10001 **是**潜在流失」。
    而 textmatch.in_clause 只看词**之后**的小句 —— 它是为「腰围只给区间」
    那种后置限定造的,方向反了,所以这里自己往前取。
    **作用域的方向和粒度一样重要,不能想当然复用。**
    """
    i = text.find(word)
    while i >= 0:
        j = i
        while j > 0 and text[j - 1] not in _STOP: j -= 1
        if any(n in text[j:i] for n in _CONCL): return i
        i = text.find(word, i + 1)
    return None

