# ── 第一层:候选集 vs 真值(**纯函数,不花钱**)──────────────────────────

def 量一题(cid, 候选集):
    """给一道题和一个筛选器给出的候选集,判这个筛选器做了什么。

    **第一层只判一件事:召回** —— 必需工具在不在候选集里。
    因为那是**筛选器能单方面搞坏的唯一一件事**:漏掉了,模型连调对的机会都没有。

    ⚠️ **禁调不在这一层判,这是第一版栽的坑。**
    第一版拿「禁调 ∩ 候选集 = ∅」当第一层判据,结果 19/20 全红、理由全一样 ——
    而那不是「基线差」,是**这个判据在这里没有分辨力**:
    「不筛选」那一组候选集是全部 77 个,恒含每一个禁调工具;
    「按角色」52 个,也几乎必然含着。候选集里有易混工具是**必然的**,
    按角色分组不可能为每个问法单独剔掉易混的那一个。

    > **一个对基线恒为假的判据,和一个真发现了问题的判据,在红勾上长得一模一样。**

    **禁调是第二层的真值** —— 它量的是「模型有没有真的去调」,不是「筛选器该不该给」。
    拿「模型不该调」的真值去量「筛选器该不该给」,是把两层的真值混在了一起。

    返回 (过了没, [哪儿不对])。
    """
    c = next(x for x in 案 if x[0] == cid)
    _, q, 角色, 必需, 禁调, _why = c
    短 = {t.rsplit("__", 1)[-1] for t in 候选集}
    bad = []
    漏 = [t for t in 必需 if t not in 短]
    if 漏:
        bad.append(f"召回:必需工具不在候选集里 {漏}"
                   f" —— 模型**连调对的机会都没有**")
    return (not bad), bad


def 混进来的(cid, 候选集):
    """这道题的禁调工具,有几个也在候选集里。

    **这是辅助数,不是判据** —— 它对「不筛选」那一组恒为满(77 个全给),
    所以它单独看没有意义,**必须和候选集大小一起读**:
    一个给 77 个候选的筛选器,它「什么都没剔掉」不是发现,那是不筛选的定义。

    它有意义的地方是**动态筛选**:候选上限 5 的时候,
    「5 个里有没有混进那个易混的」是真问题。
    """
    c = next(x for x in 案 if x[0] == cid)
    短 = {t.rsplit("__", 1)[-1] for t in 候选集}
    return [t for t in c[4] if t in 短]


def 量一组(给候选集, 名):
    """对全部题跑一遍某个筛选器。`给候选集(角色, 问法)` 返回工具名列表。

    **比例一律同时报分子分母** —— A-8 口径。
    一个只有分母的比例,和一个算错的比例,在报表上长得一模一样。
    """
    行 = []
    for cid, q, 角色, 必需, 禁调, _why in 案:
        候 = 给候选集(角色, q)
        ok, bad = 量一题(cid, 候)
        行.append(dict(题=cid, 过=ok, 为什么=bad, 候选数=len(set(候)), 角色=角色,
                       混=混进来的(cid, 候), 禁调数=len(禁调)))
    候 = [r["候选数"] for r in 行]
    禁 = sum(r["禁调数"] for r in 行)
    混 = sum(len(r["混"]) for r in 行)
    return dict(组=名,
                召回过=sum(1 for r in 行 if r["过"]), 共=len(行),
                禁调混进=混, 禁调共=禁,
                候选均=round(sum(候) / len(候), 1) if 候 else 0,
                候选最大=max(候) if 候 else 0, 候选最小=min(候) if 候 else 0,
                行=行)


