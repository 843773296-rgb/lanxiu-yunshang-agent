#!/usr/bin/env python3
"""放宽 `agentsite/guards.py` 让价词表里「数字 + 折」那一支 —— 别再把编号尾数 + 「折合」读成「几折」。

**为什么要用户亲手跑**:这一改让判据**拦得更少** = 放宽。项目规矩:收紧可以直接改,放宽必须用户执行。
(11-08 eureka-fc 备过一版,补丁放在临时目录里丢了;这是 11-13 重备的,放项目目录。)

**误拦的样子**:版型号 PT07 + 「折合米数」→ 「7折」→ 被当成让价拦下。
版师补题 N22、话术 T13 都栽过。

**这一改做什么**(只动一行):
    旧  |[一二三四五六七八九两\\d](?:[.．]\\d)?\\s*折(?![痕叠边])
    新  |(?:[一二三四五六七八九两]|(?<![A-Za-z0-9])\\d{1,2})(?:[.．]\\d)?\\s*折(?![痕叠边合射])
    ① 阿拉伯数字前面紧挨着字母或数字(PT07、A5)→ 那是编号,不是折扣
    ② 允许两位数字(「85折」「88折」原来靠尾数那一位配上,加了①之后要显式允许,否则会漏)
    ③ 「折」后面是「合 / 射」→ 折合、折射,不是让价

**代价(说清楚再跑)**:
    · 「7折合计 xx 元」这种「折」后面紧跟「合」的真让价话**不再被这一支拦**(现实里罕见);
    · 「A5折」「PT7折」这种编号紧贴数字再接「折」的话不再拦;
    · 三位以上数字 +「折」(「123折」)不再拦 —— 那不是折扣说法。
    「打…折」那一支**一个字没动**,带「打」的说法照旧全拦。

⚠️ 只在锚**正好出现一次**时才动手;锚不唯一或已变,什么都不改、报错退出。
改完会用文件里**真的那一行**重新编译整张词表,跑一遍该拦 / 该放的对照,任何一条不对就**改回原样**。
"""
import io
import os
import re
import sys

P = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "agentsite", "guards.py")
P = os.path.normpath(P)
旧 = r'''      r"|[一二三四五六七八九两\d](?:[.．]\d)?\s*折(?![痕叠边])"'''
新 = r'''      r"|(?:[一二三四五六七八九两]|(?<![A-Za-z0-9])\d{1,2})(?:[.．]\d)?\s*折(?![痕叠边合射])"'''

该拦 = ["给您九折", "给您9折", "85折", "8.5折", "8.5 折", "打个九折", "打8折", "七折优惠", "两折", "给您打88折", "这件7折"]
该放 = ["版型 PT07 折合米数", "PT07折合 3.2 米", "N22 折合", "两道折痕", "3折叠", "光的折射", "A5折页"]


def 取词表(源):
    m = re.search(r"^折扣词 = \((.*?)\)\n\n", 源, re.S | re.M)
    if not m:
        return None
    片 = re.findall(r'r"((?:[^"\\]|\\.)*)"', m.group(1))
    return re.compile("".join(片))


s = io.open(P, encoding="utf-8").read()
if 新 in s:
    print("ℹ️ 没动手:看起来已经改过了(新的那一行已在文件里)。")
    sys.exit(0)
n = s.count(旧)
if n != 1:
    print(f"❌ 没动手:锚在 {P} 里出现 {n} 次(要正好 1 次)。")
    print("   文件被改过了 —— 让 Claude 重新核一遍再给命令,别改这个脚本。")
    sys.exit(1)

改后 = s.replace(旧, 新)
词表 = 取词表(改后)
错 = []
if 词表 is None:
    错.append("在改后的文件里找不到「折扣词 = (...)」这张表")
else:
    错 += [f"该拦没拦:{x}" for x in 该拦 if not 词表.search(x)]
    错 += [f"该放没放:{x}" for x in 该放 if 词表.search(x)]
if 错:
    print("❌ 没动手:改后的词表对照不过 ——")
    for e in 错:
        print("   ", e)
    sys.exit(1)

io.open(P, "w", encoding="utf-8").write(改后)
print("✅ 已放宽:让价词表「数字+折」那一支不再把编号尾数 + 折合 读成几折")
print(f"   {旧.strip()}")
print(f" → {新.strip()}")
print(f"   对照:该拦 {len(该拦)} 条全拦、该放 {len(该放)} 条全放(用文件里真的那一行编译的)")
print()
print("接着跑这条验一下(Claude 会接手提交):")
print("   python3 agentsite/guards_test.py            # 必须还是绿的")
