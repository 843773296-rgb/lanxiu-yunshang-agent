#!/bin/bash
# push 前扫密钥。仓库**已公开**,所以这是一道硬闸:它绿了才允许 push。
#
# 这个坑连踩三次,每次都是**「在被扫描的文件里写下了真实的匹配串」**:
#   ① 规则正则写进 CLAUDE.md  → 文档匹配了自己
#   ② 挪进 .secretscan        → 规则文件匹配了自己
#   ③ 在这个脚本的注释里举例说明 → 脚本匹配了自己
#
# 前两次的修法都是「再挪一个地方 / 再加一条排除」,那是打地鼠。
# 真正的规矩只有一条:**任何被扫描的文件里,都不要写出真实的匹配串** ——
# 要举例就描述它(「GitHub 令牌前缀」),不要照抄。
# 排除规则文件自身是必要的兜底,但兜底不是解法。
#
# 误报的代价不是「多看一眼」:一个天天误报的检查等于没有检查,
# 人会学会忽略它,然后真漏密钥的那一次也一样被忽略。
#
# ─────────────────────────────────────────────────────────────────────
# ⚠️ 2026-11-03 补的那道样本量闸 —— 原来**这道最硬的闸自己会假绿**
#
# 原来的放行条件是「命中清单为空」。而文件清单是 `git ls-files` 列出来的,
# **它返回空的时候,命中清单也是空的** —— 于是:
#
# > 「扫了 0 个文件」和「扫过了、都干净」,
# > **在那句 ✅ 密钥扫描干净上长得一模一样。**
#
# 而 `空集合上所有性质都自动成立` 这条规矩,这个项目写在 CLAUDE.md 里、
# 落在了 rfm_check / route_check / impact.py 上,**唯独没落在这道闸上**。
# 失效路径是真实的:不在 git 仓库里跑、git 坏了、git 不在 PATH、
# 或者在一个排除了 .git 的副本里跑(`bite_run` 造的副本就排除 .git,
# 而另一条判据 2026-11-03 当天正因为这个在副本里扫了 0 个文件)。
#
# 目前没出过事,因为每次都是在正常的 worktree 里跑的。
# 但**「目前没出事」不等于「闸是硬的」**。
#
# 下限钉死、**只许涨不许掉**(和来源欠账、咬合欠账同一个办法)。
# 写 500 是因为当天跟踪 1400 个文件 —— 留足余量,但掉到三分之一以下
# 一定是列文件那一步坏了,不是真的删了一千个文件。
# ─────────────────────────────────────────────────────────────────────
set -o pipefail
cd "$(dirname "$0")/.." || { printf "\033[31m❌ 进不去仓库根目录 —— 什么都没扫\033[0m\n"; exit 1; }

FLOOR=500

# ① 规则读得到,而且不是空的 —— 空规则会让下面那条 grep 匹配所有文件(误报,不是假绿,
#    但理由会错得莫名其妙),所以在这儿先说清楚
RULES=$(cat .secretscan 2>/dev/null)
if [ -z "$RULES" ]; then
  printf "\033[31m❌ 读不到规则文件 .secretscan(或者它是空的)—— **什么都没扫**\033[0m\n"
  printf "   这不是「干净」,是这道闸自己坏了\n"
  exit 1
fi

# ② 文件清单列得出来,而且数量够 —— **这一条就是 2026-11-03 补的那道闸**
FILES=$(git ls-files 2>/dev/null) || {
  printf "\033[31m❌ git ls-files 跑不起来 —— **什么都没扫**\033[0m\n"
  printf "   这不是「干净」(不在 git 仓库里?git 坏了?)\n"
  exit 1
}
N=$(printf '%s\n' "$FILES" | grep -c . || true)
if [ "$N" -lt "$FLOOR" ]; then
  printf "\033[31m❌ 只列出 %s 个文件(下限 %s)—— **这是没扫到东西,不是「都干净」**\033[0m\n" "$N" "$FLOOR"
  printf "   空集合上所有性质都自动成立。常见原因:不在 git 仓库里跑、\n"
  printf "   或者在一个排除了 .git 的副本里跑(bite_run 造的副本就排除 .git)\n"
  exit 1
fi

# ③ 真扫。`grep -l` 没找到时退 1(正常),出错时退 2 —— 两者都让 HIT 为空,
#    所以上面那两道闸才是分母的保证,不能靠这一条自己说话
HIT=$(printf '%s\n' "$FILES" | grep -v '^\.secretscan$' | xargs grep -lE "$RULES" 2>/dev/null)
if [ -n "$HIT" ]; then
  printf "\033[31m❌ 疑似密钥:\033[0m\n%s\n" "$HIT"; exit 1
fi
printf "\033[32m✅ 密钥扫描干净(扫了 %s 个跟踪文件 / 下限 %s)\033[0m\n" "$N" "$FLOOR"
