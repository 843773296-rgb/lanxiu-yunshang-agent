def _挑星(rng, 分布):
    x, acc = rng.random(), 0.0
    for 星 in (5, 4, 3, 2, 1):
        acc += 分布[星]
        if x <= acc:
            return 星
    return 5


def _按配额挑星(rng, 分布, 账):
    """**按配额发星**:这一组(店 × 评价月)已经发出去几颗几星记在「账」里,每次发**欠得最多**的那一档。

    ⚠️ 原来是每条独立掷骰子(`_挑星`)。每店每月只有 40–90 条,**一组的均分抽样误差约 0.1** ——
    2026-10-03 世界平移到这一天,三家店的 9 月碰巧都抽低、7 月碰巧都抽高,
    合并趋势只剩 +0.13(业务拍的 +0.30,判据下限是一半),CI 从零重建当天就红。
    目标分和星级分布都是对的,**错在「造一个形状」用了「抽样」** —— 形状是要造出来的,不是要碰运气的。
    配额发星让一组的分布几乎正好等于目标分布,而**每天平移、每次重建都一样稳**。
    仍然消耗一个随机数:后面的评语、改评价都按原来的随机序列走,不整体挪位。
    """
    rng.random()
    n = sum(账.values())
    星 = max((5, 4, 3, 2, 1), key=lambda k: (分布[k] * (n + 1) - 账.get(k, 0), k))
    账[星] = 账.get(星, 0) + 1
    return 星


def 造数的输入(c, 今):
    """造数读的**全部库内输入**,只在这一处查 —— 算指纹时调的也是这个函数。

    ⚠️ 为什么非要单一来源:判据要靠「输入的指纹」分开两件事,
    而指纹要是另写一份查询,它就会和造数真正读的东西漂开 ——
    于是「造数代码改了」会被当成「数据被动过」**放过去**,
    而那恰恰是判据唯一要抓的东西。
    """
    今s = 今.isoformat()
    # ⚠️ **处理差评的人只能是店长或售后**(`rating_write.能关差评的角色`)。
    # 从 `staff` 表现读,**不手抄工号** —— 手抄的话哪天花名册改了这里不会跟着变,
    # 而造出来的数据会悄悄变成「规则不允许的处理人」(2026-10-11 就是这么发现
    # 201 条差评的处理人全是顾问的)。
    店长们 = {r["shop"]: r["no"] for r in c.execute(
        "SELECT shop, no FROM staff WHERE role='店长' AND status='启用'")}
    _售 = c.execute("SELECT no FROM staff WHERE role='售后' AND status='启用' "
                   "ORDER BY no LIMIT 1").fetchone()
    # ⚠️ 四条资格,一条都不能少:
    #   ① 真签收过(至少一件合身,而且有 fit_at)—— 判据和写口那道闸同一个事实
    #   ② 签收**不在世界的未来**(19 个曾经在,已由 clamp_future_done 挪回来)
    #   ③ 包裹没作废
    #   ④ 客户没被匿名化 —— 人的数据都擦了,名下还挂着评价说不通
    #      (order_spread_check 有一条同源的:已匿名化的客户名下没有订单)
    包 = [dict(r) for r in c.execute("""
        SELECT t.pkg_id, MAX(t.fit_at) 签收于, k.order_id, o.customer_id, o.shop,
               (SELECT t2.fit_verified_by FROM pickup_item t2
                 WHERE t2.pkg_id=t.pkg_id AND t2.fit_result='合身'
                   AND t2.fit_verified_by IS NOT NULL LIMIT 1) 顾问
          FROM pickup_item t JOIN pkg k ON k.pkg_id=t.pkg_id
          JOIN ordr o ON o.id=k.order_id JOIN customer u ON u.id=o.customer_id
         WHERE t.fit_result='合身' AND t.fit_at IS NOT NULL AND k.void_at IS NULL
           AND u.phone NOT LIKE 'DELETED-%'
         GROUP BY t.pkg_id HAVING substr(MAX(t.fit_at),1,10) <= ?
         ORDER BY t.pkg_id""", (今s,))]
    return dict(包=包, 店长们=店长们, 售后工号=(_售["no"] if _售 else None),
                月目标=月目标_于(今))


def 指纹料(inp):
    """把造数的全部输入压成一个指纹。**纯函数,不碰库。**

    ⚠️ 指纹必须覆盖**所有**影响随机序列的输入,漏一个就会把「数据被动过」
    误报成「代码改了」,或者反过来把真的代码改动放过去:
      · **取行集(逐行全字段)** —— 多一行少一行都让 rng 整体错位。
        2026-10-14 实测:只动一个元素,重合率从 100% 掉到 **6%**
      · **售后工号** —— `bool(售后工号) and rng.random() < 0.22` 是**短路求值**,
        工号为空时右边**不执行**,连消耗的随机数个数都不一样
      · **店长们** —— 挑处理人要用
      · **月目标** —— 挑星的配额按它算(而它跟着世界今天走)
    """
    import hashlib
    料 = json.dumps(dict(
        包=[[r["pkg_id"], r["签收于"], r["order_id"], r["customer_id"],
             r["shop"], r["顾问"]] for r in inp["包"]],
        店长们=sorted(inp["店长们"].items()),
        售后工号=inp["售后工号"],
        月目标=sorted(inp["月目标"].items()),
    ), ensure_ascii=False, sort_keys=True, default=str)
    return hashlib.sha256(料.encode("utf-8")).hexdigest()[:16]


