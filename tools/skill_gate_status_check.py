#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""技能放行只读口 · 检查 —— **它会被管理后台依赖,所以不许悄悄少一列**。

`tools/skill_gate_status.py` 给四列:在目录里 / 自有吗 / 放行吗 / 真挂上了。
少任何一列都会让人读反,而 2026-10-27 真读反过一次:
我查 `skill_cfg` 看到空表,得出「表里没有 = 放行」——
而默认值**分来源反着定**(自有 = 已发布、第三方 = 待审查),
于是三个第三方改造技能**两天没挂上**,门禁全绿、没有任何东西会红。

> 一条「表里没它所以放行」和一条「表里没它所以待审查」,
> **在「空表」这个事实上长得一模一样。**

⚠️ 这条检查**不要求那三个技能被放行** —— 放不放行是业务决定。
它要求的是**这个口把真相说全**:谁没挂上、为什么、默认值往哪边倒。
"""
import json, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PY = os.path.join(ROOT, "agentsite", ".venv", "bin", "python")
# 咬合 —— 改坏的是什么、该红的是哪一条。
咬合 = [
    ("把「真挂上了」那一列去掉(只剩「在目录里」)",
     "四列一个都不少(在目录里/自有吗/放行吗/真挂上了)"),
    ("让小结里的「真挂上了」直接等于目录数(不去问 skills_for)",
     "两个数对得上:目录里 − 没挂上 == 真挂上了"),
]

G, R, D = "\033[32m", "\033[31m", "\033[0m"
坏, n = [], 0


def ck(名, 得, 应=True):
    global n
    n += 1
    ok = (得 == 应)
    print(f"  {G + '✅' + D if ok else R + '❌' + D} {名}" + ("" if ok else f"  得到={得!r}"))
    if not ok:
        坏.append(名)


print("技能放行只读口 · 检查")
if not os.path.exists(PY):
    print(f"ℹ️ 没有 agentsite/.venv —— **这一轮没验**(不是验过了)。先 ./start.sh")
    sys.exit(0)

r = subprocess.run([PY, os.path.join(HERE, "skill_gate_status.py"), "--json"],
                   capture_output=True, text=True)
ck("只读口跑得起来(退出码 0)", r.returncode, 0)
try:
    d = json.loads(r.stdout)
except Exception as e:
    print(f"  {R}❌ 输出不是 JSON({e})—— 管理后台取不了{D}")
    print(f"{R}❌ 放行只读口 1 条不过{D}")
    sys.exit(1)

ck("有「技能」这一节", isinstance(d.get("技能"), list) and bool(d["技能"]))
ck("有「小结」这一节", isinstance(d.get("小结"), dict))

# ── 四列一个都不许少 ─────────────────────────────────────────────
四列 = ("在目录里", "自有吗", "放行吗", "真挂上了")
缺 = [c for c in 四列 if any(c not in x for x in d.get("技能", []))]
# ⚠️ 这个判据名**写成字面量**,不用 f-string 拼 ——
# `tools/bite_check.py` 从**源码文本**上核对「散文清单里的预期红是否真在脚本里」,
# 拼出来的它读不到。
# > 一个「判据名和散文清单逐字一致」和一个「它们运行时看起来一致」,
# > 在终端输出上长得一模一样 —— 只有前者能被机器核对。
ck("四列一个都不少(在目录里/自有吗/放行吗/真挂上了)", 缺, [])
ck("还带着「没登记时的默认」(默认值分来源反着定,不印出来就得去读代码)",
   all("没登记时的默认" in x for x in d.get("技能", [])))
ck("还带着「状态」原文(10-27 那次以为是「库里没登记」,实际是「已安装待审查」)",
   all("状态" in x for x in d.get("技能", [])))

# ── 「在目录里」和「真挂上了」必须是两列,不许合成一列 ───────────
# 这正是 10-27 那个 bug 的形状:目录 13 个、挂上去 10 个。
目录数 = d["小结"].get("目录里")
挂了数 = d["小结"].get("真挂上了")
ck("小结里「目录里」和「真挂上了」分开报", 目录数 is not None and 挂了数 is not None)
ck("「在目录里却没挂上」这一项在(不空的时候它就是那个 bug 的报警)",
   "在目录里却没挂上" in d["小结"])
没挂 = d["小结"].get("在目录里却没挂上") or []
ck("两个数对得上:目录里 − 没挂上 == 真挂上了",
   (目录数 - len(没挂)) if 目录数 is not None else None, 挂了数)

# ── 挂了却不在目录里:正常必须是空 ───────────────────────────────
ck("没有「挂了却不在目录里」的技能(挂载清单和目录对得上)",
   d["小结"].get("⚠️ 挂了却不在目录里") or [], [])

# ── 怎么读的那几句话要在(口径跟着数走)─────────────────────────
怎么读 = " ".join(d.get("⚠️ 怎么读") or [])
ck("说明里点明「在目录里 ≠ 真挂上了」", "≠" in 怎么读 and "真挂上" in 怎么读)
ck("说明里点明默认值分来源反着定", "第三方" in 怎么读 and "自有" in 怎么读)

print(f"  (验了 {n} 条;这一轮目录里 {目录数} 个、真挂上 {挂了数} 个、没挂上 {len(没挂)} 个)")
if n == 0:
    print(f"{R}❌ 一条都没验{D}"); sys.exit(1)
if 坏:
    print(f"{R}❌ 放行只读口 {len(坏)} 条不过{D}"); sys.exit(1)
print(f"{G}✅ 放行只读口:四列齐、两个数对得上、口径印在里面"
      f"(**不要求那几个技能被放行 —— 那是业务决定**){D}")
