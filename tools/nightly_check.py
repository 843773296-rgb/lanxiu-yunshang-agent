#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""夜跑评测清单 · 检查(不调模型、不碰库)

## 为什么要这条检查

2026-11-06 往夜跑里挂技能触发评测时发现:**`tools/nightly_eval.py` 在门禁里一条检查都没有。**
而它是这个项目唯一一个「没人看着也会自己跑」的东西 —— 挂错了的后果不是报错,
是**明早没有结果,而日志里只有一行「崩了」**。

那天差点踩的那一脚最说明问题:`跑一套()` 把脚本路径写死成 `agent/<套名>`,
而技能触发评测在 `agentsite/` 下。照老写法挂上去,清单里它赫然在列、plist 也照旧触发,

> 一个「挂上去了、今晚真会跑」和一个「挂上去了、而那个文件不在那儿」,
> **在这张清单上长得一模一样。**

## 这条检查管五件

  ① **样本量**先报 —— 空清单上「每个套都找得到」自动成立
  ② **每个套的脚本真的在那儿**(含 `别处的套` 的映射);找不到的**分类报**
  ③ **反向检查:点名的套不许囤积** —— `别处的套` / `额外参数` /
     `单独上限分钟` / `单跑那晚` 里写着的套名,必须真的出现在某一晚的清单里。
     少了这一半,一次改名会留下一条**静默失效**的登记(它既不报错也不生效)
  ④ **单跑那晚的那几套塞得进夜里那个窗口**(写死的上限分钟会和窗口脱节)
  ⑤ **「这台机器上没有它」和「跑完了判红」不许是同一个结果字** ——
     走真入口验(真调 `跑一套()`,不在这儿重写一份判断)

⚠️ 这里**不验**「今晚会不会真跑出结果」:那要调模型、要 70 分钟。
   这条检查只回答「清单和接线对不对」,**而那恰恰是会安静坏掉的那一半**。
"""
import ast
import datetime as dt
import importlib.util as _u
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
_源 = os.path.join(HERE, "nightly_eval.py")

G, R, Y, D = "\033[32m", "\033[31m", "\033[33m", "\033[0m"
坏, n = [], 0


def ck(名, 得, 应):
    global n
    n += 1
    ok = (得 == 应)
    print(f"  {G + '✅' + D if ok else R + '❌' + D} {名}" + ("" if ok else f"\n       得到={得!r}\n       应={应!r}"))
    if not ok:
        坏.append(名)


def 几条(xs, 上限=4):
    """截断要说**还有几条** —— 照着前几条修完再跑,第 5 条「又冒出来」会被编出错解释。"""
    xs = list(xs)
    return "、".join(map(str, xs[:上限])) + (f"  ……**还有 {len(xs) - 上限} 条**(共 {len(xs)})" if len(xs) > 上限 else "")


# 咬合 —— 改坏的是什么、该红的是哪一条。(可执行的在 tools/bite_specs.json)
咬合 = [
    ("把 `别处的套` 里技能触发那一条的路径改成 agent/ 下的(夜里会去跑一个不存在的文件)",
     "每个套的脚本都找得到"),
    ("往 `单跑那晚` 里加一个早就改过名的套(囤积的登记:既不报错也不生效)",
     "反向检查:点名的套都真的在某一晚的清单里"),
    ("只往两处白名单里的一处加东西(源码注释写着必须同时改)",
     "两处白名单一字不差(源码注释写着必须同时改)"),
    ("往两处白名单都加上「没跑成(找不到脚本)」(于是没跑成的那一晚会被算成跑完了)",
     "「找不到脚本」不算「跑完了」"),
]

sp = _u.spec_from_file_location("nightly_eval", _源)
M = _u.module_from_spec(sp)
sp.loader.exec_module(M)

print("夜跑评测清单 · 检查(不调模型、不碰库)")

# ── ① 样本量 ────────────────────────────────────────────────────────
七晚 = {星期: M.清单(星期) for 星期 in range(7)}
全部套 = sorted({f for xs in 七晚.values() for f, _ in xs})
print(f"     验了 {len(全部套)} 个套 / 七晚各一份清单(普通那几晚 {len(七晚[0])} 套、"
      f"单跑那晚 {min(len(x) for x in 七晚.values())} 套)")
ck("样本量:套数够(空清单上下面几条会自动成立)", len(全部套) >= 20, True)
ck("样本量:七晚每一晚都有东西跑", all(len(x) > 0 for x in 七晚.values()), True)

# ── ② 每个套的脚本真的在那儿 ────────────────────────────────────────
def 路径(名):
    return M.别处的套.get(名) or os.path.join("agent", 名)


缺 = [(f, 路径(f)) for f in 全部套 if not os.path.exists(os.path.join(ROOT, 路径(f)))]
ck("每个套的脚本都找得到", 几条(f"{f} → {p}" for f, p in 缺) or "都在", "都在")

# 把「靠映射才找得到的」单独印出来 —— 它们是最容易在搬文件时断掉的那几个
_映射的 = sorted(M.别处的套)
print(f"     ℹ️ 其中 {len(_映射的)} 个不在 agent/ 下,靠 `别处的套` 映射:"
      + "、".join(f"{f} → {M.别处的套[f]}" for f in _映射的))

# ── ③ 反向检查:点名的套不许囤积 ────────────────────────────────────
# 一条指着已改名套的登记,**既不报错也不生效** —— 而它和一条真在生效的登记
# 在这份文件里长得一模一样。所以每一处点名都要能在清单里找到主人。
囤 = []
for 表名, 表 in (("别处的套", M.别处的套), ("额外参数", M.额外参数),
                ("单独上限分钟", M.单独上限分钟), ("单跑那晚", M.单跑那晚),
                ("每晚都跑", {x: 1 for x in M.每晚都跑})):
    囤 += [f"{表名} 里的 {f}" for f in 表 if f not in 全部套]
ck("反向检查:点名的套都真的在某一晚的清单里", 几条(囤) or "没有囤积的", "没有囤积的")

# ── ④ 单跑那晚塞得进窗口 ────────────────────────────────────────────
窗口分钟 = (dt.datetime.combine(dt.date.today(), M.不开新的)
            - dt.datetime.combine(dt.date.today(), M.窗口开始)).total_seconds() / 60
超 = []
for 星期, xs in 七晚.items():
    要 = sum(M.单独上限分钟.get(f, M.每套上限分钟) for f, _ in xs)
    if f := (f"星期{星期}:上限合计 {要} 分钟 > 窗口 {int(窗口分钟)} 分钟" if 要 > 窗口分钟 else ""):
        超.append(f)
# ⚠️ 普通那几晚本来就是「排到 04:30 就不开新的」—— 那是设计,不是故障。
#    这一条只看**单跑那晚**:那几晚的意思就是「给它一整晚」,塞不进就是配错了。
超单跑 = [x for x in 超 if int(x.split(":")[0][2:]) in set(M.单跑那晚.values())]
ck("单跑那晚的那几套塞得进夜里的窗口", 几条(超单跑) or "塞得进", "塞得进")
if 超 and not 超单跑:
    print(f"     ℹ️ 普通那几晚的上限合计超过窗口,这是设计(排到 {M.不开新的:%H:%M} 就不开新的),不算故障")

# ── ⑤ 走真入口:「这台机器上没有它」≠「跑完了判红」────────────────────
# 项目里栽过(2026-11-04 `tools/impact.py`):用例全打在纯函数上,
# 把入口里调它那一支关掉,用例照旧全绿。所以这一条**真调 `跑一套()`**。
M.评测环境 = lambda: dict(os.environ)          # 不要凭据:这一条根本走不到 subprocess
_r = M.跑一套("压根不存在的_eval.py", [], dt.datetime.now() + dt.timedelta(hours=1))
ck("走真入口:挂了个找不到的套 → 结果说「找不到脚本」", "找不到脚本" in _r["结果"], True)

# 「跑完了」的白名单从源码里现读,不在这儿抄第二份 —— 抄一份就会漂。
# ⚠️⚠️ **源码里有两处一模一样的白名单**(「认证失败改判」那一处 + 「算今晚跑完了」那一处),
# 而 `nightly_eval.py` 自己的注释写着「这个元组和下面那个**必须同时改**」:
# 漏了其中一处的话,跑到一半掉登录、而那一套又判了退步,它就躲过那条改判。
#
# 2026-11-06 这条检查的第一版只读「第一个含『过』的元组」—— 于是咬合改坏了**另一处**,
# 它看不见,报「改坏了却没红」。
# > 两处一模一样的字面量,**在「我读到了一张白名单」这件事上长得一模一样** ——
# > 而我读到的是哪一处,从输出上完全看不出来。
# 所以这里**全部读出来**,并把「两处一字不差」本身当成一条判据。
_树 = ast.parse(io.open(_源, encoding="utf-8").read())
_白们 = [[e.value for e in _n.comparators[0].elts]
         for _n in ast.walk(_树)
         if (isinstance(_n, ast.Compare) and isinstance(_n.ops[0], ast.In)
             and isinstance(_n.comparators[0], ast.Tuple)
             and all(isinstance(e, ast.Constant) for e in _n.comparators[0].elts)
             and "过" in [e.value for e in _n.comparators[0].elts])]
# 样本量:一处都找不到 → 下面两条自动成立,那是假绿
if len(_白们) < 2:
    print(f"{R}❌ 在 nightly_eval.py 里只找到 {len(_白们)} 处「算跑完了」的白名单(应当有 2 处)"
          f" —— 它被改写了,下面两条验不了。**扫不到不等于没问题**{D}")
    sys.exit(1)
print(f"     ℹ️ 「算今晚跑完了」的白名单:找到 {len(_白们)} 处,"
      f"内容 {'、'.join(_白们[0])}")
ck("两处白名单一字不差(源码注释写着必须同时改)",
   all(x == _白们[0] for x in _白们), True)
# 落在**任何一处**里都会让「没跑成」被当成跑完了,所以按并集判
_并 = {y for x in _白们 for y in x}
ck("「找不到脚本」不算「跑完了」", _r["结果"] in _并, False)
_r2 = M.跑一套("skill_eval.py", [], dt.datetime.now() - dt.timedelta(hours=1))   # 截止已过 → 不真跑
ck("「找不到脚本」和「超时被停」不是同一个结果字", _r["结果"] == _r2["结果"], False)

# ── 技能触发那套的参数:不许写死,也不许和自己比 ──────────────────────
_参 = M.技能触发的参数()
ck("技能触发:一定会存一版基线", "--save" in _参, True)
_存的 = _参[_参.index("--save") + 1]
ck("技能触发:存的那一版带日期(不覆盖上一版)", _存的.startswith("夜-") and _存的[2:].isdigit(), True)
if "--diff" in _参:
    ck("技能触发:不拿今天这一版和自己比", _参[_参.index("--diff") + 1] != _存的, True)
else:
    print("     ℹ️ 这次没有可比的上一版(第一次跑就是这样)—— **只存不比,不是配错了**")

print()
print(f"  (验了 {n} 条)")
if n == 0:
    print(f"{R}❌ 一条都没验{D}")
    sys.exit(1)
if 坏:
    print(f"{R}❌ 夜跑清单 {len(坏)} 条不过{D}")
    sys.exit(1)
print(f"{G}✅ 夜跑清单:每个套的脚本都在、点名的套没囤积、单跑那晚塞得进窗口、"
      f"「找不到脚本」不算「跑完了」(**夜跑没人看着,挂错了明早只剩一行日志**){D}")
