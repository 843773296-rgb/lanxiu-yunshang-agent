def main():
    值 = {}
    for s in 规格:
        try:
            值[s["键"]] = s["现算"]()
        except Exception as e:
            print(f"❌ 现算 {s['键']} 失败:{e}")
            return 1

    错, 没认领, 对账数, 豁免数 = [], [], 0, 0
    附录行 = 0
    for f in 文档:
        p = ROOT / f
        if not p.exists():
            print(f"❌ 找不到 {f}")
            return 1
        在附录 = False
        for no, ln in enumerate(p.read_text(encoding="utf-8").split("\n"), 1):
            if ln.startswith("## "):
                在附录 = bool(附录头.match(ln))
            if not 计数行.search(ln):
                continue
            if 在附录:
                附录行 += 1
                continue
            # **版本历史是历史事实,不跟着现值走。**
            # V1.0 那行写「60 个工具」是对的 —— 那是发版当天的数。
            # 让它跟着今天的数变,等于把历史改了。
            #
            # ⚠️ 这条排除必须**在规格匹配之前**。豁免表里本来就有一条
            # `^\|\s*V\d`,但它只在「一条规格都没命中」时才生效 ——
            # 而版本行里的「60 个工具」恰好会被工具总数那条规格命中,
            # 于是豁免永远轮不到。**判据的顺序错了:「这行是历史」
            # 应该先于「这行的数对不对」。**
            if 历史行.match(ln):
                豁免数 += 1
                continue
            命中 = {}          # (键, 起始位置) → 数字。两条正则命中同一处只算一次
            for s in 规格:
                for r in s["正则"]:
                    for m in r.finditer(ln):
                        命中[(s["键"], m.start(1))] = int(m.group(1))
            命中 = [(k[0], v) for k, v in 命中.items()]
            if 命中:
                for 键, got in 命中:
                    对账数 += 1
                    if got != 值[键]:
                        错.append((f, no, 键, got, 值[键], ln.strip()[:88]))
                continue
            if any(r.search(ln) for r, _ in 豁免):
                豁免数 += 1
                continue
            没认领.append((f, no, ln.strip()[:88]))

    print(f"对账 {对账数} 处 · 豁免 {豁免数} 处 · 附录记录 {附录行} 行不对账 · 无人认领 {len(没认领)} 处")

    # **样本量下限。** 空集合上所有性质都成立 —— 规格全写错了导致一处都没匹配,
    # 输出会是「全部通过」,和真的全部通过长得一模一样。
    if 对账数 < 30:
        print(f"❌ 只对账到 {对账数} 处,低于下限 30 —— 这是**没扫到东西**,不是都通过")
        return 1

    # ⚠️ **每条失败自己占一行 ❌,并且那一行要写清失败的是哪一条。**
    # 原来写的是「❌ N 处对不上」+ 缩进明细,咬合的第三关(红的是不是那一条)
    # 只看带 ❌ 的行 —— 于是三条咬合全部判成「红了,但红的不是那一条」。
    # 一个不说清自己为什么红的检查,和随机失败没区别。
    for f, no, ln in 没认领[:20]:
        print(f"❌ 无人认领:{f}:{no} 带着计数,既没有规格认领,也不在豁免表里")
        print(f"     {ln}")
    if 没认领:
        print(f"   共 {len(没认领)} 行。→ 要么在 规格 里给它一个现算出处,"
              f"要么在 豁免 里写清为什么不算。")
        return 1

    for f, no, 键, got, want, ln in 错:
        print(f"❌ {键}:文档写 {got},现算 {want} —— {f}:{no}")
        print(f"     {ln}")
    if 错:
        print(f"   共 {len(错)} 处对不上。")
        return 1

    print("✅ 文档数字与代码对账一致:" + " · ".join(f"{k} {v}" for k, v in 值.items()))
    return 0


