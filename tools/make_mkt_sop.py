def _表(头, 行):
    out = ["| " + " | ".join(头) + " |", "|" + "---|" * len(头)]
    out += ["| " + " | ".join(str(x).replace("|", "/") for x in r) + " |" for r in 行]
    return "\n".join(out)


def _一条(编号, 标题, 出处, 正文, 适用, 该做, 不该做, 凭据):
    """渲染**一个独立可检索的片段**。

    ⚠️ 每条都自带:编号 + 标题 + 出处 + 四段。
    **不靠上文** —— 检索命中这一条时,读到的要够顾问判断,
    而不是「还得往上翻才知道这在说什么」。
    > 一个要靠上文才看得懂的片段,和一个自足的,
    > **在命中那一刻长得一模一样** —— 而前者答不了问题。
    """
    out = [f"### {编号} · {标题}", "", f"`出处:{出处}`", ""]
    if 正文:
        out += [正文, ""]
    out += [f"**什么时候适用**:{适用}", "",
            f"**该做什么**:{该做}", "",
            f"**⚠️ 明确不该做什么**:{不该做}", "",
            f"*凭什么这么定*:{凭据}", ""]
    return "\n".join(out)


