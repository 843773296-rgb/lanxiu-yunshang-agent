def main():
    新 = 生成()
    if "--check" in sys.argv:
        print("营销 SOP · 检查")
        旧 = open(OUT, encoding="utf-8").read() if os.path.isfile(OUT) else ""
        节数 = 新.count("\n## ")
        if 旧 != 新:
            差 = next((i for i, (a, b) in enumerate(
                zip(旧.split("\n"), 新.split("\n"))) if a != b),
                min(len(旧.split("\n")), len(新.split("\n"))))
            print(f"  ❌ 营销 SOP 和现在的代码对得上(验了 {节数} 节)  "
                  f"第 {差 + 1} 行起不一样 —— **口径改了而 SOP 没重新生成**;"
                  f"跑 `python3 tools/make_mkt_sop.py`")
            return 1
        # ⚠️ **节数和必含项都要验** —— 只比字符串的话,
        # 一份被整体清空又重新生成的空 SOP 也能「对得上」。
        片段数 = 新.count("\n### MKT-")
        if 节数 < 8:
            print(f"  ❌ 只生成了 {节数} 节,该有 8 节 —— **少一节不叫「对得上」**")
            return 1
        # ⚠️ **片段数也要验,而且这一条比节数要紧。**
        # 业务 2026-10-04:「做 RAG 量太少了」—— 于是拆成了一个情形一条。
        # 而只验节数的话:**一份退回「8 个大节」的 SOP 照样通过** ——
        # > 一份拆好了的语料,和一份退回大节的,
        # > **在「有 8 节」这件事上长得一模一样。**
        # 下限取 35(现在 41)—— 留一点余量给口径模块删条目,
        # 但掉到 35 以下说明结构被改回去了。
        if 片段数 < 35:
            print(f"  ❌ 只有 {片段数} 个可检索片段(`### MKT-xx-xx`),该有 35+ —— "
                  f"**结构退回大节了**。业务要的是「一个情形一条」(做 RAG),"
                  f"而只验节数的话这种退化看不出来")
            return 1
        for 必 in ("MKT-01", "MKT-08", "MKT-10", "明确不该做什么", "只给参谋"):
            if 必 not in 新:
                print(f"  ❌ 营销 SOP 覆盖「{必}」")
                return 1
        print(f"  ✅ 营销 SOP 和现在的代码对得上(验了 {节数} 节 · "
              f"**{片段数} 个可检索片段**)  "
              f"分档 / 促活 / 挽回 / 预约 / 活动 / 归因 / 渠道 / 价格 / "
              f"触点 / 流失预警")
        return 0
    open(OUT, "w", encoding="utf-8").write(新)
    print(f"写了 {os.path.relpath(OUT, ROOT)}({len(新.splitlines())} 行)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
