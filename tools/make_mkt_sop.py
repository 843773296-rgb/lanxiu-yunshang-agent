def _口径表(d):
    """把 `口径说明()` 返回的 dict 渲染成表。

    ⚠️ **它返回的是 dict 不是字符串** —— 第一版我猜成了字符串,当场炸。
    (这个仓库为「凭名字猜」栽过十一次,这次是猜返回类型。)

    而它的内容比手写的好得多:`channel` 那份里有一条键叫
    「⚠️ 渠道和活动 100% 共线」—— 这种东西手写一百遍也写不出来,
    因为它是做那块功能的人**实际撞到过**才写下的。
    > 手写 SOP 的代价不只是「会和代码分家」,
    > 还有「**写的人不知道的东西写不进去**」。
    """
    行 = []
    for k, v in d.items():
        if isinstance(v, dict):
            v = ";".join(f"**{a}** {b}" for a, b in v.items())
        行.append((k, str(v).replace("\n", " ")))
    return _表(["这一条", "说的是"], 行)


