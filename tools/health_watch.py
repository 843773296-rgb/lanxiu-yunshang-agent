#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""健康哨 —— 发现「**跑着但答不了**」,而不只是「进程还在不在」。

## 为什么要它(用户 2026-11-02 拍)

用户原话:「数据库也能不能一直保持激活…不然我哪怕页面能活动,我依旧进不去」,
以及「我希望数据库在不使用 Claude 的时候也能用」。

查下来:**库和页面本来就不依赖 Claude**(夜跑每晚 0:00 无人值守跑三小时就是证据),
而那次进不去是 API 服务把文件描述符漏光了(250 个没关的库句柄 / 上限 256)。

而这件事的要害在于 —— **三个服务都配着 `KeepAlive=true`,它从头到尾没有任何动作**:

> 进程一直活着,每一个请求都失败。

KeepAlive 只在进程**退出**时拉起来。数据库也一直开着。监控上一切正常,而用户打不开。

> 一个「服务在跑」和一个「服务在跑而且答得出来」,
> **在「进程还在不在」这件事上长得一模一样** —— 而 KeepAlive 只看前者。

(顺带核过:那个叫 `supervise` 的常驻任务守的是**业务数据同步**,不是服务健康。
所以在这之前,这台机器上没有任何东西会发现「跑着但坏了」。)

## 什么叫「坏了」—— 这一条最容易写错

查的时候亲手撞过一次:API 服务的 `/health` 返回 **404**,而服务是**好的**
(它只是没有那个路由);而它真正坏掉时的症状是 `Empty reply from server` ——
**根本没有 HTTP 响应**。所以判据不是「状态码是不是 200」:

    收到合法 HTTP 响应、状态码 < 500   → 好(404 / 401 / 302 都是业务答复)
    没收到响应(空回复 / 超时)         → 坏
    5xx                              → 坏(门禁页面冒烟当时看到的就是 502)
    探测自己失败(curl 不在之类)       → **不知道** ← 绝不据此重启

最后那一行是整个文件最要紧的一行:**「我探不到」和「它坏了」必须分开**。
混在一起的后果是探测工具一出问题,哨兵就开始反复重启一个健康的服务 ——
而那正是这个项目反复栽的那个形状(失败被表示成了另一件事)。

## 两道刹车

1. **连续坏够次数才动手**(默认 3 次)。一次抖动不重启 —— 不然它会把
   一次正常的慢请求读成故障。
2. ⚠️ **门禁在跑就不动手。** `/tmp/lanxiu-gate.lock` 在 = 有人占着共享资源
   (门禁 / 冒烟 / 写共享库)。那时候重启服务会造出**跟任何改动都无关的红**,
   而那种红查起来和真回归一模一样。这一轮只记一笔,不重启。

## 自动重启会掩盖问题,所以**每次重启都必须留账**

这是用户在选项里点名的代价。一个只会自动重启的哨兵,会把下一次泄漏永久藏起来:
服务每天半夜被重启一次,而没人知道为什么。

所以每次重启都往 `.feynman/health/restarts.jsonl` 追一行,带着
**重启前的总句柄数和库句柄数** —— 那是让下一次泄漏可被发现的唯一凭据。
这个账**只在真重启时写**(平时一个字不写),所以它不会像滚动日志那样天天脏。

## 怎么跑

    python3 tools/health_watch.py            # **默认:判定逻辑自测**(不发请求、不动手)
    python3 tools/health_watch.py --探        # 真探一遍,只报不动手
    python3 tools/health_watch.py --循环 60   # 常驻,每 60 秒一轮,坏了就重启

⚠️ **默认是自测,不是探测**:它一个请求都不发、一个服务都不重启,验的是**判定函数**,
所以进得了门禁(真探测依赖外部状态,放门禁会变成随机拦路)。
`--自测` 这个写法照旧认,和裸跑一样。
"""
import json
import os
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

G, R, Y, D = "\033[32m", "\033[31m", "\033[33m", "\033[0m"

# 锁目录和 `tools/gate_lock.sh` 写死的那一个**必须一致**。
# ⚠️ 那个脚本的注释专门警告过别改路径:换一个路径的后果是两边各锁各的,
# 「互斥当场失效,而双方都显示『我拿到锁了』」。这里只**读**它,不碰。
锁目录 = os.environ.get("LANXIU_GATE_LOCK", "/tmp/lanxiu-gate.lock")

账 = os.path.join(ROOT, ".feynman", "health", "restarts.jsonl")

# 探哪些 —— 每个服务一个**真会答话**的地址,不是只连 TCP。
# ⚠️ 别给 8760 填 `/`:它本来就没有那个路由,正常情况下就是空回复,
# 填了会让健康的服务被判成坏的(2026-11-02 实测撞到过)。
服务们 = [
    dict(名="聊天站", 端口=8770, 路径="/login", 服务="com.lanxiu.agentsite"),
    dict(名="API",   端口=8760, 路径="/health", 服务="com.lanxiu.backend"),
    dict(名="管理后台", 端口=8801, 路径="/",      服务="com.lanxiu.aimc"),
]

坏够几次 = 3


# ── 判定:纯函数,所以验得起 ────────────────────────────────────────────
#
# ⚠️ **抽成纯函数不是洁癖。** 一条要起服务、要等故障发生才验得到的判据,
# 等于没有判据 —— 这个项目在技能评测的真值那一条上栽过一次,
# 修法就是把它抽成模块级函数单独验(`agentsite/skill_eval.定真值`)。
def 判一个(探):
    """一次探测 → (状态, 理由)。状态只有四种,**「不知道」不算坏**。

    探:{"探测挂了": str|None, "有响应": bool, "状态码": int|None}
    """
    if 探.get("探测挂了"):
        return "不知道", f"探测自己没跑成({探['探测挂了']})—— **这不是它坏了**"
    if not 探.get("有响应"):
        return "坏", "连上了却没有 HTTP 响应(空回复 / 超时)—— 正是句柄漏光时的症状"
    码 = 探.get("状态码")
    if 码 is None:
        return "坏", "有连接但读不出状态码"
    if 码 >= 500:
        return "坏", f"HTTP {码} —— 服务自己报错了"
    return "好", f"HTTP {码}(<500 就算答得出来:404 / 401 / 302 都是业务答复)"


def 该重启吗(连续坏, 锁在, 门槛=坏够几次):
    """(要不要动手, 为什么)。**锁在就一律不动手** —— 哪怕它真的坏了。"""
    if 锁在:
        return False, (f"门禁 / 冒烟 / 写共享库正占着锁,这一轮**不重启** —— "
                       f"那会造出跟任何改动都无关的红(已连续坏 {连续坏} 次,记一笔)")
    if 连续坏 >= 门槛:
        return True, f"连续坏 {连续坏} 次(门槛 {门槛})"
    return False, f"坏了 {连续坏} 次,还没到门槛 {门槛} —— 一次抖动不重启"


# ── 探测 ──────────────────────────────────────────────────────────────
def 探一个(s, 超时=8):
    """用 curl 探(这台机器的 Python urllib 会证书校验失败,记忆里记着)。"""
    url = f"http://127.0.0.1:{s['端口']}{s['路径']}"
    try:
        p = subprocess.run(["curl", "-s", "-o", "/dev/null", "-w", "%{http_code}",
                            "--max-time", str(超时), url],
                           capture_output=True, text=True, timeout=超时 + 5)
    except Exception as e:                      # noqa: BLE001
        return dict(探测挂了=f"{type(e).__name__}: {e}"[:80], 有响应=False, 状态码=None)
    码 = (p.stdout or "").strip()
    # curl 的 `%{http_code}` 在**一个响应都没拿到**时给 000 —— 那正是「坏」,
    # 而 curl 自己的退出码非 0 也可能只是 000。两者都归到「没有响应」。
    if not 码.isdigit():
        return dict(探测挂了=f"curl 输出读不出状态码:{码[:30]!r}", 有响应=False, 状态码=None)
    n = int(码)
    return dict(探测挂了=None, 有响应=n != 0, 状态码=(n or None))


def 句柄数(端口):
    """重启前量一下 —— **这是让下一次泄漏可被发现的唯一凭据**。"""
    try:
        pid = subprocess.run(["lsof", "-nP", f"-iTCP:{端口}", "-sTCP:LISTEN"],
                             capture_output=True, text=True, timeout=10).stdout.strip().split("\n")
        pid = pid[-1].split()[1] if pid and len(pid[-1].split()) > 1 else None
        if not pid:
            return dict(pid=None, 总=None, 库=None)
        out = subprocess.run(["lsof", "-p", pid], capture_output=True, text=True,
                             timeout=20).stdout.split("\n")
        return dict(pid=pid, 总=len(out), 库=sum(1 for l in out if "lanxiu.db" in l))
    except Exception as e:                      # noqa: BLE001
        return dict(pid=None, 总=None, 库=None, 量不到=f"{type(e).__name__}"[:40])


def 记一笔(行):
    os.makedirs(os.path.dirname(账), exist_ok=True)
    with open(账, "a", encoding="utf-8") as fh:
        fh.write(json.dumps(行, ensure_ascii=False) + "\n")


def 重启(服务名):
    try:
        p = subprocess.run(["launchctl", "kickstart", "-k",
                            f"gui/{os.getuid()}/{服务名}"],
                           capture_output=True, text=True, timeout=30)
        return p.returncode, (p.stderr or p.stdout or "").strip()[:120]
    except Exception as e:                      # noqa: BLE001
        return -1, f"{type(e).__name__}: {e}"[:120]


# ── 跑一轮 ────────────────────────────────────────────────────────────
def 一轮(连续, 动手=False):
    锁在 = os.path.isdir(锁目录)
    for s in 服务们:
        探 = 探一个(s)
        状态, 理由 = 判一个(探)
        if 状态 == "好":
            连续[s["名"]] = 0
            print(f"  {G}✅{D} {s['名']:<6} {理由}")
            continue
        if 状态 == "不知道":
            # **不累加** —— 探不到不是它坏了,累加会让探测故障变成重启风暴
            print(f"  {Y}❔{D} {s['名']:<6} {理由}")
            continue
        连续[s["名"]] = 连续.get(s["名"], 0) + 1
        要动, 为什么 = 该重启吗(连续[s["名"]], 锁在)
        print(f"  {R}❌{D} {s['名']:<6} {理由} · {为什么}")
        if not (动手 and 要动):
            if 锁在 and 连续[s["名"]] >= 坏够几次:
                记一笔(dict(时间=time.strftime("%Y-%m-%d %H:%M:%S"), 服务=s["服务"],
                           名=s["名"], 做了="没重启(门禁占着锁)", 连续坏=连续[s["名"]],
                           理由=理由))
            continue
        前 = 句柄数(s["端口"])
        rc, 说 = 重启(s["服务"])
        记一笔(dict(时间=time.strftime("%Y-%m-%d %H:%M:%S"), 服务=s["服务"], 名=s["名"],
                   做了="重启了", 连续坏=连续[s["名"]], 理由=理由,
                   重启前句柄=前, 重启退出码=rc, 重启输出=说))
        print(f"       ↻ 重启 {s['服务']}(退出码 {rc})· 重启前句柄 "
              f"总 {前.get('总')} / 库 {前.get('库')} —— 已记进 {os.path.relpath(账, ROOT)}")
        连续[s["名"]] = 0
    return 连续


# ── 自测:自造形状,一个请求都不发 ──────────────────────────────────────
咬合 = [
    ("把 判一个 里「探测挂了」那一支去掉(探测工具出问题会被当成服务坏了)",
     "探不到**不算坏**"),
    ("把 该重启吗 里「锁在就不动手」那一支去掉(门禁跑着也重启)",
     "门禁占着锁时一律不动手"),
]
# ── 这两条为什么配得上可重放规格 ──────────────────────────────────────
# 因为**默认那一支是自测**(见 `main` 的说明)。第一版默认是真探测,于是规格必须带
# `--自测` 才跑得到判定逻辑 —— 而 `bite_check` 按 `script` 字段**原样**配对,配不上。
# 两条检查当场互相顶住:**没清单**违反「没有咬合记录的脚本 ≤ 0」,
# **有清单而规格带参数**违反「新加的检查别再添新账」。
# 换掉默认那一支之后两边都成立,而那个改动本身更对(理由在 `main` 里)。
# > 一条「没登记」和一条「登记了但按另一个键存着」,**在那个欠债数上长得一模一样。**


def 自测():
    形 = [
        ("①正常答话(200)", dict(探测挂了=None, 有响应=True, 状态码=200), "好"),
        ("②没有那个路由(404)—— **服务是好的**,API 的 /health 实测就是这样",
         dict(探测挂了=None, 有响应=True, 状态码=404), "好"),
        ("③要登录(302 / 401)—— 也是业务答复,不是坏",
         dict(探测挂了=None, 有响应=True, 状态码=302), "好"),
        ("④服务自己报错(502)—— 门禁页面冒烟当时看到的就是它",
         dict(探测挂了=None, 有响应=True, 状态码=502), "坏"),
        ("⑤连上了却没有响应 —— **句柄漏光时的症状**",
         dict(探测挂了=None, 有响应=False, 状态码=None), "坏"),
        ("⑥探测自己没跑成 —— 不知道,**不是坏**",
         dict(探测挂了="FileNotFoundError: curl", 有响应=False, 状态码=None), "不知道"),
    ]
    坏 = []
    for 名, 探, 期 in 形:
        得, 理 = 判一个(探)
        好 = 得 == 期
        print(f"  {G + '✅' + D if 好 else R + '❌' + D} {名}\n      期望 {期} · 实得 {得}")
        if not 好:
            坏.append(名)
    吐 = {判一个(探)[0] for _, 探, _ in 形}
    # ⚠️ **不许空转**:三类都得真造出来。只造「好」的话,「坏」那一支永远没被验过,
    # 而「全是好」和「坏那一支坏了」在这份输出上长得一模一样。
    三类齐 = {"好", "坏", "不知道"} <= 吐
    print(f"  {G + '✅' + D if 三类齐 else R + '❌' + D} "
          f"三类都造出来了(好 / 坏 / 不知道):{sorted(吐)}")

    # 探不到不算坏 —— 这一条单独断言,因为它是整个文件最要紧的一条
    探不到 = 判一个(dict(探测挂了="curl 不在", 有响应=False, 状态码=None))[0] != "坏"
    print(f"  {G + '✅' + D if 探不到 else R + '❌' + D} "
          f"探不到**不算坏**(否则探测工具一出问题就会重启风暴)")

    # 两道刹车
    锁刹 = (该重启吗(99, True)[0] is False)
    print(f"  {G + '✅' + D if 锁刹 else R + '❌' + D} "
          f"门禁占着锁时一律不动手(连续坏 99 次也不重启)")
    抖刹 = (该重启吗(1, False)[0] is False) and (该重启吗(坏够几次, False)[0] is True)
    print(f"  {G + '✅' + D if 抖刹 else R + '❌' + D} "
          f"坏 1 次不动手、坏够 {坏够几次} 次才动手")

    ok = not 坏 and 三类齐 and 探不到 and 锁刹 and 抖刹
    print(("\n" + G + "✅ 健康哨的判定逻辑自测全过" + D) if ok else
          ("\n" + R + "❌ 健康哨自测没过 —— **它会误判故障或漏掉故障**" + D))
    return 0 if ok else 1


def main():
    """⚠️ **默认那一支是自测,不是探测。**

    理由两条,第二条才是真理由:
    ① 这个项目的纪律是「写完判分器**先跑人造对照**」—— 默认就跑自测,
       等于把那条纪律做进了入口,而不是写在文档里靠人记得;
    ② 默认那一支**不依赖外部状态**。裸跑要是去真探测,门禁里跑它会因为
       某个服务恰好没起而随机变红 —— 而「随机拦路的检查」迟早被注释掉。
       而且那样**咬合的攻击也打不出红**:真探测永远退 0,第二关过不去。
    """
    参 = sys.argv[1:]
    循环 = None
    if "--循环" in 参:
        i = 参.index("--循环")
        循环 = int(参[i + 1]) if len(参) > i + 1 else 60
    if not 循环 and "--探" not in 参:
        return 自测()
    连续 = {}
    print(f"\n健康哨 · 探 {len(服务们)} 个服务"
          + (f" · 每 {循环} 秒一轮,坏够 {坏够几次} 次就重启" if 循环 else " · 只报不动手"))
    if not 循环:
        一轮(连续, 动手=False)
        print(f"\n  ℹ️ 这是**只报不动手**的一遍。要让它常驻并真重启:--循环 60")
        print(f"  ℹ️ 它**不验**库里的数据对不对,只验「答不答得出来」")
        return 0
    while True:
        print(f"\n[{time.strftime('%H:%M:%S')}]")
        连续 = 一轮(连续, 动手=True)
        sys.stdout.flush()
        time.sleep(循环)


if __name__ == "__main__":
    sys.exit(main())
