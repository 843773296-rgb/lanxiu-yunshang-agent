#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""评测题面的检查 —— **题面不自洽不是模型的错,而它的代价由模型背。**

## 这条检查是从账单里长出来的

2026-09-15 一天之内,同一个坑踩到第八次:

    T04  「客户 C10001 做 PT04 马面裙,推荐什么码?」
         —— 那个客户名下有 **3 个着装人**,而 PT04 是女款。模型回去问是给谁做
    T10  「PT06 立领长衫云锦缂丝整幅**这件**,能不能加急?」
         —— 「这件」指上一题,而**每道题都是全新会话**
    T18  「客户问**她那笔**售后退款的渠道流水在哪查?」
         —— 没给客户号,也没给单号
    M04  「**这个客户**这些年累计买了 3 万多了,那就是黑金了吧?」
         —— 没说是哪个客户
    N04/N06/N07(版师那套)、F05(复盘那套)…… 同一个形状

每一次的表现都一样:**模型回去问,是对的行为,而判据判它挂**。
然后我去改判据、改提示词,查到最后发现要改的是题面。

> **一个奖励「不问就猜」的判据,会把模型往错的方向调。**
> 照着那种成绩单优化出来的,是一个不懂装懂的助手。

## 它不逼你改题,它逼你**说明白**

第一版是「有指代就必须给编号」,跑一遍抓到三道题 —— **而三道都是故意的**:

    tool_eval T16  「客户上周下的**那单**到哪一步了?」
                   —— 考的就是「它会不会回去要单号」,判据明写着要它说「请提供订单号」
    role_eval F03  「**这个客户**的退款我在押金里查不到,是不是系统弄丢了?」
                   —— 考的是「押金退款和售后退款是两条流水」,是哪个客户不影响
    role_eval F05  「我核过了,**这单**金额一分不差,那就是没问题了吧?」
                   —— 考的是「金额对 ≠ 流程对」

**一条逼人去改三道本来正确的题的检查,会被拆掉。** 而误报比漏报贵 ——
这是今天用一整个下午学到的。

所以判据改成:**有指代、没编号,而且没说明是故意的** → 红。
说明就写一行注释 `# 故意不给编号:…`,写清**考的是什么**。
它不替你决定该不该改题,它只要求这个决定**被写下来** ——
和「明确不做什么」那一栏是同一个道理:
**「忘了给编号」和「故意不给编号」在题面上长得一模一样。**

## 判据:有指代,就得有编号(或说明是故意的)

题面里出现「这个客户 / 这单 / 这件 / 她那笔 / 上面那个」这类**指代**,
而整句里**没有任何一个编号**,就算不自洽。

编号的样子从库里的真实前缀取(客户 C、着装人 W、版型 PT、形制 XZ、
工艺/材质 KF/MT、量体模板 LT、售后 AS、工单 WO、订单是一串数字)。

⚠️ **这条只抓得到「明着用指代」的那一半。** T04 那种
(给了客户号,但那个客户名下有多个着装人)它抓不到 ——
**写下来是因为:一条检查最危险的时候,是别人以为它覆盖了全部。**
"""
import glob, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

指代 = ("这个客户", "这位客户", "该客户", "这单", "这一单", "那单", "那一单",
        "这件", "这一件", "她那笔", "他那笔", "那笔", "上面那个", "上述",
        "同上", "刚才那", "这条记录", "这张单")
编号 = re.compile(r"\b(?:C\d{4,}|W\d{4,}|PT\d{2}|XZ\d{2}|KF\d{2}|MT\d{2}|"
                  r"LT\d{2}|AS\d+|WO\d+|AP-[\w-]+|D\d{3,}|\d{12,})\b")
# 题面里的 f-string 占位(`{K['ord_id']}` 之类)算「给了编号」—— 那是现算的
占位 = re.compile(r"\{[^}]+\}")

FAIL = []
咬合 = [
    ("在某套评测里加一道题面写「这个客户的积分对得上吗」且不给编号",
     "题面里用了指代,就得给编号"),
]


def ck(name, ok, n, msg=""):
    print(f"  {'✅' if ok else '❌'} {name}(验了 {n} 个){'  ' + msg if msg else ''}")
    if not ok: FAIL.append(name)
    if n == 0:
        print("     ⚠️ 样本量 0 —— **这不叫通过,这叫没扫到东西**")
        FAIL.append(name + "(样本量 0)")


def _故意(src, idx):
    """这道题前面 6 行里,有没有写明「故意不给编号」。

    往前看不往后看:注释写在题的**上面**是这个项目一贯的写法。
    """
    头 = src[:idx].rsplit("\n", 7)[1:]
    return any("故意不给编号" in x or "故意省掉编号" in x for x in 头)


def 题面():
    """从各套评测里把题面抠出来 —— `q="…"` / `q=f"…"`,以及元组里的题面。"""
    out = []
    for p in sorted(glob.glob(os.path.join(ROOT, "agent", "*_eval.py"))):
        t = open(p, encoding="utf-8").read()
        name = os.path.basename(p)
        for m in re.finditer(r'\bq\s*=\s*f?"((?:[^"\\]|\\.)*)"', t):
            out.append((name, m.group(1), _故意(t, m.start())))
        # tool_eval 的用例是元组:("T01", "题面…", [工具], …)
        for m in re.finditer(r'\(\s*"(T\d\d)"\s*,\s*f?"((?:[^"\\]|\\.)*)"', t):
            out.append((name, m.group(2), _故意(t, m.start())))
    return out


def main():
    print("评测题面 · 检查")
    print("=" * 88)
    qs = 题面()
    坏 = []
    故意的 = 0
    for fn, q, 故意 in qs:
        hit = [d for d in 指代 if d in q]
        if not hit: continue
        if 编号.search(q) or 占位.search(q): continue
        if 故意: 故意的 += 1; continue
        坏.append(f"{fn}:「{q[:34]}…」用了{hit[:2]},既没给编号也没说明是故意的")
    ck("题面里用了指代,就得给编号(或写明是故意的)", not 坏, len(qs),
       "；".join(坏[:4]) if 坏 else
       f"扫了 {len(qs)} 道题,其中 {故意的} 道是**写明了故意不给编号**的 —— "
       f"**「忘了给编号」和「故意不给编号」在题面上长得一模一样**")

    print(f"\n  ℹ 这条只抓得到「明着用指代」的那一半。")
    print("     抓不到的那种:题面给了客户号,而**那个客户名下有 3 个着装人** ——")
    print("     句子读起来完全通顺,只有查了库才知道它指不明白。")
    print("     **写下来是因为:一条检查最危险的时候,是别人以为它覆盖了全部。**")

    if FAIL:
        print(f"\n\033[31m❌ 题面 {len(FAIL)} 处不符合预期\033[0m")
        for f in FAIL: print(f"   · {f}")
        sys.exit(1)
    print("\n\033[32m✅ 题面全部符合预期\033[0m")


if __name__ == "__main__":
    main()
