#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""咬合记录的检查 —— **最贵的那一步,现在只有做的人知道。**

## 为什么

`CLAUDE.md` 第 8 节写着这个项目最重的一条纪律:

> 新加一项检查,必须做「咬合测试」:故意把被检查的东西改坏,
> 确认检查真的会红,再改回来。**没红过的检查等于没有。**

而这条纪律**没有任何落点** —— 做没做过、改坏的是哪一处、红的是哪一条,
全在做的人脑子里。下一个人打开一个检查脚本,看不出它有没有被验证过,
**而「验证过」和「没验证过」的脚本长得一模一样**。

更要命的是:**咬合本身也会失效,而且失效时和通过长得一样。**
这个项目已经栽过四次 ——

  · 注入没进检查的视野(改的是 `X += [...]`,而正则读的是 `X = [...]`)
  · 破坏点不可观测(对调的那两档按定义互斥,顺序本来就没有语义)
  · 咬合用了已知的占位符(改成「待补」,而「待补」本来就在占位符名单里)
  · 攻击自己跑不起来(import 不动,于是任何异常都被读成「被拦下」)
  · **判据的搜索范围盖住了被测的东西自己** —— 这一条是写这份检查时当场撞到的:
    判据去正文里找「预期红的那句话」,而**咬合清单本身也在正文里**,
    于是把某条记录改成一句不存在的话,检查照样绿
  · **注释里的例子被当成了真声明** —— 也是当场撞到的:这份检查的文档字符串里
    有一段示例 `咬合 = [...]`,正则匹配到的是那一段。改用 AST 取模块级赋值之后才对
    (**一个写在注释里的例子,和一份真的声明,在正则眼里长得一模一样**)

**把改坏的是什么写下来,这六种才看得出来。**

## 约定

检查脚本里写一个模块级的清单:

```python
咬合 = [
    ("把「褶裥」窄回「褶裥片」", "有褶裥片的版型,腰围一个不漏地标了「仅供参考」"),
    ("改坏一格档差且不标仅供参考", "每条尺码要么档差对得上,要么在表上标着「不作数」"),
]
```

左边是**改坏了什么**(具体到那一行怎么改的),右边是**预期红的那一条**
(检查里那句话的原文)。两样都要 —— 只写「测过了」和没写是一回事。

## 钉的是上限,不是归零

87 个检查脚本里现在有记录的是少数。**要求立刻全补会有一个下场:这条检查被注释掉。**
所以和来源欠账同一个办法:**只许降不许涨** —— 新加的检查必须带记录,
旧的慢慢还。
"""
import ast, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# **没有咬合记录的检查脚本数上限** —— 2026-09-15 首次扫出来的账。
# 只许降不许涨:补了记录就把这个数改小,**别把检查改掉**。
# 首次扫出来是 86 个全欠着;当场补了 4 个这次真咬合过的,所以钉在 82。
#
#   82 → 78   2026-09-16 晚。补的三个是**按「这条坏了会漏掉什么」挑的**,
#             不是按顺序挑的 —— 它们守的都是**边界**,
#             而边界坏了的表现是「一切正常」:
#
#     `backend/selftest.py`        truth 表(评测答案)不许经工具层暴露
#     `agentsite/gate_test.py`     写工具的闸(连着写好几条 / 同参数重试 / 反复猜)
#     `backend/isolation_check.py` A 顾问看不到 B 顾问的东西
#
#   其余多数守的是数据勾稽 —— 它们坏了会有**别的检查跟着红**,
#   而这三条**没有第二道网**。
#
#   ⚠️ 补 `selftest.py` 时先做了一件事:**给它加具名检查**。
#   它原来的判定是两句 `print` 拼出来的一行话,**没有名字可指**,
#   于是咬合记录的「预期红的是哪一条」无处可填 ——
#   **它不是没测过,是没法按这套格式记。**
#   78 → 67   2026-09-16 晚。这一批 11 个是**判分器的对照自测**(9 个 judgetest
#             + textmatch + ops 侧),它们守的是「成绩单是不是真的」——
#             判分器太松,满分成绩单就是假的,而**假的满分和真的满分长得一模一样**。
#
#             ⚠️ 这一批开始,咬合不再只是散文记录:每一条在 `tools/bite_specs.json` 里
#             都有一份**可执行的规格**,`python3 tools/bite_run.py` 能重放 ——
#             对照先要绿、改坏之后要红、而且红的必须是记录右边那一条。
#             散文不会在回归时自己变红,规格会。
#
#             做的过程里有六处变异**改坏了却没红**,那本身是发现:
#             那几处代码对照根本没覆盖。其中 `tool_eval` 那处是因为
#             **同一道题被两条轴同时网住** —— 关掉一条,另一条还接着。
#   67 → 61   2026-09-16 晚。第二批 6 个:记录仪覆盖、V1 离线循环、页面内联 JS、
#             页面元素引用、回答体检的闸、skill 分段形状。
#
#             ⚠️ 做这批时撞出一个**假绿**:`agent/offline_test.py` 打了「❌ ② 结果回灌」
#             却退出 0 —— 门禁看的是退出码,所以那一步无论结果如何都是绿的。
#             **一个自己说「我失败了」却报成功的检查,比没有这个检查更糟。** 已修。
#   61 → 54   2026-09-16 晚。第三批 7 个:knowledge/ 的口径模块。
#             改坏的都是**口径本身的那个数或那一行表**(工艺权重、突增窗口、
#             方案确认天数、人工干预窗口、分档数、判定表里的责任方)。
#
#             ⚠️ 三个模块第一次没咬住,原因值得记:**自测的期望值和被测的常量同源**,
#             改常量时期望值跟着变,于是永远对得上。RFM 那条尤其典型 ——
#             判据是「分数落在 1–5」,把五分位改成三分位仍然落在里面(单边界),
#             要改成七分位才越界。**一个只卡一边的判据,另一边坏了它不吭声。**
#   54 → 50   2026-09-16 晚。第四批 4 个:backend/ 的数据勾稽与日志一致性。
#             这批的破坏多半直接改库里的一行(活动栏写成空字符串、品类改成字典里没有的值),
#             因为它们守的就是**库里那一行对不对**。
#
#             ⚠️ `edit_log_check` 第一次的变异是往 UPDATE 里加字段,结果 SQL 绑定数对不上,
#             脚本**崩了**。崩和被抓到不是一回事 —— 「攻击自己跑不起来」这个项目栽过。
#             换成改「日志覆盖的字段」清单,不碰 SQL,才是真的咬合。
欠账上限 = 50

# ── 咬合记录 ────────────────────────────────────────────────────────────
# ⚠️ **这份检查自己也得有记录** —— 一个要求别人交作业、自己不交的检查,
# 会第一个被当成形式主义丢掉。
咬合 = [
    ("把 grading_check.py 里的 `咬合 = [` 整段删掉",
     "没有咬合记录的脚本不超过"),
    ("把某条记录右边那句「预期红的那一条」改成一句脚本里不存在的话",
     "有咬合记录的,记录本身是对的"),
]

FAIL = []


def ck(name, ok, n, msg=""):
    print(f"  {'✅' if ok else '❌'} {name}(验了 {n} 个){'  ' + msg if msg else ''}")
    if not ok: FAIL.append(name)
    if n == 0:
        print("     ⚠️ 样本量 0 —— **这不叫通过,这叫没扫到东西**")
        FAIL.append(name + "(样本量 0)")


def 脚本():
    sh = open(os.path.join(ROOT, "check.sh"), encoding="utf-8").read()
    out = []
    for line in sh.split("\n"):
        if not line.startswith("run "): continue
        for m in re.findall(r"([\w/]+\.py)", line):
            p = os.path.join(ROOT, m)
            if os.path.isfile(p): out.append(m)
    return sorted(set(out))


def main():
    print("咬合记录 · 检查")
    print("=" * 84)
    ss = 脚本()
    有, 无, 坏 = [], [], []
    for m in ss:
        t = open(os.path.join(ROOT, m), encoding="utf-8").read()
        # ⚠️ **用 AST 取模块级赋值,不用正则。**
        # 正则版当场栽了:这份检查自己的**文档字符串里有一段示例**
        # (演示 `咬合 = [...]` 该怎么写),而 `^咬合 = \[` 匹配到的是**那一段**,
        # 于是它把一段说明文字当成了真记录,报「预期红的那一条在脚本里找不到」。
        # **一个写在注释里的例子,和一份真的声明,在正则眼里长得一模一样。**
        条 = None
        try:
            for node in ast.parse(t).body:
                if (isinstance(node, ast.Assign)
                        and any(getattr(x, "id", None) == "咬合" for x in node.targets)
                        and isinstance(node.value, ast.List)):
                    条 = [(e.elts[0].value, e.elts[1].value) for e in node.value.elts
                          if isinstance(e, ast.Tuple) and len(e.elts) == 2]
        except SyntaxError:
            坏.append(f"{m}:语法错,读不出来"); continue
        if 条 is None:
            无.append(m); continue
        if not 条:
            坏.append(f"{m}:有 `咬合` 但一条都没写"); continue
        # 右边那句必须**真的出现在这个脚本里** —— 不然写的是一句不存在的检查名。
        #
        # ⚠️ **要把咬合清单本身从搜索范围里挖掉。**
        # 第一版只去掉了「咬合」那两个字,于是判据在**清单自己**里找到了那句话 ——
        # 咬合时把某条记录改成一句脚本里根本没有的话,**检查没红**。
        # 这正是这份检查开头列的那四种「咬合失效」的第五种:
        # **判据的搜索范围盖住了被测的东西自己。**
        # 搜索范围要把**咬合清单里那些右边的话**排除掉,否则判据在清单自己里
        # 就能找到它 —— 咬合时把某条改成一句不存在的话,检查不会红。
        # 这是这份检查开头列的那四种「咬合失效」的第五种:
        # **判据的搜索范围盖住了被测的东西自己。**
        正文 = t
        for a, b in 条: 正文 = 正文.replace(b, "", 1)
        缺 = [b for a, b in 条 if b[:12] not in 正文]
        if 缺: 坏.append(f"{m}:预期红的那一条在脚本里找不到 {缺[:1]}")
        else: 有.append(m)

    ck("有咬合记录的,记录本身是对的(预期红的那条真的在脚本里)", not 坏, len(有) + len(坏),
       "；".join(坏[:2]) if 坏 else
       "**只写「测过了」和没写是一回事** —— 要写清改坏的是什么、该红的是哪一条")
    ck(f"没有咬合记录的脚本不超过 {欠账上限} 个(只许降不许涨)",
       len(无) <= 欠账上限, len(ss),
       f"现在 {len(无)} 个 —— **涨了,新加的检查没带咬合记录**"
       if len(无) > 欠账上限 else
       f"{len(ss)} 个脚本,{len(有)} 个有记录、{len(无)} 个还欠着(上限 {欠账上限})")

    print(f"\n  ℹ 有记录的:{', '.join(os.path.basename(x) for x in 有)}")
    print("     **咬合本身也会失效,而且失效时和通过长得一样** —— "
          "这个项目栽过四次,把改坏的是什么写下来,那四种才看得出来。")

    if FAIL:
        print(f"\n\033[31m❌ 咬合记录 {len(FAIL)} 处不符合预期\033[0m")
        for f in FAIL: print(f"   · {f}")
        sys.exit(1)
    print("\n\033[32m✅ 咬合记录符合预期\033[0m")


if __name__ == "__main__":
    main()
