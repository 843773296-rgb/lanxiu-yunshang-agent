欠账上限 = 8

# ── 咬合记录 ────────────────────────────────────────────────────────────
# ⚠️ **这份检查自己也得有记录** —— 一个要求别人交作业、自己不交的检查,
# 会第一个被当成形式主义丢掉。
咬合 = [
    ("把 grading_check.py 里的 `咬合 = [` 整段删掉",
     "没有咬合记录的脚本不超过"),
    ("把某条记录右边那句「预期红的那一条」改成一句脚本里不存在的话",
     "有咬合记录的,记录本身是对的"),
]

FAIL = []


def ck(name, ok, n, msg=""):
    print(f"  {'✅' if ok else '❌'} {name}(验了 {n} 个){'  ' + msg if msg else ''}")
    if not ok: FAIL.append(name)
    if n == 0:
        print("     ⚠️ 样本量 0 —— **这不叫通过,这叫没扫到东西**")
        FAIL.append(name + "(样本量 0)")


def 脚本():
    sh = open(os.path.join(ROOT, "check.sh"), encoding="utf-8").read()
    out = []
    for line in sh.split("\n"):
        if not line.startswith("run "): continue
        for m in re.findall(r"([\w/]+\.py)", line):
            p = os.path.join(ROOT, m)
            if os.path.isfile(p): out.append(m)
    return sorted(set(out))


def main():
    print("咬合记录 · 检查")
    print("=" * 84)
    ss = 脚本()
    有, 无, 坏 = [], [], []
    for m in ss:
        t = open(os.path.join(ROOT, m), encoding="utf-8").read()
        # ⚠️ **用 AST 取模块级赋值,不用正则。**
        # 正则版当场栽了:这份检查自己的**文档字符串里有一段示例**
        # (演示 `咬合 = [...]` 该怎么写),而 `^咬合 = \[` 匹配到的是**那一段**,
        # 于是它把一段说明文字当成了真记录,报「预期红的那一条在脚本里找不到」。
        # **一个写在注释里的例子,和一份真的声明,在正则眼里长得一模一样。**
        条 = None
        try:
            for node in ast.parse(t).body:
                if (isinstance(node, ast.Assign)
                        and any(getattr(x, "id", None) == "咬合" for x in node.targets)
                        and isinstance(node.value, ast.List)):
                    条 = [(e.elts[0].value, e.elts[1].value) for e in node.value.elts
                          if isinstance(e, ast.Tuple) and len(e.elts) == 2]
        except SyntaxError:
            坏.append(f"{m}:语法错,读不出来"); continue
        if 条 is None:
            无.append(m); continue
        if not 条:
            坏.append(f"{m}:有 `咬合` 但一条都没写"); continue
        # 右边那句必须**真的出现在这个脚本里** —— 不然写的是一句不存在的检查名。
        #
        # ⚠️ **要把咬合清单本身从搜索范围里挖掉。**
        # 第一版只去掉了「咬合」那两个字,于是判据在**清单自己**里找到了那句话 ——
        # 咬合时把某条记录改成一句脚本里根本没有的话,**检查没红**。
        # 这正是这份检查开头列的那四种「咬合失效」的第五种:
        # **判据的搜索范围盖住了被测的东西自己。**
        # 搜索范围要把**咬合清单里那些右边的话**排除掉,否则判据在清单自己里
        # 就能找到它 —— 咬合时把某条改成一句不存在的话,检查不会红。
        # 这是这份检查开头列的那四种「咬合失效」的第五种:
        # **判据的搜索范围盖住了被测的东西自己。**
        正文 = t
        for a, b in 条: 正文 = 正文.replace(b, "", 1)
        缺 = [b for a, b in 条 if b[:12] not in 正文]
        if 缺: 坏.append(f"{m}:预期红的那一条在脚本里找不到 {缺[:1]}")
        else: 有.append(m)

    ck("有咬合记录的,记录本身是对的(预期红的那条真的在脚本里)", not 坏, len(有) + len(坏),
       "；".join(坏[:2]) if 坏 else
       "**只写「测过了」和没写是一回事** —— 要写清改坏的是什么、该红的是哪一条")
    ck(f"没有咬合记录的脚本不超过 {欠账上限} 个(只许降不许涨)",
       len(无) <= 欠账上限, len(ss),
       f"现在 {len(无)} 个 —— **涨了,新加的检查没带咬合记录**"
       if len(无) > 欠账上限 else
       f"{len(ss)} 个脚本,{len(有)} 个有记录、{len(无)} 个还欠着(上限 {欠账上限})")

    print(f"\n  ℹ 有记录的:{', '.join(os.path.basename(x) for x in 有)}")
    print("     **咬合本身也会失效,而且失效时和通过长得一样** —— "
          "这个项目栽过四次,把改坏的是什么写下来,那四种才看得出来。")

    if FAIL:
        print(f"\n\033[31m❌ 咬合记录 {len(FAIL)} 处不符合预期\033[0m")
        for f in FAIL: print(f"   · {f}")
        sys.exit(1)
    print("\n\033[32m✅ 咬合记录符合预期\033[0m")


if __name__ == "__main__":
    main()
