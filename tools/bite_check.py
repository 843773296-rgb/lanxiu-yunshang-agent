def 规格的预期红扫不到的(specs):
    """→ {脚本: 处数}:`bite_specs.json` 里某条规格的「预期红」在它要跑的那个脚本里**字面找不到**。

    ## 为什么要有这一条(2026-11-07 当天撞到)

    上面那条判据核的是**脚本里手写的散文清单**,而规格文件那一半一直没人核。
    那天我把一条判据改了名字(「装配没宣告」→「装配载进来了、而它没宣告」),
    规格里的「预期红」就**静默过期**了:

    > 重放时它只报「红了,但**红的不是那一条**」—— 而那要花一次共享资源锁 + 十几分钟
    > 才看得见,而且和「攻击真的没咬到」长得一模一样。

    静态一扫就知道,所以这一条值得在门禁里。
    ⚠️ `script` 那一栏可能带参数(`./tools/gate_lock.sh --selftest`),取第一段。
    ⚠️ 搜索范围要把**脚本里那份散文清单**挖掉 —— 不挖的话,清单里那句话会让判据
       在「清单自己」里找到它,于是改名之后照旧扫得到(和上面那条同一个坑)。
    """
    import ast as _ast
    按脚本 = {}
    for x in specs:
        s0 = (x.get("script") or "").split()
        if s0:
            按脚本.setdefault(s0[0], set()).add(x.get("预期红"))

    def _清单里那些话(t):
        try:
            树 = _ast.parse(t)
        except Exception:                                                  # noqa: BLE001
            return []            # 不是 Python(.mjs / .sh)—— 没有清单可挖
        出 = []
        for n in _ast.walk(树):
            if (isinstance(n, _ast.Assign)
                    and any(getattr(y, "id", "") == "咬合" for y in n.targets)
                    and isinstance(n.value, (_ast.List, _ast.Tuple))):
                for e in n.value.elts:
                    if (isinstance(e, (_ast.Tuple, _ast.List)) and len(e.elts) >= 2
                            and isinstance(e.elts[1], _ast.Constant)
                            and isinstance(e.elts[1].value, str)):
                        出.append(e.elts[1].value)
        return 出

    出 = {}
    for m, 们 in 按脚本.items():
        p0 = m if os.path.isabs(m) else os.path.join(ROOT, m)
        if not os.path.exists(p0):
            continue             # 脚本不在了是另一回事,别混进这一条
        t = open(p0, encoding="utf-8", errors="replace").read()
        正文 = t
        for b in _清单里那些话(t):
            正文 = 正文.replace(b, "", 1)
        for b in 们:
            # 和上面那条同一个比法:前 12 个字(整句常被换行切开)
            if not b or b[:12] not in 正文:
                出[m] = 出.get(m, 0) + 1
    return 出


