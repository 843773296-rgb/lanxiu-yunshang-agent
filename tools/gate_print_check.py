#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""门禁通过时印什么 —— **只在通过时才有意义的提示,不许被 `tail -3` 截掉。**

## 这条判据是为什么存在的

`check.sh` 的 `run` 在**通过**时只印 `tail -3`(失败时才印全文)。
这对**结论性**输出是对的筛选器:绿了就别刷屏。

而有一类输出不是结论,是「验过了,不过有件事值得你确认一下」——
项目里统一用 `ℹ️` 开头。**它们的全部意义只在通过时成立**:
红的时候人本来就会去读全文,绿的时候才需要有人提醒一句。

于是 `tail -3` 对这一类是**恰好反向**的筛选器:

> **它们唯一有用的场合,正好是它们唯一不可见的场合。**

2026-11-03 一天两条判据栽在这上面(边界审计的夹具账、`intent_check` 的「只报不拦」),
而**两次的修法都是让脚本自己挤进那 3 行** —— intent 那处的注释甚至写着
「**必须是一行**,否则把 ✅ 挤出视野」。那句注释本身就是证据:
在让提示信息和「通过了」抢位子,而没去问为什么只有 3 行。
**修了两次症状,才看见根因在 `run` 里。**

## 它查什么

**把 `check.sh` 里的 `run` 函数原样抽出来跑**,不另写一份印刷逻辑 ——
照「判据要真调被测代码:别在夹具里照样子重实现一份」。
重实现一份的话,改坏 `check.sh` 之后这条判据照旧是绿的。

六条用例,每一条都**只有它会挂**:

    A 通过 + ℹ️ 落在中间        → 必须看得见(这是主判据)
    B 通过 + 普通行落在中间      → 必须**看不见**(tail -3 还在起作用,没变成全印)
    C 通过 + 5 条 ℹ️ 落在中间   → 只印 3 条 + 明说「另有 2 条」(截断要说还有几条)
    D 失败                      → 全文都印(保证没把失败路径改坏)
    E 通过 + ✅ 被两行 ℹ️ 顶出窗口 → 结论行必须补回来(**第二半**)
    F 通过 + 窗口里已有结论      → 窗口外的 ✅ **不许**重复补(否则子项全印会刷屏)

⚠️ **B、D、F 是反向用例,缺了它们这条判据会把「全印」也判成通过** ——
而「全印」会让 tail -3 本来要防的刷屏原样回来,
于是**两种相反的坏法都显示成绿的**。

## 为什么走 `./check.sh --跑一条`,而不是把 run 函数抽出来

第一版是**抽函数**:按「函数体整段缩进」去找结尾。**当场漂了** ——
`run` 里嵌着一段多行单引号的 Python,它的续行**顶格**,
于是抽取在第 3 行就停了。

救回来的是样本量那道闸(「只抽出 3 行 —— 这是抽取失败,不是函数变短了」)。
**没有它的话**:抽出 3 行 → 跑它 → `run` 未定义 → 输出空 →
报「通过时看不见 ℹ️」—— **红错理由**,照着去查那段 awk 是白费功夫。

> 一个会漂的抽取层,和一条守得住的判据,**在绿勾上长得一模一样。**

所以改成让 `check.sh` 开一个入口(`--跑一条`),判据直接调 ——
**零猜测、用的就是门禁自己那个 `run`**。
"""
import os, re, shlex, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# ⚠️ 这里不写 `tail -3` 这四个字当判据 —— 判据查的是「ℹ️ 看不看得见」这个**行为**,
#    不是「check.sh 里有没有某个命令名」。换成别的实现方式照样该通过。
咬合 = [
    ("把筛 ℹ️ 那一支逻辑废掉(通过路径只剩尾三行)",
     "通过时看不见"),
    ("把补印的封顶放开(5 条 ℹ️ 全印出来)",
     "没封顶"),
    ("把尾三行的窗口起点挪到第一行(通过时也印全文)",
     "变成全印"),
    ("把补结论行那一支废掉(✅ 被两行提示顶出窗口就没人捞它)",
     "结论行没被补回来"),
    ("把「窗口里已经有结论吗」那一问废掉(窗口外的 ✅ 也一律补)",
     "会从这儿刷屏"),
]


def 跑一次(输出行, 退出码):
    """让**门禁自己那个 `run`** 跑一个假检查,返回它印出来的东西。"""
    d = tempfile.mkdtemp(prefix="gate_print_")
    假 = os.path.join(d, "fake_check.sh")
    with open(假, "w", encoding="utf-8") as f:
        f.write("#!/bin/bash\n")
        for x in 输出行:
            f.write("printf '%s\\n' " + shlex.quote(x) + "\n")
        f.write(f"exit {退出码}\n")
    os.chmod(假, 0o755)
    r = subprocess.run(["./check.sh", "--跑一条", "bash", 假],
                       cwd=ROOT, capture_output=True, text=True, timeout=180)
    return r.stdout + r.stderr


def 入口没法用(out):
    """**「入口没工作」必须和「印刷坏了」分开。**

    查的是**行为**(它有没有真的调到 run),不是「check.sh 里有没有那行字」——
    那行字在而入口坏了的情况是存在的。
    """
    if "库正在重建" in out:
        return "SKIP库正在重建"
    if not out.strip():
        return "`./check.sh --跑一条` 一个字都没印 —— **这是入口没工作,不是印刷对了**"
    if "外部驱动" not in out:
        return ("输出里没有 run 自己打的那行标题 —— "
                "**入口没走到真的 run 上**,下面几条什么都没验")
    return None


def main():
    print("门禁通过时印什么 · 只在通过时才有用的提示不许被截掉")
    print("=" * 72)
    坏 = []

    # A 通过 + ℹ️ 落在中间 → 必须看得见
    out = 跑一次(["开头", "ℹ️ 这条只在通过时有用", "中间甲", "中间乙",
                 "中间丙", "尾三之一", "尾三之二", "✅ 通过了"], 0)
    # ⚠️ **这一步先验「入口通不通」** —— 入口坏了时下面几条会在空输出上
    #    报成「通过时看不见 ℹ️」,红错理由(第一版就是这么骗过我的)
    病 = 入口没法用(out)
    if 病 and 病.startswith("SKIP"):
        print(f"  ℹ️ {病[4:]} —— 这时候跑出来的不代表任何东西,"
              f"**这几条没东西可验,不是验过了**")
        return 0
    if 病:
        print(f"  ❌ {病}")
        return 1
    if "ℹ️ 这条只在通过时有用" not in out:
        坏.append("A 通过时看不见 ℹ️ 提示 —— 它只在通过时有意义,"
                  "被截掉等于从没写过(这正是 11-03 两次翻车的根因)")
    if "✅ 通过了" not in out:
        坏.append("A 补印把 ✅ 挤出去了 —— **人反而看不到「通过了」**")

    # B 通过 + 普通行落在中间 → 必须看不见(否则 tail -3 废了,刷屏回来)
    if "中间甲" in out:
        坏.append("B 普通的中间行也印出来了 —— 这是**变成全印**,"
                  "tail -3 本来要防的刷屏会原样回来(反向的坏法)")

    # C 5 条 ℹ️ → 封顶 3 条,且明说还有几条
    out3 = 跑一次(["头"] + [f"ℹ️ 提示{i}" for i in range(1, 6)]
                  + ["尾甲", "尾乙", "✅ 通过了"], 0)
    印了 = sum(1 for i in range(1, 6) if f"ℹ️ 提示{i}" in out3)
    if 印了 > 3:
        坏.append(f"C 5 条 ℹ️ 印了 {印了} 条 —— 没封顶,刷屏会从这儿回来")
    elif not re.search(r"另有\s*\d+\s*条", out3):
        坏.append(f"C 截断了({印了}/5 条)却没说还有几条 —— "
                  "「截断要说还有几条」:照着看得见的那几条修完再跑,"
                  "剩下的会「又冒出来」,人会编一个错解释")

    # E 通过 + ✅ 被两行 ℹ️ 顶出窗口 → 结论行必须补回来
    #    ⚠️ 这一条是「第二半」:补印 ℹ️ 只救 ℹ️ 行,而 `✅ 通过了` 不是 ℹ️ 开头,
    #       没人捞它。少了这条,脚本就得把提示压成一行去给结论腾位子 ——
    #       **让代码迁就显示窗口**,和「让提示挤进 3 行」是同一个病。
    outE = 跑一次(["开头", "✅ 通过了", "那句格言", "ℹ️ 提示一", "ℹ️ 提示二"], 0)
    if "✅ 通过了" not in outE:
        坏.append("E 两行 ℹ️ 把 ✅ 顶出窗口之后,**人看不到「通过了」** —— "
                  "结论行没被补回来")

    # F 窗口里已经有结论 → 窗口外的 ✅ 不许重复补(反向:否则每条子检查都印 ✅ 的脚本会刷屏)
    outF = 跑一次(["子项甲 ✅ 过", "子项乙 ✅ 过", "子项丙 ✅ 过",
                 "尾甲", "尾乙", "✅ 全部通过"], 0)
    if "子项丙 ✅ 过" in outF:
        坏.append("F 窗口里已经有结论行了,还把窗口外的 ✅ 也补出来 —— "
                  "每条子检查都印 ✅ 的脚本会从这儿刷屏(反向的坏法)")

    # D 失败 → 全文都印(保证没把失败路径改坏)
    outf = 跑一次(["开头", "中间甲", "❌ 不合格"], 1)
    for 应有 in ("开头", "中间甲", "❌ 不合格"):
        if 应有 not in outf:
            坏.append(f"D 失败时少印了「{应有}」—— 失败路径必须印全文,"
                      "不然查不出为什么红")
            break

    for x in 坏:
        print(f"  ❌ {x}")
    if 坏:
        return 1
    print("  ✅ 6 条全过:ℹ️ 提示通过时看得见 · 普通中间行照旧截掉 · "
          "超 3 条说还有几条 · 失败仍印全文 · 结论行被顶出窗口会补回来 · "
          "窗口里已有结论就不重复补")
    print("     **判据走 `./check.sh --跑一条`,用的就是门禁自己那个 run** —— "
          "另写一份印刷逻辑的话,改坏门禁之后这条照旧是绿的")
    return 0


if __name__ == "__main__":
    sys.exit(main())
