def 读(路):
    try:
        return datetime.fromisoformat(open(路, encoding="utf-8").read().strip())
    except Exception:
        return None


def main():
    print("\n\033[1m▸ 每日平移的定时任务还在不在跑\033[0m")
    # **说清这些数是哪个目录的。** 不说的话,worktree 里读到的「成功过」
    # 看起来像是这个工作区的,而它其实是主检出的 —— 而那正是上一个版本的病根。
    if 在哪:
        print(f"  {Y}⚠ {在哪}{D}")
    t, o = 读(尝试), 读(成功)

    装了吗 = os.path.exists(PLIST)
    if t is None and o is None:
        if not 装了吗:
            # 第一档:**不算红** —— CI 和别人的机器上本来就没有。
            print(f"  {Y}⚠ 这台机器没装每日平移的定时任务{D}"
                  f"(没有 plist,也没有 {os.path.basename(尝试)})")
            print(f"     装法:`bash tools/install_world_cron.sh`;"
                  f"CI 和别人的机器上没有是正常的,**所以这不算错**")
            print(f"\n  {G}✅ 跳过(没装){D}")
            return 0
        装了几天 = (datetime.now()
                - datetime.fromtimestamp(os.path.getmtime(PLIST))).days
        if 装了几天 <= 容忍天数:
            # 第二档:**不算红** —— 装完到第一次 05:10 之间的窗口。
            print(f"  {Y}⚠ 装了({装了几天} 天前),但**还没跑过一次**{D} —— "
                  f"到点(05:10)才会跑;想立刻验一次:`bash tools/daily_shift.sh`")
            print(f"\n  {G}✅ 跳过(刚装上,还没到点){D}")
            return 0
        # 第三档:**红** —— 装了这么久一次都没跑过,那就是没在跑。
        print(f"  {R}❌ plist 装了 {装了几天} 天,**一次都没跑过**{D} —— "
              f"看 `launchctl list | grep lanxiu`;"
              f"机器一直关机、或者 plist 有错都会这样")
        print(f"\n❌ 1 条不对")
        return 1

    坏 = []
    现在 = datetime.now()
    差尝试 = (现在 - t).days if t else None
    差成功 = (现在 - o).days if o else None

    if 差尝试 is None or 差尝试 > 容忍天数:
        坏.append(f"**任务装了却没在跑** —— 上一次尝试是 "
                  f"{t.isoformat(' ', 'minutes') if t else '(从来没有)'}"
                  f"{f',{差尝试} 天前' if 差尝试 is not None else ''}。"
                  f"看 `launchctl list | grep lanxiu`;机器一直关机也会这样")
    else:
        print(f"  {G}✅ 任务在跑{D}  上一次尝试:{t.isoformat(' ', 'minutes')}")

    if 差成功 is None or 差成功 > 容忍天数:
        坏.append(f"**任务在跑,但没有成功过** —— 上一次成功是 "
                  f"{o.isoformat(' ', 'minutes') if o else '(从来没有)'}"
                  f"{f',{差成功} 天前' if 差成功 is not None else ''}。"
                  f"看日志:{os.path.relpath(日志, 根)}")
    else:
        print(f"  {G}✅ 最近成功过{D}  上一次成功:{o.isoformat(' ', 'minutes')}")

    # ── 第四档:**「尝试过」新、「成功过」旧 = 在跑,但最近那次失败了** ──────
    #
    # ⚠️⚠️ **这一档文档里一直写着,而代码里没有** —— 2026-10-21 当场撞到:
    # 那天 05:10 的任务失败了(我前一晚建的 `rating_shadow` 有三列混着日期,
    # 而跑任务的那个检出还没拉到登记那三列的代码),而这条检查报的是
    # **「✅ 定时任务健康」**。
    #
    # 原因是上面两条**各自**看一个时间戳够不够新:尝试 = 今天(0 天前)、
    # 成功 = 昨天(1 天前),两个都在容忍里,于是两条都绿。
    # > **一个健康的任务,和一个每天早上都失败的任务,
    # > 在「两个时间戳都还新」这件事上长得一模一样。**
    # 而这两个时间戳当初**就是为了分开这两种情形才存两个的**
    # (见文件头那四档)—— 判据却没把第四档实现出来。
    #
    # 这个洞的代价和 2026-10-01 那次一样:世界停在原地,
    # 而红出来的是 7 条带时间的业务判据,**没有一条指向定时任务**。
    # 它还有个 2 天的盲窗:要等「成功过」也旧过容忍天数才红,
    # 那时候世界已经差了两三天。
    #
    # ⚠️ 阈值用**小时**而不是天:任务一天跑一次,失败一次 gap 就是 ~24 小时;
    # 而一次正常运行里「先写尝试、干完写成功」之间只有一两分钟。
    # 2 小时把这两种分得很开,又容得下跑得慢的那种。
    # ⚠️ 让开的那两种情况(重建在跑 / 还没有库)**不更新「尝试过」**,
    # 所以不会在这儿假红 —— 那是 `daily_shift.sh` 刻意设计的。
    _失败了, _差秒 = 最近那次成功了吗(t, o)
    if _失败了:
        坏.append(f"**任务在跑,但最近那次失败了** —— 尝试于 "
                  f"{t.isoformat(' ', 'minutes')},而上一次成功是 "
                  f"{o.isoformat(' ', 'minutes')}(早了 "
                  f"{_差秒 / 3600:.1f} 小时)。"
                  f"看日志:{os.path.relpath(日志, 根)};"
                  f"修好之后跑一次 `tools/daily_shift.sh`(在**跑这个任务的那个检出**里)"
                  f"把「成功过」那个戳推上来 —— 它同时也证明修的那一下真的让"
                  f"**那条路**跑得通(在别的检出里验,验的是另一条路)。"
                  f"⚠️ 它**会写库**:平移本身可能是空操作,但后面那段会按今天重算客户汇总"
                  f"(回滚记录在 order_mix_batch)—— 所以跑之前要库窗口")
    elif t and o:
        print(f"  {G}✅ 最近那次尝试成功了{D}  尝试 {t.isoformat(' ', 'minutes')} → "
              f"成功 {o.isoformat(' ', 'minutes')}")

    # ⚠️ 这一档读的是**另一个目录**的标记,咬合副本改不到 —— 所以在这儿自测。
    # 少了这几条,它就是「没有第二道网」的那一类,而它本来就是补那种洞的。
    from datetime import timedelta as _td
    _基 = datetime(2026, 10, 21, 5, 10)
    _自 = [
        (最近那次成功了吗(_基, _基 - _td(hours=24))[0] is True, "失败一次(差 24 小时)→ 报"),
        (最近那次成功了吗(_基, _基 - _td(seconds=90))[0] is False, "正常跑完(差 90 秒)→ 不报"),
        (最近那次成功了吗(_基, _基)[0] is False, "两个戳同时间 → 不报"),
        (最近那次成功了吗(_基, None)[0] is False, "没成功过 → 这一档不判(上面那条管)"),
        (最近那次成功了吗(None, _基)[0] is False, "没尝试过 → 这一档不判"),
        (最近那次成功了吗(_基, _基 - _td(hours=3))[0] is True, "差 3 小时 → 报(超过 2 小时那条线)"),
    ]
    if not all(ok for ok, _ in _自):
        坏.append("**这一档自己的自测没过** —— "
                  + "；".join(名 for ok, 名 in _自 if not ok))
    else:
        print(f"  {G}✅ 这一档自测过了{D}(失败 / 正常 / 同时刻 / 两种缺戳 / 刚过线,共 {len(_自)} 种)")

    # ── 看一眼 launchd 自己的输出 ──────────────────────────────────────
    # launchd 只在**有输出**的时候往这儿写,而这个脚本正常跑完是不出声的 ——
    # 所以「这个文件里有东西、而且比上一次成功还新」= **失败过而没人知道**。
    if os.path.exists(LAUNCHD日志) and os.path.getsize(LAUNCHD日志) > 0:
        日志时 = datetime.fromtimestamp(os.path.getmtime(LAUNCHD日志))
        # ⚠️ 比的是「**比上一次成功新**」,不是「有没有内容」——
        # 一次早就修好的旧失败留在日志里,不该让判据一直红
        # (**会误报的判据会把人教会忽略它**)。
        if o is None or 日志时 > o:
            尾 = ""
            try:
                尾 = open(LAUNCHD日志, encoding="utf-8",
                         errors="replace").read().strip().splitlines()[-3:]
                尾 = " / ".join(x.strip() for x in 尾)[:260]
            except Exception:
                尾 = "(日志读不出来)"
            坏.append(f"**launchd 报过错,而且比上一次成功还新** —— "
                      f"日志时间 {日志时.isoformat(' ', 'minutes')},"
                      f"上一次成功 "
                      f"{o.isoformat(' ', 'minutes') if o else '(从来没有)'}。\n"
                      f"       最后几行:{尾}\n"
                      f"       ⚠️ 脚本跑不起来的时候,两个标记文件**一个字都不会动** ——"
                      f"所以光看标记会说「一切正常」。"
                      f"\n       常见原因:macOS 把目录保护起来了"
                      f"(`Operation not permitted`)—— launchd agent 要在"
                      f"「系统设置 → 隐私与安全性 → 完全磁盘访问权限」里放行 `/bin/bash`")

    # ── 开跑前问的是哪个问题(2026-10-19 加)─────────────────────────────
    #
    # 用户 2026-10-18 拍的 B 案把 `shift_world.py --check` 拆成了两个问题:
    # 「自不自洽」(人看,把「数据太旧」报成错)和「能不能挪」(自动平移看,只验库坏没坏)。
    # 在那之前开跑前问的是 `--check`,而「太旧」算进了不自洽,于是机器关两周之后**死锁**:
    # 落后 > 14 天 → 自检红 → 拒绝平移 → 更落后 → 永远红。
    #
    # 📌 **为什么要单独一条检查盯这一行**:它改对之后,**没有任何东西盯着它别改回去** ——
    # 改回 `--check` 不报错、本地门禁全绿、CI 也全绿,而后果要等到**机器连续关两周**
    # 才看得见,那时候没人会想到是这一行。这正是这个项目那句规矩问的:
    # 「新加一条保证时问一句:**如果它其实没生效,我靠什么会发现?**」——
    # 在加这条之前,答案是「靠机器关两周」。
    #
    # ⚠️ 2026-10-19 当场撞过一次这个形状:那天早上世界日期跟上了机器日期,
    # 我差点把它当成那个修复的第一次真实验证 —— 而定时任务跑的是主检出、
    # 那会儿还是旧代码,**世界只落后 1 天,旧逻辑照样过**,什么都没证明。
    # > 一个「这个修复生效了」和一个「那个条件碰巧没触发」,
    # > **在「它成功了」上长得一模一样。**
    _sh = os.path.join(_仓库根, "tools", "daily_shift.sh")
    if not os.path.exists(_sh):
        坏.append("找不到 tools/daily_shift.sh —— **扫挂了,不是「没问题」**")
    else:
        _调 = [(i, l.strip()) for i, l in enumerate(
                   open(_sh, encoding="utf-8").read().splitlines(), 1)
               if "shift_world.py" in l and not l.lstrip().startswith("#")]
        # 「不带 -- 参数」那一行就是平移本身,它把前后分成两段:
        # 之前的是「这个库能不能挪」,之后的是「我挪完有没有挪坏」。
        _挪 = next((i for i, l in _调 if "--" not in l), None)
        if _挪 is None:
            坏.append(f"在 daily_shift.sh 里找不到「不带参数直接平移」那一行"
                      f"(只扫到 {len(_调)} 处调用)—— **扫挂了,不是「没问题」**")
        else:
            _前 = [(i, l) for i, l in _调 if i < _挪]
            _后 = [l for i, l in _调 if i > _挪]
            _不对 = [i for i, l in _前
                   if "--can-shift" not in l and "--能不能挪" not in l]
            if not _前:
                坏.append("daily_shift.sh 在平移之前一次自检都没有 —— "
                          "往一个半平移的库上再挪一次,只会得到一个更说不清的库")
            elif _不对:
                坏.append(f"开跑前问的不是「能不能挪」—— daily_shift.sh 第 {_不对} 行。"
                          f"问 `--check` 的话,**数据一落后超过 14 天就永远挪不动了**:"
                          f"落后 → 自检报不自洽 → 这一步拒绝平移 → 更落后。"
                          f"那两个问题 2026-10-18 已经拆开,开跑前要问 `--can-shift`")
            elif not any("--check" in l for l in _后):
                坏.append("平移完之后没有用「自不自洽」核一遍 —— "
                          "`--can-shift` **故意不验**「数据旧不旧」,"
                          "所以跑完那一次必须问 `--check`,否则挪坏了也看不出来")

    for x in 坏:
        print(f"  {R}❌ {x}{D}")
    print(f"\n{'✅ 定时任务健康' if not 坏 else f'❌ {len(坏)} 条不对'}")
    return 1 if 坏 else 0


if __name__ == "__main__":
    sys.exit(main())
