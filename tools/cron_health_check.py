# 「最近那次尝试之后多久还没成功,就算它失败了」。
# ⚠️ 用小时不用天:任务一天跑一次,失败一次 gap 就是 ~24 小时,
# 而一次正常运行里「先写尝试、干完写成功」之间只有一两分钟 —— 2 小时把两者分得很开。
# 这个数也是**拍脑袋的**,写明了:没有数据支撑,只是「几分钟太紧、一天太松」。
最近一次没成功的秒数 = 2 * 3600

def 最近那次成功了吗(t, o):
    """两个时间戳 → (最近那次失败了吗, 差了多少秒)。

    `t` = 「尝试过」(干活**之前**写),`o` = 「成功过」(成了才写)。
    任务一天跑一次:失败一次,gap 就是 ~24 小时;
    而一次正常运行里这两下之间只有一两分钟。

    ⚠️ 任一个为 None 时**不判**(那是上面两条管的档:没装 / 没跑过)。

    ⚠️ 抽成函数是为了能**自测** —— 这一档读的是**另一个目录**
    (跑任务那个检出)的标记文件,咬合副本改不到它,所以普通咬合验不了。
    不抽的话这一档自己就没有第二道网,而它本来就是补「没有第二道网」的那个洞的。
    """
    if not (t and o):
        return False, None
    差 = (t - o).total_seconds()
    return 差 > 最近一次没成功的秒数, 差


