#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""往模型上下文里塞东西的地方,有没有两处在管同一件事 —— 而谁也不知道另一处存在。

## 为什么有这条检查

2026-09-22 实测:工厂承诺 8-28 完工、业务上的今天是 8-31(晚 3 天),
助手答成「已经过期一个月」「已晚 25 天」,原话写着「现在 9 月 22 日」。

查下来不是模型不行,是**我们自己往它上下文里塞的两句话在打架**:

    规矩 TL53(系统提示词里)   「业务上的今天是 2026-08-31」
    每轮开场注入(钩子里)       「今天是 <机器日期>,**一律以这一天为准**」

后者贴着用户消息、还是命令口气,所以它赢了。
**而当时没有任何东西会发现这两处的存在** —— 是靠评测里露出的一句原话才查到的。

## 这条检查做什么(以及不做什么)

**不猜语义。** 中文同义写法接近无限,靠枚举「今天/当日/现在/截至」这类词表必输
(这个项目在词表上栽过七次,见 CLAUDE.md 第 8 节)。

改成**登记制**:每一处注入自己声明「我管的是哪件事」——

    prompts.Rule(..., 管=("日期",))          规矩(系统提示词)
    agentsite/guards.注入登记                 每轮开场注入

然后只做一个机械判断:**同一件事,被两处以上管着吗?**
是 → 红,除非在下面豁免表里写清**哪一处说了算**。

⚠️ **「两处说法一致」不等于没问题。** 一致只是此刻一致,而改的人多半只会改一处 ——
日期这件事今天正是「两处一致」,它仍然要登记豁免并写清谁是权威,**因为下一次改动会拆散它们**。

## 它抓不到什么(说清楚,免得被当成万能的)

- 两处都没声明的冲突(所以新增注入不声明要红,见 ③)
- 工具描述(73 个、1.9 万字)里夹带的口径 —— **还没纳入,记成欠债**
- 语义上的细微矛盾(比如一处说「先问」一处说「直接做」)—— 那要靠评测
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path[:0] = [ROOT, os.path.join(ROOT, "agentsite")]

咬合 = [
    ("再给一条规矩登记 管=('日期',)(制造第三处管日期的)", "同一件事只由一处管着(或写清谁说了算)"),
    ("把豁免写成按「事」整件豁免(不写是哪几处)", "同一件事只由一处管着(或写清谁说了算)"),
    ("把 guards.注入登记 里「业务今天」那条的主题删掉(不声明)", "每一段注入都声明了自己管什么"),
]

# ── 豁免:**同一件事确实由两处说,但写清了谁说了算** ─────────────────────
# 每一条都要写:谁是权威、为什么另一处也要说、改的时候要一起改。
# ⚠️ **豁免要写清是哪几处,不是哪件事。** 第一版按「事」整件豁免,咬合当场抓到:
# 再加第三处管日期的规矩,它照样绿 —— 豁免把整件事的门开着,新来的谁都能进。
豁免 = {}   # 值是 (说好的那几处, 为什么)
# 2026-09-24 **清空了**:原来「日期」这件事由 规矩 TL53 和 每轮注入 两处管着,
# 豁免里写清了权威在注入那一处。当天业务把演示世界改成跟着真实日期走之后,
# TL53 不再声称今天是哪天(它改成管「别自己拿日期去减」,那是另一件事),
# 于是**日期真的只剩一处在管了,豁免自然就不需要了**。
#
# 这正是豁免表该有的结局:**它是欠条,不是许可证。**
# 所以这份检查里有一条「豁免表里没有过期的条目」—— 一条已经不成立的豁免留着,
# 下次真出现两处管同一件事时,它会替那两处开门。
欠债上限 = 0          # 没写清谁说了算的冲突,**只许降不许涨**

FAIL, N = [], [0]


def ck(name, ok, extra=""):
    N[0] += 1
    print(f"  {'✅' if ok else '❌'} {name}{('  ' + str(extra)[:160]) if extra else ''}")
    if not ok: FAIL.append(name)


def 谁在管():
    """{这件事: [谁在管, ...]} —— 只收**声明过**的,不猜。"""
    import prompts, guards
    出 = {}
    for r in {r.id: r for r in prompts.KB_RULES + prompts.TASK_RULES + prompts.WORKSHOP_RULES}.values():
        for 事 in getattr(r, "管", ()):
            出.setdefault(事, []).append(f"规矩 {r.id}")
    for 段, 事们 in guards.注入登记.items():
        for 事 in 事们:
            出.setdefault(事, []).append(f"每轮注入「{段}」")
    return 出


def 注入段名():
    """钩子里真的往上下文塞了几段 —— 从源码里数 `ctx_add` 的赋值和追加。

    **判的是结构不是词**:每一段后面跟着一句 `# 登记:xxx` 注释,注释里的名字必须在 注入登记 里。
    这样新增一段注入时,不写登记就红 —— 而**新增的那个人正是最需要被拦住的**。
    """
    src = open(os.path.join(ROOT, "agentsite", "guards.py"), encoding="utf-8").read()
    i = src.index("async def on_prompt")
    j = src.index("\n    async def ", i + 10)
    段 = re.findall(r"#\s*登记:\s*(\S+)", src[i:j])
    n = len(re.findall(r"ctx_add\s*(?:\+)?=", src[i:j]))
    return 段, n


def main():
    print("上下文注入 · 有没有两处在管同一件事")
    print("=" * 84)
    import guards
    管 = 谁在管()
    ck("扫到了声明过的注入点", bool(管), f"{len(管)} 件事:" + "、".join(管))

    # ① 同一件事只由一处管着,或者豁免里写清了谁说了算
    冲突 = {事: 谁 for 事, 谁 in 管.items() if len(谁) > 1}
    # 豁免只对**说好的那几处**生效:多出来一处(哪怕它也声明了)照样红 —— 门是给指定的人开的,不是敞着的
    没写清 = {事: 谁 for 事, 谁 in 冲突.items()
             if 事 not in 豁免 or set(谁) != set(豁免[事][0])}
    ck("同一件事只由一处管着(或写清谁说了算)", len(没写清) <= 欠债上限,
       f"{len(冲突)} 件事有两处以上在管;其中没写清谁说了算的 {len(没写清)} 件 "
       + (str({k: v for k, v in 没写清.items()}) if 没写清 else "") + f"(上限 {欠债上限},只许降)")
    for 事, 谁 in 冲突.items():
        print(f"     · 「{事}」由 {len(谁)} 处管着:{'、'.join(谁)}"
              + ("  ← 已写清谁说了算" if 事 in 豁免 and set(谁) == set(豁免[事][0])
                 else "  ← **没写清,或者和豁免里说好的那几处对不上**"))

    # ② 豁免不许囤积:写了豁免,那件事就必须真的有两处在管(否则是过期的豁免)
    过期 = [事 for 事 in 豁免 if 事 not in 冲突]      # 豁免着、实际却没有两处在管 = 过期
    ck("豁免表里没有过期的条目", not 过期, 过期 or "")

    # ③ 每一段注入都声明了自己管什么 —— **不声明就红**
    段, n = 注入段名()
    漏 = [x for x in 段 if x not in guards.注入登记]
    ck("每一段注入都声明了自己管什么", not 漏 and len(段) >= 1, f"源码里 {len(段)} 段带登记、{n} 处写 ctx_add;"
       + (f"登记表里没有的:{漏}" if 漏 else ""))
    ck("登记表里的每一段都真的在钩子里用着(别囤积)", not [k for k in guards.注入登记 if k not in 段],
       [k for k in guards.注入登记 if k not in 段] or "")

    print()
    if FAIL:
        print(f"\033[31m❌ 上下文注入 {len(FAIL)} 处不符合预期(验了 {N[0]} 条)\033[0m")
        for f in FAIL: print(f"   · {f}")
        print("   两处管同一件事时,**贴着用户消息的那处会赢** —— 所以必须写清谁是权威,而不是指望它们碰巧一致")
        sys.exit(1)
    print(f"\033[32m✅ 上下文注入 {N[0]} 条全过\033[0m —— 每件事只有一处说了算"
          + (f",两处都说的那几件({'、'.join(豁免)})写清了权威在哪" if 豁免
             else ";**豁免表是空的** —— 眼下没有一件事由两处管着"))
    print("   ⚠️ 还没纳入的:73 个工具描述(1.9 万字)里夹带的口径 —— 记成欠债")


if __name__ == "__main__":
    main()
