G, R, Y, D = "\033[32m", "\033[31m", "\033[33m", "\033[0m"
DB = os.path.join(ROOT, "backend", "lanxiu.db")
任一日期 = re.compile(r"\d{4}-\d{2}-\d{2}")


def 月末(d):
    nxt = dt.date(d.year + (d.month == 12), d.month % 12 + 1, 1)
    return nxt - dt.timedelta(days=1)


def 该对齐到(kind, 起, 止):
    """这一行该对齐成什么 → (新起, 新止, 人话)。**纯函数,不读库不取时间。**

    口径从 `knowledge/weekly.py` 来:业务周 = 周一到周日,月 = 自然月。
    ⚠️ **不在这儿手抄「周一是 0」** —— 用 `weekday()`,而「周几算周首」那件事
    由 weekly.py 的 `周起止()` 定;这里只做对齐,不另立口径。
    """
    if kind == "日":
        # 日报的期就是那一天,挪几天都还是「某一天」—— 不用校正
        return 起, 起, "日报:期就是那一天,不用对齐"
    if kind == "周":
        一 = 起 - dt.timedelta(days=起.weekday())      # 它落入的那个业务周的周一
        return 一, 一 + dt.timedelta(days=6), (
            f"周报:对齐到它落入的那个业务周({一} 周一 → {一 + dt.timedelta(days=6)} 周日)")
    if kind == "月":
        一 = dt.date(起.year, 起.month, 1)
        return 一, 月末(一), f"月报:对齐到自然月({一} → {月末(一)})"
    return 起, 止, f"⚠️ 不认识的报告种类「{kind}」—— **不动它**,也不假装对齐过了"


def 看一遍(db=DB):
    """→ [(id, kind, 旧起, 旧止, 新起, 新止, 校正天数, 人话)],只列**要改的**。"""
    c = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    c.row_factory = sqlite3.Row
    try:
        rs = [dict(r) for r in c.execute(
            "SELECT id, kind, period_start, period_end FROM store_report_doc "
            "WHERE period_start IS NOT NULL AND period_end IS NOT NULL ORDER BY id")]
    except sqlite3.Error as e:
        c.close()
        return None, f"读不到 store_report_doc:{e}"
    c.close()
    出 = []
    for r in rs:
        try:
            起 = dt.date.fromisoformat(str(r["period_start"])[:10])
            止 = dt.date.fromisoformat(str(r["period_end"])[:10])
        except ValueError:
            出.append((r["id"], r["kind"], r["period_start"], r["period_end"],
                       None, None, None, "⚠️ 期不是日期,**不动它**"))
            continue
        新起, 新止, 话 = 该对齐到(r["kind"], 起, 止)
        if (新起, 新止) != (起, 止):
            出.append((r["id"], r["kind"], 起, 止, 新起, 新止, (新起 - 起).days, 话))
    return 出, None


def _挪文字里的日期(s, 天):
    """把一段文字里的日期各加 `天` 天。**和 `shift_world._挪文字` 同一个做法** ——
    连那条「日期后面紧跟 `.数字` 的是版本号,不挪」也要带上,否则这里会把
    取数口径版本号挪歪(2026-10-22 那件事就是这么出来的)。"""
    import shift_world as SW
    return SW._挪文字(s, 天)


def 改(db=DB, 真写=False, 说=print):
    要改, 错 = 看一遍(db)
    if 错:
        说(f"  {R}❌ {错}{D}")
        return 1
    总 = sqlite3.connect(f"file:{db}?mode=ro", uri=True).execute(
        "SELECT COUNT(*) FROM store_report_doc").fetchone()[0]
    说(f"库:{db}")
    说(f"报告 {总} 份;**报告期没对齐日历边界的 {len(要改)} 份**")
    if not 要改:
        说(f"  {Y}一份都不用改 —— 这不叫没查,是查过了({总} 份全在日历边界上){D}")
        return 0
    for i, kind, 旧起, 旧止, 新起, 新止, 校正, 话 in 要改:
        说(f"  {i} [{kind}报] {旧起} → {旧止}"
           + (f"   ⇒ {新起} → {新止}(校正 {校正:+d} 天)" if 新起 else "")
           + f"\n      {话}")
    动不了 = [x for x in 要改 if x[4] is None]
    if 动不了:
        说(f"  {Y}其中 {len(动不了)} 份动不了(期不是日期 / 种类不认识)—— **照实报,不假装对齐过**{D}")
    能改 = [x for x in 要改 if x[4] is not None]
    if not 真写:
        说(f"  {Y}(试跑,一个字都没写。确认之后加 `--写`){D}")
        return 0
    c = sqlite3.connect(db)
    with c:
        for i, kind, 旧起, 旧止, 新起, 新止, 校正, _ in 能改:
            # ⚠️ **只改这两列。** 不给 body / pack 里的日期加校正量 ——
            # 理由见文件头:那里面混着**来路日期**(「用户 2026-10-20 定」),
            # 加上去就把一个现在是对的日期改错了;而正文该走**重新渲染**修,
            # 不是按正则替换字符串(同 2026-10-22 那 56 份确认书的做法)。
            c.execute("UPDATE store_report_doc SET period_start=?, period_end=? WHERE id=?",
                      (新起.isoformat(), 新止.isoformat(), i))
    c.close()
    说(f"  {G}已对齐 {len(能改)} 份的 period_start / period_end{D}")
    说(f"  {Y}⚠️ **正文和取数包没动,所以它们现在和 period 对不上** —— "
      f"照实报,不假装已经一致了。{D}")
    说(f"     正文里写的还是旧的期(比如「周期 | 旧起 ~ 旧止」),"
      f"而修它该走**重新渲染**(报告那条线的生成器),不是按正则替换字符串;")
    说(f"     取数包里还混着**来路日期**(「用户 X 定」),"
      f"那一条归报告那条线:别把来路日期放进 pack 的自由文本。")
    return 0


def 自测():
    说 = print
    坏 = []

    def ck(名, ok, 说明=""):
        说(f"  {G + '✅' + D if ok else R + '❌' + D} {名}" + ("" if ok else f"  —— {说明}"))
        if not ok:
            坏.append(名)

    说("平移后重对齐报告期 · 自测")
    说("=" * 78)
    D_ = dt.date
    # ① 三种报告的对齐各不相同 —— 这条是整个脚本存在的理由
    起, 止, _ = 该对齐到("周", D_(2026, 10, 16), D_(2026, 10, 22))   # 周五 → 周四
    ck("周报:对齐到它落入的那个业务周(周一→周日)",
       (起, 止) == (D_(2026, 10, 12), D_(2026, 10, 18)), f"{起} → {止}")
    起, 止, _ = 该对齐到("月", D_(2026, 10, 3), D_(2026, 11, 2))
    ck("月报:对齐到自然月(1 号 → 月末),**不是挪 30 天**",
       (起, 止) == (D_(2026, 10, 1), D_(2026, 10, 31)), f"{起} → {止}")
    起, 止, _ = 该对齐到("日", D_(2026, 10, 16), D_(2026, 10, 16))
    ck("日报:挪几天都还是「某一天」,不用校正",
       (起, 止) == (D_(2026, 10, 16), D_(2026, 10, 16)), f"{起} → {止}")
    # ② 二月:月末不是 30 也不是 31 —— 「挪固定天数」在这儿必然出错
    起, 止, _ = 该对齐到("月", D_(2027, 2, 9), D_(2027, 3, 8))
    ck("二月的月报:月末是 28 号(固定天数的挪法在这儿必然错)",
       (起, 止) == (D_(2027, 2, 1), D_(2027, 2, 28)), f"{起} → {止}")
    起, 止, _ = 该对齐到("月", D_(2028, 2, 9), D_(2028, 3, 8))
    ck("闰年二月:月末是 29 号", (起, 止) == (D_(2028, 2, 1), D_(2028, 2, 29)), f"{起} → {止}")
    # ③ 已经对齐的不许被再动一次(幂等)
    一 = 该对齐到("周", D_(2026, 10, 12), D_(2026, 10, 18))
    ck("已经对齐的周报:再跑一次不变(幂等)",
       (一[0], 一[1]) == (D_(2026, 10, 12), D_(2026, 10, 18)), f"{一}")
    # ④ 不认识的种类:不动,也不假装对齐过了
    起, 止, 话 = 该对齐到("季", D_(2026, 10, 16), D_(2026, 12, 31))
    ck("不认识的报告种类:原样不动,而且说出来",
       (起, 止) == (D_(2026, 10, 16), D_(2026, 12, 31)) and "不认识" in 话, 话)
    # ⑤ 真改一遍:期 + 正文 + 取数包按同一个校正量走
    import tempfile
    tmp = tempfile.mkdtemp()
    db = os.path.join(tmp, "t.db")
    c = sqlite3.connect(db)
    c.execute("CREATE TABLE store_report_doc(id TEXT PRIMARY KEY, kind TEXT, "
              "period_start TEXT, period_end TEXT, body TEXT, pack TEXT)")
    # ⚠️ **参数化 INSERT,不把 JSON 拼进 SQL 字面量。**
    # 第一版拼进去了,而里面既有单引号又有双引号又有反斜杠 —— 转义当场写坏。
    # ⚠️ **点名列,不用位置参数。** 门禁有一条专门盯这个:
    # 「列数恰好相等而顺序错了**是不报错的**,值会整体挪一格」——
    # 而挪了一格的那份数据,和对的那份,在行数和每一行上都长得一模一样。
    c.execute("INSERT INTO store_report_doc"
              "(id, kind, period_start, period_end, body, pack) VALUES(?,?,?,?,?,?)",
              ("R1", "周", "2026-10-16", "2026-10-22",
               "本周 2026-10-16 至 2026-10-22 的经营情况",
               '{"区间":"2026-10-16","取数口径":"2026-10-21.1"}'))
    c.commit()
    c.close()
    改(db=db, 真写=True, 说=lambda *a: None)
    r = sqlite3.connect(db).execute(
        "SELECT period_start, period_end, body, pack FROM store_report_doc").fetchone()
    ck("真改一遍:期对齐到周一→周日", r[0] == "2026-10-12" and r[1] == "2026-10-18", f"{r[0]} → {r[1]}")
    # ⚠️ 这三条是**改方案之后的新断言**:正文和取数包**一个字节都不许动**。
    # 第一版给它们加了同样的校正量,而副本上的 diff 显示那会把
    # 取数包里的**来路日期**(「用户 2026-10-20 定」)也改掉 ——
    # 那是一个**现在是对的**日期。详见文件头。
    ck("正文**一个字节都没动**(修它该走重新渲染,不是正则替换)",
       r[2] == "本周 2026-10-16 至 2026-10-22 的经营情况", r[2])
    ck("取数包**一个字节都没动**",
       r[3] == '{"区间":"2026-10-16","取数口径":"2026-10-21.1"}', r[3])
    ck("所以来路日期和版本号都不会被这个脚本碰到",
       "2026-10-21.1" in r[3], r[3])
    import shutil
    shutil.rmtree(tmp, ignore_errors=True)
    说("=" * 78)
    if 坏:
        说(f"{R}❌ {len(坏)} 条没过:{坏}{D}")
        return 1
    说(f"{G}✅ 11 条全过{D}")
    return 0


