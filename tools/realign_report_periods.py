"""平移之后把**报告期重新对齐到日历边界** —— 周报回到周一→周日,月报回到 1 号→月末。

默认**只报不写**,要真改加 `--写`。`--自测` 在临时库上验那几种形状。

## 要解决什么(2026-10-23 并行会话的经营报告子任务查出来的)

每日平移把整个演示世界往前挪 N 天,而 `store_report_doc.period_start / period_end`
是整列日期 —— **跟着一天一天挪**。于是一份已确认的周报变成:

    RPT000001  周报  2026-10-16(周五) → 2026-10-22(周四)   跨 7 天

**长度对、对齐错。** 而 `knowledge/weekly.py` 第一行就写着
「业务周 = 周一 00:00 到周日 24:00」,`周起止()` 是按 `weekday()` 对齐的 ——
所以这个窗口**不属于任何一个业务周**。

后果不是报错,是**模型稳定答错**:被问「上周的周报」时,
它要么认不出这一份,要么把它当成「上周」而其实不是 ——
> **一份对齐正确的周报和一份被挪歪了的,在那张报告列表上长得一模一样**
> (都是「周报,跨 7 天」),分开它们的只有 `period_start` 是不是周一。

用户 2026-10-23 拍的是「**按整周挪**」,外加「把已经歪的那一行改回来」。

## 为什么是「平移后重对齐」而不是「这张表按整周挪」

⚠️ 一张表里装着**日报 / 周报 / 月报三种**,而它们的对齐要求**各不相同**:
日报挪几天都行;周报要落在周一→周日;**月报要是自然月 —— 而自然月不是固定天数**,
按「30 天」挪会把二月挪成跨月。所以**没有一个能同时满足三种的「每表一个挪法」**。

而平移里本来就有这个家族:`平移后重算`(排班按星期编排,星期一一动就不成立)。
报告期是同一类 —— **挪完再把它掰回日历边界**,而不是在逐列挪法里开特例。

## ⚠️ 只改 period 两列,**不碰正文和取数包** —— 这一段是改方案的理由

第一版打算给同一行的 `body` / `pack` 里的日期加同样的校正量(它们登记在
「文字里也挪」,正文里写着报告期,不跟着改就和 period 自相矛盾)。
**在副本上把 diff 摆出来之后发现那会造成损害**,两条:

① 取数包里有这么一句:

       "时区": "中国时间(按演示世界的日期;**用户 2026-10-20 定**)"

   那个日期是**来路**(用户哪天拍的板),**不是世界里发生的事**。
   给它加 −4 天就把一个**现在是对的**日期改错了。
   > 根子是老问题的又一例:**同一个文本列里混着两种日期** ——
   > 世界日期(区间 / 截至)和来路日期(谁哪天定的)。
   > 而 `pack` 登记成「文字里也挪」,所以那个来路日期**一直在被每日平移挪**。
   > 这件归报告那条线修(别把来路日期放进 pack 的自由文本,
   > 或者让 pack 的日期只在已知的几个键里挪),不是这里能解的。

② **正文是生成出来的,修它该走重新渲染,不是按正则替换字符串。**
   2026-10-22 修那 56 份确认书正文时用的就是重渲染(走
   `order_contract.拼这一单()`,和正门同一份实现)——
   理由是「各写一份的话,补出来的和新签的长得不一样,而两边分别看都正常」。
   同一天对同一类问题不该用两种标准。

所以这个脚本**只改 `period_start` / `period_end` 两列**(那是日历对齐,纯结构),
并在输出里**明说正文和取数包现在和 period 对不上、要靠重新渲染修** ——
照实报,不假装已经一致了。

"""
