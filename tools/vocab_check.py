#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""判据词表的检查 —— **只验过首选说法的词表,和只认一个词的判据没区别。**

## 这一维为什么必须自动查

`intent/judge-audit.md` 记着四类病,其中两类**到今天为止只能靠人看**:
**词表差一个字** 和 **夹具静默失效**。而那份 intent 的最后一句是:

> **靠人看的东西会在同一处栽第八次。**

这个文件堵的是前一维,`前提`(见各套评测顶部 + `tools/fixture_check.py`)堵的是后一维。

## 「词表差一个字」长什么样

    must_say("走量", "卖得快", "冷门", why="同一条件数线对走量款太晚、对冷门款天天在报")

模型答「对**销量高**的款太晚、对**销量低**的款天天在报」—— **意思完全对**,
而这三个词一个都没命中,判挂。

然后会发生的事是:有人看到分数低,**去改一个本来正确的提示词**。
**误报比漏报贵** —— 这个项目为这句话立过规矩。

## 这个检查要的是什么

> **每条枚举词表,都要有一条「用非首选说法答对」的对照用例。**

也就是:`*_eval_judgetest.py` 里针对这道题、标着「该过」的用例中,
至少有一条**不含词表里的第一个词**,却照样通过。

这证明的是一件很具体的事:**备选说法真的管用**,而不是摆在那儿好看。

⚠️ **这个检查不要求词表写得全** —— 中文说法枚不完,要求写全是做不到的。
它只要求:**你声称有备选,那就至少验过一条备选。**

## 欠账记成上限,不是一次清零

首次扫出来的账记在 `欠账上限`,**只许降不许涨**。
一个「必须立刻全绿」的检查,在还不了的债面前只有一个下场:**被注释掉**。
"""
import importlib, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path[:0] = [os.path.join(ROOT, "agent"), os.path.join(ROOT, "backend"),
                os.path.join(ROOT, "agentsite"), ROOT]

咬合 = [
    ("把 must_say 里的 `g.needles = ...` 那行删掉",
     "查得到枚举词表(判据要把自己的词表记下来)"),
    ("把 all_of 里的 `g.parts = ...` 那行删掉",
     "查得到枚举词表(判据要把自己的词表记下来)"),
    ("把某道题「用非首选说法答对」的那条对照用例改成含首选词",
     "验过备选说法的词表不少于下限"),
    ("把「织造」那条的 why 里「没有备选」四个字删掉",
     "只有一个词的判据,要说明为什么不需要备选"),
    # ⚠️ 「「还没验过备选」必须是 0」这条**咬不住** —— 试过两种改法都不红:
    #   · 给已验过的词表加个备选词  → 那条对照仍然不含首选,照样算验过
    #   · 整条换成新词表            → 已有的对照**碰巧也不含新首选**,还是算验过
    #
    # 根因是判法本身:**「不含首选词」是一个很容易满足的条件** ——
    # 一条随便写的答案大概率就不含某个特定的词。
    #
    # **所以这条检查偏松,而我把它写下来而不是假装它严。**
    # 要真验「这个备选说法管用」,得让对照**含那个备选词**才算 ——
    # 那是另一套判法,代价更高,**这里没做**。
    #
    # ⚠️ 一条咬不住的检查,和一条咬得住的,**在绿色里长得一模一样**。

]

# **首次扫出来的账** —— 只许降不许涨。补一条对照用例就把这个数改大。
# (这里钉的是**下限**:验过备选的词表至少要有这么多条。)
# **首次扫出来的账(2026-09-16):36 条枚举词表,只有 6 条验过备选说法。**
# 当天给新加的十道题(K/M/C 三组)各补了一条「用备选说法答对」的对照,
# 涨到 13 条。**只许涨不许降** —— 补一条对照就把这个数改大,**别把检查改掉**。
#
#   6 → 13   2026-09-16 下午,K1–K4 / M1–M3 / C1–C3 各补一条
#   13 → 27  2026-09-16 晚,**把老题的欠账清完了**(W/L/R/D/M/C/K 全补)
#
# ⚠️ **「还没验过」现在是 0,而这不等于全验过了** —— 还有 8 条
# **验不了**(首选是单字,任何中文答案里都躲不开它,这个判法对它不成立)。
# 那 8 条单独记一档,**「验不了」和「还没验」是两件事**,
# 混在一起的话这个账本会一直报一个偏好看的数。
验过备选_下限 = 27

FAIL = []


def ck(name, ok, n, msg=""):
    print(f"  {'✅' if ok else '❌'} {name}(验了 {n} 个){'  ' + msg if msg else ''}")
    if not ok: FAIL.append(name)
    if n == 0:
        print("     ⚠️ 样本量 0 —— **这不叫通过,这叫没扫到东西**")
        FAIL.append(name + "(样本量 0)")


def _取判据(g):
    """把一条判据(可能套着 all_of)里带 needles 的那些挖出来。"""
    out = []
    if hasattr(g, "needles"): out.append(g)
    for p in getattr(g, "parts", []): out += _取判据(p)
    return out


def 词表(g):
    """把一条判据(可能套着 all_of)里的所有枚举词表挖出来。"""
    out = []
    if hasattr(g, "needles"):
        out.append(list(g.needles))
    for p in getattr(g, "parts", []):
        out += 词表(p)
    return out


def main():
    print("判据词表 · 检查")
    print("=" * 84)
    import ops_eval as E
    import ops_eval_judgetest as J

    # ── ① 判据得把自己的词表记下来 ────────────────────────────────────
    表 = {}
    for c in E.CASES:
        ws = 词表(c["grade"])
        if ws: 表[c["id"]] = ws
    ck("查得到枚举词表(判据要把自己的词表记下来)", bool(表), len(E.CASES),
       f"{len(表)}/{len(E.CASES)} 道题带着枚举词表 —— "
       f"**套在 all_of 里的也要透出来**,否则查到的永远是 0")

    # ── ② 每条词表要有一条「用非首选说法答对」的对照用例 ────────────────
    # ⚠️ **只有一个词的判据,和「有备选但没验过」是两件事。**
    #
    # 实测撞到一条:`must_say("织造", why="瓶颈工种要点出来")` ——
    # 「织造」不是一种说法,是**工种的专有名词**,它没有同义词。
    # 而第一版把它和真有备选的混在一起报成「还没验过备选」,**那是误报**。
    #
    # 判据又一次**贴着字面(词表长度),不贴着含义(这是说法还是专名)**。
    #
    # 现在要求:**只有一个词的,`why` 里要说明为什么不需要备选** ——
    # 「没有备选」和「忘了写备选」在代码里长得一模一样,而前者该放行、后者该补。
    单词的, 没说明 = [], []
    for cid, ws in sorted(表.items()):
        for w in ws:
            if len(w) == 1:
                单词的.append((cid, w[0]))
    for cid, ws in sorted(表.items()):
        for w in ws:
            if len(w) != 1: continue
            g = next((x for c in E.CASES if c["id"] == cid
                      for x in _取判据(c["grade"]) if getattr(x, "needles", None) == w), None)
            if not g or "没有备选" not in (getattr(g, "why", "") or ""):
                没说明.append((cid, w[0]))
    ck("只有一个词的判据,要说明为什么不需要备选", not 没说明, len(单词的) or 1,
       f"{没说明}" if 没说明 else
       f"{len(单词的)} 条只有一个词(如「织造」—— **专有名词,没有同义词**),"
       f"每条都在 why 里说明了 —— **「没有备选」和「忘了写备选」"
       f"在代码里长得一模一样**")

    验过, 没验过, 单字首选 = [], [], []
    for cid, ws in sorted(表.items()):
        过 = [t for t in J.T if t[1] == cid and t[4]]      # 这道题标「该过」的对照
        for w in ws:
            if len(w) == 1:
                continue          # 没有备选可验 —— 上面那条已经单独管了
            首 = w[0]
            # ⚠️ **首选词只有一个汉字时,这个判法不成立。**
            #
            # 判法是「找一条**不含首选词**却照样通过的对照」。而首选是「不」这种
            # 单字时,**几乎任何一句中文里都躲不开它** ——
            # 「**不**在我这儿」「没有」后面往往跟着「**不**」……
            # 我给 M3 写了一条用「得由/不在」的备选答案,**它仍然含「不」**,
            # 于是算不进「验过」。
            #
            # 那时候有两条路,只有一条对:
            #   ❌ 硬凑一句不含「不」的话  —— **那不是真实答案**,是为了让检查绿
            #   ✅ 承认这个判法对单字首选无效,**单独记一档**
            #
            # ⚠️ 单独记一档不等于放行:它们仍然在账上(见下面那个数),
            # 只是**账的名目不同** —— 「验不了」和「还没验」是两件事。
            if len(首) <= 1:
                单字首选.append((cid, 首, len(w)))
                continue
            # **不含首选词却照样通过** —— 这才证明备选真的管用
            if any(首 not in (t[3] or "") for t in 过):
                验过.append((cid, 首))
            else:
                没验过.append((cid, 首, len(w)))

    print(f"\n  枚举词表 {len(验过) + len(没验过) + len(单字首选)} 条:"
          f"**验过备选 {len(验过)} 条**、还没验过 {len(没验过)} 条、"
          f"**验不了 {len(单字首选)} 条**(首选是单字)")
    for cid, 首, n in 单字首选[:6]:
        print(f"    · {cid} 的「{首}」等 {n} 个说法 —— **首选是单字,"
              f"任何中文答案里都躲不开它**,这个判法对它不成立")
    for cid, 首, n in 没验过[:8]:
        print(f"    · {cid} 的「{首}」等 {n} 个说法 —— "
              f"**只有首选被验过**,备选摆在那儿没人试过")

    下限 = 验过备选_下限
    if 下限 is None:
        print(f"\n  ℹ️ 首次运行 —— 把 `验过备选_下限` 填成 {len(验过)},"
              f"**只许涨不许降**")
    else:
        ck("验过备选说法的词表不少于下限", len(验过) >= 下限, len(表),
           f"{len(验过)} 条验过(下限 {下限})—— **只许涨不许降**。"
           f"补一条「用非首选说法答对」的对照用例就把下限改大,"
           f"**别把检查改掉**")

    # ⚠️ 欠账 2026-09-16 晚清零了,所以这条从「不超过上限」升级成「必须是 0」——
    # **一笔还清了的账,不该再留一个「允许欠多少」的口子。**
    ck("「还没验过备选」必须是 0", not 没验过, len(表),
       f"{[(c, w) for c, w, _ in 没验过[:4]]}" if 没验过 else
       "**老题的欠账清完了**(第一次扫出来是 30 条)—— "
       "新加判据时补一条「用非首选说法答对」的对照,这条就一直是 0")

    print()
    if FAIL:
        print(f"\033[31m❌ 判据词表 {len(FAIL)} 处不符合预期\033[0m")
        for f in FAIL: print(f"   · {f}")
        sys.exit(1)
    print("\033[32m✅ 判据词表符合预期\033[0m")
    print(f"    **中文说法枚不完,所以不要求写全** —— "
          f"只要求「你声称有备选,那就至少验过一条」。")


if __name__ == "__main__":
    main()
