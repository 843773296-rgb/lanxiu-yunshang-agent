from merge_append_json import (三方合, 不是纯追加, 键, 像同一条吗, 分辨删改,  # noqa: E402
                               字段差, main as 入口)


def 跑入口(目, 文件):
    """在 目 里跑一遍入口,**把它自己的输出吃掉** → 退出码。

    ⚠️ 不吃掉的话,⑧ 这条反向用例会让被测工具印一个 `❌ 不是纯追加`,
       而那是**预期行为**。项目自己写着「判绿看退出码,别数输出里的 ❌」——
       这里就别去造一个会骗到那条规矩的 ❌:
       一个「反向用例里工具正确拒绝」的 ❌,和一个「这条检查挂了」的 ❌,
       在门禁日志里长得一模一样。
    """
    老 = os.getcwd()
    吞 = _io.StringIO()
    try:
        os.chdir(目)
        with contextlib.redirect_stdout(吞):
            return 入口(["x", 文件])
    finally:
        os.chdir(老)

G, R, D = "\033[32m", "\033[31m", "\033[0m"


def _git(目, *a):
    return subprocess.run(["git", *a], cwd=目, capture_output=True, text=True)


def _写(目, xs):
    with open(os.path.join(目, "台账.json"), "w", encoding="utf-8") as h:
        json.dump(xs, h, ensure_ascii=False, indent=1)


def _读(目):
    return json.load(open(os.path.join(目, "台账.json"), encoding="utf-8"))


def 造冲突(目, 我, 他):
    """在一个一次性仓库里造出真冲突 → 成了吗。

    ⚠️ 台账写成**一行**(indent 由 _写 给,但这里刻意把条目挤在少数行上)——
       目的是让两边的改动落在同一块,git 必然冲突。
       要是写得很松散,git 可能自己合掉,那样**这一关就没验到接线**,
       而「git 自己合掉了」和「我的工具合对了」在结果上长得一模一样。
    """
    base = [{"script": f"s{i}.py", "预期红": f"r{i}"} for i in range(2)]
    for a in (("init", "-q", "."), ("config", "user.email", "t@t"),
              ("config", "user.name", "t")):
        _git(目, *a)
    with open(os.path.join(目, "台账.json"), "w", encoding="utf-8") as h:
        json.dump(base, h, ensure_ascii=False)        # 一行,逼出冲突
    _git(目, "add", "-A")
    _git(目, "commit", "-qm", "base")
    _git(目, "branch", "他")
    with open(os.path.join(目, "台账.json"), "w", encoding="utf-8") as h:
        json.dump(我(base), h, ensure_ascii=False)
    _git(目, "commit", "-qam", "我")
    _git(目, "checkout", "-q", "他")
    with open(os.path.join(目, "台账.json"), "w", encoding="utf-8") as h:
        json.dump(他(base), h, ensure_ascii=False)
    _git(目, "commit", "-qam", "他")
    _git(目, "checkout", "-q", "-")
    r = _git(目, "merge", "他")
    return "CONFLICT" in (r.stdout + r.stderr)


def main():
    过, 挂 = 0, []

    def ck(编, 行不行, 说, 详=""):
        nonlocal 过
        if 行不行:
            过 += 1
            print(f"  {G}✅{D} {编} {说}")
        else:
            挂.append(f"{编} {说}")
            print(f"  {R}❌{D} {编} {说}" + (f"\n        {详}" if 详 else ""))

    print("\n  只追加的 JSON 台账 · 三方合并(前六条纯函数,⑦⑧ 真造 git 冲突验接线)")
    B = [{"s": 1}, {"s": 2}]

    出, 我, 他 = 三方合(B, B + [{"s": 3}], B + [{"s": 4}])
    ck("①", [x["s"] for x in 出] == [1, 2, 3, 4] and len(我) == 1 and len(他) == 1,
       "两边各追加一条 → 都留着,base 顺序不变")

    出, _, _ = 三方合(B, B + [{"s": 9}], B + [{"s": 9}])
    ck("②", [x["s"] for x in 出] == [1, 2, 9],
       "**反向** · 两边加了同一条 → 只留一份(不许重复)")

    for 编, 名, o, t in (("③", "我方删", [{"s": 1}], B),
                         ("④", "对方删(base 删了一条、我方照旧追加)",
                          B + [{"s": 7}], [{"s": 1}])):
        try:
            三方合(B, o, t)
            ck(编, False, f"**反向** · {名} → 该拒绝,**却合了**(取并集会把删掉的复活)")
        except 不是纯追加:
            ck(编, True, f"**反向** · {名} → 拒绝合并(不许静默复活)")

    出, _, _ = 三方合(B, B, B)
    ck("⑤", [x["s"] for x in 出] == [1, 2], "两边都没动 → 原样")

    ck("⑥", 键({"a": 1, "b": 2}) == 键({"b": 2, "a": 1}),
       "**反向** · 字段顺序不同的同一条算**一条**(少了 sort_keys 会合完多出几条,"
       "而多出来没人觉得怪)")

    # ── ⑥b-d 「真删」和「改过」要说得开(2026-11-05 加)──────────────────
    # 逼出这几条的事:给 4 条已有规格加了一个字段(`前置`),三方合并眼里那是
    # 「删 4 条 + 加 4 条」,工具报「删/改了」就拒绝 —— 对方只能手工拼 JSON,
    # 中途还把带冲突标记的文件 add 进了 rebase。拒绝照旧拒绝,但两种得分开说。
    甲 = {"script": "a.py", "预期红": "x", "file": [{"path": "a.py"}]}
    甲加字段 = dict(甲, 前置=["git init -q"])
    乙 = {"script": "完全无关.py", "预期红": "y"}

    ck("⑥b", 像同一条吗(甲, 甲) == 1.0 and 0.5 < 像同一条吗(甲, 甲加字段) < 1.0
             and 像同一条吗(甲, 乙) < 0.5,
       "加了个字段的还认得出是同一条;毫不相干的认不成同一条")

    判 = 分辨删改([甲], [甲加字段])
    ck("⑥c", len(判) == 1 and 判[0][1] is not None and 字段差(甲, 甲加字段) == ["+前置"],
       "**给已有条目加字段** → 认成「改过」,并说出差的是哪个字段")

    # ⚠️⚠️ **这一条的用例必须「有一点像、但不到门槛」。**
    #    第一版我拿「毫不相干」那条(相似度恰好 0.0)当 ⑥d,于是**它通过的理由是错的**:
    #    `分辨删改` 里 `最, 分 = None, 0.0`,而循环只在 `s > 分` 时才选中候选 ——
    #    相似度 0.0 的那条**压根没被选中**,`门槛` 那个数根本没参与判断。
    #    结果:咬合把门槛放宽成 0,⑥d 照旧是绿的(实测报「改坏了却没红」)。
    #    > 一条因为「候选压根没被选中」而通过的用例,
    #    > 和一条因为「门槛把它挡住了」而通过的用例,**在绿勾上长得一模一样。**
    #    改成「同一个脚本的**另一条**规格」(共享 script 那一对 → 像 20%):
    #    门槛 0.5 挡住它、门槛 0 放它过 —— 门槛这才是那个决定性的东西。
    #    而这也更贴真实:这个仓库 1245 条规格里,一个脚本常挂着好几条。
    同脚本另一条 = {"script": "a.py", "预期红": "y", "改坏": "完全是另一刀"}
    判2 = 分辨删改([甲], [同脚本另一条])
    判3 = 分辨删改([甲], [乙])
    ck("⑥d", 判2[0][1] is None and 0 < 判2[0][2] < 0.5 and 判3[0][1] is None,
       "**反向** · 真删了一条(同边新增的是同一个脚本的另一条规格,像 20%)→ "
       "**不许**认成「改过」—— 认错了就会建议「直接取新那版」,"
       "而那正是把故意删掉的条目复活",
       # ⚠️ 这一行不只是报数:相似度掉到 0 或涨过门槛,这条用例就不再「决定性」了 ——
       #    那时它会红,而那正是我们要知道的事(别让它安静退化成绿错了理由)
       f"像 {判2[0][2]:.0%}(要落在 0 和门槛之间,否则门槛不是决定性的那一环)")

    # ── ⑦⑧ 接线:真造 git 冲突,真调入口 ──────────────────────────────
    目 = tempfile.mkdtemp(prefix="maj-")
    try:
        成 = 造冲突(目, lambda b: b + [{"script": "我的.py", "预期红": "我"}],
                   lambda b: b + [{"script": "他的.py", "预期红": "他"}])
        if not 成:
            ck("⑦", False, "造不出 git 冲突 —— **这一关没验到接线**"
                           "(git 自己合掉了,而那和「我的工具合对了」结果上一样)")
        else:
            rc = 跑入口(目, "台账.json")
            得 = [x["script"] for x in _读(目)]
            ck("⑦", rc == 0 and 得 == ["s0.py", "s1.py", "我的.py", "他的.py"],
               "**接线** · 真造 git 冲突、真调入口 → 两边的追加都在,base 顺序不变",
               f"退出码 {rc},合出来 {得}")
    finally:
        subprocess.run(["rm", "-rf", 目])

    目 = tempfile.mkdtemp(prefix="maj-")
    try:
        成 = 造冲突(目, lambda b: b + [{"script": "我的.py", "预期红": "我"}],
                   lambda b: [b[0]] + [{"script": "他的.py", "预期红": "他"}])
        if not 成:
            ck("⑧", False, "造不出带删除的 git 冲突 —— **这一关没验到接线**")
        else:
            rc = 跑入口(目, "台账.json")
            ck("⑧", rc == 2,
               "**接线 + 反向** · 真冲突里对方删过一条 → 入口退非零拒绝,不自动合",
               f"退出码 {rc}(该是 2)")
    finally:
        subprocess.run(["rm", "-rf", 目])

    print(f"\n  {'❌' if 挂 else '✅'} 只追加台账三方合并 {过} 条过"
          + (f",{len(挂)} 条没过:{挂[:3]}" if 挂 else ""))
    return 1 if 挂 else 0


