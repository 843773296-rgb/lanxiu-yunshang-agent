"""应用与发布的闸(规格 §17.4-9 / 实施必须遵守第 1、2 条)。

纯逻辑,不碰库、不碰 HTTP。

## 四句写在规格里的话,这个模块就是它们的兑现

**① 「清单里全是确切版本,不许出现『用最新的那个』」**

⚠️ 这一条**在表结构上已经保证了**:`release_manifests` 的每一项依赖都是
一列版本 id,`"latest"` 这种值**根本没有地方放**。
所以这里的闸只管「**这一项填没填**」,不用管「它会不会漂」——
**能用约束表达的不要用判据表达**,而一个放不下「最新」的列,任何时候都放不下。

为什么这条重要:一份写着「用最新的那个」的清单,
**同一份清单在不同时间跑出不同行为**,而那个差别**不报错** ——
出事时「上周二到底跑的是什么」这个问题永远答不出来。

**② 「生产只认审核过的清单」**

测试/预发可以直接切,**生产不行**。而「审过」不是一个布尔:
它得说得出**谁审的、审的是哪一版**。审完之后清单再变过,那次审核就作废 ——
和审批那边「批准之后内容有没有再变过」是同一条判据。

**③ 「指针变更原子」**

环境指针只有一行,切的时候**要么整行是新的,要么整行是旧的**。
半切的后果:一部分流量拿到新版、一部分拿到旧版,而**两边都不报错**。
这条靠事务 + 乐观锁(`expected_revision`)兜,不靠判据。

**④ 「回滚是一次新的部署动作,不是把历史改回去」**

改历史的后果很具体:「上周二在跑哪一版」会变成**现在这一版** ——
而那正是回滚之后最需要问的问题。
所以回滚 = 把环境指针指回一份**历史清单**,并**新记一行**,
历史那几行一个字都不动。
"""

依赖项 = (
    ("prompt_version_id", "Prompt 版本"),
    ("connection_version_id", "模型连接版本"),
    ("index_build_id", "知识索引构建"),
    ("retrieval_config_version_id", "检索配置版本"),
    ("model_artifact_id", "模型产物"),
    ("evaluation_id", "评测实验"),
)

# 哪些依赖对哪种流水线是必须的。
# ⚠️ **按流水线分,而不是「全都必填」** —— 一个 Prompt 生成应用没有知识索引,
# 硬要它填的话,人只会随便填一个,而那比不填糟得多:
# **一个被随便填上的依赖,和一个认真挑过的依赖,在清单上长得一模一样。**
流水线必填 = {
    "prompt": ("prompt_version_id", "connection_version_id"),
    "rag": ("prompt_version_id", "connection_version_id",
            "index_build_id", "retrieval_config_version_id"),
}
流水线们 = tuple(流水线必填)

生产环境 = "production"
环境们 = ("test", "staging", "production")


def 可以出候选吗(*, 流水线, 草稿):
    """能不能把这份候选冻成发布清单。返回问题清单(空 = 可以)。"""
    问 = []
    if 流水线 not in 流水线必填:
        问.append(f"认不出的流水线 {流水线!r} —— 首版只有 {list(流水线们)}")
        return 问
    d = 草稿 or {}
    for 键 in 流水线必填[流水线]:
        中文 = dict(依赖项)[键]
        值 = (d.get(键) or "")
        if not str(值).strip():
            问.append(f"**{中文}没挑**(`{键}`)—— 这条流水线少不了它")
        elif str(值).strip().lower() in ("latest", "最新", "current", "head"):
            # 表结构上其实放得下这几个字符串(它是 TEXT 的 id 列),
            # 所以这条判据不是多余的:**它拦的是「把占位词当成 id 填进去」**。
            问.append(f"**{中文}填的是「{值}」** —— 清单里不许出现「用最新的那个」:"
                      f"同一份清单在不同时间会跑出不同行为,**而那个差别不报错**")
    return 问


def 审核还算数吗(*, 审核, 清单内容哈希):
    """这次审核对**现在这份清单**还算不算数。

    `审核` 形如 `{"审核人": ..., "审的哈希": ..., "结论": "通过"/"驳回"}`。

    ⚠️ 判据**不是「审过没有」**,是「**审的是不是这一份**」——
    审完之后清单再变过,那次审核就作废。
    (和审批那边「批准之后内容有没有再变过」是同一条。)
    """
    if not 审核:
        return False, "**还没审核过**"
    if (审核.get("结论") or "") != "通过":
        return False, f"审核结论是「{审核.get('结论')}」,不是「通过」"
    if (审核.get("审的哈希") or "") != (清单内容哈希 or ""):
        return False, ("**审核之后这份清单又变过了** —— 审的是另一份内容。"
                       "重新审一次;不然「审过」这三个字保的不是现在这一版")
    return True, None


def 可以发布吗(*, 环境, 清单, 审核):
    """能不能把这份清单发到这个环境。返回问题清单(空 = 可以)。"""
    问 = []
    if 环境 not in 环境们:
        问.append(f"环境只收 {list(环境们)},拿到 {环境!r} —— **不给默认值**")
        return 问
    if not 清单:
        问.append("没有这份发布清单")
        return 问
    if 环境 == 生产环境:
        # **只有生产要审。** 测试/预发直接切 —— 那正是它们存在的理由。
        行, 为什么 = 审核还算数吗(审核=审核,
                             清单内容哈希=(清单.get("content_hash") or ""))
        if not 行:
            问.append(f"**生产只认审核过的清单** —— {为什么}")
    return 问


def 可以回滚吗(*, 目标清单, 当前指针):
    """能不能回滚到这份历史清单。返回问题清单(空 = 可以)。"""
    问 = []
    if not 目标清单:
        问.append("没有这份历史清单")
        return 问
    if 当前指针 and 当前指针.get("release_manifest_id") == 目标清单.get("id"):
        问.append("**这个环境现在就指着它** —— 回滚到自己不是一个动作,"
                  "而返回「成功」会让人以为回滚发生过")
    return 问
