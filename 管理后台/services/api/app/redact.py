"""导出前的敏感信息检测(方案 B 的**受限首版**,2026-09-28 用户拍板)。

## ⚠️ 这个模块**不脱敏**,它只做两件事

    ① 检出来 → **把那一条隔离掉**,并说清是哪一类命中的
    ② 检不出来的情况下 → **默认不放行**

第二条是用户当天明确纠正的一处:我原来的方案卡写「今天语料 0 命中 → 全部放行」。

> **零命中不等于没有敏感信息。** 它只说明**我这几个检测器没找到**。
> 把「没找到」当成「没有」,是这套机制最容易出的那个错 ——
> 而它出错的时候一个字都不会报,只会安静地把带客户信息的语料交出去。

所以放行不靠「扫了一遍没命中」,靠**来源在覆盖已验证的白名单里**(见下)。

## 白名单的范围:**按数据来源白名单,不按样本白名单**

`samples.source` 说这条样本是哪来的。只有**做过覆盖验证**的来源才允许在
零命中的时候自动放行:

    覆盖已验证的来源 = ("seed", "fixture", "mock")

这两个是项目自己造的构造数据,它们里面有什么是**我们自己写的**,
所以「零命中 = 没有」在它们身上成立。

其余来源(生产会话、人工回流、第三方导入……)**一律不自动放行** ——
不是因为它们一定有敏感信息,而是因为**没人验证过检测器在那种数据上的覆盖率**。
要放行得先做覆盖验证,再把来源加进这张白名单里(改这一行要连着提交覆盖报告)。

## 检测类别:五类,每一类**都写明已知盲区**

一个不写盲区的检测器,会被当成「扫过了就安全」。下面每一类的盲区都是
`tools/redact_coverage.py` 里**有测例**的 —— 盲区不是免责声明,是待办清单。

## ⚠️ 手机号那条正则为什么要锚定

实测:不锚定的 `1[3-9]\\d{9}` 在真实会话记录(5402 行)上命中 683 行,
而那 683 个「号码」**没有一个是库里真实客户的号** —— 逐个看过去,
它们全是 `sdk_cost_usd: 0.15664500000000003` 这类**浮点尾数**。

**真阳性 0 个,误报 683 个。** 一个这样的脱敏器会把成本数字改坏,
而一个真手机号都没挡住。所以前后都加了「不许紧挨数字或小数点」。

## ⚠️ 姓名这一类是**已知不完整**的,而且不假装完整

中文姓名写不出可靠的正则(「周姐」「小林」「林先生」都是称呼,
而「周末」「小林子」不是人名)。这一版只认**紧邻称呼词**的窄模式,
并且在报告里明说它**抓不到散在句子里的姓名**。

→ 所以一个声明了「可能有客户姓名」的数据集,**光靠这个检测器不许自动放行**;
  它的来源必须在覆盖白名单里,否则一律拒。**检不出来就不给**,不是「检不出来就当没有」。
"""
