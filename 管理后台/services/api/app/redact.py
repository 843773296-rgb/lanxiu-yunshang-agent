# 一条一条看不出来 —— 一条没命中的生产会话和一条没命中的构造数据,
# 在样本上长得一模一样,而它们的「零命中」含义完全不同。
覆盖已验证的来源 = ("seed", "fixture", "mock")


def 扫一条(文本):
    """返回命中清单 [(类别, 说明)]。空 = **这几个检测器没找到**,不等于没有。"""
    出 = []
    s = str(文本)
    for 名, 正则, 说明, _盲 in _类别:
        命中 = _姓名称呼(s) if 正则 is None else bool(正则.search(s))
        if 命中:
            出.append((名, 说明))
    return 出


_称呼词 = ("先生", "女士", "小姐", "太太")


def _姓名称呼(s):
    """「X先生/女士/小姐/太太」或「小X/老X」,**且 X 必须是百家姓里的单姓**。

    ⚠️ 这一条是覆盖报告逼出来的:`小周说下周来` 要抓到,
    而 `小票要一起给客户` 不许抓 —— 两者结构完全相同(小 + 一个汉字),
    **区别只在「周」是姓而「票」不是**。所以判据必须查姓,不能查结构。
    """
    for 词 in _称呼词:
        i = s.find(词)
        while i > 0:
            if s[i - 1] in _单姓:
                return True
            i = s.find(词, i + 1)
    for k, ch in enumerate(s):
        if ch in ("小", "老") and k + 1 < len(s) and s[k + 1] in _单姓:
            return True
    return False


def 盲区表():
    """每一类的已知盲区。**报告里要带上它** —— 不写盲区的检测器会被当成「扫过了就安全」。"""
    return [{"类别": 名, "查的是": 说明, "已知盲区": 盲} for 名, _, 说明, 盲 in _类别]


def 能自动放行吗(来源):
    """这个来源的零命中,算不算数。

    ⚠️ **默认否。** 用户 2026-09-28 拍板时明确的一条:
    「不能把零命中当作无敏感信息」「未经覆盖验证的数据暂不自动放行」。
    """
    return (来源 or "").strip().lower() in 覆盖已验证的来源


def 分拣(样本们):
    """把一批样本分成 (放得出去的, 被隔离的, 账)。

    `样本们` 要有 `id` / `source` / `文本`(样本内容拍平成字符串)。

    三档,**不是两档**:
      · 命中 → 隔离,说清哪一类
      · 没命中但来源没做过覆盖验证 → **也不放行**(零命中 ≠ 没有)
      · 没命中且来源在白名单里 → 放行
    """
    出, 隔离 = [], []
    for s in 样本们:
        命中 = 扫一条(s.get("文本", ""))
        if 命中:
            隔离.append({"id": s.get("id"), "为什么": "命中 " + "、".join(n for n, _ in 命中),
                         "命中类别": [n for n, _ in 命中],
                         "代号": [代号.get(n, "other") for n, _ in 命中]})
            continue
        if not 能自动放行吗(s.get("source")):
            隔离.append({"id": s.get("id"),
                         "为什么": f"来源 `{s.get('source')}` **没做过覆盖验证** —— "
                                 f"检测器零命中只说明没找到,不说明没有",
                         "命中类别": [], "代号": [来源没验证代号]})
            continue
        出.append(s)
    账 = {
        "总数": len(样本们),
        "放得出去": len(出),
        "被隔离": len(隔离),
        "因为命中被隔离": sum(1 for x in 隔离 if x["命中类别"]),
        "因为来源没验证被隔离": sum(1 for x in 隔离 if not x["命中类别"]),
        "覆盖已验证的来源": list(覆盖已验证的来源),
    }
    # 按代号汇总,给响应头用(ASCII)
    计 = {}
    for x in 隔离:
        for c in x["代号"]:
            计[c] = 计.get(c, 0) + 1
    账["隔离代号计数"] = 计
    return 出, 隔离, 账
