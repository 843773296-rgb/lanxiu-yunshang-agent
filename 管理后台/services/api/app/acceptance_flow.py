def 判_十条(行们):
    """行们:[{编号, 结论, 签字人, 签字时间}]。全签 = 十条都在、每条结论「通过」且有签字人。
    **一行都没有 → 拿不到**(空集合上「全都签了」自动成立,那不叫通过)。"""
    应有 = [c for c, _, _ in 十条场景]
    有 = {r["编号"]: r for r in 行们}
    缺 = [c for c in 应有 if c not in 有]
    if not 行们:
        return {"项": "十条全签", "状态": 状态_拿不到, "已签通过": 0, "应有": len(应有),
                "说明": "这个项目里一条验收场景都没有 —— 拿不到 ≠ 通过"}
    签了通过 = [c for c in 应有 if c in 有 and 有[c]["结论"] == "通过" and 有[c]["签字人"]]
    不通过 = [c for c in 应有 if c in 有 and 有[c]["结论"] == "不通过"]
    未签 = [c for c in 应有 if c in 有 and c not in 签了通过]
    if 缺:
        return {"项": "十条全签", "状态": 状态_拿不到, "已签通过": len(签了通过), "应有": len(应有),
                "说明": f"少了 {'、'.join(缺)} 这几条场景的记录 —— 拿不到 ≠ 通过"}
    if len(签了通过) == len(应有):
        return {"项": "十条全签", "状态": 状态_通过, "已签通过": len(签了通过), "应有": len(应有),
                "说明": f"{len(应有)} 条都是「通过」并由店长签了字"}
    话 = f"已签且通过 {len(签了通过)} / {len(应有)} 条;还没签或没通过:{'、'.join(未签)}"
    return {"项": "十条全签", "状态": 状态_不通过 if 不通过 else 状态_进行中, "已签通过": len(签了通过),
            "应有": len(应有), "说明": 话 + (f"(其中结论「不通过」的:{'、'.join(不通过)})" if 不通过 else "")}


def 判_试点(起算日, 今天):
    """起算日 = 真数据导入日(date 或 None);今天由调用方给 —— **口径函数不自己取当前日期**(CLAUDE.md 第 9 节①)。
    没设 → 未开始;**不许默认成今天**(那会让「两周」从打开页面那天自己开始走)。"""
    if 起算日 is None:
        return {"项": "试点满两周", "状态": 状态_未开始, "起算日": None, "已过天数": None, "还差天数": None,
                "说明": "未开始 —— 真实试点还没开始(真数据导入日还没设)。拿不到 ≠ 通过"}
    已过 = (今天 - 起算日).days
    if 已过 < 0:
        # 接口不收将来的日期;库里要是有(手改的),照实说,不算开始
        return {"项": "试点满两周", "状态": 状态_未开始, "起算日": 起算日.isoformat(), "已过天数": 已过, "还差天数": None,
                "说明": f"起算日 {起算日.isoformat()} 在今天之后 —— 还没开始,不算通过"}
    if 已过 >= 试点天数:
        return {"项": "试点满两周", "状态": 状态_通过, "起算日": 起算日.isoformat(), "已过天数": 已过, "还差天数": 0,
                "说明": f"从 {起算日.isoformat()} 起已经 {已过} 天(要满 {试点天数} 天)"}
    return {"项": "试点满两周", "状态": 状态_进行中, "起算日": 起算日.isoformat(), "已过天数": 已过,
            "还差天数": 试点天数 - 已过,
            "说明": f"从 {起算日.isoformat()} 起第 {已过} 天,还差 {试点天数 - 已过} 天满两周"}


def 判_费用(汇总):
    """汇总:None(拿不到这份数据)或 {行数, 已知金额, 金额未知的行数, 币种们, 月份}。
    **只有「每一行都算得出参考价、币种都是美元、合计不超过上限」才算通过**;没数据 / 算不出 / 币种对不上一律「拿不到」。"""
    基 = {"项": "月费用未超上限", "上限": 月费用上限, "币种": 费用币种}
    if 汇总 is None:
        return dict(基, 状态=状态_拿不到, 已知金额=None, 说明="未接入 —— 后台读不到费用汇总。拿不到 ≠ 通过")
    月 = 汇总.get("月份")
    if not 汇总.get("行数"):
        return dict(基, 状态=状态_拿不到, 已知金额=None,
                    说明=f"{月} 这个月没有一笔真调用的用量上报进来(mock 不算)—— 没数据,拿不到 ≠ 通过")
    if 汇总.get("金额未知的行数"):
        return dict(基, 状态=状态_拿不到, 已知金额=汇总.get("已知金额"),
                    说明=(f"{月} 有 {汇总['金额未知的行数']} 行算不出参考价(没有价目表快照),"
                          f"已知的 {汇总.get('已知金额')} 不是全部 —— 拿不到 ≠ 通过"))
    外币 = [c for c in (汇总.get("币种们") or []) if c != 费用币种]
    if 外币:
        return dict(基, 状态=状态_拿不到, 已知金额=汇总.get("已知金额"),
                    说明=f"{月} 有币种 {'、'.join(外币)} 的账,不换算就比不了美元上限 —— 拿不到 ≠ 通过")
    额 = 汇总.get("已知金额") or 0
    if 额 > 月费用上限:
        return dict(基, 状态=状态_不通过, 已知金额=额, 说明=f"{月} 参考价合计 {额} 美元,超过上限 {月费用上限}")
    return dict(基, 状态=状态_通过, 已知金额=额,
                说明=f"{月} 参考价合计 {额} 美元,没超过上限 {月费用上限}(参考价按标价估,不是账单)")


def 判_做完(十条, 试点, 费用):
    三项 = [十条, 试点, 费用]
    做完 = all(x["状态"] == 状态_通过 for x in 三项)
    拿不到的 = [x["项"] for x in 三项 if x["状态"] in (状态_拿不到, 状态_未开始)]
    return {"做完了吗": 做完, "三项": 三项,
            "说明": ("三项都通过 —— 按 11-12 拍的标准算做完" if 做完 else
                   "还没做完:三项都「通过」才算" + (f";{'、'.join(拿不到的)} 现在拿不到数据 —— **拿不到 ≠ 通过**" if 拿不到的 else ""))}


def 签于试点前吗(签字时间, 起算日):
    """签字在真实试点开始之前(虚拟试点,拍板第二十条)。只标出来,**算不算数由业务定,这里不替它判**。"""
    if 签字时间 is None:
        return None
    if 起算日 is None:
        return True
    d = 签字时间.date() if isinstance(签字时间, _dt.datetime) else 签字时间
    return d < 起算日
