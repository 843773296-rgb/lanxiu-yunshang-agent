# -*- coding: utf-8 -*-
"""设置组的闸:成员与权限 / 预算 / 审计。纯逻辑。

## ⚠️ 一、不能通过邀请获得自己没有的权限

规格 §15.3 最后一句,落点是 `perms.可以授予吗()` —— 它**早就写好了**,
而在这之前**没有任何接口调用它**。
> 判据写好了却没被调用,和没写是一样的。

## ⚠️ 二、不许把最后一个能管权限的人去掉

这一条不在规格里,是推出来的:`POST /memberships` 能改角色,
那就能把自己降成 viewer。而**一个没有任何人能管权限的项目,
从接口这一侧永远救不回来** —— 只能去改库。

所以它和别的闸不一样:**别的闸拦的是「做错了」,这道拦的是「做完之后没法回头」**。

## ⚠️ 三、预算 0 不是「没限制」

`limit_amount = 0` 的意思是**一分都不许花**,而不是「没设上限」。
「没设上限」要用**没有这一行**来表达。

把两者混成一个数的后果很具体:某天有人把预算清成 0 想临时停掉,
而系统当成「不限」—— **然后账单继续涨,而界面上显示预算是 0**。

同理 `reserved_amount`(已预留)**不是**已花:
预留是「打算花」,花掉是「已经花」。两者在一个数里的话,
「还能花多少」这个问题会答出两个不同的值,取决于谁来算。
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "contract"))
import perms as PM

周期们 = ("day", "month", "total")
范围们 = ("project", "connection")


def 谁能管权限(成员们):
    """这批成员里,哪些人能改权限(即有 `配置密钥与预算`)。"""
    出 = []
    for m in 成员们:
        行, _ = PM.判("配置密钥与预算", m.get("role"), m.get("special_grants") or [])
        if 行:
            出.append(m.get("user_id"))
    return 出


def 可以改成员吗(*, 我角色, 我专项, 目标工号, 要给的角色, 要给的专项, 现有成员们):
    """能不能把 `目标工号` 设成这套权限。返回问题清单(空 = 可以)。"""
    问 = []
    if 要给的角色 not in PM.角色们:
        问.append(f"角色只收 {PM.角色们},拿到 {要给的角色!r}")
        return 问
    坏专项 = sorted(set(要给的专项 or []) - set(PM.能力们))
    if 坏专项:
        问.append(f"这些专项授权不在能力表里:{坏专项} —— "
                  f"**不收任意字符串**:一个拼错的授权会安静地什么都不开")

    # ⓪ **给了但不生效的授权,当场说** ——
    #
    # ⚠️ 2026-10-01 页面接线测试当场抓到:给一个 `viewer` 加 `审批工具动作`,
    # 接口**收下了(201,`专项授权` 里存着它)**,而 `实际能做的` 里没有它 ——
    # 因为那条能力对 viewer 是 `deny`,只对 admin 是 `grantable`。
    #
    # > **一个存下来却不生效的授权,比没存更坏**:
    # > 界面上它看着是给了的,而那个人点下去会被拒 ——
    # > 到那时候没人会想到是这一行权限的问题。
    #
    # 为什么是**拦住**而不是「静默丢掉」:丢掉之后那条授权在界面上消失了,
    # 人会以为自己没点上,再点一次 —— 而第二次也一样。
    # 拦住并说清「这个角色不能被授权它」,人才知道要先换角色。
    没用的 = sorted(x for x in (要给的专项 or [])
                 if x in PM.能力们
                 and PM.矩阵.get(x, {}).get(要给的角色) != PM.可授权)
    if 没用的:
        能授的 = sorted(k for k, v in PM.矩阵.items()
                     if v.get(要给的角色) == PM.可授权)
        问.append(f"这几条专项授权对「{PM.角色中文.get(要给的角色, 要给的角色)}」"
                  f"**给了也不生效**:{没用的} —— "
                  f"「可授权」是**按角色**算的,而角色名上看不出来。"
                  f"这个角色能被授权的是 {能授的 or '一条都没有'}。"
                  f"**不静默丢掉**:丢掉之后那条授权在界面上消失了,"
                  f"人会以为自己没点上,再点一次 —— 而第二次也一样")

    # ① 不能授予自己没有的权限(§15.3)
    行, 超 = PM.可以授予吗(我角色, 我专项, 要给的角色, 要给的专项 or [])
    if not 行:
        问.append(f"**这套权限超出你自己有的**:{超} —— "
                  f"不能通过邀请获得自己没有的权限。要给就先让人给你")

    # ② 不许把最后一个能管权限的人去掉
    能管的 = set(谁能管权限(现有成员们))
    他本来能管 = 目标工号 in 能管的
    他改完还能管, _ = PM.判("配置密钥与预算", 要给的角色, 要给的专项 or [])
    if 他本来能管 and not 他改完还能管 and 能管的 == {目标工号}:
        问.append(f"**{目标工号} 是这个项目里最后一个能管权限的人** —— "
                  f"改完就没人能改权限了,而那个状态**从接口这一侧救不回来**"
                  f"(只能去改库)。先把权限给别人,再改他")
    return 问


def 可以设预算吗(*, 范围, 周期, 上限, 币种):
    """返回问题清单(空 = 可以)。"""
    问 = []
    if 范围 not in 范围们:
        问.append(f"范围只收 {list(范围们)},拿到 {范围!r}")
    if 周期 not in 周期们:
        问.append(f"周期只收 {list(周期们)},拿到 {周期!r}")
    if 上限 is None:
        问.append("**上限必填。** 想表达「不限」就**别建这一行** —— "
                  "`0` 的意思是「一分都不许花」,不是「没设上限」")
    else:
        try:
            v = float(上限)
        except Exception:
            问.append(f"上限要是个数,拿到 {上限!r}")
            v = None
        if v is not None and v < 0:
            问.append("上限不能是负数")
    if not (币种 or "").strip():
        问.append("币种必填 —— **不给默认值**:两个币种的数放在一列里,"
                  "「总共花了多少」会算出一个没有意义的和")
    return 问


def 还能花多少(预算行):
    """**「还能花多少」只由这一行自己回答,而且把两个数分开报。**

    `reserved_amount`(已预留)**不是**已花:预留是「打算花」,花掉是「已经花」。
    合成一个数的话,这个问题会答出两个不同的值,取决于谁来算。
    """
    if not 预算行:
        # ⚠️ **没有这一行 = 没设上限**,而不是「上限 0」。
        return {"设了上限吗": False, "上限": None, "已预留": None, "还能预留": None,
                "note": "**没设上限**(没有这一行)—— 和「上限 0」完全不是一回事"}
    上限 = 预算行.get("limit_amount")
    预留 = 预算行.get("reserved_amount") or 0
    return {"设了上限吗": True, "上限": 上限, "已预留": 预留,
            "还能预留": (None if 上限 is None else float(上限) - float(预留)),
            "note": ("⚠️ **上限是 0 = 一分都不许花**,不是「不限」。"
                     if 上限 is not None and float(上限) == 0 else
                     "「已预留」不是「已花」—— 预留是打算花,花掉是已经花")}
