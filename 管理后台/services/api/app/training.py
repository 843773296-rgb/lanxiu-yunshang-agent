# -*- coding: utf-8 -*-
"""微调链的闸:**一份样本能不能拿去训练**(规格 §17.4)。

这个模块只有纯逻辑,不碰库、不碰 HTTP —— 和 `evals.py` / `approvals.py` 一样,
判据要能在没有服务的情况下逐条喂进去验。

## 为什么闸在控制面,而正文在应用层

一份训练数据导出,危险的地方不是「导得慢」,是**它一旦流出去就追不回来**。
所以规格把「数据集 / 版本 / 训练任务」放在控制面:控制面管的不是字节,
是**谁能导、导的时候脱了什么、这一版喂给了哪个训练任务**。

## ⚠️ 一、「一条都不剩」必须是拒,不是空文件

过完所有闸之后一条样本也不剩,返回 200 加一个空的 `.jsonl`
**看起来是完全成功的** —— 下游拿它去训练,训出一个什么都没学到的模型,
**而每一步都不报错**。

和账本那条「未知不是 0」同一个形状:
**「什么都没有」和「成功地什么都没有」必须长得不一样。**

所以拒的时候要同时回答「**那里面到底有什么**」——
「全部 5 条都是独立测试档」是一句能让人知道下一步做什么的话,
「没有可导出的样本」不是。
(这个仓库的老规矩:报告「我没有 X」时,同时报告「我有什么」。)

## ⚠️ 二、训练导出和评测分集是同一个泄漏问题

把独立测试档的样本混进训练集 → 模型在评测上分数虚高,
**而那个分数看起来完全正常**,没有任何一步会报错。

所以这里**复用 `evals.查分集泄漏()`**,不写第二份:
同一个 `group_id` 的样本一部分在训练档、一部分在评测档 —— 那批样本的
分集本身就不可信,所以**拒整批,不是过滤掉冲突的那几条**。
过滤等于替人做了「这几条算训练」的决定,而那正是分不清的那部分。

## ⚠️ 三、mock 的产物不许默认混进真实训练

铁律(规格 §17.4):`TRAINING_ADAPTER=mock` 的产物不许计入真实评测或发布。
一份 mock 样本在**数据形状上和真的一模一样** —— 所以只能靠 `source` 认,
而且**默认拒**:要 mock 得显式说要,说了之后导出的每一处(文件名、
审计记录、响应头)都带着 mock 的标记,不给它一个能装成真数据的机会。

## ⚠️ 四、脱敏策略「没声明」和「脱不干净」是两件事

`datasets.redaction_policy` 为空 = **没人声明过这个数据集该怎么脱**。
这时候拒的理由是「策略没声明」,不是「脱不干净」——
两者下一步完全不同(去声明 / 去改脱敏器),而混成一句话会把人指向错的方向。

⚠️ **脱敏器本身还没选型**(正则 / 白名单 / 模型三条路差别很大,
是个要拍板的选择),所以现在这条闸只判「声明了没有」,
**不假装自己在脱** —— 一个声称脱过而实际没脱的接口比不脱危险得多。
"""
import evals
import redact

训练档 = "训练"
可训练的复核状态 = ("已通过",)

# 声明成这个开头 = 「这份数据里没有要脱的东西」,导出放行而且一个字都不改。
# 其余任何声明 = 确实需要脱,而**脱敏器还没选型** → 不放行。
无需脱敏前缀 = "无需脱敏:"


def 脱敏还没选型(策略):
    """声明了「需要脱敏」但脱敏器还没选型 → 返回一句理由;否则 None。

    ⚠️ **这条判据必须和列表页用同一份。** 第一版只写在接口里,
    于是列表页上那一份显示「**能导出**」,而真的去导会被 422 拦住 ——
    **列表承诺的和接口做的不是一回事**,而两边各自看都对。
    (同一族:一个含义两个实现。两份实现早晚各自演化,而漂掉的那天
     表现成「界面说能、点下去不能」,没人会想到是两处判据。)
    """
    策 = (策略 or "").strip()
    if not 策 or 策.startswith(无需脱敏前缀):
        return None
    return ("这个数据集**声明了需要脱敏**,而脱敏器还没选型"
            "(正则 / 白名单 / 模型三条路差别很大,要先拍板)—— "
            "在那之前这里**不给不脱的版本**:一个声称脱过而实际没脱的接口,"
            "比明说「没脱」危险得多")


def 分档统计(样本们):
    """每个分集各有几条。**空数据集返回空字典,不是 0** —— 见下面 `能导出吗`。"""
    出 = {}
    for s in 样本们:
        出[s.get("split") or "(没标分集)"] = 出.get(s.get("split") or "(没标分集)", 0) + 1
    return 出


def 能导出吗(样本们, *, 脱敏策略, 要mock=False):
    """返回 (能导出的样本, 拦下的原因清单, 报给人的账)。

    原因清单空 = 能导。**非空就一条都不给** ——
    「导一半」在训练这件事上没有意义:少掉的那一半不会报错,
    只会让训练出来的东西和你以为的不一样。
    """
    拒 = []
    账 = {"总数": len(样本们), "分档": 分档统计(样本们)}

    # ① 空数据集。**先判这条** —— 后面每条闸在空集上都恰好通过,
    #    于是一个空数据集会一路绿灯走到「导出成功,0 条」。
    if not 样本们:
        拒.append("这个数据集里**一个样本都没有** —— 空的导出文件"
                  "看起来是成功的,而下游会拿它去训练")
        return [], 拒, 账

    # ② 脱敏策略没声明(不是「脱不干净」,见文件头第四节)
    if not (脱敏策略 or "").strip():
        拒.append("**没声明脱敏策略**(`datasets.redaction_policy` 是空的)—— "
                  "拒的理由是「没人声明过这个数据集该怎么脱」,不是「脱不干净」;"
                  "下一步是去声明,不是去改脱敏器")

    # ②bis 声明了要脱,而脱敏器还没选型。**和 ② 分开报** ——
    #      「没人声明过怎么脱」和「声明了但我们还脱不了」下一步完全不同。
    还没选 = 脱敏还没选型(脱敏策略)
    if 还没选:
        拒.append(还没选)

    # ③ 同组跨档 = 这批样本的分集不可信。**拒整批**,见文件头第二节。
    漏 = evals.查分集泄漏(样本们)
    if 漏:
        拒.append(f"有 {len(漏)} 组样本**跨了分集**:{漏[:5]}"
                  f"{' …' if len(漏) > 5 else ''} —— 同一组一部分在训练档、"
                  "一部分在评测档,那么「哪几条算训练」这件事本身就是不清楚的。"
                  "**不过滤掉冲突的那几条** —— 过滤等于替人做了那个决定")

    # ④ 只有训练档能出去
    训练 = [s for s in 样本们 if s.get("split") == 训练档]
    非训练 = len(样本们) - len(训练)
    账["训练档"] = len(训练)
    账["拦下的非训练档"] = 非训练

    # ⑤ 没复核过的不出去
    过了复核 = [s for s in 训练 if s.get("review_status") in 可训练的复核状态]
    账["拦下的没复核"] = len(训练) - len(过了复核)

    # ⑥ mock 产物默认拒(铁律)
    有mock = [s for s in 过了复核 if (s.get("source") or "").lower() == "mock"]
    账["里面的 mock 条数"] = len(有mock)
    if 有mock and not 要mock:
        拒.append(f"里面有 {len(有mock)} 条 **mock 产物**,而 mock 的产物"
                  "不许计入真实训练(规格 §17.4 的铁律)。"
                  "mock 样本在数据形状上和真的一模一样,只能靠 `source` 认 —— "
                  "**要它就得显式说要**(`要mock=1`),说了之后导出的每一处都会带 mock 标记")
    出 = 过了复核 if 要mock else [s for s in 过了复核 if (s.get("source") or "").lower() != "mock"]

    # ⑥bis **来源覆盖**:零命中不等于没有敏感信息(用户 2026-09-28 拍板)。
    #
    # ⚠️ 这一条放在这里、而不是只放在接口里,是因为**列表页要和接口说同一句话**。
    # 第一版只写在接口里,于是列表上那两份显示「能导出」,点下去 422 ——
    # **界面承诺的和接口做的不是一回事**,而两边各自看都对。
    # 今天这个形状第三次了(前两次:脱敏器那条、`usage_ledger.source` 一列两义)。
    #
    # ⚠️ 只判得了**来源**这一半:另一半(逐条扫内容)要读 `content`,
    # 而这个函数和列表页都只拿形状。所以列表上会注明「还有一道要看内容的闸」。
    没验证的来源 = sorted({(s.get("source") or "?") for s in 出
                       if not redact.能自动放行吗(s.get("source"))})
    if 没验证的来源:
        拒.append(f"这些来源**没做过覆盖验证**:{没验证的来源} —— "
                  f"检测器零命中只说明没找到,不说明没有。"
                  f"覆盖已验证的是 {list(redact.覆盖已验证的来源)};"
                  f"要放行得先跑 `tools/redact_coverage.py` 做覆盖验证再加进白名单")
        出 = []

    # ⑦ 过完闸一条不剩 —— 拒,并且说清里面到底有什么(文件头第一节)
    #
    # ⚠️ **判的是 `过了复核` 而不是 `出`,而且不管前面有没有别的闸响过。**
    # 第一版写的是 `if not 出 and not 拒` —— 于是脱敏策略没声明时这条不说话,
    # 人去补了声明、再试一次,才知道**里面压根没有训练档的样本**。
    # 一轮修一条,而两件事本来同时就能看出来。
    # (仓库老规矩:报告「我没有 X」时,同时报告「我有什么」。
    #  一次只报一条拦阻理由,是同一条规矩在**数量**上没做到。)
    #
    # 判 `过了复核` 而不是 `出`:`出` 会被 mock 那道闸过滤掉一部分,
    # 那时候说「一条不剩」是误导 —— 真相是「只剩 mock 的」,而那句话
    # 第六条已经说过了。**两条闸不许说同一件事的两个版本。**
    if not 过了复核:
        档 = "、".join(f"{k} {v} 条" for k, v in sorted(账["分档"].items()))
        拒.append(f"过完闸**一条可训练的样本都不剩**,而这个数据集里有 "
                  f"{len(样本们)} 条:{档}。"
                  f"(训练档 {len(训练)} 条,其中过了复核 {len(过了复核)} 条)"
                  " —— 不返回空文件:空文件看起来是成功的")

    账["能导出"] = len(出) if not 拒 else 0
    return (出 if not 拒 else []), 拒, 账


