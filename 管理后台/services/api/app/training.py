# 微调训练链的三道闸(规格 §17.4 / 开篇第 4 条)
# ══════════════════════════════════════════════════════════════════
#
# 规格开篇第 4 条是这一整块的骨架:
#
# > **训练完成仅代表得到产物;须经过登记、兼容检查、评测、部署与发布才能服务用户。**
#
# 所以这条链上有**四个各不相同的状态**:
#
#     训练完成  →  有产物  →  产物可用(校验过)  →  在服务用户(部署了)
#
# **把任意两个合成一个,就是这个模块最容易出的错** ——
# 而合并之后界面上看起来一切正常:一个没校验过的产物会显示成「可以用了」。
# 三道闸分别守三个边界,而不是一道「训练成功了吗」。

训练目标 = ("SFT", "DPO")
参数更新方式 = ("LoRA", "全量")

# ⚠️ 规格 §原文:「SFT/DPO 是训练目标或方法;LoRA/全量更新是参数更新方式。
# **表单必须分别选择,不能做成「SFT、DPO、LoRA 三选一」**。」
#
# 做成三选一的后果不是少一个选项,是**一个维度被悄悄丢掉** ——
# 选了 LoRA 的那些任务,没人说得出它们是 SFT 还是 DPO,
# 而那两者训出来的东西完全不是一回事。


def 可以提交训练吗(*, 目标, 更新方式, 版本, 样本们, 是mock):
    """能不能提交这个训练任务。返回问题清单(空 = 可以)。

    `版本` 是冻结的数据集版本行(None = 没给或不存在)。
    """
    问 = []
    if 目标 not in 训练目标:
        问.append(f"训练目标只收 {list(训练目标)},拿到 {目标!r} —— "
                  f"**它和参数更新方式是两个维度**,不是三选一")
    if 更新方式 not in 参数更新方式:
        问.append(f"参数更新方式只收 {list(参数更新方式)},拿到 {更新方式!r} —— "
                  f"**它和训练目标是两个维度**,不是三选一")

    # ⚠️ **只能拿冻结过的版本训练,不能拿「当前样本」训练。**
    # 拿活数据训练的后果:训完之后没人说得出它到底学了什么,
    # 因为那批样本已经被改过了 —— 而这正是 `frozen_samples` 存在的理由。
    if not 版本:
        问.append("没有指定**冻结过的数据集版本** —— 拿活数据训练的话,"
                  "训完之后没人说得出它到底学了什么(样本随时会被改)")
    elif not 版本.get("frozen_samples"):
        问.append(f"数据集版本 {版本.get('id')} **没有固化内容**(老版本行)—— "
                  f"拿不回当时那批题,这次训练不可复现。重新冻一版再训")

    # ⚠️ 规格原文:「**独立测试集不能被选择为训练数据;校验分集泄漏**」。
    # 这和导出那道闸是**同一个泄漏问题**,所以**复用同一个判据**,不写第二份。
    if 样本们:
        漏 = evals.查分集泄漏(样本们)
        if 漏:
            问.append(f"这批样本有 {len(漏)} 组**跨了分集**:{漏[:5]} —— "
                      f"独立测试集不能被选进训练数据,而跨档意味着「哪几条算训练」"
                      f"本身就说不清")
        非训练 = [s for s in 样本们 if s.get("split") != 训练档]
        if not [s for s in 样本们 if s.get("split") == 训练档]:
            问.append(f"这一版里**一条训练档的样本都没有**(共 {len(样本们)} 条,"
                      f"分档 {分档统计(样本们)})—— 训练拿不到料")
        elif 非训练:
            # 不是错:一版里同时有训练/验证/独立测试是正常的。
            # 但**要说出来**,因为「我以为整版都拿去训练了」是个常见误会。
            pass

    # mock 不是错,但**必须当场标下来**,而且标的是「这次跑的是什么」。
    # ⚠️ `是mock` **不给默认值** —— 忘传会把 mock 记成真训练,
    # 而一份 mock 产物在数据形状上和真的一模一样(今天这条兑现第三次)。
    if 是mock is None:
        问.append("`是mock` **没传** —— 不默认 False:"
                  "忘传会把 mock 记成真训练,而两者的产物形状一模一样")
    return 问


def 可以标可用吗(产物):
    """产物能不能标「可用」。返回问题清单(空 = 可以)。

    规格:**「校验后才能标可用」—— 训练完成只代表得到产物。**
    """
    问 = []
    if not 产物:
        问.append("没有这个产物")
        return 问
    if not 产物.get("verified_at"):
        问.append("**还没校验过**(`verified_at` 是空的)—— "
                  "「训练完成」只代表得到产物,不代表这份产物装得上、跑得起来")
    if not 产物.get("content_hash"):
        问.append("**没有内容哈希** —— 没有它,「部署的那一版和校验的那一版是同一份吗」"
                  "这个问题答不出来")
    if not 产物.get("file_manifest"):
        问.append("**没有文件清单** —— 少一个文件的产物装载时才会报错,"
                  "而那时候它已经被标成可用了")
    return 问


def 可以部署吗(产物, *, 环境, 训练是mock):
    """能不能把这个产物部署出去。返回问题清单(空 = 可以)。

    `训练是mock`:**三值** —— True / False / **None(说不清)**。
    """
    问 = []
    if not 产物:
        问.append("没有这个产物")
        return 问
    if not 产物.get("usable"):
        问.append("这个产物**没标可用** —— 先过 `可以标可用吗` 那几条。"
                  "「有产物」和「产物可用」是两个状态,合成一个之后,"
                  "一个没校验过的产物会显示成「可以用了」")

    # ⚠️ 铁律(规格 §17.4):**mock 的产物不许计入真实评测或发布。**
    if 训练是mock is True:
        问.append("这份产物来自 **mock 训练适配器**,不许发布 —— "
                  "它在数据形状上和真产物一模一样,**只能靠这个标记认**")
    elif 训练是mock is None:
        # **未知不是 False。** 这条是这个仓库反复兑现的那一条。
        问.append("**说不清这份产物是不是 mock 训练出来的**"
                  "(没有对应的训练任务,或者任务里没记适配器)—— "
                  "**未知不是「不是」**:放行的话,铁律靠的就只是运气了。"
                  "要么补上它的训练任务,要么让有权的人显式登记来源")

    if 环境 not in 部署环境:
        问.append(f"环境只收 {list(部署环境)},拿到 {环境!r} —— "
                  f"**不给默认值**:默认成 test 的话,一次忘了传"
                  f"就把生产部署记成了测试部署")
    return 问


部署环境 = ("test", "staging", "production")
