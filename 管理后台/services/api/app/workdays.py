# -*- coding: utf-8 -*-
"""工作日与首次处理截止时刻(意见受理台,2026-11-04)。

## 用户拍的口径(AskUserQuestion,11-04)

- 意见进来后 **1 个工作日**内要第一次处理(意见收集 PRD §6「普通意见建议 1 个工作日首次响应」)
- 工作日 = **跳过周末和法定假日**,调休上班的周末算工作日

## 算法:数满 24 个「工作日里的小时」

从提交那一刻起往后数,只数落在工作日里的时间,数满 24 小时那一刻就是截止。
  · 周五 15:00 提交 → 周五剩 9 小时 + 下一个工作日 15 小时 → 下周一 15:00
  · 周六 10:00 提交 → 周六周日不数 → 周一 00:00 起数 24 小时 → 周二 00:00
时区固定 Asia/Shanghai(门店在国内;服务器时区变了截止时刻不该跟着变)。

**截止时刻在提交那一刻算好存下**(opinions.first_response_due_at)—— 放假表以后补录、口径以后改,
只影响新进来的;老的那条当时按什么算的,记在 due_basis_code 里。

## 放假表:只认录进来的年份

2026 年那份照《国务院办公厅关于 2026 年部分节假日安排的通知》(新华社 2025-11-04 播发)逐日抄。
**表里没有的年份,退回「只跳周末」,并且如实标出来**(due_basis_code = 只跳周末·放假表没覆盖)——
不假装算准了。每年 11 月国务院公布下一年的安排后,要有人把那一年补进 放假 / 调休上班 两张表。
"""
import datetime as _dt
from zoneinfo import ZoneInfo

时区 = ZoneInfo("Asia/Shanghai")

# 《国务院办公厅关于 2026 年部分节假日安排的通知》—— 放假日(含被调成假日的周末)
放假 = {
    2026: {
        # 元旦 1/1(四)–1/3(六)
        "2026-01-01", "2026-01-02", "2026-01-03",
        # 春节 2/15(日)–2/23(一)
        "2026-02-15", "2026-02-16", "2026-02-17", "2026-02-18", "2026-02-19",
        "2026-02-20", "2026-02-21", "2026-02-22", "2026-02-23",
        # 清明 4/4(六)–4/6(一)
        "2026-04-04", "2026-04-05", "2026-04-06",
        # 劳动节 5/1(五)–5/5(二)
        "2026-05-01", "2026-05-02", "2026-05-03", "2026-05-04", "2026-05-05",
        # 端午 6/19(五)–6/21(日)
        "2026-06-19", "2026-06-20", "2026-06-21",
        # 中秋 9/25(五)–9/27(日)
        "2026-09-25", "2026-09-26", "2026-09-27",
        # 国庆 10/1(四)–10/7(三)
        "2026-10-01", "2026-10-02", "2026-10-03", "2026-10-04", "2026-10-05", "2026-10-06", "2026-10-07",
    },
}
# 同一份通知里的调休上班日(周末但要上班)
调休上班 = {
    2026: {"2026-01-04", "2026-02-14", "2026-02-28", "2026-05-09", "2026-09-20", "2026-10-10"},
}
首次处理工作小时 = 24


def 覆盖了吗(日):
    return 日.year in 放假


def 是工作日(日):
    """日:date。调休上班 → 是;放假 → 否;其余看是不是周一到周五。没覆盖的年份只看周末。"""
    s = 日.isoformat()
    if s in 调休上班.get(日.year, ()):
        return True
    if s in 放假.get(日.year, ()):
        return False
    return 日.weekday() < 5


def 首次处理截止(提交时刻, 小时=首次处理工作小时):
    """→ (截止时刻 带时区, 依据 code)。依据 = 「2026放假表」或「只跳周末·放假表没覆盖」。"""
    if 提交时刻.tzinfo is None:
        raise ValueError("提交时刻要带时区 —— 不带时区的时刻,换一台服务器算出来的截止就不一样")
    当前 = 提交时刻.astimezone(时区)
    剩 = _dt.timedelta(hours=小时)
    没覆盖 = False
    for _ in range(400):            # 一年都数不满 24 个工作小时,那是表录错了 —— 宁可抛,不死循环
        没覆盖 = 没覆盖 or not 覆盖了吗(当前.date())
        次日零点 = _dt.datetime.combine(当前.date() + _dt.timedelta(days=1), _dt.time(0), 时区)
        if 是工作日(当前.date()):
            可数 = 次日零点 - 当前
            if 可数 >= 剩:
                截止 = 当前 + 剩
                return 截止, ("只跳周末·放假表没覆盖" if 没覆盖 else f"{提交时刻.astimezone(时区).year}放假表")
            剩 -= 可数
        当前 = 次日零点
    raise ValueError("往后数了 400 天都没数满 —— 放假表录错了")
