#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""照着证据生成答案(§9.5 那条链的最后一步)—— **业务 2026-10-08 拍的 A**。

检索实验室原来停在「选了哪几片」。那一页回答得了「它怎么找、找到什么」,
**回答不了「它答成什么」** —— 而答案才是顾问真正拿到手的东西。

## 为什么这一步值得单独做(不是「顺手把答案也显示出来」)

RAG 最常见的失效**不在检索上**:片段选对了,而模型答的时候**自己补了内容**。
而只看检索结果看不出来 —— 那几片证据是对的,链路看起来完全正常。

> 一次「照着证据答」和一次「拿证据当装饰、内容是自己编的」,
> **在那几片选中的证据上长得一模一样。**

所以这一步的产物不只是一段话,是**一段话 + 它指得出的出处**。

## ⚠️ 这一版验到的,和验不到的 —— 写在这儿,不等人发现

**验得到(代码真去查):**
  ① 答案不是空的 ——「生成了空答案」不当结果
  ② 引用的证据编号**必须在给出的那几片里** —— 编一个不存在的编号当场抓到
  ③ 每条引用要**从那片里原样抄一句**,代码去验那句话真的在那片里
     (复用 `reranker._剥格式` 的子串比对,**不另写一套口径** ——
      两份口径迟早分叉,而分叉时两边各自都是绿的)

**验不到(而且这一版不假装验):**
  · **答案里有没有超出证据的内容。** 要判它得做句子级蕴含(NLI),
    而那是另一个模型调用 + 另一套判据。
    > 一个「每句话都指得出出处」的答案,和一个
    > 「有出处的那几句之外还加了两句自己的」的,
    > **在上面这三条判据上长得一模一样。**
    所以界面上那句话写的是「**它指得出出处**」,不是「它没有超出证据」——
    **判据没覆盖的事,文案不许替它担保。**

## ⚠️ 「证据不够」必须能被说出来

`enough=False` 时**不要求**它给引用 —— 和 `reranker` 的「0 分免引文」是同一条:
要求一个「证据里没有」的回答给出引文,等于**逼模型为一个不存在的关联编证据**。
**判据不该逼被测对象造假。**

反过来:`enough=True` 却一条引用都给不出 → **失败**。
说得出「够」就该指得出是哪一句。

## 失败怎么办:**抛,降级由调用方决定**

和 `rewriter` 同一个分工(见它的文件头):这里只负责「跑成了 / 没跑成」,
而「没跑成要不要让整条检索挂掉」是调用方的判断 ——
检索实验室的答案是**附加**的一步,检索链本身仍然有价值,所以 `retrieval`
把失败写进链路、不抛;而换个调用方(比如 chat)可能要当硬失败处理。

## 凭据与计费

走 `reranker._凭据()`(CLI 登录态,月租)。默认 `claude-haiku-4-5` ——
而**用的是哪个模型跟着结果返回**,不写死在文档里。
⚠️ 用 curl,不用 urllib(这台机器有 TLS 拦截)。
"""
import json
import os
import subprocess
import sys
import time

_这 = os.path.dirname(os.path.abspath(__file__))
if _这 not in sys.path:
    sys.path.insert(0, _这)

import llmtrace as trace          # noqa: E402  (名字见 reranker 文件头那段)
import reranker as RR             # noqa: E402  凭据 + `_剥格式` 复用,不另起一套

生成器版本 = "answer-1"
默认模型 = "claude-haiku-4-5"
# 答案最多多长。**不是随便定的**:顾问要的是一段能直接用的话,
# 而长答案会把「超出证据」藏得更深(越长越难逐句核)。
_最多token = 1200
# 一片证据最多给模型看多少字 —— 和 `reranker` 的 600 不同:
# 精排只要判「相不相关」,生成要**照着答**,截短了会让它缺着内容编。
_每片最多字 = 1200


class 生成失败(Exception):
    """模型返回的东西不符合契约(空答案 / 编了证据编号 / 引用是编的)。

    **不降级成「把证据原样贴出来」** —— 那会让
    「生成坏了」和「证据本身就是答案」长得一模一样。
    """


_提示 = """你在给一个汉服定制工坊的顾问回答问题。**只能用下面给出的证据作答。**

顾问的问题:
{问题}

证据片段(每条带编号,来自知识库):
{证据}

要求:

1. **只用证据里的内容作答。** 证据里没有的,不许补 ——
   你不知道的事,顾问也不会因为你编一句就知道。
2. 答案要是**顾问能直接用的一段话**(不要分点罗列全部证据,不要复述问题)。
3. 对每一条你**真的用到**的证据,从那条里**原样抄一个短语**(5-25 字),
   放进 `cited`。⚠️ **这是复制粘贴,不是转述** ——
   一个标点都不许改、不许跳字、不许自己补完括号。
   (`**` 之类的标记连着抄下来就行,我这边会处理。)
4. **证据不够回答这个问题的时候,`enough` 填 false**,
   在 `answer` 里**明说证据里没有**,并在 `missing` 里写缺什么。
   ⚠️ 这不是失败 ——「证据里没有」是一个正确答案,
   而编一个听起来合理的答案是错的。
5. 不许在答案里写「根据证据 [1]」这种编号 —— 出处由 `cited` 承担,
   顾问看到的是那段话本身。"""

# ⚠️ 工具名和 schema 的属性名**必须 ASCII**(见 reranker 文件头那段:
# 工具名 `^[a-zA-Z0-9_-]{1,128}$`、属性名 `^[a-zA-Z0-9_.-]{1,64}$`)。
_工具 = {
    "name": "answer_from_evidence",
    "description": "照着给出的证据回答顾问的问题,并指出每条用到的证据里的原话。",
    "input_schema": {
        "type": "object",
        "properties": {
            "answer": {"type": "string",
                       "description": "给顾问的那段话。证据不够时在这里明说"},
            "enough": {"type": "boolean",
                       "description": "证据够不够回答这个问题。"
                                      "不够就填 false —— 那不是失败"},
            "cited": {
                "type": "array",
                "description": "真的用到的那几条证据。不够作答时可以是空的",
                "items": {
                    "type": "object",
                    "properties": {
                        "index": {"type": "integer",
                                  "description": "证据编号,必须是给出的那些之一"},
                        "quote": {"type": "string",
                                  "description": "从那条证据里**原样抄**的短语"
                                                 "(5-25 字),不许改写"},
                    },
                    "required": ["index", "quote"],
                },
            },
            "missing": {"type": "string",
                        "description": "证据不够时,缺的是什么"},
        },
        "required": ["answer", "enough", "cited"],
    },
}


def 校验答案(出的, 编号到证据):
    """校验模型返回的答案。**纯函数** —— 不发请求,所以判据能零依赖测。

    返回 `{答案, 够不够答, 缺什么, 引用们, 引用没通过校验的}`;
    不合契约就抛 `生成失败`。

    ## 为什么提成纯函数(和 `reranker.校验打分` 同一条理由)

    CI 里**没有 Claude 凭据**。判据要是只能在有人手工跑的时候验,
    > **一条只在手工跑时被验过的防护,和没有防护的差别只在验的人脑子里。**
    """
    if not isinstance(出的, dict):
        raise 生成失败(f"返回的不是对象,是 {type(出的).__name__}")
    答案 = (出的.get("answer") or "").strip()
    if not 答案:
        # ⚠️ **空答案不当结果。**「生成了空答案」和「证据里没有」是两件事,
        # 而后者要写在 answer 里说出来(见 `_提示` 第 4 条)。
        raise 生成失败("模型给了空答案 —— **不拿空串当答案**。"
                     "「证据里没有」要在答案里明说,那是一句话,不是空的")
    够 = 出的.get("enough")
    if not isinstance(够, bool):
        # ⚠️ **不默认成 True。** 默认成「够」会让「模型没表态」
        # 和「模型说够了」长得一模一样 —— 而前者是契约没守住。
        raise 生成失败(f"`enough` 不是布尔值,是 {出的.get('enough')!r} —— "
                     f"**不默认成「够」**:那会让「没表态」和「说够了」长得一样")
    引们 = 出的.get("cited")
    if 引们 is None:
        引们 = []
    if not isinstance(引们, list):
        raise 生成失败(f"`cited` 不是清单,是 {type(引们).__name__}")

    # ── ② 编号必须在给出的那几片里 ────────────────────────────────────
    # ⚠️ 这里是**子集**判据,不是集合相等(和 `reranker` 不同,而这是有意的):
    # 精排要给**每一条**打分,所以那边是相等;生成只用到其中几条是正常的,
    # 要求相等等于逼它假装每片都用上了。
    # 但**编出不存在的编号**仍然当场抓 —— 那是「编」,不是「只用了几条」。
    给了 = set(编号到证据)
    编的号 = sorted({x.get("index") for x in 引们
                   if isinstance(x, dict)} - 给了 - {None})
    if 编的号:
        raise 生成失败(
            f"引用了不存在的证据编号 {编的号}(给出的是 {sorted(给了)})—— "
            f"**一个指向不存在片段的出处比没有出处糟**:它看起来有出处")

    if 够 and not 引们:
        # 说「够」却指不出是哪一句 —— 那段答案的内容来源说不清。
        raise 生成失败(
            "说证据够(enough=true)却一条引用都没给 —— "
            "**说得出「够」就该指得出是哪一句**。"
            "(反过来 enough=false 时不要求引用:那不逼它为不存在的关联编证据)")

    出, 编的 = [], []
    for x in 引们:
        if not isinstance(x, dict):
            raise 生成失败(f"`cited` 里有一项不是对象:{x!r}")
        i = x["index"]
        c = 编号到证据[i]
        引 = (x.get("quote") or "").strip()
        一条 = dict(编号=i, id=c.get("id"), 证据=c.get("证据"), 原话=引,
                  原话可信=True, 原话问题=None)
        if not 引:
            一条.update(原话可信=False,
                      原话问题="引用了这条证据但没给原话 —— "
                             "出处的用处是让人照着它翻回原文核对")
            编的.append(i)
        elif RR._剥格式(引) not in RR._剥格式(c.get("文") or ""):
            # ⚠️ **复用 `reranker._剥格式`,不另写一套。**
            # 它剥掉 Markdown 标记再比子串:抄原话(哪怕清理了格式)能过,
            # 重写一句话过不了 —— 重写会动到字,剥格式不动字。
            # 两份口径迟早分叉,而分叉的时候**两边各自都是绿的**。
            一条.update(原话可信=False,
                      原话问题=f"这句话在证据 [{i}] 里找不到:{引[:24]!r}"
                             f" —— 模型改写了原话")
            编的.append(i)
        出.append(一条)

    # ── ③ 原话对不上:**少数是噪声,大面积是故障**(和 reranker 同一个形状)──
    # 不同的是阈值的分母:这里是**它自己引了几条**,不是候选总数 ——
    # 引了 2 条全对不上,是「出处全是编的」,不该因为候选有 12 条就算 2/12 放行。
    if 编的:
        阈值 = max(1, len(引们) // 3)
        if len(编的) > 阈值:
            raise 生成失败(
                f"{len(编的)}/{len(引们)} 条引用的原话在证据里找不到"
                f"(超过 1/3 的阈值 {阈值})—— **出处能被核对,才算出处**。"
                f"大面积对不上说明这段答案不是从证据来的")

    return dict(答案=答案, 够不够答=够,
                缺什么=((出的.get("missing") or "").strip() or None),
                引用们=出, 引用没通过校验的=len(编的))


def 生成(问题, 证据们, *, 模型=None):
    """照着证据生成答案。

    `证据们`:`[{"id":…, "证据":…, "文":…}]`,至少一条(顺序 = 给模型看的顺序)。
    返回 `{答案, 够不够答, 缺什么, 引用们, 引用没通过校验的, 用量, 模型,
           生成器版本, 是mock=False}`。

    失败抛 `生成失败` —— **降级由调用方决定**(见文件头)。
    """
    if not 证据们:
        raise 生成失败("一条证据都没有 —— 生成不该在没有证据的时候被调用,"
                     "「没检索到」和「照着证据答不出来」是两件事")
    模型 = 模型 or os.environ.get("ANSWER_MODEL") or 默认模型
    编号到证据 = {i + 1: c for i, c in enumerate(证据们)}
    证据文 = "\n\n".join(
        f"[{i}] 【{c.get('证据') or ''}】\n{(c.get('文') or '')[:_每片最多字]}"
        for i, c in 编号到证据.items())
    体 = {
        "model": 模型, "max_tokens": _最多token,
        # ⚠️ `temperature` 不设 —— 和 `rewriter` 不同,**而这是有意的**:
        # 改写的产物是**下一步的输入**(召回靠它),所以要尽量稳定;
        # 答案是**给人读的终点**,同一份证据措辞略有不同不影响可核对性,
        # 而出处由 `cited` + 原话校验钉住。
        "tools": [_工具],
        "tool_choice": {"type": "tool", "name": "answer_from_evidence"},
        "messages": [{"role": "user", "content": _提示.format(
            问题=问题, 证据=证据文)}],
    }
    参 = ["curl", "-sS", "-m", "90", "https://api.anthropic.com/v1/messages",
          "-H", "content-type: application/json"]
    for h in RR._凭据():
        参 += ["-H", h]
    参 += ["-d", json.dumps(体, ensure_ascii=False)]
    _t0 = time.time()
    r = subprocess.run(参, capture_output=True, text=True)
    耗时 = int((time.time() - _t0) * 1000)

    def _记(成功, 用量=None, 细节=None):
        # ⚠️ **每一条出口都要记**,包括失败的那些 ——
        # 只记成功的调用会让「失败花掉的时间」变成黑的。
        try:
            trace.record(用途="知识检索生成答案", 模型=模型, 成功=成功,
                         耗时毫秒=耗时, 用量=用量 or {}, 是mock=False,
                         细节={"生成器版本": 生成器版本,
                             "证据数": len(证据们), **(细节 or {})})
        except Exception:
            pass

    if r.returncode != 0:
        _记(False, 细节={"curl退出码": r.returncode})
        # ⚠️ 只报退出码和 stderr,**不回显请求体**(它带着 header)
        raise 生成失败(f"curl 失败(退出码 {r.returncode}):{r.stderr.strip()[:200]}")
    try:
        d = json.loads(r.stdout)
    except json.JSONDecodeError:
        _记(False, 细节={"为什么": "返回的不是 JSON"})
        raise 生成失败(f"返回的不是 JSON:{r.stdout[:200]}")
    if "error" in d or d.get("type") == "error":
        _记(False, 细节={"API报错": str(d.get("error"))[:120]})
        raise 生成失败(f"API 报错:{str(d.get('error'))[:200]}")
    if d.get("stop_reason") == "max_tokens":
        # ⚠️ **先看有没有被截断。** tool_use 的 JSON 截断之后解析出来缺项,
        # 而那会被下面的判据报成「模型没守契约」,**把人引向模型行为,
        # 而根因在 `_最多token` 上**(和 reranker 那条同一个坑)。
        _记(False, 用量=d.get("usage") or {}, 细节={"stop_reason": "max_tokens"})
        raise 生成失败(
            f"**输出被截断了**(stop_reason=max_tokens,给了 {_最多token} token,"
            f"{len(证据们)} 条证据)—— 这不是「模型没守契约」,是 `_最多token` 不够")
    块们 = [b for b in d.get("content", []) if b.get("type") == "tool_use"]
    if not 块们:
        # 模型没调工具 —— **不去解析它的自由文本当答案**。
        # 那会让「它没按契约来」变成「我猜它想说什么」,
        # 而猜出来的那段话**没有任何出处校验**。
        文 = " ".join(b.get("text", "") for b in d.get("content", []))
        _记(False, 用量=d.get("usage") or {}, 细节={"没有tool_use": True})
        raise 生成失败(
            f"模型没调 answer_from_evidence(stop_reason={d.get('stop_reason')})"
            f",说的是:{文[:150]} —— **不去解析自由文本当答案**:"
            f"那段话没经过出处校验")
    # ⚠️⚠️ **先记这次调用,再校验契约。** 顺序是有意的,而且和 `reranker` 不同。
    #
    # 校验失败时 token **已经花掉了** —— 把 `_记` 放在校验之后的话,
    # 一次「模型回了但不合契约」的调用在记录仪里**一条记录都没有**:
    # > 一次「没调过模型」和一次「调了、花了钱、而返回不合契约」,
    # > **在那份日志上长得一模一样** —— 而后者正是要查的那种。
    #
    # 所以这一条记的是「**这次调用**成功了」(它确实成功了,有 usage),
    # 契约没守住再补一条 `成功=False` 的 —— 而那一条**用量留空**,
    # 否则同一次调用的 token 在日志里被算两遍。
    _记(True, 用量=d.get("usage") or {},
        细节={"阶段": "调用成功,还没校验契约"})
    try:
        结 = 校验答案(块们[0].get("input") or {}, 编号到证据)
    except 生成失败 as e:
        _记(False, 用量=None, 细节={"阶段": "契约校验没过",
                                "为什么": str(e)[:200],
                                "⚠️用量": "留空 —— 上一条已经记过这次的 token"})
        raise
    _记(True, 用量=None,
        细节={"阶段": "契约校验过了", "够不够答": 结["够不够答"],
            "引了几条": len(结["引用们"]),
            "引用没通过校验的": 结["引用没通过校验的"],
            "⚠️用量": "留空 —— 上一条已经记过这次的 token"})
    return dict(**结, 用量=d.get("usage") or {},
                模型=d.get("model") or 模型,
                生成器版本=生成器版本, 是mock=False)


# ── 这几条改坏了,哪一节会红 ────────────────────────────────────────
# 判据在 `tests/orchestration/test_answerer.py`:
#   空答案被当结果放行              → ① 空答案不当结果
#   编出来的证据编号被放行          → ② 编号必须在给出的那几片里
