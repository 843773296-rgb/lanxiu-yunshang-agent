#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""上传校验 —— **纯逻辑,不碰库也不碰存储**(所以每条规则都能单测)。

规格 §17.1:「**服务端校验之后才算文件引用** —— 上传成功不等于内容可用。」
这个文件回答的就是「校验」到底查什么。

## ⚠️ 最重要的一条:校验不自己发明「像不像文本」的判断,它**真的调一次解析器**

自己发明一套判断的代价是**两套判断迟早不一致**,而不一致的两个方向都坏:
  · 校验比解析器松 → 放过了解析器吃不下的文件。
    于是它在库里是「已校验」,而建索引时炸 —— **错误指向解析器,根因在上传**
  · 校验比解析器严 → 拒掉了解析器本来能吃的文件,而用户没有任何办法绕过

所以「这份字节能不能用」这个问题,只有**真正的消费者**答得准。
校验就是把解析器提前跑一遍,把它的拒绝理由原样带出来。

代价写清:校验因此**要花解析的时间**(几十毫秒级,语料再大也是一次性的),
而且**解析器版本变了,同一份文件的校验结论可能变** —— 所以结论里记了解析器版本。

## 三层,从便宜到贵

    ① 名字层  —— `POST /uploads` 就能判(后缀不支持,不该让人先传完 5MB)
    ② 字节层  —— 空 / 超限 / **和声明的字节数不一致**(截断)
    ③ 内容层  —— UTF-8 严格解码 → 真的调解析器 → 解析出 0 块也算不过

## 为什么「声明字节数」是必填

客户端现成就有这个数(`File.size`)。要它的代价约等于零,
不要它的代价是**截断上传检不出来** —— 网络断在一半产出的文件**打得开**,
少的那半段正是检索要找的那段。而且这个失效是静默的。
"""
import hashlib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import parser as PS

# ── 上限 ────────────────────────────────────────────────────────────
# ⚠️ **写死是故意的**(棘轮):它是一个上限,放宽要有人显式改这一行。
# 5 MB:澜绣那批真语料里最大的一份是 206 KB,一份纯文本资料到 5 MB
# 已经是「该拆成几篇」的量级 —— 而一份 200 MB 的「资料」切出来的片段
# 会把索引构建从几秒拖到几分钟,而它不会报错,只是看起来很慢。
最大字节数 = 5 * 1024 * 1024
最小字节数 = 1

# ⚠️ **每次调用都问解析器,不在导入时抄一份。**
#
# 抄一份(`支持的后缀 = PS.支持的后缀`)看起来也是「不另立一份」,但它是**导入时的快照**:
# 解析器加一种格式之后,校验这边还拿着旧清单 —— 于是一份解析器吃得下的文件被校验拒掉,
# 而**两边都不报错**(各自都自洽)。
#
# 这一条是被咬合测试逼出来的:抄快照的版本,咬合只有在**同时改两边**时才会变绿 ——
# 而「咬合自己把两边都改了」等于替被测对象把作业补上了。
def 支持的后缀():
    return PS.支持的后缀

规则们 = ("后缀在白名单里", "不是空文件", "不超过上限",
        "实际字节数和声明一致", "能按 UTF-8 严格解码", "解析器吃得下",
        "解析出至少一个块")


def 内容哈希(字节):
    """**服务端算**,不信客户端报的 —— 客户端算的哈希证明不了服务端收到的是同一份。"""
    return "sha256:" + hashlib.sha256(字节).hexdigest()


# ── ① 名字层:要地址的时候就能判 ─────────────────────────────────────
def 名字过得去吗(文件名):
    """返回 (行不行, 理由)。**在 `POST /uploads` 就调** —— 别让人先传完再说不支持。"""
    名 = (文件名 or "").strip()
    if not 名:
        return False, "没给文件名 —— 界面上要显示它,而且后缀决定用哪个解析器"
    if not 名.lower().endswith(tuple(支持的后缀())):
        return False, (f"这一版只收 {'、'.join(支持的后缀())},给的是 {名!r} —— "
                       f"PDF / 扫描件要 OCR(规格附录 D.5),这一版没接")
    return True, ""


def 声明字节数过得去吗(声明):
    """`POST /uploads` 时判。**超限的在这里就拒掉**,不等他传完。"""
    if 声明 is None:
        return False, ("没声明字节数 —— **必填**:不声明就检不出截断上传,"
                       "而截断产出的文件打得开,少的那半段正是检索要找的")
    if not isinstance(声明, int) or isinstance(声明, bool):
        return False, f"字节数要整数,给的是 {type(声明).__name__}"
    if 声明 < 最小字节数:
        return False, f"声明 {声明} 字节 —— 空文档会被静默索引成 0 个片段"
    if 声明 > 最大字节数:
        return False, (f"声明 {声明} 字节,超过上限 {最大字节数} —— "
                       f"一份到这个量级的纯文本资料该拆成几篇")
    return True, ""


# ── ②③ 字节层 + 内容层:complete 的时候判 ────────────────────────────
def 校验(字节, *, 文件名, 声明字节数):
    """把 `规则们` 全跑一遍。返回 dict。

    **一次把所有不过的规则都报出来,不是第一条不过就返回** ——
    只报第一条的代价是:用户改完第一条再传一次,又被第二条拒。
    (唯一例外是**解码不过就没法解析**,那一步确实做不下去了。)
    """
    没过 = []
    细 = dict(文件名=文件名, 声明字节数=声明字节数, 实际字节数=None,
             解析器版本=PS.解析器版本, 块数=None, 解析警告=[])

    if not isinstance(字节, (bytes, bytearray)):
        raise TypeError(f"校验要 bytes,给的是 {type(字节).__name__}")
    实际 = len(字节)
    细["实际字节数"] = 实际

    行, 为什么 = 名字过得去吗(文件名)
    if not 行:
        没过.append(("后缀在白名单里", 为什么))

    if 实际 < 最小字节数:
        没过.append(("不是空文件", "收到 0 字节 —— 空文档会被静默索引成 0 个片段"))
    if 实际 > 最大字节数:
        没过.append(("不超过上限", f"收到 {实际} 字节,上限 {最大字节数}"))
    if 声明字节数 is not None and 实际 != 声明字节数:
        没过.append(("实际字节数和声明一致",
                    f"声明 {声明字节数} 字节,实际收到 {实际} —— "
                    f"**很可能是传到一半断了**。半个文件打得开,"
                    f"而少掉的那半段正是检索要找的那段"))

    原文 = None
    try:
        原文 = bytes(字节).decode("utf-8")
    except UnicodeDecodeError as e:
        没过.append(("能按 UTF-8 严格解码",
                    f"第 {e.start} 字节起解不开(UTF-8 严格模式)—— "
                    f"**不退回 GBK 猜一遍**:猜错的结果是一份乱码资料,"
                    f"它切得出片段、建得成索引,只是检索永远查不到"))

    if 原文 is not None:
        # ⚠️ 这里**真的调解析器** —— 见文件头那段:
        # 「这份字节能不能用」只有真正的消费者答得准。
        try:
            解析 = PS.解析(原文, 文件名=文件名)
            细["块数"] = len(解析["块们"])
            细["解析警告"] = list(解析.get("警告") or [])[:20]
            if not 解析["块们"]:
                没过.append(("解析出至少一个块",
                            "解析器没报错,但一个块都没切出来 —— "
                            "**没报错不等于有内容**"))
        except PS.解析不了 as e:
            没过.append(("解析器吃得下", str(e)[:400]))

    return dict(通过=not 没过,
                没过的规则=[r for r, _ in 没过],
                理由们=[{"规则": r, "为什么": w} for r, w in 没过],
                细节=细,
                内容哈希=内容哈希(字节))


# ── 放弃:让状态机里的 `已放弃` 真的到得了 ────────────────────────────
# ⚠️ **一档到不了的状态,比少一档更糟。**
# 「要了地址但没传」这一档是契约里写的,理由是它和「传了但没过」必须分得开
# (前者没花存储)。但如果没有任何代码能把记录推到 `已放弃`,
# 以后有人查「放弃了多少」,查出来永远是 0 —— 他会当成「没人放弃过」。
放弃门槛小时 = 24


def 该放弃吗(创建时间, 现在, *, 门槛小时=None):
    """一条 `待上传` 放到什么时候算放弃。**纯函数,不猜「现在」是几点。**

    为什么把「现在」当参数传进来:一个自己调 `now()` 的判断没法测
    「刚好卡在门槛上」那一档 —— 而边界正是这种规则唯一容易错的地方。

    门槛 24 小时:它要比「人从点开选文件到传完」长得多(那是分钟级),
    又要短到让界面上的「待上传」不会堆成一大片看不懂的东西。
    ⚠️ **只放弃 `待上传`** —— 已经传了字节的那些占着存储,
    它们该走校验,不该被算成「没花存储」的那一档。
    """
    门槛 = 放弃门槛小时 if 门槛小时 is None else 门槛小时
    if 创建时间 is None or 现在 is None:
        raise ValueError("要两个时间都给 —— 缺一个就没法判,而**猜一个等于乱判**")
    过了几小时 = (现在 - 创建时间).total_seconds() / 3600.0
    return 过了几小时 >= 门槛, 过了几小时
