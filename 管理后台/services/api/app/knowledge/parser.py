#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""文档解析 —— **每一段都要能指回原文的哪一节、哪一段**(规格 §19.4 DocumentParser)。

## 这个模块唯一的硬要求:source_location

规格给 `DocumentParser` 那一行的「必须保留的结果」是
`text / structure / source_location / warnings / parser_version`,并解释了为什么:

> **source_location 是证据链的一环**:片段要能指回原文第几页第几段,
> 否则「有出处」只是一句话。

所以这里**不返回裸文本**。每一块都带 `位置`,而且位置是**结构性的**
(标题路径 + 段序号),不是行号 —— 行号会在文档插一行之后全体失效,
而那时候所有历史证据链都指错了地方,**而且看不出来**。

## parser_version 为什么必须记

规格同一行:「**parser_version 要记** —— 升级解析器会改变切片结果,
而那会让旧索引和新索引不可比」。

一次解析器升级会静默地改变「同一份文档切出几块、每块含什么」。
两个索引构建如果用了不同的解析器版本,它们的检索结果**不可比**,
而报表上那两个数看起来是同一个口径的。

## 为什么先只做 Markdown

澜绣那批真语料(`业务决策/业务拍板-*.md`、根目录那些设计说明)全是 Markdown,
而 Markdown 的标题层级**天然就是 source_location** ——
「第几节第几段」不用猜。

PDF / 扫描件要 OCR(规格附录 D.5 明写「扫描件依赖 OCR」,而这一版没接),
所以**认不出的格式当场报错,不假装解析成功**:一个把 PDF 读成一堆乱码的解析器,
产出的片段在数据形状上和正常片段一模一样。
"""
import hashlib
import re

# ⚠️ **改这个版本号 = 宣告「切片结果会变」。** 它进 index_builds,
# 于是两个用了不同解析器版本的索引在报表上分得开。
解析器版本 = "md-1"

支持的后缀 = (".md", ".markdown", ".txt")


class 解析不了(Exception):
    """认不出的格式 —— **当场报,不假装解析成功**。"""


def _块哈希(文):
    return "sha256:" + hashlib.sha256(文.encode("utf-8")).hexdigest()


def 解析(原文, *, 文件名="", ):
    """Markdown → [块]。每块带 `位置`(标题路径 + 段序号)。

    返回 dict(块们, 结构, 警告, 解析器版本)。

    ## 切到「段」为止,不切到句

    段是作者自己划的边界 —— 一个自然段通常是一个完整意思。
    切到句会把「决定」和「它的代价」拆到两块里,而那两句**必须一起被检索到**
    (见澜绣那批拍板记录:「业务知情后仍然这么选」那段紧跟在决定后面)。
    """
    if 文件名 and not 文件名.lower().endswith(支持的后缀):
        raise 解析不了(
            f"这一版只解析 {支持的后缀},给的是 {文件名} —— "
            f"**认不出的格式当场报,不假装解析成功**:"
            f"一个把 PDF 读成乱码的解析器,产出的片段在数据形状上和正常片段一模一样。"
            f"PDF / 扫描件要 OCR(规格附录 D.5),这一版没接")
    if not isinstance(原文, str) or not 原文.strip():
        raise 解析不了("原文是空的 —— 空文档不该被静默索引成 0 个片段")

    块们, 警告 = [], []
    标题路径 = []            # [(级别, 标题文字)]
    段序 = 0
    在代码块 = False
    缓冲 = []

    # 只由分隔符/符号组成的段:`---`、`***`、`___`、`|---|---|` 这种。
    # ⚠️ **它们要被丢掉,但要计入「丢了几块」并报出来**,不能静默丢:
    # 「这份文档切出 13 块」和「切出 11 块 + 丢了 2 块分隔符」是两个不同的事实,
    # 而只报前者的话,某天解析器把正文也当分隔符丢掉了**没人看得出来**。
    _只是分隔符 = re.compile(r"^[\s\-\*_=|:·—…]+$")
    丢掉的 = []

    def 收(段落行们, 起行=None):
        nonlocal 段序
        文 = "\n".join(段落行们).strip()
        if not 文:
            return
        if _只是分隔符.match(文):
            丢掉的.append(文[:20])
            return
        段序 += 1
        节路径 = " / ".join(t for _, t in 标题路径)
        块们.append(dict(
            文=文,
            # **位置是结构性的,不是行号。** 插一行不会让历史证据链失效。
            位置=dict(节路径=节路径 or "(正文开头)",
                     节级别=[lv for lv, _ in 标题路径],
                     段序号=段序,
                     # ⚠️ **起始行号是「这一块在原文的哪儿」的唯一标识。**
                     # 它会随着文档编辑而漂,**所以不当对外的引用**
                     # (对外引用用「节路径 + 段序号」,那个稳)。
                     # 但**检查需要一个真唯一的锚**:
                     # 判「这一块属于哪一节」时拿文本去 `find()` 会找到别处 ——
                     # `|---|---|`、重复的小标题在一份文档里出现多次。
                     # 栽过:判据从「段序号」换到「内容」,两版都以为自己用的标识唯一。
                     起始行=起行),
            文哈希=_块哈希(文),
            字数=len(文),
        ))

    缓冲起行 = None
    for i, line in enumerate(原文.splitlines(), 1):
        t = line.rstrip()
        if t.startswith("```"):
            在代码块 = not 在代码块
            if 缓冲起行 is None:
                缓冲起行 = i
            缓冲.append(t)
            continue
        if 在代码块:
            if 缓冲起行 is None:
                缓冲起行 = i
            缓冲.append(t)
            continue
        m = re.match(r"^(#{1,6})\s+(.*)$", t)
        if m:
            收(缓冲, 缓冲起行); 缓冲 = []; 缓冲起行 = None
            级 = len(m.group(1))
            # 标题路径按级别回退 —— `## 二、` 出现时要把上一个 `## 一、` 顶掉
            while 标题路径 and 标题路径[-1][0] >= 级:
                标题路径.pop()
            标题路径.append((级, m.group(2).strip()))
            段序 = 0                 # 段序号在**节内**计,不是全文流水号
            continue
        if not t.strip():
            收(缓冲, 缓冲起行); 缓冲 = []; 缓冲起行 = None
            continue
        if 缓冲起行 is None:
            缓冲起行 = i
        缓冲.append(t)
    收(缓冲, 缓冲起行)

    if not 块们:
        raise 解析不了("解析出 0 个块 —— **这不叫「文档是空的」,这叫解析失败**;"
                     "空文档在上面就被拦住了")
    if 丢掉的:
        # **报出来,不静默。** 见 `_只是分隔符` 上面那段。
        警告.append(f"丢掉 {len(丢掉的)} 块只有分隔符的段:{丢掉的[:4]}")

    return dict(块们=块们,
                结构=[dict(级别=lv, 标题=t) for lv, t in _所有标题(原文)],
                警告=警告,
                丢掉的块数=len(丢掉的),
                解析器版本=解析器版本)


def _所有标题(原文):
    出, 在代码块 = [], False
    for line in 原文.splitlines():
        if line.startswith("```"):
            在代码块 = not 在代码块
            continue
        if 在代码块:
            continue
        m = re.match(r"^(#{1,6})\s+(.*)$", line.rstrip())
        if m:
            出.append((len(m.group(1)), m.group(2).strip()))
    return 出
