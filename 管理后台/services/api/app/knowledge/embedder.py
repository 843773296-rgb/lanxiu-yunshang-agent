#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Embedding 适配器。**首版只有 mock** —— 而 mock 向量比 mock 文本危险得多。

## 为什么这个文件开头就要讲危险

`prompt_run` 用的 mock 生成器吐出来的文本,**一眼看得出是假的**。
mock 向量不是:它算出来的相似度是个**看起来很正常的数字**(0.83),
而人会拿它当效果读 ——「检索准不准」这件事就这么被伪造了。

而实际上 mock 向量是从文本哈希派生的,所以:

    **语义相近的两段话,mock 向量完全不相关。**
    mock 下的检索排序本质上是随机的。

所以这件事必须跟着**数据**走(每个向量自带 `是mock`),不能只写在文档里 ——
文档不会跟着结果传到界面上,而数字会。

这和后台已有的做法同源:费用未知**不写 0**、质量分未知**不显示 0**
(`amount_known=false`)。未知和零是两件事,假的和真的也是。

## 为什么 mock 必须是确定性的

同一段文本每次算出同一个向量。否则:
  · 重跑一次构建,`text_hash` 没变而向量变了 —— 检查点就骗人了
  · 测试拿不到稳定结论,而不稳定的测试最后都会被人忽略
"""
import hashlib
import struct

适配器版本 = "emb-mock-1"
维度 = 1536          # ⚠️ 和 `embeddings.embedding` 列的 vector(1536) 必须一致


class 维度不符(Exception):
    """算出来的维度和声明的不一样。**当场抛** ——
    混维度的向量写进库会被 PostgreSQL 拦(实测 `expected 1536 dimensions, not 3`),
    但那时候错误信息里只有维度,没有「是哪一段文本、哪个模型」。"""


def _伪随机向量(种子串, n):
    """从一个串派生 n 个 [-1, 1) 的浮点。确定性,跨进程跨机器一致。

    做法:把种子串反复 sha256,每 4 字节取一个 32 位无符号整数,映射到 [-1,1)。
    **不用 `random.seed()`** —— Python 的 random 不保证跨版本稳定,
    而这个值会进数据库,库里的数据要比解释器活得久。
    """
    出 = []
    计 = 0
    while len(出) < n:
        块 = hashlib.sha256(f"{种子串}#{计}".encode("utf-8")).digest()
        for i in range(0, len(块), 4):
            if len(出) >= n:
                break
            (u,) = struct.unpack(">I", 块[i:i + 4])
            出.append(u / 2147483648.0 - 1.0)
        计 += 1
    return 出


def 归一化(v):
    """单位化。**除以 0 要抛,不许静默返回零向量。**

    一个全零向量和任何东西的余弦相似度都是 0/0 —— pgvector 会给出 NaN
    或者一个说不清的数,而**排序里的 NaN 不报错,只是排到某个位置**。
    """
    模 = sum(x * x for x in v) ** 0.5
    if 模 == 0:
        raise 维度不符("算出了零向量 —— 余弦相似度会变成 0/0,"
                     "而排序里的 NaN **不报错,只是排到某个位置**")
    return [x / 模 for x in v]


def 算(文本们, *, 模型id="emb-mock", 期望维度=维度):
    """给一批文本算向量。返回和入参**等长**的清单。

    每一项:{text_hash, 向量, 维度, 模型id, 是mock, 适配器版本}

    ⚠️ `是mock` 是**必填且必须往上传**:界面上要能看出
    「这个相似度不代表语义」。首版它恒为 True。
    """
    if 期望维度 != 维度:
        raise 维度不符(
            f"要 {期望维度} 维,而这个适配器只产 {维度} 维 —— "
            f"**不许截断也不许补零**:截断丢掉的是信息,补零造出的是假信息,"
            f"两种都会让检索算出一个看起来正常的错数字")
    出 = []
    for t in 文本们:
        if not isinstance(t, str) or not t.strip():
            raise ValueError("要 Embedding 的文本是空的 —— 空片段不该走到这一步,"
                             "它在切片阶段就该被丢掉并计数(chunker 的 `丢掉的块数`)")
        h = hashlib.sha256(t.encode("utf-8")).hexdigest()
        v = 归一化(_伪随机向量(f"{模型id}:{h}", 维度))
        if len(v) != 维度:
            raise 维度不符(f"算出 {len(v)} 维,要 {维度} 维")
        出.append(dict(text_hash=h, 向量=v, 维度=维度, 模型id=模型id,
                       是mock=True, 适配器版本=适配器版本))
    return 出


def 成SQL文本(向量):
    """pgvector 接受的字面量:`[0.1,0.2,…]`。

    ⚠️ 用 `repr` 而不是格式化到固定小数位。截到 6 位小数会让
    **两个不同的向量变成同一个字符串**(mock 向量的分量分布很密),
    于是唯一约束和检查点都会指向错误的东西。
    """
    return "[" + ",".join(repr(float(x)) for x in 向量) + "]"


def 余弦(a, b):
    """给测试和「没有向量索引时的顺序扫」用。

    ⚠️ **这不是检索用的那个算子。** 库里的检索走 pgvector 的 `<=>`,
    两者在浮点细节上不会完全一致 —— 所以拿这个函数算出来的排序
    去断言库里的排序,会在边界上偶发不一致。
    要断言排序,就在库里查一次,别在 Python 里重算一遍。
    """
    if len(a) != len(b):
        raise 维度不符(f"{len(a)} 维和 {len(b)} 维算不了余弦 —— "
                     f"**这正是维度写死在列类型上要防的事**")
    return sum(x * y for x, y in zip(a, b))
