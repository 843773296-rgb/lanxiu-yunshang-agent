#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""索引构建的**计划**(规格 §19.3)—— 纯逻辑,不碰数据库、不调 Embedding。

Worker 的 `@处理("index_build")` 只做 I/O:读表、调模型、写表。
**一条判断都不自己写** —— 判断全在这儿,所以判断可以零依赖测。

## 规格 §19.3 原话

> 分阶段保存检查点,**已完成片段不重复 Embedding**;
> **输入版本变化则创建新构建而不是复用错误结果**。

这两句各自对应一个陷阱,而两个陷阱的失败方向都是**安静的**:

### 陷阱一:拿「成员行存在」当「已经做完了」

`index_members` 有 `embedding_id`,而它**可空**。
一条 `embedding_id IS NULL` 的成员行意思是「登记了,向量还没写」。
如果续做时把它算成已完成 → **跳过一个没有向量的片段**。
后果:构建报成功,而那一段内容在检索里**永远不命中** ——
没有报错、没有告警,只是有一段知识凭空消失了。

所以 `已经做完的()` 要求 `embedding_id` 非空。**登记不是完成。**

### 陷阱二:输入变了却续做 → 混血索引

「输入」不只是文档和配置。**切片器版本也是输入。**
文档版本没变、检索配置没变,但 chunker 的合并规则改了 ——
旧片段和新片段**边界不一样**。续做的结果是一半旧边界一半新边界:
检索照样能跑、照样返回结果,只是答得怪,而且**没有任何一处会报错**。

所以指纹里必须有 `切片器版本` 和 `解析器版本`(它们是 §19.3 里
「输入版本」的一部分,而不是实现细节)。

## 为什么不用「计数器」做检查点

直觉做法是在 `index_builds` 上加一列「已完成片段数」。不用它,因为
**计数器和产物会漂**:写了 100 条成员但计数停在 80(或反过来),
而漂了不报错。`index_members` 里的行**就是**检查点 ——
它和真相不可能不一致,因为它就是真相。
"""
import hashlib
import json

索引计划器版本 = "plan-1"

# 指纹要覆盖的输入项。**改这张表就等于宣布所有旧构建作废** —— 那是对的,
# 因为多一项进指纹,意思正是「这一项变了不能续做」。
_指纹字段 = (
    "知识库id",
    "文档版本id们",       # 排序后进指纹 —— 集合,不是顺序
    "检索配置版本id",
    "embedding模型id",
    "embedding维度",
    "切片器版本",         # ⚠️ 少这一条就会产出混血索引(见文件头)
    "解析器版本",         # ⚠️ 同上:解析变了,块边界就变了
)


class 输入不全(Exception):
    """指纹算不出来。**不给默认值** —— 一个字段缺了就静默当空串,
    会让两批不同输入算出同一个指纹,于是「输入变了」这件事再也测不出来。"""


def 输入指纹(**kw):
    """把一次构建的全部输入算成一个串。

    缺字段直接抛。**不许 `kw.get(k, "")`** —— 那会把「没给」和「给了空」
    压成同一件事,而它们的后果完全不同:前者是调用点漏传(bug),
    后者是真的空(合法)。压平之后指纹撞了,混血索引就回来了。
    """
    缺 = [k for k in _指纹字段 if k not in kw]
    if 缺:
        raise 输入不全(
            f"算指纹缺了 {缺} —— 指纹少一项,那一项变了就不会被发现,"
            f"于是会**在变过的输入上续做**,产出一半旧一半新的索引(§19.3)")
    多 = sorted(set(kw) - set(_指纹字段))
    if 多:
        raise 输入不全(
            f"传了指纹字段之外的 {多} —— 要么它该进 `_指纹字段`(那就加进去,"
            f"并且知道这会让所有旧构建作废),要么它不是输入")

    料 = {}
    for k in _指纹字段:
        v = kw[k]
        if k == "文档版本id们":
            ids = list(v)
            if len(ids) != len(set(ids)):
                raise 输入不全(
                    f"`文档版本id们` 里有重复 —— 它是**集合**。"
                    f"重复会让同一份文档被切两遍、在索引里出现两次,"
                    f"检索时同一段话占掉两个名额")
            v = sorted(ids)     # 集合语义:顺序不该改变指纹
        料[k] = v
    串 = json.dumps(料, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return f"{索引计划器版本}:{hashlib.sha256(串.encode('utf-8')).hexdigest()[:32]}"


def 已经做完的(成员们, *, 期望维度):
    """从 `index_members` 的行里挑出**真的做完了**的 chunk_id。

    三档,不是两档 —— 「没做」和「做坏了」必须分开,因为处置不同:
      · 做完:跳过
      · 只登记没向量(`embedding_id` 空):**要重做**(它现在检索不到)
      · 维度不对:**要重做**,而且这是配置出过事的信号

    返回 (做完的集合, 要重做的 [(chunk_id, 为什么)])
    """
    好, 坏 = set(), []
    for m in 成员们:
        cid = m.get("chunk_id")
        if not cid:
            坏.append((None, "这条成员没有 chunk_id —— 它指向不了任何片段"))
            continue
        if not m.get("embedding_id"):
            # ⚠️ **这一条是本文件存在的主要理由。** 见文件头「陷阱一」。
            坏.append((cid, "登记了但 `embedding_id` 是空的 —— **登记不是完成**,"
                            "这一段现在检索不到"))
            continue
        d = m.get("embedding维度")
        if d is not None and d != 期望维度:
            坏.append((cid, f"向量是 {d} 维,这次构建声明 {期望维度} 维 —— "
                            f"混维度的索引距离算出来没有意义"))
            continue
        好.add(cid)
    return 好, 坏


def 算待做(*, 目标片段们, 成员们, 期望维度):
    """要 Embedding 哪些片段。

    `目标片段们`:[{"id":…, "text_hash":…}] —— 这一版输入切出来的全部片段
    `成员们`    :`index_members` 里属于这个构建的行

    还报一件 §19.3 没点但必须有的事:**成员里有、目标里没有的**片段。
    那意味着上一轮的输入和这一轮不同 —— 如果指纹拦住了就不该出现,
    出现了说明指纹漏了一项。所以它是**指纹自己的体检**。
    """
    目标id = [c["id"] for c in 目标片段们]
    if len(目标id) != len(set(目标id)):
        重 = sorted({i for i in 目标id if 目标id.count(i) > 1})
        raise ValueError(f"目标片段里有重复 id {重} —— 同一段会被 Embedding 两遍,"
                         f"并在检索里占掉两个名额")
    目标集 = set(目标id)
    做完, 要重做 = 已经做完的(成员们, 期望维度=期望维度)

    重做集 = {c for c, _ in 要重做 if c}
    # 一条片段既在「做完」又在「要重做」时,**按要重做算**(偏安全那一侧):
    # 同一个 chunk 有两条成员行,一条有向量一条没有 —— 那本身就不正常,
    # 而重做一次的代价只是多花一次 Embedding。
    待做 = [c for c in 目标片段们 if c["id"] not in (做完 - 重做集)]

    陈旧 = sorted((做完 | 重做集) - 目标集)
    return dict(
        待做=待做,
        已完成=sorted(做完 - 重做集),
        要重做=要重做,
        陈旧成员=陈旧,
        指纹体检=("通过" if not 陈旧 else
                 f"**指纹漏了一项** —— 索引里有 {len(陈旧)} 个片段不在这一版输入里"
                 f"({陈旧[:3]}…)。同一个构建的输入本该固定,能变说明指纹没覆盖到"
                 f"某个真实输入,而那正是混血索引的入口(§19.3)"),
        计划器版本=索引计划器版本,
    )


def 该新建还是续做(*, 构建, 现在的指纹):
    """返回 ("续做"|"新建", 一句话为什么)。

    §19.3:「**输入版本变化则创建新构建,而不是复用错误结果**」。
    「复用错误结果」在这儿的具体形状:续做一个输入已经变了的构建,
    得到一半旧边界一半新边界的索引 —— 它**不报错**,只是答得怪。

    终态的构建也不许续做:它已经被别人当成结论用过了。
    """
    旧 = (构建 or {}).get("输入指纹")
    st = (构建 or {}).get("status")
    if 构建 is None:
        return "新建", "还没有构建"
    if not 旧:
        # 老构建没记指纹 —— **不能当成「指纹一样」**。
        # 这是「没记」不是「一致」,把它放过去正好放过了要防的那件事。
        return "新建", ("这个构建没有记 `输入指纹` —— **「没记」不是「一样」**。"
                       "放它续做,就等于在不知道输入有没有变的情况下续做")
    if 旧 != 现在的指纹:
        return "新建", (f"输入变了(指纹 {旧[:16]}… → {现在的指纹[:16]}…)—— "
                       f"续做会得到一半旧一半新的索引,**而它不会报错**(§19.3)")
    if st in ("succeeded", "failed", "cancelled"):
        return "新建", (f"这个构建已经是终态({st})—— 终态的结果可能已经被谁"
                       f"当结论用过了,往里补片段会**改掉一个已经交付的东西**")
    return "续做", f"输入没变(指纹 {现在的指纹[:16]}…),状态 {st} —— 已完成的片段跳过"


def 校验检索配置(cfg):
    """检索配置版本的校验。返回问题清单(空 = 通过)。

    最要紧的一条:**最终片段数不能超过候选数**。
    配置成 `candidate_k=20, final_chunk_limit=50` 时界面上看着没毛病,
    实际是「从 20 个里挑 50 个」—— 永远挑不满。
    那不会报错,只会让人以为「知识库里就这么点东西」。
    """
    问 = []
    ck = cfg.get("candidate_k")
    fl = cfg.get("final_chunk_limit")

    def 正整数(名, v):
        if v is None:
            问.append(f"`{名}` 没填 —— 检索的取数范围必须写明,默认值会变成隐形策略")
            return False
        if isinstance(v, bool) or not isinstance(v, int):
            # bool 是 int 的子类,`isinstance(True, int)` 为真 —— 要单独排掉
            问.append(f"`{名}` 不是整数:{v!r}")
            return False
        if v <= 0:
            问.append(f"`{名}` 是 {v} —— 取 0 条或负数条没有意义,检索会永远返回空,"
                     f"而界面上看起来只是「没搜到」")
            return False
        return True

    好ck = 正整数("candidate_k", ck)
    好fl = 正整数("final_chunk_limit", fl)
    if 好ck and 好fl and fl > ck:
        问.append(
            f"`final_chunk_limit`({fl})比 `candidate_k`({ck})大 —— "
            f"**从 {ck} 个候选里挑 {fl} 个,永远挑不满**。这不会报错,"
            f"只会让人以为知识库里就这么点东西")

    模式 = cfg.get("recall_modes")
    if not 模式:
        问.append("`recall_modes` 是空的 —— 一个召回方式都没开,检索必然返回空")
    elif not isinstance(模式, (list, tuple)):
        问.append(f"`recall_modes` 该是个清单,现在是 {type(模式).__name__}")
    else:
        不认 = sorted(set(模式) - {"vector", "keyword", "hybrid"})
        if 不认:
            问.append(f"不认识的召回方式 {不认} —— 现有 vector / keyword / hybrid")
        if "hybrid" in 模式 and not cfg.get("fusion"):
            问.append("开了 `hybrid` 但没配 `fusion` —— **两路召回怎么合并没说**,"
                     "那会退化成某一路说了算,而是哪一路取决于实现细节")

    预算 = cfg.get("context_budget_tokens")
    if 预算 is not None and not isinstance(预算, bool) and isinstance(预算, int):
        if 预算 <= 0:
            问.append(f"`context_budget_tokens` 是 {预算} —— 上下文预算是 0,一段都放不进")
        elif 好fl and 预算 < fl * 20:
            # 20 token 一段是极度保守的下限(真实片段 60–600 字)。
            # 这条不是精算,是抓「预算和片段数明显对不上」。
            问.append(f"`context_budget_tokens`({预算})装不下 {fl} 个片段 —— "
                     f"到时候会**静默截断**,而被截掉的那几段和没检索到长得一样")
    return 问
