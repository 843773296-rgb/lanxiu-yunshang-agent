#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""切片 —— **解析出来的段 → 可检索的片段**,而证据链一路带着。

## 切片和解析为什么是两步

解析回答「原文有哪些段、每段在第几节第几段」;切片回答「**拿去检索的单位是什么**」。
两件事的判据不同,而且切片策略会换(按段 / 合并相邻小段 / 按 token 上限窗口),
**而解析结果不该跟着换** —— 否则换一次切片策略,所有 source_location 都得重算。

## 三条硬规矩

① **片段绑的是文档版本,不是文档**(契约登记表 `chunks` 那一行的原话)。
   绑文档的话,文档一改,历史证据链就指向了新内容 —— 而它看起来还是同一个引用。

② **合并只在同一节内做。** 跨节合并会造出一个「横跨两个决定」的片段,
   而它的 `节路径` 只能记其中一个 —— 于是引用指到的地方**只有一半是对的**,
   而那比完全指错更难发现。

③ **每个片段都有 ordinal(节内序号)**,而且它**跟着合并后的结果编**,
   不是原始段序号。理由:ordinal 是「这份文档的第几个片段」,
   它要能和 `index_members` 对上;而原始段序号在 `位置` 里另存着。
"""
import hashlib

# ⚠️ 换这个值 = 切片结果会变。它和 `解析器版本` 一起进 index_builds ——
# 两个索引只要有一个不同,它们的检索结果**不可比**。
切片器版本 = "seg-1"

# 合并阈值:短于这个字数的段尝试和**同一节内**的下一段合并。
# 为什么要合并:澜绣那批拍板记录里有大量「**决定**:xxx」这种一行段,
# 单独成片检索出来没有上下文(拿到「≤3 星算差评」而不知道它在说评价)。
# 为什么不设得太大:合并过头会把「决定」和另一个「决定」并进一块,
# 于是检索命中一个却把两个都塞进上下文。
最短字数 = 60
最长字数 = 600


def _哈希(文):
    return "sha256:" + hashlib.sha256(文.encode("utf-8")).hexdigest()


def 切(解析结果, *, 文档版本id):
    """→ [片段]。每个片段带 `section_path` / `ordinal` / `text_hash` / 来源位置。

    `文档版本id` 必填 —— 见模块开头第 ① 条。**没有它就不许切**:
    一个不知道自己属于哪一版的片段,是一条断掉的证据链。
    """
    if not 文档版本id:
        raise ValueError(
            "切片必须绑 `文档版本id` —— **片段绑的是文档版本,不是文档**"
            "(契约 `chunks` 那一行)。绑文档的话,文档一改历史证据链就指向新内容,"
            "而它看起来还是同一个引用")
    块们 = 解析结果["块们"]
    出 = []
    i = 0
    while i < len(块们):
        b = 块们[i]
        文 = b["文"]
        合了 = [b]
        # **只在同一节内合并**(模块开头第 ② 条)
        while (len(文) < 最短字数 and i + 1 < len(块们)
               and 块们[i + 1]["位置"]["节路径"] == b["位置"]["节路径"]
               and len(文) + len(块们[i + 1]["文"]) <= 最长字数):
            i += 1
            合了.append(块们[i])
            文 = 文 + "\n" + 块们[i]["文"]
        出.append(dict(
            text=文,
            text_hash=_哈希(文),
            # 证据链:这一段在原文的哪一节、哪几段
            section_path=b["位置"]["节路径"],
            # ⚠️ **要按级别做事的读这个,不要去 split `section_path`** ——
            # 29 个标题名字里带 ` / `,拆出来会多一级。见 parser.py 里那段。
            节标题们=b["位置"].get("节标题们") or [],
            段序号们=[x["位置"]["段序号"] for x in 合了],
            # ⚠️ **只给检查用的锚,不对外当引用。** 见 parser.py 里那段注释:
            # 行号会漂,所以对外引用用「节路径 + 段序号」;
            # 而判据需要一个**真唯一**的锚(文本和段序号都不唯一)。
            _原文起始行们=[x["位置"]["起始行"] for x in 合了],
            合并了几段=len(合了),
            token_count=_粗估token(文),
            文档版本id=文档版本id,
        ))
        i += 1
    # ordinal 跟着**合并后**的结果编(模块开头第 ③ 条)
    for n, c in enumerate(出, 1):
        c["ordinal"] = n
    return dict(片段们=出, 切片器版本=切片器版本,
                解析器版本=解析结果["解析器版本"])


def _粗估token(文):
    """粗估 —— **中文按字算、ASCII 按 4 字符算**。

    ⚠️ 它叫「粗估」是有意的:真实 token 数要问 tokenizer,而不同模型的
    tokenizer 不一样。这个数只用来**挡住明显超预算的片段**,
    **不许拿它去算钱** —— 规格开头那条「未知不用 0 代替」的反面同样成立:
    **一个估出来的数不许被当成实测数**。
    """
    中 = sum(1 for ch in 文 if ord(ch) > 0x2E80)
    其余 = len(文) - 中
    return 中 + max(1, 其余 // 4)


def 证据(片段):
    """给检索结果用的引用串 —— **人能照着它翻回原文**。"""
    段 = 片段["段序号们"]
    段说 = f"第 {段[0]} 段" if len(段) == 1 else f"第 {段[0]}–{段[-1]} 段"
    return f"{片段['section_path']} · {段说}"
