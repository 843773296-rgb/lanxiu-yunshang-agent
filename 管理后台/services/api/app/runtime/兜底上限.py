class 没有兜底(Exception):
    pass


def 兜底(*, 入口, 现在=None):
    """这个入口的兜底策略。返回一个**形状和「已采用的那一版」一致**的 dict。

    形状一致是故意的:运行记录里「上限来源」那一栏之外,
    其余字段读起来和真策略一样 —— 于是下游不用分两条路写。
    **而 `来源` 那一栏必须不一样**,否则就回到了「长得一模一样」。

    `现在` 只用来盖一个时间戳(给记录用),不参与判定 ——
    兜底**不会过期**,这是它和回退最大的区别。
    """
    if 入口 not in _冻.入口们:
        raise 没有兜底(
            f"入口 `{入口}` 认不出 —— 只认 {_冻.入口们}。"
            f"规格 §2.2 不给「通用」留口子,所以这儿也不给一个「通用兜底」")
    limits = dict(_兜底limits[入口])
    if not limits:
        # ⚠️ 一个空的兜底**等于没有兜底**,而它会悄悄变成「无限制」——
        # 那正是业务拍这件事要消掉的那个档。
        raise 没有兜底(
            f"入口 `{入口}` 的兜底是空的 —— **空兜底就是无限制**,"
            f"而那个档已经被业务拍掉了(2026-10-06)")
    草 = {
        "entry_kind": 入口,
        "scope": "task",
        "limits": limits,
        "counter_schema_version": _冻.旧口径,
        # ⚠️ **兜底不要求实例支持任何东西。** 要求了就会去核能力,
        # 而核不过是「拒绝启动」—— 兜底的全部意义是让它跑得起来。
        "support_conditions": [],
    }
    return {
        "来源": 内置兜底,
        "版本": None,            # ⚠️ 它没有版本号 —— **None 是「没有」,不是 0**
        "limits": limits,
        "内容哈希": _冻.算内容哈希(草),
        "entry_kind": 入口,
        "counter_schema_version": _冻.旧口径,
        # ⚠️ **这一栏要能被外面看见**,不能只活在上面那个 `草` 里。
        # 2026-10-06 写测试时抓到:我想钉「兜底不要求实例支持任何东西」,
        # 而外面观察不到它,于是写成了 `ck(..., True)` —— **一条永远真的断言**。
        # > 一条改坏之后仍然成立的断言,和一条真能抓住那次破坏的,
        # > **在那份测试的通过数上长得一模一样。**
        "support_conditions": list(草["support_conditions"]),
        "这些数字是什么": 这些数字是什么,
        "故意不给数字的": dict(故意不给[入口]),
        "⚠️": ("**这不是业务配的** —— 是代码常量。"
              "页面上要和「已发布策略」区分显示,"
              "否则一次兜底和一次正常采用在界面上长得一模一样"),
        "盖章于": 现在,
    }


