"""澜绣桥的写入闸 —— **写跟进之前,这次运行里必须有一步被人批准过**(2026-10-24)。

用户拍「核对即定稿,直接写跟进」:人工核对那一步就是草稿阶段,没过核对的东西不许写进澜绣。
判据落在**执行这一侧**,不靠模板「碰巧」把核对排在写跟进前面 —— 一张把写跟进直接接在模型后面的图,
校验器看着完全合法(端到端 ⑦ 验的就是这张图)。

零 IO:Worker 在挂起、要给澜绣记一张写跟进单之前调它;夹具测试直接调它。
"""

import 桥工具 as _桥

# 名单只在 runtime/桥工具.py 一处(2026-10-24 扩到六条流程要的能力)。原来这里写的是
# `要批准的桥工具 = ("写跟进",)` —— 新加一个写动作忘了登进来,它就**不经核对直接写进澜绣**
要批准的桥工具 = _桥.要批准


def 批准记录(节点输出, 节点类型):
    """这次运行里被人批准过的那几步。

    **只认人工节点的输出**(`节点类型[id] == "human"`)—— 模型节点的输出是模型写的,
    它完全可以在自己的 JSON 里写一个 `决定: approve, 处理人: U006`。
    只看字段长得像不像批准,等于让模型自己批自己。
    """
    return [v for i, v in (节点输出 or {}).items()
            if (节点类型 or {}).get(i) == "human"
            and isinstance(v, dict) and v.get("决定") == "approve" and v.get("处理人")]


def 放行吗(工具, 节点输出, 节点类型):
    """(能不能记这张单, 不能的理由)。只读的桥工具不需要批准。

    `节点类型` = {node_id: type},从**这次运行挂起时存下的那一版定义**取。"""
    种 = _桥.种类(工具)
    if 种 is None:
        return False, f"「{工具}」不在澜绣桥的名单里(runtime/桥工具.py)—— 不记单"
    if 种 == "只读":
        return True, None
    if 批准记录(节点输出, 节点类型):
        return True, None
    return False, f"「{工具}」之前这次运行里没有任何一步被人批准过 —— 没过核对的东西不写进澜绣"
