"""**这次运行真正生效的上限是哪几个数,以及每个数从哪来** —— 纯逻辑,零 IO。

两个地方都在说同一件事,而它们可以不一样:

    执行策略      组织级护栏(已发布的那一版 / 本地回退 / 内置兜底)
    Agent 配置    这一个 Agent 自己填的 `limits`

`agent_loop.py` 现在**只读后者**(`:120` 和 `:229`),于是策略里的数
一个都没落到执行上。这个模块回答「该用哪个」,**而接线是另一截**。

## ⚠️ 为什么不是「策略说了就按策略」

那样一个填得更严的 Agent 会被放宽 —— 组织护栏的意义是**兜住下限**,
不是**规定上限**。反过来「Agent 说了算」更糟:一个 Agent 把
`max_tool_attempts` 填成 999 就退出了护栏。

所以:**两边都有时取更严的那个**(数值更小),而且**记下来用的是谁的**。

> 一个「被组织策略拦住」的运行,和一个「Agent 自己配得严才没跑飞」的,
> **在那次停下来上长得一模一样** —— 而前者说明护栏在工作,
> 后者说明护栏可能压根没接上。

## ⚠️ `max_tool_attempts` 这个名字在骗人

看它在 `agent_loop.py` 里的位置:`if 工具尝试 >= 最大工具` 在**网关之前**
自增,所以它数的是**模型提出的请求**(含被权限拒掉的),
不是「实际进了适配器的执行尝试」。

规格 §5.2 把这两件事**明确分成两个计数器**(一个数「模型提了几次请求」、
一个数「实际进了适配器几次」),并且写着:「迁移时保留
`counter_schema_version=legacy` 的旧含义;**不将历史同名字段悄悄改成新口径**」。

⚠️ **这段话里故意不写那两个计数器的字段名字面量。**
`tools/exec_limits_report.py` 的「待建」一档判据是**落点数 == 0**,而它数的是 grep ——
> 一处在注释里提到字段名的引用,和一处真读了它的代码,
> **在 grep 的计数上长得一模一样。**
2026-10-06 我在这儿写了那两个名字,那条清单当场红了两条。

> 一个「按请求数拦住的」运行,和一个「按实际执行数拦住的」,
> **在那条 `max_tool_attempts` 上长得一模一样** —— 而它们数的不是同一件事。

所以在**旧口径**下,这一个执行点要同时兜住策略里的两个键
(`tool_request_cap` / `tool_attempt_cap`),取**更严的那个** ——
并且在「为什么」里明说这是近似。
**新口径**下直接抛:那时候得先把两个计数器分开(落点清单里还是 ⬜ 待建)。

## ⚠️ 0 不是「无限制」

`上限 0 次` 的意思是**一次都不许**。最容易写出来的恰恰是
`cap = 限.get(k) or 默认` —— 那一行把 0 读成「没填」。

> 一条「上限 0 次」的策略,和一条「没设上限」的,
> **在 `if not cap` 这个写法里长得一模一样。**

所以这里一律用 `is None` 判在不在,不用真假。

## 它不做什么

- **不读库、不取今天。** 策略哪来的由调用方给(`agents_api._本次策略`)。
- **不决定数值。** 数值来自已发布的那一版或 `兜底上限.py`。
- **不自己兜底。** 两边都没有这一项 → **抛**。
  一个「默认成无限制」的合并器,把上游所有努力一次性抵消掉。
"""
