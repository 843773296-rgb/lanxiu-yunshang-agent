# ── 来源。**每一种都要能和别的分开** ────────────────────────────────
策略更严 = "执行策略更严"
配置更严 = "Agent 配置更严"
两边一样 = "两边一样"
只有策略 = "只有执行策略有"
只有配置 = "只有 Agent 配置有"
来源们 = (策略更严, 配置更严, 两边一样, 只有策略, 只有配置)


# ── 执行点 → 它对应策略里的哪几个键 ────────────────────────────────
#
# ⚠️ **键名一个都不许猜**:左边是 `agent_loop.py` 真读的那个名字,
# 右边是 `策略冻结.认得的limits键` 里的名字。两边都点名,下面有断言核。
执行点 = {
    "max_model_turns": {
        "策略键": ("model_request_cap",),
        "读在": "agent_loop.py:120",
        "说的是": "模型最大请求次数",
    },
    "max_tool_attempts": {
        "策略键": ("tool_request_cap", "tool_attempt_cap"),
        "读在": "agent_loop.py:229",
        "说的是": "工具调用上限 —— **旧口径下这一个数同时兜住"
                "「请求数」和「实际尝试数」**(规格 §5.2),所以取更严的那个",
    },
}


class 定不了(Exception):
    """输入本身讲不通 —— 当场抛。

    ⚠️ 这个异常的默认处置**不是**「那就不限制」。
    规格 §4.3:配置服务不可用**不等于额度可以清零**。
    """


def _正整数或零(v, 哪儿):
    """校验一个上限值。**布尔判在整数之前** —— 这个仓库为它栽过。

    `True` 在 Python 里 `== 1`,所以一个 `{"max_tool_attempts": true}`
    会变成「上限 1 次」,而填的人以为自己打开了这个保护。
    """
    if isinstance(v, bool):
        raise 定不了(f"{哪儿} 是布尔值 `{v}` —— **布尔不能当数字**"
                  f"(`True == 1`,于是它变成「上限 1 次」,"
                  f"而填的人以为自己打开了这个保护)")
    if not isinstance(v, int):
        raise 定不了(f"{哪儿} 是 {type(v).__name__} `{v!r}` —— 得是整数")
    if v < 0:
        raise 定不了(f"{哪儿} 是负数 `{v}` —— **负数不是「不限制」**,它讲不通")
    return v


def 定(*, 策略, agent配置=None):
    """返回 `{执行点名: {值, 来源, ...}}`。

    `策略`:`兜底上限.兜底()` 或已采用那一版的形状,要有
        `limits` / `counter_schema_version`,`来源` 可选(只进「为什么」)。
    `agent配置`:`cfg.get("limits")`,可以是 None 或空 dict。

    **每个执行点都一定给得出一个数** —— 这样 `agent_loop.py` 那两行
    `限.get("max_model_turns", 8)` 的内联默认值才能删掉。
    > 一处写在 `.get(..., 8)` 里的兜底,和一处写在策略模块里的,
    > **在那个 8 上长得一模一样** —— 而同一个事实两个来源,必然漂。
    """
    策 = 策略 or {}
    策limits = 策.get("limits")
    if not isinstance(策limits, dict) or not 策limits:
        raise 定不了("策略里一个 limits 都没有 —— **这不叫「不限制」**,"
                  "叫没给策略。没发布过任何一版时该传 `兜底上限.兜底()` 的结果")
    口径 = 策.get("counter_schema_version")
    if 口径 not in _冻.口径们:
        raise 定不了(f"认不出计数口径 `{口径!r}` —— 只认 {_冻.口径们}。"
                  f"规格 §5.2:同名字段在两套口径下数的不是同一件事,"
                  f"**不知道是哪一套就没法合并**")
    if 口径 == _冻.新口径:
        # ⚠️ 新口径下「请求数」和「实际尝试数」是两个计数器,而
        # `agent_loop` 只有一个 `工具尝试`。接之前得先把计数器分开
        # (`tools/exec_limits_report.py` 里那几条 ⬜ 待建)。
        raise 定不了(
            "这一版策略是**新口径**(v2),而 `agent_loop` 只有一个工具计数器 ——"
            "**不拿一个计数器去冒充两个**。规格 §5.2:"
            "「模型提了几次请求」和「实际进了适配器几次」是两个数"
            "(字段名见规格 §5.2 那张表 —— 这儿不写字面量,"
            "写了会被落点清单数成「已经有人读它了」);"
            "先把计数器分开(落点清单里还是「待建」),再接新口径的策略")

    配 = agent配置 or {}
    if not isinstance(配, dict):
        raise 定不了(f"`agent配置` 得是 dict 或 None,现在是 {type(配).__name__}")

    出 = {}
    for 名, 元 in 执行点.items():
        # ── 策略侧:多个键时取更严的那个 ────────────────────────
        候选 = []
        for k in 元["策略键"]:
            v = 策limits.get(k)
            if v is not None:                      # ⚠️ **不用真假** —— 0 是有效值
                候选.append((k, _正整数或零(v, f"策略的 `{k}`")))
        策值, 策键 = (min(候选, key=lambda x: x[1])[1],
                    min(候选, key=lambda x: x[1])[0]) if 候选 else (None, None)

        # ── Agent 配置侧 ──────────────────────────────────────
        配值 = 配.get(名)
        if 配值 is not None:
            配值 = _正整数或零(配值, f"Agent 配置的 `{名}`")

        if 策值 is None and 配值 is None:
            # **不兜底。** 兜底是上游(`兜底上限.py`)的事,这儿兜一次
            # 就等于把上游所有努力抵消掉 —— 而且是静默抵消。
            raise 定不了(
                f"`{名}` 两边都没有值 —— **这不叫「不限制」**。"
                f"策略里该有 {元['策略键']} 之一(没发布过任何一版时"
                f"`兜底上限.兜底()` 会给),Agent 配置里该有 `{名}`。"
                f"两边都空就是没人说过这件事,而「没人说过」不等于「随便跑」")

        if 策值 is None:
            值, 来源 = 配值, 只有配置
        elif 配值 is None:
            值, 来源 = 策值, 只有策略
        elif 策值 < 配值:
            值, 来源 = 策值, 策略更严
        elif 配值 < 策值:
            值, 来源 = 配值, 配置更严
        else:
            值, 来源 = 策值, 两边一样

        为什么 = [f"{元['说的是']};执行点在 `{元['读在']}`"]
        if len(元["策略键"]) > 1 and 策键:
            为什么.append(
                f"⚠️ 旧口径下这一个数同时兜住 {元['策略键']} —— "
                f"实际取了更严的 `{策键}`,**这是近似**:"
                f"`{名}` 在网关之前自增,数的是**请求**(含被拒的),"
                f"不是实际执行尝试(规格 §5.2)")
        if 来源 in (策略更严, 配置更严, 两边一样):
            为什么.append(f"策略给 {策值},Agent 配置给 {配值} → 取更严的 {值}")
        if 值 == 0:
            为什么.append("⚠️ **0 的意思是一次都不许**,不是「不限制」")

        出[名] = {
            "值": 值,
            "来源": 来源,
            "口径": 口径,
            "策略给的": 策值,
            "策略用的那个键": 策键,
            "Agent 配置给的": 配值,
            "策略从哪来": 策.get("来源"),
            "为什么": ";".join(为什么),
        }
    return 出


def 说清(定出来的):
    """一行一个执行点,给运行记录和页面用 —— **来源必须出现在里面**。

    > 一个「被组织策略拦住」的运行,和一个「Agent 自己配得严才没跑飞」的,
    > **在那次停下来上长得一模一样。**
    """
    return [f"{名} = {d['值']}（{d['来源']}"
            + (f"·{d['策略从哪来']}" if d.get("策略从哪来") else "")
            + f"·口径 {d['口径']}）"
            for 名, d in sorted(定出来的.items())]


