#   去向 + 参数:提示一句 → 提示(可写 {片段} {标准词});提示先调工具 → 工具(+ 提示);交给技能 → 技能(+ 提示);转人工 → 说明
# ⚠️ 「交给技能」是**强提示,不是硬锁**(技能仍由店长助手的模型挑;用户 11-08 认了「先做强提示,评测量它听不听」)
# ⚠️ 「转人工」要在这一轮回答前短路,得改店长助手主循环(sdk.py,不在 guards.py 的 on_prompt 里 —— 并行会话的边界),
#    规则(算不算一轮 / 记录仪记不记 / 评测判什么)还没和并行会话定 → **这一版冻结时先拦住**,不让它看起来能用而实际没生效
路由去向们 = ("带术语定义", "只占位", "提示一句", "提示先调工具", "交给技能", "转人工")
条件种类们 = ("实体", "意图", "歧义")
还没接上的去向 = ("转人工",)
默认去向 = {"术语": "带术语定义", "通称": "带术语定义", "名字": "只占位", "歧义": "提示一句"}


def 路由配置问题(配置):
    """→ (阻断, 提醒)。"""
    阻, 醒 = [], []
    if not isinstance(配置, dict):
        return ["路由配置要是一个对象:{规则: [...]}"], []
    规则们 = 配置.get("规则")
    if not isinstance(规则们, list):
        return ["「规则」要是一个列表(可以是空的:空 = 全走默认)"], []
    if not 规则们:
        醒.append("一条规则都没有 —— 全走默认:术语带定义、人名只占位、拿不准提示一句")
    见名, 见条件 = set(), {}
    for k, r in enumerate(规则们, 1):
        if not isinstance(r, dict):
            阻.append(f"第 {k} 条规则格式不对"); continue
        名 = str(r.get("名称") or "").strip() or f"第 {k} 条"
        if not str(r.get("名称") or "").strip():
            阻.append(f"第 {k} 条规则没有名称")
        elif 名 in 见名:
            阻.append(f"规则名称「{名}」重复了")
        见名.add(名)
        条 = r.get("条件") or {}
        种 = 条.get("种类")
        if 种 not in 条件种类们:
            阻.append(f"「{名}」的条件要选:实体 / 意图 / 歧义")
        elif 种 in ("实体", "意图") and not str(条.get("值") or "").strip():
            阻.append(f"「{名}」的条件是「{种}」,要写是哪个{'类别' if 种 == '实体' else '意图'}")
        去 = r.get("去向")
        if 去 not in 路由去向们:
            阻.append(f"「{名}」的去向要从这几种里选:{' / '.join(路由去向们)}")
        elif 去 in 还没接上的去向:
            阻.append(f"「{名}」选了「{去}」:这个去向还没接上店长助手(要改主循环,正在和并行会话定规则)—— 这一版先别选,接上之后再开")
        elif 去 == "提示一句" and not str(r.get("提示") or "").strip():
            阻.append(f"「{名}」选了「提示一句」,但没写提示")
        elif 去 == "提示先调工具" and not str(r.get("工具") or "").strip():
            阻.append(f"「{名}」选了「提示先调工具」,但没写工具名")
        elif 去 == "交给技能" and not str(r.get("技能") or "").strip():
            阻.append(f"「{名}」选了「交给技能」,但没写技能名")
        if 去 == "带术语定义" and 种 == "实体" and str(条.get("值")) not in ("术语", "通称"):
            醒.append(f"「{名}」:给「{条.get('值')}」这类名字选「带术语定义」没有效果 —— 名字没有术语定义可带")
        if 种 == "意图":
            醒.append(f"「{名}」:按意图的规则要等「意图识别」接上后才会生效(第三期)")
        键 = (种, str(条.get("值") or ""))
        if 种 in 条件种类们 and 键 in 见条件:
            醒.append(f"「{名}」和「{见条件[键]}」条件一样 —— 只有排在前面的那条会生效")
        见条件.setdefault(键, 名)
    return 阻, 醒


def _对上(条, 段=None, 意图=None, 歧义=False):
    种 = (条 or {}).get("种类")
    if 种 == "实体":
        return 段 is not None and str(条.get("值")) == 段.get("类别")
    if 种 == "意图":
        return 意图 is not None and str(条.get("值")) == 意图
    if 种 == "歧义":
        return 歧义
    return False


def _填(文, 段, 标准词=""):
    return str(文 or "").replace("{片段}", 段.get("片段", "")).replace("{标准词}", 标准词 or "")


def 应用路由(识别结果, 路由配置=None, 意图=None, 歧义提醒=None):
    """识别结果(识别实体() 的输出)+ 路由配置 + 意图(第三期前恒为 None)→
    {术语命中, 提示们, 技能, 转人工, 走了}:
      · 术语命中:只留去向为「带术语定义」的术语 / 通称(拿不准那条的「拿不准」标记拿掉 —— 提醒改由歧义规则给,不重复)
      · 提示们:提示一句 / 提示先调工具 / 交给技能 给模型的话(去重、按出现顺序)
      · 走了:每段走了哪条规则(没对上 = 默认),给「试一句」和日志看
    路由配置为 None = 全走默认(和第一期行为一样)。"""
    规则们 = list((路由配置 or {}).get("规则") or [])
    醒默认 = 歧义提醒 or _拿不准提醒
    命中, 提示们, 走了, 技能, 转人工 = [], [], [], None, False
    见过 = set()

    def 加提示(t):
        if t and t not in 提示们:
            提示们.append(t)

    def 执行(r, 段, std=""):
        nonlocal 技能, 转人工
        去 = r.get("去向")
        if 去 == "提示一句":
            加提示(_填(r.get("提示"), 段, std))
        elif 去 == "提示先调工具":
            加提示(_填(r.get("提示"), 段, std) or f"「{段['片段']}」:先调「{r.get('工具')}」查清楚再回答")
        elif 去 == "交给技能":
            技能 = 技能 or r.get("技能")
            加提示(_填(r.get("提示"), 段, std) or f"这一句按规则交给「{r.get('技能')}」技能处理,请用这个技能")
        elif 去 == "转人工":
            转人工 = True
        return 去

    if 意图 is not None:
        r = next((r for r in 规则们 if _对上(r.get("条件"), 意图=意图)), None)
        if r:
            执行(r, {"片段": 意图})
            走了.append({"对象": f"意图「{意图}」", "规则": r.get("名称"), "去向": r.get("去向")})
    for 段 in 识别结果 or []:
        是术语 = 段["类别"] in 保留类别
        std们 = 段.get("标准词们") or []
        if 段.get("拿不准"):
            r = next((r for r in 规则们 if _对上(r.get("条件"), 歧义=True)), None)
            去 = 执行(r, 段, std们[0] if std们 else "") if r else None
            if r is None:
                加提示(_填(醒默认, 段, std们[0] if std们 else ""))
            走了.append({"对象": f"「{段['片段']}」(拿不准)", "规则": r.get("名称") if r else "默认", "去向": 去 or 默认去向["歧义"]})
        r = next((r for r in 规则们 if _对上(r.get("条件"), 段=段)), None)
        if r is None:
            去 = 默认去向["术语"] if 是术语 else 默认去向["名字"]
            if not 是术语 and 段.get("命中后") == "占位并提示" and 段.get("提示"):     # 第一期词典里写的「占位并提示」照旧认
                加提示(段["提示"]); 去 = "提示一句"
        else:
            去 = 执行(r, 段, std们[0] if std们 else "")
        走了.append({"对象": f"「{段['片段']}」({段['类别']})", "规则": r.get("名称") if r else "默认", "去向": 去})
        if 是术语 and 去 == "带术语定义":
            for std in std们:
                if std not in 见过:
                    命中.append({"标准词": std, "命中的叫法": 段["片段"], "位置": 段["位置"],
                                 **({"通称": True} if 段["类别"] == "通称" else {})})
                    见过.add(std)
    return {"术语命中": 命中, "提示们": 提示们, "技能": 技能, "转人工": 转人工, "走了": 走了}


def 上下文段(命中们, 术语们, 规则=None, 提示们=None):
    """把这次提到的那几条拼成交给模型的一段。**只有这几条**(用户拍:只带这次提到的);一条都没提到 → 空串(不带空壳)。
    规则 = 拿不准的配置(提醒的写法);提示们 = 「占位并提示」那几本词典这次命中给的提示(没有术语命中也会单独成段)。"""
    按词 = {str(t.get("标准词") or "").strip(): t for t in 术语们 or []}
    行们 = []
    for h in 命中们 or []:
        t = 按词.get(h["标准词"]) or {}
        叫 = [x for x in (t.get("叫法") or []) if x]
        行 = f"- {h['标准词']}" + (f"(也叫:{'、'.join(叫)})" if 叫 else "") + f":{(t.get('定义') or '').strip()}"
        口 = t.get("口径") or {}
        if 口:
            行 += ";口径:" + ";".join(f"{k}={v}" for k, v in 口.items() if v)
        取 = t.get("取数口") or {}
        if 取.get("工具"):
            行 += f";要取数时调「{取['工具']}」" + (f"({取['说明']})" if 取.get("说明") else "")
        行们.append(行)
    提示们 = [t for t in 提示们 or [] if t]
    if not 行们:
        return ("以下是这句话里认出来的名字,**照这里理解**:\n" + "\n".join(f"- {t}" for t in 提示们)) if 提示们 else ""
    通称们 = []
    for h in 命中们 or []:
        if h.get("通称") and h["命中的叫法"] not in 通称们:
            通称们.append(h["命中的叫法"])
    for 叫 in 通称们:
        几条 = [h["标准词"] for h in 命中们 if h.get("通称") and h["命中的叫法"] == 叫]
        行们.append(f"- 注意:「{叫}」是通称,上面的 {'、'.join(几条)} 都叫这个名字,款式不一样 —— "
                   f"对方没说是哪一款时先问清,不要自己挑一条当答案")
    for h in 命中们 or []:
        if h.get("拿不准"):
            醒 = str((规则 or {}).get("提醒") or _拿不准提醒)
            行们.append("- 注意:" + 醒.replace("{片段}", h["命中的叫法"]).replace("{标准词}", h["标准词"]))
    for t in 提示们:
        行们.append(f"- {t}")
    return ("以下是这次提到的业务术语,**按这里的定义和口径理解和回答**(和你自己的理解不一样时以这里为准;"
            "数要调指定的工具取,不要自己估):\n" + "\n".join(行们))


def 格式问题(术语们):
    """→ (阻断们, 提醒们)。阻断:标准词空 / 重复、同一叫法对到两个标准词、类别认不出、指标类缺定义或口径。
    提醒:一条的叫法是另一条叫法的一部分(最长匹配在长词没录时会误命中短词)。"""
    阻, 醒 = [], []
    见 = {}
    for i, t in enumerate(术语们 or [], 1):
        std = str(t.get("标准词") or "").strip()
        if not std:
            阻.append(f"第 {i} 条:要写「标准词」")
            continue
        if std in 见:
            阻.append(f"「{std}」写了两条(第 {见[std]} 条和第 {i} 条)—— 合成一条")
        见.setdefault(std, i)
        if (t.get("类别") or "名词") not in 类别们:
            阻.append(f"「{std}」:类别只收 {'、'.join(类别们)}")
        if not str(t.get("定义") or "").strip():
            阻.append(f"「{std}」:要写「定义」—— 带给模型的就是这一句")
        if (t.get("类别") or "名词") == "指标" and not (t.get("口径") or {}):
            阻.append(f"「{std}」是指标,要写「口径」(分子 / 分母 / 时间)—— 不写的话模型会按它自己的理解算")
    通 = _通称表(术语们)
    for 叫, stds in 通.items():
        if len(stds) < 2:
            醒.append(f"通称「{叫}」只挂在「{stds[0]}」一条上 —— 通称是好几条共用的名字;只有一条的话写进「叫法」就行")
    归属 = {}
    for 叫, std in _叫法表(术语们):
        if 叫 in 通:
            阻.append(f"「{叫}」既是「{std}」的叫法 / 标准词,又是通称 —— 二选一(是好几款共用的名字就只写在「通称」栏)")
        if 叫 in 归属 and 归属[叫] != std:
            阻.append(f"叫法「{叫}」同时对到「{归属[叫]}」和「{std}」—— 一个叫法只能对一个标准词(否则对到哪个取决于先后顺序)")
        归属.setdefault(叫, std)
    for 叫, stds in 通.items():
        归属.setdefault(叫, "、".join(stds))
    叫们 = sorted(归属)
    for a in 叫们:
        for b in 叫们:
            if a != b and a in b and 归属[a] != 归属[b] and 归属[b] not in 通.get(a, []):
                醒.append(f"「{a}」({归属[a]})是「{b}」({归属[b]})的一部分 —— 说「{b}」时会对到「{归属[b]}」(最长匹配);"
                         f"但文本里出现没录的「…{a}…」长词时会误对到「{归属[a]}」,需要的话把那个长词也录上")
    return 阻, 醒


def 注入(文本, 术语们, 版本, 记事):
    """worker 里工作流模型步骤和 Agent 共用的那一步:匹配 → 有命中就记一条 glossary.injected{术语版本, 带了} → 返回拼给模型的那一段。
    一条都没提到 → 不记事件、返回空串。抽到这里(11-06 深夜)是为了**不起 worker 也验得到**:
    e2e 里的作业会被常驻 worker(跑的是主检出那份代码)抢走,咬合在副本里改坏 worker 看不见。"""
    命 = 匹配(文本, 术语们)
    if 命:
        记事("glossary.injected", {"术语版本": 版本, "带了": [h["标准词"] for h in 命]})
    return 上下文段(命, 术语们)
