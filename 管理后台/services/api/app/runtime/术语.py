"""术语配置 / 语义层的纯函数(2026-11-06;用户拍「术语配置,做语义层」+ 选型卡四件)。不碰库、不调模型。

## 用户拍的四件

① **只带这次提到的**:按叫法在这次的输入里找出提到了哪些术语,只把那几条的定义 / 口径交给模型(否决:每次全带 / 给模型查术语工具)
② 一条术语记 **标准词 + 叫法 + 定义 + 指标口径 + 取数口**;普通名词只填前三项
③ **算法以代码为准,术语是说明**:真正的计算在 knowledge/*.py 和工具里;术语记「怎么说、调哪个工具」(否决:代码改读配置)
④ 叫法 → 标准词用 **词表最长匹配**(否决:让模型判断)

## 一条术语长什么样

    {"标准词": "到店率", "叫法": ["到店转化", "预约到店比"], "类别": "指标",
     "定义": "预约了的顾客里真到店的比例",
     "口径": {"分子": "到店的预约数", "分母": "预约数(不含已取消)", "时间": "按预约日期"},
     "取数口": {"工具": "appt_funnel", "说明": "按门店 / 周取"}}

## 最长匹配会怎么错(选型卡上说过,这里钉住)

· 只认录了的叫法 —— 没录的说法、错别字对不上(要靠补词表)
· **短叫法是长词的一部分**:只录了「纱」、没录「香云纱」,「香云纱」也会命中「纱」(这个项目记过这个坑)。
  最长匹配只在长词也录了时才挡得住 —— 所以 `格式问题()` 把「一条的叫法是另一条叫法的一部分」报成**提醒**(不阻断),让人决定补不补长词
· 同一个叫法对到两个标准词 → 先后顺序决定结果 → 报成**格式错误**(阻断)
· **通称**(11-07 用户拍「收,带上所有朝代」):「圆领袍」「褙子」「交领襦裙」是好几个朝代 / 款式共用的名字。
  写进一条的「通称」栏(不是「叫法」栏),同一个通称可以挂在多条上;说到通称时**这几条一起带**,并附一句「先问清是哪一款」。
  不放开「叫法」重复:那条阻断防的是手误;通称是**有意写的歧义**,单开一栏才分得开。
  09-21 业务拍过板:通称独占给某个朝代,会把别的朝代的款悄悄判成它(当时一款唐制袍被判成明制)
· 英文 / 数字缩写(ROI、GMV):全是 ASCII 字母数字的叫法要求前后是词边界(「ROI」不命中「ROIC」);中文叫法照旧按子串
"""

类别们 = ("名词", "指标")


def _是ASCII词字(ch):
    return ch.isascii() and ch.isalnum()


def _边界成立(s, i, 叫):
    """叫法**全是 ASCII 字母数字**时,前后不能紧挨着 ASCII 字母数字才算命中(11-06,并行会话指出):
    「ROI」不该命中「ROIC 怎么算」、「15」不该命中「115」—— 命中错的术语和命中对的,在返回结构上长得一模一样。
    中文 / 混合叫法不受影响(中文没有空格,按子串最长匹配是对的)。"""
    if not all(_是ASCII词字(c) for c in 叫):
        return True
    前 = s[i - 1] if i > 0 else ""
    后 = s[i + len(叫)] if i + len(叫) < len(s) else ""
    return not (前 and _是ASCII词字(前)) and not (后 and _是ASCII词字(后))


def _叫法表(术语们):
    """→ [(叫法, 标准词)],标准词自己也算一个叫法;按长度从长到短(最长匹配)。"""
    出 = []
    for t in 术语们 or []:
        std = str(t.get("标准词") or "").strip()
        if not std:
            continue
        for x in [std] + list(t.get("叫法") or []):
            x = str(x or "").strip()
            if x:
                出.append((x, std))
    return sorted(set(出), key=lambda p: (-len(p[0]), p[0]))


def _通称表(术语们):
    """→ {通称: [标准词…]}(按术语表顺序)。"""
    出 = {}
    for t in 术语们 or []:
        std = str(t.get("标准词") or "").strip()
        if not std:
            continue
        for x in t.get("通称") or []:
            x = str(x or "").strip()
            if x and std not in 出.setdefault(x, []):
                出[x].append(std)
    return 出


def 匹配(文本, 术语们):
    """在文本里找出提到的术语 → [{标准词, 命中的叫法, 位置}],按出现顺序,同一标准词只报第一次。

    最长匹配、不重叠:从左往右扫,每个位置先试最长的叫法;命中就跳过这一段(「宋制对襟长褙」命中后,里面的「褙」不再单独算)。"""
    s = str(文本 or "")
    通 = _通称表(术语们)
    # 通称和叫法放进同一张表一起做最长匹配(「唐制圆领缺胯袍」比「圆领袍」长,说全名时照旧只对到那一条)
    表 = sorted([(叫, (std,), False) for 叫, std in _叫法表(术语们)]
               + [(叫, tuple(stds), True) for 叫, stds in 通.items()], key=lambda p: (-len(p[0]), p[0]))
    出, 见过, i = [], set(), 0
    while i < len(s):
        hit = None
        for 叫, stds, 是通称 in 表:
            if s.startswith(叫, i) and _边界成立(s, i, 叫):
                hit = (叫, stds, 是通称)
                break
        if hit:
            for std in hit[1]:
                if std not in 见过:
                    出.append({"标准词": std, "命中的叫法": hit[0], "位置": i, **({"通称": True} if hit[2] else {})})
                    见过.add(std)
            i += len(hit[0])
        else:
            i += 1
    return 出


def 上下文段(命中们, 术语们):
    """把这次提到的那几条拼成交给模型的一段。**只有这几条**(用户拍:只带这次提到的);一条都没提到 → 空串(不带空壳)。"""
    按词 = {str(t.get("标准词") or "").strip(): t for t in 术语们 or []}
    行们 = []
    for h in 命中们 or []:
        t = 按词.get(h["标准词"]) or {}
        叫 = [x for x in (t.get("叫法") or []) if x]
        行 = f"- {h['标准词']}" + (f"(也叫:{'、'.join(叫)})" if 叫 else "") + f":{(t.get('定义') or '').strip()}"
        口 = t.get("口径") or {}
        if 口:
            行 += ";口径:" + ";".join(f"{k}={v}" for k, v in 口.items() if v)
        取 = t.get("取数口") or {}
        if 取.get("工具"):
            行 += f";要取数时调「{取['工具']}」" + (f"({取['说明']})" if 取.get("说明") else "")
        行们.append(行)
    if not 行们:
        return ""
    通称们 = []
    for h in 命中们 or []:
        if h.get("通称") and h["命中的叫法"] not in 通称们:
            通称们.append(h["命中的叫法"])
    for 叫 in 通称们:
        几条 = [h["标准词"] for h in 命中们 if h.get("通称") and h["命中的叫法"] == 叫]
        行们.append(f"- 注意:「{叫}」是通称,上面的 {'、'.join(几条)} 都叫这个名字,款式不一样 —— "
                   f"对方没说是哪一款时先问清,不要自己挑一条当答案")
    return ("以下是这次提到的业务术语,**按这里的定义和口径理解和回答**(和你自己的理解不一样时以这里为准;"
            "数要调指定的工具取,不要自己估):\n" + "\n".join(行们))


def 格式问题(术语们):
    """→ (阻断们, 提醒们)。阻断:标准词空 / 重复、同一叫法对到两个标准词、类别认不出、指标类缺定义或口径。
    提醒:一条的叫法是另一条叫法的一部分(最长匹配在长词没录时会误命中短词)。"""
    阻, 醒 = [], []
    见 = {}
    for i, t in enumerate(术语们 or [], 1):
        std = str(t.get("标准词") or "").strip()
        if not std:
            阻.append(f"第 {i} 条:要写「标准词」")
            continue
        if std in 见:
            阻.append(f"「{std}」写了两条(第 {见[std]} 条和第 {i} 条)—— 合成一条")
        见.setdefault(std, i)
        if (t.get("类别") or "名词") not in 类别们:
            阻.append(f"「{std}」:类别只收 {'、'.join(类别们)}")
        if not str(t.get("定义") or "").strip():
            阻.append(f"「{std}」:要写「定义」—— 带给模型的就是这一句")
        if (t.get("类别") or "名词") == "指标" and not (t.get("口径") or {}):
            阻.append(f"「{std}」是指标,要写「口径」(分子 / 分母 / 时间)—— 不写的话模型会按它自己的理解算")
    通 = _通称表(术语们)
    for 叫, stds in 通.items():
        if len(stds) < 2:
            醒.append(f"通称「{叫}」只挂在「{stds[0]}」一条上 —— 通称是好几条共用的名字;只有一条的话写进「叫法」就行")
    归属 = {}
    for 叫, std in _叫法表(术语们):
        if 叫 in 通:
            阻.append(f"「{叫}」既是「{std}」的叫法 / 标准词,又是通称 —— 二选一(是好几款共用的名字就只写在「通称」栏)")
        if 叫 in 归属 and 归属[叫] != std:
            阻.append(f"叫法「{叫}」同时对到「{归属[叫]}」和「{std}」—— 一个叫法只能对一个标准词(否则对到哪个取决于先后顺序)")
        归属.setdefault(叫, std)
    for 叫, stds in 通.items():
        归属.setdefault(叫, "、".join(stds))
    叫们 = sorted(归属)
    for a in 叫们:
        for b in 叫们:
            if a != b and a in b and 归属[a] != 归属[b] and 归属[b] not in 通.get(a, []):
                醒.append(f"「{a}」({归属[a]})是「{b}」({归属[b]})的一部分 —— 说「{b}」时会对到「{归属[b]}」(最长匹配);"
                         f"但文本里出现没录的「…{a}…」长词时会误对到「{归属[a]}」,需要的话把那个长词也录上")
    return 阻, 醒


def 注入(文本, 术语们, 版本, 记事):
    """worker 里工作流模型步骤和 Agent 共用的那一步:匹配 → 有命中就记一条 glossary.injected{术语版本, 带了} → 返回拼给模型的那一段。
    一条都没提到 → 不记事件、返回空串。抽到这里(11-06 深夜)是为了**不起 worker 也验得到**:
    e2e 里的作业会被常驻 worker(跑的是主检出那份代码)抢走,咬合在副本里改坏 worker 看不见。"""
    命 = 匹配(文本, 术语们)
    if 命:
        记事("glossary.injected", {"术语版本": 版本, "带了": [h["标准词"] for h in 命]})
    return 上下文段(命, 术语们)
