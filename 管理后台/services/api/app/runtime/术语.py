def 实体配置问题(配置):
    """→ (阻断, 提醒)。阻断 = 冻结不了;提醒 = 能冻,但多半不是你想要的。"""
    阻, 醒 = [], []
    if not isinstance(配置, dict):
        return ["实体识别配置要是一个对象:{词典: [...], 拿不准: {...}}"], []
    词典们 = 配置.get("词典")
    if not isinstance(词典们, list) or not 词典们:
        阻.append("至少要有一本词典")
        词典们 = []
    见名 = set()
    for k, d in enumerate(词典们, 1):
        if not isinstance(d, dict):
            阻.append(f"第 {k} 本词典格式不对"); continue
        名 = str(d.get("名称") or "").strip() or f"第 {k} 本"
        if not str(d.get("名称") or "").strip():
            阻.append(f"第 {k} 本词典没有名称")
        elif 名 in 见名:
            阻.append(f"词典名称「{名}」重复了")
        见名.add(名)
        类 = str(d.get("类别") or "").strip()
        if not 类:
            阻.append(f"「{名}」没有类别(客户 / 员工 / 着装人 / 商品…)")
        elif 类 in 保留类别:
            阻.append(f"「{名}」的类别不能叫「{类}」—— 这个名字留给术语表")
        来 = d.get("来源")
        if 来 not in 来源们:
            阻.append(f"「{名}」的来源要选「业务表」或「手工」")
        elif 来 == "业务表":
            if d.get("表列") not in 可选业务表列:
                阻.append(f"「{名}」的业务表列要从这几个里选:{'、'.join(可选业务表列.values())}")
        else:
            词 = [str(x or "").strip() for x in d.get("词条") or []]
            if not [x for x in 词 if x]:
                醒.append(f"「{名}」是手工词典但一个词条都没有 —— 冻进去也什么都不占")
        短 = d.get("最短字数", 2)
        if not isinstance(短, int) or isinstance(短, bool) or not 1 <= 短 <= 10:
            阻.append(f"「{名}」的最短字数要是 1–10 的整数")
        elif 短 == 1:
            醒.append(f"「{名}」最短字数是 1:单字名字会把「罗」「纱」这类单字术语全吃掉")
        elif 来 == "手工":
            太短 = [x for x in (str(y or "").strip() for y in d.get("词条") or []) if x and len(x) < 短]
            if 太短:
                醒.append(f"「{名}」有 {len(太短)} 个词条不到 {短} 个字,会被跳过:{'、'.join(太短[:5])}")
        if d.get("同样长时", "让给术语") not in 同样长时们:
            阻.append(f"「{名}」的「同样长时」要选「让给术语」或「压过术语」")
        后 = d.get("命中后", "占位")
        if 后 not in 命中后们:
            阻.append(f"「{名}」的「命中后」要选「占位」或「占位并提示」")
        elif 后 == "占位并提示" and not str(d.get("提示") or "").strip():
            阻.append(f"「{名}」选了「占位并提示」,但没写提示")
    疑 = 配置.get("拿不准")
    if 疑 is not None:
        if not isinstance(疑, dict):
            阻.append("「拿不准」要是一个对象:{开, 称呼前, 称呼后, 提醒}")
        else:
            for 键 in ("称呼前", "称呼后"):
                if not isinstance(疑.get(键, []), list) or not all(isinstance(x, str) and x.strip() for x in 疑.get(键, [])):
                    阻.append(f"「拿不准」的{键}要是一串非空的字")
            if 疑.get("开", True) and not (疑.get("称呼前") or 疑.get("称呼后")):
                醒.append("「拿不准」开着,但称呼前后一个字都没填 —— 等于关了")
            if "总" in (疑.get("称呼后") or []) or "工" in (疑.get("称呼后") or []):
                醒.append("称呼后里有「总」或「工」:「纱总共」「纱工艺」这类话会被误判成拿不准")
    return 阻, 醒


def 按配置的名单(配置, 现取=None):
    """实体识别配置 → 实体识别()要的名单(一本本词典,词条已展开)。

    现取(表列) → [名字…]:业务表来源**运行时**现取(聊天站传从业务库只读取的函数);
    不给 / 取不到 → 那一本这一轮是空的,记在 "取不到" 里(**空和取不到分开报**,不把错误包成空列表)。"""
    出, 取不到 = [], []
    for d in (配置 or {}).get("词典") or []:
        if d.get("来源") == "业务表":
            # ⚠️ 别写成 `list(现取(...) or [])` —— 那会把「取不到(None)」悄悄变成「空名单([])」,
            #    而这两种在「这本词典这一轮什么都没占」上长得一模一样(11-08 e2e 抓到,单测只造了「抛错」那一种)
            try:
                词 = 现取(d.get("表列")) if 现取 else None
            except Exception:                                              # noqa: BLE001
                词 = None
            词 = list(词) if 词 is not None else None
            if 词 is None:
                取不到.append(d.get("名称")); 词 = []
        else:
            词 = list(d.get("词条") or [])
        出.append({"名称": d.get("名称"), "类别": d.get("类别"), "词条": 词, "最短字数": d.get("最短字数", 2),
                   "同样长时": d.get("同样长时", "让给术语"), "命中后": d.get("命中后", "占位"), "提示": d.get("提示") or ""})
    return 出, 取不到


def _规范名单(名单):
    """老写法 {类别: [名字…]}(11-08 第一版、过渡期)和新写法(一本本词典)都认 → 新写法。"""
    if isinstance(名单, dict):
        return [{"名称": 类, "类别": 类, "词条": list(名单.get(类) or []), "最短字数": 2, "同样长时": "让给术语",
                 "命中后": "占位", "提示": ""} for 类 in 名单类别 if 名单.get(类)]
    return list(名单 or [])


def _拿不准(s, i, 叫, 规则):
    if len(叫) != 1 or not 规则.get("开", True):
        return False
    前 = tuple(规则.get("称呼前") or ())
    后 = tuple(规则.get("称呼后") or ())
    return bool((前 and i > 0 and s[i - 1] in 前) or (后 and s.startswith(后, i + 1)))


def 识别实体(文本, 术语们, 名单=None, 规则=None):
    """→ [{片段, 类别, 位置, 标准词们, 拿不准?, 词典?, 命中后?, 提示?}],按出现顺序;没对上任何词典的字不出现。

    类别 = 术语 / 通称 / 各本词典自己的类别。名单:一本本词典(`按配置的名单()` 的输出),或老写法 {类别: [名字…]};
    不给就只有术语(管理后台工作流现在就是这样)。规则 = 拿不准的配置,不给用默认。
    最长匹配、不重叠:从左往右扫,每个位置先试最长的;命中就跳过这一段(「宋制对襟长褙」命中后,里面的「褙」不再单独算)。"""
    s = str(文本 or "")
    规 = dict(默认拿不准, **(规则 or {}))
    # (词, 类别, 标准词们, 优先级, 词典):同长时优先级小的先试 —— 术语 0;名字「让给术语」1、「压过术语」-1
    候 = [(叫, "术语", (std,), 0, None) for 叫, std in _叫法表(术语们)]
    候 += [(叫, "通称", tuple(stds), 0, None) for 叫, stds in _通称表(术语们).items()]
    for d in _规范名单(名单):
        短 = d.get("最短字数", 2) or 2
        优 = -1 if d.get("同样长时") == "压过术语" else 1
        for n in set(str(x or "").strip() for x in d.get("词条") or []):
            if len(n) >= 短:                                        # 默认单字名字不收:会把单字术语全吃掉
                候.append((n, d.get("类别"), (), 优, d))
    索 = {}
    for c in sorted(候, key=lambda p: (-len(p[0]), p[3], p[0])):
        索.setdefault(c[0][0], []).append(c)
    出, i = [], 0
    while i < len(s):
        hit = next((c for c in 索.get(s[i], ()) if s.startswith(c[0], i) and _边界成立(s, i, c[0])), None)
        if hit:
            段 = {"片段": hit[0], "类别": hit[1], "位置": i, "标准词们": list(hit[2])}
            if hit[4] is not None:
                段.update(词典=hit[4].get("名称"), 命中后=hit[4].get("命中后", "占位"))
                if 段["命中后"] == "占位并提示":
                    段["提示"] = str(hit[4].get("提示") or "").replace("{片段}", hit[0])
            elif _拿不准(s, i, hit[0], 规):
                段["拿不准"] = True
            出.append(段)
            i += len(hit[0])
        else:
            i += 1
    return 出


def 取术语命中(拆):
    """识别结果 → 术语命中 [{标准词, 命中的叫法, 位置, 通称?, 拿不准?}],同一标准词只报第一次。"""
    出, 见过 = [], set()
    for 段 in 拆 or []:
        if 段["类别"] not in 保留类别:
            continue
        for std in 段["标准词们"]:
            if std not in 见过:
                出.append({"标准词": std, "命中的叫法": 段["片段"], "位置": 段["位置"],
                           **({"通称": True} if 段["类别"] == "通称" else {}),
                           **({"拿不准": True} if 段.get("拿不准") else {})})
                见过.add(std)
    return 出


def 名字提示(拆):
    """识别结果里「占位并提示」那几段的提示,去重、按出现顺序。"""
    出 = []
    for 段 in 拆 or []:
        t = 段.get("提示")
        if t and t not in 出:
            出.append(t)
    return 出


def 匹配(文本, 术语们, 名单=None, 规则=None):
    """在文本里找出提到的术语 → [{标准词, 命中的叫法, 位置}],按出现顺序,同一标准词只报第一次。
    先 `实体识别()`,只取术语 / 通称那几段;名字占掉的字不再算术语。"""
    return 取术语命中(识别实体(文本, 术语们, 名单, 规则))


