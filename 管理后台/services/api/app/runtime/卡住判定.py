#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""**一条记录卡住多久算卡住了,以及该不该由系统推它** —— 纯判定、零 IO。

业务 2026-10-07 拍的两件事:

    超时之后做什么   **分两档**:等外部确认的只报警,做不完的自动标失败
    阈值             **72 小时**

## ⚠️ 为什么必须分两档(这一条是一个真 bug 换来的)

`tests/e2e/test_training_flow.py` 的文件头记着:

> `POST /training-jobs/{id}/cancel` 第一版把「直接取消」写成「状态机允许走到
> 『已取消』就走」—— 而「取消请求中 → 已取消」那条边**只该由后台确认的时候走**。
> 于是**连点两次取消,系统就自己宣布「已取消」**,正是契约明令禁止的那件事。

所以:
> 一条「等外部确认」的记录,和一条「卡住没人管」的,
> **在那个状态上长得一模一样** —— 而前者**绝不能由系统自己推到终态**,
> 后者才需要处理。

自动推「等外部」那一档 = 重犯那个 bug。所以这里把它判成 `只报警`。

## ⚠️ 72 小时的依据,一半是实测一半是猜的 —— 两半都要写出来

    实测的那半:库里历史残留**最短等了 75.2 小时**,而刚发生的那 3 条等了 0.4 小时。
                72 卡在中间 —— 框得住全部残留,碰不到刚发生的。
    猜的那半:  「真实训练任务不会超过 3 天」—— **这个系统从没接过真的训练/部署**,
                库里那些耗时全是 mock 跑出来的(秒级)。
                > 一个「正常完成要 22 秒」的量数,和一个「真实系统正常要 2 小时」的,
                > **在那张表上长得一模一样** —— 因为那张表里一条真的都没有。

**接上真系统之后要重新量这个数**,而且重量之前它都该被当成一个占位值。

## ⚠️ 「待上传」不在这儿 —— 它已经有人管了

`knowledge/upload_rules.py` 的 `放弃门槛小时 = 24` + `该放弃吗()`,
执行脚本是 `tools/abandon_stale_uploads.py`。**门槛不一样是有道理的**:

    24h   等**人**传文件(点开选文件到传完是分钟级)
    72h   等**外部系统**确认(训练/部署可能跑几小时到几天)

所以这里对 `上传` **当场抛**,不给第二套判断 ——
> 两套实现迟早分叉,而分叉时两边各自都「有依据」,只是依据不一样。

## ⚠️ 「现在」是参数,不是 `now()`

照抄 `upload_rules.该放弃吗()` 的成语,它的理由值得再写一遍:
> 一个自己调 `now()` 的判断**没法测「刚好卡在门槛上」那一档** ——
> 而边界正是这种规则唯一容易错的地方。
"""
门槛小时 = 72        # 业务 2026-10-07 拍。依据见模块头(一半实测一半猜的)

只报警 = "只报警"
可标failed = "可标failed"       # running 跑过但什么都没留下 → 它确实炸了
可标expired = "可标expired"     # queued 从没开始、也没法开始 → 它过期了
还没超 = "还没超"

# ⚠️ **终态是状态机说的那个,不是我顺手挑的。** `contract/states.py`:
#     "queued":  ["running", "cancelled", "expired"]   ← **不能直接到 failed**
#     "running": ["succeeded", "incomplete", "failed", …]
# 所以 queued 超时只能走 `expired` —— 而那个名字本身就是「超时」:
# **设计者预见了这件事,只是没有人去执行它。**
# > 库里 `execution_runs.status` 的实际取值只有
# > succeeded/failed/cancelled/queued/running —— **`expired` 这一档
# > 从没有任何记录到过**。和 `uploads.已放弃` 完全同形,而那个道理
# > `upload_rules` 已经写过:一档到不了的状态比少一档更糟。
#
# ⚠️ 而 `expired` **不许用来藏不确定性**(states.py 注释 ④:
# 「外部动作状态不明时,不许用 expired/cancelled 把不确定性藏起来」)——
# 「queued 且没有定义引用」是**确定**做不完的,正好落在允许的那一侧。
# 「取消请求中」那种**状态不明**的,留给 `只报警`。

# 这几类等的是**外部确认** —— 系统推它们就是撒谎(而且契约明令禁止)
等外部的 = {
    ("评测", "排队中"): "评测结果由外部跑完再登记(POST /evaluations/{id}/items)",
    ("部署", "部署请求中"): "等部署系统确认",
    ("训练", "取消请求中"): "「取消请求中 → 已取消」那条边**只该由后台确认时走**",
}


class 判不了(Exception):
    """输入讲不通,或者这一类不该由这里判 —— 当场抛。

    ⚠️ 默认处置**不是**「那就当它没超」。一个把「判不了」读成「还没超」的清扫,
    和一个真判过的,**在那份空清单上长得一模一样**。
    """


def 几小时(创建时间, 现在):
    if 创建时间 is None or 现在 is None:
        raise 判不了("要两个时间都给 —— 缺一个就没法判,而**猜一个等于乱判**")
    return (现在 - 创建时间).total_seconds() / 3600.0


def 判(*, 种类, 状态, 创建时间, 现在,
      有检查点=None, 有定义引用=None, 门槛=None):
    """返回 `(哪一档, 为什么)`。

    `种类`:评测 / 部署 / 训练 / 运行。**上传不在这儿**(见模块头)。
    `有检查点` / `有定义引用`:只有 `运行` 要给 —— 它们决定「做不完」还是「可能能恢复」。
    """
    if 种类 == "上传":
        raise 判不了(
            "「待上传」不由这里判 —— 它在 `knowledge/upload_rules.该放弃吗()`,"
            "门槛 24 小时(等**人**传文件),执行脚本 `tools/abandon_stale_uploads.py`。"
            "**不给第二套判断**:两套实现迟早分叉,而分叉时两边各自都「有依据」")
    门 = 门槛小时 if 门槛 is None else 门槛
    过了 = 几小时(创建时间, 现在)
    if 过了 < 门:
        return 还没超, f"只过了 {过了:.1f} 小时,门槛 {门}"

    键 = (种类, 状态)
    if 键 in 等外部的:
        return 只报警, (
            f"过了 {过了:.1f} 小时,而它**等的是外部确认**"
            f"({等外部的[键]})—— 系统自己推它就是撒谎,"
            f"而「取消请求中 → 已取消」那一条**契约明令禁止**系统自己走")

    if 种类 == "运行":
        if 状态 == "queued":
            if 有定义引用 is None:
                raise 判不了("判 queued 的运行要知道**有没有定义引用** —— "
                          "没有它就不知道该执行什么,而那是「做不完」的判据")
            if not 有定义引用:
                return 可标expired, (
                    f"过了 {过了:.1f} 小时,而它**没有定义引用** —— "
                    f"有输入却不知道要执行什么,重派任务也没用。"
                    f"终态是 **expired**(状态机:queued 只能到 running/"
                    f"cancelled/expired,**到不了 failed**)—— "
                    f"而 expired 这一档库里从没有任何记录到过")
            return 只报警, (
                f"过了 {过了:.1f} 小时,但它**有定义引用** —— "
                f"理论上重派任务就能跑,所以**不自动标失败**,报出来让人决定")
        if 状态 == "running":
            if 有检查点 is None:
                raise 判不了("判 running 的运行要知道**有没有检查点** —— "
                          "这是「做不完」和「可能能恢复」的分界")
            if 有检查点:
                # ⚠️ 这一条是这个模块里最要紧的区分。
                # > 一个「跑到一半、有检查点可以接着跑」的 run,和一个
                # > 「跑到一半、什么都没留下」的,**在那个 `running` 上
                # > 长得一模一样** —— 而前者自动标失败会**丢掉一次可恢复的执行**。
                return 只报警, (
                    f"过了 {过了:.1f} 小时,但它**有检查点** —— "
                    f"可能还能恢复(§6.3:恢复时禁止重新初始化成零)。"
                    f"**不自动标失败**:那会丢掉一次可恢复的执行")
            return 可标failed, (
                f"过了 {过了:.1f} 小时,声称 running 而**没有任何检查点** —— "
                f"执行它的那个东西已经不在了,也没留下可恢复的中间状态。"
                f"⚠️ 终态是 **failed** 不是 cancelled:没有人取消它,"
                f"是这个系统漏了活 —— 用 cancelled 会把一次故障写成一次决定")
        raise 判不了(f"运行的状态 `{状态}` 不在判据里 —— "
                  f"只判 queued / running,**不兜底**")

    raise 判不了(
        f"没有 ({种类}, {状态}) 这一档的判据 —— **不兜底成「还没超」**:"
        f"一个把「判不了」读成「没问题」的清扫,和一个真判过的,"
        f"在那份空清单上长得一模一样")


