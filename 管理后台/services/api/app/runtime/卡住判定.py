# 判据在 `tests/orchestration/test_stale_judge.py`:
#   「等外部」那三类改成可标 failed/expired → ② 等外部的只报警
#   queued 的终态写成 failed            → ③ 状态机不允许(只能 expired)
#   running 有检查点也标失败            → ③ 有检查点的不许自动标失败
#   queued 没有定义引用时放过           → ③
#   上传那一档给了判断(不抛)            → ④ 不给第二套
#   把「现在」改成内部 now()            → ① 边界那一档测不了
#   门槛改成 24                         → ① 门槛是 72
