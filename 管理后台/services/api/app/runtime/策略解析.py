#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""**这次运行该用哪一版策略** —— 纯逻辑,零 IO。规格 §4.2 / §4.3 / §9.2。

## P0-B 的退出条件全压在这一步上

规格 §11:「**一次真实只读任务能对上后台版本与实际策略**」。
而「对上」要求四个状态分开(§4.2),所以这个函数的输出不是一个版本号,
是**一个带状态的答案**:采用 / 回退 / 拒绝启动。

## 它防的是哪一条,而那一条只要一行代码就会塌

规格 §4.3:

> 「允许使用上一次已验证的本地策略,但要**展示回退版本、年龄、原因及有效期**。
> **没有有效策略或所需硬限制不受支持时,拒绝启动受影响任务;不能回退为
> 「无限制」。配置服务不可用不等于额度可以清零。**」

而最容易写出来的恰恰是那一行:

    策略 = 拉配置() or 默认不限制        # ← 一行就塌

> **一个「配置服务挂了所以没限制」的运行,和一个「真被授权不限制」的,
> 在那次运行上长得一模一样。**

## 六条判据,顺序是有意的

### ① 入口要点名,**一个入口上过了的不代表另一个**

规格 §2.2 末:「接口、测试或页面的一边通过,
**不得被另一边借用为验收证据**」。

### ② 「版本已发布」**不等于**「实例已加载」

规格 §4.2 的表把这两行分开写了,§9.2 还规定:
存在发布但没有实例回执时**明确显示「尚未确认加载」**。
> 一条发了而没人加载的策略,和一条真在执行的,
> **在那个「已发布」上长得一模一样**。

### ③ 回执的哈希对不上 → **冲突**,不是「以回执为准」

规格 §10.3:「**服务端核验身份**」。实例不能自报它加载了什么。
> 一个「以实例自述为准」的解析,和一个真核验过的,
> **在正常情况下长得一模一样** —— 差别只在实例报错的时候出现,
> 而那正是你需要它报对的时候。

### ④ 回执**会陈旧**,而陈旧要算出来

规格 §10.2:「同一实例定期更新;**过期回执标陈旧**」。
> 一份三天前的回执,和一份刚刚确认的,
> **在那个「已加载」上长得一模一样**。

### ⑤ 硬限制「没核查过」→ **拒绝**,不是「当它支持」

`capability_map` 是三态的(支持 / 不支持 / **没核查过**)。
规格 §4.3 要求所需硬限制不受支持时拒绝启动,而**未知不是支持**:
> 一个把「没核查过」当成「支持」的判定,和一个真核查过的,
> **在那次放行上长得一模一样**。

### ⑥ 回退是一条**要显形**的路,不是静默兜底

回退必须带四样:版本、年龄、原因、有效期。缺一样就不叫回退,叫
「不知道在跑哪一版」。回退本身过期了 → **拒绝**,不是继续用。

## 它不做什么

- **不查库、不发请求。** 发布的那一版、实例回执们、本地回退都由调用方取来。
- **不判额度够不够。** 那是预算账本的事(`task_budget_ledgers`)。
- **不决定限制的数值。** 它只回答「这次该照哪一版办,还是根本不许开跑」。
"""

# 入口。**和迁移里的 CHECK 约束用同一套字面量** ——
# 两套枚举迟早分叉,而分叉时两边各自都是绿的。
门店V3 = "store_v3"
后台编排 = "admin_agent_loop"
入口们 = (门店V3, 后台编排)

# 答案的状态。**三种,不是两种** —— 「回退」必须和「采用」分开,
# 否则页面上看不出它在跑一份旧的。
采用 = "采用"
回退 = "回退(用上一次已验证的本地策略)"
拒绝启动 = "拒绝启动"

# 能力三态里的第三态。**它不是 False。**
没核查过 = "没核查过"


class 解析不了(Exception):
    """输入本身讲不通 —— 当场抛。

    ⚠️ 这个异常的默认处置**不是**「那就不限制」。
    规格 §4.3:配置服务不可用**不等于额度可以清零**。
    """


def 这次用哪一版(*, 入口, 发布的=None, 这个实例的回执=None, 现在,
             回执最长年龄秒=900, 本地回退=None):
    """返回 `(用哪一版, 状态, 细节)`。`状态` 是上面三个常量之一。

    `发布的`:环境指针指到的那一版,要有 `id` / `content_hash` /
        `entry_kind` / `support_conditions` / `limits`。
    `这个实例的回执`:**这台实例**最近一次回执,要有
        `execution_policy_version_id` / `policy_hash` / `loaded_at` /
        `capability_map`。没有就是 `None` —— 那是「尚未确认加载」。
    `本地回退`:上一次已验证的本地策略,要有
        `id` / `limits` / `验证于` / `有效到` / `为什么回退`。

    ⚠️ **拒绝启动时 `用哪一版` 是 `None`,而调用方不许把 `None` 读成
    「没有限制」** —— 那正是这个函数存在的理由。`状态` 才是答案。
    """
    if 入口 not in 入口们:
        raise 解析不了(
            f"入口 `{入口}` 认不出 —— 只认 {入口们}。"
            f"规格 §2.2:一个入口上过了的限制,**在另一个入口上可能根本没有执行点**,"
            f"所以这里不给「通用」留口子")
    if 现在 is None:
        raise 解析不了("没有时钟 —— 回执年龄和回退有效期都要算,"
                    "**拿不到时间就算不了**(而算不了不等于「还新鲜」)")

    细 = {"入口": 入口}

    # ── ② 发布的那一版在不在 ─────────────────────────────────────
    if not 发布的:
        细["为什么没采用"] = "这个环境没有指到任何一版执行策略"
        return _回退或拒绝(本地回退, 现在, 细,
                       "配置里没有发布任何一版策略")

    if 发布的.get("entry_kind") != 入口:
        raise 解析不了(
            f"发布的那一版是给 `{发布的.get('entry_kind')}` 的,而这次是 `{入口}` —— "
            f"**不跨入口借用**。规格 §2.2:一边通过不得被另一边借用为验收证据")

    for k in ("id", "content_hash", "support_conditions", "limits"):
        if k not in 发布的:
            raise 解析不了(
                f"发布的那一版缺 `{k}` —— **不拿默认值顶**。"
                f"缺 `content_hash` 就没法核回执;缺 `support_conditions` 就不知道"
                f"该要求什么;而缺 `limits` 的一版策略,和一版「不限制」的,"
                f"**在那次运行上长得一模一样**")

    # ── ② 续:有发布 ≠ 已加载 ────────────────────────────────────
    if not 这个实例的回执:
        细["为什么没采用"] = ("**尚未确认加载**(规格 §9.2)—— "
                       "这一版发布了,而这台实例没有报过它加载了什么。"
                       "一条发了而没人加载的策略,和一条真在执行的,"
                       "在那个「已发布」上长得一模一样")
        return _回退或拒绝(本地回退, 现在, 细, "实例没有回执")

    回 = 这个实例的回执
    for k in ("execution_policy_version_id", "policy_hash", "loaded_at",
              "capability_map"):
        if k not in 回:
            raise 解析不了(f"回执缺 `{k}` —— 一份缺字段的回执,"
                        f"和一份完整的,**在「它回执过了」这件事上长得一样**")

    # ── ③ 回执指的是这一版吗;哈希对得上吗 ──────────────────────
    if 回["execution_policy_version_id"] != 发布的["id"]:
        细["为什么没采用"] = (
            f"实例回执的是 `{回['execution_policy_version_id']}`,"
            f"而环境指到的是 `{发布的['id']}` —— **它还没切过去**")
        return _回退或拒绝(本地回退, 现在, 细, "实例加载的是另一版")
    if 回["policy_hash"] != 发布的["content_hash"]:
        # ⚠️ 这一支**不回退**,直接拒绝 —— 它不是「还没加载」,是**冲突**。
        # 实例声称加载了这一版,而内容不是这一版的内容。
        细["冲突"] = {"实例报的哈希": 回["policy_hash"],
                   "这一版的哈希": 发布的["content_hash"],
                   "⚠️": "实例**自报**加载了这一版,而哈希不符 —— "
                         "规格 §10.3 要求服务端核验身份,"
                         "**不是「以回执为准」**。这种情况下回退也不安全:"
                         "我们不知道那台实例在跑什么"}
        return None, 拒绝启动, 细

    # ── ④ 回执有多老 ───────────────────────────────────────────
    年龄 = 现在 - 回["loaded_at"]
    细["回执年龄秒"] = 年龄
    if 年龄 < 0:
        raise 解析不了(f"回执的时间在未来({回['loaded_at']} > {现在})—— "
                    f"**不当成「很新」**:时钟不对的时候,"
                    f"一份未来的回执会永远不过期")
    if 年龄 > 回执最长年龄秒:
        细["陈旧"] = (f"回执 {年龄} 秒前的,超过 {回执最长年龄秒} 秒 —— "
                   f"**标陈旧**(规格 §10.2)。一份三天前的回执,"
                   f"和一份刚刚确认的,在那个「已加载」上长得一模一样")
        return _回退或拒绝(本地回退, 现在, 细, "实例回执已陈旧")

    # ── ⑤ 要求的硬限制,这台实例支持吗 ──────────────────────────
    要求 = list(发布的["support_conditions"] or [])
    能力 = dict(回["capability_map"] or {})
    不支持, 未核查 = [], []
    for 项 in 要求:
        v = 能力.get(项, 没核查过)
        if v is True:
            continue
        if v is False:
            不支持.append(项)
        else:
            # ⚠️ **未知不是支持。** 三态里的第三态落到这儿。
            未核查.append(项)
    if 不支持 or 未核查:
        细["硬限制对不上"] = {"不支持": 不支持, "没核查过": 未核查}
        细["⚠️"] = ("规格 §4.3:**所需硬限制不受支持时拒绝启动受影响任务,"
                  "不能回退为「无限制」**。而「没核查过」也算不过 ——"
                  "一个把「没核查过」当成「支持」的判定,和一个真核查过的,"
                  "**在那次放行上长得一模一样**")
        # ⚠️ **这里不走回退。** 回退的是「哪一版策略」,
        # 而这条问的是「这台实例做不做得到」—— 换一版旧策略也做不到。
        return None, 拒绝启动, 细

    细["对上了"] = {"版本": 发布的["id"], "哈希": 发布的["content_hash"],
                "回执年龄秒": 年龄, "核过的硬限制": 要求}
    return 发布的, 采用, 细


def _回退或拒绝(本地回退, 现在, 细, 为什么):
    """回退是一条**要显形**的路 —— 缺一样就不叫回退。"""
    细["触发回退的原因"] = 为什么
    if not 本地回退:
        细["⚠️"] = ("没有有效策略,也没有可用的本地回退 → **拒绝启动**。"
                  "规格 §4.3:**不能回退为「无限制」**;"
                  "配置服务不可用**不等于额度可以清零**")
        return None, 拒绝启动, 细

    缺 = [k for k in ("id", "limits", "验证于", "有效到", "为什么回退")
         if k not in 本地回退]
    if 缺:
        # ⚠️ 规格 §4.3 要求回退时**展示回退版本、年龄、原因及有效期**。
        # 缺任何一样,页面上就说不出「现在在跑哪一版、多老、为什么」——
        # 而那种状态和「正常采用」在界面上长得一模一样。
        细["⚠️"] = (f"本地回退缺 {缺} —— **不叫回退,叫不知道在跑哪一版**。"
                  f"规格 §4.3 要求展示回退版本、年龄、原因及有效期")
        return None, 拒绝启动, 细

    if not (现在 < 本地回退["有效到"]):
        细["⚠️"] = (f"本地回退自己过期了(有效到 {本地回退['有效到']},"
                  f"现在 {现在})→ **拒绝启动**,不是继续用。"
                  f"**严格小于** —— 边界上偏保守那一边")
        return None, 拒绝启动, 细

    细["回退用的"] = {
        "版本": 本地回退["id"],
        "验证于": 本地回退["验证于"],
        "年龄秒": 现在 - 本地回退["验证于"],
        "有效到": 本地回退["有效到"],
        "为什么回退": 本地回退["为什么回退"],
        "⚠️": "**这四样必须显示在页面上**(规格 §4.3)—— "
              "一次静默回退,和一次正常采用,在界面上长得一模一样"}
    return 本地回退, 回退, 细
