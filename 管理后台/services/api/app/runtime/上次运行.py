#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""编辑器「上次运行」页签(工作流一期第三件,11-15;照 Dify 面板的「设置 / 上次运行」两个页签)。

这一步上次收到了什么、交出了什么、什么状态、花了多久、是整条试运行还是单独测这一步。
原来面板上那段「上次」只认**这一页里刚跑过的那次** —— 刷新页面就没了,从别处跑的也看不到。

## 谁能看、看到什么(用户 11-15 21:4x 拍)
**和运行详情同一权限**(查看有权配置);有「查看敏感输入」授权才看原文,没有只给形状 —— 跟运行详情一样。
**原文里的手机号一律只露后四位**:编辑流程的人排查要看「这一步拿到的号对不对」,后四位够认人,
完整号码不该因为有人在改流程就摊在面板上。

这个模块**不碰数据库**(和校验器同一条规矩):接口查好行交进来,这里只整理和打码 —— 夹具测试才跑得起来。
"""
import re

# 和 redact.py 的手机号检测同一个锚定写法:前后不许紧挨数字、小数点或字母(订单号 A13912345678X 不是手机号)
_手机号 = re.compile(r"(?<![\dA-Za-z.])(1[3-9]\d{5})(\d{4})(?![\dA-Za-z.])")
# 带空格 / 连字符的写法(138 1234 5678)也认 —— 只认整串数字的话,换个写法就漏
_手机号分隔 = re.compile(r"(?<![\d.])(1[3-9]\d(?:[\s\-·—]\d{4}))[\s\-·—](\d{4})(?![\d.])")


def 打码(值):
    """把值里的手机号换成只露后四位(`*******5678`)。→ (新值, 打了几处)。值可以是 str / dict / list,其余原样。"""
    计 = [0]

    def _换(m):
        计[0] += 1
        return "*" * 7 + m.group(2)

    def _走(v):
        if isinstance(v, str):
            return _手机号分隔.sub(_换, _手机号.sub(_换, v))
        if isinstance(v, dict):
            return {k: _走(x) for k, x in v.items()}
        if isinstance(v, list):
            return [_走(x) for x in v]
        return v
    return _走(值), 计[0]


来源说法 = {"graph_draft": "整条试运行", "step_test": "单独测这一步", "workflow_version": "跑这一版"}


def 整理(步, 运行, *, 看原文, 形状, 解析):
    """一行步骤记录 + 它所在的那次运行 → 页签要的一包。

    `形状(v)` 是运行详情没授权时用的那个(只给有哪些项、各多长);`解析(v)` 把库里存的 json 文本还原。
    有授权:原文 → 打码;没授权:形状(形状里本来就没有值,不用再打码)。
    错误细节里可能带着「按默认值继续」顶上的值(11-15),一样按这条规矩处理。
    """
    if 步 is None:
        return {"有记录": False, "说法": "这一步还没有跑过。点「试运行」跑整条流程,或者用「单独测这一步」,结果会出现在这里"}
    打了 = 0

    def _给(v):
        nonlocal 打了
        if v is None:
            return None
        if not 看原文:
            return 形状(v)
        x, n = 打码(解析(v))
        打了 += n
        return x
    来 = (运行.get("definition_ref") or {}) if 运行 else {}
    起, 止 = 步.get("started_at"), 步.get("ended_at")
    包 = {
        "有记录": True,
        "运行": 运行.get("id") if 运行 else None,
        "来源": 来源说法.get(来.get("kind"), "其他运行"),
        "跑法": 来.get("跑法") or "正常",
        "状态": 步.get("status"),
        "按默认值继续": ((步.get("error_detail") or {}) if isinstance(步.get("error_detail"), dict) else {}).get("处理") == "按默认值继续",
        "错误码": 步.get("error_code"),
        "错误细节": _给(步.get("error_detail")),
        "尝试": 步.get("attempt"),
        "输入": _给(步.get("input_ref")),
        "输出": _给(步.get("output_ref")),
        "时间": (止 or 起).isoformat() if (止 or 起) else None,
        "耗时毫秒": int((止 - 起).total_seconds() * 1000) if 起 and 止 else None,
        "看得到原文": bool(看原文),
    }
    if 看原文:
        包["打码了几处手机号"] = 打了
        包["打码说明"] = "原文里的手机号只露后四位(用户 11-15 拍);要看完整号码去顾客档案"
    else:
        包["说明"] = "看原文要「查看敏感输入/独立测试答案」专项授权;这里只给形状(有哪些项、各多长)"
    return 包
