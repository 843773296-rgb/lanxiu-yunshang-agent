#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""实例报上来的回执**可信吗** —— 纯逻辑,零 IO。规格 §10.3 / §4.2 / §10.2。

## 它在链路里的位置

    草稿已保存 ──冻结──▶ 版本已发布 ──回执──▶ 实例已加载 ──▶ 本次运行已采用
                                      ↑ 这儿

`策略冻结.py` 管前一步,`策略解析.py` 管后两步。这一条管**收回执时的核验**。

## 规格原话

> 「回报加载与采用 | 实例/运行上报入口 | 策略 hash、运行器版本、覆盖矩阵;
> **服务端核验身份**」(§10.3)
> 「**任一客户端传入的 `project_id`、额度和动作标识都须经服务端身份与
> 上下文核验**」(§10.3 末)

## 它防的是哪一件事

实例说「我加载了 epv_7」。而**它说的话不等于事实**:

> **一条「我加载了这一版」而内容其实不是这一版的回执,
> 和一条真实的回执,在那张「实例已加载」的表上长得一模一样。**

而后果具体:`策略解析.py` 会拿这条回执放行任务,
以为那台实例在按 epv_7 的上限执行 —— 而它其实在按别的东西执行,
**或者什么都没在执行**。

## 五条判据

### ① 哈希对不上是**冲突**,不是「以回执为准」

这是最要紧的一条。实例自报加载了某一版而哈希不符,有两种可能:
它拿到的是旧文件,或者它在撒谎 —— 而**两种都不能存**。
> 一个「存下来再说」的实现,和一个拒绝的,
> **在那次 200 响应上长得一模一样** —— 而前者在表里留下一条假事实,
> 后面所有读它的人都会相信。

### ② `project_id` 要核,**不信客户端传的**

规格 §10.3 末那句点名了它。而这条在这个仓库里有先例:
`capability_connections` 那边踩过「凭名字猜父表」,
而跨项目越权是比那个更贵的一类。

### ③ 能力矩阵是**三态**的,而「没报」不是「不支持」

`capability_map` 里每一项:`True` / `False` / **没出现**。
没出现 = 没核查过。规格 §4.3 要求所需硬限制不受支持时拒绝启动,
而**未知不是支持**,也**不是不支持** —— 它要单独报出来,
因为这两件事在界面上该显示不同的话。
> 一个把「没报」填成 `False` 的实现,和一个真的报了不支持的,
> **在那张能力表上长得一模一样** —— 而前者会让人去查「为什么实例不支持」,
> 实际上实例从没被问过这件事。

### ④ `loaded_at` 由**服务端**盖,不收客户端给的

实例的时钟可能不对。而 `loaded_at` 是算回执年龄的依据
(规格 §10.2「过期回执标陈旧」)——
> 一份时钟快了一天的实例报上来的回执,和一份刚刚确认的,
> **在那个「已加载」上长得一模一样**,而它会永远不过期。
所以这里**只校验「客户端别给」**,真正的时间由调用方(API 层)盖。

### ⑤ 回执是**只追加**的,重复回执是正常事件

规格 §10.2:「同一实例**定期更新**」。同一个实例反复回执同一个哈希,
是「它还在用这一版」被确认了很多次 —— **不是重复,不要去重**。
> 给它加幂等键的话,「它还在用这一版」这件事就只会被记一次,
> 而**第二天它还在不在用,表上看不出来**。

## ⚠️ 一个**本期没堵上**的缺口,写在这儿而不是假装它安全

`instance_ref` 是**客户端给的**,而这一版**没有实例凭据机制** ——
所以任何有「上报回执」权限的调用方,都能以任何 `instance_ref` 的名义回执。

规格 §10.3 要求核验的是 `project_id` 和动作标识,**没有要求实例自证身份**,
本期也没有建实例凭据的工作项。所以这不是漏做,是**范围之外** ——
但它必须被看见:

> **一条被冒名顶替的回执,和一条真实的,在那张表上长得一模一样。**

真要堵,得给实例发凭据并让 `instance_ref` 从凭据推导(而不是从 body 读)。
登记在 `exec_limits_report` 的「实例回执」那一条上,别让它消失在一个绿勾里。

## 它不做什么

- **不写库。** 返回「可以插进 `policy_instance_receipts` 的 dict」。
- **不判这一版该不该被加载。** 那是 `策略解析.py` 的事(它还要算年龄)。
- **不管速率。** 同一实例一秒回执一百次是速率问题,不是这里的判据。
"""

没核查过 = "没核查过"


class 回执不可信(Exception):
    """这条回执不能存 —— 当场抛。

    ⚠️ 默认处置**不是**「先存下来再说」。
    一条假事实存进「实例已加载」之后,`策略解析` 会拿它放行任务,
    而**后面所有读它的人都会相信它**。
    """


def 核(*, 这一版, 实例报的, 服务端的project_id, 现在):
    """返回**可以插进 `policy_instance_receipts` 的 dict**。

    `这一版`:库里那一行 `execution_policy_versions`,要有
        `id` / `project_id` / `content_hash` / `entry_kind` /
        `support_conditions`。
    `实例报的`:请求体,要有 `instance_ref` / `execution_policy_version_id` /
        `policy_hash` / `runner_version`;可选 `sdk_version` / `capability_map`。
    `现在`:**服务端的时间**(注入的)—— 见文件头第 ④ 条。
    """
    报 = dict(实例报的 or {})

    # ── ④ loaded_at 不收客户端给的 ──────────────────────────────
    for 禁 in ("loaded_at", "created_at"):
        if 禁 in 报:
            raise 回执不可信(
                f"请求体里带了 `{禁}` —— **服务端不收它**。"
                f"实例的时钟可能不对,而这一列是算回执年龄的依据"
                f"(规格 §10.2「过期回执标陈旧」):"
                f"一份时钟快了一天的实例报上来的回执,和一份刚刚确认的,"
                f"**在那个「已加载」上长得一模一样**,而它会永远不过期")

    缺 = [k for k in ("instance_ref", "execution_policy_version_id",
                     "policy_hash", "runner_version") if not 报.get(k)]
    if 缺:
        raise 回执不可信(
            f"回执缺 {缺} —— **不拿默认值顶**。"
            f"一份缺字段的回执,和一份完整的,"
            f"**在「它回执过了」这件事上长得一模一样**,"
            f"而页面会把它算进「实例回执覆盖数」(规格 §9.2)")

    # ── ② project_id 要核,不信客户端传的 ────────────────────────
    if 这一版.get("project_id") != 服务端的project_id:
        raise 回执不可信(
            f"这一版属于项目 {这一版.get('project_id')!r},"
            f"而请求的身份在 {服务端的project_id!r} —— **跨项目**。"
            f"规格 §10.3:任一客户端传入的 project_id 都须经服务端核验")

    if 报["execution_policy_version_id"] != 这一版.get("id"):
        raise 回执不可信(
            f"回执说的是 `{报['execution_policy_version_id']}`,"
            f"而取出来的那一版是 `{这一版.get('id')}` —— "
            f"**调用方把两者弄混了**,不是「实例还没切过去」"
            f"(后者由 `策略解析` 判,而且它走的是回退不是拒绝)")

    # ── ① 哈希对不上 → 冲突 ─────────────────────────────────────
    if 报["policy_hash"] != 这一版.get("content_hash"):
        raise 回执不可信(
            f"**哈希对不上**:实例报 {报['policy_hash']!r},"
            f"这一版是 {这一版.get('content_hash')!r} —— "
            f"这是**冲突**,不是「以回执为准」(规格 §10.3 服务端核验身份)。"
            f"两种可能:它拿到的是旧文件,或者它在撒谎 —— **两种都不能存**。"
            f"> 一个「存下来再说」的实现,和一个拒绝的,"
            f"**在那次 200 响应上长得一模一样**,"
            f"而前者在表里留下一条假事实,后面所有读它的人都会相信")

    # ── ③ 能力矩阵三态 ──────────────────────────────────────────
    要求 = list(这一版.get("support_conditions") or [])
    报的能力 = 报.get("capability_map")
    if 报的能力 is None:
        raise 回执不可信(
            "回执没带 `capability_map` —— **`{}` 和没带是两件事**:"
            "`{}` 是「我一项都不支持」,没带是「没人问过我」。"
            "而规格 §4.3 要拿它判「所需硬限制受不受支持」,"
            "拿不到就判不了")
    if not isinstance(报的能力, dict):
        raise 回执不可信(f"`capability_map` 得是个 dict,"
                    f"现在是 {type(报的能力).__name__}")

    支持, 不支持, 未核查 = [], [], []
    for 项 in 要求:
        v = 报的能力.get(项, 没核查过)
        if v is True:
            支持.append(项)
        elif v is False:
            不支持.append(项)
        else:
            # ⚠️ **不折成 False。** 「没报」和「报了不支持」要分开 ——
            # 否则有人会去查「为什么实例不支持」,而实例从没被问过这件事。
            未核查.append(项)

    # ⚠️ 这里**不拒绝**不支持或未核查的 —— 收回执是「记下它说了什么」,
    # 而「这台实例能不能跑这一版」是 `策略解析.py` 在**起任务时**判的。
    # 把它提前到收回执时拒绝,会让那台实例**连回执都发不出来**,
    # 于是页面上显示「尚未确认加载」——
    # > 而「没装」和「装了但能力不够」在那句「尚未确认加载」上长得一样,
    # > 是两种完全不同的下一步(去装 vs 去换机器/改策略)。
    return {
        "instance_ref": 报["instance_ref"],
        "execution_policy_version_id": 这一版["id"],
        "policy_hash": 这一版["content_hash"],   # 用**库里那一版的**,不是报上来的
        "runner_version": 报["runner_version"],
        "sdk_version": 报.get("sdk_version"),
        # 原样存实例报的那份 —— 它是**那一刻的事实**,
        # 不补齐、不折叠(和 `cache_capability_snapshots` 同一个道理)。
        "capability_map": 报的能力,
        "loaded_at": 现在,
        # ↓ 给调用方(和页面)用的,不进库那几列
        "_核出来的": {"支持": 支持, "不支持": 不支持, "没核查过": 未核查,
                  "怎么读": ("这三栏**各自是各自** —— 「没核查过」不是「不支持」。"
                           "能不能跑这一版由 `策略解析` 在起任务时判,"
                           "**不在收回执时拒绝**:否则那台实例连回执都发不出来,"
                           "页面上显示「尚未确认加载」,"
                           "而「没装」和「装了但能力不够」是两种不同的下一步")},
    }


# `回执够新吗` 的原因码。**三种,不是两种** —— 「陈旧」和「时间在未来」
# 要分开,因为两边的**处置不同**:
#   · 页面上两种都显示「不算已加载」
#   · `策略解析` 对「陈旧」走回退,对「时间在未来」**抛** ——
#     后者说明时钟有问题,而那时候回退也不可信
# 而判据(阈值、未来算不算新)**只有这一份**。
新鲜 = "新鲜"
陈旧 = "陈旧"
时间在未来 = "时间在未来"


def 回执够新吗(*, 回执的loaded_at, 现在, 最长年龄秒=900):
    """返回 `(够不够新, 原因码, 话)` —— 规格 §10.2「过期回执标陈旧」。

    ⚠️ **判据只有这一份**,而两个调用方的处置不同:
    页面(「实例回执覆盖数」那一栏)两种都算「不算已加载」;
    `策略解析` 对 `陈旧` 走回退、对 `时间在未来` 抛。

    > 这个函数第一版写完之后,`策略解析` 里**还有一份一样的判定** ——
    > 而我在上一版的注释里恰好写着「两处各写一遍迟早分叉」。
    > **一句写在注释里的「要共用」,和一处真的共用了的,
    > 在那段注释上长得一模一样。**
    """
    年龄 = 现在 - 回执的loaded_at
    if 年龄 < 0:
        return False, 时间在未来, (
            f"回执的时间在未来({回执的loaded_at} > {现在})—— "
            f"**不当成「很新」**:时钟不对的时候,"
            f"一份未来的回执会永远不过期")
    if 年龄 > 最长年龄秒:
        return False, 陈旧, (
            f"回执 {年龄} 秒前的,超过 {最长年龄秒} 秒 → **陈旧**。"
            f"一份三天前的回执,和一份刚刚确认的,"
            f"在那个「已加载」上长得一模一样")
    return True, 新鲜, f"回执 {年龄} 秒前的,还新鲜"
