#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""**这是哪一件事** —— 额度算在谁头上。纯逻辑,零 IO。规格 §5.1 + §D.1。

## 业务拍板(2026-10-04,用户选的)

> **自动按客户切 + 顾问也能手动开新。**

    14:00  客户 C1001 问婚服         → 自动开 #1
    14:20  「换成整幅刺绣再算一次」   → **还是 #1**(旧成本/工期失效要重查,
                                        但这不是一件新事,不给新额度)
    15:10  客户 C1002 进店           → 自动开 #2
    15:40  回头接着聊 C1001          → **回到 #1**,用它**剩下的**额度
    16:00  还是 C1001,但问售后返修   → 顾问手动点「新任务」→ 开 #3

拍板时他自己点出了要定的那条:「**自动和手动打架时谁赢**」。
答案在规格里,不在偏好里 —— 见下面第 ③ 条。

## 它防的是哪一族 bug

规格 §5.1:「用户发起独立的新任务才能分配新任务预算。
**执行器不能为了继续原任务自行换 `task_id`**。」
规格 §D.1:「模型不能……**通过改任务编号获得新的配额**。」
验收用例 C48:「无进展规则触发后,模型声称『我有进展』——
没有结构化证据不复位;**无法自主加额度**。」

这三条说的是同一件事:

> **一个「模型声称这是新任务」而被当真的,和一个顾问真的开了新任务的,
> 在那个新任务编号上长得一模一样。**

额度耗尽是**会疼的**,所以一定会有一股力气想绕过它 ——
而绕过的最便宜方式就是换个任务编号。

## 五条判据

### ① 来路必须是**服务端可核验**的,模型说的不算

只收两种来路:`顾问界面动作`(一次带身份的请求)和
`业务对象变化`(客户/订单号来自登录会话和业务库)。
收到别的(尤其是「模型自述」)→ **抛**,不是「那就当新任务」。
> 一个把模型的话当输入的判定,和一个只认业务库的,
> **在正常情况下长得一模一样** —— 差别只在有人想绕的时候出现。

### ② 自动切的输入是**模型改不了的东西**

客户 ID 和订单号来自登录会话 + 业务库。模型能改的只有它说的话,
而它说的话不是这个函数的输入。

### ③ 打架时**手动赢**,而且手动**不是永久的**

顾问手动开新是人的意图声明,有人负责;自动切只是启发式。所以手动赢。
**但手动开出来的任务不压制后续的自动切** —— 否则顾问点一次新任务,
之后换十个客户都算同一件事,额度被一份顶着,他问什么都被拦。
> 「手动赢」和「手动永久赢」差一个字,而后者会把顾问锁死。

### ④ 回头时回到**那个业务对象上最近活动的那个任务**

同一个客户可能有好几件事(#1 婚服、#3 售后返修)。回头接着聊,
回到的是最近活动的那一个,**不开新的** —— 开新的等于「回头看一眼
就刷一份额度」。

### ⑤ 客户 ID 拿不到 → **抛**,不猜

规格 §17.1:「无法确定则绕过」。拿不到业务对象就判不了这是哪件事,
而随便给一个新任务正好是最贵的那个错法。
> 一个「拿不到就开新任务」的实现,和一个真判出来是新任务的,
> **在那个新编号上长得一模一样**。

## 它不做什么

- **不读库、不查额度。** 已有的任务由调用方取来;够不够用是预算账本的事。
- **不鉴权。** 顾问能不能看这个客户,由调用方在取数时管。
- **不决定额度多少。** 它只回答「算在谁头上」。
- **放在管理后台这边,而两条入口共用它。** 规格 §4.1:策略定义维护一份,
  门店 V3 和后台 Loop **分别实现适配层**。判定逻辑共享,适配分开 ——
  V3 接的时候照抄这一份而不是重写一份,**两份判定迟早会分叉**,
  而分叉时两边各自都是绿的。
"""

# 来路。**只有这两种**,而且都在服务端可核验。
界面动作 = "顾问界面动作"      # 一次带身份的请求 —— 人点的,有人负责
对象变化 = "业务对象变化"      # 客户/订单号来自登录会话和业务库
来路们 = (界面动作, 对象变化)

# 为什么算一件新事 / 为什么不算
新建_手动 = "顾问手动开了新任务"
新建_换对象 = "业务对象变了(换客户或换订单)"
沿用_同对象 = "业务对象没变 —— 回到它上面最近活动的那件事"
沿用_改方案 = "同一个对象改了方案 —— 旧证据失效要重查,而这不是一件新事"


class 判不了(Exception):
    """输入本身讲不通 —— 当场抛,**不开一个新任务**。

    ⚠️ 这个异常的默认处置**不是**「那就当新任务」。
    开新任务 = 发一份新额度,而这正是绕过额度最便宜的方式。
    """


def 这是哪件事(*, 来路, 顾问工号, 客户id, 订单号=None,
            会话里的当前任务=None, 这个对象上的任务们=()):
    """返回 `(任务id或 None, 为什么, 细节)`。`None` 表示**要新建一件事**。

    `这个对象上的任务们`:同一个 (客户, 订单) 上已经有的任务,
    按**最近活动时间倒序** —— 第一个是最近的。
    每项要有 `id` 和 `最近活动于`。

    ⚠️ **顺序是有意的**:来路核验 → 手动 → 换对象 → 回头沿用。
    先核来路而不是先看手动,因为**一个伪造的「手动」比没有手动更危险** ——
    它带着「有人负责」的外观,而其实没有人按过那个按钮。
    """
    # ── ① 来路必须可核验 ─────────────────────────────────────────
    if 来路 not in 来路们:
        raise 判不了(
            f"来路 `{来路}` 不收 —— **只认 {来路们}**。"
            f"尤其是模型说的话不算来路:"
            f"一个把模型自述当输入的判定,和一个只认业务库的,"
            f"在正常情况下长得一模一样,差别只在有人想绕的时候出现"
            f"(规格 §D.1、C48)")

    # ── ⑤ 业务对象拿不到 → 抛,**不开新任务** ──────────────────────
    if not 顾问工号:
        raise 判不了("没有顾问工号 —— 额度要算在人头上,"
                   "**拿不到就判不了**,而不是算在一个新任务上")
    if not 客户id:
        raise 判不了(
            "没有客户 ID —— **不给它开一个新任务**。"
            "一个「拿不到就开新任务」的实现,和一个真判出来是新任务的,"
            "在那个新编号上长得一模一样,而前者等于把额度闸交给了缺数据")

    细 = {"顾问工号": 顾问工号, "客户id": 客户id, "订单号": 订单号}

    # ── ③ 手动赢(而且不永久)──────────────────────────────────────
    if 来路 == 界面动作:
        细["⚠️"] = ("**手动赢,但不压制后续的自动切** —— "
                   "否则顾问点一次新任务,之后换十个客户都算同一件事,"
                   "额度被一份顶着,他问什么都被拦。"
                   "「手动赢」和「手动永久赢」差一个字,后者会把他锁死")
        return None, 新建_手动, 细

    # 到这儿来路一定是「业务对象变化」。
    # ── ④ 回头:这个对象上已经有事了吗 ───────────────────────────
    们 = list(这个对象上的任务们)
    if 们:
        for t in 们:
            if "id" not in t or "最近活动于" not in t:
                raise 判不了(
                    f"任务项缺 `id` 或 `最近活动于`:{t} —— "
                    f"**不拿第一个顶**。排序错了的话会回到一件更早的事上,"
                    f"而那件事的额度可能已经用光,表现成「他什么都问不了」,"
                    f"却查不出是排序错了")
        # ⚠️ **自己排,不信调用方说的「已经倒序了」。**
        # 一个没排序而恰好有序的列表,和一个真排过的,在正常数据上长得一样。
        最近 = max(们, key=lambda t: t["最近活动于"])
        细["这个对象上一共有几件事"] = len(们)
        细["挑的是"] = 最近["最近活动于"]
        if len(们) > 1:
            细["怎么读"] = ("同一个客户可以有好几件事(婚服 / 售后返修)—— "
                         "回头接着聊回到**最近活动的那一个**,"
                         "**不开新的**:开新的等于回头看一眼就刷一份额度")
        return 最近["id"], 沿用_同对象, 细

    # ── ② 这个对象上一件事都没有 → 新建 ─────────────────────────
    细["⚠️"] = ("输入里的客户/订单来自**登录会话和业务库**,模型改不了它们 —— "
               "模型能改的只有它说的话,而它说的话不是这个函数的输入")
    return None, 新建_换对象, 细


def 改了方案算新事吗(*, 原方案版本, 新方案版本):
    """局部刺绣改成整幅 —— **旧结果失效,而这不是一件新事**。

    规格 §7.1:「候选版本变化,旧成本/工期结果失效,允许重新查询」。
    规格 C12 验这一条。

    返回 `(算不算新事, 旧证据还能用吗, 为什么)`。

    ⚠️ 两件事要分开:**「要重查」不等于「要新额度」**。
    > 一个把「证据失效」当成「新任务」的实现,和一个真开了新任务的,
    > **在那个新编号上长得一模一样** —— 而前者等于
    > 「顾问每改一次方案就刷一份额度」,改方案是最常见的操作。
    """
    变了 = 原方案版本 != 新方案版本
    return False, (not 变了), (
        沿用_改方案 if 变了 else "方案没变,旧证据继续有效")
