"""这一次运行到底跑的是真模型还是 mock —— **一处解析,逐项记账**。

## 为什么要这一份(外部审阅 §5.4)

> 连接探测、Prompt 单次运行、Workflow 的 LLM 节点、后台 Agent Loop、门店 V3,
> 是不同入口。**某个入口支持真实模型,不等于其他入口也支持。**

2026-10-03 实测:后台三个执行入口(Prompt 调试 / Workflow 的 LLM 节点 /
后台 Agent Loop)**全都挂着 mock 适配器**,而同一个服务里
`connections_api._真探` 已经能真发请求了。
于是「连接探测成功」看起来像「运行器接通了」——**而它们是两件事**。

## 这一份守的三句话

① **只有明确选择模拟运行才使用 mock。**
   `MODEL_ADAPTER=mock` 是一个**明确的选择**(写在环境里、启动自检看得见);
   而「代码里硬写了一个 mock 适配器」不是选择,是**默认**。
   > 一个默认是 mock 的系统,和一个选择了 mock 的系统,
   > **在那次运行的结果上长得一模一样** —— 而前者没人决定过。

② **真实调用失败不能静默降级为 mock。**
   降级之后那次运行**照样跑完、照样出一份答案**,而那份答案
   和真模型给的在数据形状上一样。
   > 一次悄悄换了模型的运行,比一次失败的运行难查得多。
   所以这里只有「跑真的」和「明确选了 mock」两条路,**没有第三条**。

③ **混合运行要逐项列替身,不许整体标成「真实」。**
   「真实模型 + 模拟工具」是合法的测试姿势(审阅原话),
   但它**必须逐项显示替换清单** —— 否则一次「模型真、工具假」的运行
   会被读成端到端真实联调。

## 它不负责什么

- **不判业务权限。** 权限在动作发生时校验,和执行模式无关。
- **不选模型型号。** 那是冻结的连接版本说的事。
- **不保证真实调用会成功。** 它只保证失败时**不偷偷换一个能成功的东西**。
"""
import os
import sys

_这儿 = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(_这儿))
import runtime_cfg as CFG  # noqa: E402

真 = "live"
假 = "mock"


class 不能跑(Exception):
    """没法按要求跑 —— **带上具体缺什么**,不退回 mock。

    错误里**不许出现凭据**(这个仓库的红线):只说「哪个定位符解析不了」,
    不说它解析出了什么。
    """

    def __init__(self, 码, 细节):
        self.码 = 码
        self.细节 = 细节
        super().__init__(f"{码}: {细节}")


def 定(*, 要模型=True, 连接=None, 允许mock=None):
    """定这一次的执行模式。返回 `(模式, 替身清单)`。

    `连接` 是**冻结的连接版本**那一行(dict),没有就给 None。
    `允许mock` 显式传 True/False 时优先;不传时按 `MODEL_ADAPTER` 决定 ——
    也就是**按那个明确的选择**,而不是按代码里有没有 mock 适配器。

    ⚠️ **三条路,没有第四条:**

    | 情况 | 结果 |
    |---|---|
    | 选了 mock(`MODEL_ADAPTER=mock` 或 `允许mock=True`) | 跑 mock,**记一条替身** |
    | 要真跑、而且连接齐 | 跑真的,替身清单为空 |
    | 要真跑、而连接缺或不支持 | **抛 `不能跑`** —— 不退回 mock |
    """
    选了mock = CFG.模型是mock() if 允许mock is None else bool(允许mock)
    替身 = []
    if not 要模型:
        return 真, 替身
    if 选了mock:
        替身.append({
            "哪一样": "模型",
            "换成了": "mock 适配器",
            "为什么": ("明确选的:MODEL_ADAPTER=mock" if 允许mock is None
                      else "调用方显式要求模拟运行"),
            "⚠️": "**它返回的是编出来的答案**,不许计入真实评测或发布",
        })
        return 假, 替身
    # 要真跑 —— 下面每一条缺失都**抛**,不退回 mock
    if not 连接:
        raise 不能跑("NO_MODEL_CONNECTION",
                   "要真跑模型,而这次运行**没有冻结的模型连接** —— "
                   "先在模型连接页建一个并探测过,再把它绑进这个应用版本。"
                   "**不退回 mock**:mock 会照样出一份答案,"
                   "而那份答案和真模型给的在数据形状上一样")
    缺 = [k for k in ("endpoint", "secret_ref") if not (连接 or {}).get(k)]
    if 缺:
        raise 不能跑("MODEL_CONNECTION_INCOMPLETE",
                   f"冻结的连接里缺 {缺} —— 这个连接配不全,真跑不了。"
                   f"**不退回 mock**")
    if not (连接 or {}).get("探过吗"):
        # ⚠️ **「探过」和「配了」是两件事。** 10-03 在另一个闸上栽过同一处:
        # 提示写着「没探过的和没给的长得一样」,而代码只检查了「连接存在」。
        raise 不能跑("MODEL_CONNECTION_UNPROBED",
                   "这个连接**从没探测过** —— 没探过的和配错了的,"
                   "在「连接存在」这件事上长得一模一样。先探一次再绑")
    return 真, 替身


def 记一笔(模式, 替身, *, 入口):
    """给 `job_events` / span 用的那条留痕。**整体不许标成「真实」除非替身为空。**

    审阅 §5.4:「运行卡片按实际阶段显示模式;允许存在『真实模型 + 模拟工具』
    的测试,但**必须逐项显示替换清单**,不能将整个运行标为完全真实。」
    """
    混 = bool(替身) and 模式 == 真
    return {
        "入口": 入口,
        "execution_mode": 模式,
        "替身清单": 替身,
        "整体算真实吗": (模式 == 真 and not 替身),
        "怎么读": ("**整个运行是 mock** —— 答案是编出来的" if 模式 == 假 else
                 ("**混合运行**:模型是真的,下面列的那几样是替身 —— "
                  "别读成端到端真实联调" if 混 else
                  "真实运行:没有任何一样被替身代替")),
    }
