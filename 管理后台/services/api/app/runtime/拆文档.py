#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""**把几个切片拆成独立文档** —— 这个动作的判定,纯逻辑、零 IO、不写库。

业务 2026-10-07 拍的:**切片级权限不做**,要给某几段单独设权限就「拆成独立文档」。
那一拍省掉了一套切片级 ACL,代价是这个动作得判对 —— 下面每一条都在拦一个
「长得一模一样」。

## 这个动作**不是**改切片的归属

`chunks` 是**不可变**子对象,而且绑的是 `document_version_id`(不是文档)——
契约里那条注释写得很清楚:「片段绑的是文档版本,不是文档 —— 否则文档一改,
历史证据链就指向了新内容」。

所以拆 = **新建**一篇文档 + 它的第一个版本 + 把那几段的正文**复制**过去。
**原切片一条都不动。**

> 一次「改了 `chunk.document_version_id`」的拆分,和一次「新建复制」的,
> **在新文档的切片列表上长得一模一样** —— 而前者把已经建好的索引、
> 已经发生过的问答留下的证据链,一起指向了新内容。

## ⚠️ 头号坑:切片器版本必须**沿用**,不许读当前常量

索引构建那一步有道 `MIXED_CHUNKER_VERSION`,它是**整个知识库一起查**的
(`workers/worker.py`:`where d.knowledge_base_id = :kb`,所有文档的片段混在一起
比 `chunker_version`)。拆出来的文档若按**当前**代码常量重切一遍,而库里其余
文档还是 `seg-1` ——

> 一次「拆分做完了」和一次「拆分做完了、而这个知识库从此一个索引都建不出来」,
> **在拆完那一刻长得一模一样**。下一次重建才炸,而那时没人会把它
> 归因到三周前那次拆分。

所以:**复制正文,沿用源切片记着的版本号字面量。** 这两件事是同一件事 ——
只要不重切,版本号自然就是对的。

## ⚠️ 原文档怎么标:新建一个 revision,不动旧的

索引取的是**每篇文档 `max(revision)` 那一版**的片段。所以让原文档「不再提供
这几段」不需要什么排除区间 —— 新建一版、只含剩下的片段就够了,
旧版的片段留着(不可变、证据链完好),而索引只看最新版。

但那个新版的 `content_hash` 和 `source_info` 得说实话:

> `object_key` 指向的原始文件**没变**(它还含着已经拆走的那几段)。
> 一个「`content_hash` 没变而内容变了」的版本,
> **和一个真的没变的版本在那一列上长得一模一样** —— 而那一列的全部用处
> 就是回答「这份资料变没变」。

所以新版的 `content_hash` 要从**剩下这些片段**算,`source_info.存储` 要标成
派生而非解析 —— 否则下一个想「查看原文」的人会从 `object_key` 拿到完整原文件,
**含着他已经没权限的那几段**。

## ⚠️ 拆出来的权限必须**写死**,不许留空继承

`语料可见` 那边定的是:文档级空 = 继承知识库。而拆出来的文档可能落在
**另一个**知识库里 —— 那上限就换了一个。

> 一篇「继承了收紧后的权限」的新文档,和一篇「继承了另一个库的宽上限」的,
> **在那个空 `acl_override` 上长得一模一样**。

而且拆的目的是**收紧**:新文档的可见范围必须是**源文档当前有效范围的子集**。
放宽要拒,并且说清多出来的是谁。

## ⚠️ 拆完**还没生效** —— 欠一次重建索引

在役的索引是**快照**(`index_members` 固定了一批 `chunk_id`)。拆分改的是
`documents` / `document_versions` / `chunks`,而检索那条 SQL 只认
`im.index_build_id = :b`。

> 一次「权限已经收紧了」的拆分,和一次「拆了而在役索引还是旧快照」的,
> **在那张 documents 表上长得一模一样** —— 而那个人仍然检索得到他不该看的
> 那几段,直到下一次重建索引完成并切换。

所以这里**不返回「成功」,返回一份计划 + 一笔欠账**。叫 `计划` 而不叫
`结果`,是为了让调用方拿不到一个能当「做完了」用的东西。

## 它不做什么

- **不查库、不写库。** 两级 ACL、片段清单、目标库 ACL 全由调用方取来。
- **不算哈希。** 算哈希要有正文,这里只有 `text_hash` —— 它只说
  「拿哪些片段的哈希去算」,怎么算在落库那一层。
- **不管推理层。** 和 `语料可见` 同一条:这是召回层的权限。
"""
import os
import sys

_这儿 = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _这儿)
import 语料可见 as _KV

角色们 = _KV.角色们
判不了 = _KV.判不了


class 拆不了(判不了):
    """这个拆分请求本身讲不通 —— 当场抛。

    ⚠️ 继承 `语料可见.判不了`,所以调用方那一个 except 就能兜住两边;
    而**默认处置仍然不是「那就按原样拆」** —— 一个把「判不了」读成
    「照常拆」的接口,和一个真判过的,**在拆出来那篇文档上长得一模一样**。
    """


# `document_versions.source_info.存储` 的第三种取值。
# 前两种(对象存储键 / 仓库相对路径)都表示「`object_key` 解析得出这一版」,
# 而派生版**解析不出来** —— 原文件里还含着已经拆走的那几段。
派生自拆分 = "拆分派生"


def _片段们(片段, 哪儿):
    """把片段清单规范一遍。要的是 dict,至少有 `id` / `ordinal`。"""
    if not 片段:
        raise 拆不了(f"{哪儿}一个片段都没有 —— **不兜底成「那就全拆」**")
    出 = []
    见过 = set()
    for x in 片段:
        if not isinstance(x, dict):
            raise 拆不了(f"{哪儿}的片段得是 dict(至少有 id / ordinal),"
                      f"现在是 {type(x).__name__}")
        i = x.get("id")
        if i is None:
            raise 拆不了(f"{哪儿}有个片段没有 id —— 判不了它是哪一段")
        if i in 见过:
            # ⚠️ 重复的 id **当场抛**。忽略重复的话,「选了 3 段」会变成
            # 「拆走 2 段」,而两边数字都讲得通。
            raise 拆不了(f"{哪儿}的片段 id `{i}` 出现了两次 —— "
                      f"**不去重**:去重之后「选了 3 段」会变成「拆走 2 段」,"
                      f"而两个数字各自都讲得通")
        见过.add(i)
        if x.get("ordinal") is None:
            raise 拆不了(f"片段 `{i}` 没有 ordinal —— 拆出来的文档要重排序号,"
                      f"排不了")
        出.append(dict(x))
    return 出


def 版本们(片段):
    """这批片段是哪些 (切片器, 解析器) 版本切的。返回排好序的清单。

    ⚠️ **`None` 保留,不折叠成「和当前一样」。** 见 `chunks` 的契约注释:
    > 空不等于「和当前一样」—— 填错的版本号比空的更糟。
    """
    return sorted({(x.get("chunker_version"), x.get("parser_version"))
                   for x in 片段}, key=lambda t: (str(t[0]), str(t[1])))


def 定(*, 源文档片段, 要拆走的id们, 源知识库acl=None, 源文档acl=None,
       目标知识库acl=None, 新文档acl=None, 目标知识库id=None, 源知识库id=None):
    """这个拆分该怎么做。返回一份**计划**(dict),或者抛 `拆不了`。

    `源文档片段`   源文档**最新那一版**的全部片段(调用方按 max(revision) 取)
    `要拆走的id们` 选中要拆出去的片段 id
    `源/目标知识库acl`  两个库各自的 ACL(同一个库就传同一份)
    `源文档acl`    源文档的 `acl_override`
    `新文档acl`    想给拆出来那篇文档设的权限 —— **必填,不许留空**

    返回的键:
      `新文档`     要新建的文档该写什么(含 `acl_override` 的字面量)
      `新版本`     它的第一个版本该写什么
      `搬过去的片段` 按新 ordinal 排好的片段计划(**沿用原版本号**)
      `原文档新版本` 原文档要新建的那一版该写什么
      `原文档留下的片段` 新版里还剩哪些
      `欠账`       拆完**还没生效**的那些事 —— 非空
    """
    全部 = _片段们(源文档片段, "源文档")
    按id = {x["id"] for x in 全部}
    要拆 = list(要拆走的id们 or [])
    if not 要拆:
        raise 拆不了("没说要拆走哪几段 —— **不兜底成「那就一段都不拆」**:"
                  "一次「什么都没选」和一次「拆了个空文档出来」,"
                  "在那次调用上长得一模一样")
    重 = [i for i in set(要拆) if 要拆.count(i) > 1]
    if 重:
        raise 拆不了(f"要拆的 id 里 {sorted(重)} 写了两次 —— **不去重**")
    野 = [i for i in 要拆 if i not in 按id]
    if 野:
        # ⚠️ 不属于这篇文档的 id **当场抛,不跳过**。跳过的话一次
        # 「选错了文档」的拆分会**拆出一篇少了几段的文档**,而它看起来正常。
        raise 拆不了(
            f"片段 {sorted(map(str, 野))} 不在这篇文档最新那一版里 —— "
            f"**不跳过**:跳过的话一次「选错了文档」的拆分会拆出一篇"
            f"少了几段的新文档,而它看起来完全正常。"
            f"(也可能是选了**旧版本**的片段 —— 索引只认 max(revision) 那一版)")
    拆集 = set(要拆)
    留下 = [x for x in 全部 if x["id"] not in 拆集]
    if not 留下:
        # ⚠️ 整篇都拆走 **不是拆分**。
        raise 拆不了(
            f"这篇文档一共 {len(全部)} 段,你要把**全部**拆走 —— "
            f"那不是拆分,是改这篇文档本身的权限(`documents.acl_override`)。"
            f"照拆会留下一篇 0 段的空文档,而**一篇空文档和一篇没被索引到的"
            f"文档在界面上长得一模一样**")

    走 = [x for x in 全部 if x["id"] in 拆集]

    # ── ① 新文档的权限:必填、写死、且必须是源文档**有效范围**的子集 ──────
    if 新文档acl is None:
        raise 拆不了(
            "没说拆出来那篇文档给谁看 —— **不许留空继承**。"
            "空的 `acl_override` 在 `语料可见` 那边是「继承知识库」,"
            "而拆出来的文档可能落在另一个库里,那上限就换了一个:"
            "一篇「继承了收紧后权限」的新文档和一篇「继承了另一个库宽上限」的,"
            "**在那个空 acl_override 上长得一模一样**")
    源可见, 源话 = _KV.定(知识库acl=源知识库acl, 文档acl=源文档acl)
    # 目标库这一级先各自判,**错要分得开** —— 被目标库卡住和被源文档卡住
    # 是两件事,前者去改目标库,后者说明这次拆分想放宽。
    新可见, 新话 = _KV.定(知识库acl=目标知识库acl, 文档acl=新文档acl)
    多 = 新可见 - 源可见
    if 多:
        raise 拆不了(
            f"拆出来的文档想让 {sorted(新可见)} 看到,而**源文档现在的有效范围"
            f"只到 {sorted(源可见)}** —— 多出来的 {sorted(多)} 原本看不到这几段。"
            f"拆分是为了**收紧**,它不该成为一条放宽的路子。"
            f"(源:{源话};新:{新话})"
            f"要让 {sorted(多)} 看到,得先改源文档那一级,**而那是另一个动作**")

    # ── ② 切片器版本:沿用,不重切 ────────────────────────────────────
    走的版本 = 版本们(走)
    留的版本 = 版本们(留下)
    欠账 = []
    if len(走的版本) > 1:
        # 不抛 —— 这个拆分仍然做得了,**只是做完那个库建不出索引**。
        # 抛了会让人无路可走(源文档本来就是混着切的),报出来才有的选。
        欠账.append(
            f"要拆走的这几段来自 {len(走的版本)} 种版本 {走的版本} —— "
            f"**拆出来的文档会是混着切的**,而索引构建那一步的 "
            f"`MIXED_CHUNKER_VERSION` 是整个知识库一起查的:这个库从此"
            f"一个索引都建不出来。先把源文档整篇重切成一个版本,再拆")

    # ── ③ 计划本身 ─────────────────────────────────────────────────
    搬 = [dict(源片段id=x["id"], 新ordinal=n,
               原ordinal=x["ordinal"],
               # ⚠️ **沿用**,不读当前常量 —— 见模块头「头号坑」。
               chunker_version=x.get("chunker_version"),
               parser_version=x.get("parser_version"),
               text_hash=x.get("text_hash"),
               section_path=x.get("section_path"),
               section_titles=x.get("section_titles"))
          for n, x in enumerate(sorted(走, key=lambda y: y["ordinal"]))]
    剩 = [dict(源片段id=x["id"], 新ordinal=n, 原ordinal=x["ordinal"],
               chunker_version=x.get("chunker_version"),
               parser_version=x.get("parser_version"),
               text_hash=x.get("text_hash"))
          for n, x in enumerate(sorted(留下, key=lambda y: y["ordinal"]))]

    欠账.append(
        "**拆完还没生效。** 在役索引是快照(`index_members` 固定了一批 "
        "chunk_id),检索只认 `index_build_id` —— 那个人仍然检索得到这几段,"
        "**直到重建索引完成并切换**。这是一笔必须有人跟的欠账,不是提示")
    欠账.append(
        f"原文档新版本的 `content_hash` 要从**剩下这 {len(剩)} 段**算,"
        f"不能照抄上一版 —— `object_key` 指向的原文件没变(还含着拆走的那几段),"
        f"而「这份资料变没变」全靠那一列。`source_info.存储` 要标成 "
        f"`{派生自拆分}`,否则「查看原文」会从原文件拿到完整内容,"
        f"**含着他已经没权限的那几段**")

    return dict(
        新文档=dict(knowledge_base_id=目标知识库id,
                  # 写死的字面量 —— 不留空、不继承。
                  acl_override={"roles": sorted(新可见)},
                  source_info={"存储": 派生自拆分,
                               "拆自文档片段": sorted(map(str, 拆集))},
                  disabled_at=None),
        新版本=dict(revision=1, object_key=None,
                  content_hash="(从搬过去的片段正文算,见欠账)",
                  source_info={"存储": 派生自拆分}),
        搬过去的片段=搬,
        原文档新版本=dict(revision="(上一版 +1,由落库那层取 max)",
                     object_key="(照抄上一版 —— 原文件没变)",
                     content_hash="(从剩下的片段正文算,**不许照抄上一版**)",
                     source_info={"存储": 派生自拆分,
                                  "拆走了": sorted(map(str, 拆集))}),
        原文档留下的片段=剩,
        权限=dict(源文档有效范围=sorted(源可见), 新文档范围=sorted(新可见),
                为什么=f"源:{源话} / 新:{新话}"),
        版本=dict(拆走的=走的版本, 留下的=留的版本),
        欠账=欠账,
    )


# ── 这几条改坏了,哪一节会红 ────────────────────────────────────────
# 判据在 `tests/orchestration/test_split_document.py`:
#
#   新文档 ACL 允许留空继承            → ① 权限必填
#   子集检查去掉(新 ⊆ 源)              → ① 放宽要拒
#   整篇拆走放过去                      → ② 整篇不是拆分
#   不属于这篇文档的 id 跳过            → ② 野 id 当场抛
#   搬过去的片段读当前 chunker 常量      → ③ 版本沿用
#   混版本改成抛(而不是记欠账)          → ③ 混版本记欠账
#   `欠账` 返回空                       → ④ 欠账非空
