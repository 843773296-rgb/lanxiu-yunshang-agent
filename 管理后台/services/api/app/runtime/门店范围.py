# -*- coding: utf-8 -*-
"""人工待办按门店分开(11-21,用户拍:店长只看到、只处理本店的单子;聊天站那一半由评测线会话接)。

两件事,都是纯函数,worker 和接口层各调一份、不各写一套:

① **一张待办归哪个门店** —— 挂起时定,之后不变。按这个顺序找,第一个找到的算:
   1. 运行的输入里有门店键(用户输入 / Webhook 推来的 `门店` / `门店编号` / `store_id` / `shop_id` / `X-Shop` 这几种写法,不分大小写)
   2. 人工步骤的核对材料里有门店键(模型整理出来的材料里常带「门店」)
   3. 发起这次运行的人在成员表里登记的门店
   4. 都没有 → 不归任何门店(下面的 ③ 决定谁能看它)
   找到了连「从哪儿来的」一起记进待办的 target_ref,排查「为什么这单店长看不到」时不用猜。

② **门店编号怎么比** —— 去两头空白、不分大小写(澜绣的门店编号是 `SH001` 这种,聊天站传过来可能是小写)。

③ **谁看得到哪些单子**:
   · 成员表里**没登记门店**的人(总部 / 管理员)看全部,包括不归任何门店的单子
   · 登记了门店的人只看**本店**的单子;不归任何门店的单子**不给他看**
     (一张定不出门店的单子让每个店长都看到,等于没分;让总部看到并派下去才对)
   不在范围内的单子对他是 **404**(和「项目下没有你的成员记录」同一个口径:不确认它存在)。
"""

门店键们 = ("门店", "门店编号", "门店id", "store_id", "store", "shop_id", "shop", "x-shop")


def 规范(编号):
    """门店编号比对口径:字符串、去空白、统一大写;空的 → None。"""
    if 编号 is None:
        return None
    s = str(编号).strip()
    return s.upper() if s else None


def _从(字典):
    if not isinstance(字典, dict):
        return None
    for k, v in 字典.items():
        if str(k).strip().lower() in 门店键们 and 规范(v):
            return 规范(v)
    return None


def 取门店(输入=None, 材料=None, 发起人门店=None):
    """→ (门店编号或 None, 来源说明)。顺序:输入 → 材料 → 发起人 → 没有。"""
    d = _从(输入)
    if d:
        return d, "运行的输入"
    d = _从(材料)
    if d:
        return d, "核对材料"
    d = 规范(发起人门店)
    if d:
        return d, "发起人的门店"
    return None, "定不出门店(只有不限门店的人看得到)"


def 看得到吗(我的门店, 单子门店):
    """成员没登记门店 → 全看;登记了 → 只看本店;定不出门店的单子只给不限门店的人。"""
    我 = 规范(我的门店)
    if 我 is None:
        return True
    return 规范(单子门店) == 我


def 为什么看不到(我的门店, 单子门店):
    if 看得到吗(我的门店, 单子门店):
        return ""
    if 规范(单子门店) is None:
        return "这张单子定不出门店,只有不限门店的人(总部 / 管理员)能处理"
    return f"这张单子是 {规范(单子门店)} 门店的,你登记的门店是 {规范(我的门店)}"
