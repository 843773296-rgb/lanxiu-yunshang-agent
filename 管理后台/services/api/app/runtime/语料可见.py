"""**这段语料这个人能不能检索到** —— 口径的唯一源头,纯判定、零 IO。

规格 §18:「**文档父级权限可收紧**」。契约里那一行写的是同一件事:
> 「知识库级 ACL 是上限,文档可以再收紧但不能放宽」

## ⚠️ 这个模块为什么现在才写:两级都**从没被填过一次**

2026-10-07 量过:`knowledge_bases.acl` 样本全空、`documents.acl_override`
**178 篇里有值的 0 篇**。
> 一个「权限体系建好了只是还没启用」的系统,和一个「字段建了而从没被填过」的,
> **在那张表上长得一模一样** —— 而后者意味着连「填进去长什么样」都还没定过。

所以这里先把**形状**定下来,再谈谁读它。

## ⚠️ ACL 存**角色**,不存人(业界叫 late-binding)

> 把展开后的人名单写进 ACL,一次调岗要重写几万条;
> 存角色,调岗只改一处(他属于哪些角色由 `memberships` 现查)。
>
> 一份「权限是最新的」索引,和一份「某人上周调岗了而索引里还是旧名单」的,
> **在那条检索结果上长得一模一样** —— 而他能继续读他已经不该读的东西。

角色字面量**一个不许自己造** —— 全部来自 `contract/perms.角色们`。

## ⚠️ 空 ACL 是什么意思:**「没说过」,不是「没有人」**

两种读法后果正好相反:
> 一份「空 = 全部角色可见」的系统,和一份「空 = 谁都看不见」的,
> **在那个 NULL 上长得一模一样** —— 前者默认开放,后者默认关闭。

这里定的是:

    知识库级空   = **全部角色**(它是上限,上限是空集的话整个库谁都读不到,
                   而那种「建完就没人能用」的状态没人会故意要)
    文档级空     = **继承知识库**(没收紧过)

和这个项目「NULL 是『没说过』,不是 0」那条一致。

## ⚠️ 只能收紧,而「收紧」要有判据

收紧 = **子集**。文档的 ACL 必须是知识库 ACL 的子集:

    知识库 {editor, approver, admin} → 文档 {admin}          ✅ 收紧
    知识库 {admin}                   → 文档 {editor, admin}  ❌ 放宽,拒

⚠️ **拒的时候要说清被哪一级卡住、多出来的是谁** ——
> 一句「权限设置失败」和一句「`editor` 不在知识库这一级的范围里」,
> **在那次失败上长得一模一样** —— 而前者让人去翻文档,后者让人去改知识库。

## 它不做什么

- **不查库。** 两级 ACL 和这个人的角色都由调用方取来。
- **不管「切片级」。** 业务 2026-10-07 拍的:切片级不做,要收紧就**拆成独立文档**
  (切片是派生物,重建索引就整批重切 —— 权限绑在它上面会静默失效)。
- **不管推理层。** 这是**召回层**的权限:过滤对了,模型仍可能从它有权限的
  几段里拼出敏感内容。业界没有干净解法,**这一点要写在文档里,不假装解决了**。
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))), "contract"))
import perms as _PM

# 角色字面量只有一份 —— 在 `contract/perms.py`。
# 两套枚举迟早分叉,而分叉时两边各自都是绿的。
角色们 = tuple(_PM.角色们)

# ⚠️ **「角色」和「专项授权」是两件事,传错一个就打开了一把万能钥匙。**
#
# 真实身份模型是 `perms.判(能力, 角色, 专项)` —— 一个人在一个项目里
# **只有一个角色**,而 `专项`(`身份.grants`)是**能力级**授权,不是角色。
# `perms.判` 自己写着:「专项授权只能打开「可授权」的格子,打不开「否」,
# 否则专项授权就变成了万能钥匙」。
#
# 下面这几个函数的入参叫 `这个人的角色们`(复数、收集合),所以接的人很容易写成
#
#     这个人的角色们=[me.role] + me.grants      # ❌ **别这样**
#
# 那一行让专项授权成了绕过语料 ACL 的路子 ——
# > 一行「把角色和专项都传进去」的接法,和一行只传角色的,
# > **在那次检索结果上长得一模一样** —— 除非恰好有人持着专项授权
# > 去查他没权限的语料,而那时没人会想到是这一行。
#
# 正确的接法只有一个:`这个人的角色们=[me.role]`。
# `_认角色()` 会把任何不是角色字面量的东西当场抛,所以**传错了会红**,
# 不是靠这段注释拦 —— 而专项授权的名字恰好都不在 `角色们` 里。
#
# ⚠️ 入参收**集合**不是因为系统支持多角色,是为了口径稳定(将来一人多角色时
# 这里不用改)。**当前它永远只有一个元素** ——
# > 一个「ACL 列了 3 个角色」的文档,和一个「列了 3 个角色而没有任何人
# > 同时属于其中两个」的,在那个 ACL 上长得一模一样;而 `?|` 的参数数组
# > 今天永远只有一个元素。别写依赖「某人同时是 editor 和 approver」的逻辑。

未说过 = "未说过(继承上一级)"
全部角色 = "全部角色"


class 判不了(Exception):
    """输入本身讲不通 —— 当场抛。

    ⚠️ 默认处置**不是**「那就让他看」。一个把「判不了」读成「可见」的检索,
    和一个真判过的,**在那条召回结果上长得一模一样**。
    """


def _规范(acl, 哪儿):
    """把一级 ACL 规范成角色集合。`None` / 空 → `None`(表示「没说过」)。

    ⚠️ **空列表和 None 都当「没说过」。** 「写了个空列表」看起来像
    「谁都不许看」,而它更可能是前端传了个空数组 ——
    > 一个「故意设成谁都看不见」的 ACL,和一个「前端传空了」的,
    > **在那个 `[]` 上长得一模一样**。
    真要谁都看不见,业务该用的是停用文档(`disabled_at`),不是空 ACL。
    """
    if acl is None:
        return None
    if isinstance(acl, dict):
        acl = acl.get("roles")
        if acl is None:
            return None
    if not isinstance(acl, (list, tuple, set)):
        raise 判不了(f"{哪儿} 的 ACL 得是角色清单或 {{\"roles\": [...]}},"
                  f"现在是 {type(acl).__name__}")
    出 = set()
    for r in acl:
        if r not in 角色们:
            # ⚠️ 认不出的角色**当场抛,不忽略**。忽略的话一个拼错的角色名
            # 会让那一档静静消失,而 ACL 看起来仍然填着东西。
            raise 判不了(f"{哪儿} 里的 `{r}` 不是认得的角色 —— 只认 {角色们}。"
                      f"**不忽略认不出的** —— 忽略会让一个拼错的角色名"
                      f"静静消失,而 ACL 看起来仍然填着东西")
        出.add(r)
    return 出 or None


def 定(*, 知识库acl=None, 文档acl=None):
    """这篇文档**最终**谁能检索到。返回 `(角色集合, 为什么)`。

    两级都没说过 → 全部角色(知识库级是上限,上限不能是空集)。
    """
    库 = _规范(知识库acl, "知识库")
    文 = _规范(文档acl, "文档")
    if 库 is None:
        库 = set(角色们)
        库话 = f"知识库没说过 → {全部角色}"
    else:
        库话 = f"知识库限 {sorted(库)}"
    if 文 is None:
        return 库, f"{库话};文档{未说过} → 跟知识库一样"
    多 = 文 - 库
    if 多:
        # ⚠️ **说清被哪一级卡住、多出来的是谁。**
        raise 判不了(
            f"文档想放宽到 {sorted(文)},而**知识库这一级只到 {sorted(库)}** —— "
            f"多出来的 {sorted(多)} 不在上一级范围里。规格 §18:"
            f"**父级权限可收紧,不可放宽**。要让 {sorted(多)} 看得到,"
            f"得先改知识库那一级")
    return 文, f"{库话};文档再收紧到 {sorted(文)}"


def 看得到吗(*, 这个人的角色们, 知识库acl=None, 文档acl=None):
    """这个人能不能检索到这篇文档。返回 `(能不能, 为什么)`。

    `这个人的角色们`:他在**这个项目**里的角色(从 `memberships` 现查)——
    **存角色不存人**,所以调岗只要改 memberships,不用重写任何 ACL。
    """
    if 这个人的角色们 is None:
        raise 判不了("不知道这个人有哪些角色 —— **判不了不等于可见**")
    我的 = set(这个人的角色们)
    野 = 我的 - set(角色们)
    if 野:
        raise 判不了(f"认不出的角色 {sorted(野)} —— 只认 {角色们}")
    可见, 话 = 定(知识库acl=知识库acl, 文档acl=文档acl)
    命中 = 我的 & 可见
    if 命中:
        return True, f"你的角色 {sorted(命中)} 在可见范围里({话})"
    return False, (f"你的角色 {sorted(我的) or '(一个都没有)'} 不在可见范围 "
                   f"{sorted(可见)} 里({话})")


def where片段(*, 这个人的角色们):
    """给检索那条 SQL 用的**过滤片段** —— 检索**前**过滤,不是召回后再筛。

    ⚠️ **为什么必须是检索前。**
    > 一次「召回 10 条、丢掉 8 条、剩 2 条」和一次「库里本来就只有 2 条相关的」,
    > **在那 2 条结果上长得一模一样** —— 用户和模型都看不出自己被过滤了。
    而它还有个更坏的后果:top-k 被权限吃掉之后模型拿到的上下文变少、答得更差,
    **表现是「这个 RAG 不准」,没人会去查是权限吃掉了召回**。

    返回 `(片段, 参数)`。片段假定调用方已经 join 到 `documents d`
    和 `knowledge_bases kb`。
    ⚠️ 它和上面那两个纯判定**必须给出同一个答案** ——
    > 一份 SQL 过滤和一份纯判定,**在各自的测试里都绿**,而它们可以给出不同的名单。
    对账在 `tests/orchestration/test_corpus_visible.py`(两种表示拿同一批输入比)。
    """
    if not 这个人的角色们:
        raise 判不了("没有角色就没有可见范围 —— **不给一个「看全部」的兜底**")
    我的 = sorted(set(这个人的角色们))
    野 = set(我的) - set(角色们)
    if 野:
        raise 判不了(f"认不出的角色 {sorted(野)} —— 只认 {角色们}")
    # 口径和 `定()` 一字对应:
    #   文档说过  → 用文档的;没说过 → 用知识库的;知识库也没说过 → 全部角色
    # ⚠️ `?|` 是 jsonb 的「任一键存在」。ACL 存成 `{"roles": [...]}`,
    #    所以比的是 `->'roles'`;而 `coalesce` 那两层就是「继承」。
    片段 = ("(coalesce(d.acl_override->'roles', kb.acl->'roles') is null"
           " or coalesce(d.acl_override->'roles', kb.acl->'roles') ?| :角色们)")
    return 片段, {"角色们": 我的}


