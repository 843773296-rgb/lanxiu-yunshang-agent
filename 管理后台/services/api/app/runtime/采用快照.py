#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""这次运行**实际采用了什么** —— 纯逻辑,零 IO。规格 §4.2 第 ④ 行 / §10.2。

## 它是四个状态的最后一个

    草稿已保存 ──▶ 版本已发布 ──▶ 实例已加载 ──▶ **本次运行已采用**
                                                  ↑ 这儿

规格 §4.2 那张表最后一行:
> 「本次运行已采用 | Run 上记录**实际策略快照与来源** |
> **不能借其他运行的回执证明本次生效**」

## 为什么存**快照本身**,不只是那个外键

环境指针(`environment_bindings`)是**可改**的。只存
`execution_policy_version_id` 的话,指针一变、或者那一版被新版取代,
**历史运行会跟着改口**说自己当时用的是新版:

> **一个事后跟着指针漂的「当时用的策略」,和一个真记下来的,
> 在那一栏上长得一模一样。**

而这一栏是出事后唯一能回答「那次到底按什么上限跑的」的地方 ——
它一漂,整条追溯就断了。

## 五条判据

### ① **来源**必须记,而且「回退」要看得出来

`策略解析` 有三种结果:采用 / 回退 / 拒绝启动。
前两种都会真的跑起来,而它们**不是一回事**:
> **一次回退的运行,和一次正常采用的,在那条 trace 上长得一模一样** ——
> 如果不记来源。
而回退意味着「用的是上一次已验证的本地策略」,出事时第一个要看的就是它。

### ② 同一任务的**多个 Run 段共用一个快照**

规格 §4.2:「**同一任务启动后固定策略快照**」;
§8:「终态 Run 不直接改回运行中,创建关联恢复段,仍引用原任务」。

所以续跑段**不重新解析** —— 它复用第一段的快照。
> 一个每段重新解析的实现,和一个固定快照的,
> **在正常情况下长得一模一样** —— 差别只在「中途发布了新版本」时出现,
> 而那正是这条规矩要管的情况。

### ③ 快照里要有**实例回执的证据**,而不只是「有回执」

规格 §4.2:「**不能借其他运行的回执证明本次生效**」。
所以记的是**这一次解析时用的那条回执**:哪个实例、它报的哈希、
它什么时候加载的。
> 一条「反正有实例回执过」的 trace,和一条记了是哪条回执的,
> **在那个「已采用」上长得一模一样**,而前者证明不了本次。

### ④ `limits` 要**原样进快照**

不是「记个版本号回头查」。版本行是不可变的,看起来查得回来 ——
但出事时要回答的是「**那次按什么上限跑的**」,而中间可能经过
运行覆盖(`cache_runtime_overrides` 那一族的同类)。
原样存一份,这个问题就永远答得出。

### ⑤ 快照里要有**真实还是模拟**

规格三处都要求区分:§9.5(运行详情顶部显示「真实/模拟模式」)、
§10.4(观测完整率「**分真实/模拟**,不让缺日志任务消失」)、
§11(交付清单里「真实/模拟区分」)。

而不记它的后果很具体:后台 Agent 那条入口现在**写死跑 mock**
(真实适配器仍报 `ENTRY_NOT_WIRED_LIVE`),于是它的 Run 会被算进
「这一版的采用覆盖数」——
> **一条 mock 运行采用了策略,和一条真实运行采用了策略,
> 在那个「采用覆盖数」上长得一模一样** —— 而前者什么都没证明:
> 它根本没有真实的工具调用可被限制。

### ⑥ 拒绝启动的**不配快照**,因为它没跑

`拒绝启动` 时根本没有 Run。给它造一条带快照的 trace,
等于在「采用数」里凭空加一条 ——
> 一条根本没跑的运行,和一条跑了的,**在那个计数上长得一模一样**。

## 它不做什么

- **不写库。** 返回一个 JSONB 能直接装的 dict。
- **不解析策略。** 那是 `策略解析.这次用哪一版()` 的事。
- **不管哪些 trace 该带它。** 五处写 `traces` 的地方里只有两处是
  「Run 开始」(没有 `ended_at` 那两处);另外三处是一次完成的知识调用,
  **不该带执行策略快照** ——
  > 一个把所有 trace 都算进「采用数」的统计,和一个只算 Run 的,
  > **在那个数字上长得一模一样**,
  > 而前者让一条没人用的策略看起来在被广泛使用。
"""

# 来源。**和 `策略解析` 的状态对应** —— 两套枚举迟早分叉。
直接采用 = "直接采用"
回退采用 = "回退采用(用的是上一次已验证的本地策略)"
继承前段 = "继承前一段(同一任务固定快照)"
来源们 = (直接采用, 回退采用, 继承前段)


class 装不出(Exception):
    """输入讲不通 —— 当场抛,**不装一个半空的快照**。

    ⚠️ 一个半空的快照和一个完整的,在「这条 trace 有快照」这件事上
    长得一模一样,而页面会把它算进「采用覆盖数」。
    """


def 装(*, 来源, 用的那一版, 这个实例的回执=None, 现在,
      前一段的快照=None, 实际limits=None, 执行模式=None):
    """返回可以塞进 `traces.policy_snapshot` 的 dict。

    `来源`:上面三个常量之一。
    `用的那一版`:`策略解析` 返回的那个对象(采用时是发布的那一版,
        回退时是本地回退)。
    `这个实例的回执`:**这一次解析时用的那条** —— 采用时必须给
        (规格 §4.2:不能借其他运行的回执证明本次生效)。
    `前一段的快照`:续跑段给它,`来源` 用 `继承前段`。
    `实际limits`:真正生效的那份(可能经过运行覆盖);不给就用那一版里的。
    """
    if 来源 not in 来源们:
        raise 装不出(f"`来源` 得是 {来源们} 之一,现在是 {来源!r} —— "
                 f"**「回退」必须看得出来**:一次回退的运行,"
                 f"和一次正常采用的,在那条 trace 上长得一模一样")
    if 现在 is None:
        raise 装不出("没有时钟 —— 快照要记「什么时候采用的」,"
                 "而**拿不到时间不等于不用记**")
    # ⚠️ **真实还是模拟必须给**(规格 §9.5 / §10.4 / §11)。
    # 不给就抛,**不默认成「真实」** ——
    # 后台 Agent 那条入口现在写死跑 mock,而它的 Run 照样会被算进
    # 「采用覆盖数」:一条 mock 运行采用了策略,和一条真实运行采用了策略,
    # 在那个数上长得一模一样,而前者根本没有真实的工具调用可被限制。
    if 来源 != 继承前段 and 执行模式 not in ("live", "mock"):
        raise 装不出(
            f"`执行模式` 得是 'live' / 'mock',现在是 {执行模式!r} —— "
            f"**不默认成 live**。规格 §10.4 要求观测完整率"
            f"「分真实/模拟,不让缺日志任务消失」;"
            f"而一条 mock 运行采用了策略,和一条真实运行采用了策略,"
            f"**在那个「采用覆盖数」上长得一模一样**,"
            f"前者根本没有真实的工具调用可被限制")

    # ── ② 续跑段:复用前一段,不重新装 ──────────────────────────
    if 来源 == 继承前段:
        if not 前一段的快照:
            raise 装不出(
                "`来源` 是「继承前段」而没给 `前一段的快照` —— "
                "**不就地新装一个**:规格 §4.2 要求「同一任务启动后固定策略快照」,"
                "而重新装出来的那个**可能已经是另一版了**。"
                "> 一个每段重新解析的实现,和一个固定快照的,"
                "在正常情况下长得一模一样 —— "
                "差别只在「中途发布了新版本」时出现,而那正是这条规矩要管的")
        if not isinstance(前一段的快照, dict) or "版本" not in 前一段的快照:
            raise 装不出(f"`前一段的快照` 形状不对:{type(前一段的快照).__name__} —— "
                     f"**不拿它顶**。一个形状不对的快照继承下来,"
                     f"整条任务链的追溯都断了")
        out = dict(前一段的快照)
        out["来源"] = 继承前段
        out["这一段采用于"] = 现在
        # ⚠️ **原来那一段的「采用于」要留着** —— 它是「这个快照是什么时候
        # 定下来的」,而新字段是「这一段什么时候开始用它」。
        # 两个时间混成一个的话,「固定了多久」这个问题就答不出来。
        out.setdefault("最初采用于", 前一段的快照.get("这一段采用于")
                       or 前一段的快照.get("最初采用于"))
        out["怎么读"] = ("**这一段没有重新解析** —— 同一任务固定快照(规格 §4.2)。"
                      "「最初采用于」是快照定下来的时刻,"
                      "「这一段采用于」是这一段开始用它的时刻")
        return out

    if not isinstance(用的那一版, dict):
        raise 装不出(f"`用的那一版` 得是个 dict,现在是 "
                 f"{type(用的那一版).__name__} —— 这是 `策略解析` 的返回值;"
                 f"它返回 `None` 时状态是**拒绝启动**,"
                 f"而**拒绝启动的不配快照,因为它没跑**")

    必 = ("id", "limits")
    缺 = [k for k in 必 if k not in 用的那一版]
    if 缺:
        raise 装不出(f"那一版缺 {缺} —— **不装一个半空的快照**。"
                 f"一个半空的快照和一个完整的,在「这条 trace 有快照」"
                 f"这件事上长得一模一样,而页面会把它算进「采用覆盖数」")

    快 = {
        "来源": 来源,
        "版本": 用的那一版["id"],
        # 回退用的那一份可能没有 content_hash(它是本地文件)——
        # **那就明写 None,不编一个**。
        "内容哈希": 用的那一版.get("content_hash"),
        "入口": 用的那一版.get("entry_kind"),
        # ── ④ limits 原样进来 ────────────────────────────────
        # 不是「记个版本号回头查」:出事时要答的是「那次按什么上限跑的」,
        # 而中间可能经过运行覆盖。
        "实际limits": dict(实际limits if 实际limits is not None
                         else 用的那一版["limits"]),
        "计数口径": 用的那一版.get("counter_schema_version"),
        "这一段采用于": 现在,
        "最初采用于": 现在,
        # 规格 §9.5 顶部要显示它;§10.4 的观测完整率要按它分组。
        "执行模式": 执行模式,
    }
    if 执行模式 == "mock":
        快["⚠️这是模拟运行"] = (
            "**它不能算作「这一版在真实运行里生效了」** —— "
            "没有真实的工具调用可被限制。规格 §10.4:观测完整率分真实/模拟。"
            "后台 Agent 那条入口的真实适配器仍报 `ENTRY_NOT_WIRED_LIVE`")
    if 实际limits is not None and 实际limits != 用的那一版["limits"]:
        # 覆盖过就说清楚 —— 否则「配置里是 12 而实际跑的是 8」这件事
        # 在快照上看不出来。
        快["⚠️被覆盖过"] = {"版本里写的": 用的那一版["limits"],
                       "实际生效的": dict(实际limits),
                       "怎么读": "两者不一致 —— 实际跑的是后者;"
                               "**不记的话「配置里是什么」会被当成「实际跑的是什么」**"}

    # ── ① / ③ 回退 vs 采用,各自要的证据不同 ──────────────────
    if 来源 == 回退采用:
        for k in ("验证于", "有效到", "为什么回退"):
            if k not in 用的那一版:
                raise 装不出(
                    f"回退采用而那一份缺 `{k}` —— 规格 §4.3 要求"
                    f"**展示回退版本、年龄、原因及有效期**。"
                    f"缺一样就说不出「现在在跑哪一版、多老、为什么」,"
                    f"而那种状态和正常采用在界面上长得一模一样")
        快["回退证据"] = {"验证于": 用的那一版["验证于"],
                     "有效到": 用的那一版["有效到"],
                     "为什么回退": 用的那一版["为什么回退"],
                     "⚠️": "**这不是正常采用** —— 用的是上一次已验证的本地策略;"
                           "出事时第一个要看这一栏"}
        # 回退时没有实例回执可记(配置服务都拉不到)—— 明写,不留空。
        快["回执证据"] = None
        快["为什么没有回执证据"] = ("回退路径上拿不到实例回执 —— "
                           "**明写 None,不留空**:一个空着的回执证据栏,"
                           "和一个「这次确实没有」的,在那一栏上长得一模一样")
        return 快

    # 直接采用:**必须有这一次用的那条回执**
    if not 这个实例的回执:
        raise 装不出(
            "直接采用而没给 `这个实例的回执` —— 规格 §4.2:"
            "**不能借其他运行的回执证明本次生效**。"
            "> 一条「反正有实例回执过」的 trace,和一条记了是哪条回执的,"
            "**在那个「已采用」上长得一模一样**,而前者证明不了本次")
    回 = 这个实例的回执
    缺回 = [k for k in ("instance_ref", "policy_hash", "loaded_at") if k not in 回]
    if 缺回:
        raise 装不出(f"回执缺 {缺回} —— 快照里要记**是哪条回执**,"
                 f"而不是「有回执」")
    快["回执证据"] = {"实例": 回["instance_ref"], "它报的哈希": 回["policy_hash"],
                 "它加载于": 回["loaded_at"],
                 "解析时回执年龄秒": 现在 - 回["loaded_at"]}
    return 快


def 该带快照吗(*, 这条trace有没有ended_at):
    """这条 trace 该带执行策略快照吗。

    ⚠️ 这个仓库里**五处**写 `traces`,而只有两处是「Run 开始」。
    判据是**有没有在插入时就写 `ended_at`**:
      · 写了 → 它是「一次完成的知识调用」,**不受执行策略管**
      · 没写 → 真正的 Run 开始(workflows_api / agents_api 那两处)

    > 给那三处也加快照的话,「有多少 Run 采用了这一版」这个数会虚高 ——
    > 而**一个把所有 trace 都算进「采用数」的统计,和一个只算 Run 的,
    > 在那个数字上长得一模一样**,
    > 前者让一条没人用的策略看起来在被广泛使用。
    """
    if 这条trace有没有ended_at:
        return False, ("插入时就有 `ended_at` → 这是一次**已完成的调用**"
                       "(知识检索那一族),不受执行策略管,**不带快照**")
    return True, "插入时只有 `started_at` → 真正的 Run 开始,**要带快照**"
