"""接口登记表 —— **OpenAPI 的唯一来源**(规格 §19.2)。

## 为什么每条接口都要声明「要哪条权限」

规格 §15.3 最后一句:「授权必须在**服务端每次请求**执行,并检查对象所属项目」。
如果权限判定散在每个 handler 里,那「这条接口要什么权限」就没有任何地方能一次看全 ——
于是漏掉一条的时候,**没有任何东西会报错**,只有那条接口悄悄对所有人开放。

所以这里每条接口都必须点名一条 `perms.能力们` 里的能力。点不出来的接口不许登记。

## 四类必须在契约层就定死的东西

① **异步的必须标出来。** 规格 §19.1:「异步动作返回 202 与 job_id,
   **不能返回「已经训练完成」**」。一条把异步做成同步返回的接口,
   在界面上表现为「点一下就说成了」—— 而那正是「用假进度冒充执行」。

② **改草稿/指针的必须要 If-Match。** 不要的话就是「最后写的人赢」,
   而输的那个人**看不到自己的改动被覆盖了**。

③ **有外部副作用的必须要 Idempotency-Key。** 提交训练、部署、发起收费调用 ——
   网络超时重发一次的代价是重复烧 GPU 或重复计费。

④ **返回列表的必须用统一信封。** `items/next_cursor/total`,而
   **total 未知时明确 null**(§19.1)—— 不许用 0 表示「我没数」。
"""
