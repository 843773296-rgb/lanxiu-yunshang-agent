"""告警判定(DF-04 第二步,2026-11-04;Dify 对标 §8.1 / 验收 C16「低样本波动与持续异常 → 按最小样本、连续次数触发并恢复;
不重复轰炸;告警能下钻到运行」)。

## 用户拍的判法(AskUserQuestion,11-04)

**连续 N 次越线才报、连续 M 次正常才算恢复**;样本不够最小样本量的那一轮**不算**(既不报也不清零);
去重周期内同一条规则不重复提醒。N / M / 最小样本 / 去重周期 / 阈值 都是规则里配的**产品配置**,不是行业标准。

## 这个文件只有判定,没有取数

`下一步(状态, 这一轮, 规则, 现在)` 是纯函数:进来的是这一轮算出来的值和样本数,出去的是新状态 + 要做的那一个动作
(开待办 / 提醒 / 恢复 / 不动)。取数在 monitoring_api.算(和监测页同一份,不另算一遍),落库在 alerts_api。
判据(test_alert_rules)真调这一个函数。
"""
import datetime as _dt

# 能告警的指标:监测页算出来的哪个数、它的样本数用哪个数
指标们 = {
    "终态成功率": ("可用性", "终态成功率", "可用性", "终态成功率分母"),
    "写入办成率": ("业务", "写入办成率", "业务", "写入办成率分母"),
    "失败次数": ("可用性", "失败", "可用性", "终态"),
    "端到端P95秒": ("性能", "端到端", "性能", "端到端"),
    "每个办成任务成本": ("成本", "每个办成任务成本", "业务", "办成"),
    "算不出金额笔数": ("成本", "算不出金额的笔数", "可用性", "接收"),
}
方向们 = ("低于", "高于")


def 取指标(监测, 指标):
    """监测页那份结果 → (值, 样本数)。值算不出(分母 0)→ None。"""
    块, 键, 样块, 样键 = 指标们[指标]
    if 指标 == "端到端P95秒":
        x = 监测["性能"]["端到端"]
        return x["P95秒"], x["样本数"]
    return 监测[块][键], 监测[样块][样键]


def 越线吗(值, 方向, 阈值):
    return (值 < 阈值) if 方向 == "低于" else (值 > 阈值)


def 下一步(状态, 值, 样本, 规则, 现在):
    """→ (新状态, 动作, 为什么)。

    状态:{连续越线, 连续正常, 触发中, 上次提醒}(上次提醒是 datetime 或 None)
    规则:{方向, 阈值, 最小样本, 连续越线才报, 连续正常才恢复, 去重分钟}
    动作:「开待办」「提醒」「恢复」「不动」之一
    """
    新 = dict(状态)
    if 值 is None or 样本 < 规则["最小样本"]:
        # 用户拍:样本不够的那一轮不算 —— 不报,也不把连续次数清零(否则流量一低,持续的异常就永远攒不够次数)
        return 新, "不动", f"样本 {样本} 条,不到最小样本 {规则['最小样本']} 条 —— 这一轮不算" if 值 is not None else "这一轮算不出(分母是 0)—— 不算"
    if 越线吗(值, 规则["方向"], 规则["阈值"]):
        新["连续越线"] = 状态["连续越线"] + 1
        新["连续正常"] = 0
        if not 状态["触发中"]:
            if 新["连续越线"] >= 规则["连续越线才报"]:
                新["触发中"], 新["上次提醒"] = True, 现在
                return 新, "开待办", f"连续 {新['连续越线']} 次{规则['方向']} {规则['阈值']}(这次 {值},{样本} 条)"
            return 新, "不动", f"越线 {新['连续越线']} / {规则['连续越线才报']} 次,还没攒够"
        上次 = 状态["上次提醒"]
        if 上次 is None or 现在 - 上次 >= _dt.timedelta(minutes=规则["去重分钟"]):
            新["上次提醒"] = 现在
            return 新, "提醒", f"还在越线(这次 {值}),去重周期 {规则['去重分钟']} 分钟过了,再提醒一次"
        return 新, "不动", f"还在越线,去重周期内不重复提醒"
    新["连续正常"] = 状态["连续正常"] + 1
    新["连续越线"] = 0
    if 状态["触发中"] and 新["连续正常"] >= 规则["连续正常才恢复"]:
        新["触发中"] = False
        return 新, "恢复", f"连续 {新['连续正常']} 次正常(这次 {值}),标已恢复"
    return 新, "不动", ("正常" if not 状态["触发中"] else f"正常 {新['连续正常']} / {规则['连续正常才恢复']} 次,还没攒够恢复")
