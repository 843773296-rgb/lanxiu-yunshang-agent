#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""人工审批的判断那一半 —— **纯逻辑,零 IO**(所以每条都能单测)。

## 为什么这块非做不可

`runtime/tool_gateway.py` 的闸**已经在拦**不可逆写入了:没有生效批准就拒。
而在这个文件之前,**没有任何代码能生产一条批准** ——
被拦住的东西永远出不去。

> **一道拦得住但没有放行入口的闸,是一个做了一半的机制。**
> 而它在检查上是绿的:「没有生效批准的不可逆写入被挡住」这条断言照样过。

契约(entities / states)把这件事想得很细,四条备注每条都是一个判断,
下面逐条落成函数。

## 闸期待的形状

    批准 = {"参数摘要": ..., "批准人": ..., "过期了吗": bool} 或 None

`参数摘要` 由 `tool_gateway.参数摘要()` 算 —— **只有那一个出口**。
这里不自己算:两个地方各算一次,一次合法的重试就会被判成「参数变了」。
"""
import datetime as _dt

待处理 = "pending"
已批准 = "approved"
已驳回 = "rejected"
要求补充 = "info_requested"
已过期 = "expired"
已取消 = "cancelled"

决定们 = (已批准, 已驳回, 要求补充)
终态 = (已批准, 已驳回, 已过期, 已取消)

# ⚠️ **不许被编辑的字段。**(契约:系统安全字段、密钥和对象归属不可编辑)
# 判据是**前缀和关键词**,不是一张穷举表 —— 穷举表会漏掉下一个新加的敏感键,
# 而漏掉的那个正是有人想改的那个。
_不许编辑的 = ("project_id", "organization_id", "owner", "owner_id", "created_by",
           "secret", "token", "api_key", "apikey", "password", "credential",
           "role", "permission", "grant", "acl")


class 不能处理(Exception):
    """这条请求现在不能被这样处理。**当场抛,不静默放行。**"""


def 过期了吗(expires_at, 现在):
    """⚠️ **在点批准的那一刻比,不是建请求的时候比**(契约备注第三条)。

    建请求时比的坏法:一条三天前建、今天才被点的请求会被当成没过期 ——
    而「审批超时」这条规则的全部意义就在于**时间流逝会让批准失效**。
    """
    if expires_at is None:
        # ⚠️ **没有截止时间 = 永不过期?不。** 这里返回 None 表示「不知道」,
        # 由调用方决定 —— 把「没设过期」当成「永不过期」是个危险的默认:
        # 一条忘了设过期的高危请求会永远可批。
        return None
    if 现在 is None:
        raise 不能处理("没给「现在」—— **不许自己取当前时间**:"
                    "那样这个函数就测不了边界,而边界正是这种规则唯一容易错的地方")
    return 现在 >= expires_at


def 能处理吗(请求, *, 谁, 他的角色, 现在, 他能碰这个对象吗=None, 是模型吗=False):
    """这个人现在能不能处理这条请求。返回 (能不能, 为什么)。

    契约的四条备注在这里全部落地。
    """
    if not 请求:
        return False, "没有这条请求"
    st = 请求.get("status")

    # ── ① 模型不能批准自己(§9.6)────────────────────────────────
    # ⚠️ 放在最前面:它和请求状态无关,而且**它是最贵的一条** ——
    # 一个能自己批准自己的 Agent,等于没有审批。
    if 是模型吗:
        return False, ("**模型不能批准自己**(§9.6)—— "
                       "一个能自己批准自己的 Agent 等于没有审批")

    # ── ② 一次请求只能被处理一次 ─────────────────────────────────
    if st in 终态:
        return False, (f"这条请求已经是「{st}」了 —— **一次请求只能被处理一次**。"
                       f"两个人同点时,第二个应该看到这个,而不是覆盖第一个")
    if st not in (待处理, 要求补充):
        return False, f"状态「{st}」认不出 —— 只有 {待处理} / {要求补充} 能被处理"

    # ── ③ 过期的批准不许生效 ────────────────────────────────────
    过 = 过期了吗(请求.get("expires_at"), 现在)
    if 过 is True:
        return False, ("这条请求已经过了截止时间 —— **过期时间在点批准的那一刻比**,"
                       "不是建请求的时候比")
    if 过 is None:
        return False, ("这条请求**没有截止时间**。不把它当成「永不过期」是有意的:"
                       "一条忘了设过期的高危请求会永远可批。"
                       "建请求时必须给 expires_at")

    # ── ④ 审批者必须对那个对象有权限,不是「有审批角色」就行 ──────────
    候选 = 请求.get("candidate_roles") or []
    if 候选 and 他的角色 not in 候选:
        return False, (f"你的角色「{他的角色}」不在这条请求的候选审批角色 {候选} 里")
    if 他能碰这个对象吗 is None:
        return False, ("没告诉我「他对这个对象有没有权限」—— **不默认有**:"
                       "契约明说『有审批角色』不等于『能碰这个对象』")
    if not 他能碰这个对象吗:
        return False, ("你有审批角色,但**对这条请求指向的对象没有权限** —— "
                       "审批者必须对那个对象有权限(§12.3)")
    if 谁 and 谁 == (请求.get("created_by") or None):
        # 发起人自己批自己:契约没明说,但它和「模型不能批准自己」同一个道理。
        # ⚠️ 这一条**比契约严**,所以单独标出来,不混在上面那些里。
        return False, ("发起这条请求的人不能自己批准它 —— "
                       "**这一条比契约严**(契约只禁了模型自批),"
                       "理由相同:自己批自己等于没有审批")
    return True, ""


def 查编辑(改了什么, 允许的字段):
    """审批时改了哪些字段,合不合法。返回问题清单(空 = 合法)。

    `允许的字段` 是请求上的 `allowed_fields`。
    """
    问 = []
    改了什么 = 改了什么 or {}
    if not 改了什么:
        return 问
    允许 = set(允许的字段 or ())
    if not 允许:
        问.append("这条请求**没有声明 `allowed_fields`** —— "
                  "那意味着一个字段都不许改,而不是随便改")
        return 问
    多 = sorted(set(改了什么) - 允许)
    if 多:
        问.append(f"{多} 不在允许编辑的字段里(只许改 {sorted(允许)})")
    # ⚠️ **敏感键一律拒,即使它被写进了 allowed_fields。**
    # 白名单可能是别人配错的,而配错了之后这里不拦就等于没拦。
    敏 = sorted(k for k in 改了什么
                if any(w in str(k).lower() for w in _不许编辑的))
    if 敏:
        问.append(f"{敏} 是系统安全字段 / 密钥 / 对象归属,**一律不许编辑** —— "
                  f"即使它被写进了 allowed_fields(白名单可能是配错的)")
    return 问


def 算批准(请求, 决定们清单, *, 现在):
    """把一条请求和它的决定记录,折成**闸要的那个形状**。

    返回 `{"参数摘要":..., "批准人":..., "过期了吗": bool}` 或 None。

    ⚠️ **参数摘要原样取请求上的 `arguments_hash`,不在这里重算。**
    重算的坏法:两个地方各算一次规范化,一次合法的重试就会被判成
    「参数变了,批准失效」——`tool_gateway.参数摘要()` 是唯一出口。

    ⚠️ **只认最后一条 `approved`,而且要看它批的是不是「当前这一版内容」。**
    「要求补充」之后 revision 前进,**旧批准对新参数无效**(状态机备注)。

    ⚠️⚠️ 判据**不是「request_revision == 当前 revision」** —— 第一版这么写,
    于是永远算不出批准:**批准这个动作本身就会让 revision 前进**
    (批完 rev 从 1 到 2,而决定记的是被处理时那一版 1)。

    该比的是「**这条批准之后,内容有没有再变过**」。
    而「内容变了」的标志是出现了新的 `info_requested` —— 那才是让
    旧批准失效的事件。所以:**最后一条批准之后不许有 `info_requested`。**
    """
    if not 请求 or 请求.get("status") != 已批准:
        return None
    决定们清单 = list(决定们清单 or [])
    批过的 = [i for i, d in enumerate(决定们清单) if d.get("decision") == 已批准]
    if not 批过的:
        # 状态是 approved 而一条批准记录都没有 —— 库不一致,不能放行
        return None
    最后批的位置 = 批过的[-1]
    # ⚠️ 最后一次批准**之后**还有「要求补充」的话,那条批准已经失效了
    后面要求补充过 = any(
        d.get("decision") == 要求补充
        for d in 决定们清单[最后批的位置 + 1:])
    if 后面要求补充过:
        return None
    最后 = 决定们清单[最后批的位置]
    return {"参数摘要": 请求.get("arguments_hash"),
            "批准人": 最后.get("actor"),
            # **在这一刻比**,不是建请求的时候
            "过期了吗": bool(过期了吗(请求.get("expires_at"), 现在))}


def 候选角色里有人能审吗(candidate_roles, 谁有审批能力):
    """建请求时就该拦:**候选角色里必须至少有一个真的有审批能力**。

    返回 (行不行, 为什么)。

    ## 为什么这条必须在建请求时拦

    `candidate_roles` 和「谁有审批能力」是**两套判断**:

        candidate_roles   这一条该找谁审  ← 业务维度,建请求时填
        权限矩阵           谁有资格审      ← 系统维度,角色定义里写

    两者取交集。而如果交集是**空**,这条请求就**永远卡住而不报错** ——
    列表上它看起来正常(pending、没过期),只是每个人点进去都被拒,
    而各自看到的理由还不一样:
      · 有审批能力的人 → 「你的角色不在候选审批角色里」
      · 在候选角色里的人 → 「你的角色不能审批工具动作」

    **两个都说得通,而真相是这条请求从出生就没人能批。**
    (2026-09-28 实测撞上过:candidate_roles=['admin','editor'],
     而 editor 在矩阵里是 deny、approver 不在候选里 —— 谁都批不了。)

    ⚠️ `谁有审批能力` 由调用方从 `perms` 算好传进来 ——
    这个文件**零 IO 也不 import perms**:两边各判一次迟早分叉。
    """
    候选 = list(candidate_roles or ())
    if not 候选:
        return False, ("`candidate_roles` 是空的 —— 那不是「谁都能审」,"
                       "是**没写该找谁审**。建请求时必须填")
    能审的 = sorted(set(候选) & set(谁有审批能力 or ()))
    if not 能审的:
        return False, (f"候选审批角色 {候选} 里**一个有审批能力的都没有** —— "
                       f"有能力的是 {sorted(谁有审批能力 or [])}。"
                       f"这条请求建出来就**没人能批**,而它在列表上看起来完全正常")
    return True, f"候选里有 {能审的} 能审"
