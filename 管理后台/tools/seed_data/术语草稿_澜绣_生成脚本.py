    for a in e["叫法"]:
        if a in seen_alias: errs.append(f"叫法重复 {a}")
        if a in seen_std and a != e["标准词"]: errs.append(f"叫法撞标准词 {a}")
        if len(a) < 2: errs.append("单字叫法 " + a)
        seen_alias[a] = e["标准词"]
    if not e.get("出处"): errs.append("缺出处 " + e["标准词"])
    if e["类别"] == "名词" and ("口径" in e or "取数口" in e): errs.append("名词带口径 " + e["标准词"])
