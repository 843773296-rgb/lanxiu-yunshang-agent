#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""**页面上的 `**加粗**` 要真的渲染成加粗,别把星号显示给人看。**

2026-10-08 用户验收时一眼看到的:知识库页上写着

    资料、片段、索引。**有片段不等于能检索** —— 要有一个「已就绪」的索引。

那两个星号**是字面显示的**。原因是这些文案直接写进 HTML,
而把 `**` 变成 `<b>` 的是 `md()`,它们没经过它。全站量到 **30 处**。

> 一句「写了加粗」的文案,和一句「加粗真的生效了」的,
> **在源码上长得一模一样** —— 而页面上一个是粗体、一个是两个星号。

## 为什么没有任何检查抓到它

`page_smoke.js` 验「取到数、渲染了、节点被填充」;`page_render_check.js`
验「每个页面函数跑得起来」;`css_class_check.py` 验「class 在 CSS 里有」。
**没有一条验「这段文字在页面上长什么样」** ——
而这正是昨天那个 `[object Object]` 和今天这个星号的共同点:
**它们都要人用眼睛看一眼才看得见。**

这条检查把其中**可机检的那一半**接住:文案里写了 `**…**` 却没过 `md()`。
(另一半 —— 排版好不好看 —— 仍然要人看,这条不假装覆盖它。)
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
WEB = os.path.join(os.path.dirname(HERE), "apps", "web")
G, R, D = "\033[32m", "\033[31m", "\033[0m"


def main():
    p = os.path.join(WEB, "app.js")
    if not os.path.isfile(p):
        # ⚠️ 找不到文件要喊 —— 一次「扫过了没犯规」和一次「文件没找到」,
        # 在那个 0 上长得一模一样。
        print(f"  {R}❌ 找不到 {p} —— 这不是「通过」{D}")
        return 1
    t = open(p, encoding="utf-8").read()
    坏 = []
    for m in re.finditer(r'<div class="((?:sub|note)[^"]*)">([^<]{0,600})', t):
        内 = m.group(2)
        if "**" in 内 and "${md(" not in 内:
            坏.append((t[:m.start()].count("\n") + 1, m.group(1),
                       内.strip().replace("\n", " ")[:56]))
    print("\n\033[1m▸ 页面文案里的 `**加粗**` 真的渲染了吗\033[0m")
    print(f"  扫了 app.js 里的 .sub / .note 文案")
    if 坏:
        print(f"\n  {R}❌ {len(坏)} 处写了 `**…**` 却没过 `md()` —— "
              f"页面上显示的是**字面的星号**{D}")
        for 行, 类, 片 in 坏[:10]:
            print(f"     第 {行} 行 .{类}: {片}")
        print("     改法:把文案包进 `${md(`…`)}`。")
        return 1
    # ── `data-raw="原文"` 的**棘轮**(2026-10-08 加)─────────────────────
    #
    # 页面冒烟那条「渲染后不许有字面星号」有一个**有名字的豁免**:
    # 带 `data-raw="原文"` 的块(语料原文 / 可编辑字段 / 原样 dump 的 JSON ——
    # 它们是**数据不是文案**,渲染成粗体就和源文件/模型看到的不再逐字相同)。
    #
    # ⚠️ 而豁免会长。**一个在长大的豁免名单,和一条被关掉的判据,
    # 最后是同一件事** —— 所以这里钉住个数:多一处就红,要加就连这个数字一起改,
    # 而改这个数字会在 review 里被看见(和 css_class_check 钉 19 处同一个形状)。
    # ⚠️ **不数注释里的那一处。** `画链路` 上方有一段注释在解释这个标记 ——
    # 把它算进来,这个数就既不是「有多少处豁免」也不是「提了多少次」。
    # (今天同一个形状踩了四次:注释写在被扫描的东西里。)
    现在 = sum(1 for L in t.split("\n")
             if 'data-raw="原文"' in L and not L.strip().startswith(("*", "//", "/*")))
    # 2026-10-08 实数:26 处,**逐条看过**,每一条都是「数据不是文案」:
    #   · 原样 dump 的 JSON(事件载荷 / 输入快照 / 影响对象 / 脱敏参数…)
    #   · 可编辑字段(textarea / input —— 它们的值要被原样提交回去)
    #   · 语料原文(片段正文 / 节路径 / 证据串 / 引文 / 原话)
    #   · **给模型的说明**(这一栏的用处正是逐字核对模型看到了什么)
    # 2026-10-08 傍晚 +2:Prompt 详情页那两个 textarea(system / user)——
    # **提示词正文是要被原样提交回去的值**,渲染成粗体就改了内容。
    # ⚠️ 这两处是 **CI 抓到的,而本地那一轮绿** —— 详情页冒烟挑 id 时
    # 本地挑到的是另一条(没有加粗的那条),CI 挑到了 `pr_article_summary`。
    # > 一次「这一页验过了」和一次「验的是另一条数据」,
    # > 在那份名单上长得一模一样。
    # 复现:`node tests/e2e/page_smoke.js '#/prompt/pr_article_summary'`
    上限 = 28
    print(f"\n  `data-raw=原文` 的豁免:{现在} 处(钉住 {上限})")
    if 现在 > 上限:
        print(f"  {R}❌ 豁免涨到 {现在} 处,超过钉住的 {上限}{D}")
        print("     新标的那几处要确认过是**数据**(不是文案),"
              "然后把上限那个数字一起改大 —— 而不是直接标上就走。")
        print("     ⚠️ 判断标准:**渲染成粗体之后,它和源文件/模型看到的还逐字相同吗**。"
              "不相同的才是数据。")
        return 1
    print(f"\n{G}  ✅ 没有写了加粗却不渲染的文案{D}")
    print("     ⚠️ 它只接住**可机检的那一半** —— 排版好不好看仍然要人看一眼")
    return 0


# ── 咬合(2026-10-08 实跑,预期红抄的真实输出)────────────────────────
#   ① 对照                                  → ✅ 没有写了加粗却不渲染的文案
#   ② 把一处 `${md(`…`)}` 还原成裸文案        → ❌ 1 处写了 `**…**` 却没过 `md()`
if __name__ == "__main__":
    sys.exit(main())
