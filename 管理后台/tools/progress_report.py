#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""实现进度报告 —— **逐项写「已实现且验过 / 已实现未验 / 未实现」**(规格 §20)。

## 为什么必须有这一份,而且必须是生成的

规格 §20 最后一句:「交付报告逐项写『已实现且验证 / 已实现未验证 / 未实现』,
**禁止用「所有页面都有了」代替完整功能验收**」。

而这个项目的形状特别容易造成那种误读:87 条接口的**契约、状态机、数据库表、
OpenAPI、前端类型全都建好了** —— 53 张表、`docs/契约.md` 里 `training_jobs` /
`chunks` / `evaluations` 写得比工作流还细。于是每一处都「看起来已经在那儿了」,
而实际只有一部分有 handler。

> **一份齐全的契约会让人觉得事情做完了。**

所以这份报告是**生成的**,不是手写的:手写的进度表第二天就会漂,
而漂的方向永远是「比实际乐观」。

## 三档怎么判,以及每一档的判据有多硬

| 档 | 判据 | 硬度 |
|---|---|---|
| 未实现 | 扫三个 router 文件,没有对应的 `@app./@router.` 装饰器 | 硬:没有 handler 就是真的没有 |
| 已实现未验 | 有 handler,但测试**没打过**它 | 硬 |
| 已实现且验过 | 有 handler,而且测试运行时**真的打到了这条路由** | 中(见下) |

「验过」用的是**运行时记账**(`AIMC_TRACE_ROUTES`,中间件记 FastAPI 实际匹配到的
路由模板),不是「在测试文件里搜这条路径的字符串」——
后者会把「被注释提到」「拼在没执行的分支里」也算成验过,**比它声称的弱**。

⚠️ **但「打过一次」不等于「行为被断言对了」。** 这条限制写进报告正文,
不靠读的人自己想起来。一条被打过但断言写错的接口,在这份报告上和真验过的一样 ——
所以这份报告回答的是「有没有被碰过」,不是「对不对」。
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "services", "api", "app", "contract"))
import endpoints as EP  # noqa: E402

账本 = os.environ.get("AIMC_TRACE_ROUTES",
                    os.path.join("/tmp", "aimc-routes.log"))
# ⚠️ **自动发现,不手写清单。**
#
# 上一版是手写的三个文件名。2026-09-27 加了 `knowledge_api.py`(知识与 RAG 的三条接口),
# 而进度表**静默认不出它** —— 症状是「那三条显示没做」,
# 指向的是**接口**,而根因在**扫描范围**。
#
# > **一份手写的文件清单是个会漂的替身。**
#
# 多扫无害:没有路由装饰器的文件不产生条目。而漏扫会静默少报,
# 那正是这份报告最不该做的事(它存在的理由就是「别把没做的说成做了」,
# 反过来「把做了的说成没做」同样是假话)。
def _找handler文件():
    出 = []
    根目录 = os.path.join(ROOT, "services", "api", "app")
    for dp, dn, fn in os.walk(根目录):
        dn[:] = [d for d in dn if d not in ("__pycache__", ".venv")]
        for f in sorted(fn):
            if f.endswith(".py"):
                出.append(os.path.relpath(os.path.join(dp, f), ROOT))
    # **样本量下限**:扫不到东西就是路径写错了,而那会让报告说「一条都没实现」
    assert len(出) >= 5, (
        f"只扫到 {len(出)} 个 .py({根目录})—— **这不叫「没有 handler」,叫没扫到文件**")
    return 出


_handler文件 = _找handler文件()

未实现, 未验, 验过 = "未实现", "已实现未验", "已实现且验过"


def _归一(p):
    """路径参数名不算差别:契约写 `{id}`、handler 写 `{pid}`,是同一条路。"""
    return re.sub(r"\{[^}]*\}", "{}", p)


def 有handler():
    出 = set()
    for f in _handler文件:
        s = open(os.path.join(ROOT, f), encoding="utf-8").read()
        for m in re.finditer(
                r'@(?:app|router)\.(get|post|patch|put|delete)\('
                r'\s*(?:前缀\s*\+\s*)?"([^"]+)"', s):
            出.add((m.group(1).upper(), _归一(m.group(2))))
    return 出


def 被打过():
    """从运行时账本读。**账本不存在 → 返回 None**,而不是空集合 ——
    空集合会让报告说「一条都没验过」,而真相是「没跑过记账」。
    **「没测」和「没查」必须分得开**,这是这个仓库的老规矩。"""
    if not os.path.exists(账本):
        return None
    出 = set()
    for line in open(账本, encoding="utf-8"):
        块 = line.split()
        if len(块) >= 2:
            出.add((块[0].upper(), _归一(块[1])))
    return 出


def 算():
    手 = 有handler()
    打 = 被打过()
    行 = []
    for a in EP.接口表:
        k = (a["方法"], _归一(EP.前缀 + a["路径"]))
        k2 = (a["方法"], _归一(a["路径"]))
        有 = (k in 手) or (k2 in 手)
        if not 有:
            档 = 未实现
        elif 打 is None:
            档 = 未验              # 账本都没有,只能说没验
        else:
            档 = 验过 if k in 打 else 未验
        行.append(dict(方法=a["方法"], 路径=a["路径"], 中文=a["中文"],
                      分组=a["分组"], 形态=a["形态"], 档=档))
    return 行, (打 is not None)


# 页面:从前端那份导航登记表读(`做了` 那一位)
def 页面们():
    s = open(os.path.join(ROOT, "apps", "web", "app.js"), encoding="utf-8").read()
    i = s.index("const 导航 = [")
    段 = s[i:s.index("];", i)]
    出 = []
    for m in re.finditer(r'\["(#[^"]*)",\s*"([^"]+)",\s*(true|false)', 段):
        出.append(dict(路=m.group(1), 名=m.group(2), 做了=m.group(3) == "true"))
    return 出


def 写():
    行, 有账本 = 算()
    页 = 页面们()
    计 = {未实现: 0, 未验: 0, 验过: 0}
    for r in 行:
        计[r["档"]] += 1
    分组 = {}
    for r in 行:
        分组.setdefault(r["分组"], []).append(r)

    出 = []
    w = 出.append
    w("# 实现进度(逐项)\n")
    w("> **这份是生成的** —— `python3 tools/progress_report.py`。手写的进度表第二天就会漂,")
    w("> 而漂的方向永远是「比实际乐观」。\n")
    w("规格 §20:「交付报告逐项写**已实现且验证 / 已实现未验证 / 未实现**,")
    w("禁止用『所有页面都有了』代替完整功能验收」。\n")
    w("## 一句话\n")
    w(f"| 档 | 条数 | 占 87 条 |")
    w("|---|---|---|")
    for 档 in (验过, 未验, 未实现):
        w(f"| {档} | {计[档]} | {计[档] * 100 // len(行)}% |")
    if not 有账本:
        w("\n⚠️ **没有运行时账本,所以「验过」这一列全算成「未验」。**")
        w("这不是「一条都没验过」,是**没查** —— 跑 `make progress` 会先带记账跑一遍测试。")
    w("\n## 判据(以及它有多硬)\n")
    w("| 档 | 判据 | 硬度 |")
    w("|---|---|---|")
    w("| 未实现 | 三个 router 文件里没有对应的装饰器 | **硬** —— 没有 handler 就是真没有 |")
    w("| 已实现未验 | 有 handler,测试没打过 | **硬** |")
    w("| 已实现且验过 | 有 handler,而且测试运行时**真的打到了这条路由** | **中**,见下 |")
    w("")
    w("「验过」用的是**运行时记账**(中间件记 FastAPI 实际匹配到的路由模板),")
    w("不是「在测试文件里搜这条路径的字符串」—— 后者会把「被注释提到」")
    w("「拼在没执行的分支里」也算成验过,**比它声称的弱**。")
    w("")
    w("⚠️ **但「打过一次」不等于「行为被断言对了」。**")
    w("一条被打过、而断言写错了的接口,在这份报告上和真验过的一样 ——")
    w("所以这份报告回答的是「**有没有被碰过**」,不是「对不对」。")
    w("\n## 接口(按分组)\n")
    for 组 in sorted(分组, key=lambda x: (-sum(1 for r in 分组[x] if r["档"] == 验过),
                                        -len(分组[x]))):
        rs = 分组[组]
        好 = sum(1 for r in rs if r["档"] == 验过)
        w(f"### {组} — 验过 {好}/{len(rs)}\n")
        w("| | 接口 | 做什么 |")
        w("|---|---|---|")
        for r in sorted(rs, key=lambda x: x["档"]):
            标 = {验过: "✅", 未验: "🟡", 未实现: "⬜"}[r["档"]]
            w(f"| {标} | `{r['方法']} {r['路径']}` | {r['中文']} |")
        w("")
    w("## 页面\n")
    w(f"侧栏 {len(页)} 个入口,**能点开的 {sum(1 for p in 页 if p['做了'])} 个**。\n")
    w("| | 入口 | |")
    w("|---|---|---|")
    for p in 页:
        w(f"| {'✅' if p['做了'] else '⬜'} | {p['名']} | `{p['路']}` |")
    w("")
    w("⚠️ 标 ⬜ 的入口**保留着并标「未实现」**,不藏起来 ——")
    w("规格 §3:「不能因为没有 GPU,就从需求中删除微调模块」。")
    w("但**保留入口不等于做了**,这份表就是为了让这两件事分得开。")
    w("")
    路 = os.path.join(ROOT, "docs", "实现进度.md")
    open(路, "w", encoding="utf-8").write("\n".join(出) + "\n")
    print(f"写好了:{路}")
    print(f"  {验过} {计[验过]} · {未验} {计[未验]} · {未实现} {计[未实现]}"
          f"{'' if 有账本 else '  ⚠️ 没账本,「验过」算不出来'}")
    return 计, 有账本


# ── 棘轮:实现数和验过数**只许涨不许跌** ─────────────────────────────
#
# 一份生成的进度报告有个天然的弱点:**它永远是绿的** —— 它只是报数,不判对错。
# 于是某次重构悄悄让三条接口失效,报告老老实实把数字从 24 降到 21,而**没人会看见**。
#
# 所以把下限写死。⚠️ **写死成数字,不是 `len(...)` 算出来的** ——
# 从被测的东西自己算出下限,那个下限会跟着一起跌(同源谬误,这个仓库栽过)。
# 往上调这两个数是**做完一件事的收尾动作**,而调它会在 review 里被看见。
实现下限 = 79   # 2026-09-29 设置组:+5(审计记录/成员列表/加成员改权限/预算列表/设预算)
验过下限 = 78   # 同上 —— **写死的数字,不许用 len(...) 现算**(同源谬误)
#
# ⚠️ **2026-09-28:上一版的「验过 50」里有一笔虚账。**
# 加完数据集那五条之后重跑,验过从 50 掉到 49 —— 掉下去的不是新改动弄坏的,
# 是那四条(`GET /traces/{id}` / `POST /feedback` / `GET /evaluations/compare` /
# 人工待办两条)**从来没有可重跑的断言打过**,那个 ✅ 来自我自己在开着
# 路由记账的服务上手敲的几下 curl。
#
# > **「验过」= 有可重跑的断言打过,不是「有人手工试过一次」。**
# > 手工试过一次和从没试过,在这份报告上长得一模一样,而报告是给不在场的人看的。
#
# 棘轮拦住了它,而正确的修法是**把断言补上**(`tests/e2e/test_handover_flow.py`,
# 25 条),不是把下限调低。调低一次,这个数字就再也不代表任何东西了。
#
# ⚠️ 还有一个这份报告本身的弱点,已知但没修:**账本只记「这条路由被打过」,
# 而一个中途崩掉的测试照样会打一串路由**。实测撞到过:数据集那份第二遍
# 崩在一句解包上,而 `POST /datasets` 照样被记成「验过」。
# 兜着它的是 `make progress` 里那条「**任一端到端跑挂 → 不许生成报告**」
# (原来每条都接 `| tail -2`,而管道吞退出码,所以跑挂了报告照样出)。


def 棘轮():
    行, 有账本 = 算()
    实 = sum(1 for r in 行 if r["档"] != 未实现)
    验 = sum(1 for r in 行 if r["档"] == 验过)
    坏 = []
    if 实 < 实现下限:
        坏.append(f"实现数掉了:{实} < 写死的下限 {实现下限} —— "
                  f"**某个 handler 没了,而报告只会老实报数,不会喊**")
    if not 有账本:
        坏.append("没有运行时账本 —— **这不叫通过,叫没查**;跑 make progress")
    elif 验 < 验过下限:
        坏.append(f"验过数掉了:{验} < 写死的下限 {验过下限} —— "
                  f"**有接口不再被测试打到了**")
    return 坏, 实, 验


if __name__ == "__main__":
    if "--棘轮" in sys.argv:
        坏, 实, 验 = 棘轮()
        print(f"  {'❌' if 坏 else '✅'} 实现 {实}/{len(EP.接口表)}(下限 {实现下限})"
              f" · 验过 {验}(下限 {验过下限})")
        for x in 坏:
            print("     ·", x)
        sys.exit(1 if 坏 else 0)
    写()
