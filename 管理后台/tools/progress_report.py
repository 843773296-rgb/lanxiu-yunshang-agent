# ── 棘轮:实现数和验过数**只许涨不许跌** ─────────────────────────────
#
# 一份生成的进度报告有个天然的弱点:**它永远是绿的** —— 它只是报数,不判对错。
# 于是某次重构悄悄让三条接口失效,报告老老实实把数字从 24 降到 21,而**没人会看见**。
#
# 所以把下限写死。⚠️ **写死成数字,不是 `len(...)` 算出来的** ——
# 从被测的东西自己算出下限,那个下限会跟着一起跌(同源谬误,这个仓库栽过)。
# 往上调这两个数是**做完一件事的收尾动作**,而调它会在 review 里被看见。
实现下限 = 95   # 2026-09-29 最后七条:调试×4 + 评测×2 + 改片段 —— **未实现 0**
验过下限 = 94   # 同上 —— **写死的数字,不许用 len(...) 现算**(同源谬误)
#
# ⚠️⚠️ **2026-10-03:下面这段话已经过期了 —— 留着是为了记住它怎么过期的。**
# 它写的是「到这儿契约登记的接口全部实现了…未实现 0」,
# 而当天实测是**未实现 7**(工具筛选那条线的 7 条接口进了契约、而那条线拍了不开)。
#
# **棘轮没拦住这件事**,而它拦不住是设计使然:它守的是
# 「实现数、覆盖数不许跌」,而契约新增条目只会**抬高分母** ——
# 于是「未实现从 0 长到 7」不触发任何红。
#
# > 一句曾经为真的注释,和一句一直为假的注释,**在代码里长得一模一样** ——
# > 而前者更危险:它曾经被验证过,所以读的人更信它。
#
# 现在那 7 条在报告里有专门一节写「为什么不做」(见 `明写不做`)。
#
# ↓↓ 以下是 2026-09-29 当时为真的原话 ↓↓
# **到这儿契约登记的接口全部实现了。** 但**「实现完」不是「做完」**:
#   · 还有 1 条「已实现未验」(`GET /jobs/{id}/events`,SSE 那条)
#   · 侧栏 23 个入口里还有 7 个点不开 —— **接口有了不等于人能用**
#   · 棘轮从此守的是「不许掉下来」,而不再是「往上爬」
#
# ⚠️ **2026-09-28:上一版的「验过 50」里有一笔虚账。**
# 加完数据集那五条之后重跑,验过从 50 掉到 49 —— 掉下去的不是新改动弄坏的,
# 是那四条(`GET /traces/{id}` / `POST /feedback` / `GET /evaluations/compare` /
# 人工待办两条)**从来没有可重跑的断言打过**,那个 ✅ 来自我自己在开着
# 路由记账的服务上手敲的几下 curl。
#
# > **「验过」= 有可重跑的断言打过,不是「有人手工试过一次」。**
# > 手工试过一次和从没试过,在这份报告上长得一模一样,而报告是给不在场的人看的。
#
# 棘轮拦住了它,而正确的修法是**把断言补上**(`tests/e2e/test_handover_flow.py`,
# 25 条),不是把下限调低。调低一次,这个数字就再也不代表任何东西了。
#
# ⚠️ 还有一个这份报告本身的弱点,已知但没修:**账本只记「这条路由被打过」,
# 而一个中途崩掉的测试照样会打一串路由**。实测撞到过:数据集那份第二遍
# 崩在一句解包上,而 `POST /datasets` 照样被记成「验过」。
# 兜着它的是 `make progress` 里那条「**任一端到端跑挂 → 不许生成报告**」
# (原来每条都接 `| tail -2`,而管道吞退出码,所以跑挂了报告照样出)。


def 棘轮():
    行, 有账本 = 算()
    实 = sum(1 for r in 行 if r["档"] != 未实现)
    验 = sum(1 for r in 行 if r["档"] == 验过)
    坏 = []
    if 实 < 实现下限:
        坏.append(f"实现数掉了:{实} < 写死的下限 {实现下限} —— "
                  f"**某个 handler 没了,而报告只会老实报数,不会喊**")
    if not 有账本:
        坏.append("没有运行时账本 —— **这不叫通过,叫没查**;跑 make progress")
