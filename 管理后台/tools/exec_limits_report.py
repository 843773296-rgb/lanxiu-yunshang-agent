    if not 表:
        print("  ❌ 登记表是空的 —— 不叫「全都对」,叫没登记")
        return 1

    红 = []
    计 = {}
    上一个入口 = None
    for 名, 入口, 字段, 文件, 正则, 性质, 为什么 in 表:
        if 入口 != 上一个入口:
            print(f"\n▸ {入口}")
            上一个入口 = 入口
        图, 结论, 是红 = _核一条(名, 入口, 字段, 文件, 正则, 性质, 为什么)
        计[图] = 计.get(图, 0) + 1
        print(f"  {图} {名}  `{字段}`")
        print(f"      {结论}")
        if 是红:
            红.append(名)

