#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""敏感信息检测器的覆盖报告:**漏检和误拦分开报**(用户 2026-09-28 要求)。

    python3 tools/redact_coverage.py

## 为什么不能合成一个数字

「准确率 94%」这种数在这件事上没有意义,因为两种错的**代价完全不对称**:

  · **漏检**(该抓没抓到)—— 客户信息跟着训练数据出去了,**追不回来**
  · **误拦**(不该抓抓了)—— 一条能用的样本被排除了,损失是少一条训练数据

合成一个数,等于让一次泄露和一条样本互相抵消。所以这份报告**两栏分开**,
而且下面这条是关键:

## ⚠️ 「已知盲区内的漏检」和「意外漏检」要分开

姓名那一类**写明了抓不到散在句子里的姓名**。那么「今天周叙来量体」漏掉,
不是回归,是**已知盲区**;而手机号漏掉就是回归。

  · 意外漏检 → **红**
  · 已知盲区内的漏检 → 报出来、计数、列进待办,**不红**
  · 误拦 → **红**(任何一条「正常内容」被拦都算)

不这么分的话只有两个下场:要么盲区让它一直红(于是没人看)、
要么把盲区当通过(于是盲区消失在报告里)。

## ⚠️ 这份报告不回答「数据里有没有敏感信息」

它只回答「**这几个检测器在这些例子上表现如何**」。
零命中不等于没有 —— 那条在 `redact.py` 里由**来源白名单**兜着,不由这份报告兜。
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))), "services", "api", "app"))
import redact as R

G, R_, Y, D = "\033[32m", "\033[31m", "\033[33m", "\033[0m"

# (例子, 该不该命中, 属于哪一类, 如果漏了算不算已知盲区)
# ⚠️ 「该命中」的例子里,**姓名那几条大多落在已知盲区** —— 那是故意的:
#    盲区要在报告里**有名字有计数**,不能只写在注释里。
例子 = [
    # ── 一、必须抓到(漏了就是漏检)──────────────────────────────
    ("联系电话 13912345678,请回拨", True, "手机号", False),
    ("客户手机:139-1234-5678", True, "手机号·分隔写法", False),
    ("手机 139 1234 5678 打不通", True, "手机号·分隔写法", False),
    ("身份证 330102199001011234 已核", True, "身份证", False),
    ("邮箱 zhou.xu@example.com 发过去了", True, "邮箱", False),
    ("浙江省杭州市的客户", True, "地址", False),
    ("杭州市西湖区那位", True, "地址", False),
    ("周先生要加急", True, "姓名·称呼式", False),
    ("小周说下周来", True, "姓名·称呼式", False),

    # ── 二、已知盲区:该抓但这一版抓不到 ────────────────────────
    #    ⚠️ 这几条**不让报告变红**,但必须逐条出现在「已知盲区内的漏检」里。
    ("今天周叙来量体,袖长要放 2 公分", True, "姓名·称呼式", True),
    ("晏巡川的那件云锦改好了", True, "姓名·称呼式", True),
    ("电话１３９１２３４５６７８(全角)", True, "手机号", True),
    ("旧身份证 330102900101123", True, "身份证", True),
    ("西湖区文三路 100 号送货", True, "地址", True),
    ("住我家隔壁那位客户", True, "地址", True),
    ("手机尾号 5678 的那个", True, "手机号", True),

    # ── 三、绝不能抓(抓了就是误拦)──────────────────────────────
    #    ⚠️ 头四条是**真实语料里量出来的**:不锚定的手机号正则在 5402 行
    #    会话记录上命中 683 行,而那 683 个全是这种浮点尾数,真阳性 0 个。
    ('{"sdk_cost_usd": 0.15664500000000003}', False, "成本数字", False),
    ('{"sdk_cost_usd": 0.022189900000000002}', False, "成本数字", False),
    ('{"cost": 0.026041900000000003, "ok": true}', False, "成本数字", False),
    ('{"参考价": 0.021510500000000002}', False, "成本数字", False),
    ("订单号 A13912345678X 已发货", False, "单号", False),
    ("这批 13912345678901 是流水号", False, "长数字", False),
    ("小票要一起给客户", False, "普通词", False),
    ("老款立领改成新款", False, "普通词", False),
    ("杭州的天气不错", False, "只有城市名", False),
    ("这件云锦用的是妆花工艺", False, "普通业务话", False),
    ("input_tokens 1390 output_tokens 240", False, "用量数字", False),
]


def main():
    漏检, 盲区漏检, 误拦, 对 = [], [], [], 0
    for 文, 该命中, 类, 是盲区 in 例子:
        命中 = R.扫一条(文)
        有 = bool(命中)
        if 该命中 and not 有:
            (盲区漏检 if 是盲区 else 漏检).append((文, 类))
        elif (not 该命中) and 有:
            误拦.append((文, 类, [n for n, _ in 命中]))
        else:
            对 += 1

    print(f"\n\033[1m▸ 敏感信息检测覆盖 · 漏检和误拦分开报\033[0m")
    print(f"  例子 {len(例子)} 条 · 判对 {对} 条")

    print(f"\n  \033[1m漏检(该抓没抓到)\033[0m —— 代价:客户信息跟着训练数据出去,**追不回来**")
    if 漏检:
        print(f"    {R_}❌ 意外漏检 {len(漏检)} 条(这是回归){D}")
        for 文, 类 in 漏检:
            print(f"       [{类}] {文[:44]}")
    else:
        print(f"    {G}✅ 意外漏检 0 条{D}")
    print(f"    {Y}⚠️ 已知盲区内的漏检 {len(盲区漏检)} 条 —— 不红,但它们是待办不是免责{D}")
    for 文, 类 in 盲区漏检:
        print(f"       [{类}] {文[:44]}")

    print(f"\n  \033[1m误拦(不该抓抓了)\033[0m —— 代价:能用的样本被排除,少一条训练数据")
    if 误拦:
        print(f"    {R_}❌ 误拦 {len(误拦)} 条{D}")
        for 文, 类, 命 in 误拦:
            print(f"       [{类}] {文[:40]} → 被判成 {命}")
    else:
        print(f"    {G}✅ 误拦 0 条{D}")
        print(f"       (其中四条是真实语料里量出来的浮点尾数 —— "
              f"不锚定的手机号正则在 5402 行会话上命中 683 行,**真阳性 0 个**)")

    print(f"\n  \033[1m每一类的已知盲区\033[0m(不写盲区的检测器会被当成「扫过了就安全」)")
    for x in R.盲区表():
        print(f"    · {x['类别']}:查的是{x['查的是']}")
        print(f"        盲区:{x['已知盲区']}")

    print(f"\n  \033[1m放行规则\033[0m")
    print(f"    覆盖已验证的来源:{list(R.覆盖已验证的来源)} —— **只有这些来源零命中才自动放行**")
    print(f"    其余来源一律隔离。⚠️ **零命中不等于没有敏感信息**,")
    print(f"    它只说明这几个检测器没找到 —— 而上面那张盲区表说明了它们找不到什么。")

    坏 = len(漏检) + len(误拦)
    print(f"\n{'✅' if not 坏 else '❌'} 意外漏检 {len(漏检)} · 误拦 {len(误拦)}"
          f" · 已知盲区 {len(盲区漏检)}(不计入红)")
    return 1 if 坏 else 0


if __name__ == "__main__":
    sys.exit(main())
