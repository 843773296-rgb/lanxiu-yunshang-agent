#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""**没有任何已发布策略时用的那套上限** —— 零 IO。

业务 2026-10-06 在「拒绝启动 / 只记录不拦 / 内置兜底」三条里选了**兜底**。
判据不是省事,是**消掉「无限制」这个档**:

> 一个「没有策略所以不限制」的运行,和一个「策略说了不限制」的,
> **在运行记录上长得一模一样。**

## 这一组钉三件事

**① 数字有出处。** 全部来自规格 §5.3 那张表,而那一节开头写着
   「可替换的测试起点,**不是行业标准,也不是当前生产配置**」——
   这句话要**跟着数字进运行记录**,不能只写在注释里。

**② 只填真有执行点的键。** 规格 §2.2:「一个入口上过了的限制,
   **在另一个入口上可能根本没有执行点**」。
   > 一条**填得进去而没人读**的上限,和一条真在执行的,
   > **在配置表上长得一模一样。**
   ⚠️ 而这一条**不靠记忆验** —— 第 ③ 节直接拿
   `tools/exec_limits_report.py` 的登记表对账(那份是每次门禁现查的)。

**③ 兜底不是回退。** `回退` 指「上一次**已验证的本地**策略」,
   带版本/年龄/原因/有效期(规格 §4.3 要求四样都显示)。
   兜底一样都没有,也不会过期。
   > 一次「用了上周验证过的那一版」和一次「用了代码里写死的默认值」,
   > **在那个「回退」标签上长得一模一样** —— 而前者是业务配过的。
"""
import os
import sys

_根 = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
# ⚠️ `_根` 往上三层已经是 `管理后台` 了 —— 照 `test_policy_resolve.py` 那一行写。
# 第一版我多拼了一层 `管理后台`,于是 import 报「没有这个模块」,
# 而那句报错**和「这个模块真的不存在」长得一模一样**。
sys.path.insert(0, os.path.join(_根, "services", "api", "app", "runtime"))
sys.path.insert(0, os.path.join(_根, "tools"))

import 兜底上限 as B
import 策略冻结 as F

G, R, D = "\033[32m", "\033[31m", "\033[0m"
过, 挂 = 0, 0


def ck(说, ok, 附=""):
    global 过, 挂
    if ok:
        过 += 1
        print(f"  {G}✅{D} {说}  {附}")
    else:
        挂 += 1
        print(f"  {R}❌{D} {说}  {附}")


print("▸ ① 数字的出处 —— 规格 §5.3 那张表,逐字")
后 = B.兜底(入口=F.后台编排)
店 = B.兜底(入口=F.门店V3)
ck("后台 Loop 模型请求上限 = 8", 后["limits"]["model_request_cap"] == 8,
   后["limits"]["model_request_cap"])
ck("后台 Loop 工具尝试上限 = 12", 后["limits"]["tool_attempt_cap"] == 12,
   后["limits"]["tool_attempt_cap"])
ck("门店 V3 的 SDK 轮数 = 12,**不是 8**(规格明写「不因本规格自动改成 8」)",
   店["limits"]["sdk_turn_cap"] == 12, 店["limits"]["sdk_turn_cap"])
ck("那句「不是当前生产配置」跟着数字进了返回值",
   "不是当前生产配置" in 后["这些数字是什么"])
ck("还带一句「这不是业务配的」(否则界面上和正常采用一样)",
   "不是业务配的" in 后["⚠️"])

print("\n▸ ② 键名和冻结那边同一套(两套键名分叉时,冻结会报「认不出」而兜底照跑)")
for 入, d in B._兜底limits.items():
    for k in d:
        ck(f"{入} 的 `{k}` 在 `策略冻结.认得的limits键` 里",
           k in F.认得的limits键)

print("\n▸ ③ 🔑 只填真有执行点的键 —— **拿现查的那份报告对账,不靠记忆**")
import exec_limits_report as X
# 登记表每条:(上限名, 入口, 配置字段, 文件, 正则, 性质, 为什么)
性质 = {}
for 条 in X.登记:
    性质.setdefault(条[2], set()).add(条[5])
欠着的 = {X.已建待接, X.待建, X.没人读}
坏 = []
for 入, d in B._兜底limits.items():
    for k in d:
        有 = 性质.get(k, set())
        if 有 & 欠着的:
            坏.append(f"{入}/{k} 在报告里是 {sorted(有)}")
ck("兜底里没有一个键在报告里标着「已建待接 / 待建 / 没人读」", not 坏, 坏)

# 反向也验:**报告里标着欠账的那几个键,确实被挡在兜底外面**。
# ⚠️ 少了这一条,上一条证明不了任何事 ——
# > 一个「登记表里压根没有这些键」的情况,和一个「真把它们挡住了」的,
# > **在上一条断言上长得一模一样**(两边都是「没有命中」)。
欠账键 = sorted(k for k, v in 性质.items() if v & 欠着的)
ck(f"报告里确实有欠账的键可挡(挡住了 {len(欠账键)} 个)", len(欠账键) >= 3, 欠账键[:6])
for k in ("tool_timeout_seconds", "task_deadline_seconds"):
    ck(f"`{k}` 在报告里是欠账,所以不在任何兜底里",
       k in 欠账键 and all(k not in d for d in B._兜底limits.values()))

print("\n▸ ④ 故意不给数字的,各自说得出原因")
# > 一条「想清楚了不填」的上限,和一条「忘了填」的,
# > **在那份兜底里长得一模一样。**
for 入, 兜 in ((F.后台编排, 后), (F.门店V3, 店)):
    ck(f"{入} 的「故意不给」不是空的", bool(兜["故意不给数字的"]),
       sorted(兜["故意不给数字的"]))
    ck(f"{入} 每条原因都有话",
       all(v.strip() for v in 兜["故意不给数字的"].values()))
    ck(f"{入}:故意不给的键**不和已给的重叠**",
       not (set(兜["故意不给数字的"]) & set(兜["limits"])))

print("\n▸ ⑤ 兜底不是回退,也不是采用")
ck("来源那一栏里没有「回退」两个字", "回退" not in 后["来源"], 后["来源"])
ck("没有版本号 —— **None 是「没有」,不是 0**", 后["版本"] is None, 后["版本"])
# ⚠️ 这一条第一版写成了 `ck(..., True)` —— **一条永远真的断言**。
# 要求实例支持某个限制,`策略解析` 就会去核能力,核不过是「拒绝启动」——
# 而兜底的全部意义是让它跑得起来。所以这一栏必须是空的,**而且要看得见**。
ck("不要求实例支持任何东西(要求了就会去核能力,核不过就拒绝启动)",
   后["support_conditions"] == [] and 店["support_conditions"] == [],
   (后["support_conditions"], 店["support_conditions"]))
ck("算得出内容哈希(能和已发布的那一版比对)",
   isinstance(后["内容哈希"], str) and len(后["内容哈希"]) == 64)
ck("两个入口的兜底哈希不同(入口算进哈希)",
   后["内容哈希"] != 店["内容哈希"])
ck("同一个入口两次调用哈希一样(确定性)",
   B.兜底(入口=F.后台编排)["内容哈希"] == 后["内容哈希"])

print("\n▸ ⑥ 认不出的入口 / 空兜底 —— 都当场抛")
try:
    B.兜底(入口="通用")
    ck("认不出的入口 → 抛", False, "它没抛")
except B.没有兜底 as e:
    ck("认不出的入口 → **抛**(不给「通用兜底」留口子)", "通用" in str(e))
原 = B._兜底limits[F.后台编排]
try:
    B._兜底limits[F.后台编排] = {}
    try:
        B.兜底(入口=F.后台编排)
        ck("空兜底 → 抛", False, "它没抛")
    except B.没有兜底 as e:
        ck("空兜底 → **抛**(空兜底就是无限制,那个档被拍掉了)",
           "无限制" in str(e))
finally:
    B._兜底limits[F.后台编排] = 原

print("\n" + "=" * 92)
if 挂:
    print(f"{R}❌ 过 {过} / 挂 {挂}{D}")
    sys.exit(1)
print(f"{G}✅ 过 {过} / 挂 {挂}{D}")
