#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""术语配置 / 语义层的纯函数(2026-11-06)。不要数据库。真调 runtime/术语.py。

  ① 最长匹配:「宋制对襟长褙」命中长的那条,里面的「褙」不再单独算;短词是长词前缀时(到店 / 到店率)对到长的;同一标准词只报第一次
  ① 英文 / 数字叫法要词边界(ROI 不命中 ROIC、15 不命中 115;中文挨着不算破坏边界)
  ② 标准词自己也算叫法;一条都没提到 → 空列表
  ③ **短叫法的坑**(项目记过「香云纱」里有「纱」):长词录了 → 对到长词;长词没录 → 误对到短词(这是最长匹配的已知限定,钉住)
  ④ 交给模型的那一段**只有这次提到的**(用户拍):没提到的一条都不带;一条都没提到 → 空串;指标带口径和取数口
  ⑤ 格式检查:标准词空 / 重复、同一叫法对两个标准词、指标缺口径 → 阻断;短叫法是长叫法的一部分 → 提醒(不阻断)
  ⑥ 注入():有命中才记 glossary.injected(带了哪几条)、返回的段只含命中的;没命中不记事件、返回空串
  ⑦ 接线(读 worker.py 的语法树,不起 worker —— e2e 的作业会被跑主检出代码的常驻 worker 抢走,副本里改坏看不见):
     两处取段的函数都走 注入();模型步骤 live / mock 两支都拿同一段文本去匹配;Agent 步骤先换上这一步的任务再匹配;
     两处 Agent 都把段拼在指令前面
  ⑧ 通称(11-07):同一通称可挂多条、说通称时这几条一起带并附「先问清是哪一款」;说全名只对那一条;
     通称同时又当叫法 → 阻断;只挂一条 → 提醒
"""
import os
import sys

_根 = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(_根, "services", "api", "app", "runtime"))
import 术语 as T  # noqa: E402
import ast  # noqa: E402

过, 挂 = [], []


def ck(名, 真, 补=""):
    print(f"  {'✅' if 真 else '❌'} {名}{('  ' + str(补)[:300]) if 补 and not 真 else ''}")
    (过 if 真 else 挂).append(名)


表 = [
    {"标准词": "褙子", "叫法": ["褙", "长褙"], "类别": "名词", "定义": "宋制对襟长衣"},
    {"标准词": "宋制对襟长褙", "叫法": [], "类别": "名词", "定义": "宋制褙子里衣长过膝的那一种"},
    {"标准词": "到店率", "叫法": ["到店转化", "预约到店比"], "类别": "指标", "定义": "预约了的顾客里真到店的比例",
     "口径": {"分子": "到店的预约数", "分母": "预约数(不含已取消)", "时间": "按预约日期"},
     "取数口": {"工具": "appt_funnel", "说明": "按门店 / 周取"}},
    {"标准词": "纱", "叫法": [], "类别": "名词", "定义": "轻薄透气的织物"},
]


def main():
    命 = T.匹配("想做一件宋制对襟长褙,上周到店转化怎么样", 表)
    ck("① 最长匹配:命中「宋制对襟长褙」而不是里面的「褙」;按出现顺序;叫法「到店转化」对到「到店率」",
       [h["标准词"] for h in 命] == ["宋制对襟长褙", "到店率"] and 命[1]["命中的叫法"] == "到店转化", 命)
    前缀 = 表 + [{"标准词": "到店", "叫法": [], "类别": "名词", "定义": "顾客来到门店"}]
    ck("① 短词是长词的前缀(「到店」/「到店率」)→ 对到长的「到店率」(这条专门造来区分最长 / 最短优先)",
       [h["标准词"] for h in T.匹配("上周到店率多少", 前缀)] == ["到店率"], T.匹配("上周到店率多少", 前缀))
    英 = [{"标准词": "投入产出比", "叫法": ["ROI"], "类别": "名词", "定义": "x"}, {"标准词": "十五天", "叫法": ["15"], "类别": "名词", "定义": "x"}]
    ck("① 英文 / 数字叫法要词边界:「ROIC」「115」不命中;「这次ROI多少」「ROI。」「第15天」照样命中(中文挨着不算破坏边界)",
       T.匹配("ROIC 怎么算,还有 115 天", 英) == []
       and [h["标准词"] for h in T.匹配("这次ROI多少,第15天", 英)] == ["投入产出比", "十五天"], (T.匹配("ROIC 怎么算,还有 115 天", 英), T.匹配("这次ROI多少,第15天", 英)))
    命 = T.匹配("褙子和长褙都要,褙子再来一件", 表)
    ck("① 同一标准词只报第一次(褙子 / 长褙都对到「褙子」)", [h["标准词"] for h in 命] == ["褙子"], 命)
    ck("② 标准词自己也算叫法;一条都没提到 → 空列表",
       [h["标准词"] for h in T.匹配("到店率多少", 表)] == ["到店率"] and T.匹配("今天天气不错", 表) == [])
    长 = 表 + [{"标准词": "香云纱", "叫法": [], "类别": "名词", "定义": "广东传统丝织物"}]
    ck("③ 长词录了 → 「香云纱」对到「香云纱」、不对到「纱」", [h["标准词"] for h in T.匹配("香云纱的", 长)] == ["香云纱"])
    ck("③ 长词没录 → 「香云纱」误对到「纱」(最长匹配的已知限定,靠补词表;格式检查会提醒)",
       [h["标准词"] for h in T.匹配("香云纱的", 表)] == ["纱"])

    段 = T.上下文段(T.匹配("上周到店转化怎么样", 表), 表)
    ck("④ 交给模型的只有这次提到的那条(到店率),没提到的(褙子 / 纱)一条都不带",
       "到店率" in 段 and "褙子" not in 段 and "纱" not in 段, 段)
    ck("④ 指标那条带着口径(分母不含已取消)和取数口(调 appt_funnel)", "不含已取消" in 段 and "appt_funnel" in 段, 段)
    ck("④ 一条都没提到 → 空串(不带一个空壳标题)", T.上下文段([], 表) == "")

    阻, 醒 = T.格式问题(表)
    ck("⑤ 合格的表 → 没有阻断;「褙」是「宋制对襟长褙」的一部分 → 提醒(不阻断)",
       阻 == [] and any("「褙」" in x and "宋制对襟长褙" in x for x in 醒), (阻, 醒))
    阻, _ = T.格式问题([{"标准词": "", "定义": "x"}, {"标准词": "A", "定义": "x"}, {"标准词": "A", "定义": "y"},
                        {"标准词": "B", "叫法": ["甲"], "定义": "x"}, {"标准词": "C", "叫法": ["甲"], "定义": "x"},
                        {"标准词": "D", "类别": "指标", "定义": "x"}, {"标准词": "E", "类别": "乱写", "定义": "x"},
                        {"标准词": "F"}])
    ck("⑤ 阻断:标准词空 / 重复 / 同一叫法对两个标准词 / 指标缺口径 / 类别认不出 / 缺定义 —— 各报一条",
       len(阻) == 6 and any("同时对到" in x for x in 阻) and any("口径" in x for x in 阻), 阻)
    事 = []
    段 = T.注入("上周到店转化怎么样", 表, "glv_x", lambda k, v: 事.append((k, v)))
    ck("⑥ 注入():命中就记一条 glossary.injected(版本 + 带了哪几条),段里只有命中的",
       事 == [("glossary.injected", {"术语版本": "glv_x", "带了": ["到店率"]})] and "到店率" in 段 and "褙子" not in 段, (事, 段))
    事 = []
    ck("⑥ 注入():一条都没提到 → 不记事件、返回空串", T.注入("今天天气不错", 表, "glv_x", lambda k, v: 事.append((k, v))) == "" and 事 == [], 事)

    # ⑧ 通称(11-07 用户拍「收,带上所有朝代」)
    通表 = [{"标准词": "宋制褙子", "叫法": [], "通称": ["褙子"], "定义": "宋款_chk"},
           {"标准词": "宋制长褙子", "叫法": ["长褙子"], "通称": ["褙子"], "定义": "宋长款_chk"},
           {"标准词": "唐制圆领缺胯袍", "叫法": ["缺胯袍"], "通称": ["圆领袍"], "定义": "唐款_chk"},
           {"标准词": "明制圆领袍", "叫法": ["常服袍"], "通称": ["圆领袍"], "定义": "明款_chk"}]
    命 = T.匹配("褙子能敞着穿吗", 通表)
    ck("⑧ 说通称「褙子」→ 挂了这个通称的两条都带(宋制褙子、宋制长褙子),都标是通称命中",
       [(h["标准词"], h.get("通称")) for h in 命] == [("宋制褙子", True), ("宋制长褙子", True)], 命)
    ck("⑧ 说全名「唐制圆领缺胯袍」→ 只对到那一条(全名比通称长,最长匹配照旧),不把明制带上",
       [h["标准词"] for h in T.匹配("唐制圆领缺胯袍怎么量", 通表)] == ["唐制圆领缺胯袍"])
    段 = T.上下文段(T.匹配("圆领袍能做吗", 通表), 通表)
    ck("⑧ 通称命中时段里两条定义都在,并附一句「是通称,先问清是哪一款」",
       "唐款_chk" in 段 and "明款_chk" in 段 and "是通称" in 段 and "先问清" in 段, 段)
    ck("⑧ 没走通称的段里不出现那句提醒", "是通称" not in T.上下文段(T.匹配("缺胯袍", 通表), 通表))
    阻, 醒 = T.格式问题(通表)
    ck("⑧ 同一个通称挂在多条上 → 不阻断(这正是通称的用途);通称是自己全名的一部分不报提醒", 阻 == [] and 醒 == [], (阻, 醒))
    阻, _ = T.格式问题(通表 + [{"标准词": "披风", "叫法": ["褙子"], "定义": "d"}])
    ck("⑧ 同一个词既当某条的叫法又当通称 → 阻断(叫法照旧不许对两个标准词)",
       len(阻) == 1 and "又是通称" in 阻[0], 阻)
    _, 醒 = T.格式问题([{"标准词": "宋制褙子", "通称": ["褙子"], "定义": "d"}])
    ck("⑧ 通称只挂一条 → 提醒「写进叫法就行」", any("只挂在" in x for x in 醒), 醒)

    源 = open(os.path.join(_根, "workers", "worker.py"), encoding="utf-8").read()
    树 = ast.parse(源)
    函 = {n.name: n for n in ast.walk(树) if isinstance(n, ast.FunctionDef)}

    def 调了(节点, 名):
        return [x for x in ast.walk(节点) if isinstance(x, ast.Call)
                and ((isinstance(x.func, ast.Name) and x.func.id == 名) or (isinstance(x.func, ast.Attribute) and x.func.attr == 名))]
    ck("⑦ 两处取段的函数(工作流 _术语段 / Agent _Agent术语段)都走 注入()(不各写一份匹配 + 记事件)",
       all(调了(函[f], "注入") for f in ("_术语段", "_Agent术语段") if f in 函) and {"_术语段", "_Agent术语段"} <= set(函), sorted(函)[:0])
    同段 = [x for x in 调了(树, "_术语段") if x.args and isinstance(x.args[0], ast.Call)
            and isinstance(x.args[0].func, ast.Name) and x.args[0].func.id == "_这一步的文本"]
    ck("⑦ 模型步骤 live / mock 两支都调 _术语段(_这一步的文本(...)) —— 同一段文本(原来 mock 只匹配输入,CI 验到的不是 live 的行为)",
       len(同段) == 2 and len(调了(树, "_术语段")) == 2, (len(同段), len(调了(树, "_术语段"))))
    live = [n for n in ast.walk(函.get("_按节点llm", 树)) if isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "系统" for t in n.targets)
            and isinstance(n.value, ast.BinOp) and isinstance(n.value.left, ast.Name) and n.value.left.id == "段"]
    ck("⑦ live 那一支把段拼在系统提示**前面**(系统 = 段 + …)", len(live) == 1, len(live))
    行 = 源.split("\n")
    任务行 = [i for i, x in enumerate(行) if 'acfg["task_template"] = 包["任务"]' in x]
    取段行 = [i for i, x in enumerate(行) if "_段 = _Agent术语段(c, job[\"project_id\"], acfg" in x]
    ck("⑦ 工作流里的 Agent 步骤:先换上这一步的任务,再匹配术语(原来排在前面,匹配的是版本里的模板)",
       len(任务行) == 1 and len(取段行) == 1 and 任务行[0] < 取段行[0], (任务行, 取段行))
    拼 = [i for i, x in enumerate(行) if 'acfg["instructions"] = _段 + ' in x or "instructions=_段 + " in x]
    ck("⑦ 两处 Agent(工作流里的步骤 / 单独跑)都把段拼在指令前面", len(拼) == 2, 拼)
    print()
    if 挂:
        print(f"❌ {len(挂)} 条不过:{' / '.join(挂)}")
        return 1
    print(f"✅ 术语配置 / 语义层:{len(过)} 条全过")
    return 0


if __name__ == "__main__":
    sys.exit(main())
