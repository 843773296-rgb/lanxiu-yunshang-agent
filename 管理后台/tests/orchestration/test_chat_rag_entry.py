#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""chat 的检索入口(A3)—— **零 IO**。业务 2026-10-08 拍的两条,判据在这儿。

接上 chat 那天,拍板的那两条很容易在某次重构里被「顺手优化掉」,
而**优化掉它们的后果都是不报错的**:

   ① 加一条退路(查不到就退回 `mcp/kb`)→ 顾问看到的是一段正常的回答,
      而他不知道那句话**没有知识库的出处**
   ② 加一个「这个问题要不要查知识库」的判断 → 省了钱,
      而判断错的那些问题**答得没有出处,也没人知道**

所以这一份盯的是「**那两条还在不在**」,而不是「它跑得起来」
(跑得起来由 `test_knowledge_flow.py` 真调模型验)。

## ⚠️ 还有一条更锋利的:**两套角色词表对不上**

语料 ACL 用管理后台的词表(viewer/editor/…),chat 那边是岗位
(门店顾问/工坊排产/后台运营)。而**今天两级 ACL 全是空的** ——
传错角色名也「看起来能用」(什么都过滤不掉)。
> 一个「权限接对了」的接口,和一个「两套词表碰巧都没生效」的,
> **在今天的检索结果上长得一模一样。**
所以入口**当场拒**词表外的名字。这一份钉住那条拒绝。
"""
import io
import os
import re
import sys

_根 = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
G, R, D = "\033[32m", "\033[31m", "\033[0m"
过, 挂 = 0, 0


def ck(说, ok, 附=""):
    global 过, 挂
    if ok:
        过 += 1
        print(f"  {G}✅{D} {说}  {附}")
    else:
        挂 += 1
        print(f"  {R}❌{D} {说}  {附}")


源 = io.open(os.path.join(_根, "services", "api", "app", "knowledge_api.py"),
            encoding="utf-8").read()
# 只取这条接口那一段(整文件太大,别的接口里有别的东西)
起 = 源.index("async def chat问一次知识库")
那一段 = 源[起:]
契约 = io.open(os.path.join(_根, "services", "api", "app", "contract",
                          "endpoints.py"), encoding="utf-8").read()

print("=" * 92)
print("chat 的检索入口 · 业务拍的那两条还在不在(零 IO)")
print("=" * 92)

print("\n▸ ① 这条路断了就报错,**不退回澜绣自己的 mcp/kb**")
ck("🔑 这一段里**没有** mcp / kb 的退路(一处都没有)",
   "mcp_kb" not in 那一段 and "mcp/kb" not in 那一段.split('"""')[2:][0]
   if len(那一段.split('"""')) > 2 else True)
ck("挑不到已就绪索引 → `NO_READY_INDEX`,而且**说清了不退回**",
   "NO_READY_INDEX" in 那一段 and "不退回「没找到相关内容」" in 那一段)
ck("没凭据 / 精排失败 → 503,**不降级成只走向量**"
   "(那个排序不可靠:实测一个表格头排到过第 1 名)",
   "NO_MODEL_CREDENTIAL" in 那一段 and "不降级" in 那一段)
ck("生成跑不成**不编一段话** —— `答案` 是 None,"
   "而 `为什么没有答案` 说清是哪一种",
   '"答案": (生.get("答案") if 生.get("做了") else None)' in 那一段
   and '"为什么没有答案"' in 那一段)
# ⚠️ 这一条是「反向」判据:**源码里不许出现退路的那几种写法**。
# 而「我记得我没写」和「它真的不在」是两件事。
退路词 = [w for w in ("退回", "fallback", "降级成", "兜底") if w in 那一段]
ck("源码里出现 `退路/降级` 这类词的地方,**都是在说「不这么做」**",
   all(any(否 + w in 那一段 or w + "」" in 那一段
           for 否 in ("不", "没有", "**不"))
       for w in 退路词), f"出现的词:{退路词}")

print("\n▸ ② 每次都查 —— 不自己判断「要不要查」")
ck("🔑 入参里**没有**「要不要检索 / 要不要查」这种开关",
   not re.search(r"要不要(检索|查)[^,。)]*=\s*体\.get", 那一段))
ck("而这件事**写在文档里**(和 `rewriter` 不自己判断要不要改写同一条理由)",
   "不自己判断" in 源[:起] or "不自己判断" in 那一段)
ck("契约登记里也写明了这两条(别人读清单就能看到)",
   "不退回澜绣自己的 mcp/kb" in 契约 and "每次都查" in 契约)

print("\n▸ ③ 角色:白名单,**不给默认值**")
ck("🔑 词表外的角色名 → `UNKNOWN_ROLE` **当场拒**",
   "UNKNOWN_ROLE" in 那一段)
ck("↳ 而且错误里说清了**为什么今天传错也「看起来能用」**"
   "(ACL 全空 → 什么都过滤不掉)",
   "今天两级 ACL 全是空的" in 那一段)
ck("↳ 也说清了岗位名**不是**这套词表(映射要业务先拍)",
   "门店顾问" in 那一段 and "不是这套词表" in 那一段.replace("**", ""))
ck("角色漏传 → 当场 422,**没有「没传就不过滤」这条路**",
   "必填,而且是个非空清单" in 那一段
   and "静默放开语料" in 那一段)
ck("用的是 `perms` 的词表,**不自己抄一份**(抄的那份会和权限页漂)",
   "PM.角色们" in 那一段)

print("\n▸ ④ 一次 chat 检索要留下什么")
ck("进**同一张** `retrieval_runs`,来源记 `chat`",
   '来源="chat"' in 那一段)
ck("返回里**一定有 `试跑id`** —— 顾问评价那一下要用它",
   '"试跑id"' in 那一段)
ck("而且告诉调用方**怎么评价**(5 档走和实验室同一条路)",
   "怎么评价这一次" in 那一段 and "rating" in 那一段)
ck("记账也走同一处(精排 + 生成各一笔)",
   "记这次检索的账" in 那一段)

print("\n▸ ⑤ 方向是单向的:澜绣调,管理后台答")
ck("模块头写明**管理后台绝不反过来查澜绣的库**"
   "(互相依赖会让「谁先起来」在部署那天才暴露)",
   "绝不反过来" in 源)

print("\n" + "=" * 92)
if 挂:
    print(f"{R}❌ 过 {过} / 挂 {挂}{D}")
    sys.exit(1)
print(f"{G}✅ 过 {过} / 挂 {挂}{D}")
