# -*- coding: utf-8 -*-
"""定时触发的时间口径(10-26,方案 §8.5)—— **期望值全部手写**,不是跑一遍抄回来。

日期挑的是会出错的地方:周一 / 周日、月初 / 月末、跨年、闰年二月、8:00 前后一分钟、时区换算(UTC 晚上 = 北京次日早上)。
"""
import os
import sys
from datetime import date, datetime, timezone, timedelta

_这 = os.path.dirname(os.path.abspath(__file__))
根 = os.path.dirname(os.path.dirname(_这))
sys.path.insert(0, os.path.join(根, "services", "api", "app", "runtime"))
import 定时 as T  # noqa: E402

过, 挂 = [], []


def ck(名, 真, n, 补=""):
    print(f"  {'✅' if 真 else '❌'} {名}(验了 {n} 个){'  ' + str(补)[:190] if 补 else ''}")
    (过 if 真 else 挂).append(名)


北京 = timezone(timedelta(hours=8))
日, 周, 月 = (T.校验规则({"周期": p}) for p in ("日", "周", "月"))

print("▸ 统计哪一段(两头都含)")
例 = [  # (规则, 执行日, 期望起, 期望止, 为什么)
    (日, date(2026, 10, 27), date(2026, 10, 26), date(2026, 10, 26), "日报 = 前一天"),
    (日, date(2026, 1, 1), date(2025, 12, 31), date(2025, 12, 31), "跨年"),
    (周, date(2026, 10, 26), date(2026, 10, 19), date(2026, 10, 25), "周一跑 → 上周一到上周日,不是过去 7 天"),
    (周, date(2026, 1, 5), date(2025, 12, 29), date(2026, 1, 4), "跨年的那一周"),
    (月, date(2026, 11, 1), date(2026, 10, 1), date(2026, 10, 31), "月报 = 上一个自然月"),
    (月, date(2026, 3, 1), date(2026, 2, 1), date(2026, 2, 28), "平年二月 28 天"),
    (月, date(2028, 3, 1), date(2028, 2, 1), date(2028, 2, 29), "闰年二月 29 天"),
    (月, date(2027, 1, 1), date(2026, 12, 1), date(2026, 12, 31), "跨年的月报"),
]
坏 = [(w, T.统计区间(r, d), (o, z)) for r, d, o, z, w in 例 if T.统计区间(r, d) != (o, z)]
ck("每种周期在月初 / 月末 / 跨年 / 闰年都对", not 坏, len(例), 坏)

print("\n▸ 下次什么时候跑")
现 = datetime(2026, 10, 26, 7, 59, tzinfo=北京)           # 周一 7:59
ck("周一 7:59 → 周报今天 8:00 就跑", T.下次执行(周, 现)[0] == datetime(2026, 10, 26, 8, 0, tzinfo=北京), 1, T.下次执行(周, 现))
现 = datetime(2026, 10, 26, 8, 0, tzinfo=北京)
ck("周一 8:00 整(刚跑过)→ 下一次是下周一", T.下次执行(周, 现)[0].date() == date(2026, 11, 2), 1, T.下次执行(周, 现))
现 = datetime(2026, 10, 26, 23, 30, tzinfo=timezone.utc)   # = 北京 10-27 7:30
ck("**时区换算**:UTC 10-26 23:30 = 北京 10-27 7:30 → 日报下一次是北京 10-27 8:00,统计 10-26",
   T.下次执行(日, 现)[0].astimezone(北京) == datetime(2026, 10, 27, 8, 0, tzinfo=北京)
   and T.下次执行(日, 现)[1] == date(2026, 10, 26), 1, T.下次执行(日, 现))
ck("月报在 10-26 → 下一次 11-01,统计 10 月整月",
   T.下次执行(月, datetime(2026, 10, 26, 12, 0, tzinfo=北京))[1:] == (date(2026, 10, 1), date(2026, 10, 31)), 1)

print("\n▸ 该不该发起:同一期只一次、关机只补最近一期、设定之前的不算错过")
设 = datetime(2026, 10, 1, 9, 0, tzinfo=北京)
r = T.该发起吗(日, datetime(2026, 10, 26, 8, 1, tzinfo=北京), 上次统计起=date(2026, 10, 24), 设定于=设)
ck("日报:上次跑的是 10-24 那期,今天 8:01 → 发起 10-25 那期", r["发起"] and r["发起"][1] == date(2026, 10, 25) and not r["错过"], 1, r)
r = T.该发起吗(日, datetime(2026, 10, 26, 8, 1, tzinfo=北京), 上次统计起=date(2026, 10, 25), 设定于=设)
ck("**这一期已经发起过 → 不再发起**(重启、重发都不多跑)", r["发起"] is None, 1, r)
r = T.该发起吗(日, datetime(2026, 10, 26, 8, 1, tzinfo=北京), 上次统计起=date(2026, 10, 20), 设定于=设)
ck("**关机错过了 21—24 四期 → 只发起最近的 25 号,其余四期列出来不补**",
   r["发起"][1] == date(2026, 10, 25) and [x[0] for x in r["错过"]] == [date(2026, 10, 24), date(2026, 10, 23), date(2026, 10, 22), date(2026, 10, 21)],
   1, r)
r = T.该发起吗(周, datetime(2026, 10, 27, 10, 0, tzinfo=北京), 上次统计起=None, 设定于=datetime(2026, 10, 27, 9, 0, tzinfo=北京))
ck("周二刚设好的周报 → 不把昨天(周一)那期当成错过去补", r["发起"] is None and not r["错过"], 1, r)
r = T.该发起吗(日, datetime(2026, 10, 26, 7, 0, tzinfo=北京), 上次统计起=date(2026, 10, 24), 设定于=设)
ck("今天 7:00、8:00 还没到;最近该跑的是昨天那次(统计 10-24),已经跑过 → **不发起**,也不算错过",
   r["发起"] is None and not r["错过"], 1, r)
ck("期键里带流程、周期、统计起始日(当幂等键)", T.期键("wf_x", 周, date(2026, 10, 19)) == "定时:wf_x:周:2026-10-19", 1)

print("\n▸ 规则写错要说人话")
坏规则 = [{"周期": "年"}, {"周期": "日", "时刻": "25:00"}, {"周期": "日", "时刻": "八点"}, {"周期": "日", "时区": "火星"}]
拦 = []
for x in 坏规则:
    try:
        T.校验规则(x)
    except T.规则不对 as e:
        拦.append(str(e))
ck("周期 / 时刻 / 时区写错都拦,而且说清怎么写", len(拦) == len(坏规则) and all(拦), len(坏规则), 拦)

print(f"\n{'❌ ' + str(len(挂)) + ' 条挂了' if 挂 else '✅ ' + str(len(过)) + ' 条全过'}")
for x in 挂:
    print(f"   · {x}")
sys.exit(1 if 挂 else 0)
