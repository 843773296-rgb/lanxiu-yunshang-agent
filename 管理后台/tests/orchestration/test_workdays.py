#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""工作日与首次处理截止(意见受理台,2026-11-04;用户拍「1 个工作日」「跳过周末和法定假日」)。

## 判据(期望值全是**手算**的,不拿被测代码现算 —— 同源谬误)

  ① 放假表自己对不对:通知原文里写的星期几(手抄的锚点)和日历对得上;调休上班日都是周末
  ② 平常日子:周五下午 → 下周一同一时刻;周六提交 → 周二零点(周末不数)
  ③ 长假:国庆前一天提交 → 跳过整个假期;调休上班的周六照数
  ④ 表里没有的年份(2027):退回只跳周末,**依据如实标「放假表没覆盖」**;跨年跨进没覆盖的那年也要标
  ⑤ 不带时区的时刻 → 当场抛(换台服务器算出来不一样);UTC 进来按北京时间算
"""
import datetime as dt
import os
import sys
from zoneinfo import ZoneInfo

_根 = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(_根, "services", "api", "app"))
import workdays as W  # noqa: E402

过, 挂 = [], []
京 = ZoneInfo("Asia/Shanghai")


def ck(名, 真, 补=""):
    print(f"  {'✅' if 真 else '❌'} {名}{('  ' + str(补)[:300]) if 补 and not 真 else ''}")
    (过 if 真 else 挂).append(名)


def t(s):
    return dt.datetime.fromisoformat(s).replace(tzinfo=京)


def 截(s):
    return W.首次处理截止(t(s))


def main():
    print("▸ ① 放假表对得上通知原文")
    # 通知原文里写着星期几的那几天(手抄):对不上就是表抄错了
    锚 = {"2026-01-01": 3, "2026-01-03": 5, "2026-01-04": 6, "2026-02-14": 5, "2026-02-15": 6, "2026-02-23": 0,
          "2026-02-28": 5, "2026-04-04": 5, "2026-04-06": 0, "2026-05-01": 4, "2026-05-05": 1, "2026-05-09": 5,
          "2026-06-19": 4, "2026-06-21": 6, "2026-09-20": 6, "2026-09-25": 4, "2026-09-27": 6,
          "2026-10-01": 3, "2026-10-07": 2, "2026-10-10": 5}
    错 = [d for d, w in 锚.items() if dt.date.fromisoformat(d).weekday() != w]
    ck(f"通知原文写的星期几和日历一致(验了 {len(锚)} 个锚点)", not 错, 错)
    ck("放假天数和通知一致:3 + 9 + 3 + 5 + 3 + 3 + 7 = 33", len(W.放假[2026]) == 33, len(W.放假[2026]))
    ck("调休上班日 6 天,全是周末", len(W.调休上班[2026]) == 6
       and all(dt.date.fromisoformat(d).weekday() >= 5 for d in W.调休上班[2026]), W.调休上班[2026])
    ck("放假和调休上班没有同一天", not (W.放假[2026] & W.调休上班[2026]))

    print("\n▸ ② 平常日子")
    c, 依 = 截("2026-11-06T15:00")
    ck("周五 15:00 → 下周一 15:00", c == t("2026-11-09T15:00") and 依 == "2026放假表", (c, 依))
    c, _ = 截("2026-11-07T10:00")
    ck("周六 10:00 → 周二 00:00(周末不数,从周一零点起数满 24 小时)", c == t("2026-11-10T00:00"), c)
    c, _ = 截("2026-11-04T00:00")
    ck("周三 00:00 → 周四 00:00(正好一个整工作日)", c == t("2026-11-05T00:00"), c)

    print("\n▸ ③ 长假与调休")
    c, _ = 截("2026-09-30T10:00")
    ck("国庆前一天(9/30 周三)10:00 → 10/8 10:00(10/1–7 整段不数)", c == t("2026-10-08T10:00"), c)
    c, _ = 截("2026-10-09T18:00")
    ck("10/9 周五 18:00 → 10/10 周六 18:00(那个周六调休上班,照数)", c == t("2026-10-10T18:00"), c)
    c, _ = 截("2026-02-13T12:00")
    ck("春节前 2/13 周五 12:00 → 2/14 周六 12:00(调休上班)", c == t("2026-02-14T12:00"), c)
    c, _ = 截("2026-02-14T20:00")
    ck("2/14 周六 20:00 → 2/24 周二 20:00(春节 2/15–23 不数)", c == t("2026-02-24T20:00"), c)

    print("\n▸ ④ 放假表没覆盖的年份")
    c, 依 = 截("2027-01-01T00:00")
    ck("2027-01-01(周五)→ 只跳周末算出 1/2 00:00,**依据标「放假表没覆盖」**",
       c == t("2027-01-02T00:00") and 依 == "只跳周末·放假表没覆盖", (c, 依))
    c, 依 = 截("2026-12-31T12:00")
    ck("12/31 中午提交、截止跨进 2027 → 依据也要标没覆盖(不说成按 2026 表算准了)",
       c == t("2027-01-01T12:00") and 依 == "只跳周末·放假表没覆盖", (c, 依))

    print("\n▸ ⑤ 时区")
    try:
        W.首次处理截止(dt.datetime(2026, 11, 6, 15, 0))
        ck("不带时区 → 抛", False, "没抛")
    except ValueError:
        ck("不带时区 → 抛", True)
    c, _ = W.首次处理截止(dt.datetime(2026, 11, 6, 7, 0, tzinfo=dt.timezone.utc))
    ck("UTC 07:00(北京周五 15:00)→ 北京下周一 15:00", c == t("2026-11-09T15:00"), c)

    print()
    if 挂:
        print(f"❌ {len(挂)} 条不过:{' / '.join(挂)}")
        return 1
    print(f"✅ 工作日与截止:{len(过)} 条全过")
    return 0


if __name__ == "__main__":
    sys.exit(main())
