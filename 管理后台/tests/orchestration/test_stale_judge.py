#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""**卡住多久算卡住,以及该不该由系统推它** —— 零 IO。业务 2026-10-07 拍的两档。

## 这一组每一条对着一种「推错了」

   ① 门槛那一条线:**刚好卡在 72.0 小时**算不算(边界是这种规则唯一容易错的地方)
   ② 「等外部确认」的被自动推到终态 → **重犯一个契约明令禁止的 bug**
   ③ running **有检查点**也标失败 → 丢掉一次可恢复的执行
   ④ 给「待上传」也写一套判断 → 和 `upload_rules` 两套实现,迟早分叉
   ⑤ 判不了的时候兜底成「还没超」→ 一份空清单读起来像「都正常」

## ⚠️ 第 ② 节是这一组存在的主要理由

`tests/e2e/test_training_flow.py` 的文件头记着一个真 bug:
> 「取消请求中 → 已取消」那条边**只该由后台确认的时候走**。
> 第一版写成「状态机允许就走」,于是**连点两次取消,系统自己宣布「已取消」**。

> 一条「等外部确认」的记录,和一条「卡住没人管」的,
> **在那个状态上长得一模一样** —— 自动推前者 = 重犯那个 bug。
"""
import datetime as dt
import os
import sys

_根 = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(_根, "services", "api", "app", "runtime"))
sys.path.insert(0, os.path.join(_根, "services", "api", "app", "knowledge"))

import 卡住判定 as S          # noqa: E402
import upload_rules as UR     # noqa: E402

G, R, D = "\033[32m", "\033[31m", "\033[0m"
过, 挂 = 0, 0
现 = dt.datetime(2026, 10, 7, 16, 0, 0)


def ck(说, ok, 附=""):
    global 过, 挂
    if ok:
        过 += 1
        print(f"  {G}✅{D} {说}  {附}")
    else:
        挂 += 1
        print(f"  {R}❌{D} {说}  {附}")


def 抛(说, f, 要含=()):
    global 过, 挂
    try:
        f()
    except S.判不了 as e:
        缺 = [w for w in 要含 if w not in str(e)]
        if 缺:
            挂 += 1
            print(f"  {R}❌{D} {说} —— 抛了但理由没提 {缺}\n      「{e}」")
        else:
            过 += 1
            print(f"  {G}✅{D} {说}\n      「{str(e)[:130]}」")
    except Exception as e:
        挂 += 1
        print(f"  {R}❌{D} {说} —— 抛的是 {type(e).__name__}:{e}")
    else:
        挂 += 1
        print(f"  {R}❌{D} {说} —— **没抛**")


def 前(h):
    return 现 - dt.timedelta(hours=h)


print("=" * 92)
print("卡住判定 · 两档(等外部只报警 / 做不完可标失败)· 门槛 72 小时")
print("=" * 92)

print("\n▸ ① 门槛那一条线 —— **边界是这种规则唯一容易错的地方**")
ck("门槛是业务拍的 72 小时", S.门槛小时 == 72, S.门槛小时)
ck("🔑 **刚好 72.0 小时算超**(`>=`,不是 `>`)",
   S.判(种类="评测", 状态="排队中", 创建时间=前(72.0), 现在=现)[0] == S.只报警)
ck("71.9 小时**不算超**",
   S.判(种类="评测", 状态="排队中", 创建时间=前(71.9), 现在=现)[0] == S.还没超)
ck("没超时的理由里要带上过了几小时和门槛(不然读不出离线还有多远)",
   "71.9" in S.判(种类="评测", 状态="排队中", 创建时间=前(71.9), 现在=现)[1]
   and "72" in S.判(种类="评测", 状态="排队中", 创建时间=前(71.9), 现在=现)[1])
# ⚠️ 这一条原来写的是 `"现在" in S.判.__kwdefaults__ or True` ——
# `现在` 没有默认值,所以它**不在** `__kwdefaults__` 里,前半恒为 False,
# 整条靠那个 `or True` 过的。**它什么都没验。**
# > 一条「验了参数是必填」的断言,和一条「写了 or True 所以永真」的,
# > **在那个绿勾上长得一模一样。**
# 真正的判据是「不传它会不会炸」—— `现在` 是 keyword-only 且无默认值,
# 所以漏传是 TypeError,当场炸在那一行(比任何检查都可靠)。
try:
    S.判(种类="评测", 状态="排队中", 创建时间=前(100))
    ck("🔑 「现在」是**必填参数**,不是内部 `now()`", False,
       "**没炸** —— 说明它有默认值,那上面两条边界就测不了了")
except TypeError as e:
    ck("🔑 「现在」是**必填参数**,不是内部 `now()` —— 漏传是 TypeError,"
       "当场炸;否则上面那两条边界根本测不了", True, str(e)[:60])
ck("  同一组输入两次调用结果一样(没有隐藏的时钟)",
   S.判(种类="评测", 状态="排队中", 创建时间=前(100), 现在=现)
   == S.判(种类="评测", 状态="排队中", 创建时间=前(100), 现在=现))

print("\n▸ ② 等外部确认的三类:**只报警,绝不自动推**")
for 种, 态 in (("评测", "排队中"), ("部署", "部署请求中"), ("训练", "取消请求中")):
    档, 为 = S.判(种类=种, 状态=态, 创建时间=前(200), 现在=现)
    ck(f"`{种}/{态}` 超了 200 小时也只是 **{S.只报警}**", 档 == S.只报警)
    ck(f"  理由点明**等的是外部**,而不是「超时了」", "外部" in 为)
ck("🔑 理由里点名了那条契约禁令(「取消请求中 → 已取消」只该由后台确认时走)——"
   "否则下一个人会以为这只是「保守一点」",
   "契约明令禁止" in S.判(种类="训练", 状态="取消请求中",
                      创建时间=前(200), 现在=现)[1])
ck("对照:这三类**一个都不会**被判成可标 failed/expired",
   not any(S.判(种类=种, 状态=态, 创建时间=前(500), 现在=现)[0]
           in (S.可标failed, S.可标expired)
           for 种, 态 in (("评测", "排队中"), ("部署", "部署请求中"),
                        ("训练", "取消请求中"))))

print("\n▸ ③ 运行:做不完 vs 可能能恢复")
ck("running + 没有检查点 → **可标 failed**(状态机 running→failed 允许)",
   S.判(种类="运行", 状态="running", 创建时间=前(100), 现在=现,
       有检查点=False)[0] == S.可标failed)
ck("🔑 running + **有检查点** → 只报警 —— "
   "一个「有检查点可以接着跑」的 run 和一个「什么都没留下」的,"
   "在那个 running 上长得一模一样,而自动标失败会**丢掉一次可恢复的执行**",
   S.判(种类="运行", 状态="running", 创建时间=前(100), 现在=现,
       有检查点=True)[0] == S.只报警)
ck("  有检查点那条理由里点了 §6.3(恢复时禁止重新初始化成零)",
   "6.3" in S.判(种类="运行", 状态="running", 创建时间=前(100), 现在=现,
                有检查点=True)[1])
ck("🔑 queued + 没有定义引用 → **可标 expired,不是 failed** —— "
   "状态机写着 queued 只能到 running/cancelled/expired,**到不了 failed**。"
   "终态是状态机说的那个,不是我顺手挑的",
   S.判(种类="运行", 状态="queued", 创建时间=前(100), 现在=现,
       有定义引用=False)[0] == S.可标expired)
ck("  而 expired 这一档**库里从没有任何记录到过** —— "
   "和 uploads.已放弃 完全同形:一档到不了的状态比少一档更糟",
   "从没有任何记录到过" in S.判(种类="运行", 状态="queued", 创建时间=前(100),
                          现在=现, 有定义引用=False)[1])
ck("queued + **有定义引用** → 只报警(重派任务就能跑,让人决定)",
   S.判(种类="运行", 状态="queued", 创建时间=前(100), 现在=现,
       有定义引用=True)[0] == S.只报警)
ck("🔑 理由里写明**终态是 failed 不是 cancelled** —— "
   "没有人取消它,是系统漏了活;用「已取消」会把一次故障写成一次决定",
   "cancelled" in S.判(种类="运行", 状态="running", 创建时间=前(100), 现在=现,
                     有检查点=False)[1]
   and "failed" in S.判(种类="运行", 状态="running", 创建时间=前(100), 现在=现,
                       有检查点=False)[1])
抛("running 没告诉它有没有检查点 → 当场抛,不默认「没有」",
   lambda: S.判(种类="运行", 状态="running", 创建时间=前(100), 现在=现),
   ("检查点", "分界"))
抛("queued 没告诉它有没有定义引用 → 当场抛",
   lambda: S.判(种类="运行", 状态="queued", 创建时间=前(100), 现在=现),
   ("定义引用",))

print("\n▸ ④ 「待上传」不在这儿 —— 不给第二套判断")
抛("种类=上传 → 当场抛,并指向 upload_rules 和那个脚本",
   lambda: S.判(种类="上传", 状态="待上传", 创建时间=前(100), 现在=现),
   ("upload_rules", "abandon_stale_uploads", "两套实现"))
ck("🔑 两个门槛**都在,而且不一样** —— 24h 等人传文件、72h 等外部系统确认。"
   "统一成一个数会让其中一个失去依据",
   UR.放弃门槛小时 == 24 and S.门槛小时 == 72,
   f"上传 {UR.放弃门槛小时}h / 等外部 {S.门槛小时}h")
ck("  而两个门槛各自的理由都写在代码里(不是只写了数字)",
   "分钟级" in (UR.该放弃吗.__doc__ or "") and "mock" in (S.__doc__ or ""))

print("\n▸ ⑤ 判不了的时候**不许兜底成「还没超」**")
抛("缺创建时间 → 抛", lambda: S.判(种类="评测", 状态="排队中",
                              创建时间=None, 现在=现), ("猜一个等于乱判",))
抛("缺「现在」 → 抛", lambda: S.判(种类="评测", 状态="排队中",
                             创建时间=前(100), 现在=None), ("猜一个等于乱判",))
抛("没见过的种类 → 抛,不兜底",
   lambda: S.判(种类="训练产物", 状态="怪状态", 创建时间=前(100), 现在=现),
   ("不兜底", "空清单"))
抛("运行的状态不在判据里 → 抛",
   lambda: S.判(种类="运行", 状态="paused", 创建时间=前(100), 现在=现),
   ("不兜底",))
ck("🔑 对照:**没有一种输入会让它返回「还没超」却其实超了** —— "
   "超了的要么只报警要么可标失败,判不了的抛",
   all(S.判(种类=种, 状态=态, 创建时间=前(500), 现在=现, **额)[0] != S.还没超
       for 种, 态, 额 in (("评测", "排队中", {}), ("部署", "部署请求中", {}),
                        ("训练", "取消请求中", {}),
                        ("运行", "running", {"有检查点": True}),
                        ("运行", "running", {"有检查点": False}),
                        ("运行", "queued", {"有定义引用": True}),
                        ("运行", "queued", {"有定义引用": False}))))

print("\n▸ ⑥ 不假装解决的事")
ck("模块文档写清了 72 这个数**一半是实测一半是猜的**,并说了重量的条件",
   "一半是实测" in (S.__doc__ or "") and "重新量" in (S.__doc__ or ""))
ck("也写清了为什么必须分两档(那条禁令是一个真 bug 换来的)",
   "真 bug 换来的" in (S.__doc__ or ""))

print("\n" + "=" * 92)
if 挂:
    print(f"{R}❌ 过 {过} / 挂 {挂}{D}")
    sys.exit(1)
print(f"{G}✅ 过 {过} / 挂 {挂}{D}")
