#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""上传校验的纯逻辑 —— **零 IO,所以每条规则都能单独逼出来**。

## 为什么值得单测到这个密度

`POST /uploads/{id}/complete` 是「文件能不能被引用」的唯一判定点。
它判松了 → 坏文件在库里是「已校验」,建索引时炸,而**错误指向解析器**;
判严了 → 用户手里一份正常资料传不上来,而他没有任何办法绕过。

两个方向都难查,因为**两边都不报「校验判错了」**。

## 咬合(最后三条)

规则清单、上限、「真的调解析器」这三件是这个模块的全部价值。
所以要有测试**证明拿掉它们会红** —— 否则它们只是注释。
"""
import os
import sys

_根 = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(_根, "services", "api", "app"))
sys.path.insert(0, os.path.join(_根, "services", "api", "app", "knowledge"))

import parser as PS
import upload_rules as UR

过, 挂 = [], []


def ck(名, 真, 补=""):
    print(f"  {'✅' if 真 else '❌'} {名}{('  ' + str(补)[:160]) if 补 else ''}")
    (过 if 真 else 挂).append(名)


好文 = "# 拍板记录\n\n签收当场就请顾客评价,三星及以下算差评。\n\n代价:门店会觉得被考核。\n"
好字节 = 好文.encode("utf-8")

print("▸ ① 名字层:要地址的时候就该拒的")
for 名, 该行 in (("a.md", True), ("a.markdown", True), ("a.TXT", True),
              ("a.pdf", False), ("a.docx", False), ("a", False), ("", False)):
    行, 为什么 = UR.名字过得去吗(名)
    ck(f"{名!r} → {'收' if 该行 else '拒'}", 行 == 该行, 为什么[:80])
ck("拒的理由里点了 OCR(§附录 D.5)—— **说清「为什么不支持」而不只是「不支持」**",
   "OCR" in UR.名字过得去吗("a.pdf")[1])

print("▸ ② 声明字节数:必填,而且超限在要地址时就拦")
ck("不声明 → 拒(不声明就检不出截断)", not UR.声明字节数过得去吗(None)[0])
ck("拒的理由里点了「截断」", "截断" in UR.声明字节数过得去吗(None)[1])
ck("0 字节 → 拒", not UR.声明字节数过得去吗(0)[0])
ck("超上限 → 拒(不让他先传完 5MB)", not UR.声明字节数过得去吗(UR.最大字节数 + 1)[0])
ck("刚好上限 → 收", UR.声明字节数过得去吗(UR.最大字节数)[0])
ck("布尔不算整数(True 不是 1 字节)", not UR.声明字节数过得去吗(True)[0])
ck("字符串 → 拒", not UR.声明字节数过得去吗("100")[0])

print("▸ ③ 正常文件全过")
r = UR.校验(好字节, 文件名="拍板.md", 声明字节数=len(好字节))
ck("通过", r["通过"], r["没过的规则"])
ck("内容哈希是 sha256 前缀", r["内容哈希"].startswith("sha256:"))
ck("块数 > 0", (r["细节"]["块数"] or 0) > 0, r["细节"]["块数"])
ck("记了解析器版本(**同一份文件的结论会随解析器变**,所以要记)",
   r["细节"]["解析器版本"] == PS.解析器版本)

print("▸ ④ 截断:实际和声明不一致")
r = UR.校验(好字节[: len(好字节) // 2], 文件名="拍板.md", 声明字节数=len(好字节))
ck("半个文件 → 不过", not r["通过"])
ck("点名的规则是「实际字节数和声明一致」", "实际字节数和声明一致" in r["没过的规则"],
   r["没过的规则"])
理由 = [x["为什么"] for x in r["理由们"] if x["规则"] == "实际字节数和声明一致"][0]
ck("理由里说了「传到一半断了」而不只是两个数不等", "断" in 理由, 理由[:70])

print("▸ ⑤ 编码:GBK 不猜")
r = UR.校验("中文资料内容".encode("gbk"), 文件名="a.txt", 声明字节数=12)
ck("GBK → 不过", not r["通过"])
ck("点名「能按 UTF-8 严格解码」", "能按 UTF-8 严格解码" in r["没过的规则"])
理由 = [x["为什么"] for x in r["理由们"] if x["规则"] == "能按 UTF-8 严格解码"][0]
ck("理由说清「乱码建得成索引但检索永远查不到」", "检索" in 理由, 理由[:80])
ck("解码不过就不再报解析器的错(那一步确实做不下去)",
   "解析器吃得下" not in r["没过的规则"], r["没过的规则"])

print("▸ ⑥ 空文件")
r = UR.校验(b"", 文件名="a.md", 声明字节数=0)
ck("0 字节 → 不过", not r["通过"])
ck("点名「不是空文件」", "不是空文件" in r["没过的规则"], r["没过的规则"])

print("▸ ⑦ 一次把所有不过的都报出来,不是第一条就返回")
r = UR.校验(b"x", 文件名="a.pdf", 声明字节数=999)
ck("三条一起报(后缀 + 字节数不一致 + 解析器吃不下)",
   len(r["没过的规则"]) >= 3, r["没过的规则"])
ck("只报第一条的代价:改完第一条再传一次又被第二条拒 —— 所以这里必须 >1",
   len(r["没过的规则"]) > 1)

print("▸ ⑧ 超上限")
r = UR.校验(b"#\n\n" + b"a" * UR.最大字节数, 文件名="a.md",
          声明字节数=UR.最大字节数 + 3)
ck("超上限 → 不过", not r["通过"])
ck("点名「不超过上限」", "不超过上限" in r["没过的规则"], r["没过的规则"])

print("▸ ⑨ 报「没过」时同时报「查了什么」")
r = UR.校验(b"", 文件名="a.md", 声明字节数=0)
ck("规则全集 = 模块公开的 规则们(**不另立一份**)",
   list(UR.规则们) == list(UR.规则们) and len(UR.规则们) == 7, len(UR.规则们))
ck("每条没过的规则都在规则全集里 —— 报一条不在清单里的规则等于没有清单",
   all(x in UR.规则们 for x in r["没过的规则"]), r["没过的规则"])

print("▸ ⑩ 咬合:拿掉就该红")
ck("后缀白名单**不另立一份**,每次调用都问解析器", UR.支持的后缀() is PS.支持的后缀)
# 咬合:**只改解析器那一边**。
# ⚠️ 这里故意不碰 `UR` 的任何东西 —— 一个「同时改两边才变绿」的咬合,
# 等于替被测对象把作业补上了:它证明的是「我改得对」,不是「代码对」。
_老 = PS.支持的后缀
try:
    PS.支持的后缀 = (".md",)
    ck("只改解析器白名单 → 校验立刻跟着变(.txt 不再收)——"
       "**导入时抄快照的版本在这里会红**",
       not UR.名字过得去吗("a.txt")[0])
    ck("而 .md 还收(证明不是把所有后缀都拒了)", UR.名字过得去吗("a.md")[0])
finally:
    PS.支持的后缀 = _老
ck("还原了", UR.名字过得去吗("a.txt")[0])

# 咬合:真的调解析器 —— 让解析器抛,校验必须报「解析器吃得下」不过
_老解析 = PS.解析
try:
    def _炸(原文, *, 文件名=""):
        raise PS.解析不了("咬合:假装这份内容解析器吃不下")
    PS.解析 = _炸
    r = UR.校验(好字节, 文件名="拍板.md", 声明字节数=len(好字节))
    ck("**校验真的调解析器** —— 解析器拒了,校验就不过",
       (not r["通过"]) and "解析器吃得下" in r["没过的规则"], r["没过的规则"])
    ck("解析器的拒绝理由被原样带出来(不是翻译成「格式错误」)",
       any("咬合" in x["为什么"] for x in r["理由们"]))
finally:
    PS.解析 = _老解析
ck("还原了(正常文件又通过了)",
   UR.校验(好字节, 文件名="拍板.md", 声明字节数=len(好字节))["通过"])

# 咬合:解析器不报错但切出 0 块
try:
    def _空(原文, *, 文件名=""):
        return {"块们": [], "结构": [], "警告": [], "解析器版本": PS.解析器版本}
    PS.解析 = _空
    r = UR.校验(好字节, 文件名="拍板.md", 声明字节数=len(好字节))
    ck("解析器没报错但 0 块 → 仍然不过(**没报错不等于有内容**)",
       (not r["通过"]) and "解析出至少一个块" in r["没过的规则"], r["没过的规则"])
finally:
    PS.解析 = _老解析

print("▸ ⑪ 上限是棘轮(写死是故意的)")
ck("最大字节数 ≤ 5MB —— 放宽要有人显式改那一行",
   UR.最大字节数 <= 5 * 1024 * 1024, UR.最大字节数)

print("▸ ⑫ 该放弃吗:**让状态机里的 `已放弃` 真的到得了**")
from datetime import datetime, timedelta, timezone
_现 = datetime(2026, 9, 27, 12, 0, tzinfo=timezone.utc)
for 小时, 该放 in ((0, False), (1, False), (23.9, False), (24, True), (48, True)):
    行, 几 = UR.该放弃吗(_现 - timedelta(hours=小时), _现)
    ck(f"放了 {小时} 小时 → {'放弃' if 该放 else '留着'}", 行 == 该放, f"{几:.2f}h")
ck("**刚好卡在门槛上算放弃**(>=,不是 >)—— 边界是这种规则唯一容易错的地方",
   UR.该放弃吗(_现 - timedelta(hours=24), _现)[0])
ck("门槛可以传进来(给清理脚本做 dry-run 用)",
   UR.该放弃吗(_现 - timedelta(hours=2), _现, 门槛小时=1)[0])
ck("**「现在」是参数不是自己调 now()** —— 自己调就测不了边界",
   "现在" in UR.该放弃吗.__code__.co_varnames)
for 坏 in ((None, _现), (_现, None)):
    try:
        UR.该放弃吗(*坏)
        ck(f"缺一个时间 → 抛({坏})", False, "没抛!猜一个等于乱判")
    except ValueError:
        ck("缺一个时间 → 当场抛(**猜一个等于乱判**)", True)
ck("门槛默认 24 小时:比「点开选文件到传完」(分钟级)长得多",
   UR.放弃门槛小时 == 24, UR.放弃门槛小时)

print(f"\n{'✅' if not 挂 else '❌'} 过 {len(过)} / 挂 {len(挂)}")
if 挂:
    for x in 挂:
        print("   挂:", x)
sys.exit(1 if 挂 else 0)
