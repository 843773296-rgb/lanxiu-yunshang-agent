#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""评测「答得对不对」的判法(用户 2026-11-05 拍:C 两种结合 + 两轮都对才算对)。不要数据库,真调 runtime/判对.py。

  ① 字段判据四种方式各一条对的、一条错的(每种都要有活用例,不然那种方式坏了看不出来)
  ② 取不到那一项 ≠ 取到了 None:「有这一项」对空值判错、对缺项判错;「等于 None」对缺项判错
  ③ 在范围内不认布尔(True 在 Python 里等于 1,会被当成 1 落进 [0, 2])
  ④ 每一条都要过才算对;理由逐条写清是哪一项、期望什么、实际是什么
  ⑤ 判法:有判据 → 字段;只有期望说明 → 模型;都没有 → 不判(不是判错)
  ⑥ 判据格式:没有「包含某个词」这种方式(拿关键词判成段的话,这个项目栽过七次)
  ⑦ 两轮合起来:都对 → 对;一对一错 → 错且标「两轮不一致」;有一轮没判出来 → 没结论(不当成错)
"""
import os
import sys

_根 = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(_根, "services", "api", "app", "runtime"))
import 判对 as PD  # noqa: E402

过, 挂 = [], []


def ck(名, 真, 补=""):
    print(f"  {'✅' if 真 else '❌'} {名}{('  ' + str(补)[:300]) if 补 and not 真 else ''}")
    (过 if 真 else 挂).append(名)


def 一条(输出, 项, 式, 值=None):
    j = {"项": 项, "方式": 式}
    if 值 is not None or 式 == "等于":
        j["值"] = 值
    return PD.按字段判(输出, [j])[0]


def main():
    出 = {"品类": "褙子", "预算": 3000, "客户号": "C10001", "工期档": "常规", "空": "", "无": None,
          "列表": [{"x": 1}], "真": True}
    ck("① 等于:对的对、错的错", 一条(出, "/品类", "等于", "褙子") and not 一条(出, "/品类", "等于", "马面裙"))
    ck("① 在范围内:对的对、错的错", 一条(出, "/预算", "在范围内", [2800, 3200]) and not 一条(出, "/预算", "在范围内", [100, 200]))
    ck("① 有这一项:有的对、没有的错", 一条(出, "/客户号", "有这一项") and not 一条(出, "/订单号", "有这一项"))
    ck("① 是其中之一:在里面的对、不在的错", 一条(出, "/工期档", "是其中之一", ["常规", "加急"])
       and not 一条(出, "/工期档", "是其中之一", ["加急"]))
    ck("① 嵌套位置也取得到(/列表/0/x)", 一条(出, "/列表/0/x", "等于", 1))

    ck("② 有这一项:值是空字符串 / None → 判错(「有个空壳」不算交出了这一项)",
       not 一条(出, "/空", "有这一项") and not 一条(出, "/无", "有这一项"))
    ck("② 等于 None:那一项真是 None → 对;缺这一项 → 错(取不到 ≠ 取到了 None)",
       一条(出, "/无", "等于", None) and not 一条(出, "/根本没有", "等于", None))
    ck("③ 在范围内不认布尔(True 会被当成 1 落进 [0, 2])", not 一条(出, "/真", "在范围内", [0, 2]))

    对, 理由 = PD.按字段判(出, [{"项": "/品类", "方式": "等于", "值": "褙子"}, {"项": "/预算", "方式": "在范围内", "值": [1, 2]}])
    ck("④ 每一条都要过才算对(一条过一条不过 → 错)", 对 is False, 理由)
    ck("④ 理由逐条:写了哪一项、实际是什么", len(理由) == 2 and "/预算" in 理由[1] and "3000" in 理由[1] and 理由[0].startswith("✓"), 理由)

    ck("⑤ 判法:有判据 → 字段;只有期望说明 → 模型;都没有 → 不判",
       PD.判法({"判据": [{"项": "/a", "方式": "有这一项"}], "期望说明": "x"}) == "字段"
       and PD.判法({"期望说明": "提到两种面料"}) == "模型" and PD.判法({"输入": {}}) is None and PD.判法({"期望说明": "  "}) is None)

    问 = PD.判据格式问题([{"项": "/备注", "方式": "包含", "值": "真丝"}])
    ck("⑥ 判据格式:「包含某个词」不收,并且说清成段的话该写进期望说明", len(问) == 1 and "期望说明" in 问[0], 问)
    ck("⑥ 判据格式:合格的一组 → 没问题;范围倒过来 / 项不以 / 开头 / 空列表 → 各报一条",
       PD.判据格式问题([{"项": "/a", "方式": "等于", "值": 1}]) == []
       and len(PD.判据格式问题([{"项": "/a", "方式": "在范围内", "值": [5, 1]}, {"项": "a", "方式": "等于", "值": 1}])) == 2
       and PD.判据格式问题([]) != [])

    ck("⑦ 两轮都对 → 对", PD.两轮合起来({1: True, 2: True})[0] is True)
    结, 说 = PD.两轮合起来({1: True, 2: False})
    ck("⑦ 一轮对一轮错 → 错,并标「两轮不一致」", 结 is False and "不一致" in 说, (结, 说))
    ck("⑦ 两轮都错 → 错", PD.两轮合起来({1: False, 2: False})[0] is False)
    ck("⑦ 有一轮没判出来 → 没结论(不当成错);一轮都没有 → 没结论",
       PD.两轮合起来({1: True, 2: None})[0] is None and PD.两轮合起来({})[0] is None)

    ck("⑧ 评审回答:正常 JSON → 取出对 / 理由;前后夹了别的字也认得",
       PD.解析评审('{"对": true, "理由": "提到了真丝和棉麻"}') == (True, "提到了真丝和棉麻")
       and PD.解析评审('好的。\n{"对": false, "理由": "没提面料"}\n以上')[0] is False)
    ck("⑧ 评审回答看不懂 / 「对」不是布尔 → 没结论(不当成错也不当成对),理由带原文",
       PD.解析评审("我觉得还行")[0] is None and PD.解析评审('{"对": "是"}')[0] is None
       and "我觉得还行" in PD.解析评审("我觉得还行")[1])
    ck("⑧ 评审要看的东西都在消息里:期望说明、题的输入、实际输出",
       all(x in PD.评审用户消息({"期望说明": "要提面料", "输入": {"a": "宋制"}}, {"跟进": "真丝"}) for x in ("要提面料", "宋制", "真丝")))

    print()
    if 挂:
        print(f"❌ {len(挂)} 条不过:{' / '.join(挂)}")
        return 1
    print(f"✅ 评测判对规则:{len(过)} 条全过")
    return 0


if __name__ == "__main__":
    sys.exit(main())
