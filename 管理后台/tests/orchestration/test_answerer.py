#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""照着证据生成答案 —— **零 IO、不调模型**。业务 2026-10-08 拍的 A。

真调模型那一步由 `make test-live` / 手动验;这一份分两半:

  **A. 真跑那个纯函数**(`校验答案`)—— 它是这一步全部的防护所在:
     空答案 / 编出来的编号 / 改写了的原话 / 「没表态」当成「够」。
     ⚠️ 这半边**不是源码正则**,是真的调它看它抛不抛 ——
     > 一条「判据写在代码里」和一条「判据真的会拦」,
     > **在源码上长得一模一样。**

  **B. 周围那些不该出错的东西**(这些只能看源码):
     口径复用、失败不自己降级、每条出口接记录仪、
     **记录仪在校验之前就记**(否则花了钱而日志里什么都没有)、
     以及**文案不许替判据担保**(没验「超出证据」就不许写成验了)。
"""
import io
import os
import re
import sys

_根 = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
_k = os.path.join(_根, "services", "api", "app", "knowledge")
sys.path.insert(0, _k)

import answerer as AW          # noqa: E402

G, R, D = "\033[32m", "\033[31m", "\033[0m"
过, 挂 = 0, 0


def ck(说, ok, 附=""):
    global 过, 挂
    if ok:
        过 += 1
        print(f"  {G}✅{D} {说}  {附}")
    else:
        挂 += 1
        print(f"  {R}❌{D} {说}  {附}")


def 抛吗(出的, 编):
    """调一次 `校验答案`,返回 (抛了吗, 那句话)。"""
    try:
        AW.校验答案(出的, 编)
        return False, ""
    except AW.生成失败 as e:
        return True, str(e)


源 = io.open(os.path.join(_k, "answerer.py"), encoding="utf-8").read()
检索源 = io.open(os.path.join(_k, "retrieval.py"), encoding="utf-8").read()
前端源 = io.open(os.path.join(_根, "apps", "web", "app.js"), encoding="utf-8").read()

# 一份真实形状的证据:带 Markdown 加粗(**模型抄原话时会顺手清理格式**,
# 而那不是「编」—— 这正是要复用 `reranker._剥格式` 的理由)
证据 = {
    1: {"id": "ch_1", "证据": "业务拍板 · 2026-09-27 / 二、几星算差评 · 第 4 段",
        "文": "**≤3 星算差评**;差评自动进待处理清单(有人负责跟)"},
    2: {"id": "ch_2", "证据": "业务拍板 · 2026-09-27 / 一、什么时候请评价 · 第 3 段",
        "文": "签收后 24 小时内发评价邀请,超过 7 天不再发"},
}

print("=" * 92)
print("照着证据生成答案 · 判据真的会拦吗(零 IO,**真跑纯函数**)")
print("=" * 92)

print("\n▸ ① 对照先绿 —— 一个合规的答案必须过")
好 = {"answer": "客户给了 3 星及以下就算差评,会自动进待处理清单,有人负责跟。",
      "enough": True,
      "cited": [{"index": 1, "quote": "≤3 星算差评"}]}
抛, 话 = 抛吗(好, 证据)
ck("合规的答案不抛(**对照先绿**:不绿的话下面每条红都说明不了问题)",
   not 抛, 话[:70])
结 = AW.校验答案(好, 证据)
ck("引文带 Markdown 加粗的原文也算对得上 —— "
   "**复用 `reranker._剥格式`**:抄原话(哪怕清理了 `**`)能过",
   结["引用们"][0]["原话可信"] is True)
ck("出处带回了**能翻回原文的证据串**(一个查不回去的引用比没有引用糟)",
   " · 第 " in (结["引用们"][0]["证据"] or ""), 结["引用们"][0]["证据"])

print("\n▸ ② 空答案不当结果")
抛, 话 = 抛吗({**好, "answer": "   "}, 证据)
ck("🔑 空答案**当场抛** ——「生成了空答案」和「证据里没有」是两件事",
   抛 and "不拿空串当答案" in 话, 话[:60])

print("\n▸ ③ 编出来的证据编号 —— 这是「编」的一种,不是「只用了几条」")
抛, 话 = 抛吗({**好, "cited": [{"index": 9, "quote": "随便"}]}, 证据)
ck("🔑 引用不存在的编号**当场抛** —— "
   "一个指向不存在片段的出处比没有出处糟:它看起来有出处",
   抛 and "不存在的证据编号" in 话, 话[:60])
抛, 话 = 抛吗({**好, "cited": [{"index": 1, "quote": "≤3 星算差评"}]}, 证据)
ck("而**只引其中一条是正常的**(子集判据,不是集合相等)—— "
   "要求相等等于逼它假装每片都用上了",
   not 抛, 话[:60])

print("\n▸ ④ 原话必须真在那片证据里")
抛, 话 = 抛吗({**好, "cited": [{"index": 1, "quote": "三星以下都算差评"}]}, 证据)
ck("改写过的「原话」被标成不可信(**单条是噪声,不整条失败**)", not 抛, 话[:50])
出 = AW.校验答案({**好, "cited": [{"index": 1, "quote": "三星以下都算差评"}]}, 证据)
ck("↳ 而且**标记传得出来**(判据标了却传不出去,等于没有判据)",
   出["引用们"][0]["原话可信"] is False and bool(出["引用们"][0]["原话问题"]),
   (出["引用们"][0]["原话问题"] or "")[:60])
ck("↳ 汇总了「几条没通过校验」(不用逐条看才知道)",
   出["引用没通过校验的"] == 1, 出["引用没通过校验的"])
抛, 话 = 抛吗({**好, "cited": [{"index": 1, "quote": "三星以下都算差评"},
                            {"index": 2, "quote": "签收后三天内发邀请"}]}, 证据)
ck("🔑 **大面积对不上就是故障**(2/2 超过 1/3 的阈值)—— "
   "出处能被核对,才算出处",
   抛 and "找不到" in 话, 话[:60])
ck("↳ 阈值的分母是**它自己引了几条**,不是候选总数 —— "
   "引了 2 条全对不上不该因为候选有 12 条就算 2/12 放行",
   "len(引们)" in 源 and "阈值 = max(1, len(引们) // 3)" in 源)

print("\n▸ ⑤ 「证据不够」要能被说出来,而且不逼它造假")
抛, 话 = 抛吗({"answer": "这几段证据里没写退货运费谁承担。", "enough": False,
            "cited": [], "missing": "退货运费的承担方"}, 证据)
ck("🔑 `enough=false` + 一条引用都没有 → **放行**(和 reranker 的「0 分免引文」同一条:"
   "判据不该逼被测对象为不存在的关联编证据)", not 抛, 话[:60])
结2 = AW.校验答案({"answer": "证据里没写。", "enough": False, "cited": [],
                "missing": "退货运费的承担方"}, 证据)
ck("↳ 「缺什么」带出来了(不然人只知道「不够」,不知道缺哪一块)",
   结2["缺什么"] == "退货运费的承担方", 结2["缺什么"])
抛, 话 = 抛吗({**好, "cited": []}, 证据)
ck("🔑 反过来:说 `enough=true` 却一条引用都给不出 → **抛**。"
   "说得出「够」就该指得出是哪一句", 抛 and "指得出" in 话, 话[:60])

print("\n▸ ⑥ 「没表态」不许被当成「说够了」")
抛, 话 = 抛吗({"answer": "随便答一句", "cited": [{"index": 1, "quote": "≤3 星算差评"}]},
            证据)
ck("🔑 `enough` 缺失 → **抛,不默认成 True** —— "
   "默认成「够」会让「模型没表态」和「模型说够了」长得一模一样",
   抛 and "不默认成" in 话, 话[:60])
抛, 话 = 抛吗({**好, "enough": "true"}, 证据)
ck("字符串 'true' 也不算布尔(宽松收下它等于又开一条默认的路)", 抛, 话[:50])

print("\n▸ ⑦ 口径只有一份 —— 不另写一套剥格式")
ck("🔑 用的是 `RR._剥格式`,**没有自己定义一份** —— "
   "两份口径迟早分叉,而分叉的时候两边各自都是绿的",
   "RR._剥格式" in 源 and not re.search(r"^def _剥格式", 源, re.M))

print("\n▸ ⑧ 失败抛,降级交给调用方")
ck("模块里一处都没有「失败就把证据原样贴出来」(那是调用方的决定)",
   "原样贴出来" in 源 and "不降级成" in 源)
ck("失败一律 `raise 生成失败`", 源.count("raise 生成失败") >= 7,
   f"{源.count('raise 生成失败')} 处")
ck("截断**先看**(tool_use 的 JSON 截断之后解析缺项,"
   "而那会被报成「模型没守契约」,把人引向模型而根因在 max_tokens 上)",
   "stop_reason" in 源 and "_最多token` 不够" in 源)
ck("模型不调工具时**不去解析自由文本当答案**(那段话没经过出处校验)",
   "不去解析自由文本当答案" in 源)

print("\n▸ ⑨ 记录仪:**先记这次调用,再校验契约**")
ck("有 `trace.record`(管理后台那个叫 llmtrace,见 reranker 文件头)",
   "trace.record" in 源)
_记行 = [i for i, L in enumerate(源.split("\n")) if re.search(r"^\s+_记\(", L)]
_校行 = next(i for i, L in enumerate(源.split("\n")) if "结 = 校验答案(" in L)
ck("🔑 校验那一行**之前**就有一次 `_记(True, 用量=…)` —— "
   "放在校验之后的话,一次「调了、花了钱、而返回不合契约」的调用"
   "在日志里一条记录都没有",
   any(i < _校行 and "用量=d.get" in 源.split("\n")[i] for i in _记行))
ck("↳ 而补记的那两条**用量留空**(否则同一次的 token 在日志里被算两遍)",
   源.count("上一条已经记过这次的 token") >= 2)
ck("`_记(` 的次数不少于 `raise 生成失败` 在发请求之后的那些",
   源.count("_记(") >= 6, f"_记 {源.count('_记(')} 次")

print("\n▸ ⑩ 检索链:三种「没有答案」要分得开,而且不靠认文案")
ck("🔑 有**结构化**的 `哪一种`(这次没要 / 跑不成 / 炸了)—— "
   "让界面去 `in` 那段文案,会在下一个人改文案的那天静默失效",
   all(f'哪一种="{x}"' in 检索源 for x in ("这次没要", "跑不成", "炸了")))
ck("生成失败**不让整条检索挂掉**(检索链本身有价值),但失败写进链路",
   "生成没跑成" in 检索源 and "检索链本身是好的" in 检索源)
ck("↳ 而且写明「这**不是**证据里答不出来」—— "
   "后者会是一段明说「证据里没有」的答案,不是一条失败",
   "不是**「证据里答不出来」" in 检索源 or "**不是**「证据里答不出来」" in 检索源)
ck("默认不生成(多一次模型调用),而「这次没要」也写进链路",
   "要生成=False" in 检索源 and "这不是「这一版没做生成」" in 检索源)
ck("答案回答的是**原问**,而算向量用的是改写后的 —— 这件事在链路里看得见",
   "照着谁答的" in 检索源)

print("\n▸ ⑪ 文案不许替判据担保 —— **这一条最容易被写坏**")
ck("🔑 模块头明说**验不到**「答案有没有超出证据」(要句子级蕴含,这一版没做)",
   "验不到" in 源 and ("蕴含" in 源 or "NLI" in 源))
ck("🔑 页面上那句话写的是「**指得出出处**」,而不是「没有超出证据」—— "
   "判据没覆盖的事,文案不许替它担保",
   "指得出出处" in 前端源 and "没有超出证据" in 前端源)
ck("↳ 而且页面把那个「长得一模一样」直接写给人看"
   "(每句话都有出处 ≠ 没加自己的话)",
   "还加了两句自己的" in 前端源)

print("\n▸ ⑫ 前端:两种「没有答案」用不同的颜色,不是同一个灰「没做」")
ck("🔑 「这次没要」用灰 pill、「跑不成 / 炸了」用红 —— "
   "同一个灰会让一次故障看起来像一个选择",
   'pill none">这次没要' in 前端源 and 'pill fail">${esc(g["哪一种"]' in 前端源)
ck("答案用 `md()` 不用 `esc()`(md 自己先 esc,所以既安全、"
   "又不会把模型写的 `**` 显示成字面星号 —— 10-07 用户用眼睛抓到过 32 处)",
   'md(g["答案"]' in 前端源)

print("\n" + "=" * 92)
if 挂:
    print(f"{R}❌ 过 {过} / 挂 {挂}{D}")
    sys.exit(1)
print(f"{G}✅ 过 {过} / 挂 {挂}{D}")
