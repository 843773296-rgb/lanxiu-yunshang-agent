# -*- coding: utf-8 -*-
"""告警判定(DF-04 第二步,2026-11-04;C16)。不要数据库,真调 alert_rules.下一步。

用户拍的判法:连续 N 次越线才报、连续 M 次正常才恢复、样本不够那一轮不算(既不报也不清零)、去重周期内不重复提醒。

  ① 一两次波动不报:越线 1 次(N=3)→ 不动
  ② 连续 3 次越线 → 开待办;第 4 次在去重周期内 → 不动;过了去重周期 → 提醒
  ③ 样本不够那一轮:不报、**不清零**(流量一低,持续的异常不能因此永远攒不够)
  ④ 恢复要连续 M 次正常:正常 1 次(M=2)→ 还在触发中;第 2 次 → 恢复;中间再越线 → 正常次数清零
  ⑤ 「高于」方向;值算不出(分母 0)→ 这一轮不算
  ⑥ 一整段 12 轮的序列,开待办只开 1 次(不重复轰炸)
"""
import datetime as dt
import os
import sys

_根 = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(_根, "services", "api", "app"))
import alert_rules as A  # noqa: E402

过, 挂 = [], []
规则 = {"方向": "低于", "阈值": 90, "最小样本": 10, "连续越线才报": 3, "连续正常才恢复": 2, "去重分钟": 60}
零 = {"连续越线": 0, "连续正常": 0, "触发中": False, "上次提醒": None}
T0 = dt.datetime(2026, 11, 4, 9, 0, tzinfo=dt.timezone.utc)


def ck(名, 真, 补=""):
    print(f"  {'✅' if 真 else '❌'} {名}{('  ' + str(补)[:300]) if 补 and not 真 else ''}")
    (过 if 真 else 挂).append(名)


def 跑(序列, 规=规则, 起=零):
    """序列:[(值, 样本, 第几分钟)…] → 每一步的动作。"""
    s, 出 = dict(起), []
    for 值, 样本, 分 in 序列:
        s, 动, _ = A.下一步(s, 值, 样本, 规, T0 + dt.timedelta(minutes=分))
        出.append(动)
    return s, 出


def main():
    print("▸ ① 一两次波动不报")
    s, 动 = 跑([(80, 20, 0)])
    ck("越线 1 次(要连续 3 次)→ 不动,连续越线记 1", 动 == ["不动"] and s["连续越线"] == 1 and not s["触发中"], (动, s))
    s, 动 = 跑([(80, 20, 0), (80, 20, 5), (95, 20, 10)])
    ck("越线两次又正常 → 不报,连续越线清零", 动 == ["不动"] * 3 and s["连续越线"] == 0, (动, s))

    print("\n▸ ② 连续越线 → 开待办 → 去重周期内不提醒 → 过了再提醒")
    s, 动 = 跑([(80, 20, 0), (80, 20, 5), (80, 20, 10), (80, 20, 15), (80, 20, 75)])
    ck("**第 3 次开待办;第 4 次(5 分钟后)不动;过了 60 分钟去重周期 → 提醒**",
       动 == ["不动", "不动", "开待办", "不动", "提醒"] and s["触发中"], 动)

    print("\n▸ ③ 样本不够那一轮不算")
    s, 动 = 跑([(80, 20, 0), (50, 3, 5), (80, 20, 10), (80, 20, 15)])
    ck("**中间一轮只有 3 条样本 → 不算、不清零**:越线 1 → (不算) → 2 → 3 开待办",
       动 == ["不动", "不动", "不动", "开待办"], 动)
    s2, 动2 = 跑([(80, 20, 0), (50, 3, 5)])
    ck("样本不够那一轮后,连续越线还是 1(没被清零)", s2["连续越线"] == 1, s2)
    s3, 动3 = 跑([(None, 0, 0)])
    ck("值算不出(分母 0)→ 不算", 动3 == ["不动"] and s3 == 零, s3)

    print("\n▸ ④ 恢复要连续正常")
    触 = {"连续越线": 3, "连续正常": 0, "触发中": True, "上次提醒": T0}
    s, 动 = 跑([(95, 20, 5)], 起=触)
    ck("正常 1 次(要 2 次)→ 还在触发中", 动 == ["不动"] and s["触发中"] and s["连续正常"] == 1, (动, s))
    s, 动 = 跑([(95, 20, 5), (95, 20, 10)], 起=触)
    ck("**连续 2 次正常 → 恢复**", 动 == ["不动", "恢复"] and not s["触发中"], (动, s))
    s, 动 = 跑([(95, 20, 5), (80, 20, 10), (95, 20, 15)], 起=触)
    ck("正常一次、又越线、再正常一次 → 不恢复(正常次数被越线清零)", "恢复" not in 动 and s["触发中"], (动, s))

    print("\n▸ ⑤ 方向")
    高 = dict(规则, 方向="高于", 阈值=5, 连续越线才报=1)
    s, 动 = 跑([(7, 20, 0)], 规=高)
    ck("「高于 5」、这次 7 → 开待办", 动 == ["开待办"], 动)
    s, 动 = 跑([(5, 20, 0)], 规=高)
    ck("正好等于阈值不算越线(「高于」是严格大于)", 动 == ["不动"] and not s["触发中"], 动)

    print("\n▸ ⑥ 不重复轰炸")
    序 = [(80, 20, 5 * i) for i in range(12)]          # 一小时里一直越线
    s, 动 = 跑(序)
    ck("一小时里一直越线(12 轮)→ 开待办只 1 次,去重 60 分钟内一次提醒都没有", 动.count("开待办") == 1 and 动.count("提醒") == 0, 动)
    ck("指标表里的每个指标都取得出(取指标不抛)", all(
        A.取指标({"可用性": {"终态成功率": None, "终态成功率分母": 0, "失败": 0, "终态": 0, "接收": 0},
                  "业务": {"写入办成率": None, "写入办成率分母": 0, "办成": 0},
                  "性能": {"端到端": {"P95秒": None, "样本数": 0}},
                  "成本": {"每个办成任务成本": None, "算不出金额的笔数": 0}}, k) is not None for k in A.指标们))

    print()
    if 挂:
        print(f"❌ {len(挂)} 条不过:{' / '.join(挂)}")
        return 1
    print(f"✅ 告警判定:{len(过)} 条全过")
    return 0


if __name__ == "__main__":
    sys.exit(main())
