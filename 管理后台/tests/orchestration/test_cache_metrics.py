#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""缓存指标的纯逻辑 —— **零 IO,跑在 CI 里**。规格 §17.2 + 附录 A-8。

## 这一组每一条都对着一种**会算出假收益**的方式

附录 A-8 列了三种:「把无调用当未命中、只展示成功样本、用总均值掩盖关键错用」;
审阅又加一条:「不能依据工具数下降或 Token 数下降直接宣称成本下降」。

而这个仓库**真的栽过那一条**(2026-10-03):报「开筛选省 71%」,
真因是基线臂第一题在**写**缓存(14 万 token)、对照臂跑在后面吃热缓存 ——
焐热 + 交错跑之后真数是 12%。

> **一个把未知项当 0 算出来的「省了 71%」,和一个真的省了 71% 的,
> 在那个百分比上长得一模一样。**
"""
import os
import sys

_根 = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(_根, "services", "api", "app", "cache"))

import metrics as M

过, 挂 = [], []


def ck(名, 真, 补=""):
    print(f"  {'✅' if 真 else '❌'} {名}{('  ' + str(补)[:170]) if 补 else ''}")
    (过 if 真 else 挂).append(名)


print("缓存指标(规格 §17.2 / 附录 A-8)")
print("=" * 92)

print("\n▸ ① 分母为 0 → **「不适用」**,不是 0%")
ck("一次都没尝试查缓存 → **不适用**",
   M.答案命中率(返回了缓存答案的请求数=0, 真的尝试过查缓存的请求数=0) == M.不适用)
ck("而「尝试了 10 次、命中 0 次」→ **0.0**(这个要去查,上面那个不用)",
   M.答案命中率(返回了缓存答案的请求数=0, 真的尝试过查缓存的请求数=10) == 0.0)
ck("**这两件事不是同一个数** —— 混成 0% 的话,"
   "「一次都没用上」和「用了但一次没命中」就分不开了",
   M.答案命中率(返回了缓存答案的请求数=0, 真的尝试过查缓存的请求数=0)
   != M.答案命中率(返回了缓存答案的请求数=0, 真的尝试过查缓存的请求数=10))

print("\n▸ ② 命中率和覆盖率**分母不同**,不许混")
命 = M.答案命中率(返回了缓存答案的请求数=3, 真的尝试过查缓存的请求数=3)
覆 = M.答案复用覆盖率(返回了缓存答案的请求数=3, 全部请求数=100)
ck("只对 3 个请求查了缓存、全中 → 命中率 100%", 命 == 1.0, 命)
ck("而复用覆盖率只有 3%", abs(覆 - 0.03) < 1e-9, 覆)
ck("**两个数差 33 倍** —— 混成一个的话,"
   "「只对 3% 请求开了而全中」和「对全部开了而中 3%」长得一模一样",
   命 / 覆 > 30)

print("\n▸ ③ 分子大于分母 → **抛**,不许截到 100%")
try:
    M.答案命中率(返回了缓存答案的请求数=11, 真的尝试过查缓存的请求数=10)
    ck("分子 > 分母 → 抛", False, "**它没抛 —— 等于把事件重复计数显示成了 100%**")
except M.算不了 as e:
    ck("分子 > 分母 → 抛(截了的话「事件被重复计数」会显示成一个漂亮的数)",
       "不截到 100%" in str(e), str(e)[:90])

print("\n▸ ④ 提示词命中率:**未知既不算命中也不算未命中**(A-8 的「把无调用当未命中」)")
r = M.提示词命中调用率(确认缓存读大于0的调用数=6, 缓存读字段已知的调用数=8,
                总生成调用数=20)
ck("分母是**字段已知的那 8 次** → 命中率 75%", abs(r["命中率"] - 0.75) < 1e-9, r["命中率"])
ck("而可观测覆盖率是 8/20 = 40%(规格明写「另报可观测覆盖率」)",
   abs(r["可观测覆盖率"] - 0.4) < 1e-9, r["可观测覆盖率"])
ck("未知的那 12 次**单独报出来**,没被当成未命中", r["未知的调用数"] == 12, r)
ck("要是拿「全部调用」当分母,命中率会变成 30% —— **而那 12 次根本没有字段可判**",
   abs(6 / 20 - 0.3) < 1e-9 and r["命中率"] != 0.3)
try:
    M.提示词命中调用率(确认缓存读大于0的调用数=6, 缓存读字段已知的调用数=8,
                 总生成调用数=None)
    ck("少给一个计数 → 抛", False, "它没抛")
except M.算不了 as e:
    ck("少给一个计数 → **抛**(省掉的那个会让分母变小、命中率变高)",
       "省一个" in str(e), str(e)[:80])

print("\n▸ ⑤ 抽检率**必须带抽样方法**,而且少量零错不许说成零错")
try:
    M.抽检错误复用率(判为不适用的交付数=0, 完成独立抽检的交付数=5, 抽样怎么来的="")
    ck("不说抽样怎么来的 → 抛", False, "它没抛")
except M.算不了 as e:
    ck("不说抽样怎么来的 → **抛**(抽检率不带抽样方法等于没有意义)",
       "抽样" in str(e), str(e)[:80])
少 = M.抽检错误复用率(判为不适用的交付数=0, 完成独立抽检的交付数=5,
               抽样怎么来的="按时间等距抽,冻结于 2026-10-04")
ck("抽了 5 条零错 → 率是 0,**而那句话明说「不能宣称总体零错」**",
   少["错误复用率"] == 0.0 and "不能宣称总体零错" in 少["怎么读"], 少["怎么读"])
ck("而且**抽检量跟着那个数一起出现**(规格 §7:错误率旁显示抽检量)",
   少["抽检了多少"] == 5)

print("\n▸ ⑥ 任一桶缺单价 → 金额**未知**,不是「少算那一桶的部分和」")
金, 缺 = M.已知生成费用(计费桶们={"input_tokens": 1000, "ephemeral_1h_input_tokens": 500},
                 单价们={"input_tokens": 1e-6})
ck("缺 1 小时档的单价 → 金额是 **None**", 金 is M.未知, 金)
ck("而且点名缺的是哪一桶", 缺 == ["ephemeral_1h_input_tokens"], 缺)
ck("**不返回 0.001(只算了 input 那一桶)** —— "
   "一个少算了一桶的总额,和一个算全了的,在那个数字上长得一样", 金 != 0.001)
金2, 缺2 = M.已知生成费用(计费桶们={"input_tokens": 1000},
                   单价们={"input_tokens": 1e-6})
ck("桶的单价都有 → 算得出", abs(金2 - 0.001) < 1e-12 and 缺2 == [], 金2)

print("\n▸ ⑦ 净节省:**未知项当 0 就是假收益**(这个仓库栽过的那一次)")
假 = M.净节省估算(基线费用=0.10, 当前已知费用=0.029, 还没纳入的缓存成本=None,
            对照是怎么来的="实测对比")
ck("有一项未知 → 净节省是 **None**,并点名哪一项",
   假["净节省"] is M.未知 and 假["未知项"] == ["还没纳入的缓存成本"], 假["未知项"])
ck("**不返回 0.071** —— 那正是 2026-10-03 那次「省 71%」的形状",
   假["净节省"] != 0.071)
真 = M.净节省估算(基线费用=0.10, 当前已知费用=0.029, 还没纳入的缓存成本=0.059,
            对照是怎么来的="反事实估算")
ck("三项都有 → 算得出(0.10 − 0.029 − 0.059 = 0.012)",
   abs(真["净节省"] - 0.012) < 1e-12, 真["净节省"])
ck("而且**明说这是反事实估算,不是真跑出来的**",
   "不是真跑出来的" in 真["怎么读"], 真["怎么读"][:70])
for 坏 in ("", "大概算的", "调用少了 8 次", None):
    try:
        M.净节省估算(基线费用=1, 当前已知费用=1, 还没纳入的缓存成本=0,
               对照是怎么来的=坏)
        ck(f"对照来路给 {坏!r} → 抛", False, "它没抛")
    except M.算不了 as e:
        ck(f"对照来路给 {坏!r} → **抛**(只收「实测对比」/「反事实估算」)",
           "实测对比" in str(e), str(e)[:60])

print("\n▸ ⑧ 答案命中那一次:生成费用 0,**而总费用可能仍未知**")
账 = M.一次答案命中的账(来源那次的费用=0.013)
ck("本次生成费用 = 0(确实没有模型调用)", 账["本次生成费用"] == 0.0)
ck("而本次**总**费用是 **None** —— 缓存查询和存储还没算进来",
   账["本次总费用"] is M.未知, 账["本次总费用"])
ck("**来源那次的 $0.013 只当来路,不进本次总额** —— "
   "复制过来就是「复用旧费用形成假节省」(附录 A-6)",
   账["来源那次花了多少"] == 0.013 and 账["本次总费用"] != 0.013)
账2 = M.一次答案命中的账(来源那次的费用=0.013, 本次缓存查询费用=0.0001,
                 本次存储费用=0.00002)
ck("两项都给了 → 总费用算得出,而且**不等于 0**"
   "(「本次生成费用 0」不等于「本次免费」)",
   abs(账2["本次总费用"] - 0.00012) < 1e-12 and 账2["本次总费用"] != 0,
   账2["本次总费用"])

print("\n" + "=" * 92)
print(f"{'✅' if not 挂 else '❌'} 过 {len(过)} / 挂 {len(挂)}")
for x in 挂:
    print("   挂:", x)
sys.exit(1 if 挂 else 0)
