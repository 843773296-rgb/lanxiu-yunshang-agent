#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""「这次运行该用哪一版策略」—— 零 IO。规格 §4.2 / §4.3 / §9.2 / §10.3。

## 这一组每一条都对着一种**悄悄变成「没有限制」**的方式

规格 §4.3:「没有有效策略或所需硬限制不受支持时,**拒绝启动受影响任务;
不能回退为「无限制」**。配置服务不可用不等于额度可以清零。」

而最容易写出来的恰恰是那一行 `策略 = 拉配置() or 默认不限制`:

> **一个「配置服务挂了所以没限制」的运行,和一个「真被授权不限制」的,
> 在那次运行上长得一模一样。**

⚠️ **时间用注入的,不读墙钟**(这个仓库为「夹具写死日期」栽过)。
"""
import os
import sys

_根 = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(_根, "services", "api", "app", "runtime"))

import 策略解析 as P

过, 挂 = [], []


def ck(名, 真, 补=""):
    print(f"  {'✅' if 真 else '❌'} {名}{('  ' + str(补)[:150]) if 补 else ''}")
    (过 if 真 else 挂).append(名)


现在 = 10_000

版 = dict(id="epv_7", content_hash="h7", entry_kind=P.门店V3,
         support_conditions=["tool_attempt_cap", "task_deadline"],
         limits={"tool_attempt_cap": 12, "task_deadline_seconds": 60})
回执 = dict(execution_policy_version_id="epv_7", policy_hash="h7",
          loaded_at=现在 - 60,
          capability_map={"tool_attempt_cap": True, "task_deadline": True})
回退 = dict(id="epv_6", limits={"tool_attempt_cap": 10}, 验证于=现在 - 3600,
          有效到=现在 + 3600, 为什么回退="配置服务 5xx")

print("这次用哪一版策略(规格 §4.2 / §4.3 / §9.2 / §10.3)")
print("=" * 92)

print("\n▸ ① 一切都对 → 采用,而且细节里能对上版本和哈希")
v, st, d = P.这次用哪一版(入口=P.门店V3, 发布的=版, 这个实例的回执=回执, 现在=现在)
ck("发布了、实例回执了这一版、哈希对、不陈旧、硬限制都支持 → 采用",
   st == P.采用 and v is 版, st)
ck("细节里给出版本 / 哈希 / 回执年龄 / 核过的硬限制(P0-B 的退出条件就是「对得上」)",
   d["对上了"]["版本"] == "epv_7" and d["对上了"]["哈希"] == "h7"
   and d["对上了"]["回执年龄秒"] == 60 and len(d["对上了"]["核过的硬限制"]) == 2,
   d["对上了"])

print("\n▸ ② **有发布 ≠ 已加载** —— 没有回执不是「已生效」(规格 §9.2)")
v2, st2, d2 = P.这次用哪一版(入口=P.门店V3, 发布的=版, 这个实例的回执=None,
                      现在=现在, 本地回退=None)
ck("发布了而实例没回执、也没本地回退 → **拒绝启动**", st2 == P.拒绝启动 and v2 is None, st2)
ck("理由里点名「尚未确认加载」", "尚未确认加载" in str(d2.get("为什么没采用")),
   str(d2.get("为什么没采用"))[:60])
ck("⚠️ 而且说出那个形状:一条发了而没人加载的策略,和一条真在执行的,"
   "**在那个「已发布」上长得一样**", "长得一模一样" in str(d2))
v3, st3, d3 = P.这次用哪一版(入口=P.门店V3, 发布的=版, 这个实例的回执=None,
                      现在=现在, 本地回退=回退)
ck("同样情形但**有**本地回退 → 回退(不是采用,也不是拒绝)",
   st3 == P.回退 and v3 is 回退, st3)

print("\n▸ ③ 哈希不符 → **冲突,直接拒绝**;连回退都不走")
v4, st4, d4 = P.这次用哪一版(入口=P.门店V3, 发布的=版,
                      这个实例的回执=dict(回执, policy_hash="h_别的"),
                      现在=现在, 本地回退=回退)
ck("实例自报加载了这一版而哈希不符 → **拒绝启动**", st4 == P.拒绝启动 and v4 is None, st4)
ck("**即使有本地回退也不回退** —— 我们不知道那台实例在跑什么",
   "回退用的" not in d4 and "冲突" in d4, list(d4.keys()))
ck("理由里点名规格 §10.3「服务端核验身份」,不是「以回执为准」",
   "核验身份" in str(d4["冲突"]), str(d4["冲突"]["⚠️"])[:70])
v5, st5, d5 = P.这次用哪一版(入口=P.门店V3, 发布的=版,
                      这个实例的回执=dict(回执,
                                   execution_policy_version_id="epv_6"),
                      现在=现在, 本地回退=回退)
ck("而「回执的是另一版」是**另一回事** → 走回退(它只是还没切过去)",
   st5 == P.回退, st5)
ck("⚠️ 这两种**不能混**:哈希不符是冲突(拒绝),回执旧版是没切过去(回退)",
   st4 != st5)

print("\n▸ ④ 回执**会陈旧**,而陈旧要算出来(规格 §10.2)")
for 老, 该 in ((899, P.采用), (900, P.采用), (901, P.回退)):
    vx, stx, dx = P.这次用哪一版(入口=P.门店V3, 发布的=版,
                          这个实例的回执=dict(回执, loaded_at=现在 - 老),
                          现在=现在, 回执最长年龄秒=900, 本地回退=回退)
    ck(f"回执 {老} 秒前(上限 900)→ {该}", stx == 该, (stx, dx.get("回执年龄秒")))
_, _, d6 = P.这次用哪一版(入口=P.门店V3, 发布的=版,
                   这个实例的回执=dict(回执, loaded_at=现在 - 5000),
                   现在=现在, 回执最长年龄秒=900, 本地回退=回退)
ck("陈旧时点名那个形状:一份三天前的回执,和一份刚刚确认的,"
   "**在那个「已加载」上长得一样**", "长得一模一样" in str(d6.get("陈旧")),
   str(d6.get("陈旧"))[:70])
try:
    P.这次用哪一版(入口=P.门店V3, 发布的=版,
             这个实例的回执=dict(回执, loaded_at=现在 + 100), 现在=现在)
    ck("回执时间在未来 → 抛", False, "它没抛")
except P.解析不了 as e:
    ck("回执时间在**未来** → 抛(**不当成「很新」**:时钟不对时它会永远不过期)",
       "永远不过期" in str(e), str(e)[:70])

print("\n▸ ⑤ 硬限制:**「没核查过」不是「支持」**,而且这一支不走回退")
for 能力, 叫法, 该键 in (
        ({"tool_attempt_cap": True, "task_deadline": False}, "明确不支持", "不支持"),
        ({"tool_attempt_cap": True}, "少报了一项(没核查过)", "没核查过"),
        ({"tool_attempt_cap": True, "task_deadline": None}, "报了 None", "没核查过"),
        ({"tool_attempt_cap": True, "task_deadline": "unknown"}, "报了字符串",
         "没核查过")):
    vy, sty, dy = P.这次用哪一版(入口=P.门店V3, 发布的=版,
                          这个实例的回执=dict(回执, capability_map=能力),
                          现在=现在, 本地回退=回退)
    ck(f"{叫法} → **拒绝启动**(不是回退)",
       sty == P.拒绝启动 and vy is None
       and dy["硬限制对不上"][该键] == ["task_deadline"],
       dy.get("硬限制对不上"))
ck("⚠️ 这一支**有本地回退也不回退** —— 回退换的是「哪一版策略」,"
   "而这条问的是「这台实例做不做得到」,换旧策略照样做不到",
   "回退用的" not in P.这次用哪一版(
       入口=P.门店V3, 发布的=版,
       这个实例的回执=dict(回执, capability_map={"tool_attempt_cap": False}),
       现在=现在, 本地回退=回退)[2])
ck("理由里点名「**不能回退为「无限制」**」(规格 §4.3)",
   "无限制" in str(P.这次用哪一版(
       入口=P.门店V3, 发布的=版,
       这个实例的回执=dict(回执, capability_map={"tool_attempt_cap": False}),
       现在=现在)[2].get("⚠️")))

print("\n▸ ⑥ 回退是**要显形**的路:四样缺一就不叫回退")
for 缺 in ("id", "limits", "验证于", "有效到", "为什么回退"):
    v7, st7, d7 = P.这次用哪一版(
        入口=P.门店V3, 发布的=None, 现在=现在,
        本地回退={k: v for k, v in 回退.items() if k != 缺})
    ck(f"本地回退缺 `{缺}` → **拒绝启动**(不叫回退,叫不知道在跑哪一版)",
       st7 == P.拒绝启动 and 缺 in str(d7.get("⚠️")), str(d7.get("⚠️"))[:60])
v8, st8, d8 = P.这次用哪一版(入口=P.门店V3, 发布的=None, 现在=现在, 本地回退=回退)
ck("四样都齐 → 回退,且四样都在细节里(规格 §4.3 要求页面展示)",
   st8 == P.回退 and all(k in d8["回退用的"]
                       for k in ("版本", "验证于", "年龄秒", "有效到", "为什么回退")),
   d8["回退用的"])
for t, 该 in ((回退["有效到"] - 1, P.回退), (回退["有效到"], P.拒绝启动),
            (回退["有效到"] + 1, P.拒绝启动)):
    _, st9, _ = P.这次用哪一版(入口=P.门店V3, 发布的=None, 现在=t, 本地回退=回退)
    ck(f"回退有效到 {回退['有效到']},现在 {t} → {该}(**严格小于**)", st9 == 该, st9)

print("\n▸ ⑦ 完全没东西 → **拒绝启动**,这是这个函数存在的理由")
v10, st10, d10 = P.这次用哪一版(入口=P.门店V3, 发布的=None, 现在=现在, 本地回退=None)
ck("没发布、没回退 → 拒绝启动,**不是「不限制」**",
   st10 == P.拒绝启动 and v10 is None, st10)
ck("理由里明说「配置服务不可用**不等于额度可以清零**」",
   "额度可以清零" in str(d10.get("⚠️")), str(d10.get("⚠️"))[:70])
ck("⚠️ 返回的 `用哪一版` 是 None,而**调用方不许把 None 读成「没有限制」** —— "
   "`状态` 才是答案", v10 is None and st10 != P.采用)

print("\n▸ ⑧ 入口不跨借;缺字段就抛")
for 坏 in ("", None, "store_V3", "通用", "v3"):
    try:
        P.这次用哪一版(入口=坏, 发布的=版, 这个实例的回执=回执, 现在=现在)
        ck(f"入口 {坏!r} → 抛", False, "它没抛")
    except P.解析不了 as e:
        ck(f"入口 {坏!r} → **抛**(不给「通用」留口子)", "认不出" in str(e))
        break
try:
    P.这次用哪一版(入口=P.后台编排, 发布的=版, 这个实例的回执=回执, 现在=现在)
    ck("发布的是给门店 V3 的,而这次是后台编排 → 抛", False, "它没抛")
except P.解析不了 as e:
    ck("**不跨入口借用**(规格 §2.2:一边通过不得被另一边借用为验收证据)",
       "不跨入口借用" in str(e), str(e)[:70])
for 去 in ("id", "content_hash", "support_conditions", "limits"):
    try:
        P.这次用哪一版(入口=P.门店V3,
                 发布的={k: v for k, v in 版.items() if k != 去},
                 这个实例的回执=回执, 现在=现在)
        ck(f"发布的那一版缺 `{去}` → 抛", False, "它没抛")
    except P.解析不了 as e:
        ck(f"缺 `{去}` → **抛,不拿默认值顶**", 去 in str(e), str(e)[:60])
ck("⚠️ 缺 `limits` 尤其要抛 —— 一版缺 limits 的策略,"
   "和一版「不限制」的,**在那次运行上长得一模一样**", True)
try:
    P.这次用哪一版(入口=P.门店V3, 发布的=版, 这个实例的回执=回执, 现在=None)
    ck("没有时钟 → 抛", False, "它没抛")
except P.解析不了 as e:
    ck("没有时钟 → **抛**(算不了年龄不等于「还新鲜」)", "算不了" in str(e))

print("\n" + "=" * 92)
print(f"{'✅' if not 挂 else '❌'} 过 {len(过)} / 挂 {len(挂)}")
for x in 挂:
    print("   挂:", x)
sys.exit(1 if 挂 else 0)
