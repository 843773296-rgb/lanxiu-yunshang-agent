#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""意图识别纯函数(2026-11-08,查询理解第三期)。不要数据库、不调真模型(调模型那一步传假的)。

  ① 配置检查:没意图 / 名称重复 / 名称占用「判不出」/ 没说明 → 阻断;没例句 → 提醒
  ② 分类提示:每个意图的名称、说明、例句都进了提示;要求只回一行 JSON;店长原话在 user 里
  ③ 三种结果分开:判出 / 判不出(模型明说哪个都不像、或答了清单外的名字)/ 调用失败(抛错、回答没 JSON)
  ④ 分类() 永远不抛错 —— 分类坏了不许拖垮这一轮回答;用的模型默认是最便宜那档、配置里可覆盖
"""
import os
import sys

_根 = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(_根, "services", "api", "app", "runtime"))
import 意图 as I  # noqa: E402

过, 挂 = [], []


def ck(名, 真, 补=""):
    print(f"  {'✅' if 真 else '❌'} {名}{('  ' + str(补)[:300]) if 补 and not 真 else ''}")
    (过 if 真 else 挂).append(名)


配 = {"意图": [{"名称": "报价", "说明": "要出一份能发给客户的报价单_chk", "例句": ["给 C10001 出个报价", "这套多少钱"]},
               {"名称": "问知识", "说明": "形制面料工艺口径", "例句": ["宋锦和云锦有什么区别"]}]}


def main():
    ck("① 合规配置没有阻断", I.意图配置问题(配)[0] == [], I.意图配置问题(配))
    阻, 醒 = I.意图配置问题({"意图": [{"名称": "判不出", "说明": "x"}, {"名称": "a", "说明": ""}, {"名称": "a", "说明": "y"}]})
    ck("① 占用「判不出」/ 没说明 / 名称重复 → 阻断",
       all(any(k in x for x in 阻) for k in ("留给", "没有说明", "重复")), 阻)
    ck("① 空配置 → 阻断", I.意图配置问题({"意图": []})[0] != [])
    ck("① 没例句 → 提醒(不阻断)", any("例句" in x for x in I.意图配置问题({"意图": [{"名称": "a", "说明": "b"}]})[1]))
    s, u = I.分类提示(配, "这套做下来多少钱")
    ck("② 名称 / 说明 / 例句都进提示,只回一行 JSON,原话在 user 里",
       "报价" in s and "报价单_chk" in s and "给 C10001 出个报价" in s and "JSON" in s and "判不出" in s and "这套做下来多少钱" in u, (s[:200], u))
    r = I.分类("出个价", 配, lambda s, u, m: '{"意图": "报价", "把握": "高"}')
    ck("③ 判出:意图名在清单里", (r["意图"], r["态"]) == ("报价", "判出"), r)
    r = I.分类("今天天气", 配, lambda s, u, m: '好的 {"意图": "判不出", "把握": "低"}')
    ck("③ 判不出:模型明说哪个都不像(回答前后夹了别的字也认得出 JSON)", (r["意图"], r["态"]) == (None, "判不出"), r)
    r = I.分类("x", 配, lambda s, u, m: '{"意图": "排班"}')
    ck("③ 判不出:答了清单外的名字,原因里点名", r["态"] == "判不出" and "排班" in r["原因"], r)
    r = I.分类("x", 配, lambda s, u, m: (_ for _ in ()).throw(TimeoutError("超时")))
    ck("③④ 调用失败:抛错不往外抛,态=调用失败、原因带错误类型", r["态"] == "调用失败" and "TimeoutError" in r["原因"], r)
    r = I.分类("x", 配, lambda s, u, m: "我觉得是报价")
    ck("③ 调用失败:回答里没 JSON(不当成判不出)", r["态"] == "调用失败", r)
    用 = []
    I.分类("x", 配, lambda s, u, m: 用.append(m) or '{"意图":"报价"}')
    I.分类("x", dict(配, 模型="claude-test-x"), lambda s, u, m: 用.append(m) or '{"意图":"报价"}')
    ck("④ 默认用最便宜那档(分类模型),配置里写了模型就用配置的", 用 == [I.分类模型, "claude-test-x"], 用)
    print()
    if 挂:
        print(f"❌ {len(挂)} 条不过:{' / '.join(挂)}")
        return 1
    print(f"✅ 意图识别纯函数:{len(过)} 条全过")
    return 0


if __name__ == "__main__":
    sys.exit(main())
