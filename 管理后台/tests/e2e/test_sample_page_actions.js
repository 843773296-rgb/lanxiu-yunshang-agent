/* 样本那一页的改样本动作**在页面代码里真走一遍**。
 *
 * ## 这一页和别的不一样:它同时是一条**安全边界**
 *
 * 样本是真实客户对话(姓名/手机号/地址/体型尺寸)。所以除了接线,
 * 这一份还断两件安全性质:
 *
 *   ① **没有那条字段级授权时,页面拿到的响应里一个原文字都没有** ——
 *      不是「界面没显示」,是**接口根本没给**。
 *      (界面没显示而数据在响应里,等于原文已经到了浏览器、进了 devtools。)
 *   ② **没有截断版**。给的是字数。截到前几个字,那几个字仍然是原文,
 *      而「截断过」会让人以为它安全了。
 *
 * ## 接线那一半
 *
 * | 容易错的地方 | 错了会怎样 |
 * |---|---|
 * | 拿**数据集的** revision 改样本 | 409「这条样本已经被改过」—— 读起来像「别人改过了」 |
 * | 一页多条样本共用一个 revision | 改第二条时必 409,而第一条看起来是好的 |
 * | 复核状态在前端硬编 | 和白名单漂 —— 少一个能选的或多一个会被 422 拒的 |
 */
"use strict";
const fs = require("fs"), path = require("path");
const 桩 = require("./_页面桩.js");

const 项目 = 桩.默认项目;
const P = 桩.P(项目);
const src = fs.readFileSync(
  path.join(__dirname, "..", "..", "apps", "web", "app.js"), "utf8");

const 该跑几组 = 4;
const { ck, 组, 结束, 状 } = 桩.计分(该跑几组);

// 改过的样本原值 —— `finally` 里按它还原。
const 原值 = [];
let 那份id = null;

// ⚠️ 挑**真有内容**的那一份 —— 拿「一个样本都没有的那一份」来验
// 「原文拿不到」会是空跑:空列表上所有性质都成立。
const 要这份 = "里面真带客户信息的那一份";

(async () => {
  console.log("\n\x1b[1m▸ 样本:改一条 + 原文默认拿不到\x1b[0m");
  console.log("  ⚠️ 这一份同时是一条**安全边界**:验的是「接口有没有给原文」,"
    + "不是「界面有没有显示」");

  // U002(editor)**没有**「查看敏感输入」——「原文拿不到」要用他验
  const { 请求们, 弹过 } = 桩.装桩({ hash: "#/datasets", 我: "U002", 项目 });
  try { 桩.跑页面(src); } catch (e) {
    ck("app.js 同步执行不挂", false, e.message); 结束(弹过); return;
  }
  const 动 = globalThis.样本动作;
  ck("app.js 把 `样本动作` 导出来了", 动 && typeof 动.改 === "function",
     动 ? Object.keys(动) : null);
  if (!动) { 结束(弹过); return; }

  try {
    // ── ① 原文:没授权就**接口不给** ────────────────────────────────
    组("① 没有字段级授权 → **接口根本不给原文**");
    const [, ds] = await 桩.直打("GET", `${P}/datasets`, null, "U002");
    const 那份 = ((ds || {})["数据集"] || []).find((x) => x["名字"] === 要这份);
    ck(`找得到「${要这份}」(找不到的话下面全是空跑 —— 先 seed_datasets.py)`,
       Boolean(那份), 那份 && 那份.id);
    if (!那份) { 结束(弹过); return; }
    那份id = 那份.id;

    const [码, sl] = await 桩.直打("GET",
      `${P}/datasets/${那份.id}/samples`, null, "U002");
    const 样本们 = (sl || {})["样本们"] || [];
    ck("样本列表拿得到,而且有内容的样本不止一条"
       + "(只有一条的话「各自的 revision」那一组验不出来)",
       码 === 200 && 样本们.filter((x) => (x["内容"] || {})["有内容吗"]).length >= 2,
       样本们.length);
    ck("`看得到原文吗` = false(**明说**,不让人自己猜为什么是空的)",
       (sl || {})["看得到原文吗"] === false, (sl || {})["看得到原文吗"]);
    // ⚠️ **整个响应里一个原文字段都不许有。** 不只是断 `原文 === null` ——
    // 那样一个把原文放到别的键上的实现照样过。
    const 全文 = JSON.stringify(sl);
    ck("响应里**一个原文字段都没有**(断的是整个响应,不是某一个键 ——"
       + "只断那个键的话,把原文放到别的键上的实现照样过)",
       !/"原文":\s*"(?!null)/.test(全文) && !全文.includes('"content"'),
       全文.length + " 字的响应");
    ck("而且**没有截断版** —— 给的是字数(截到前几个字,那几个字仍然是原文)",
       样本们.every((x) => typeof (x["内容"] || {})["字数"] === "number"),
       样本们.slice(0, 3).map((x) => (x["内容"] || {})["字数"]));
    // 「本来是空的」和「被挡住了」要分得开
    ck("`有内容吗` 把「本来是空的」和「被挡住了」分开了"
       + "(画成同一个的话,下一步完全不同的两件事长得一样)",
       样本们.every((x) => "有内容吗" in (x["内容"] || {})),
       样本们.slice(0, 3).map((x) => (x["内容"] || {})["有内容吗"]));

    // ── ② 表单选项由接口给 ─────────────────────────────────────────
    组("② 分集 / 复核状态的选项**由接口给**");
    ck("接口给了 `可选分集` 和 `可选复核状态`",
       Array.isArray((sl || {})["可选分集"])
       && Array.isArray((sl || {})["可选复核状态"]),
       { 分集: (sl || {})["可选分集"], 复核: (sl || {})["可选复核状态"] });
    // 源码级:页面不许自己写一份复核状态
    const 页段 = src.slice(src.indexOf("async function 页_样本"),
                         src.indexOf("async function 页_训练任务"));
    const 硬编 = ["待复核", "已通过", "已退回"].filter((w) => 页段.includes(`"${w}"`));
    ck("页面**没有硬编**那三档复核状态(硬编会和白名单漂 ——"
       + "少一个能选的或多一个会被 422 拒的,都不报错)",
       硬编.length === 0, 硬编);

    // ── ③ 改样本:用**这一条自己的** revision ──────────────────────
    组("③ 改样本:用这一条自己的 revision");
    const 有内容的 = 样本们.filter((x) => (x["内容"] || {})["有内容吗"]);
    const 甲 = 有内容的[0], 乙 = 有内容的[1];
    // ⚠️ U002 是 editor —— 改样本要「改训练样本」,他是**可授权(默认关)**。
    // 所以这里换成 U004(annotator)。
    //   用 U002 打的话拿到 403,而那时红的理由是「改不了」,和接线无关。
    const { 请求们: 请求们B } = 桩.装桩({ hash: "#/datasets", 我: "U004", 项目 });
    try { 桩.跑页面(src); } catch (e) { ck("换身份后重载 app.js", false, e.message); }
    const 动B = globalThis.样本动作;

    // ⚠️ **改之前把原值记下来 —— 这一份要还原。**
    // 第一版我写的是「不还原,seed 每次重铺」,而那句话**是错的**:
    // `test_datasets_flow` 的「隔离了两条」依赖哪几条样本在训练集里,
    // 我把一条的分集改走之后它只剩一条命中 —— **那份测试当场红了**。
    // > 写脏了不还原,下一轮的结论就不可信,**而且先害的是别人那份测试**。
    // 而「再发一次真实 PATCH 等于没还原」也是错的:它带当前 revision,
    // **那不是绕过锁,那是用锁** —— 还原之后夹具是别人期望的样子。
    原值.push({ sid: 甲.id, 分集: 甲["分集"], 复核状态: 甲["复核状态"] });
    if (乙) 原值.push({ sid: 乙.id, 分集: 乙["分集"], 复核状态: 乙["复核状态"] });
    const 新分集 = ((sl || {})["可选分集"] || []).find((x) => x !== 甲["分集"])
      || 甲["分集"];
    const r1 = await 动B.改(那份.id, 甲.id, { 分集: 新分集 }, 甲["revision"]);
    ck("改第一条 → revision 涨了", (r1 || {})["revision"] === 甲["revision"] + 1,
       { 之前: 甲["revision"], 之后: (r1 || {})["revision"] });
    const 请1 = 桩.头里(请求们B, `/samples/${甲.id}`);
    ck("带的 If-Match 就是**这一条样本**的 revision(不是数据集的)",
       请1 && 请1.头["If-Match"] === String(甲["revision"]),
       { 带的: 请1 && 请1.头["If-Match"], 该带: 甲["revision"],
         数据集的: 那份["revision"] });

    // ⚠️ **第二条要用它自己的 revision。** 一页多条样本,各自的 revision 各自涨 ——
    // 共用一个的实现在改第二条时必 409,而第一条看起来完全正常。
    if (乙) {
      const r2 = await 动B.改(那份.id, 乙.id, { 分集: 乙["分集"] }, 乙["revision"]);
      ck("改第二条也成(**各自的 revision 各自用** ——"
         + "共用一个的实现在这一步必 409,而第一条看起来完全正常)",
         (r2 || {})["revision"] === 乙["revision"] + 1,
         { 乙之前: 乙["revision"], 乙之后: (r2 || {})["revision"] });
    } else {
      ck("⚠️ 只有一条有内容的样本 —— **「各自的 revision」这一条没验到**(不是通过)",
         false, 有内容的.length);
    }

    // 拿**数据集的** revision 去改样本 → 必须被拒
    let 混 = null;
    try {
      await 动B.改(那份.id, 甲.id, { 分集: 甲["分集"] }, 那份["revision"]);
    } catch (e) { 混 = e; }
    ck("拿**数据集的** revision 去改样本 → 409"
       + "(混起来的表现是一个读起来像「别人改过了」的错)",
       混 && 混.码 === 409,
       { 码: 混 && 混.码, 拿的是数据集的: 那份["revision"] });

    let 空 = null;
    try { await 动B.改(那份.id, 甲.id, { 分集: 甲["分集"] }, null); }
    catch (e) { 空 = e; }
    ck("revision 为 null → **当场本地报错,不发请求**",
       空 && (空.体 || {}).code === "NO_SAMPLE_REVISION",
       空 && (空.体 || {}).code);

    // ── ④ 白名单:拼错的复核状态**不许自成一档** ────────────────────
    组("④ 复核状态白名单(2026-09-29 补的)");
    // ⚠️ 这个白名单**原来是 None**(任意字符串都收)。
    // 同一个仓库在审核那条接口上写着「**不收任意字符串**:
    // 一个拼错的结论会自成一档」—— 同样的道理这儿以前没落地。
    const [, 详] = await 桩.直打("GET",
      `${P}/datasets/${那份.id}/samples`, null, "U004");
    const 甲2 = ((详 || {})["样本们"] || []).find((x) => x.id === 甲.id);
    let 拼错 = null;
    try {
      await 动B.改(那份.id, 甲.id, { 复核状态: "已通過" },  // 繁体「過」
                  (甲2 || {})["revision"]);
    } catch (e) { 拼错 = e; }
    ck("一个**繁体拼错**的复核状态(「已通過」)→ **422,不许自成一档**",
       拼错 && 拼错.码 === 422, 拼错 && { 码: 拼错.码, code: (拼错.体 || {}).code });
    ck("而且**说清只收哪几个**(不说的话人只能一个个试)",
       拼错 && /只收/.test(JSON.stringify(拼错.体 || {})),
       拼错 && JSON.stringify((拼错.体 || {}).field_errors || {}).slice(0, 80));
    const [, 详2] = await 桩.直打("GET",
      `${P}/datasets/${那份.id}/samples`, null, "U004");
    const 甲3 = ((详2 || {})["样本们"] || []).find((x) => x.id === 甲.id);
    ck("被拒之后那一条**没被改坏**(先写后拒等于已经出事了)",
       ((详2 || {})["可选复核状态"] || []).includes((甲3 || {})["复核状态"]),
       (甲3 || {})["复核状态"]);
  } catch (e) {
    ck(`跑到「${状.走过[状.走过.length - 1] || "开头"}」就抛了:${e.message}`,
       false, (e.体 && JSON.stringify(e.体).slice(0, 160))
       || String(e.stack || "").slice(0, 180));
  } finally {
    // ── 收尾:**把改过的标注还原**(带当前 revision 的合法 PATCH)───────
    // ⚠️ 这一段是补的。第一版写的是「不还原」,理由是
    // 「再发一次真实 PATCH 和不还原没区别」——**那是错的**:
    // 还原之后夹具是**别人那份测试期望的样子**。
    // 不还原的代价当场就来了:`test_datasets_flow` 的「隔离了两条」
    // 依赖哪几条样本在训练集里,我把一条的分集改走 → 它只剩一条命中 → 红。
    // > 写脏了不还原,下一轮的结论就不可信,**而且先害的是别人那份测试**。
    let 还原了 = 0, 还原失败 = [];
    for (const o of 原值) {
      try {
        const [, now] = await 桩.直打("GET",
          `${P}/datasets/${那份id}/samples`, null, "U004");
        const 现 = ((now || {})["样本们"] || []).find((x) => x.id === o.sid);
        if (!现) { 还原失败.push(o.sid + "(找不到了)"); continue; }
        if (现["分集"] === o.分集 && 现["复核状态"] === o.复核状态) {
          还原了++; continue;          // 本来就没变
        }
        await 桩.直打("PATCH", `${P}/datasets/${那份id}/samples/${o.sid}`,
                    { 分集: o.分集, 复核状态: o.复核状态 }, "U004",
                    { "If-Match": String(现["revision"]) });
        还原了++;
      } catch (e) { 还原失败.push(o.sid + ":" + String(e.message).slice(0, 40)); }
    }
    console.log(`\n▸ 收尾:还原了 ${还原了}/${原值.length} 条样本的标注`
      + (还原失败.length ? ` ⚠️ **没还原干净**:${还原失败}` : ""));
    if (还原失败.length) {
      // ⚠️ 还原失败要**红**,不是打印一句就算了 ——
      // 一条没还原干净的夹具,下一轮会去害别人那份测试,而那时红的是别人。
      状.挂.push("收尾没还原干净:" + 还原失败.join("; "));
    }
    结束(弹过);
  }
})();
