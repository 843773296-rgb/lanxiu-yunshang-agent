/* 成员与权限那一页的动作**在页面代码里真走一遍**。
 *
 * ## 这一页最硬的一条闸和别的都不一样
 *
 * 别的闸拦「**你做错了**」,这一道拦「**你做完之后没法回头**」:
 * 不许把项目里**最后一个能改权限的人**降下来 ——
 * 降了之后没有任何人能把权限加回来,而那一刻**界面上什么都不会报**。
 *
 * 所以这一份除了断「闸会拦」,还断**界面有没有提前把那个数说出来** ——
 * 一个只在被拒那一刻才出现的警告,**来得太晚**。
 *
 * ## 还有一条「角色名上看不出来」
 *
 * `可授权` 那一档**默认是关闭的**:一个角色「可以被授权某条能力」
 * 和「默认就有它」是两件事。所以:
 *   · 专项授权那一栏只能列 `可授权的能力`(全列 12 条的话大部分填了会被拒);
 *   · `实际能做的` 必须是**现算**的,不是存的字段 —— 存的会漂。
 *
 * ## 接线那一半
 *
 * | 容易错的地方 | 错了会怎样 |
 * |---|---|
 * | 角色 / 可授权能力在前端硬编 | 和权限矩阵漂 —— 少一个能选的或多一个会被拒的 |
 * | 把「加成员」和「改权限」做成两个口 | 人会去别处找「改权限」,而那儿没有 |
 * | 只显示 message 不显示闸 | 看到的是「改不了」,而**为什么**在 field_errors 里 |
 */
"use strict";
const fs = require("fs"), path = require("path");
const 桩 = require("./_页面桩.js");

const 项目 = 桩.默认项目;
const P = 桩.P(项目);
const 根 = path.join(__dirname, "..", "..");
const src = fs.readFileSync(path.join(根, "apps", "web", "app.js"), "utf8");

const 该跑几组 = 4;
const { ck, 组, 结束, 状 } = 桩.计分(该跑几组);

const 临时工号 = "Umem" + Math.random().toString(16).slice(2, 8);
// 这一轮动过 seed 里的成员吗 —— 动过就要在 finally 里用 seed_demo 还原。
let 动过seed成员 = false;

(async () => {
  console.log("\n\x1b[1m▸ 成员与权限:加成员 / 改角色与专项授权\x1b[0m");
  console.log("  ⚠️ 这一页最硬的闸拦的不是「做错了」,是**「做完之后没法回头」**");

  const { 请求们, 弹过 } = 桩.装桩({ hash: "#/members", 我: "U001", 项目 });
  try { 桩.跑页面(src); } catch (e) {
    ck("app.js 同步执行不挂", false, e.message); 结束(弹过); return;
  }
  const 动 = globalThis.成员动作;
  ck("app.js 把 `成员动作` 导出来了", 动 && typeof 动.保存 === "function",
     动 ? Object.keys(动) : null);
  if (!动) { 结束(弹过); return; }

  try {
    // ── ① 选项由接口给 ─────────────────────────────────────────────
    组("① 角色和可授权能力**由接口给**");
    const [码, d] = await 桩.直打("GET", `${P}/memberships`, null, "U001");
    ck("成员列表拿得到", 码 === 200 && Array.isArray((d || {})["成员"]),
       (d || {})["条数"]);
    ck("给了 `可选角色`", Array.isArray((d || {})["可选角色"])
       && (d || {})["可选角色"].length >= 5,
       ((d || {})["可选角色"] || []).map((x) => x["值"]));
    // ⚠️ **「可授权」那一栏单独给是必需的。** 矩阵里 12 条能力,
    // 只有标着 grantable 的那几条能当专项授权 —— 全列出来的话
    // 大部分填了会被闸拒,而界面上它们和能填的长得一样。
    // ⚠️ **这一条第一版断的是「一张拉平的清单」,而那是错的。**
    // 页面接线测试当场证明:给一个 `viewer` 加 `审批工具动作`,
    // 接口**收下了(201)**,而 `实际能做的` 里没有它 ——
    // 那条能力对 viewer 是 `deny`,只对 admin 是 `grantable`。
    // > **一个存下来却不生效的授权,比没存更坏** —— 界面上它看着是给了的。
    // 现在接口按**角色**给,而且 `可以改成员吗` 多了一道闸把这种当场拦住。
    const 可授权表 = (d || {})["可授权的能力"] || {};
    ck("`可授权的能力` 是**按角色**给的(不是一张拉平的清单 ——"
       + "拉平的话界面会给 viewer 摆一个勾了没用的框)",
       可授权表 && !Array.isArray(可授权表)
       && Object.keys(可授权表).length >= 5,
       Object.keys(可授权表).map((r) => `${r}:${(可授权表[r] || []).length}`));
    ck("而且 **viewer 是空的**(它一条都不能被授权 ——"
       + "「空」在这儿是个答案,不是「还没查」)",
       Array.isArray(可授权表["viewer"]) && 可授权表["viewer"].length === 0,
       可授权表["viewer"]);
    ck("admin 能被授权的那几条**不是空的**(两边都空的话这组分不出对错)",
       (可授权表["admin"] || []).length >= 1, 可授权表["admin"]);
    ck("明说了**`可授权` 默认是关的**(角色名上看不出来)",
       Boolean((d || {})["⚠️可授权是默认关的"]),
       String((d || {})["⚠️可授权是默认关的"] || "").slice(0, 36));
    // 源码级:页面不许硬编角色
    const 页段 = src.slice(src.indexOf("const 成员动作 = {"),
                         src.indexOf("async function 页_成员与权限"));
    const 硬编 = ["viewer", "editor", "annotator", "trainer", "approver"]
      .filter((r) => 页段.includes(`"${r}"`));
    ck("页面**没有硬编**那几个角色(硬编会和权限矩阵漂)", 硬编.length === 0, 硬编);

    // ── ② 界面**提前**把「几个人能改权限」说出来 ─────────────────────
    组("② 界面提前说出「几个人能改权限」");
    ck("接口给了 `能改权限的`", Array.isArray((d || {})["能改权限的"]),
       (d || {})["能改权限的"]);
    // ⚠️ 这一条是**源码级**的,而且它守的是时机:
    // 一个只在被拒那一刻才出现的警告,**来得太晚** ——
    // 那时人已经点了「保存」,而他想做的事做不了。
    const 列表段 = src.slice(src.indexOf("async function 页_成员与权限"),
                           src.indexOf("async function 页_数据集"));
    ck("页面**在列表上就把那个人数写出来**(而不是等被拒才说)",
       /能改权限的"\] \|\| \[\]\)\.length/.test(列表段),
       列表段.includes("能改权限的"));
    ck("而且只剩一个人的时候**单独标出来并说怎么办**(「先加一个再动他」)",
       列表段.includes("先加一个再动他"), 列表段.includes("先加一个再动他"));

    // ── ③ 加成员 / 改权限是同一个口 ───────────────────────────────
    组("③ 加成员和改权限**是同一个口**");
    const r1 = await 动.保存(临时工号, "viewer", []);
    ck("加一个 viewer → 有结果", Boolean(r1), JSON.stringify(r1).slice(0, 110));
    ck("`实际能做的` 是**现算**的(不是存的字段 —— 存的会漂)",
       Array.isArray((r1 || {})["实际能做的"])
       && (r1 || {})["实际能做的"].includes("查看有权配置"),
       (r1 || {})["实际能做的"]);
    // ⚠️ **给 viewer 加一条它不能被授权的 → 必须当场被拦。**
    // 这一条是这一组里最值钱的:第一版它**没被拦**(201 + 存下来了),
    // 而 `实际能做的` 里没有 —— 一个存下来却不生效的授权。
    let 没用 = null;
    try { await 动.保存(临时工号, "viewer", ["审批工具动作"]); }
    catch (e) { 没用 = e; }
    const 没用闸 = 没用 && (((没用.体 || {}).field_errors || {})["闸"] || []);
    ck("给 viewer 加一条它**不能被授权**的能力 → **422,不静默收下**"
       + "(收下的话界面上它看着是给了的,而那个人点下去会被拒 ——"
       + "到那时候没人会想到是这一行权限的问题)",
       没用 && 没用.码 === 422
       && 没用闸 && 没用闸.some((x) => x.includes("给了也不生效")),
       没用 && (没用闸 || [])[0] && (没用闸 || [])[0].slice(0, 54));
    ck("而且闸里**列出了这个角色到底能被授权什么**"
       + "(不列的话人只能一个个试)",
       没用闸 && 没用闸.some((x) => x.includes("能被授权的是")),
       没用闸 && (没用闸 || [])[0] && (没用闸 || [])[0].slice(-48));

    // 同一个工号再提交一次 = 改他(用一个**真能生效**的组合)
    // ⚠️ **操作人要换成 U007,不能是 U001。**
    // 第一版用 U001(admin),交集是**空的** —— 那几条 grantable 能力
    // 对 admin 是「可授权」= **默认关**,而 U001 自己没有任何专项授权,
    // 所以他一条都给不出去(「不能通过邀请获得自己没有的权限」)。
    // U007 是 seed 里特意配的:admin + 显式带着 `审批工具动作`。
    // > **「这个角色可以被授权它」和「这个人手上有它」是两件事** ——
    // > 只看前者的话,这一条永远是空跑。
    const 七号 = ((d || {})["成员"] || []).find((m) => m["工号"] === "U007");
    const 能授的 = (可授权表["admin"] || [])
      .filter((x) => ((七号 || {})["实际能做的"] || []).includes(x));
    ck("找得到一条 **U007 手上有、而且 admin 能被授权**的能力"
       + "(找不到的话下面两条是空跑)",
       能授的.length >= 1,
       { 候选: 可授权表["admin"], U007手上的: (七号 || {})["实际能做的"] });
    if (能授的.length) {
      桩.装桩({ hash: "#/members", 我: "U007", 项目 });
      try { 桩.跑页面(src); } catch (e2) { ck("换成 U007 重载 app.js", false, e2.message); }
      const r2 = await globalThis.成员动作.保存(临时工号, "admin", [能授的[0]]);
      ck("同一个工号再提交一次 → **就是改他**(不是报「已存在」)",
         Boolean(r2), JSON.stringify(r2).slice(0, 110));
      ck(`而且那条专项授权**真的生效了**(${能授的[0]})`,
         ((r2 || {})["实际能做的"] || []).includes(能授的[0]),
         (r2 || {})["实际能做的"]);
      桩.装桩({ hash: "#/members", 我: "U001", 项目 });   // 换回来继续
      try { 桩.跑页面(src); } catch (e2) { ck("换回 U001 重载 app.js", false, e2.message); }
    }
    // 认不出的角色 / 不可授权的能力
    let 坏角色 = null;
    try { await 动.保存(临时工号, "随便写的角色", []); } catch (e) { 坏角色 = e; }
    ck("认不出的角色 → 422", 坏角色 && 坏角色.码 === 422,
       坏角色 && { 码: 坏角色.码 });
    let 坏专项 = null;
    try { await 动.保存(临时工号, "viewer", ["根本不存在的能力"]); }
    catch (e) { 坏专项 = e; }
    ck("不在能力表里的专项授权 → 422(**不静默忽略** ——"
       + "忽略的话界面上那一条看着是给了的)",
       坏专项 && 坏专项.码 === 422, 坏专项 && { 码: 坏专项.码 });

    // ── ④ **那道「做完没法回头」的闸** ───────────────────────────────
    组("④ 不许把最后一个能改权限的人去掉");
    // 先把临时工号升成 admin —— 这样「能改权限的」里就有一个**我能降的**。
    await 动.保存(临时工号, "admin", []);
    const [, d2] = await 桩.直打("GET", `${P}/memberships`, null, "U001");
    const 能管的 = (d2 || {})["能改权限的"] || [];
    ck("现在能改权限的不止一个(**只有一个的话这一组测不出来** ——"
       + "那时把谁降下来都会被拦,分不出是因为「最后一个」还是别的)",
       能管的.length >= 2, 能管的);
    // ⚠️ **`try` 里不许调 `结束()`** —— 它里面是 `process.exit()`,
    // 而 `process.exit()` **会跳过 `finally`**:夹具一条都不会清。
    // 这一轮就因为这个在库里留了一个 `Umem…` 成员。
    // > 一个「提前退出」的分支,会把收尾整段跳过去 ——
    // > 而收尾跳过去这件事**在输出上一点迹象都没有**。
    if (能管的.length < 2) { return; }

    // ⚠️ **先把除了我自己之外的都降掉,只留我一个** —— 才能真的试到「最后一个」。
    //
    // ⚠️ 这一步第一版降的是 `U007`(seed 里那个 admin),而**还原不回去**:
    // 他原来带着 `审批工具动作` 这条专项授权,而 U001 自己没有它 ——
    // 「**不能通过邀请获得自己没有的权限**」那道闸正当地拒绝了还原。
    // > 一个**只能单向走**的夹具改动,下一轮会害别人那份测试。
    // 所以现在**不碰 seed 里的成员**:自己先建一个临时 admin,
    // 要降只降临时的那个;而 U007 的权限原样不动。
    // (真要降他也行 —— `finally` 里用 `seed_demo.py` 还原,它是幂等的。)
    // ⚠️ 降 seed 成员(U007)是允许的,但**必须在 finally 里用
    // `seed_demo.py` 还原** —— 接口那条路还不回去:他原来带着
    // `审批工具动作`,而 U001 自己没有它,「不能通过邀请获得自己没有的权限」
    // 那道闸**正当地拒绝**还原。
    // > 一个只能单向走的夹具改动,下一轮会害别人那份测试。
    const 别人 = 能管的.filter((x) => x !== "U001");
    动过seed成员 = 别人.some((u) => !u.startsWith("Umem"));
    for (const u of 别人) await globalThis.成员动作.保存(u, "viewer", []);
    const [, d3] = await 桩.直打("GET", `${P}/memberships`, null, "U001");
    ck("降完之后**只剩我一个**能改权限",
       ((d3 || {})["能改权限的"] || []).length === 1,
       (d3 || {})["能改权限的"]);

    let 最后一个 = null;
    try { await 动.保存("U001", "viewer", []); } catch (e) { 最后一个 = e; }
    ck("**把自己(最后一个能改权限的人)降成 viewer → 被拦**"
       + "(降了之后没有任何人能把权限加回来)",
       最后一个 && 最后一个.码 === 422,
       最后一个 && { 码: 最后一个.码, code: (最后一个.体 || {}).code });
    const 闸 = 最后一个 && (((最后一个.体 || {}).field_errors || {})["闸"] || []);
    ck("而且理由**点名「最后一个」**(只说「改不了」的话,"
       + "人会以为是自己权限不够,然后去找一个更大的号)",
       闸 && 闸.some((x) => x.includes("最后一个")),
       闸 && (闸 || [])[0] && (闸 || [])[0].slice(0, 60));
    // ⚠️ **被拒之后权限不许被改坏** —— 先写后拒等于已经出事了,
    // 而这一处「出事」的后果是**整个项目没人能改权限**。
    const [, d4] = await 桩.直打("GET", `${P}/memberships`, null, "U001");
    ck("被拒之后我**还是能改权限的**(先写后拒等于已经出事了,"
       + "而这一处出事的后果是整个项目没人能改权限)",
       ((d4 || {})["能改权限的"] || []).includes("U001"),
       (d4 || {})["能改权限的"]);
    // 把那个临时 admin 加回来 —— **夹具还原也是一条断言**:
    // 还原不回去说明上面那几步把状态弄坏了。
    await 动.保存(临时工号, "admin", []);
    const [, d5] = await 桩.直打("GET", `${P}/memberships`, null, "U001");
    ck("把临时 admin 加回来之后,能改权限的又不止一个了",
       ((d5 || {})["能改权限的"] || []).length >= 2, (d5 || {})["能改权限的"]);
  } catch (e) {
    ck(`跑到「${状.走过[状.走过.length - 1] || "开头"}」就抛了:${e.message}`,
       false, (e.体 && JSON.stringify(e.体).slice(0, 160))
       || String(e.stack || "").slice(0, 180));
  } finally {
    // 收尾:把临时工号那条成员删掉。
    // ⚠️ 不删的话成员列表会越跑越长,而「能改权限的几个人」是这一页的主角数。
    const { execSync } = require("child_process");
    try {
      // ⚠️ **动过 seed 成员就必须用 `seed_demo.py` 还原。**
      // 接口那条路还不回去(见上面那段),而 seed 是幂等的
      // (`seed_rerun_check` 的「铺 → 跑测试 → 再铺」盯着它)——
      // 所以它是这里**唯一正当的还原器**。
      if (动过seed成员) {
        execSync("./.venv/bin/python services/api/app/seed_demo.py",
                 { cwd: 根, stdio: "pipe" });
        console.log("\n▸ 收尾:动过 seed 成员,已用 `seed_demo.py` 还原");
      }
      execSync(`./.venv/bin/python -c "
import os,sys
sys.path.insert(0, os.path.join('services','api','app'))
from sqlalchemy import text
from db import 事务
with 事务() as c:
    n = c.execute(text(\\"\\"\\"delete from memberships where project_id=:p
        and user_id like 'Umem%'\\"\\"\\"), {'p': '${项目}'}).rowcount
print('清掉', n)
"`, { cwd: 根, stdio: "pipe" });
      console.log("\n▸ 收尾:临时工号清了"
        + "(不清的话成员列表越跑越长,而「几个人能改权限」是这一页的主角数)");
    } catch (e) {
      console.log("\n  ⚠️ 收尾没清干净:" + String(e.message).slice(0, 120));
      状.挂.push("收尾没清干净");
    }
    结束(弹过);
  }
})();
