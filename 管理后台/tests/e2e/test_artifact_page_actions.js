/* 模型产物那一页的部署动作**在页面代码里真走一遍**。
 *
 * ## 这一页考的是**三道闸长得几乎一样,下一步完全不同**
 *
 * | 闸 | 下一步 |
 * |---|---|
 * | 没标可用 | 去校验 |
 * | mock 训练出来的 | 换真训练 |
 * | **说不清是不是 mock** | **先把来路查清** |
 *
 * 第三种是「**未知不是「不是」**」这条规矩唯一的落点。
 * 把三种合成一句「不能部署」,这条规矩就没了 ——
 * 而界面上那一句话读起来完全合理。
 *
 * ## ⚠️ 一个比表单大的缺口(2026-10-01 查出来的)
 *
 * **四状态链的第三步没有门。** `verified_at` 整个仓库里
 * 只有 `tools/seed_training.py` 写过 —— 也就是只有夹具。
 * 真实路径上登记完产物之后,**没有任何接口能把它标成校验过**,
 * 于是 `POST /deployments` 永远被「还没校验过」拦住。
 *
 * 所以这一份能验的是:**夹具里那个「唯一能部署的」真能部署**,
 * 以及另外三个**各被哪一道闸拦住**。
 * 「标可用」那一步要什么证据,是个业务决定 —— 接口上明说了这件事,
 * 这一份也断了那句话在不在(**不说的话,人会对着一个永远「还差」的列表猜**)。
 */
"use strict";
const fs = require("fs"), path = require("path");
const 桩 = require("./_页面桩.js");

const 项目 = 桩.默认项目;
const P = 桩.P(项目);
const src = fs.readFileSync(
  path.join(__dirname, "..", "..", "apps", "web", "app.js"), "utf8");

const 该跑几组 = 3;
const { ck, 组, 结束, 状 } = 桩.计分(该跑几组);

(async () => {
  console.log("\n\x1b[1m▸ 模型产物:部署(三道闸各一条)\x1b[0m");
  console.log("  ⚠️ 三道闸在列表上长得几乎一样,**下一步却完全不同**");

  // U001(admin)有「生产审核/发布/回滚」
  const { 请求们, 弹过 } = 桩.装桩({ hash: "#/artifacts", 我: "U001", 项目 });
  try { 桩.跑页面(src); } catch (e) {
    ck("app.js 同步执行不挂", false, e.message); 结束(弹过); return;
  }
  const 动 = globalThis.产物动作;
  ck("app.js 把 `产物动作` 导出来了", 动 && typeof 动.部署 === "function",
     动 ? Object.keys(动) : null);
  if (!动) { 结束(弹过); return; }

  try {
    // ── ① 接口把该给的都给了 ─────────────────────────────────────
    组("① 接口给了环境白名单,也明说了那个缺口");
    const [码, d] = await 桩.直打("GET", `${P}/model-artifacts`, null, "U001");
    ck("产物列表拿得到", 码 === 200 && Array.isArray((d || {})["产物"]),
       (d || {})["条数"]);
    ck("给了 `可选部署环境`(前端硬编会和 `training.部署环境` 漂)",
       Array.isArray((d || {})["可选部署环境"])
       && (d || {})["可选部署环境"].length >= 2,
       (d || {})["可选部署环境"]);
    // ⚠️ 这一条盯的是「接口有没有把那个缺口说出来」。
    // 不说的话,人会对着一个永远「还差:还没校验过」的列表猜是自己操作错了。
    ck("**明说「标可用这一步还没有接口」**"
       + "(不说的话,人会对着一个永远「还差」的列表猜)",
       Boolean((d || {})["⚠️标可用这一步还没有接口"]),
       String((d || {})["⚠️标可用这一步还没有接口"] || "").slice(0, 44));
    // 源码级:页面不许硬编环境
    const 页段 = src.slice(src.indexOf("const 产物动作 = {"),
                         src.indexOf("function 挂产物事件("));
    const 硬编 = ["production", "staging"].filter((e) => 页段.includes(`"${e}"`));
    ck("页面**没有硬编**部署环境", 硬编.length === 0, 硬编);

    // ── ② 三道闸各自认得出来 ────────────────────────────────────
    组("② 三道闸:**各是各的,不合成一句**");
    const 产物们 = (d || {})["产物"] || [];
    // ⚠️ **要看 `部署还差什么`,不是 `还差什么`。**
    // 后者回答的是「能不能**标可用**」—— 我第一版拿它当部署闸,
    // 于是 `ma_seed_mock` 和 `ma_seed_说不清` 在列表上「什么都不差」,
    // 点部署才被拦。**界面上说能、点了不能**,而那个名字正好让人以为是同一件事。
    // (接口现在两栏分开给,并且 `⚠️两栏别混` 明说了这件事。)
    const 按差 = (关键词) => 产物们.filter(
      (a) => (a["部署还差什么"] || []).some((x) => x.includes(关键词)));
    ck("接口把**两个问题分开给**了(`标可用还差什么` / `部署还差什么`)",
       产物们.every((a) => "部署还差什么" in a && "标可用还差什么" in a),
       Boolean((d || {})["⚠️两栏别混"]));
    const 没校验 = 按差("校验");
    const mock的 = 按差("mock 训练适配器");
    const 说不清 = 产物们.filter((a) => a["是mock训练的"] === null);
    ck("认得出「还没校验过」那一类", 没校验.length >= 1,
       没校验.map((a) => a.id.slice(-8)));
    ck("认得出「mock 训练的」那一类", mock的.length >= 1,
       mock的.map((a) => a.id.slice(-8)));
    // ⚠️ **这一条是「未知不是『不是』」唯一的落点。**
    ck("认得出「**说不清**是不是 mock」那一类"
       + "(`是mock训练的` 为 null —— 把它当成「不是」就等于放行一个来路不明的产物)",
       说不清.length >= 1, 说不清.map((a) => a.id.slice(-8)));
    const 能部署的 = 产物们.filter((a) => a["能部署吗"]);
    ck("而且**只有一个三道闸全过的**(四种里只有一种能部署 ——"
       + "另外三种各被一道不同的闸拦住,而它们在界面上长得几乎一样)",
       能部署的.length === 1, 能部署的.map((a) => a.id));
    if (!能部署的.length) { 结束(弹过); return; }

    // ── ③ 部署:能的那个真能,不能的各自被对的理由拦 ──────────────────
    组("③ 部署");
    const 环境 = ((d || {})["可选部署环境"] || [])[0];
    const r = await 动.部署(能部署的[0].id, 环境);
    ck(`把那个能部署的发到 ${环境} → 有结果`, Boolean(r),
       JSON.stringify(r).slice(0, 110));
    const 请 = 桩.头里(请求们, "/deployments");
    ck("**带了幂等键**(部署是异步 + 对外的动作,超时重发是常态)",
       请 && typeof 请.头["Idempotency-Key"] === "string",
       请 && 请.头["Idempotency-Key"]);

    // 三道闸各打一次,**断的是「被哪一条拦的」而不是「被拦了」**
    for (const [名, 组子, 关键词] of [
      ["没标可用", 没校验, "校验"],
      ["mock 训练的", mock的, "mock"],
    ]) {
      if (!组子.length) {
        ck(`⚠️ 没有「${名}」的样例 —— **这一条没验到**(不是通过)`, false, 0);
        continue;
      }
      let 拦 = null;
      try { await 动.部署(组子[0].id, 环境); } catch (e) { 拦 = e; }
      const 闸 = 拦 && (((拦.体 || {}).field_errors || {})["闸"] || []);
      ck(`部署「${名}」的 → 被拦,**而且理由点名那一条**`
         + "(只说「不能部署」的话,三种下一步完全不同的情况长得一样)",
         拦 && 拦.码 === 422 && 闸
         && 闸.some((x) => x.includes(关键词)),
         拦 && { 码: 拦.码, 闸: (闸 || [])[0] && (闸 || [])[0].slice(0, 46) });
    }
    // ⚠️ 「说不清」单独打一次 —— 它的理由必须和 mock 那条**分得开**。
    let 说不清拦 = null;
    try { await 动.部署(说不清[0].id, 环境); } catch (e) { 说不清拦 = e; }
    const 说不清闸 = 说不清拦
      && (((说不清拦.体 || {}).field_errors || {})["闸"] || []);
    ck("部署「说不清」的 → 被拦,理由是**说不清**而不是「是 mock」"
       + "(两者混起来,「未知不是『不是』」这条就没了)",
       说不清拦 && 说不清拦.码 === 422 && 说不清闸
       && 说不清闸.some((x) => x.includes("说不清")),
       说不清拦 && (说不清闸 || [])[0] && (说不清闸 || [])[0].slice(0, 50));

    let 坏环境 = null;
    try { await 动.部署(能部署的[0].id, "随便写的环境"); } catch (e) { 坏环境 = e; }
    ck("认不出的环境 → 422(**不给默认值** —— 猜一个默认环境"
       + "等于把东西发到一个没人要求的地方)",
       坏环境 && 坏环境.码 === 422, 坏环境 && { 码: 坏环境.码 });
  } catch (e) {
    ck(`跑到「${状.走过[状.走过.length - 1] || "开头"}」就抛了:${e.message}`,
       false, (e.体 && JSON.stringify(e.体).slice(0, 160))
       || String(e.stack || "").slice(0, 180));
  } finally {
    // ⚠️ **不还原部署记录。** 部署是真实动作,留一行记录是对的 ——
    // 而 `seed_training.py` 每次重铺会把它连带清掉
    // (那件事有 `seed_rerun_check` 的「铺 → 跑测试 → 再铺」盯着)。
    console.log("\n▸ 收尾:**不还原部署记录** —— 部署是真实动作,留一行是对的;"
      + "seed_training.py 重铺时会连带清掉(按引用链)");
    结束(弹过);
  }
})();
