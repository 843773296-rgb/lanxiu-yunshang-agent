def 拼正文(*, 订单号, 门店, 顾客, 下单日, 明细, 合计, 已付, 交付日=None, 着装人=None):
    """→ Markdown 正文。明细:[{名称, 规格, 数量, 金额}]。交付日没有就照实写「排产后书面告知」—— 不编一个日子。"""
    行 = [f"# 定制订单确认书",
          "",
          f"**订单号** {订单号} · **门店** {门店} · **顾客** {顾客}" + (f" · **着装人** {着装人}" if 着装人 else ""),
          f"**确认日期** {下单日} · **条款版本** {版本}",
          "",
          "## 一、商品与价款",
          "",
          "| 商品 | 规格 | 数量 | 金额(元) |",
          "|---|---|---|---|"]
    for x in 明细:
        行.append(f"| {x['名称']} | {x.get('规格') or '—'} | {x.get('数量') or 1} | {x['金额']:,.2f} |")
    行 += ["",
           f"**合计 {合计:,.2f} 元 · 已付 {已付:,.2f} 元**(确认下单时付清)",
           "",
           "## 二、交付",
           "",
           (f"约定交付日:**{交付日}**" if 交付日 else
            "约定交付日:**排产后由门店书面告知**(这张单确认时系统里还没有排定的交付日,不先口头给日子)"),
           ""]
    for i, (题, 文) in enumerate(条款, 3):
        行 += [f"## {'三四五六七八九十'[i - 3]}、{题}", "", 文, ""]
    行 += ["---", "顾客确认下单即表示已阅读并同意以上条款。本确认书由系统在确认下单时生成并留档,可随时查看、下载。"]
    return "\n".join(行)


