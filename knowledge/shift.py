#!/usr/bin/env python3
"""排班判定的口径 —— **唯一源头**,不碰库、不取今天。

业务 2026-09-20:「排班就按业内最佳实践来做」。
⚠️ **没有汉服门店的排班数据**,这里是零售/服务业通行的机制。

## 🔑 「查不到记录」只能表示一件事:**还没排**

    未排        这一周店长还没排到 —— **要说「排班还没出来」,不能当他没空**
    已发布休息  明确不上班 —— 可以当没空

**休息必须是显式记录**,不能靠「没有记录」表示。
否则店长还没排下周的班,agent 照样给出推荐,依据是「所有人下周都有空」——
**而这个结论看起来完全正常**。

## 🔑 「草稿」和「已发布」在排班表里长得一模一样

都是有记录。而两者对派单的含义完全相反:

    草稿     店长还在调,**随时会变** —— 不该拿它派单
    已发布   定了,员工看到了,客户也能按它约 —— 可以派

不分开的后果很具体:店长周三排了个草稿准备周五发,而 agent 周四就按草稿派了单 ——
**等店长改完发布,那些单全挂在错的人身上。**

## 五态,不是两态

    未排 / 草稿 / 已发布-上班 / 已发布-休息 / 请假

按「只有下一步动作不同才分开」逐个验过,而且**这件事下面的自测会机械核对**:
五个码的下一步两两不同,有两个一样就报错 —— 那它们本来就不该分成两个。

## 「在班」不等于「那个点有空」

他是早班(10:00–16:00),而预约在 17:00 —— 他今天上班,但那个点不在。
这两件事混起来,排班表上「他今天上班」就会变成「什么时候都能约」。
"""
import datetime

# 按天排不按小时:按小时店长不会填,而预约本来就是按时段来的。
班次 = [
    ("S1", "早班", "10:00", "16:00"),
    ("S2", "晚班", "16:00", "22:00"),
    ("S3", "全天", "10:00", "22:00"),
    ("S0", "休息", None, None),
]
班次表 = {c: (n, a, b) for c, n, a, b in 班次}

草稿, 已发布 = "草稿", "已发布"

# 业务 2026-09-20:**排班权给店长,值班经理本期不做。**
# 设计稿里「值班经理」看着像有排班职责 —— 但那是设计稿,以讨论为准。
排班角色 = ("店长",)

下一步 = {
    "ON":           "可以派单给他",
    "UNSCHEDULED":  "催店长把这一天的班排出来 —— **这不是他没空**",
    "DRAFT":        "等店长发布 —— 草稿随时会改,按它派的单会挂在错的人身上",
    "OFF":          "他这天休息,换个人或换一天",
    "LEAVE":        "他请假了 —— **而且已经派给他的单要重新分配**",
    "OUT_OF_SHIFT": "他这天上班,但不在这个时段 —— 换个时段或换个人",
}


def 判在班(事实):
    """某人某天能不能派。返回 (能不能, 码, 人话)。

    `事实` 要的键:
        日期        'YYYY-MM-DD'
        请假种类    有已批准的请假就给种类(事假/年假…),没有就 None
        排班        没有这一行就 None;有就 {"status": 草稿/已发布, "shift": "S1"}

    ⚠️ **请假压过一切** —— 包括「已发布为上班」。
    请假是**盖掉**排班,不是改排班:排班表上他那天仍然是上班,
    **而他人不在**。两份记录并存是有意的,改掉排班会把「本来该他上」这件事抹掉。
    """
    日期 = 事实.get("日期") or "那天"
    请 = 事实.get("请假种类")
    if 请:
        return False, "LEAVE", f"{日期} 请假中({请})—— **已经派给他的单要重新分配**"
    r = 事实.get("排班")
    if not r:
        # **这一条是整套机制的命根子**:没有记录 = 还没排,不等于没空
        return False, "UNSCHEDULED", (
            f"{日期} 还没排班 —— **这不是「他没空」,是「排班还没出来」**;"
            f"拿它当没空,会在店长还没排的时候给出一份看起来正常的推荐")
    if r.get("status") != 已发布:
        return False, "DRAFT", f"{日期} 的排班还是草稿,**店长随时会改** —— 等发布"
    if r.get("shift") == "S0":
        return False, "OFF", f"{日期} 已发布为休息"
    名, a, b = 班次表.get(r.get("shift"), ("?", None, None))
    if not a:
        return False, "OFF", f"{日期} 没有班次时间,当休息处理"
    return True, "ON", f"{日期} {名}({a}–{b})"


# ── 合规(写排班时拦)────────────────────────────────────────────────
# 业务 2026-09-22:每人每周(自然周,周一到周日)至少休一天。
# 用户 2026-11-11 夜(一张卡,选推荐项):**最多连上 6 天** —— 按滚动 7 天算,跨周也算。
#   「每周休一天」按自然周算的话,上周一休、这周日休,中间能连上 12 天 —— 所以要单独一条。
# 两条都是**发布时拦**(超了不许发布),草稿里随便排。
每周至少休几天 = 1
最多连上几天 = 6


def 连上超限(日到班):
    """{日期: 班次码} → [(起, 止, 连上几天)]:连续上班超过「最多连上几天」的那几段。

    ⚠️ **没排的日子打断连续** —— 不知道他那天上不上,不能替他算成「上了」;
    休息(S0)当然也打断。所以这条只认**排了而且是上班**的连续日期。
    (反过来,「每周休一天」那条里没排的日子**不算休息** —— 两条对「没排」的处理相反,
    都是同一个原则:**没排 = 不知道**,不能拿来证明合规,也不能拿来证明违规。)
    """
    日们 = sorted(d for d, s in 日到班.items() if s and s != "S0")
    段, 出 = [], []
    for d in 日们:
        if 段 and datetime.date.fromisoformat(d) - datetime.date.fromisoformat(段[-1]) == datetime.timedelta(days=1):
            段.append(d)
        else:
            if len(段) > 最多连上几天:
                出.append((段[0], 段[-1], len(段)))
            段 = [d]
    if len(段) > 最多连上几天:
        出.append((段[0], 段[-1], len(段)))
    return 出


def 一周休够吗(一周的班次):
    """一个人一个自然周的班次码列表 → (够吗, 一句话)。**没排的日子不算休息。**"""
    休 = sum(1 for x in 一周的班次 if x == "S0")
    if 休 >= 每周至少休几天:
        return True, f"这一周休了 {休} 天"
    return False, f"这一周只休了 {休} 天,规定每周至少休 {每周至少休几天} 天"


# ── 改班撞单(用户 2026-11-11 夜:照发,自动建改派任务)──────────────────
# **哪些任务算「被撞到」**:
#   · 那天改成休息 → 当天所有没做完的任务都算(人不在,谁来做)
#   · 那天上班     → 只有**要人在场**的任务落在班次外才算;回电、商机提醒、订单跟踪这类
#                    是「当天的待办」,早班的人下午三点前做完就行,不按时段卡
# 不分的话:系统给每条知会任务写的 09:00–18:00 永远「落在早班外」,每次改班冒一堆假的改派任务 ——
# 假警报多了,店长会学会全部点掉,真撞上的那条也一起点掉。
# 名字要和 backend/tasktypes.py 的 TYPES 对得上 —— roster_write_check 逐个核。
要人在场的类型 = ("预约到店", "上门沟通", "接待任务", "团建培训")


def 撞了吗(新班次, 任务类型, 起hhmm, 止hhmm):
    """(撞了吗, 人话)。新班次是发布后那天的班次码。"""
    if 新班次 == "S0":
        return True, "那天改成了休息"
    名, a, b = 班次表.get(新班次, ("?", None, None))
    if not a:
        return True, "那天没有班次时间"
    if 任务类型 not in 要人在场的类型:
        return False, f"{任务类型}是当天待办,不按时段卡"
    # 写法故意和 判时段 不同(a <= 起):那一句是一条老咬合规格的改坏锚点,原文出现两次只会换第一处
    if a <= 起hhmm and 止hhmm <= b:
        return False, f"落在{名}({a}–{b})内"
    return True, f"{任务类型} {起hhmm}–{止hhmm} 落在{名}({a}–{b})外"


def 判时段(事实, 起hhmm, 止hhmm):
    """预约时段落不落在他的班次里。

    ⚠️ **含端**:预约正好从班次开始、正好到班次结束,都算在班内。
    这类边界写错了不会报错,只会让整点的预约莫名其妙派不出去。
    """
    ok, 码, why = 判在班(事实)
    if not ok:
        return False, 码, why
    名, a, b = 班次表.get((事实.get("排班") or {}).get("shift"), ("?", None, None))
    if 起hhmm >= a and 止hhmm <= b:
        return True, "ON", f"{事实.get('日期','那天')} {名}({a}–{b}),预约 {起hhmm}–{止hhmm} 落在班内"
    return False, "OUT_OF_SHIFT", (
        f"{事实.get('日期','那天')} 他是{名}({a}–{b}),而预约是 {起hhmm}–{止hhmm} —— "
        f"**在班 ≠ 那个点有空**")


def 判排班权(员工):
    """谁能排班。返回 (能不能, 人话)。

    `员工` 是 None 表示员工表里查无此人。
    **「查不到这个人」和「这个人没权限」要分开** ——
    前者是数据问题(去修档案),后者是权限问题(去找店长),下一步不同。
    """
    if not 员工:
        return False, "这个工号员工表里没有 —— **这是数据问题,不是权限问题**"
    if 员工.get("status") != "启用":
        return False, f"{员工.get('name')} 已{员工.get('status')},不能排班"
    if 员工.get("role") not in 排班角色:
        return False, (f"{员工.get('name')} 是{员工.get('role')},排班权在{排班角色[0]}"
                       f"(业务 2026-09-20:值班经理本期不做)")
    return True, f"{员工.get('name')}({员工.get('role')})可以排班"


# ── 咬合记录 ────────────────────────────────────────────────────────
咬合 = [
    ("把「没有排班记录」当成休息(还没排就说人家没空)", "没排班 ≠ 休息"),
    ("让草稿也能派单(店长还在调的班被拿去派单)", "草稿不能派"),
    ("让请假不再压过已发布的上班(人不在却显示可派)", "请假压过已发布上班"),
    ("把时段判成「只要那天上班就行」(早班的人被派了晚上的预约)", "在班≠那个点有空"),
    ("把「查无此人」当成「没权限」(数据问题被说成权限问题)", "查无此人不是没权限"),
    ("连上上限从「超过 6 天」改成「达到 6 天」就算超(差一错位)", "连上 6 天不超(边界含端)"),
    ("没排的日子不打断连续(把不知道当成上了班)", "没排的日子也断开(不知道 ≠ 上了)"),
    ("撞单不分类型,一律按时段卡(知会类待办冒假改派)", "早班 + 知会类待办 09–18 → 不撞(不按时段卡)"),
]


def _自测():
    G, R, D = "\033[32m", "\033[31m", "\033[0m"
    坏, 验了 = [], [0]

    def ck(说, 得, want):
        验了[0] += 1
        if 得 != want:
            坏.append(f"{说}:要 {want!r},得 {得!r}")

    def 事实(**kw):
        d = dict(日期="2026-09-23", 请假种类=None, 排班=None)
        d.update(kw); return d
    码 = lambda **kw: 判在班(事实(**kw))[1]

    # ── 🔑 未排 / 休息 / 草稿,三种「不能派」不能合成一个 ──────────
    ck("没排班 ≠ 休息", 码(), "UNSCHEDULED")
    ck("已发布休息才是休息", 码(排班={"status": 已发布, "shift": "S0"}), "OFF")
    ck("草稿不能派", 码(排班={"status": 草稿, "shift": "S1"}), "DRAFT")
    ck("已发布上班可以派", 码(排班={"status": 已发布, "shift": "S1"}), "ON")
    ck("草稿排的休息也是草稿(还会变)", 码(排班={"status": 草稿, "shift": "S0"}), "DRAFT")

    # ── 请假盖掉排班,不是改排班 ──────────────────────────────
    ck("请假压过已发布上班",
       码(请假种类="年假", 排班={"status": 已发布, "shift": "S3"}), "LEAVE")
    ck("请假压过未排", 码(请假种类="事假"), "LEAVE")

    # ── 在班 ≠ 那个点有空(含端) ──────────────────────────────
    早 = 事实(排班={"status": 已发布, "shift": "S1"})       # 10:00–16:00
    ck("在班≠那个点有空", 判时段(早, "17:00", "18:00")[1], "OUT_OF_SHIFT")
    ck("落在班内", 判时段(早, "11:00", "12:00")[1], "ON")
    ck("正好从班次开始(含端)", 判时段(早, "10:00", "11:00")[1], "ON")
    ck("正好到班次结束(含端)", 判时段(早, "15:00", "16:00")[1], "ON")
    ck("跨出一分钟就不行", 判时段(早, "15:00", "16:01")[1], "OUT_OF_SHIFT")
    # 不能派的时候,时段判定要把原因原样传出来 —— 别变成 OUT_OF_SHIFT
    ck("没排班时问时段,给的还是「没排班」",
       判时段(事实(), "11:00", "12:00")[1], "UNSCHEDULED")

    # ── 排班权 ───────────────────────────────────────────────
    ck("店长能排", 判排班权({"name": "张静静", "role": "店长", "status": "启用"})[0], True)
    ck("顾问不能排", 判排班权({"name": "沈砚", "role": "顾问", "status": "启用"})[0], False)
    ck("停用的店长不能排", 判排班权({"name": "甲", "role": "店长", "status": "停用"})[0], False)
    ck("查无此人不是没权限", "数据问题" in 判排班权(None)[1], True)

    # ── 合规:最多连上 6 天(用户 11-11 夜)/ 每周至少休一天 ─────────────
    def 连(n, 起="2026-11-02", 班="S1"):
        d0 = datetime.date.fromisoformat(起)
        return {(d0 + datetime.timedelta(days=i)).isoformat(): 班 for i in range(n)}
    ck("连上 6 天不超(边界含端)", 连上超限(连(6)), [])
    ck("连上 7 天超", 连上超限(连(7)), [("2026-11-02", "2026-11-08", 7)])
    ck("跨周也算(上周四到这周三连上 7 天)", len(连上超限(连(7, "2026-10-29"))), 1)
    中间休 = 连(10); 中间休["2026-11-05"] = "S0"
    ck("中间休一天就断开(4 + 5)", 连上超限(中间休), [])
    中间没排 = 连(10); del 中间没排["2026-11-05"]
    ck("没排的日子也断开(不知道 ≠ 上了)", 连上超限(中间没排), [])
    ck("全天班也算上班", 连上超限(连(7, 班="S3")), [("2026-11-02", "2026-11-08", 7)])
    ck("一周排了一天休 → 够", 一周休够吗(["S1"] * 6 + ["S0"])[0], True)
    ck("一周没排休 → 不够", 一周休够吗(["S1"] * 7)[0], False)
    ck("没排的日子不算休息", 一周休够吗(["S1"] * 5)[0], False)

    # ── 改班撞单:改成休息全撞;上班只卡要人在场的 ─────────────────────
    ck("改成休息 → 回电也撞", 撞了吗("S0", "电话回电", "09:00", "18:00")[0], True)
    ck("早班 + 知会类待办 09–18 → 不撞(不按时段卡)", 撞了吗("S1", "归属转移", "09:00", "18:00")[0], False)
    ck("早班 + 预约到店 17:00 → 撞", 撞了吗("S1", "预约到店", "17:00", "18:00")[0], True)
    ck("早班 + 预约到店 15–16 → 不撞(含端)", 撞了吗("S1", "预约到店", "15:00", "16:00")[0], False)
    ck("晚班 + 上门沟通 10:00 → 撞", 撞了吗("S2", "上门沟通", "10:00", "11:00")[0], True)

    # ── 五个码的下一步必须两两不同 ───────────────────────────
    # **分成五个码的全部理由就是动作不同** —— 有两个一样,它们就不该分成两个。
    动作 = list(下一步.values())
    if len(set(动作)) != len(动作):
        坏.append("有两个码的下一步一模一样 —— **那它们就不该是两个码**")
    for c in ("ON", "UNSCHEDULED", "DRAFT", "OFF", "LEAVE", "OUT_OF_SHIFT"):
        if not 下一步.get(c):
            坏.append(f"{c} 说不出下一步")

    if 坏:
        print(f"{R}❌ 排班口径自测 {len(坏)} 条不过{D}")
        for b in 坏:
            print(f"    ❌ {b}")
        return 1
    # 条数现印,不写死(原来写死「18 条」—— 加了用例它照样印 18)
    print(f"{G}✅ 排班口径自测 {验了[0]} 条全过{D}")
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(_自测())
