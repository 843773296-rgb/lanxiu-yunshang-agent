def 判完了没有(记录):
    """店长判完了没有、能不能进「待入库」(开始收衣服准备返修)。返回 (能不能, 一句人话)。

    记录  {责任方, 处理, 预估费用, 顾客同意于, 判责人}
    """
    r = 记录 or {}
    if not r.get("判责人"):
        return False, "店长还没判责 —— 谁承担、返修还是重做,都要店长定"
    if r.get("责任方") not in 责任方:
        return False, f"责任方只能是 {' / '.join(责任方)}"
    if r.get("处理") not in 处理方式:
        return False, f"处理方式只能是 {' / '.join(处理方式)}"
    if r["责任方"] == "顾客":
        try:
            费 = float(r.get("预估费用") or 0)
        except (TypeError, ValueError):
            费 = 0
        if 费 <= 0:
            return False, "判给顾客承担的,先录预估费用 —— 顾客要知道多少钱才谈得上同意"
        if not r.get("顾客同意于"):
            return False, (f"判给顾客承担({r['处理']},预估 ¥{费:g}),**顾客还没同意付费** —— "
                           "先跟顾客确认,记下同意再开工:改下去的衣服没有回头路")
    return True, f"店长已判:{r['责任方']}承担,{r['处理']}" + (
        f",预估 ¥{float(r.get('预估费用')):g},顾客已同意" if r["责任方"] == "顾客" else ",免费")


def 下一档(当前):
    """维保状态链上的下一档;到头或不认识返回 None。"""
    return 链[链.index(当前) + 1] if 当前 in 链[:-1] else None


