"""订单交付风险分档 · 逐例真值(用户 2026-10-25 拍「全用规则分档,模型只写建议」)。

绝对判定 → **逐例手标边界真值**(CLAUDE.md §9 ③),期望值是这里手写的,不从被测模块现算。
最要紧的两条:**缺承诺完工日不许落进低风险**(方案「无法判断不可被压成低风险」)、临近线上下各差一天。
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import datetime as _d
import delivery_risk as DR

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "backend"))
import worldclock as _wc

G, R, D = "\033[32m", "\033[31m", "\033[0m"
# 今天取演示世界的今天(世界每天平移,写死某一天会和数据越错越远);承诺完工日一律写成「今天加减几天」
今 = str(_wc.今天())[:10]
def 日(差, 时分=""):
    return (_d.date.fromisoformat(今) + _d.timedelta(days=差)).isoformat() + 时分
定 = "定制品订单"

咬合 = [
    ("临近线从「≤ 3 天」改成「< 3 天」", "**还有 3 天(正好在临近线上)→ 需关注**"),
    ("在产但缺承诺完工日时判成暂无已识别风险", "**在产但没有承诺完工日 → 无法判断,不压成低风险**"),
]

# (说明, 类型, 状态, 承诺完工日, 该催, 临近天数, 期望档)
例 = [
    ("标品单 → 不适用", "标品订单", "待发货", None, False, 3, "不适用"),
    ("已完成 → 已结束", 定, "已完成", 日(-23), False, 3, "已结束"),
    ("已关闭 → 已结束", 定, "已关闭", None, False, 3, "已结束"),
    ("待收货(工厂已发出)即使过了承诺日 → 已结束,不算延期", 定, "待收货", 日(-14), False, 3, "已结束"),
    ("待付款 → 无法判断(还没进生产)", 定, "待付款", None, False, 3, "无法判断"),
    ("方案确认中 → 无法判断", 定, "方案确认中", None, False, 3, "无法判断"),
    ("**在产但没有承诺完工日 → 无法判断,不压成低风险**", 定, "待发货", None, False, 3, "无法判断"),
    ("**在产、没承诺日、而且在该催里 → 照样无法判断**(缺的是日期,不靠猜)", 定, "待发货", None, True, 3, "无法判断"),
    ("过了 1 天 → 已延期", 定, "待发货", 日(-1), False, 3, "已延期"),
    ("就是今天 → 需关注(没过)", 定, "待发货", 日(0), False, 3, "需关注"),
    ("**还有 3 天(正好在临近线上)→ 需关注**", 定, "待发货", 日(3), False, 3, "需关注"),
    ("**还有 4 天(过了临近线一天)→ 暂无已识别风险**", 定, "待发货", 日(4), False, 3, "暂无已识别风险"),
    ("还有 10 天、但在该催里 → 需关注", 定, "待发货", 日(10), True, 3, "需关注"),
    ("临近线改成 5:还有 4 天 → 需关注(阈值由调用方传,不写死)", 定, "待发货", 日(4), False, 5, "需关注"),
    ("承诺日带时分(还有 3 天、18:00)按日算", 定, "待发货", 日(3, " 18:00"), False, 3, "需关注"),
]


def main():
    print("订单交付风险分档 · 逐例真值")
    坏 = 0
    for 说, 类, 状, 承, 催, 临, 期 in 例:
        r = DR.分档(类, 状, 承, 催, 今, 临, "开工 30 天了工厂还没回接单" if 催 else None)
        ok = r["档"] == 期
        坏 += not ok
        print(f"  {G + '✅' + D if ok else R + '❌' + D} {说}" + ("" if ok else f"  得到「{r['档']}」"))
    r = DR.分档(定, "待发货", None, False, 今)
    ok = bool(r["缺"]) and "承诺完工日" in r["缺"][0]
    坏 += not ok
    print(f"  {G + '✅' + D if ok else R + '❌' + D} 无法判断时**说清缺什么**(缺「承诺完工日」)" + ("" if ok else f"  {r}"))
    r = DR.分档(定, "待发货", 日(37), False, 今)
    ok = r["档"] == "暂无已识别风险" and any("不等于保证准时" in x for x in r["依据"])
    坏 += not ok
    print(f"  {G + '✅' + D if ok else R + '❌' + D} 暂无已识别风险时写明「不等于保证准时」" + ("" if ok else f"  {r}"))
    ok = set(DR.要跟踪的档) == {"已延期", "需关注"} and set(DR.要跟踪的档) <= set(DR.档们)
    坏 += not ok
    print(f"  {G + '✅' + D if ok else R + '❌' + D} 只有「已延期 / 需关注」才可能派跟踪任务")
    n = len(例) + 3
    print()
    if 坏:
        print(f"{R}❌ 交付风险分档 {坏} 条不对(验了 {n} 条){D}")
        return 1
    print(f"{G}✅ 交付风险分档逐例都对(验了 {n} 条){D}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
