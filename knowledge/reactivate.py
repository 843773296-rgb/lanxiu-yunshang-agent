#!/usr/bin/env python3
"""促活判断的口径 —— **唯一源头**,不碰库、不取今天。

业务定的边界(2026-09-20):**agent 只面对顾问,只给参谋。**
产出是**一个判断加一句人话**,不是一个动作,也不是一个分数 ——
顾问要照着它打电话,「87 分」没法照着说,理由可以。

## 核心判据:「很久没买」不是理由,是筛子

促活要同时回答两件事:**为什么是他,为什么是现在。**
只按闲置天数筛,顾问拿到名单也不知道说什么,打过去就是尬聊,而且会骚扰。

**所以:没有由头的,不进名单 —— 哪怕他闲置 300 天。**

## ⚠️ 时间要「相对他自己」,不是一个全局阈值

一个每季度买一次的人(节奏 91 天),闲置 200 天是**异常**;
一个一年买一次的人(节奏 365 天),闲置 200 天还在他自己的节奏里,**正常**。
同样是 200 天,一个该促一个不该 —— **差别只在他自己**。

全局阈值会把「这个人本来就买得少」和「这个人变了」混成同一件事 ——
**而后者才是该管的那个。**

所以 `RHYTHM_BREAK` 比的是他自己的节奏:`365 / 他过去 12 个月的单数`。

⚠️ **这一条是整个模块最容易在重构里走样的地方。** 写成一个固定天数,
它照样跑得出名单、照样不报错 —— **一份按全局阈值筛出来的名单,
和一份按各人节奏筛出来的名单,长得一模一样**,直到顾问打过去发现
「这人本来就一年买一次」。下面的自测里有两条专门钉它。

## ⚠️ 三个参数是**拍的**,不是算出来的

`断节奏倍数` / `刚联系过` / `刚下过单` 现在的取值没有依据。
**它们看起来和有出处的数一模一样**,所以每次出现在理由里都要标出来,
不让下游把它当成结论。
"""
import datetime

# ── 参数 ────────────────────────────────────────────────────────────
断节奏倍数 = 2.0      # 闲置超过「他自己节奏」的几倍算断了
刚联系过 = 14         # 几天内联系过就不再打扰
刚下过单 = 14         # 几天内下过单就不再推新
回访窗口 = (7, 45)    # 上一单完成后第几天到第几天适合回访
生日提前 = 30         # 生日前几天算「临近」

# **哪几个是拍的** —— 这份名单本身要能被检查看见,
# 不能只写在注释里(注释不会出现在输出里,而输出才是顾问看到的东西)。
待校准 = ("断节奏倍数", "刚联系过", "刚下过单")

下一步 = {
    "JUST_BOUGHT":    "先别打 —— 人家刚买完,让他消停会儿",
    "AFTERSALE":      "先把售后办完再谈别的(这时候推销是火上浇油)",
    "RECENT_CONTACT": "先别打 —— 最近刚联系过,防骚扰也防两个顾问撞车",
    "NO_REASON":      "不进名单 —— **闲置久本身不是理由**,打过去不知道说什么",
    "NOT_YET":        "不归促活管 —— 他还没下过单,是还没热过,不是冷了",
    "ANNIVERSARY":    "按他往年同期那次的由头联系",
    "BIRTHDAY":       "生日临近,按生日的由头联系",
    "POST_ORDER":     "上一单做完到回访窗口了,先问穿着感受",
    "MAINTAIN":       "有维保没办完,先把维保推进",
    "RHYTHM_BREAK":   "他断了自己的节奏,问问是不是有什么变化",
}


def 他自己的节奏(orders_12m):
    """他平均多少天来一次。

    **算不出来返回 None —— 「算不出」和「节奏很慢」是两回事。**
    前者是没有依据可用(12 个月 0 单),后者是有依据、只是数字大。
    混成一个的话,一个从没买过的人会被算成「节奏 365 天」,
    然后在第 731 天被判成「断了节奏」—— 而他压根没有节奏。
    """
    n = orders_12m or 0
    if n <= 0:
        return None
    return 365.0 / n


def 判(事实, today):
    """这个客户现在需不需要促活。返回 (需不需要, 码, 人话理由)。

    **False 不是「这人没价值」** —— 多数 False 是「现在不是时候」,
    所以每个码都配一条下一步(见 `下一步`)。

    `事实` 要的键(都由调用方查好):
        name                 姓名
        刚买过天数           最近一张未终态订单距今几天;没有就 None
        有未结售后           True/False
        最近跟进天数         最近一次跟进距今几天;没有就 None
        往年同期年份         往年这个月下过单的年份列表(**不含今年**)
        生日                 datetime.date 或 None
        上一单完成天数       最近一张完成单距今几天;没有就 None
        维保件               还没办完的维保件名;没有就 None
        orders_12m           过去 12 个月单数
        idle_days            闲置天数
        有过首单             True/False
    """
    name = 事实.get("name") or 事实.get("id") or "这位客户"

    # ── 第一层:硬门槛 ────────────────────────────────────────
    # ⚠️ **「手上有单在做」不是门槛。** 定制周期长,常年有单在做是常态
    # (这批数据里 89% 的客户都有),拿它当门槛等于把绝大多数人永久挡在外面。
    # 真正不该促的是**刚下过单**。在做的单是**聊进度的由头**,那属于服务不属于促活。
    d = 事实.get("刚买过天数")
    if d is not None and d < 刚下过单:
        return False, "JUST_BOUGHT", (
            f"{name}刚下过单 —— **刚买完就推新会掉价**"
            f"(门槛 {刚下过单} 天是**待校准的默认值**)")

    if 事实.get("有未结售后"):
        return False, "AFTERSALE", f"{name}有未结的售后 —— **这时候推销是火上浇油**,先把售后办完"

    d = 事实.get("最近跟进天数")
    if d is not None and d < 刚联系过:
        return False, "RECENT_CONTACT", (
            f"{d} 天前刚联系过{name} —— 防骚扰,也防两个顾问撞车"
            f"(门槛 {刚联系过} 天是**待校准的默认值**)")

    # ── 第二层:由头(有一个就够,按强弱排) ──────────────────────
    理由 = []

    # ① 历史同期 —— 汉服的节庆性很强,而「他自己的历史同期」比一张节庆表更准,
    #    也不用维护农历。
    # ⚠️ **年份里必须不含今年。** 第一版把「今年这个月刚买过」也算成往年同期,
    #    理由那句话自相矛盾:「他在 2026 年的这个月都下过单 —— 今年还没动静」。
    #    **是那句人话把错误暴露出来的** —— 只看数量或布尔值,这个 bug 藏得住。
    年份 = sorted({int(y) for y in (事实.get("往年同期年份") or []) if int(y) < today.year})
    if 年份:
        理由.append(("ANNIVERSARY",
                     f"他在 {'、'.join(str(y) for y in 年份)} 年的这个月都下过单 —— 今年到现在还没动静"))

    bd = 事实.get("生日")
    if bd:
        try:
            今年生日 = bd.replace(year=today.year)
        except ValueError:            # 2 月 29 日
            今年生日 = bd.replace(year=today.year, day=28)
        差 = (今年生日 - today).days
        if 0 <= 差 <= 生日提前:
            理由.append(("BIRTHDAY", f"{差} 天后是{name}的生日"))

    d = 事实.get("上一单完成天数")
    if d is not None and 回访窗口[0] <= d <= 回访窗口[1]:
        理由.append(("POST_ORDER", f"上一单 {d} 天前做完,到回访的时候了"))

    if 事实.get("维保件"):
        理由.append(("MAINTAIN", f"有一件「{事实['维保件']}」的维保还没办完"))

    # ⑤ 断了自己的节奏 —— **不是「超过 N 天」,是「超过他自己的 N 倍」**
    节奏 = 他自己的节奏(事实.get("orders_12m"))
    闲置 = 事实.get("idle_days")
    if 节奏 is not None and 闲置 is not None and 闲置 > 节奏 * 断节奏倍数:
        理由.append(("RHYTHM_BREAK",
                     f"他平均 {节奏:.0f} 天来一次,这次已经 {闲置} 天了"
                     f"(**{断节奏倍数} 倍这个门槛是待校准的默认值**)"))

    if not 理由:
        # **从没下过单的,单独一个码。** 他不是「冷了」,是还没热过 ——
        # 和「买过但现在没由头」该做的事完全不同(前者归拉新,后者等由头)。
        if not 事实.get("有过首单"):
            return False, "NOT_YET", (
                f"{name}从来没下过单 —— **他不是冷了,是还没热过**,这不归促活管")
        return False, "NO_REASON", (
            f"{name}没有可说的由头 —— **闲置久本身不是理由**,"
            f"打过去不知道说什么,只会消耗关系")

    码, 话 = 理由[0]
    其余 = f";另外{'、'.join(t for _, t in 理由[1:])}" if len(理由) > 1 else ""
    return True, 码, 话 + 其余


# ── 咬合记录 ────────────────────────────────────────────────────────
咬合 = [
    ("把「相对他自己的节奏」换成一个全局天数阈值", "一年买一次的人闲置 200 天不算断"),
    ("让「算不出节奏」也当成节奏很慢(从没买过的被判成断了节奏)", "12 个月 0 单算不出节奏"),
    ("把「往年同期」的今年也算进去(理由会自相矛盾)", "往年同期不含今年"),
    ("没有由头也让他进名单(闲置久本身当理由)", "闲置 300 天但没由头,不进名单"),
]


def _自测():
    G, R, D = "\033[32m", "\033[31m", "\033[0m"
    today = datetime.date(2026, 9, 21)
    坏 = []

    def ck(说, 得, want):
        if 得 != want:
            坏.append(f"{说}:要 {want!r},得 {得!r}")

    def 事实(**kw):
        d = dict(name="张三", 刚买过天数=None, 有未结售后=False, 最近跟进天数=None,
                 往年同期年份=[], 生日=None, 上一单完成天数=None, 维保件=None,
                 orders_12m=0, idle_days=None, 有过首单=True)
        d.update(kw); return d
    码 = lambda **kw: 判(事实(**kw), today)[1]

    # ── 第一层:硬门槛,而且优先级不能乱 ──────────────────────
    ck("刚下过单不促", 码(刚买过天数=3), "JUST_BOUGHT")
    ck("刚好到门槛就可以促了", 码(刚买过天数=14, orders_12m=4, idle_days=300), "RHYTHM_BREAK")
    ck("未结售后压过由头", 码(有未结售后=True, 维保件="马面裙"), "AFTERSALE")
    ck("刚联系过压过由头", 码(最近跟进天数=3, 维保件="马面裙"), "RECENT_CONTACT")
    ck("刚买过压过未结售后", 码(刚买过天数=1, 有未结售后=True), "JUST_BOUGHT")

    # ── 🔑 时间相对他自己 ────────────────────────────────────
    # 这两条是整个模块的判据本身。**它们必须一起看** ——
    # 同样是闲置 90 天,一个该促一个不该,差别只在他自己的节奏。
    # **同样的闲置天数,一个该促一个不该** —— 这两条必须一起看。
    ck("每季度买一次的人闲置 200 天算断", 码(orders_12m=4, idle_days=200), "RHYTHM_BREAK")
    ck("一年买一次的人闲置 200 天不算断", 码(orders_12m=1, idle_days=200), "NO_REASON")
    ck("一年买一次的人 800 天才算断", 码(orders_12m=1, idle_days=800), "RHYTHM_BREAK")
    ck("12 个月 0 单算不出节奏(不许当成节奏很慢)",
       码(orders_12m=0, idle_days=3000), "NO_REASON")
    ck("他自己的节奏算得对", round(他自己的节奏(4)), 91)
    ck("算不出就是 None", 他自己的节奏(0), None)

    # ── 由头 ─────────────────────────────────────────────────
    ck("往年同期", 码(往年同期年份=[2024, 2025]), "ANNIVERSARY")
    ck("往年同期不含今年(今年的要被滤掉)", 码(往年同期年份=[2026]), "NO_REASON")
    ck("生日临近", 码(生日=datetime.date(1990, 10, 10)), "BIRTHDAY")
    ck("生日过完了不算", 码(生日=datetime.date(1990, 9, 1)), "NO_REASON")
    ck("回访窗口内", 码(上一单完成天数=20), "POST_ORDER")
    ck("回访窗口外", 码(上一单完成天数=100), "NO_REASON")
    ck("维保没办完", 码(维保件="马面裙"), "MAINTAIN")

    # ── 没有由头就是没有由头 ─────────────────────────────────
    ck("闲置 300 天但没由头,不进名单",
       判(事实(orders_12m=0, idle_days=300), today)[:2], (False, "NO_REASON"))
    ck("从没下过单的单独一个码", 码(有过首单=False), "NOT_YET")

    # 多个由头时,理由里要带上其余那些
    ok, c, why = 判(事实(维保件="马面裙", 生日=datetime.date(1990, 10, 10)), today)
    if not (ok and "另外" in why):
        坏.append("有多个由头时,没有把其余的一起说出来")

    # ── 待校准的参数必须在输出里标出来 ───────────────────────
    # **一个拍脑袋的门槛和一个有出处的门槛,在数字上长得一模一样。**
    if "待校准" not in 判(事实(刚买过天数=3), today)[2]:
        坏.append("刚下过单的理由里没标「待校准」")
    if "待校准" not in 判(事实(orders_12m=4, idle_days=300), today)[2]:
        坏.append("断节奏的理由里没标「待校准」")
    for c in 下一步:
        if not 下一步[c]:
            坏.append(f"{c} 说不出下一步")
    if len(set(下一步.values())) != len(下一步):
        坏.append("有两个码的下一步一模一样 —— **那它们就不该是两个码**")

    if 坏:
        print(f"{R}❌ 促活口径自测 {len(坏)} 条不过{D}")
        for b in 坏:
            print(f"    ❌ {b}")
        return 1
    print(f"{G}✅ 促活口径自测 25 条全过{D}")
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(_自测())
