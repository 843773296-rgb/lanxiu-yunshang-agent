# -*- coding: utf-8 -*-
"""能力管理的口径 —— **一件事该做成 MCP 工具 / Skill / Hook / CLI 中的哪一类。**

判定写在这里,`agentsite/capman.py` 只负责扫描和生成。

## 为什么需要这份口径

这个项目已经有 48 个 MCP 工具、239 个 Skill、3 个 Hook。
**东西越多,「再加一个」的默认答案就越应该是「不加」** ——
每加一个技能,所有技能的描述都在互相竞争;每加一个工具,提示词就长一分。

实测过一次:同一条用例,场上 3 个技能时 3/3 触发,场上 239 个时 **0/3**。
**装了 ≠ 每次都上场。**

所以这份口径的主要作用不是「教你怎么加」,是**让「该加哪一类」有个判据,
以及让「其实不该加」说得出口**。

## 四类,各自的判据

### MCP 工具 —— 它需要知道一个只有库里才有的事实,或要改一个业务对象

    该用    「这个客户是什么等级」「把这条任务派给谁」
    不该用   「帮我把这段话改得客气一点」(不需要查任何东西)

**判据是「信息在哪」**:答案在库里 → 工具;答案在模型脑子里 → 不需要工具。

### Skill —— 必须整体看才有意义,或产出物有固定格式

    该用    月度复盘(单看一条改派说明不了什么,看一个月才看得出是排班问题)
            报价单(产出物有格式要求)
    不该用   「查一下这个订单」(单条就够,那是工具)

**判据是「一条够不够」**:一条就能回答 → 工具;必须看一批 → 技能。

### Hook —— 这条规矩漏一次就出事

    该用    写工具的权限校验、交付前体检、预算闸门
    不该用   「回答要简洁」(漏一次没关系)

**判据是「漏一次的代价」**。提示词里的「必须」「不许」只是**祈使句**,
模型可以不听;**hook 才是强制**。
这个项目栽过:`allowed_tools` 以为是白名单,其实只是「不弹确认」,
内置的 Bash / Write 一直在场 —— **「模型没用」和「模型不能用」是两回事。**

### CLI —— 步骤能提前枚举,而且不需要理解自然语言

**这一条就是这个项目 V2 vs V3 的那条判断标准**:
「任务步骤能不能提前枚举 —— 能就停在 V2(更可控更便宜更好调试),不能才上 V3。」

    该用    造数据、迁移、对账、生成报表文件
    不该用   「客户说这句话是什么意思」

CLI 相比让模型做,有四个硬优势:
  · **确定性** —— 同样的输入永远同样的输出,可以进 check.sh 当门禁
  · **不花钱** —— 跑一万次和跑一次一样
  · **可组合** —— 别的脚本能调它,模型也能调它
  · **好调试** —— 出错有栈,不是「它这次没照做」

**默认答案是 CLI。** 只有当「这一步需要判断,而判断的依据没法提前写全」时,
才轮到模型。
"""

类别 = {
    "mcp": ("MCP 工具", "它需要知道一个只有库里才有的事实,或要改一个业务对象",
            "判据是「信息在哪」:答案在库里 → 工具;在模型脑子里 → 不需要"),
    "skill": ("Skill", "必须整体看才有意义,或产出物有固定格式",
              "判据是「一条够不够」:一条就能回答 → 工具;必须看一批 → 技能"),
    "hook": ("Hook", "这条规矩漏一次就出事",
             "判据是「漏一次的代价」。提示词里的「必须」只是祈使句,hook 才是强制"),
    "cli": ("CLI 脚本", "步骤能提前枚举,而且不需要理解自然语言",
            "**默认答案就是这个**。确定性 / 不花钱 / 可组合 / 好调试"),
}

# 「这一步需要判断吗」—— 出现这些词,说明步骤里有分支,**可能**不适合纯 CLI。
# 注意是「可能」:分支本身可以写成 if,真正不适合 CLI 的是
# **分支的依据没法提前写全**(比如「客户这句话是什么语气」)。
#
# ⚠️ **中英文都要有。** 第一版只写了中文,而这个项目装着 236 个英文技能 ——
# 英文技能一个都命中不了,于是全被判成「不需要判断」,
# **140/239 被标成「该改成 CLI」**。两个 bug 方向一致,所以结果看起来很确信。
# 这是「枚举必输」那个家族的新变种:**词表只覆盖中文,而语料是英文的。**
要判断的信号 = ("如果", "若", "视情况", "取决于", "判断", "酌情", "看情况",
              "根据上下文", "理解", "语气", "意图", "猜", "推测", "权衡", "评估",
              "if ", "when ", "depends", "depending", "judge", "decide", "assess",
              "evaluate", "interpret", "context", "tone", "intent", "appropriate",
              "consider", "determine", "based on", "tailor", "adapt", "nuance")

# 反过来:出现这些,说明步骤是死的,**该考虑 CLI**。
#
# ⚠️ **不许把「1. 2. 3.」当证据。** 第一版用了,而任何 markdown 都有编号列表 ——
# 那不是「死步骤」的证据,只是「这是一份文档」的证据。
# 真正的证据是**可执行的动作**:跑一个命令、读一个文件、调一个接口。
可枚举的信号 = ("第一步", "第二步", "依次", "逐条", "遍历", "对每一",
              "运行", "执行脚本", "命令行", "调用接口",
              "run ", "execute", "script", "command", "cli ", "bash",
              "for each", "iterate", "loop over")

# 这份正文是中文还是英文 —— **判不出语言就不下结论**。
def _像英文(t):
    if not t: return False
    中 = sum(1 for ch in t if "\u4e00" <= ch <= "\u9fff")
    return 中 * 20 < len(t)


def 该做成哪类(要知道库里的事, 要改业务对象, 要整体看, 漏一次就出事, 步骤能枚举):
    """按判据给出类别和理由。**返回一串,因为一件事可能同时需要两类**
    (比如一个写工具,既要 MCP 工具本身,也要 Hook 兜住它的权限)。
    """
    out = []
    if 漏一次就出事:
        out.append(("hook", "漏一次就出事 —— 提示词里的「必须」是祈使句,hook 才是强制"))
    if 要改业务对象:
        out.append(("mcp", "要改业务对象 —— 必须走工具层,而且得配 hook 兜权限"))
    elif 要知道库里的事:
        out.append(("mcp", "答案只有库里有 —— 模型猜不出来"))
    if 要整体看:
        out.append(("skill", "必须看一批才有意义 —— 单条说明不了什么"))
    if 步骤能枚举 and not (要整体看 or 漏一次就出事):
        out.append(("cli", "步骤能提前枚举 —— 确定性、不花钱、可组合、好调试"))
    if not out:
        out.append(("cli", "**默认答案是 CLI** —— 没有哪一条判据指向模型"))
    return out


def 该不该改成CLI(正文):
    """一个已有的 Skill,该不该改成 CLI。返回 (该不该, 理由, 证据)。

    **这条判得保守**:说「该改」要拿得出证据,说「不该改」只要一条反例。
    理由是改错的代价不对称 —— 把一个真需要判断的技能改成 CLI,
    它会在边界情况上默默给出错答案;而把一个死步骤留成技能,
    只是慢一点、贵一点。
    """
    t = (正文 or "")
    低 = t.lower()
    判断 = [w for w in 要判断的信号 if (w if w.strip().isascii() else w) in
            (低 if w.strip().isascii() else t)]
    枚举 = [w for w in 可枚举的信号 if (低 if w.strip().isascii() else t).find(w) >= 0]
    if 判断:
        return (False, f"正文里有需要判断的地方({判断[:3]})—— "
                       f"**把真需要判断的改成 CLI,它会在边界情况上默默给错答案**",
                判断[:5])
    # **证据门槛调高到 3 条「可执行动作」,而且要求正文不算太短。**
    # 一份两百字的说明文里凑出三个词,说明不了它是死步骤。
    if len(枚举) >= 3 and len(t) > 400:
        return (True, f"正文全是可执行动作({枚举[:4]}),没有一处要判断 —— "
                      f"**这种东西交给模型是浪费**:每次跑都要钱,"
                      f"而且不保证两次一样", 枚举[:6])
    return (False, "证据不够 —— 既看不出要判断,也看不出是死步骤。"
                   "**不确定就不动**", 枚举[:3])
