#!/usr/bin/env python3
"""谁能看到哪些订单 —— **口径的唯一源头**,纯判定、不取数、不取今天。

业务 2026-10-06 拍的三档:

    总部运营   全部门店
    店长       本店
    顾问       **他名下客户的单 ∪ 他经手下的单**(并集)

## 为什么单独一个模块

这套范围**有两个落点**:聊天里列卡片那头(`backend/api.py` 的 `orders_by_date`)
和点开弹窗那头(`backend/server.py` 的 `chat_order_detail`)。
第一版我在两处各写了一遍 —— 而 CLAUDE.md 第 9 节第 ① 条点名了这件事:

> 「判定逻辑写在工具里,迟早变成第二份手抄件。」

两处各自看起来都对,**而它们迟早漂**。漂的那天表现是:
卡片上列着一张单、点开却说「看不到」(前松后紧,顾问以为系统坏了),
或者更糟 —— **卡片没列而弹窗给得出来**(前紧后松,那是一个可以直接拿 URL 捞数据的洞)。

> 一份写在工具里的范围口径,和一份写在接口里的,
> **在各自的测试里都绿** —— 而它们可以给出不同的名单。

所以这里出**纯判定**,两处都调它。
取数那一头仍然要写 SQL(不可能把 31660 单全捞出来逐条判),
而 `backend/chat_order_check.py` 有一条**拿真数据对账**:
SQL 选出来的那批,必须和纯判定说能看的那批**一模一样**。

## ⚠️ 为什么顾问那一档是并集

两种读法在 **39% 的订单上给出不同名单**
(2026-10-06 实测:31660 单里 12393 单的「订单上的顾问」和「客户归属顾问」不是同一个人):

    只算「名下客户」   他帮同事客户下的单,他自己看不到
    只算「经手的单」   他休假时同事帮他客户下的单,他看不到

**而并集之后每一行必须标清是哪一种**,两个数也要分开报:
> 一份「我的客户的单」和一份「我做的单」混成一个数,**业绩就说不清了** ——
> 而混之前和混之后,那个总数长得一模一样。

## ⚠️ 看不到的理由分开写,但对外同形

一个「订单不存在」回 404、「存在但你看不到」回 403 的接口,
**本身就是一个「这单存不存在」的探测器**。
所以这里只回「能不能 + 为什么」,**而调用方要把两种都包成同一个形状**
(和 `backend/auth.py` 那条「不区分查无此人和密码错」同一个道理)。
"""

# 角色字面量。**和库里 staff.role 的取值一字不差** ——
# 两套枚举迟早分叉,而分叉时两边各自都是绿的。
# (库里现有:工匠 / 店长 / 总部运营 / 版师 / 财务 / 顾问)
总部运营 = "总部运营"
店长 = "店长"
顾问 = "顾问"

# ⚠️ **「导购」是业务的说法,系统里的角色名是「顾问」。**
# 库里没有「导购」这个角色(2026-10-06 查过),只在设计稿和产品文档里出现。
# 这一行写在这儿,是为了下一个按「导购」去 grep 的人能找到落点。
导购就是顾问 = 顾问

我的客户 = "我的客户"
我下的单 = "我下的单"
标们 = (我的客户, 我下的单)


def 范围话(*, 角色, 门店=None):
    """这个人看到的是哪一段 —— **要显示给他看**,不是内部变量。

    > 一份「只看到自己那些」的清单,和一份「全店的」,
    > **在那串订单上长得一模一样** —— 除非把范围写在上面。
    """
    if 角色 == 总部运营:
        return "全部门店"
    if 角色 == 店长:
        return f"{门店}(你的门店)" if 门店 else "你的门店(档案里没填门店,**判不了**)"
    if 角色 == 顾问:
        return "你名下的客户 ∪ 你经手下的单"
    # ⚠️ 其余角色(工匠/版师/财务)**不给兜底** —— 他们本来就不该看订单清单。
    # 兜一个「本店」出来的话,一个财务就能看到全店订单,而界面上看不出异常。
    return f"「{角色}」这个角色不在订单范围的三档里"


def 看得到吗(*, 角色, 工号=None, 门店=None,
          单的门店=None, 单的顾问=None, 客户归属顾问=None):
    """这个人能不能看这一单。返回 `(能不能, 为什么)`。

    **五个事实都要给。** 缺一个不猜 —— 猜出来的那次,
    放行和拦住都看起来完全合理。
    """
    if not 角色:
        return False, "不知道你是谁 —— 没有身份就不知道该给你看什么"

    if 角色 == 总部运营:
        return True, "总部运营看全部门店"

    if 角色 == 店长:
        if not 门店:
            # ⚠️ **判不了不等于可以看。** 档案里没填门店时,
            # 「本店」这个范围算不出来 —— 而算不出来时放行等于给了全部。
            return False, "你的档案里没填门店,**算不出「本店」是哪一段** —— 判不了,不放行"
        if 单的门店 != 门店:
            return False, "这单不在你的门店"
        return True, f"本店的单({门店})"

    if 角色 == 顾问:
        if not 工号:
            return False, "你的档案里没有工号,**算不出哪些是你的** —— 判不了,不放行"
        if 单的顾问 == 工号:
            return True, "这单是你经手的"
        if 客户归属顾问 == 工号:
            return True, "这单的客户在你名下(单是别人经手的)"
        return False, "这单既不是你经手的,客户也不在你名下"

    return False, f"「{角色}」这个角色不在订单范围的三档里 —— **不兜底成「本店」**"


def 标(*, 角色, 工号=None, 单的顾问=None, 客户归属顾问=None):
    """这一单对这个人是哪一种。**顾问之外返回空** —— 不编一个标出来。

    ⚠️ 顺序固定(先「我的客户」后「我下的单」)—— 一份今天这个顺序、
    明天那个顺序的标签,会让人以为数据变了。
    """
    if 角色 != 顾问 or not 工号:
        return []
    出 = []
    if 客户归属顾问 == 工号:
        出.append(我的客户)
    if 单的顾问 == 工号:
        出.append(我下的单)
    return 出


# ── 咬合记录 ──────────────────────────────────────────────────────────
# 左边「改坏了什么」,右边「预期红的那一条」。三关缺一关这条记录就不算数:
# 对照先绿 / 改坏要红 / **红的必须是点名那一条**。
咬合 = [
    ("顾问那一档只认「订单上的顾问」(丢掉「名下客户」那一半)",
     "名下客户、别人经手 → 看得到"),
    ("店长档案里没门店时放行(算不出本店却给了全部)",
     "店长没填门店 → 判不了,不放行"),
    ("给工匠/版师/财务兜一个「本店」出来",
     "三档之外的范围话不说成「本店」"),
    ("把标签顺序改成跟着命中次序走",
     "标签顺序固定"),
]


def _自测():
    G, R, D = "\033[32m", "\033[31m", "\033[0m"
    坏, n = [], [0]

    def ck(说, 得, want):
        n[0] += 1
        if 得 != want:
            坏.append(f"{说}:要 {want!r},得 {得!r}")

    看 = lambda **kw: 看得到吗(**kw)[0]

    # ── 🔑 顾问那一档是并集 —— 两个方向都要验 ────────────────
    # **这两条必须一起看。** 只验第一条的话:
    # > 一个「只认订单上的顾问」的实现,和一个真做了并集的,
    # > **在「他经手的单他看得到」这条上长得一模一样。**
    ck("经手的单 → 看得到",
       看(角色=顾问, 工号="A", 单的顾问="A", 客户归属顾问="B"), True)
    ck("名下客户、别人经手 → 看得到",
       看(角色=顾问, 工号="A", 单的顾问="B", 客户归属顾问="A"), True)
    ck("两者都不是 → 看不到",
       看(角色=顾问, 工号="A", 单的顾问="B", 客户归属顾问="C"), False)
    ck("两者都是 → 看得到",
       看(角色=顾问, 工号="A", 单的顾问="A", 客户归属顾问="A"), True)
    ck("客户没归属顾问(NULL)而单是他经手的 → 看得到",
       看(角色=顾问, 工号="A", 单的顾问="A", 客户归属顾问=None), True)
    # ⚠️ **NULL 不是「等于谁」。** 工号为空的顾问不能因为客户也没归属就看到它
    ck("客户没归属、单也不是他经手的 → 看不到",
       看(角色=顾问, 工号="A", 单的顾问="B", 客户归属顾问=None), False)
    ck("顾问没有工号 → 判不了,不放行",
       看(角色=顾问, 工号=None, 单的顾问=None, 客户归属顾问=None), False)
    ck("而理由说的是「判不了」", "判不了" in 看得到吗(
        角色=顾问, 工号=None)[1], True)

    # ── 店长 ────────────────────────────────────────────────
    ck("店长看本店 → 看得到", 看(角色=店长, 门店="S1", 单的门店="S1"), True)
    ck("店长看别店 → 看不到", 看(角色=店长, 门店="S1", 单的门店="S2"), False)
    ck("🔑 店长没填门店 → 判不了,不放行",
       看(角色=店长, 门店=None, 单的门店="S1"), False)
    ck("而理由说的是「算不出」", "算不出" in 看得到吗(
        角色=店长, 门店=None, 单的门店="S1")[1], True)

    # ── 总部运营 / 其余角色 ─────────────────────────────────
    ck("总部运营看任意一单 → 看得到",
       看(角色=总部运营, 单的门店="S9", 单的顾问="Z"), True)
    for 其余 in ("工匠", "版师", "财务", "", None, "导购"):
        ck(f"三档之外的角色「{其余}」→ 不放行",
           看(角色=其余, 门店="S1", 单的门店="S1"), False)
    ck("⚠️ 连「导购」这个字面量也不放行 —— 库里的角色名是「顾问」",
       看(角色="导购", 工号="A", 单的顾问="A"), False)
    ck("而 `导购就是顾问` 这一行指得对", 导购就是顾问, 顾问)

    # ── 标签 ────────────────────────────────────────────────
    ck("标签顺序固定",
       标(角色=顾问, 工号="A", 单的顾问="A", 客户归属顾问="A"), [我的客户, 我下的单])
    ck("只是名下客户", 标(角色=顾问, 工号="A", 单的顾问="B", 客户归属顾问="A"), [我的客户])
    ck("只是经手的", 标(角色=顾问, 工号="A", 单的顾问="A", 客户归属顾问="B"), [我下的单])
    ck("店长不带标", 标(角色=店长, 工号="A", 单的顾问="A", 客户归属顾问="A"), [])
    ck("运营不带标", 标(角色=总部运营, 工号="A", 单的顾问="A"), [])

    # ── 范围话 ──────────────────────────────────────────────
    ck("运营的范围话", 范围话(角色=总部运营), "全部门店")
    ck("店长的范围话带门店名", "S1" in 范围话(角色=店长, 门店="S1"), True)
    ck("店长没门店时范围话也说「判不了」",
       "判不了" in 范围话(角色=店长, 门店=None), True)
    ck("顾问的范围话说清是并集", "∪" in 范围话(角色=顾问), True)
    ck("三档之外的范围话不说成「本店」",
       "门店" in 范围话(角色="财务"), False)

    # ── 每一条「看不到」都要说得出为什么 ───────────────────
    for kw in (dict(角色=顾问, 工号="A", 单的顾问="B", 客户归属顾问="C"),
               dict(角色=店长, 门店="S1", 单的门店="S2"),
               dict(角色=店长, 门店=None, 单的门店="S1"),
               dict(角色="财务", 门店="S1", 单的门店="S1"),
               dict(角色=None)):
        能, 为 = 看得到吗(**kw)
        if 能 or not (为 or "").strip():
            坏.append(f"{kw} 的「看不到」没说出理由")
        n[0] += 1

    if 坏:
        print(f"{R}❌ 订单范围口径自测 {len(坏)}/{n[0]} 条不过{D}")
        for b in 坏:
            print(f"    ❌ {b}")
        return 1
    print(f"{G}✅ 订单范围口径自测 {n[0]} 条全过{D}")
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(_自测())
