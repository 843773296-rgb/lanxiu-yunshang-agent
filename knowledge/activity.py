"""活动投入产出的口径 —— **钱怎么算、成交怎么算、什么时候不许给 ROI**。

判定写在这里,`backend/api.py` 只取数。口径模块不碰数据库,也不取当前日期。

## 一、表上的「报名 209 / 成交 42」是随机数,不是快照

`activity.signup` 和 `activity.orders` 两列由 `random.randint` 生成,
**从来没有和订单表发生过任何关系**。所以「表上 42 / 现算 12」不是漂移 ——
那两列从一开始就不是真的。

**这里一律不读那两列**,并且在输出里明说它们不可用。
悄悄不用比用了更糟:下次有人看见这两列还会去用它。

## 二、归因期外的订单不静默计入

实测:AC2602「春季新品预售」活动期 2026-03-01~04-15,
而挂在它名下的 12 单**全部创建于 8 月** —— 期外率 100%。

一个 4 月就结束的活动收到 8 月的订单,只有两种可能:
归因错了,或者活动日期错了。**两种都得有人看一眼。**

所以期内期外**分开报**,不合并成一个「成交 12 单」。
合并的话会算出一个看起来很正常的 ROI,而它建立在一批不该算的订单上。

## 三、成交有三个数,不是一个

    应收   payable 之和         客户答应给的钱
    实收   received 之和        **真正到账的钱**
    完成   status='完成' 的     真正走完的单

实测归因到活动的 45 单里,只有 2 单是「完成」,6 单「待付款」实收为 0。
**只报「成交 12 单」会把 6 单还没付钱的算成战果。**

默认用**实收**算 ROI —— 投入产出比要用真到账的钱,
应收里有一部分永远收不回来(那 2 单取消的就是)。

**取消的单一律排除**:它既不是收入,也不该占分母。

## 四、成本也有三个数

    预算   activity.budget          计划花多少
    已发生 activity_cost 全部        实际记了账的(含待开票)
    已开票 activity_cost 里已开票的   已经走完票据流程的

实测 16 笔成本里 11 笔是「待开票」,占 66%。
**默认用「已发生」** —— 钱已经花出去了,票据流程没走完不改变这个事实。
但三个数都要报出来,因为它们回答的是不同的问题
(预算管控看预算、现金流看已开票、算 ROI 看已发生)。

## 五、没开始的活动不给 ROI

「未开始」的活动已经有成本(场地定金之类),但不可能有成交。
给它算 ROI 会得到 0,而 **0 会被读成「这活动效果很差」** ——
实际是「它还没开始」。这和复盘里那条「分母为零不给数」是同一条。

已取消的活动也一样:成本是**沉没的**,要单独报,不参与 ROI 排名。
"""

# **不许读这两列。** 写在这儿是为了让这个决定有个落点 ——
# 散在工具里的话,下一个人写新报表时会很自然地去 SELECT signup, orders。
不可用的列 = {
    "signup": "报名数 —— random.randint 生成的,库里也没有报名表可对账",
    "orders": "成交数 —— random.randint 生成的,和订单表毫无关系",
}

不算成交的状态 = ("取消",)
不给ROI的活动状态 = {"未开始": "还没开始,不可能有成交 —— 算出来的 0 会被读成「效果差」",
                    "已取消": "成本是沉没的,单独报,不参与排名"}

成本口径 = {"预算": "计划花多少", "已发生": "实际记了账的(含待开票)",
           "已开票": "已经走完票据流程的"}
默认成本口径 = "已发生"
默认成交口径 = "实收"


def 在活动期内(订单创建日, 开始日, 结束日):
    """订单算不算这个活动期内的。**日期都从外面传,这里不取当天。**"""
    if not (订单创建日 and 开始日 and 结束日):
        return None          # 判不了 —— **不许猜成「在期内」**
    return 开始日 <= str(订单创建日)[:10] <= 结束日


def roi(实收, 成本):
    """投入产出比。**成本为零时不给数** —— 除以零不是无穷大,是「没花钱」。

    返回 (可读文本, 数值或 None)。
    """
    if not 成本:
        return ("没有记过成本(0 元),投入产出比无从谈起", None)
    return (f"{实收:.0f}/{成本:.0f} = {实收 / 成本:.2f}", round(实收 / 成本, 4))


def 单均(总额, 单数, 名=""):
    """单均成本 / 单均成交。分母为零时不给数。"""
    if not 单数:
        return (f"没有成交(0 单),{名 or '单均'}无从谈起", None)
    return (f"{总额 / 单数:,.0f} 元", round(总额 / 单数, 2))


def 该不该给ROI(活动状态):
    """返回 (给不给, 为什么不给)。"""
    why = 不给ROI的活动状态.get(活动状态)
    return (why is None, why or "")


def 一句话(名, 状态, 实收, 成本, 期外单数, 总单数):
    """**先说该管的,再说效果好不好。**

    顺序是有意的:一个 ROI 2.48 会把「一半订单归因存疑」盖住。
    """
    急 = []
    if 期外单数 and 总单数 and 期外单数 == 总单数:
        急.append(f"**归因全部存疑**({期外单数}/{总单数} 单在活动期外)")
    elif 期外单数:
        急.append(f"{期外单数}/{总单数} 单在活动期外,归因存疑")
    给, why = 该不该给ROI(状态)
    if not 给:
        急.append(f"「{状态}」—— {why}")
    if 给 and 成本 and 实收 < 成本:
        急.append(f"**花的比收的多**(花 {成本:,.0f},收 {实收:,.0f})")
    return ("；".join(急) if 急 else "没有归因存疑,投入产出为正")
