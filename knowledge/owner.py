#!/usr/bin/env python3
"""「这个客户实际上有没有人管」的判定口径 —— **唯一源头**。

## 为什么要单独一个模块

`customer.advisor_no` 非空,只说明**字段里有个工号**,不说明有人在管。
2026-09-20 查库查出来的:一个停用的顾问名下还挂着 3 个客户,
他接待的预约是 0,那 3 个客户的预约全由别人接待 ——
**他们实际无人管理,而任何按「有没有顾问」筛的逻辑都查不出他们**,因为字段非空。

## 🔑 分成几种,只因为**下一步动作不同**

    NONE        归属为空            → 等分配(本来就无主)
    NO_SUCH     工号员工表里查无此人  → **数据要修**,不是业务问题
    LEFT        顾问已停用/离职      → 进重分配队列,店长指人
    NO_SHOP     顾问档案没填门店      → **数据要修** —— 判不了是不是跨店
    CROSS_SHOP  顾问不在客户所在门店  → 业务动作:要么转店要么转人

前四种在「有没有顾问」这个筛子下长得一模一样(三种非空、一种空),
而它们要做的事完全不同 —— 这就是分开的全部理由。
**不是为了分类好看,是为了下一步动作不混。**

### NO_SHOP 是 2026-09-21 补的,补的是一个**静默**

原来的写法是「客户门店和顾问门店都非空**且**不同,才算跨店」。
于是顾问档案没填门店时,它**什么都不报** —— 和「确认过是同一家店」
长得一模一样。库里现在有 5 个员工门店是空的(总部运营 / 财务 / 版师),
他们名下暂时没有客户,所以这个分支一次都没走过。
**没有样本的分支永远测不到,而检查会一直绿。**

「不知道是不是跨店」和「确认过不跨店」不是一回事:前者要去补员工档案,
后者什么都不用做。

## 这个模块不碰库,也不取时间

只吃**已经查好的事实**,回一个判定。取数是 `backend/ownership.py` 的事。
理由和 `knowledge/lifecycle.py` 一样:谁负责判定,谁就不该同时负责取数据,
否则同一批事实在不同地方算出不同结果,对不了账。
"""

# 优先级:排在前面的压过后面的。
# 一个客户可能同时满足好几条(比如顾问既停用、档案又没填门店),
# **只报一条** —— 报两条会让「先做哪个」变成读的人自己猜。
优先级 = ["NONE", "NO_SUCH", "LEFT", "NO_SHOP", "CROSS_SHOP"]

下一步 = {
    "NONE":       "等店长分配",
    "NO_SUCH":    "修数据:这个工号在员工表里不存在",
    "LEFT":       "店长重新指人(离职不会把客户一起带走)",
    "NO_SHOP":    "修数据:把这个员工的门店补上,否则判不了跨没跨店",
    "CROSS_SHOP": "店长定:转店还是转人",
}


def 判(事实):
    """回 None 表示「有人管」,否则回 {码, 说法, 下一步}。

    `事实` 要的键:
        advisor_no   客户档案上的归属工号(可能是空串或 None)
        adv_found    这个工号在员工表里查到了没有(True/False)
        adv_name     员工姓名(查到了才有)
        adv_status   员工状态:启用 / 停用
        cust_shop    客户所在门店
        adv_shop     员工所在门店

    ⚠️ **空字符串和 None 一律当成「没填」。** 库里两种都有,
    而「填了个空格」和「没填」在业务上是一回事,在 `if x` 之外的写法里不是。
    """
    def 有(k):
        v = 事实.get(k)
        return bool(v and str(v).strip())

    if not 有("advisor_no"):
        return {"码": "NONE", "说法": "还没有归属顾问", "下一步": 下一步["NONE"]}

    if not 事实.get("adv_found"):
        return {"码": "NO_SUCH",
                "说法": f"档案写的工号「{str(事实.get('advisor_no')).strip()}」"
                        f"员工表里没有 —— **数据要修**",
                "下一步": 下一步["NO_SUCH"]}

    名 = 事实.get("adv_name") or "该顾问"
    状态 = (事实.get("adv_status") or "").strip()
    if 状态 != "启用":
        return {"码": "LEFT",
                "说法": f"归属顾问 {名} 已{状态 or '不在启用状态'} —— "
                        f"**离职不会把客户一起带走**,要重新指人",
                "下一步": 下一步["LEFT"]}

    # 门店:两边都得填了才比得出来。**比不出来要说出来,不能当成没问题。**
    if not 有("cust_shop") or not 有("adv_shop"):
        缺 = "客户档案" if not 有("cust_shop") else f"顾问 {名} 的档案"
        return {"码": "NO_SHOP",
                "说法": f"{缺}没填门店 —— **判不了是不是跨店**,"
                        f"这和「确认过不跨店」不是一回事",
                "下一步": 下一步["NO_SHOP"]}

    if str(事实["cust_shop"]).strip() != str(事实["adv_shop"]).strip():
        return {"码": "CROSS_SHOP",
                "说法": f"客户在 {事实['cust_shop']},归属顾问在 {事实['adv_shop']}",
                "下一步": 下一步["CROSS_SHOP"]}
    return None


# ── 咬合记录 ────────────────────────────────────────────────────────
咬合 = [
    ("把「门店没填」那一支去掉(回到静默:判不了就当没问题)", "顾问档案没填门店"),
    ("把空白字符串当成「填了」(「填了个空格」和「填了工号」混成一个)", "空格填的工号"),
    ("让停用的顾问不报 LEFT", "停用的顾问"),
]


def _自测():
    G, R, D = "\033[32m", "\033[31m", "\033[0m"
    坏 = []

    def ck(说, 得, want):
        if 得 != want:
            坏.append(f"{说}:要 {want},得 {得}")

    好 = dict(advisor_no="60000001", adv_found=True, adv_name="张三",
              adv_status="启用", cust_shop="SH001 静安旗舰店", adv_shop="SH001 静安旗舰店")
    码 = lambda f: (判(f) or {}).get("码")

    ck("一切正常", 码(好), None)
    ck("没有归属", 码(dict(好, advisor_no=None)), "NONE")
    ck("空格填的工号", 码(dict(好, advisor_no="   ")), "NONE")
    ck("工号查无此人", 码(dict(好, adv_found=False)), "NO_SUCH")
    ck("停用的顾问", 码(dict(好, adv_status="停用")), "LEFT")
    ck("顾问档案没填门店", 码(dict(好, adv_shop="")), "NO_SHOP")
    ck("客户档案没填门店", 码(dict(好, cust_shop=None)), "NO_SHOP")
    ck("跨店", 码(dict(好, adv_shop="SH002 徐汇店")), "CROSS_SHOP")

    # 优先级:同时满足好几条时只报排在最前面的那一条
    ck("查无此人压过停用", 码(dict(好, adv_found=False, adv_status="停用")), "NO_SUCH")
    ck("停用压过没填门店", 码(dict(好, adv_status="停用", adv_shop="")), "LEFT")
    ck("没填门店压过跨店(根本判不了跨不跨)",
       码(dict(好, adv_shop="", cust_shop="SH002 徐汇店")), "NO_SHOP")
    ck("没归属压过一切", 码(dict(好, advisor_no="", adv_found=False)), "NONE")

    # 每个码都得说得出下一步 —— **分开是为了动作不同,说不出动作就不该分开**
    for c in 优先级:
        if not 下一步.get(c):
            坏.append(f"{c} 说不出下一步")
    动作 = [下一步[c] for c in 优先级]
    if len(set(动作)) != len(动作):
        坏.append("有两个码的下一步一模一样 —— **那它们就不该是两个码**")

    if 坏:
        print(f"{R}❌ 归属口径自测 {len(坏)} 条不过{D}")
        for b in 坏:
            print(f"    ❌ {b}")
        return 1
    print(f"{G}✅ 归属口径自测 15 条全过{D}")
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(_自测())
