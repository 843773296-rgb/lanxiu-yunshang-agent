# -*- coding: utf-8 -*-
"""报价的口径 —— **报价是事件,不是状态。**

业务 2026-09-27 拍的:报价结构化落到方案上,但**另建一张表、每次报价一行**,
不是往 `scheme` 上加几列。

## 为什么是事件而不是状态

报价单是**会被截图转发**的东西(`quote` skill 的文件头就是这么开头的)。
顾问发出去之后它脱离对话独自存在:客户转给家人、隔三个月翻出来问
「**你们当时说 8600**」。

如果只在方案上留最后一次:

> 顾客手里那份是上周那个价,系统里已经是新的 —— **而不一致时不报错。**
> 两份都合法、都能打开,只有把它们放在一起看才矛盾。

所以每次报价留一行:报于哪天、谁报的、物料成本多少、当时的依据是什么。
顾客说「上次说 8600」时,**查得出来是哪一次**。

## 算错了怎么办:**可以作废那一条,但不许改、不许删**(业务 2026-09-27 拍)

顾问把报价单发给客户之后发现物料成本算错了 —— 三种做法摆给业务,选的是**作废留痕**:

    09-01  ¥4956  已作废(「幅宽算错了」)
    09-20  ¥5310  ← 作数的那条

为什么不是「允许改那一行」:**改了就和「报价是事件」这条相反** ——
改完之后「客户手里那份到底是多少」变成一个靠推理的问题,而不是查得出来的。

⚠️ **用户明确知情并接受的代价,原样记下来**:
> **客户手里那份不会因为系统标了作废就消失。作废只对内,对外还是得跟客户说。**

所以 `作废()` 这个动作在系统里的意义是「**这一份不作数**」,
不是「这一份没发生过」—— 后者做不到,而**假装做得到比不做更危险**。

## 「哪一次算数」

**取最新那条(未作废的)。** 这是业务拍板时明确问过的代价。
但 `作数的那条()` 有两件事和「随便取个最新」不同:

  · **失效的方案上那些报价不作数** —— 方案已失效,它的价没有承诺力;
  · **返回的时候一定带上「一共报过几次」** —— 只返回一个数的话,
    「只报过一次」和「报过五次、这是最后一次」在输出上一模一样,
    而顾问看到后者时该知道客户手里可能是另一个数。

## 报价里哪几样必须齐

`quote` skill 第一步列了五样「一样都不能省」的查询(可行性 / 尺码 / 用料 /
工期 / 现货)。落到结构上就是这五样都要有值。

⚠️ **缺了不许拿默认值糊过去**:`齐不齐()` 把缺的那几样列出来。
理由是 skill 里那句话 —— 缺一句,三个月后就是一场纠纷;
而一个**缺项被填成 0** 的报价,比一个明说「工期没查」的报价危险得多。

## 不做的

- **不存最终售价。** skill 里写着「助手不给最终售价,物料成本 × 系数才是售价,
  系数由财务和店长定」。这里也不存 —— 存了就等于系统给出了一个它无权给的数。
- **不判「这个价合不合理」。** 那是业务判断,不是机器的。
"""
import datetime

必须齐的 = ("物料成本", "工期区间", "可行性", "尺码", "现货")
可行性取值 = ("可", "需评估", "不可")
不作数的方案状态 = ("已失效",)
最短作废原因 = 6          # 作废要写原因,**判据只写这一处**(同 rating 的最短处理记录)


def _t(s):
    return datetime.datetime.strptime(str(s)[:16], "%Y-%m-%d %H:%M")


def 齐不齐(报价):
    """五样查完了没有。返回 (齐不齐, 缺了哪几样, 一句人话)。

    ⚠️ **判「有没有值」而不是「值好不好」**,而且 0 和 None 要分开:
    物料成本真的可以是 0(全用库存尾料),而 None 是「没查」。
    第一版写的是 `if not 报价.get(k)`,那样 `物料成本=0` 会被判成缺项 ——
    **「这一格是 0」和「这一格没填」是两件事**,这个项目在别处也栽过这一条。
    """
    缺 = [k for k in 必须齐的 if 报价.get(k) is None or 报价.get(k) == ""]
    if 缺:
        return False, 缺, (f"还差 {len(缺)} 样没查:{'、'.join(缺)} —— "
                          "`quote` skill 列的五样一样都不能省,"
                          "**缺项被填成 0 的报价比明说「没查」的危险得多**")
    if 报价.get("可行性") not in 可行性取值:
        return False, ["可行性"], (f"可行性只能是 {'/'.join(可行性取值)},"
                                 f"收到「{报价.get('可行性')}」")
    return True, [], "五样都齐了"


def 能不能出单(报价):
    """这份报价能不能真出成一份发给客户的单。返回 (能不能, 一句人话)。"""
    齐, 缺, 话 = 齐不齐(报价)
    if not 齐:
        return False, 话
    if 报价["可行性"] == "不可":
        return False, ("可行性是「不可」—— **不出报价单**,直接说做不了并给替代方案"
                       "(skill 第二步第 2 段定的)")
    if 报价["可行性"] == "需评估":
        return True, ("可以出,但**必须写明:未经工艺负责人确认前,本方案不构成承诺** —— "
                      "这句不是客套,它是这份单唯一的退路")
    return True, "可以出"


def 能不能作废(报价, 原因):
    """作废一条报价。返回 (能不能, 一句人话)。

    ⚠️ **必须写原因**(同 `rating.待办能不能关` 那一条):
    不要求的话,清单上会出现一串没人知道为什么作废的报价 ——
    而那比留着错的那一条更难查。

    ⚠️ **已经作废的不许再作废** —— 不是洁癖:重复作废会把原因覆盖掉,
    而第一次那个原因才是真的那个。
    """
    if 报价.get("作废于"):
        return False, (f"这条已经在 {报价['作废于']} 作废过了"
                       f"(原因:{报价.get('作废原因') or '没写'})—— **不许再作废一次**,"
                       f"重复作废会把第一次那个原因覆盖掉")
    s = str(原因 or "").strip()
    if len(s) < 最短作废原因:
        return False, (f"作废要写原因(比如「幅宽算错了」「工艺选错了」),"
                       f"至少 {最短作废原因} 个字 —— 现在是「{s}」。"
                       f"⚠️ 而且要知道:**作废只对内,客户手里那份不会因此消失**,"
                       f"对外还是得跟客户说")
    return True, f"可以作废:{s}"


def 作数的那条(报价们, 方案状态=None):
    """一份方案上报过好几次,哪一次算数。返回 (那一条 or None, 一句人话)。

    ⚠️ 返回的话里**一定带上「一共报过几次」** ——
    只给一个数的话,「只报过一次」和「报过五次、这是最后一次」在输出上一模一样,
    而顾问看到后者时该知道**客户手里可能是另一个数**。

    ⚠️ **作废的不参与,但要在话里说出来** —— 只把它们过滤掉的话,
    「报过一次」和「报过三次、两次作废了」在输出上又一样了,
    而后者说明这份方案的价反复变过,顾问该知道。

    ⚠️ **同一分钟报两次时,靠报价号兜底排序。**
    世界时钟只到分钟(`worldclock.当下()`),所以同一分钟内报两次,`报于` 完全相同。
    第一版只按 `报于` 排,`sorted` 是稳定排序 —— 于是结果取决于**传进来的顺序**,
    而那个顺序来自 SQL 的 `ORDER BY quoted_at`,**同值时 SQLite 不保证顺序**。
    实测:同样两条,正序传取到第二条、反序传取到第一条。
    > **它当时「碰巧是对的」,而碰巧对和真的对在那一次输出上一模一样。**
    报价号里带着递增序号(`…-01` / `…-02`,见 `quote_write.落一次报价`),
    所以用 `(报于, id)` 排就有确定的答案。
    """
    全 = [q for q in (报价们 or []) if q.get("报于")]
    if 方案状态 in 不作数的方案状态:
        return None, (f"这份方案已经「{方案状态}」—— 它上面的报价**不作数**"
                      f"(报过 {len(全)} 次,都只能当历史看)")
    废 = [q for q in 全 if q.get("作废于")]
    好 = sorted([q for q in 全 if not q.get("作废于")],
               key=lambda q: (str(q["报于"]), str(q.get("id") or "")))
    尾 = f";另有 {len(废)} 次已作废" if 废 else ""
    if not 好:
        if 废:
            return None, (f"这份方案报过 {len(废)} 次,**全都作废了** —— "
                          f"现在没有作数的报价(最后一次作废原因:"
                          f"{废[-1].get('作废原因') or '没写'})")
        return None, "这份方案还没报过价"
    最新 = 好[-1]
    n = len(好)
    话 = f"按最新那次算:{最新['报于']}"
    if n > 1:
        话 += (f" —— ⚠️ **这份方案一共报过 {n} 次**(最早 {好[0]['报于']})。"
               f"客户手里那份可能是前面某一次,报数之前先确认他说的是哪一次")
    else:
        话 += "(只报过这一次)"
    return 最新, 话 + 尾


def 价变了多少(报价们):
    """相邻两次报价之间物料成本变了多少。给顾问看「为什么和上次不一样」。

    返回 [(前一次, 后一次, 差额, 一句人话)],没有两次以上就返回空。
    ⚠️ **不判「涨了合不合理」** —— 那是业务判断。只把变化摆出来。
    """
    # 作废的不参与算差额 —— 一条被作废的报价和一条真实的涨价放在一起比,
    # 算出来的「涨了多少」是假的(它比的是一个已经说了不算的数)。
    好 = sorted([q for q in (报价们 or [])
                if q.get("报于") and q.get("物料成本") is not None and not q.get("作废于")],
               key=lambda q: (str(q["报于"]), str(q.get("id") or "")))
    出 = []
    for a, b in zip(好, 好[1:]):
        差 = round(b["物料成本"] - a["物料成本"], 2)
        向 = "涨" if 差 > 0 else ("降" if 差 < 0 else "没变")
        出.append((a["报于"], b["报于"], 差,
                  f"{a['报于'][:10]} → {b['报于'][:10]}:物料成本{向}"
                  + (f" ¥{abs(差):.2f}" if 差 else "")))
    return 出


