if __name__ == "__main__":
    import sys
    bad = []

    def ck(名, 取):
        try:
            ok, 说 = bool(取()), ""
        except Exception as e:
            ok, 说 = False, f"  ← **崩了**:{type(e).__name__}: {e}"
        print(f"  {'✅' if ok else '❌'} {名}{说}")
        if not ok: bad.append(名)

    齐 = dict(物料成本=4956.0, 工期区间="28~35 天", 可行性="可", 尺码="M", 现货="有")
    print("报价口径 · 自测\n" + "=" * 72)
    ck("五样都齐 → 齐", lambda: 齐不齐(齐)[0])
    ck("物料成本是 0 不算缺项(全用库存尾料是真事)",
       lambda: 齐不齐({**齐, "物料成本": 0})[0])
    ck("缺工期 → 不齐,而且把缺的列出来",
       lambda: (lambda r: not r[0] and r[1] == ["工期区间"])(齐不齐({**齐, "工期区间": None})))
    ck("空字符串也算缺", lambda: not 齐不齐({**齐, "尺码": ""})[0])
    ck("可行性写了别的词 → 不收", lambda: not 齐不齐({**齐, "可行性": "应该行"})[0])
    ck("可行性「可」→ 能出单", lambda: 能不能出单(齐)[0])
    ck("可行性不可 → 不出报价单", lambda: not 能不能出单({**齐, "可行性": "不可"})[0])
    ck("可行性「需评估」→ 能出,但话里要有「不构成承诺」",
       lambda: (lambda r: r[0] and "不构成承诺" in r[1])(能不能出单({**齐, "可行性": "需评估"})))
    ck("缺项 → 不能出单", lambda: not 能不能出单({**齐, "现货": None})[0])

    q1 = dict(报于="2026-09-01 10:00", 物料成本=4956.0)
    q2 = dict(报于="2026-09-20 15:00", 物料成本=5310.0)
    ck("只报过一次 → 取它,并说明只报过一次",
       lambda: (lambda r: r[0] is q1 and "只报过这一次" in r[1])(作数的那条([q1])))
    ck("报过两次 → 取最新那条", lambda: 作数的那条([q1, q2])[0] is q2)
    ck("顺序乱了也取最新", lambda: 作数的那条([q2, q1])[0] is q2)
    ck("报过多次要说出来(客户手里可能是前一次)",
       lambda: "报过 2 次" in 作数的那条([q1, q2])[1])
    ck("已失效的方案上,报价不作数",
       lambda: 作数的那条([q1, q2], 方案状态="已失效")[0] is None)
    ck("已失效也要说清报过几次(不是「没报过」)",
       lambda: "报过 2 次" in 作数的那条([q1, q2], 方案状态="已失效")[1])
    ck("还没报过 → 明说没报过,不返回空对象",
       lambda: (lambda r: r[0] is None and "还没报过" in r[1])(作数的那条([])))
    ck("没有报于的那条不算(数据不全)", lambda: 作数的那条([{"物料成本": 1}])[0] is None)

    # ── 作废(业务 2026-09-27 拍:允许作废、留痕,不许改不许删)──
