    ck("作废要写原因", lambda: not 能不能作废(q1, "")[0])
    ck("原因太短也不行", lambda: not 能不能作废(q1, "错了")[0])
    ck("写清楚了能作废", lambda: 能不能作废(q1, "幅宽算错了,按整幅算了")[0])
