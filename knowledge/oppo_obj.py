"""商机**对象**的口径 —— 状态怎么走、终态有几个、诉求凭什么。

`knowledge/oppo.py` 管的是「这通电话里**有没有**商机」(一次判断);
这里管判断之后:**商机作为一个对象**,活多久、走到哪、凭什么。
(intent `opportunity-and-call-notes`,业务 2026-09-20 两轮定的;口径不取当前日期、不碰库。)

## 和方案是两样东西(业务明确否掉了「商机 = 草稿方案」)

    商机 ──触发──> 方案草稿 ──> 方案锁定 ──> 订单

**商机可以完全没有服饰信息;方案草稿必须至少挂一件具体服饰。**
混成一个的后果:同一件事在两个对象里各记一份,两份不一致时没人知道哪个是真的。

## 终态不是一个(「她拒绝了」和「当时没货」在「没成交」上长得一模一样)

    已关闭      看了不喜欢 / 嫌贵 / 不需要 —— **永久关掉,上新了也别再去烦她**
    搁置等供给  当时没有红色 / 工期赶不上 / 尺码断了 —— **上新那天要唤醒**,
                而且**必须写清等的是什么**(结构化,能拿去和上新匹配)

混成一个「已丢单」,两种都会错:要么漏商机,要么骚扰明确拒绝过的客户。

## 每条诉求都要指得回原话

「凭什么认为她喜欢红色」—— 答得上来的是那句原话;答不上来,这条提醒和瞎猜没区别。
**指不回原话的诉求,不许进回捞池。**
"""
import re

状态 = ("待确认", "跟进中", "已转方案", "已关闭", "搁置等供给")
终态 = ("已转方案", "已关闭")          # 搁置不是终态:供给变了要能唤醒
# 模型(或规则)给判断,**顾问点头才落库**(业务 D5)—— 所以新建的商机一律从「待确认」起
起始状态 = "待确认"

# 合法的状态转移。**已关闭不许被唤醒**,唤醒只能从「搁置等供给」走
转移 = {
    "待确认": ("跟进中", "已关闭"),                       # 顾问不认 = 关掉
    "跟进中": ("已转方案", "已关闭", "搁置等供给"),
    "搁置等供给": ("跟进中", "已关闭"),                   # 供给到了 → 唤醒;等太久不要了 → 关
    "已转方案": (),
    "已关闭": (),
}

# 诉求可匹配的维度(业务 D3:价位 / 工期 / 尺码 / 性别也纳入;季节、「预算弹性」不做 —— 「贵点也行」是态度不是属性)
诉求维度 = ("颜色", "形制", "面料", "纹样", "场合", "预算", "工期", "尺码", "性别")

咬合 = []


def 能转吗(现, 到):
    """返回 (能不能, 一句人话)。"""
    if 现 not in 转移:
        return False, f"「{现}」不是商机的状态"
    if 到 in 转移[现]:
        return True, ""
    if 现 == "已关闭":
        return False, "已关闭的商机**不许唤醒** —— 关掉就是客户明确不要了,上新了也别再去烦她"
    return False, f"商机不能从「{现}」直接到「{到}」(能去的:{'、'.join(转移[现]) or '没有,这是终态'})"


def 搁置理由合格吗(等什么):
    """搁置必须写清等的是什么,而且是**可匹配的字段**,不是一段话。等什么 = {维度: 值}。"""
    if not isinstance(等什么, dict) or not 等什么:
        return False, "搁置必须写清等的是什么(如 {\"颜色\": \"红\"}),否则上新时匹配不上,等于永久丢了"
    坏 = [k for k in 等什么 if k not in 诉求维度]
    if 坏:
        return False, f"「{'、'.join(坏)}」不是可匹配的维度(能用:{'、'.join(诉求维度)})"
    return True, ""


def 原话(客户话行们, 词):
    """在客户说的话里找到含这个词的那一句(按句号、问号、感叹号、换行切)。找不到返回 None —— **不编**。"""
    for 行 in 客户话行们:
        for 句 in re.split(r"(?<=[。!?!?])|\n", 行):
            if 词 in 句:
                return 句.strip()
    return None
