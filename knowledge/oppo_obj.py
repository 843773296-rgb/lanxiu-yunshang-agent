# 回捞出来的是**给顾问的提醒**,不改商机状态:顾问看了原话、决定去找,才把商机转回「跟进中」(业务 D5:人点头才算)
# **仍然不给成单概率** —— 给依据(原话 + 对上了哪一条),不给数字


def 在时效内(诉求日, 今天):
    """诉求日 / 今天 都是 date。月数按「同一天往前推 N 个月」算。"""
    y, m = 今天.year, 今天.month - 回捞_时效月数
    while m <= 0:
        m += 12; y -= 1
    import calendar, datetime as _dt
    起 = _dt.date(y, m, min(今天.day, calendar.monthrange(y, m)[1]))
    return 诉求日 >= 起


def 冷却中(上次推送日, 今天):
    return 上次推送日 is not None and (今天 - 上次推送日).days < 回捞_冷却天数


