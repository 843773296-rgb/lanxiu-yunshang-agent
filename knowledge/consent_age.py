"""量体存身体数据,按年龄要哪几份同意(知识 12 第七节;14—18 周岁是业务 2026-10-10 晚 #9 定的)。

    不满 14 周岁    身体数据同意 + 「未成年人」同意,**都由监护人签**(个保法 31)
    14—18 周岁      **以本人同意为准**:身体数据那一份要本人签;
                    **付款的是家长时**(着装人不是账户本人,即家长替孩子下单),身体数据那项**家长也签一份**(双签)
                    营销触达**只看本人**,家长不能替孩子同意
    18 周岁以上     本人

为什么 14—18 要改:原来系统只写了「未成年 → 监护人签」,于是 14—18 周岁的同意**全是家长签的**
(2026-10-10 量:95 位存了身体数据的 14—17 岁着装人,本人签的 0 份)。
法律只要求不满 14 周岁由监护人同意;GB/T 35273 对 14 周岁以上写的是「未成年人**或**其监护人」——
业务选了「本人为准 + 家长双签」:本人是法定那一签,家长那一签防「家长不知道店里存了孩子的身体数据」。

「家长」怎么认:`consent.relation` 以「监护人」开头(库里有「监护人」「监护人(母)」「监护人(父)」三种写法)。
**只认这个结构,不认 granted_by 的人名。**
生日没登记 → 判不出年龄,按原来的规矩走(只要有一份身体数据同意),不猜。

**这里不取数、不取日期**:岁数和同意记录由调用方传进来。
"""

咬合 = [
    ("14—18 周岁只有家长签的身体数据同意 → 缺本人那一签", "14—18 周岁只有家长签 → 缺本人"),
    ("家长付款的 14—18 周岁只有本人签 → 缺家长那一签(双签)", "家长付款只有本人签 → 缺家长"),
]

本人 = "本人"


def 是家长(relation):
    return str(relation or "").startswith("监护人")


def 缺什么(岁, 着装人关系, 同意们):
    """同意们 = [(scope, relation)],**只传没撤回的**。→ 缺的那几样的说法列表;空列表 = 齐了。"""
    身体 = [r for s, r in 同意们 if s == "身体数据"]
    if not 身体:
        return ["没有有效的身体数据同意"]
    if 岁 is None or 岁 >= 18:
        return []
    if 岁 < 14:
        return [] if any(s == "未成年人" for s, _ in 同意们) else ["不满十四周岁,缺监护人的未成年人同意"]
    缺 = []
    if 本人 not in 身体:
        缺.append("已满 14 周岁,身体数据要**孩子本人**同意(家长签的不能代替本人)")
    if 着装人关系 != 本人 and not any(是家长(r) for r in 身体):
        缺.append("家长付款的单,身体数据这一项**家长也要确认**(双签)")
    return 缺


def 营销能不能触达(岁, 同意们):
    """营销触达:14—18 周岁**只看本人**签的那一份;不满 14 看监护人;成年看本人。"""
    营 = [r for s, r in 同意们 if s == "营销触达"]
    if 岁 is not None and 14 <= 岁 < 18:
        return 本人 in 营
    return bool(营)


if __name__ == "__main__":
    坏 = 0

    def ck(名, ok):
        global 坏
        坏 += not ok
        print(f"  {'✅' if ok else '❌'} {名}")

    家 = "监护人(母)"
    ck("成年人有一份身体数据同意就齐", 缺什么(30, 本人, [("身体数据", 本人)]) == [])
    ck("不满 14 周岁:没有未成年人同意 → 缺", 缺什么(10, "子", [("身体数据", 家)]) != [])
    ck("不满 14 周岁:监护人签了两份 → 齐", 缺什么(10, "子", [("身体数据", 家), ("未成年人", 家)]) == [])
    ck("14—18 周岁只有家长签 → 缺本人", any("本人" in x for x in 缺什么(15, "子", [("身体数据", 家)])))
    ck("家长付款只有本人签 → 缺家长", any("家长" in x for x in 缺什么(15, "子", [("身体数据", 本人)])))
    ck("14—18 周岁本人 + 家长都签了 → 齐", 缺什么(15, "子", [("身体数据", 本人), ("身体数据", 家)]) == [])
    ck("14—18 周岁自己是账户本人(自己付款)→ 本人签就齐,不要家长", 缺什么(17, 本人, [("身体数据", 本人)]) == [])
    ck("满 14 周岁那天起就按本人算(14 岁不再走监护人那条)", 缺什么(14, "子", [("身体数据", 家), ("未成年人", 家)]) != [])
    ck("满 18 周岁:家长签的旧同意也不再要求双签", 缺什么(18, "子", [("身体数据", 本人)]) == [])
    ck("生日没登记(岁 None)不猜,按原规矩", 缺什么(None, "子", [("身体数据", 家)]) == [])
    ck("营销触达 14—18 周岁只看本人:家长签的不算", not 营销能不能触达(16, [("营销触达", 家)])
       and 营销能不能触达(16, [("营销触达", 本人)]))
    ck("「家长」只认关系以「监护人」开头,配偶不算", 是家长("监护人") and 是家长(家) and not 是家长("配偶"))
    raise SystemExit(1 if 坏 else 0)
