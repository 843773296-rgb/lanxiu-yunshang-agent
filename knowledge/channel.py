def 可比吗(渠道名):
    """这个渠道能不能拿来做渠道对比。返回 (能不能, 理由)。"""
    if 渠道名 in 不是渠道:
        是什么, 为什么 = 不是渠道[渠道名]
        return False, f"{是什么} —— {为什么}"
    return True, None


def 比率(分子, 分母, 说明=""):
    """算一个比率。**分母为零不给数;给了数就把「一单值多少」一起给。**

    返回 (可读文本, 数值或 None)。数值为 None 表示无从谈起,
    调用方**不许把它当 0 用**。

    分母为零那一档直接用 `review.rate` —— **同一件事不写第二遍**。
    """
