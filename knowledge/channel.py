    文, 值 = review.rate(分子, 分母, 说明)
    if 值 is None:
        return 文, None
    一单 = round(100.0 / 分母, 1)
    return (f"{分子}/{分母}({round(值 * 100, 1)}%,"
            f"**一单就值 {一单} 个百分点**)"), 值


