"""库存预警的口径 —— **算得出的算,算不出的明说算不出。**

## 为什么不用「低于 N 件就预警」

固定件数阈值对走量款**太晚**(卖得快的,10 件够撑两天)、
对冷门款**天天在报**(一年卖两件的,10 件够撑五年)。

**有用的是可售天数** —— 「按现在的速度,这些货还能卖几天」。

## ⚠️ 而可售天数在这个库上**算不出来**,这件事必须说出来

2026-09-15 扫的实情:

    有销量的 SKU        **71 / 805** —— 其余 734 个一件都没卖过
    这 71 个各卖了几件  **全部恰好 1 件**
    订单时间跨度        **17 天**(2026-08-10 → 08-27)

也就是说:销售速度要么是 0(734 个),要么是同一个数(71 个都是 1/17 天)。
**这样的数据算出来的「可售天数」,不是一个指标,是一个装饰。**

> **算不出就要明说算不出,不许退回成件数阈值假装算得出。**
>
> 这个项目为「抓不到 ≠ 零分」「空 ≠ 零」「估算 ≠ 实测」栽过好几次 ——
> 一个编出来的可售天数,会让人按它去补货。

所以这份口径分两层:

    **能算的**   可用库存(在手 − 已占用)、断没断货、卖不卖得动 —— 这些是**事实**
    **算不出的** 可售天数、补货点 —— **明说缺什么才算得出**,不给一个凑出来的数

## 「在手」和「可用」是两回事

`stock` 是**在手**,`locked` 是**已被订单占用**。
客户问「还有货吗」,要的是 **可用 = 在手 − 已占用**。

实测(2026-09-15):**可用为 0 的有 184 个**,拆开看是两件完全不同的事 ——

    **164 个** 在手就是 0        真断货,要不要补是采购的事
    **20 个**  在手有货、全被占用  **报「在手」会说有货,而实际一件都发不出**

后面这 20 个才是这个工具存在的理由:它们在库存表上**看起来是有货的**。
"""

# 可售天数要算得出来,至少得有这些 —— 缺哪样就说缺哪样
需要 = {
    "销量样本": "每个 SKU 有过若干笔销售(不是全库只有 71 个各卖 1 件)",
    "时间跨度": "订单跨度够长(现在只有 17 天,算不出季节性,也算不出趋势)",
}

# ⚠️ **这条线要业务定,不许在这儿编一个数。**
# 「可用库存低到什么程度算要补」取决于补货周期和缺货代价,
# 而这两样都是商业决定。
补货点 = None
补货点_为什么是空的 = (
    "补货点 = 补货周期内会卖掉多少 + 安全库存。"
    "前者要销量数据(现在算不出),后者要业务定「缺货一次的代价有多大」。"
    "**两样都没有的时候,任何一个补货点都是编的。**")


# ── 哪些订单行算「卖掉了」──────────────────────────────────────────────
#
# 2026-09-15 由另一个会话(假数据工厂)指出来的一个真 bug:
# 第一版数销量写的是 `SELECT sku, COUNT(*), SUM(qty) FROM ordr_item GROUP BY sku`,
# **一个订单状态都没过滤** —— 取消的单、还没付钱的单,全被算成卖出去了。
#
# 又是这个项目那条主线:**「下过单」和「卖掉了」长得一模一样。**
# 库里现在 11 单待付款、2 单取消、1 单已退款,全在销量分母里。
# 数据量小的时候看不出来,**数据一补上就会放大成系统性高估**。
#
# ## 这里不另立一套口径,两条都是项目里已经定过的
#
#     待付款   `recovery.py` 明写它是**未成交**(未成交挽回清单的两摊之一)
#     取消     `activity.py` 明写「**取消的单一律排除**:它既不是收入,也不该占分母」
#
# 同一件事在两个模块里各算各的,必然漂 —— 所以照搬,不重新拍。
不算卖掉 = {
    "待付款": "钱还没到 —— **recovery.py 把它算作未成交**,是挽回清单的一摊",
    "取消":   "**activity.py:取消的单一律排除** —— 它既不是收入,也不该占分母",
}
已退款不算 = "退了钱的行不是销量。**退款中**的还没退完,先当卖掉了 —— 退成了会再扣回去"

# ⚠️ **白名单,不是黑名单** —— 认不出来的状态**不算销量**,而且要报出来。
#
# 两种写法偏错的方向正好相反,而这决定了选哪个:
#
#     黑名单(不认识的算进销量)  → 销量高估 → 速度偏快 → 可售天数偏小 → **误报**
#     白名单(不认识的不算)      → 销量低估 → 速度偏慢 → 可售天数偏大 → **漏报**
#
# 按「**往宽松方向改之前先问偏错的代价朝哪边**」——
# 这个项目的结论一直是**误报比漏报贵**:一条误报会让采购去补一个不缺的款,
# 而且报多了人就不看了。所以选白名单。
#
# 但白名单有它自己的坑:**静默少算**。所以认不出来的状态要**列出来说**,
# 不许悄悄丢掉 —— 「抓不到」和「零」不是一回事,这个项目为它栽过好几次。
算卖掉 = ("待审核", "待生产", "生产中", "已生产",
          "待发货", "已发货", "待完成", "完成")


def 卖掉了(状态, 退款状态=None):
    """这一行订单算不算销量。返回 (算不算, 为什么不算)。"""
    if 状态 in 不算卖掉:
        return False, 不算卖掉[状态]
    if (退款状态 or "") == "已退款":
        return False, 已退款不算
    if 状态 not in 算卖掉:
        return False, (f"**状态「{状态}」不在已知的那几种里** —— "
                       f"不认识就不算销量(宁可少算),但**要说出来**")
    return True, None


# ── 速度的分母:**这个 SKU 自己能卖的那段时间** ────────────────────────
#
# 2026-09-15 由假数据工厂那个会话指出来的第二个问题:
# 第一版拿**全局** min..max 当分母,于是一个 6 月才上架的 SKU,
# 速度也按「2 月到 9 月」来除 —— **被稀释、可售天数偏大、该报的不报**。
#
# 按「误报比漏报贵」那条,这是朝**漏报**那边偏,而且偏得没道理:
# 那个 SKU 在它上架之前根本没机会卖。**分母要是它自己能卖的那段。**
#
# ⚠️ 这里**不设「窗口至少多少天」的下限**。
# 一个上架三天卖了两笔的 SKU,速度算出来会很高、可售天数会很短 ——
# 那确实可能是噪音。但「多短算太短」是业务判断(和补货点、超时天数一类),
# **这个项目不替业务猜数**。
# 做的是另一件事:**把窗口长度和笔数一起报出去**,让看的人自己看得见
# 这个天数是按多少数据算出来的。一个「12 天(上架 20 天、3 笔)」
# 和一个「12 天(上架 300 天、90 笔)」,数字一样而分量完全不同。


def 可卖窗口(上架日, 区间起, 区间止):
    """这个 SKU 在统计区间里**有多少天是能卖的**。

    返回 (天数, 从哪天起, 说明)。天数为 None 表示**算不出**。
    """
    import datetime as _d
    if not 区间起 or not 区间止:
        return None, None, "**算不出** —— 没有统计区间"
    起 = max(上架日[:10], 区间起) if 上架日 else 区间起
    补 = None if 上架日 else "**这个商品没记上架日**,按统计区间起算 —— 窗口可能偏长"
    if 起 > 区间止:
        return None, 起, f"**算不出** —— 上架日 {起} 晚于统计区间,它还没开卖"
    n = (_d.date.fromisoformat(区间止) - _d.date.fromisoformat(起)).days + 1
    return n, 起, 补


# ── `stock_log` 记的是哪个量:**这件事从来没定义过** ────────────────────
#
# 2026-09-15 由假数据工厂那个会话提出来,核过之后确认是一个真的口径缺口。
#
# 流水的 kind 只有六种:入库 / 报损 / 盘点调整 / 订单占用 / 订单释放 / 退货入库,
# **没有「发货出库」**。那么发货那一刻在手和占用各减一样多、**可用不变** ——
# 不写流水是对的。倒过来推:
#
#     这条链只可能记的是**可用**,不可能是在手。
#
# 因为「订单占用」减的是可用,不是在手(货还在仓库里,只是被订走了)。
#
# ⚠️ **而种子那 60 条是按「在手」写的**:实测 8 条里 7 条 `after_n == sku.stock`,
# 还有 1 条(退货入库 after=9)和在手、可用都对不上。
#
# **所以不是谁记错了,是这张表从来没说过自己记的是哪个量** ——
# 而两种读法在表上**长得一模一样**:都是一串加加减减的整数。
#
# 这里定下来的是**唯一自洽的那个读法**,并把对不上的条数钉成上限
# (和 `source_check.py` 的出处欠账同一个办法:只许降不许涨)——
# **不去改种子数据**,那是别人的真值,而且改了要业务点头。
流水记的是 = "可用"
流水记的是_为什么 = (
    "kind 里**没有「发货出库」**。发货时在手和占用各减一样多、可用不变,"
    "所以不写流水是对的 —— 倒过来推,这条链只能是可用。"
    "「订单占用」减的也是可用(货还在仓库里,只是被订走了),不是在手。")
# **首次扫出来的账:60 个有流水的 SKU 里,47 个链尾对不上可用。**
# 只许降不许涨 —— 补一个就把这个数改小,**别把检查改掉**。
# 一个「必须立刻全绿」的检查,在还不了的债面前只有一个下场:被注释掉。
流水对不上的上限 = 47


def 可用(在手, 已占用):
    """客户问「还有货吗」要的是这个数,不是在手。

    实测有 **20 个 SKU 在手有货但全被占用** ——
    报在手会说有货,而实际一件都发不出。
    """
    return (在手 or 0) - (已占用 or 0)


# 「快没了」的件数线。**业务 2026-09-22 定:可用 ≤ 5 件。**
#
# ⚠️ 原来这里写的是 4,后台库存列表页写的是 5 —— **同一个「快没了」,两处各写一个数**,
# 店长在后台看到的和智能助手说的对不上。收成这一个常数,两边都从这里取。
# 这条线以前注释成「权宜」(立项时说不用固定件数当阈值);现在是业务拍的板,不是权宜了。
# 档内仍按可售天数从急到缓排 —— 线划在哪是业务的事,排序是算术的事。
快没了_件数 = 5


def 档(在手, 已占用, 卖过几件):
    """把一个 SKU 归档。**只用算得出的事实,不用编出来的速度。**

    返回 (档位, 一句人话)。
    """
    a = 可用(在手, 已占用)
    if a <= 0 and (在手 or 0) > 0:
        return ("发不出", f"在手 {在手} 件但**全被占用了**,可用 0 —— "
                          f"报「有货」会让客户白等")
    if a <= 0:
        return ("断货", "在手和可用都是 0")
    if not 卖过几件:
        return ("卖不动", f"可用 {a} 件,而**一件都没卖过** —— "
                          f"这不是缺货风险,是压货")
    if a <= 快没了_件数:
        return ("快没了", f"可用只剩 {a} 件,而它**卖得动**(卖过 {卖过几件} 件)")
    return ("够", f"可用 {a} 件")


# 要谈「速度」,至少得有**两笔**销售 —— 这不是业务阈值(那种不许编),
# 是算术:**一个点画不出一条斜率**。
#
# 只卖过一笔的 SKU,「每 18 天卖 1 件」和「那 18 天里碰巧卖了 1 件」
# 在数据上**一模一样**,而它们对补货的含义完全相反。
#
# ⚠️ 两笔也只是**能不能算**的下限,不是**算得准**的门槛。
# 实测全库 71 个有销量的 SKU **每个都只有一笔**,所以这条线下来是全军覆没 ——
# 这正是要说的事实,不是要绕过的障碍。
最少笔数 = 2
最少笔数_为什么 = "一笔销售画不出速度:「每 18 天卖 1 件」和「碰巧卖了 1 件」数据上一样"


def 可售天数(在手, 已占用, 卖过几笔, 卖过几件, 统计天数):
    """**返回 None 表示算不出**,并给出缺什么。不许凑一个数。

    注意要**笔数**和**件数**两个参数:件数决定速度的大小,
    笔数决定这个速度**能不能算** —— 一单卖 10 件,也还是一个点。
    """
    if not 卖过几笔 or not 统计天数:
        return None, "**算不出** —— 这个 SKU 在统计区间里一件都没卖过"
    if 卖过几笔 < 最少笔数:
        return None, (f"**算不出** —— 只卖过 {卖过几笔} 笔,"
                      f"{最少笔数_为什么}")
    速度 = (卖过几件 or 0) / 统计天数
    if 速度 <= 0:
        return None, "**算不出** —— 销售速度是 0"
    a = 可用(在手, 已占用)
    if a <= 0:
        # ⚠️ **这个 0 是真的 0,不是「算不出」的伪装。**
        #
        # 一个已经卖空、而且卖得动的 SKU,可售天数就是 0 天 —— 事实如此。
        # 而这里曾经有一条判据写成「**算不出**不许写成 0 天」,
        # 它会把这一行判成违规。
        #
        # 判据画错了边:它贴着**「0」这个值**,而该贴的是**这个 0 从哪来**。
        # 同一个 0,一个来自「不知道」(危险),一个来自「已经卖空了」(事实)。
        # **两者在表上长得一模一样** —— 这个项目的主线。
        #
        # 分法很干净:**算不出的那一路返回的是句子,永远不可能是 0。**
        # 所以「0 天」只可能出自这里,而这里只在可用 ≤ 0 时走到。
        return 0.0, None
    return round(a / 速度, 1), None


