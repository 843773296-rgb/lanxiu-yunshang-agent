"""标品退货率 / 换货率 / 退货原因 —— 口径只在这里定一次(工具层只取数、只装配)。

## 口径(用户 2026-11-15 早拍板,算法选型卡全选推荐项 + 补问一条)

① **按付款日分批,观察期满才算**:付款日离今天不足 `观察期天数`(14 天)的件,分子分母一起不算。
   法定 7 日无理由(knowledge/09-养护与售后.md)+ 实测退货最晚在付款后 9.7 天。
   否决「本月退货 ÷ 本月卖出」:月底卖的下月才退,当月率系统性偏低,**偏低的率和「这个月货特别好」长得一样**。
② **每个率带可信范围**(Clopper-Pearson 精确区间,95%),**范围整体高于全店、而且至少退过 3 件才说「偏高」;
   范围整体低于全店才说「偏低」;其余「说不清」**。
   退货是稀有事件(全店件退货率约 1%):照搬易损分析「分母 ≥30 件给结论」会让卖了 54 件没人退的品类读成 0%,
   而 54 件里一个人都没退在 1% 的率下很正常 —— 「没有证据」读成了「有证据说没问题」。易损分析暂不改(用户 11-15)。
   ⚠️ **写的时候换过一次方法、补问过一次**(11-15):第一版用 Wilson 近似区间,按商品切时「卖 9 件退 1 件」都判成偏高 ——
   率接近 0 时近似区间的下限偏高。换成精确区间后,「卖 2 件退 1 件」仍会被判偏高:统计上不算错(全店率不到 1%),
   但商品有 140 个档,一起比凭运气就会冒出几个。补问用户后定「**至少退过 3 件才判偏高**」(否决:档越多门槛越严 ——
   按商品切时连云肩绣片 179 件退 8 件都会被压掉)。
③ **换货单独一个换货率**,不并进退货率(换货 = 想要只是码 / 色不对,退货 = 不要了)。
④ **退货原因原样 6 类**,不替业务分组。
⑤ **申请退货率和实际退货率两个都给**(用户 11-15 补问):申请 = 提过的全算(含审批拒绝、还在审的);
   实际 = 批了 / 在办 / 办完的(去掉审批拒绝和还没批的)。两个数并列不合成。
统计单位按「件」(一条售后单对一行订单明细)。

⚠️ 这个库上的退货率是**造数时按比例种进去的**(fakedata/planted.py S12:退货 1.2% · 换货 0.44%)——
   哪个品类「偏高」多半是随机分配撞出来的,返回里带着这句话。
"""
from math import sqrt

观察期天数 = 14      # 用户 2026-11-15 确认:法定 7 日 + 实测最晚 9.7 天,取整到两周
置信度 = 0.95       # 可信范围的置信度 —— 统计惯例;用户 11-15 选的是「带可信范围」,95% 没单问
偏高最少件 = 3       # 用户 2026-11-15 补问确认:退 1–2 件的一律「说不清」,防 140 个商品档里凭运气冒出的偏高
没批的状态 = ("审批拒绝", "提交申请")   # 实际退货率里不算:拒了的不是退货,还在审的可能被拒
造数提醒 = ("这批退货 / 换货是造演示数据时按比例种进去的(退货 1.2%、换货 0.44%,fakedata/planted.py S12)—— "
          "哪个档「偏高」多半是随机撞出来的,**不是发现**;报的时候要带上这句")


def _尾(k, n, p):
    """二项分布 P(X ≤ k)。p 在 (0,1) 内;用对数加和,n 到几万也不溢出。"""
    from math import exp, lgamma, log
    if k < 0:
        return 0.0
    if k >= n:
        return 1.0
    基 = lgamma(n + 1)
    return min(1.0, sum(exp(基 - lgamma(i + 1) - lgamma(n - i + 1) + i * log(p) + (n - i) * log(1 - p))
                        for i in range(k + 1)))


def 范围(k, n, 置信=置信度):
    """Clopper-Pearson 精确区间 (下, 上),都是比例;n=0 → None。二分法解尾概率,不依赖 scipy。"""
    if n <= 0:
        return None
    a = (1 - 置信) / 2
    def 解(满足):
        lo, hi = 0.0, 1.0
        for _ in range(60):
            m = (lo + hi) / 2
            if 满足(m):
                hi = m
            else:
                lo = m
        return (lo + hi) / 2
    下 = 0.0 if k == 0 else 解(lambda p: 1 - _尾(k - 1, n, p) >= a)
    上 = 1.0 if k == n else 解(lambda p: _尾(k, n, p) <= a)
    return 下, 上


def _判(k, n, 全店):
    r = 范围(k, n)
    if r is None:
        return "没卖出"
    if r[0] > 全店:
        return "偏高" if k >= 偏高最少件 else "说不清"
    if r[1] < 全店:
        return "偏低"
    return "说不清"


def _率(k, n):
    return None if n <= 0 else round(100 * k / n, 2)


def 算(卖出, 售后, 今天, 取维度):
    """卖出:[{付款日 'YYYY-MM-DD…', 件数, …维度字段}];售后:[{付款日, kind, status, reason, …维度字段}]。
    今天:date。取维度:行 → 维度值。返回 dict(全店 / 各档 / 原因 / 观察期)。"""
    import datetime as _dt
    界 = (今天 - _dt.timedelta(days=观察期天数)).isoformat()
    满 = lambda 行: (行.get("付款日") or "")[:10] and (行["付款日"][:10] <= 界)
    卖 = [x for x in 卖出 if 满(x)]
    售 = [x for x in 售后 if 满(x)]
    未满件 = sum(x["件数"] for x in 卖出 if not 满(x))

    档 = {}
    for x in 卖:
        档.setdefault(取维度(x), dict(件=0, 申请退=0, 实际退=0, 换=0, 拒=0))["件"] += x["件数"]
    原因 = {}
    for x in 售:
        t = 档.setdefault(取维度(x), dict(件=0, 申请退=0, 实际退=0, 换=0, 拒=0))
        if x["kind"] == "退货退款":
            t["申请退"] += 1
            if x["status"] == "审批拒绝":
                t["拒"] += 1
            if x["status"] not in 没批的状态:
                t["实际退"] += 1
                原因[x.get("reason") or "(没填原因)"] = 原因.get(x.get("reason") or "(没填原因)", 0) + 1
        elif x["kind"] == "换货" and x["status"] not in 没批的状态:
            t["换"] += 1
    N = sum(t["件"] for t in 档.values())
    合 = {k: sum(t[k] for t in 档.values()) for k in ("申请退", "实际退", "换", "拒")}
    全 = {k: (合[k] / N if N else 0.0) for k in ("申请退", "实际退", "换")}
    行们 = []
    for 名, t in 档.items():
        行 = dict(档=名, 卖出件=t["件"])
        for k, 名字 in (("实际退", "实际退货"), ("申请退", "申请退货"), ("换", "换货")):
            r = 范围(t[k], t["件"])
            行[名字] = dict(件=t[k], 率=_率(t[k], t["件"]),
                          范围=None if r is None else [round(100 * r[0], 2), round(100 * r[1], 2)],
                          判=_判(t[k], t["件"], 全[k]))
        行["申请被拒"] = t["拒"]
        行们.append(行)
    行们.sort(key=lambda r: (-(r["实际退货"]["率"] or 0), -r["卖出件"]))
    原因总 = sum(原因.values())
    return dict(
        全店=dict(卖出件=N, 实际退货=合["实际退"], 申请退货=合["申请退"], 申请被拒=合["拒"], 换货=合["换"],
                实际退货率=_率(合["实际退"], N), 申请退货率=_率(合["申请退"], N), 换货率=_率(合["换"], N)),
        各档=行们,
        退货原因=[dict(原因=k, 件=v, 占比=round(100 * v / 原因总, 1)) for k, v in sorted(原因.items(), key=lambda kv: -kv[1])],
        观察期=dict(天数=观察期天数, 只算付款日不晚于=界, 未满观察期的件=未满件,
                  说明=f"付款不满 {观察期天数} 天的件还在退货期里,分子分母一起不算(否则最近的率系统性偏低)"),
        判法=(f"每个率带 95% 可信范围;范围整体高于全店、而且至少退过 {偏高最少件} 件才说「偏高」,"
            f"整体低于全店才说「偏低」,其余「说不清」(用户 2026-11-15 定)"),
        偏高的=[r["档"] for r in 行们 if r["实际退货"]["判"] == "偏高"],
        提醒=造数提醒,
    )
