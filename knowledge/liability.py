#!/usr/bin/env python3
"""售后判责 —— 从 09-养护与售后.md 第五节那张「返修判定」表推结论。

## 这块能力为什么早该有

09 那份文档第六节自己写着售后是智能体的天然落点,理由是:
「客服面对的问题**高度重复**、判定依据**是结构化的**、但结论必须由人给」。

标准写好了、决策表在库里(kb_tables 的「售后争议判定」)、
工具说明里还专门指了路(get_aftersale:「只给事实,不给判责结论」)——
**但那条路从来没人走过。** 知识资产闲置最容易被忽略,因为它不报错。

## 判责其实是可枚举的,难的是前一步

第五节那张表只有 7 行,**规则完全覆盖得住** —— 所以 V2 能做。
真正难的是**把客户那句话归到哪一类**:
「面料起球」是特性还是洗护不当?「尺寸不对」是谁的量体记录有问题?
归类要看现场(面料工艺、量体记录全不全、有没有书面告知),
这一步才是要调工具的地方。

**这是个好例子:一件事看起来需要判断,拆开之后判断只占一小段。**

## 一条判据原来落不了地

第五节写着「特性类**且已书面告知** → 无责」「**未**书面告知 → 我方让步」,
但库里原本没有任何字段记「告知过没有」——**所以那两行永远跑不到**。
这次补了 `delivery_notice` 表。和当初「体型特征」的情况一模一样:
**文档里写着的判据,如果数据里没有对应字段,它就只是一句话。**
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
MD = os.path.join(HERE, "09-养护与售后.md")
_c = {}


# ── 咬合记录 ──────────────────────────────────────────────────────────
# 左边「改坏了什么」,右边「预期红的那一条」。**每一条都在 tools/bite_specs.json 里
# 有一份可执行的规格**,`python3 tools/bite_run.py` 能重放:对照要先绿,改坏之后
# 要红,而且红的必须是右边这一条 —— 三关缺一关,这条记录就不算数。
咬合 = [
    ('把判定表里「脱线」那一行的责任方从我方改成客方',
     '工艺瑕疵 → 我方免费返修'),
]

def _md():
    if "t" not in _c: _c["t"] = open(MD, encoding="utf-8").read()
    return _c["t"]


def table():
    """第五节「返修判定」:情形 → (责任, 处理)。从 md 解析,不在代码里另存一份。"""
    if "tbl" in _c: return _c["tbl"]
    t = _md()
    seg = t.split("## 五、返修判定", 1)[-1].split("\n## ", 1)[0]
    out = []
    for line in seg.split("\n"):
        l = line.strip()
        if not l.startswith("|") or l.startswith("|---") or "情形" in l: continue
        col = [x.strip().replace("**", "") for x in l.strip("|").split("|")]
        if len(col) == 3: out.append(tuple(col))
    if len(out) < 5:
        raise RuntimeError(f"返修判定表没解析出来(只拿到 {len(out)} 行)—— md 表格格式变了?")
    _c["tbl"] = out
    return out


# issue → 大类。**这一步是归类,不是判责** —— 判责在下面那张表里。
# ── 量体记录「完整 / 不全」的分界 ────────────────────────────────────
#
# 09 号文件第五节把「尺寸偏差」分成两行:
#
#     量体记录**完整且相符** → 客方,收费改
#     量体记录**缺失/不全**  → 我方,**免费改**
#
# 一条收钱一条不收钱,而 md 里**没有写几项才算完整** ——
# 那个数(4)原来只活在 `backend/seed.py` 的真值生成里,
# 知识库和这个口径模块**一个字都没有**。
#
# 违反的是这个项目的第一条规矩:**口径进 `knowledge/`,工具只取数**。
# 代价 2026-09-15 真跑时兑现了:`get_maintain` 只给「条数 3」,
# 模型把它读成「数据完整且可信度高」,判成**客方收费改** ——
# 责任判反、钱收反,而它没有任何办法知道该有几项。
#
# ⚠️ **这个 4 是 demo 级的**(和整份 09 一样)。真实项目要由售后负责人定,
# 而且大概率不是一个固定数字,是「关键尺寸有没有量全」。
# 写在这儿是为了**让它只有一个来源**,不是为了假装它有依据。
完整门槛 = 4
完整门槛_依据 = ("09-养护与售后.md 第五节只写了「完整 / 不全」两行,没写几项算完整。"
                "这个数是 demo 级的,真实项目须由售后负责人定 —— "
                "而且大概率该按「关键尺寸有没有量全」判,不是按条数。")


def 量体完整(项数):
    """够不够「完整」。返回 (完整吗, 一句人话)。"""
    齐 = (项数 or 0) >= 完整门槛
    return 齐, (f"{项数}/{完整门槛} 项,"
                + ("**完整**(09 第五节第 2 行:客方,收费改)" if 齐 else
                   "**不全**(09 第五节第 3 行:**我方,免费改**)"))


KIND = {
    "盘扣脱线": "工艺瑕疵", "下摆开线": "工艺瑕疵",
    "刺绣局部脱落": "工艺瑕疵", "拉链损坏": "工艺瑕疵",
    "尺寸需调整": "尺寸偏差",
    "面料起球": "特性类", "染色不均": "特性类",
}
FEATURE_WORDS = ("色差", "掉色", "勾丝", "起球", "染色不均", "褪色", "手工痕迹")


def classify(issue):
    """把客户报的问题归到大类。归不出来就返回 None —— **不猜**。"""
    if issue in KIND: return KIND[issue]
    if any(w in (issue or "") for w in FEATURE_WORDS): return "特性类"
    return None


def judge(issue, notified=None, measure_full=None, 试衣状态=None, 签收合身=None):
    """按第五节判责。返回 dict,判不出来时 rule=None(交给人/模型)。

    notified      特性类才用:交付时有没有**书面告知**过这一条
    measure_full  尺寸类才用:量体记录是否完整且相符
    签收合身       尺寸类才用:交付签收时顾客本人试穿、输码确认过合身(业务 09-22:之后的尺寸问题顾客承担)
    试衣状态       尺寸类才用,取值见 `muslin.状态`:
                  已试已签 / 该试没试 / 已试未签 / 不必试

    ## 白坯试衣优先于量体记录,**这是有意的**

    两者说的不是一件事:

        量体记录  「**我们**量得对不对」
        试衣签字  「**他本人穿过**并且认可了」

    一个人到店穿过白坯、当场确认合身并签了字,之后再说尺寸不对,
    **这时候量体记录全不全已经不重要了** —— 他自己验收过。
    (原来还有一行「远程量体 → 按合同分担」,2026-09-22 业务定不准远程量体,那一行删了。)

    ## 「该试而没试」往**我方**判,这也是有意的

    只写「签了字就转客方」的话,这个字段就成了一个**单向对我方有利**的东西 ——
    而一条只会往有利方向走的判据,业务不会信,也不该信。
    """
    tb = {row[0]: row for row in table()}
    kind = classify(issue)
    d = dict(问题=issue, 归类=kind, 责任=None, 处理=None, 依据=None, 判得出=False)
    if kind is None:
        d["依据"] = "归不到第五节任何一类 —— **不猜**,转人工"
        return d

    def _pick(key, why):
        row = next((r for k, r in tb.items() if key in k), None)
        if not row: return d
        d.update(责任=row[1], 处理=row[2], 依据=f"09-养护与售后.md 第五节「{row[0]}」—— {why}",
                 判得出=True)
        return d

    if kind == "工艺瑕疵":
        return _pick("工艺瑕疵", "脱线/开线/绣面脱落属工艺瑕疵")
    if kind == "尺寸偏差":
        # 签收确认合身排在最前:那是**成衣**上的顾客本人确认,比白坯试衣更靠后、更直接(业务 09-22)。
        # 工艺瑕疵不走这一支 —— 上面已经按工艺瑕疵判掉了。
        if 签收合身:
            return _pick("签收时顾客已确认试穿合身",
                         "签收时顾客本人试穿成衣、输码确认合身 —— 之后的尺寸问题顾客承担")
        if 试衣状态 == "已试已签":
            return _pick("白坯试衣已签字",
                         "他本人穿过白坯并签字确认了 —— **比量体记录硬**")
        if 试衣状态 == "该试没试":
            return _pick("该做白坯试衣而没做",
                         "这一单该做白坯试衣而没做 —— **流程没走到,是我方的**")
        if measure_full is None:
            d["依据"] = "尺寸类要先查量体记录完不完整,现在查不到 —— 转人工"
            return d
        d2 = _pick("量体记录完整且相符" if measure_full else "量体记录缺失",
                   "量体记录完整且相符" if measure_full else "量体记录缺失或不全")
        if 试衣状态 is None and d2.get("判得出"):
            # ⚠️ **没查试衣记录,不许假装这个结论是完整的。**
            # 一个「该做白坯试衣而没做」的重工单,量体记录完整时会被判成
            # **客方收费改** —— 而正确结论是我方。两者在这里长得一模一样:
            # 都是一条「量体记录完整」的记录。
            # 不改结论(那会把所有老用例judge反),而是**把缺口说出来**。
            d2["依据"] += ("。⚠️ **没查白坯试衣记录** —— "
                           "如果这是重工单且该做试衣而没做,结论应是**我方免费改**")
        return d2
    if kind == "特性类":
        if notified is None:
            d["依据"] = "特性类要先查有没有书面告知,现在查不到 —— 转人工"
            return d
        # 注意:table() 解析时已经把 ** 去掉了,这里的查找键**不能再带 **
        return _pick("且已书面告知" if notified else "但未书面告知",
                     "交付时已书面告知" if notified else "交付时未书面告知")
    return d


if __name__ == "__main__":
    fail = []
    def ck(name, cond, extra=""):
        print(f"  {'✅' if cond else '❌'} {name}{('  ' + extra) if extra else ''}")
        if not cond: fail.append(name)

    print("售后判责 · 自测\n" + "=" * 88)
    tb = table()
    print(f"\n▸ 返修判定表:{len(tb)} 行(从 09-养护与售后.md 第五节解析)")
    for r in tb: print(f"    {r[0]:32s} → {r[1]:8s} {r[2]}")
    ck("表至少 7 行", len(tb) >= 7, f"实际 {len(tb)}")

    print("\n▸ 归类")
    ck("脱线 → 工艺瑕疵", classify("下摆开线") == "工艺瑕疵")
    ck("起球 → 特性类", classify("面料起球") == "特性类")
    ck("没见过的问题不猜", classify("客户说不好看") is None)

    print("\n▸ 判责")
    a = judge("盘扣脱线")
    ck("工艺瑕疵 → 我方免费返修", a["责任"] == "我方" and "免费返修" in a["处理"], str(a["处理"]))
    b = judge("尺寸需调整", measure_full=True)
    ck("尺寸偏差 + 记录完整 → 客方收费改", b["责任"] == "客方", str(b["责任"]))
    c2 = judge("尺寸需调整", measure_full=False)
    ck("尺寸偏差 + 记录不全 → 我方免费改", c2["责任"] == "我方", str(c2["责任"]))
    ck("判责表里不再有「远程量体」那一行(业务 09-22 删了)",
       not any("远程" in row[0] for row in table()), str([row[0] for row in table()])[:60])
    d1 = judge("面料起球", notified=True)
    ck("特性类已告知 → 无责", d1["责任"] == "无责", str(d1["责任"]))
    d2 = judge("面料起球", notified=False)
    ck("特性类未告知 → 我方让步", d2["责任"] == "我方" and "让步" in d2["处理"], str(d2["处理"]))

    print("\n▸ 白坯试衣(2026-09-15 新增两行)")
    f1 = judge("尺寸需调整", measure_full=False, 试衣状态="已试已签")
    ck("试衣已签 → 客方(**压过「量体记录不全」**)", f1["责任"] == "客方", str(f1["责任"]))
    f2 = judge("尺寸需调整", measure_full=True, 试衣状态="该试没试")
    ck("该试没试 → 我方(**压过「量体记录完整」**)", f2["责任"] == "我方", str(f2["责任"]))
    f4 = judge("尺寸需调整", measure_full=True, 试衣状态="已试未签")
    ck("试了没签 → 回落到量体记录", f4["责任"] == "客方" and "试衣" not in (f4["依据"] or ""),
       str(f4["依据"])[:40])
    f5 = judge("尺寸需调整", measure_full=True)
    ck("没查试衣记录 → 判得出,但要说出这个缺口",
       f5["判得出"] and "没查白坯试衣记录" in (f5["依据"] or ""), str(f5["依据"])[-40:])

    print("\n▸ 查不到证据时不硬判")
    ck("特性类不知道有没有告知 → 判不出", not judge("面料起球")["判得出"])
    ck("尺寸类不知道记录全不全 → 判不出", not judge("尺寸需调整")["判得出"])
    ck("归不了类 → 判不出", not judge("客户说不好看")["判得出"])

    print("\n▸ 每条结论都带出处")
    ck("判得出的都带 md 出处",
       all("09-养护与售后.md" in (judge(*x)["依据"] or "")
           for x in [("盘扣脱线",), ("面料起球", True), ("面料起球", False)]))

    # ── 咬合:把 md 那张表弄坏,判责必须立刻失败而不是照旧输出 ──────────
    print("\n▸ 咬合测试")
    _bak = dict(_c)
    _c["tbl"] = [r for r in table() if "工艺瑕疵" not in r[0]]
    got = judge("盘扣脱线")
    ck("表里删掉「工艺瑕疵」那行 → 判不出而不是瞎判", not got["判得出"], str(got["责任"]))
    _c.clear(); _c.update(_bak)
    ck("咬合后表已复原", len(table()) >= 7)

    print("\n" + "=" * 88)
    # 业务 09-22:签收时顾客确认过试穿合身 → 之后的尺寸问题顾客承担;工艺瑕疵不在此列
    ck("签收确认合身后报尺寸 → 客方收费改", judge("尺寸需调整", 签收合身=True)["责任"] == "客方")
    ck("签收确认合身不管工艺瑕疵(开线仍是我方)", judge("下摆开线", 签收合身=True)["责任"] == "我方")
    ck("签收确认合身排在白坯该试没试前面", judge("尺寸需调整", 签收合身=True, 试衣状态="该试没试")["责任"] == "客方")
    ck("没传签收合身时老规则一条不变(该试没试 → 我方)", judge("尺寸需调整", 试衣状态="该试没试")["责任"] == "我方")
    if fail:
        print(f"❌ {len(fail)} 条没过:" + " / ".join(fail)); sys.exit(1)
    print(f"✅ 售后判责自测全部通过 —— 规则覆盖 {len(table())} 行,证据不足时一律不硬判")
