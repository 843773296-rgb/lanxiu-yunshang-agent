#!/usr/bin/env python3
"""售后判责 —— 从 09-养护与售后.md 第五节那张「返修判定」表推结论。

## 这块能力为什么早该有

09 那份文档第六节自己写着售后是智能体的天然落点,理由是:
「客服面对的问题**高度重复**、判定依据**是结构化的**、但结论必须由人给」。

标准写好了、决策表在库里(kb_tables 的「售后争议判定」)、
工具说明里还专门指了路(get_aftersale:「只给事实,不给判责结论」)——
**但那条路从来没人走过。** 知识资产闲置最容易被忽略,因为它不报错。

## 判责其实是可枚举的,难的是前一步

第五节那张表只有 7 行,**规则完全覆盖得住** —— 所以 V2 能做。
真正难的是**把客户那句话归到哪一类**:
「面料起球」是特性还是洗护不当?「尺寸不对」是谁的量体记录有问题?
归类要看现场(面料工艺、量体记录全不全、有没有书面告知),
这一步才是要调工具的地方。

**这是个好例子:一件事看起来需要判断,拆开之后判断只占一小段。**

## 一条判据原来落不了地

第五节写着「特性类**且已书面告知** → 无责」「**未**书面告知 → 我方让步」,
但库里原本没有任何字段记「告知过没有」——**所以那两行永远跑不到**。
这次补了 `delivery_notice` 表。和当初「体型特征」的情况一模一样:
**文档里写着的判据,如果数据里没有对应字段,它就只是一句话。**
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
MD = os.path.join(HERE, "09-养护与售后.md")
_c = {}


# ── 咬合记录 ──────────────────────────────────────────────────────────
# 左边「改坏了什么」,右边「预期红的那一条」。**每一条都在 tools/bite_specs.json 里
# 有一份可执行的规格**,`python3 tools/bite_run.py` 能重放:对照要先绿,改坏之后
# 要红,而且红的必须是右边这一条 —— 三关缺一关,这条记录就不算数。
咬合 = [
    ('把判定表里「脱线」那一行的责任方从我方改成客方',
     '工艺瑕疵 → 我方免费返修'),
]

def _md():
    if "t" not in _c: _c["t"] = open(MD, encoding="utf-8").read()
    return _c["t"]


def table():
    """第五节「返修判定」:情形 → (责任, 处理, 来路)。从 md 解析,不在代码里另存一份。"""
    if "tbl" in _c: return _c["tbl"]
    t = _md()
    seg = t.split("## 五、返修判定", 1)[-1].split("\n## ", 1)[0]
    out = []
    for line in seg.split("\n"):
        l = line.strip()
        if not l.startswith("|") or l.startswith("|---") or "情形" in l: continue
        col = [x.strip().replace("**", "") for x in l.strip("|").split("|")]
        # 第四列是**来路**(`demo` / `业务 09-24` 这类)—— 2026-09-24 加的:
        # 整张表标一个 demo,等于把「业务已经逐条定了的」和「还没人认领的」压成同一个字。
        # 判定只用前三列,来路单独给出去(说判责结论时要能说清这一行是谁定的)。
        if len(col) in (3, 4): out.append(tuple(col[:3]) + (col[3] if len(col) == 4 else "demo",))
    if len(out) < 5:
        raise RuntimeError(f"返修判定表没解析出来(只拿到 {len(out)} 行)—— md 表格格式变了?")
    _c["tbl"] = out
    return out


# issue → 大类。**这一步是归类,不是判责** —— 判责在下面那张表里。
# ── 量体记录「完整 / 不全」的分界 ────────────────────────────────────
#
# 09 号文件第五节把「尺寸偏差」分成两行:
#
#     量体记录**完整且相符** → 客方,收费改
#     量体记录**缺失/不全**  → 我方,**免费改**
#
# 一条收钱一条不收钱,而 md 里**没有写几项才算完整** ——
# 那个数(4)原来只活在 `backend/seed.py` 的真值生成里,
# 知识库和这个口径模块**一个字都没有**。
#
# 违反的是这个项目的第一条规矩:**口径进 `knowledge/`,工具只取数**。
# 代价 2026-09-15 真跑时兑现了:`get_maintain` 只给「条数 3」,
# 模型把它读成「数据完整且可信度高」,判成**客方收费改** ——
# 责任判反、钱收反,而它没有任何办法知道该有几项。
#
# ⚠️ **这个 4 是 demo 级的**(和整份 09 一样)。真实项目要由售后负责人定,
# 而且大概率不是一个固定数字,是「关键尺寸有没有量全」。
# 写在这儿是为了**让它只有一个来源**,不是为了假装它有依据。
完整门槛 = 4
完整门槛_依据 = ("09-养护与售后.md 第五节只写了「完整 / 不全」两行,没写几项算完整。"
                "这个数是 demo 级的,真实项目须由售后负责人定 —— "
                "而且大概率该按「关键尺寸有没有量全」判,不是按条数。")


def 量体完整(项数):
    """够不够「完整」。返回 (完整吗, 一句人话)。"""
    齐 = (项数 or 0) >= 完整门槛
    return 齐, (f"{项数}/{完整门槛} 项,"
                + ("**完整**(09 第五节第 2 行:客方,收费改)" if 齐 else
                   "**不全**(09 第五节第 3 行:**我方,免费改**)"))


KIND = {
    "盘扣脱线": "工艺瑕疵", "下摆开线": "工艺瑕疵",
    "刺绣局部脱落": "工艺瑕疵", "拉链损坏": "工艺瑕疵",
    "尺寸需调整": "尺寸偏差",
    "面料起球": "特性类", "染色不均": "特性类",
}
FEATURE_WORDS = ("色差", "掉色", "勾丝", "起球", "染色不均", "褪色", "手工痕迹")


def classify(issue):
    """把客户报的问题归到大类。归不出来就返回 None —— **不猜**。"""
    if issue in KIND: return KIND[issue]
    if any(w in (issue or "") for w in FEATURE_WORDS): return "特性类"
    return None


# ── 尺寸公差(业务 2026-09-24 定,原样见 业务决策/业务拍板-20260924.md)──────
# 只有这三行是业务逐条定的,其余按**同类默认**;认不出的部位返回 None → 判不了,**不猜**。
公差_业务定 = {"领围": 1.0, "胸围": 1.5, "腰围": 1.5, "衣长": 2.0, "裙长": 2.0, "通袖长": 2.0}
公差_同类默认 = {"围度": 1.5, "长度": 2.0}
围度类 = ("领围", "胸围", "腰围", "臀围", "胸上围", "臂围")
长度类 = ("衣长", "裙长", "通袖长", "袖长", "裤长")
举证期月数 = 6                      # 签收起 6 个月内证据不全 → 默认我方(业务 2026-09-24)
# 送不送第三方检测(业务 2026-09-24):**平时不送**,按「有没有书面告知」判;
# 只有走到专项那一档(谈不拢,或我方要出的钱超过授权档上限)才送 —— 和授权档合并,不另开流程。
# 代价业务知情:我们用的是**程序性**判据(说没说过),行业用**实体性**判据(到底合不合格),
# 「告知过了但面料确实不合格」这种情况,在走到专项之前判不出来。
送检 = "只在专项那一档送(谈不拢,或我方支出超过授权上限)"
授权档 = (1000, 5000)               # ≤1000 店长定;1000–5000 报总部;>5000 走专项


def 公差(部位):
    """这个部位差多少还算正常。返回 (厘米数 or None, 出处)。**认不出就返回 None** —— 不猜。"""
    b = str(部位 or "").strip()
    if b in 公差_业务定:
        return 公差_业务定[b], "业务 2026-09-24 定"
    if b in 围度类:
        return 公差_同类默认["围度"], "按同类(围度)默认,业务没逐条定"
    if b in 长度类:
        return 公差_同类默认["长度"], "按同类(长度)默认,业务没逐条定"
    return None, f"「{b or '没说部位'}」不在公差表里 —— 判不了,转人工"


def 超公差(尺寸差):
    """实测和量体差了多少 → 超没超公差。

    尺寸差  {部位: 差多少厘米(取绝对值)},比如 {"腰围": 4}
    返回 (超没超, 一句人话)。**有一个部位认不出就返回 (None, …)** —— 宁可判不了,不猜。
    """
    if not 尺寸差:
        return None, "没量成衣和量体的差 —— 这一支判不了"
    超, 内 = [], []
    for 部位, 差 in 尺寸差.items():
        允, 出处 = 公差(部位)
        if 允 is None:
            return None, f"{出处}"
        d = abs(float(差))
        (超 if d > 允 else 内).append(f"{部位}差 {d:g}cm(允许 ±{允:g})")
    if 超:
        return True, "超出公差:" + "、".join(超) + " —— 我方做错,免费返修"
    return False, "都在公差内:" + "、".join(内) + " —— 要改的话收费改"


def 在举证期内(签收于, 今天):
    """签收起 举证期月数 个月内吗。返回 (在不在, 一句人话);时间不知道返回 (None, …)。"""
    import datetime as _dt
    def _d(s):
        try:
            return _dt.date.fromisoformat(str(s)[:10])
        except (TypeError, ValueError):
            return None
    签, 今 = _d(签收于), _d(今天)
    if not 签 or not 今:
        return None, "不知道什么时候签收的 —— 举证期算不出来"
    天 = (今 - 签).days
    限 = 举证期月数 * 30
    if 天 <= 限:
        return True, f"签收 {天} 天(不满 {举证期月数} 个月)—— 证据不全时默认我方"
    return False, f"签收已 {天} 天(超过 {举证期月数} 个月)—— 要顾客拿得出依据"


def 谁能拍板(我方支出):
    """免费返修 / 赔付这类**我方支出**,谁有权定。返回 (谁, 一句人话)。"""
    try:
        钱 = float(我方支出 or 0)
    except (TypeError, ValueError):
        return None, "金额说不清 —— 先把预估费用算出来"
    小, 大 = 授权档
    if 钱 <= 小:
        return "店长", f"我方出 ¥{钱:g},在店长权限内(≤{小})"
    if 钱 <= 大:
        return "总部", f"我方出 ¥{钱:g},超过店长权限({小}–{大} 要报总部)—— 报了才能开工"
    return "专项", (f"我方出 ¥{钱:g},超过 {大} —— 走专项处理,店长和总部都不能直接定;"
                   "面料合不合格有争议的,**这一档才送第三方检测**(业务 2026-09-24)")


def judge(issue, notified=None, measure_full=None, 试衣状态=None, 签收合身=None,
          尺寸差=None, 签收于=None, 今天=None):
    """按第五节判责。返回 dict,判不出来时 rule=None(交给人/模型)。

    notified      特性类才用:交付时有没有**书面告知**过这一条
    measure_full  尺寸类才用:量体记录是否完整且相符
    签收合身       尺寸类才用:交付签收时顾客本人试穿、输码确认过合身(业务 09-22:之后的尺寸问题顾客承担)
    尺寸差         尺寸类才用:{部位: 差多少厘米},实测成衣和量体的差。**业务 09-24:超公差我方免费返修,
                  而且这一支排在「签收确认合身」前面** —— 顾客当场觉得合身,和我们做得对不对,是两回事
    签收于 / 今天   尺寸类才用:证据不全时按举证时间窗判(业务 09-24:签收起 6 个月内默认我方)
    试衣状态       尺寸类才用,取值见 `muslin.状态`:
                  已试已签 / 该试没试 / 已试未签 / 不必试

    ## 白坯试衣优先于量体记录,**这是有意的**

    两者说的不是一件事:

        量体记录  「**我们**量得对不对」
        试衣签字  「**他本人穿过**并且认可了」

    一个人到店穿过白坯、当场确认合身并签了字,之后再说尺寸不对,
    **这时候量体记录全不全已经不重要了** —— 他自己验收过。
    (原来还有一行「远程量体 → 按合同分担」,2026-09-22 业务定不准远程量体,那一行删了。)

    ## 「该试而没试」往**我方**判,这也是有意的

    只写「签了字就转客方」的话,这个字段就成了一个**单向对我方有利**的东西 ——
    而一条只会往有利方向走的判据,业务不会信,也不该信。
    """
    tb = {row[0]: row for row in table()}
    kind = classify(issue)
    d = dict(问题=issue, 归类=kind, 责任=None, 处理=None, 规则行=None, 依据=None, 判得出=False)
    if kind is None:
        d["依据"] = "归不到第五节任何一类 —— **不猜**,转人工"
        return d

    def _pick(key, why):
        row = next((r for k, r in tb.items() if key in k), None)
        if not row: return d
        # **命中的是哪一行要报出来**:同一个「尺寸偏差 · 我方」现在对应三行(超公差 / 记录不全 /
        # 证据不全+6 个月内),下游再按(归类, 责任)反推就会推错(2026-09-24 V2 当场判错 3 条)
        d.update(责任=row[1], 处理=row[2], 规则行=row[0],
                 依据=f"09-养护与售后.md 第五节「{row[0]}」—— {why}", 判得出=True)
        return d

    if kind == "工艺瑕疵":
        return _pick("工艺瑕疵", "脱线/开线/绣面脱落属工艺瑕疵")
    if kind == "尺寸偏差":
        # **实测超没超公差排在最前**(业务 2026-09-24 当天追问后定):
        # 顾客签收时点过「试穿合身」、一个月后量出腰围小了 4cm —— 仍然我方免费返修。
        # 业务的说法:「顾客当场觉得合身」和「我们做得对不对」是两回事,公差是我们对自己手艺的承诺。
        # ⚠️ 这一条**削弱了 09-22 那条签收确认**,是有意的,代价业务认了(见 09 md 五之二)。
        # 量不出来(没给尺寸差、或者部位认不出)时**不拦着往下判** —— 判不了的那一支在最后。
        超, 话 = 超公差(尺寸差)
        if 超 is True:
            return _pick("实测超出公差", 话)
        if 超 is False:
            return _pick("实测在公差内", 话)
        # 签收确认合身排在量体记录之前:那是**成衣**上的顾客本人确认,比白坯试衣更靠后、更直接(业务 09-22)。
        # 工艺瑕疵不走这一支 —— 上面已经按工艺瑕疵判掉了。
        if 签收合身:
            return _pick("签收时顾客已确认试穿合身",
                         "签收时顾客本人试穿成衣、输码确认合身 —— 之后的尺寸问题顾客承担")
        if 试衣状态 == "已试已签":
            return _pick("白坯试衣已签字",
                         "他本人穿过白坯并签字确认了 —— **比量体记录硬**")
        if 试衣状态 == "该试没试":
            return _pick("该做白坯试衣而没做",
                         "这一单该做白坯试衣而没做 —— **流程没走到,是我方的**")
        if measure_full is not True:
            # **证据不全 = 记录不全(False)或者连查都查不到(None)**,两种都走举证时间窗(业务 2026-09-24)。
            # 原来「记录不全 → 我方免费改」是**无限期**的:三年后来说尺寸不对一样判我方。
            # 加了时间窗之后,**超过 6 个月的不再自动算我方**,要顾客拿得出依据 ——
            # 拿不出仍然是**判不了**,不自动判给顾客(一条只会往有利方向走的判据,业务不会信)。
            在, 话 = 在举证期内(签收于, 今天)
            缺 = "量体记录不全" if measure_full is False else "量体记录查不到"
            if 在 is True:
                return _pick("量体记录缺失/不全", f"{缺};{话}")
            if 在 is False:
                d["依据"] = f"{缺},而且{话} —— 转人工,别直接判给顾客"
                return d
            # 不知道什么时候签收的:沿用时间窗之前的老行为
            if measure_full is False:
                return _pick("量体记录缺失/不全", "量体记录不全,又不知道什么时候签收的 —— 按老规矩我方免费改")
            d["依据"] = "尺寸类要先查量体记录完不完整,现在查不到 —— 转人工"
            return d
        d2 = _pick("量体记录完整且相符" if measure_full else "量体记录缺失",
                   "量体记录完整且相符" if measure_full else "量体记录缺失或不全")
        if 试衣状态 is None and d2.get("判得出"):
            # ⚠️ **没查试衣记录,不许假装这个结论是完整的。**
            # 一个「该做白坯试衣而没做」的重工单,量体记录完整时会被判成
            # **客方收费改** —— 而正确结论是我方。两者在这里长得一模一样:
            # 都是一条「量体记录完整」的记录。
            # 不改结论(那会把所有老用例judge反),而是**把缺口说出来**。
            d2["依据"] += ("。⚠️ **没查白坯试衣记录** —— "
                           "如果这是重工单且该做试衣而没做,结论应是**我方免费改**")
        return d2
    if kind == "特性类":
        if notified is None:
            d["依据"] = "特性类要先查有没有书面告知,现在查不到 —— 转人工"
            return d
        # 注意:table() 解析时已经把 ** 去掉了,这里的查找键**不能再带 **
        return _pick("且已书面告知" if notified else "但未书面告知",
                     "交付时已书面告知" if notified else "交付时未书面告知")
    return d


if __name__ == "__main__":
    fail = []
    def ck(name, cond, extra=""):
        print(f"  {'✅' if cond else '❌'} {name}{('  ' + extra) if extra else ''}")
        if not cond: fail.append(name)

    print("售后判责 · 自测\n" + "=" * 88)
    tb = table()
    print(f"\n▸ 返修判定表:{len(tb)} 行(从 09-养护与售后.md 第五节解析)")
