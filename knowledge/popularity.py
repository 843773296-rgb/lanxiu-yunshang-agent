# -*- coding: utf-8 -*-
"""**受欢迎程度**与**易损程度** —— 给版师的打版依据。

业务 2026-09-18 提的:
> 订单需要能够统计出当月最受欢迎的商品,并需要分析版型、花型、布料等内容
> 对于**受欢迎程度**的影响,给予打版师打版依据。
> 并且需要统计维保单,判断哪些面料、款式更容易受损、更需要维保。

⚠️ 业务当场纠正过一次:**「不是对售价的影响,而是受欢迎程度」**。
这条纠正很要紧 —— 售价是商家定的,受欢迎是客户投的票,
**前者能被一次调价改掉,后者不能**,给版师看的必须是后者。

---

## 一、三个口径,以及为什么不能只给一个

### 1.1 受欢迎:**件数**和**金额**是两回事,都要给

    件数   卖出去几件      —— 打版的**工作量**跟着它走
    金额   卖出去多少钱     —— 打版的**价值**跟着它走

一件卖 3 件的重工和一件卖 30 件的常服,**按件数排是后者赢,按金额排可能是前者**。
只给一个口径,版师会照着它把另一边的活漏掉。所以两个都给,并列排,不合成一个分数。

> 合成分数(比如 0.6×件数 + 0.4×金额)看着高级,但**权重是谁定的没人知道**,
> 而排名一旦变了,没人说得清是数据变了还是权重变了。**不合成。**

### 1.2 「当月」只数**算数的单**

取消的单不算 —— 客户下了又退,不构成「受欢迎」。
退货退款的也不算,理由同上。**未完成的算**:钱付了、在做,那就是投过票了。

    算数    待生产 · 生产中 · 已生产 · 待发货 · 已发货 · 待完成 · 完成 · 待审核 · 待付款
    不算    取消
    另扣    这一单后来发生过退货退款 / 换货的,扣掉那一件

⚠️ **「待付款」算不算,是个真问题。** 现在算,因为它代表了一次选择;
但如果后来大量待付款单最终取消,这个口径会偏乐观 ——
所以返回里**单独给出待付款的占比**,让看的人自己判断要不要打折扣。

### 1.3 易损:**必须用率,不能用绝对数**

「哪些面料更容易受损」如果按维保单的**绝对数**排,
排出来的是**「哪些面料卖得多」** —— 卖得多自然修得多。

    维保率 = 这个面料的维保单数 ÷ 这个面料的销售件数

**而率有它自己的陷阱:分母小的时候率会疯**。卖了 2 件修了 1 件 = 50%,
这个数字毫无意义但看起来触目惊心。所以:

- **必须同时返回分子和分母**,不许只给一个百分比
- **分母低于下限的,不给结论**,明说「样本不足」——
  不是给一个「0%」让人以为它不容易坏

---

## 二、这一层**只报相关,不报因果**

版师会拿这个决定打什么版,所以必须说清楚它能支撑什么:

    能说   「这个月云锦的马面裙卖了 18 件,是同期最多的」
    不能说 「改用云锦能让销量涨」

中间隔着的东西太多:上架时间、定价、库存、有没有被推荐位带过、季节。
**同一批数据,描述性结论是可靠的,因果性结论是编的。**

所以每个返回里都带一行 `口径说明`,写明这是相关不是因果 ——
**不是免责声明,是防止下游把它当因果用**。

## 三、上架时间不拉平,但要报出来

新品自然卖得少。拉平(比如按「上架后日均」)会引入另一个假设:
**销量在生命周期里是均匀的** —— 而汉服有明显的季节和节日峰,这个假设不成立。

所以不拉平,改成**把上架天数一起返回**,让版师自己看:
一个上架 15 天卖了 8 件的,和一个上架 200 天卖了 10 件的,**不是一回事**,
而这件事只有把两个数并排放才看得出来。
"""

# ── 口径常数。**手抄在这里,不从库里现算** ────────────────────────────
# 现算「库里出现过哪些状态」再拿去分类,是拿被测数据当口径。
不算数的订单状态 = ("取消",)

# 低于这个分母不给结论。**这个数是拍的,但它必须存在** ——
# 没有下限的话,「卖 2 件修 1 件 = 50%」会排在第一位。
易损分母下限 = 10
受欢迎分母下限 = 3


def 算数的单(状态):
    """这一单算不算进「受欢迎」。"""
    return 状态 not in 不算数的订单状态


def 受欢迎(行):
    """把订单行聚成排行。

    `行` 每条要有:spu / name / qty / total / status。
    返回**两张榜**(件数、金额),不合成一个分数 —— 权重没人定得了。
    """
    聚 = {}
    待付款件数 = 0
    总件数 = 0
    for r in 行:
        if not 算数的单(r.get("status")):
            continue
        k = r.get("spu")
        if not k:
            continue
        d = 聚.setdefault(k, {"spu": k, "名称": r.get("name"), "件数": 0, "金额": 0.0})
        q = int(r.get("qty") or 0)
        d["件数"] += q
        d["金额"] += float(r.get("total") or 0)
        总件数 += q
        if r.get("status") == "待付款":
            待付款件数 += q
    榜 = list(聚.values())
    return {
        "按件数": sorted(榜, key=lambda x: (-x["件数"], x["spu"])),
        "按金额": sorted(榜, key=lambda x: (-x["金额"], x["spu"])),
        "总件数": 总件数,
        # ⚠️ 单独给出来,让看的人自己决定要不要打折扣(见 §1.2)
        "其中待付款件数": 待付款件数,
    }


def 维度分布(行, 取维度):
    """按某个维度(形制 / 面料 / 工艺)聚合销量。

    `取维度(r)` 返回一个列表 —— 一件商品可以有多个面料选项,
    **它在每个选项下都计一次**。所以各档之和会大于总件数,这是对的,
    但**必须在返回里说明**,否则看的人会拿它当占比去算百分比。
    """
    g = {}
    for r in 行:
        if not 算数的单(r.get("status")):
            continue
        for v in 取维度(r) or []:
            d = g.setdefault(v, {"值": v, "件数": 0, "金额": 0.0, "商品数": set()})
            d["件数"] += int(r.get("qty") or 0)
            d["金额"] += float(r.get("total") or 0)
            d["商品数"].add(r.get("spu"))
    out = []
    for d in g.values():
        d["商品数"] = len(d["商品数"])
        out.append(d)
    return sorted(out, key=lambda x: (-x["件数"], x["值"]))


def 易损率(销量行, 维保行, 取维度):
    """按维度算维保率。**分子分母都返回,分母不足的不给结论。**

    `销量行` 同上;`维保行` 每条要有 spu(经 order_item → sku → spu 反查到的)。
    """
    销 = {}
    for r in 销量行:
        if not 算数的单(r.get("status")):
            continue
        for v in 取维度(r) or []:
            销[v] = 销.get(v, 0) + int(r.get("qty") or 0)
    修 = {}
    for r in 维保行:
        for v in 取维度(r) or []:
            修[v] = 修.get(v, 0) + 1

    out = []
    for v in sorted(set(销) | set(修)):
        分母, 分子 = 销.get(v, 0), 修.get(v, 0)
        条 = {"值": v, "维保单数": 分子, "销售件数": 分母}
        if 分母 < 易损分母下限:
            # **不给 0%,给「样本不足」。** 0% 会被读成「这个面料不容易坏」,
            # 而真相是「这个面料没卖几件,看不出来」——
            # **「没有证据」和「有证据说没问题」是两回事。**
            条["维保率"] = None
            条["结论"] = f"样本不足(销售 {分母} 件 < 下限 {易损分母下限}),**不给结论**"
        else:
            条["维保率"] = round(分子 / 分母, 4)
            条["结论"] = f"每卖 {分母} 件出现 {分子} 次维保"
        out.append(条)
    # 有结论的按率降序在前,样本不足的沉底 —— 但**都返回**,不隐藏
    有 = [x for x in out if x["维保率"] is not None]
    无 = [x for x in out if x["维保率"] is None]
    return sorted(有, key=lambda x: -x["维保率"]) + 无


def 差异显著吗(率表):
    """这批数据里,各档的维保率差异**够不够支撑「某某更易损」这个结论**。

    这一条是 2026-09-18 做出来之后立刻发现要补的:
    第一版跑出来,42 种面料的维保率全部挤在 **9.9%–13.6%** 这个窄带里。
    看起来像一张很专业的排行榜,**而它什么都没说** ——
    维保单是按销量比例撒下去的,所以每种面料的率必然趋同。

    > **一张排出了名次的榜,和一张有信息量的榜,长得一模一样。**
    > 版师会照着第一名去打版,而第一名和第十名之间可能只是噪声。

    判法:拿合并率 p 当基准,看有没有哪一档偏离超过两倍二项标准差。
    一档都没有 → 明说「差异不显著,不足以支撑结论」。

    **这不是统计洁癖。** 报一个不显著的第一名,比不报更糟:
    不报的话版师知道自己没依据,报了他以为自己有。
    """
    有 = [x for x in 率表 if x.get("维保率") is not None]
    if len(有) < 3:
        return {"显著": False, "说明": f"只有 {len(有)} 档有足够样本,比不出差异"}
    分子 = sum(x["维保单数"] for x in 有)
    分母 = sum(x["销售件数"] for x in 有)
    if 分母 == 0:
        return {"显著": False, "说明": "分母为零"}
    p = 分子 / 分母
    突出 = []
    for x in 有:
        n = x["销售件数"]
        噪声 = 2 * (p * (1 - p) / n) ** 0.5
        if abs(x["维保率"] - p) > 噪声:
            突出.append({"值": x["值"], "率": x["维保率"],
                        "偏离": round(x["维保率"] - p, 4),
                        "两倍噪声": round(噪声, 4)})
    if not 突出:
        lo = min(x["维保率"] for x in 有)
        hi = max(x["维保率"] for x in 有)
        return {"显著": False, "合并率": round(p, 4),
                "说明": f"{len(有)} 档的维保率全在 {lo:.1%}–{hi:.1%} 之间,"
                        f"没有一档偏离合并率 {p:.1%} 超过两倍噪声 —— "
                        f"**这批数据不足以支撑「某种面料更易损」的结论**。"
                        f"排行榜排得出来,但第一名和最后一名的差可能只是噪声。"}
    return {"显著": True, "合并率": round(p, 4), "突出的": 突出,
            "说明": f"{len(突出)} 档偏离合并率超过两倍噪声,这几档值得版师注意"}


