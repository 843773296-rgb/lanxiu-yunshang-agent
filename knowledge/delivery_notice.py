"""交付告知 —— 「交付时必须书面告知的六条」按这单商品对上哪几条印哪几条(用户 2026-11-15 下午拍)。

## 口径(用户 11-15 一张卡拍的三条)
① **只印和这单商品相关的**,对不上的商品标「没有对得上的告知项」—— 否决六条全印(一件棉麻短衫也印「金线不可水洗」,顾客当套话不看)。
② 聊天里和管理后台订单页**两处**都能起草 / 发。
③ 「发」= **记一笔「已告知」**(告知了哪几条、谁、什么渠道、什么时候),文字给顾问复制去发 —— 系统没有给顾客发消息的通道;
   **「告知过」不等于「顾客签了」**:签收照旧记在 signed_at,售后判责读的还是签收。

## ⚠️ 怎么对上的:按商品名认词,方法由数据决定
标品**没有面料 / 工艺属性**(那组属性只有定制品有),能用的只有商品名。所以每条告知配一组词,
商品名里出现就算对上,**草稿里写明凭的是哪个词**(「凭商品名里的『织金』对上第 4 条」),对错一眼看得出。
⚠️ 六条本身在 knowledge/09-养护与售后.md 第三节,标着 `demo` —— 内容业务还没核;词表也是我配的,不是业务给的。
"""
import re

# (编号, 告知原文(照抄 09 第三节), 认词正则, 排除正则 or None)
六条 = [
    (1, "草木染 / 手工染件存在批次色差,属工艺特性", r"草木染|植物染|手工染|扎染|蓝染|蜡染", None),
    (2, "香云纱颜色整体耐晒耐洗;新衣头几次清水漂洗可能有少量浮色、带薯莨特有气味,属正常", r"香云纱|莨绸|莨纱", None),
    (3, "纱罗类易勾丝,穿着与存放需避开尖锐物", r"纱罗|杭罗|素罗|花罗|绡|欧根纱|乔其纱|纱", r"香云纱|莨纱|麻纱|真丝袜"),
    (4, "金线类不可水洗", r"织金|盘金|钉金|金线|金银线", None),
    (5, "珠绣线迹会随穿着磨损,属正常消耗", r"珠绣|钉珠", None),
    (6, "手工制品允许在约定公差内存在细微差异", r"手工|手绣|手作|苏绣|湘绣|粤绣|蜀绣|缂丝|盘金", None),
]
六条出处 = "knowledge/09-养护与售后.md 第三节「交付时必须书面告知的六条」(标着 demo,业务还没核)"


def 对上(商品名):
    """→ [(编号, 原文, 凭的词)]。"""
    名 = 商品名 or ""
    出 = []
    for 号, 文, 认, 排 in 六条:
        看 = re.sub(排, "", 名) if 排 else 名      # 先把排除词抠掉再认,免得「香云纱」被当成纱罗
        m = re.search(认, 看)
        if m:
            出.append((号, 文, m.group(0)))
    return 出


def 起草(明细们, 顾问名=None):
    """明细们:[{名, 件数?}] → dict(适用 / 没对上 / 文字)。适用按编号去重,每条记下是哪几件商品、凭哪个词对上的。"""
    适用, 没对上 = {}, []
    for it in 明细们:
        hits = 对上(it.get("名"))
        if not hits:
            没对上.append(it.get("名"))
        for 号, 文, 词 in hits:
            适用.setdefault(号, dict(编号=号, 告知=文, 依据=[]))["依据"].append(f"「{it.get('名')}」里的「{词}」")
    条 = [适用[k] for k in sorted(适用)]
    if 条:
        行 = [f"{i}. {x['告知']}" for i, x in enumerate(条, 1)]
        文字 = ("您好,您订购的商品已交付。以下几点请您知悉:\n" + "\n".join(行) +
               "\n如有疑问请随时联系我" + (f"({顾问名})" if 顾问名 else "") + "。")
    else:
        文字 = None
    return dict(适用=条, 没对上的商品=没对上, 文字=文字, 出处=六条出处,
                说明=("按商品名认词对上的,每条写明凭的是哪个词;对不上的商品没有要书面告知的特性项"
                      if 条 else "这一单的商品都没有对得上的告知项 —— 不用发交付告知,也别硬凑一条"))
