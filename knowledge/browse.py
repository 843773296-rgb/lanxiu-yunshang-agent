# ── 怎么数(给查询和检查用,纯函数)───────────────────────────────────────
def 漏斗(行们):
    """一组事件行 → 按商品的浏览漏斗。行要有 customer_id / event / spu / dwell_s / order_id。

    口径(写死在这一处):
      · 浏览次数 = 「进入详情」行数;浏览人数 = 进过详情的不同客户数
      · 平均停留 = 「离开详情」那几行 dwell_s 的**中位数**(拖尾长,平均数会被挂着没看的那几次拉高)
      · 加购率 / 分享率 / 收藏率 = 加购人数 / 分享人数 / 收藏人数 ÷ 浏览人数(**按人**,一个人加购三次算一个)
      · 下单人数 = 在这件商品上有「下单」行的不同客户数;转化率 = 下单人数 ÷ 浏览人数
    浏览人数为 0 的商品不出现(**没东西可算,不是率为 0**)。
    """
    from statistics import median
    按品 = {}
    for r in 行们:
        spu = r.get("spu")
        if not spu:
            continue
        d = 按品.setdefault(spu, {"浏览次数": 0, "人": set(), "停留": [], "加购": set(), "分享": set(), "下单": set(), "收藏": set()})
        ev, cid = r.get("event"), r.get("customer_id")
        if ev == 进入详情:
            d["浏览次数"] += 1; d["人"].add(cid)
        elif ev == 离开详情 and r.get("dwell_s") is not None:
            d["停留"].append(r["dwell_s"])
        elif ev == 加购:
            d["加购"].add(cid)
        elif ev == 分享:
            d["分享"].add(cid)
        elif ev == 下单:
            d["下单"].add(cid)
        elif ev == 收藏:
            d["收藏"].add(cid)
    out = {}
    for spu, d in 按品.items():
        n = len(d["人"])
        if not n:
            continue
        out[spu] = {
            "浏览次数": d["浏览次数"], "浏览人数": n,
            "停留中位秒": int(median(d["停留"])) if d["停留"] else None,
            "加购人数": len(d["加购"]), "分享人数": len(d["分享"]), "下单人数": len(d["下单"]),
            "收藏人数": len(d["收藏"]),
            "加购率": round(len(d["加购"]) / n, 4), "分享率": round(len(d["分享"]) / n, 4),
            "收藏率": round(len(d["收藏"]) / n, 4),
            "转化率": round(len(d["下单"]) / n, 4),
        }
    return out
