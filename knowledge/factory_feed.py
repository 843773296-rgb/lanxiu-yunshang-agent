"""工厂回传的口径 —— **生产和发货是工厂回传的事实,不是门店推的状态。** 唯一源头,不碰库、不取今天。

## 业务 2026-09-22 / 09-23 定

  · 「已生产」「发货」是工厂回传数据,走供应链系统 —— 不给门店做「推进生产」的入口
  · 生产方**自有工坊和外发工厂都有**,谁接的单谁报;**不许转厂**(别家来报 → 挂异常)
  · **可以分批发货**:做好几件先发,**每个包裹独立**(件清单、快递单号、各自签收);
    订单状态是各件的汇总 —— 所以完工 / 质检 / 发出都**按件报**,不带件清单就是整单所有件
  · 工厂**可以撤回 / 更正**已报的回传(只能改时间和快递单号;要否定「完工」本身走撤回),
    **必须留日志**;撤回**不自动退订单状态**,只标作废并提醒店长(门店可能已经通知顾客了)
  · 工厂**整批延期**:更新承诺完工日,**原承诺日和延期次数留痕**,受影响的单要提醒顾问去通知顾客

现在没接真的供应链系统,由假数据工厂里的模拟工厂(fakedata/factory_sim.py)扮演它。
两边只隔着一条消息 —— 将来接真系统,拿掉模拟工厂,这一份和接收写口一行不改。

## 七种回传

    接单      工厂收到生产单,回一个承诺完工日     订单不动(之后按它判超期)
    完工      这几件缝制做完                     件 → 已完工
    质检通过  这几件质检过了、打包待发           件 → 已质检
    发出      这几件装一个包裹发往门店,**要快递单号**   件 → 已发出;**一个包裹一条**
    撤回      前面某一条报错了,撤掉             原消息作废,订单状态不动,提醒店长
    更正      前面某一条的时间 / 快递单号写错了  改那两样,别的改不了
    延期      这一批要晚                         更新承诺完工日,原承诺日留痕,提醒顾问通知顾客

## 一条回传怎么判

  重复      同一条消息号收过了;或这几件这一步已经收过(工厂换个号重发)—— **只记一次,订单不再动**
  挂异常    查无此单 / 单已取消 / 别家报这张单(不许转厂)/ 车间工单还在制却报完工 —— **不动订单**
  拒收      不是定制单 / 不认识的回传 / 缺必填 / 时间晚于今天 / 时间早于上一步 /
            件不属于这张单 / 这次报的几件进度不齐(要分开报)/ 更正想改时间和单号以外的东西
  暂存      **来早了**:这几件还没到这一步的前一档(还没完工就先来了质检)——
            不拒,先存着,等前一条到了再放行。网络上消息乱序是常态,拒了就丢了
  收下      这几件正好在前一档,时间也对 → 件往前推一档,订单按**所有件**汇总

**判不清就不推。** 和开裁、下单那几道闸同一条:判不了不等于可以。
"""

