# -*- coding: utf-8 -*-
"""工厂回传的口径 —— **生产和发货是工厂回传的事实,不是门店推的状态。** 唯一源头,不碰库、不取今天。

## 业务 2026-09-22 定

  「已生产」「发货」应该是工厂回传数据,走供应链系统 —— 不给门店做「推进生产」的入口。
  我们系统**只接收、核对、落状态**;回传没来的时候,提醒顾问去催。

现在没接真的供应链系统,由假数据工厂里的模拟工厂(fakedata/factory_sim.py)扮演它。
两边只隔着一条消息 —— 将来接真系统,拿掉模拟工厂,这一份和接收写口一行不改。

## 四种回传

    接单        工厂收到生产单,回一个承诺完工日     订单不动(之后按它判超期)
    完工        缝制做完                           生产中 → 已生产
    质检通过    质检过了、打包待发                  已生产 → 待发货
    发出        发往门店,**要物流单号**            待发货 → 已发货(工厂发往门店,不是寄给顾客)

## 一条回传怎么判

  重复      同一条消息号收过了;或这张单这一步已经收过(工厂换个号重发)—— **只记一次,订单不再动**
  挂异常    查无此单 / 单已取消(工厂还在做一张取消了的单,要人去处理)—— **不动订单**
  拒收      不是定制单 / 不认识的回传 / 缺必填(发出没物流单号、接单没承诺日)/
            时间晚于今天 / 时间早于上一步(完工比开裁还早)
  暂存      **来早了**:订单还没走到这一步的前一档(还没完工就先来了质检通过)——
            不拒,先存着,等前一条到了再放行。网络上消息乱序是常态,拒了就丢了
  收下      订单正好在这一步的前一档,时间也对 → 推到下一档

  挂异常(续)别家报这张单的进度(接单的是甲厂、报完工的是乙厂);车间工单还在制却报完工

**生产方两种都有**(业务 09-22):自有工坊、外发工厂。**谁接的单谁报** —— 自有工坊也走同一个收件箱,
报的时候写「自有工坊」;接收这一半不分两套。

**判不清就不推。** 和开裁、下单那几道闸同一条:判不了不等于可以。
"""

咬合 = [
    ("让 判一条() 对同一步换了消息号的重发也收下(订单会被推两次)", "同一步换个号重发 → 重复"),
    ("让 判一条() 把「来早了」的回传直接收下(跳档)", "来早了 → 暂存,不推"),
    ("让 判一条() 不查时间晚于今天", "时间晚于今天 → 拒收"),
    ("让 判一条() 不查是不是接单那家报的", "别家报这张单的完工 → 挂异常"),
]

# 事件 → (要求订单现在在哪一档, 推到哪一档, 必填字段)
事件 = {
    "接单":     (None,     None,     ("承诺完工日",)),
    "完工":     ("生产中", "已生产", ()),
    "质检通过": ("已生产", "待发货", ()),
    "发出":     ("待发货", "已发货", ("物流单号",)),
}
# 定制单的档位顺序 —— 判「来早了」还是「已经过了」
档序 = ["待确认", "待付款", "待审核", "待生产", "生产中", "已生产", "待发货", "已发货", "待完成", "完成"]


自有工坊 = "自有工坊"


def 判一条(消息, 订单, 收过的消息号, 收过的步, 今天, 接单方=None, 车间在制=False):
    """一条回传该怎么处理。返回 (结论, 一句人话, 推到哪一档或 None)。

    消息         {消息号, 订单号, 事件, 时间, 物流单号?, 承诺完工日?}
    订单         None(查无此单)或 {类型, 状态, 上一步时间} —— 上一步时间:开裁(没有就审核)/ 完工 / 质检
    收过的消息号  已经收下或判过的消息号集合
    收过的步      这张单已经收下的事件集合
    今天         演示世界的今天(调用方给,这里不取)
    接单方       这张单收下的「接单」是谁发的(自有工坊 / 某家工厂);还没接单是 None
    车间在制     这张单还有没做完的车间工单(绣片、手绘这类自有工坊的活)
    """
    号, 事 = str(消息.get("消息号") or ""), 消息.get("事件")
    if 号 and 号 in 收过的消息号:
        return "重复", f"消息 {号} 已经收过 —— 只记一次", None
    if 订单 is None:
        return "挂异常", f"查无此单 {消息.get('订单号')} —— 工厂那边的单号可能录错了,要人去核", None
    if 订单.get("状态") == "取消":
        return "挂异常", "这张单已经取消,工厂还在回传 —— 要人去通知工厂停做 / 处理料", None
    if 订单.get("类型") != "定制品订单":
        return "拒收", "标品不走工厂回传", None
    if 事 not in 事件:
        return "拒收", f"不认识的回传「{事}」", None
    前档, 后档, 必填 = 事件[事]
    缺 = [k for k in 必填 if not 消息.get(k)]
    if 缺:
        return "拒收", f"「{事}」缺 {'、'.join(缺)}", None
    t = str(消息.get("时间") or "")
    if not t:
        return "拒收", "回传没带时间", None
    if t[:10] > str(今天)[:10]:
        return "拒收", f"回传时间 {t} 晚于今天 {今天} —— 已经发生的事不会在未来", None
    if 事 in 收过的步:
        return "重复", f"这张单「{事}」已经收过一次(工厂换了个消息号重发)—— 只记一次", None
    # **按分钟比。** 工厂报的时间只到分钟,我们系统记的开裁时间带秒 —— 直接比字符串,
    # 同一分钟的「19:19」会排在「19:19:05」前面,被判成倒挂(重建时造旅程的 31 条接单全栽在这)
    上 = str(订单.get("上一步时间") or "")
    if 上 and t[:16] < 上[:16]:
        return "拒收", f"「{事}」时间 {t} 早于上一步 {上} —— 时间倒挂", None
    # **谁接的单谁报**(业务 09-22:自有工坊和外发工厂都有)—— 别家报这张单的进度,要人去核
    if 事 != "接单" and 接单方 and 消息.get("工厂") and 消息.get("工厂") != 接单方:
        return "挂异常", f"这张单是「{接单方}」接的,报「{事}」的却是「{消息.get('工厂')}」—— 要人去核", None
    # **车间工单没做完,衣服缝不完** —— 报完工说明要么车间忘了结单、要么报错了,都要人看
    if 事 == "完工" and 车间在制:
        return "挂异常", "这张单还有车间工单在制(绣片 / 手绘没交),却报了完工 —— 要人去核", None
    if 前档 is None:                                     # 接单:不动订单
        return "收下", f"工厂接单,承诺 {消息.get('承诺完工日')} 完工", None
    现 = 订单.get("状态")
    if 现 == 前档:
        return "收下", f"「{事}」→ 订单从「{前档}」到「{后档}」", 后档
    if 现 in 档序 and 档序.index(现) < 档序.index(前档):
        return "暂存", f"来早了:订单还在「{现}」,「{事}」要等它到「{前档}」—— 先存着,前一条到了再放行", None
    return "重复", f"订单已经是「{现}」,过了「{事}」这一步 —— 不再动", None


def 该催(状态, 承诺完工日, 接单了吗, 进生产中的时间, 今天, 回执宽限天=3):
    """生产中的单要不要提醒顾问去催。返回 (要不要, 一句人话)。

    · 进了生产中超过宽限天,工厂连接单都没回 → 催(单可能没发到工厂)
    · 过了承诺完工日还没完工 → 催,并建议顾问**先告诉顾客会晚**
    """
    import datetime as dt
    if 状态 != "生产中":
        return False, ""
    d = lambda s: dt.date.fromisoformat(str(s)[:10])
    if not 接单了吗:
        if 进生产中的时间 and (d(今天) - d(进生产中的时间)).days > 回执宽限天:
            return True, f"开工 {(d(今天) - d(进生产中的时间)).days} 天了工厂还没回接单 —— 单可能没发到工厂,去问"
        return False, ""
    if 承诺完工日 and d(今天) > d(承诺完工日):
        return True, (f"工厂承诺 {承诺完工日} 完工,已经过了 {(d(今天) - d(承诺完工日)).days} 天还没回完工 —— "
                      "去催,并先告诉顾客可能会晚")
    return False, ""


if __name__ == "__main__":
    import sys
    fail = []
    def ck(n, c, e=""):
        print(f"  {'✅' if c else '❌'} {n}{('  ' + str(e)[:90]) if e else ''}")
        if not c: fail.append(n)
    print("工厂回传口径 · 自测\n" + "=" * 80)
    今 = "2026-08-31"
    单 = lambda 状态, 上="2026-08-01 10:00", 类型="定制品订单": dict(类型=类型, 状态=状态, 上一步时间=上)
    m = lambda 事, t="2026-08-20 10:00", 号="M1", **k: dict(消息号=号, 订单号="O1", 事件=事, 时间=t, **k)
    ck("正常完工 → 收下,推到已生产", 判一条(m("完工"), 单("生产中"), set(), set(), 今) [::2] == ("收下", "已生产"))
    ck("同一消息号 → 重复", 判一条(m("完工"), 单("生产中"), {"M1"}, set(), 今)[0] == "重复")
    ck("同一步换个号重发 → 重复", 判一条(m("完工", 号="M2"), 单("已生产"), {"M1"}, {"完工"}, 今)[0] == "重复")
    ck("查无此单 → 挂异常", 判一条(m("完工"), None, set(), set(), 今)[0] == "挂异常")
    ck("已取消的单 → 挂异常", 判一条(m("完工"), 单("取消"), set(), set(), 今)[0] == "挂异常")
    ck("标品 → 拒收", 判一条(m("完工"), 单("生产中", 类型="标品订单"), set(), set(), 今)[0] == "拒收")
    ck("发出没物流单号 → 拒收", 判一条(m("发出"), 单("待发货"), set(), set(), 今)[0] == "拒收")
    ck("接单没承诺日 → 拒收", 判一条(m("接单"), 单("生产中"), set(), set(), 今)[0] == "拒收")
    ck("时间晚于今天 → 拒收", 判一条(m("完工", t="2026-10-01 10:00"), 单("生产中"), set(), set(), 今)[0] == "拒收")
    ck("同一分钟、一边带秒一边不带 → 不算倒挂",
       判一条(m("完工", t="2026-08-01 10:00"), 单("生产中", 上="2026-08-01 10:00:05"), set(), set(), 今)[0] == "收下")
    ck("完工早于开裁 → 拒收(时间倒挂)", 判一条(m("完工", t="2026-07-01 10:00"), 单("生产中"), set(), set(), 今)[0] == "拒收")
    g = 判一条(m("质检通过"), 单("生产中"), set(), set(), 今)
    ck("来早了 → 暂存,不推", g[0] == "暂存" and g[2] is None, g[1])
    ck("接单 → 收下,订单不动", 判一条(m("接单", 承诺完工日="2026-09-10"), 单("生产中"), set(), set(), 今)[::2] == ("收下", None))
    ck("发出带物流单号 → 推到已发货", 判一条(m("发出", 物流单号="SF1"), 单("待发货"), set(), set(), 今)[2] == "已发货")
    ck("别家报这张单的完工 → 挂异常",
       判一条(m("完工", 工厂="乙厂"), 单("生产中"), set(), set(), 今, 接单方="甲厂")[0] == "挂异常")
    ck("接单的工坊自己报完工 → 收下",
       判一条(m("完工", 工厂=自有工坊), 单("生产中"), set(), set(), 今, 接单方=自有工坊)[0] == "收下")
    ck("车间工单还在制却报完工 → 挂异常",
       判一条(m("完工", 工厂="甲厂"), 单("生产中"), set(), set(), 今, 接单方="甲厂", 车间在制=True)[0] == "挂异常")
    ck("没接单、开工 5 天 → 催", 该催("生产中", None, False, "2026-08-26", 今)[0])
    ck("没接单、开工 2 天 → 不催", not 该催("生产中", None, False, "2026-08-29", 今)[0])
    ck("过了承诺日没完工 → 催", 该催("生产中", "2026-08-25", True, "2026-08-01", 今)[0])
    ck("没过承诺日 → 不催", not 该催("生产中", "2026-09-10", True, "2026-08-01", 今)[0])
    ck("已生产的单 → 不催", not 该催("已生产", "2026-08-25", True, "2026-08-01", 今)[0])
    print()
    print("❌ 有不符预期" if fail else "✅ 工厂回传口径自测全过")
    sys.exit(1 if fail else 0)
