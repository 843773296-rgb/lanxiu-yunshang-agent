# 事件 → (这几件推到哪个进度, 必填字段)。进度是**件**的,不是订单的
事件 = {
    "接单":     (None,     ("承诺完工日",)),
    "完工":     ("已完工", ()),
    "质检通过": ("已质检", ()),
    "发出":     ("已发出", ("物流单号",)),
    "撤回":     (None,     ("原消息号",)),
    "更正":     (None,     ("原消息号",)),
    "延期":     (None,     ("承诺完工日",)),
}
件进度档 = ["在做", "已完工", "已质检", "已发出"]
# 定制单的档位顺序 —— 判订单「来早了」还是「已经过了」
档序 = ["待确认", "待付款", "待审核", "待生产", "生产中", "已生产", "待发货", "已发货", "待完成", "完成"]
自有工坊 = "自有工坊"
# 更正要改的东西写成「新时间 / 新物流单号」——
# 叫「时间」会和这条更正消息**自己的时间**撞名(自测当场撞上:一个字段两个意思)
更正能改 = {"新时间": "时间", "新物流单号": "物流单号"}


def _前一档(进度):
    return 件进度档[件进度档.index(进度) - 1]


def 判一条(消息, 订单, 收过的消息号, 收过的步, 今天, 接单方=None, 车间在制=False,
          全部件=(), 件进度=None, 原消息=None):
    """一条回传该怎么处理。返回 (结论, 一句人话, 效果)。

    效果是个 dict,调用方照着做,**这里不碰库**:
        {"件": [...], "到": "已完工"}      这几件推到这个进度
        {"作废": 消息号}                    撤回:把那条标作废
        {"改": {"时间": ..., "物流单号": ...}, "原消息号": ...}   更正
        {"新承诺完工日": "2026-10-08"}      延期
        None                                不用做什么(接单只记录)

    消息      {消息号, 订单号, 事件, 时间, 工厂?, 物流单号?, 承诺完工日?, 件?, 原消息号?}
    订单      None(查无此单)或 {类型, 状态, 上一步时间}
    收过的步  这张单已经收下的 (事件, 件) 对的集合
    全部件    这张单的全部订单行号
    件进度    {件: 进度},没给的件当「在做」
    原消息    撤回 / 更正指向的那条(None = 找不到)
    """
    件进度 = dict(件进度 or {})
    号, 事 = str(消息.get("消息号") or ""), 消息.get("事件")
    if 号 and 号 in 收过的消息号:
        return "重复", f"消息 {号} 已经收过 —— 只记一次", None
    if 订单 is None:
        return "挂异常", f"查无此单 {消息.get('订单号')} —— 工厂那边的单号可能录错了,要人去核", None
    if 订单.get("状态") == "取消":
        return "挂异常", "这张单已经取消,工厂还在回传 —— 要人去通知工厂停做 / 处理料", None
    if 订单.get("类型") != "定制品订单":
        return "拒收", "标品不走工厂回传", None
    if 事 not in 事件:
        return "拒收", f"不认识的回传「{事}」", None
    到, 必填 = 事件[事]
    缺 = [k for k in 必填 if not 消息.get(k)]
    if 缺:
        return "拒收", f"「{事}」缺 {'、'.join(缺)}", None
    t = str(消息.get("时间") or "")
    if not t:
        return "拒收", "回传没带时间", None
    if t[:10] > str(今天)[:10]:
        return "拒收", f"回传时间 {t} 晚于今天 {今天} —— 已经发生的事不会在未来", None
    # **谁接的单谁报**(业务 09-22;09-23 定:不许转厂)—— 别家报这张单的进度,要人去核
    if 事 != "接单" and 接单方 and 消息.get("工厂") and 消息.get("工厂") != 接单方:
        return "挂异常", (f"这张单是「{接单方}」接的,报「{事}」的却是「{消息.get('工厂')}」—— "
                          "业务 09-23:不许转厂,要人去核"), None

    if 事 == "接单":
        return "收下", f"工厂接单,承诺 {消息.get('承诺完工日')} 完工", None

    if 事 in ("撤回", "更正"):
        原 = str(消息.get("原消息号") or "")
        if not 原消息:
            return "拒收", f"要{事}的消息 {原} 不在收件箱里 —— 找不到就不能{事}", None
        if 原消息.get("处理") != "收下":
            return "拒收", f"消息 {原} 当时是「{原消息.get('处理')}」,不是收下的 —— 没什么可{事}的", None
        if 原消息.get("工厂") and 消息.get("工厂") and 原消息["工厂"] != 消息["工厂"]:
            return "挂异常", f"消息 {原} 是「{原消息['工厂']}」报的,来{事}的却是「{消息['工厂']}」—— 要人去核", None
        if 事 == "撤回":
            return "收下", (f"撤回消息 {原}(原报「{原消息.get('回传')}」{原消息.get('时间') or ''})—— "
                            "那条作废;**订单状态不自动退**,要不要退回由店长定"), {"作废": 原}
        改 = {更正能改[k]: 消息.get(k) for k in 更正能改 if 消息.get(k)}
        if not 改:
            return "拒收", f"更正没说要改什么 —— 只能改{'、'.join(更正能改)}", None
        乱改 = [k for k in ("件", "承诺完工日") if 消息.get(k)]
        if 乱改:
            return "拒收", (f"更正只能改{'、'.join(更正能改)},不能改 {'、'.join(乱改)} —— "
                            "要否定「完工」这件事本身,走撤回"), None
        return "收下", f"更正消息 {原}:" + "、".join(f"{k} → {v}" for k, v in 改.items()), \
               {"改": 改, "原消息号": 原}

    if 事 == "延期":
        if 订单.get("状态") not in ("待生产", "生产中"):
            return "拒收", f"这张单已经是「{订单.get('状态')}」,不在生产中 —— 延期通知对不上", None
        return "收下", (f"工厂通知延期到 {消息.get('承诺完工日')}"
                        + (f",原因:{消息.get('原因')}" if 消息.get("原因") else "")
                        + " —— 要提醒顾问去告诉顾客"), {"新承诺完工日": 消息.get("承诺完工日")}

    # ── 完工 / 质检通过 / 发出:按件报 ────────────────────────────────
    件 = [str(x) for x in (消息.get("件") or [])] or [str(x) for x in 全部件]
    if not 件:
        return "拒收", f"「{事}」不知道是哪几件 —— 这张单一件商品都没有?", None
    外 = [x for x in 件 if x not in {str(y) for y in 全部件}]
    if 外:
        return "拒收", f"件 {'、'.join(外[:3])} 不属于这张单 —— 工厂那边的行号可能录错了", None
    if 事 == "完工" and 车间在制:
        return "挂异常", "这张单还有车间工单在制(绣片 / 手绘没交),却报了完工 —— 要人去核", None
    前 = _前一档(到)
    现 = {x: 件进度.get(x, "在做") for x in 件}
    早 = [x for x, g in 现.items() if 件进度档.index(g) < 件进度档.index(前)]
    过 = [x for x, g in 现.items() if 件进度档.index(g) >= 件进度档.index(到)]
    if len(过) == len(件):
        return "重复", f"这几件的「{事}」已经收过一次(工厂换了个消息号重发)—— 只记一次", None
    if 早 and len(早) == len(件):
        return "暂存", (f"来早了:这几件还在「{现[早[0]]}」,「{事}」要等它们到「{前}」—— "
                        "先存着,前一条到了再放行"), None
    if 早 or 过:
        return "拒收", (f"这次报的 {len(件)} 件进度不齐:{len(早)} 件还没到「{前}」、{len(过)} 件已经过了 —— "
                        "**分开报**,不然一条消息说不清哪几件动了"), None
    上 = str(订单.get("上一步时间") or "")
    # **按分钟比。** 工厂报的时间只到分钟,系统记的开裁时间带秒 —— 直接比字符串,
    # 同一分钟的「19:19」会排在「19:19:05」前面,被判成倒挂(重建时造旅程的 31 条接单全栽在这)
    if 上 and t[:16] < 上[:16]:
        return "拒收", f"「{事}」时间 {t} 早于上一步 {上} —— 时间倒挂", None
    话 = f"「{事}」{len(件)} 件 → {到}" + (f"(快递 {消息.get('物流单号')})" if 事 == "发出" else "")
    return "收下", 话, {"件": 件, "到": 到}


def 订单该到哪一档(件进度, 全部件, 现状态):
    """各件的进度汇总成订单状态。返回目标档或 None(不动)。

    · **任一件发出** → 已发货(业务 09-23:包裹独立,发出一个包裹订单就算发货了;
      到不到齐看包裹签收,不看订单状态)
    · 所有件都质检过 → 待发货
    · 所有件都完工   → 已生产
    · 其余不动 —— **部分件完工不算完工**,否则一张三件的单会在做好一件时就报「已生产」
    """
    if not 全部件:
        return None
    档 = [件进度.get(str(x), "在做") for x in 全部件]
    目标 = None
    if any(g == "已发出" for g in 档):
        目标 = "已发货"
    elif all(g == "已质检" for g in 档):
        目标 = "待发货"
    elif all(g in ("已完工", "已质检") for g in 档) and all(g == "已完工" for g in 档):
        目标 = "已生产"
    if 目标 is None or 目标 == 现状态:
        return None
    if 现状态 in 档序 and 目标 in 档序 and 档序.index(目标) < 档序.index(现状态):
        return None                      # 不往回推 —— 退回只能走人工回退(业务 09-23)
    return 目标


# 回执宽限 3 天:开工 3 天工厂还没回接单就提醒去催(**业务 2026-09-23 确认**,原为提议值)
def 该催(状态, 承诺完工日, 接单了吗, 进生产中的时间, 今天, 回执宽限天=3):
    """生产中的单要不要提醒顾问去催。返回 (要不要, 一句人话)。

    · 进了生产中超过宽限天,工厂连接单都没回 → 催(单可能没发到工厂)
    · 过了承诺完工日还没完工 → 催,并建议顾问**先告诉顾客会晚**
      ⚠️ 承诺完工日按**最新的**算(业务 09-23:工厂延期后按新日子判),
      而原承诺日和延期次数由调用方留痕 —— 不然工厂可以靠不断延期把逾期永远清零
    """
    import datetime as dt
    if 状态 != "生产中":
        return False, ""
    d = lambda s: dt.date.fromisoformat(str(s)[:10])
    if not 接单了吗:
        if 进生产中的时间 and (d(今天) - d(进生产中的时间)).days > 回执宽限天:
            return True, f"开工 {(d(今天) - d(进生产中的时间)).days} 天了工厂还没回接单 —— 单可能没发到工厂,去问"
        return False, ""
    if 承诺完工日 and d(今天) > d(承诺完工日):
        return True, (f"工厂承诺 {承诺完工日} 完工,已经过了 {(d(今天) - d(承诺完工日)).days} 天还没回完工 —— "
                      "去催,并先告诉顾客可能会晚")
    return False, ""


def 能不能回退(状态, 角色, 原因, 理由):
    """人工回退(业务 2026-09-23):工厂发错件 / 到店发现要返工。返回 (能不能, 话, 退到哪一档)。

    · **只有店长能点** —— 和判责收费同一类,是要担责任的操作
    · 发错件 → 退回「待发货」(等工厂重发);到店发现要返工 → 退回「生产中」(算重新生产)
    · 必须写理由;退回后这张单一直留着「倒退过」的痕迹(调用方落日志)
    """
    退到 = {"发错件": "待发货", "到店返工": "生产中"}
    if 原因 not in 退到:
        return False, f"回退原因只能是{'、'.join(退到)},不认识「{原因}」", None
    if 角色 != "店长":
        return False, f"人工回退只有店长能点,你是「{角色}」—— 顾问负责把衣服寄回,回退由店长确认", None
    if not (理由 or "").strip():
        return False, "回退要写清为什么(哪件不对、怎么发现的)—— 不写理由的倒退,过后查不出发生过什么", None
    目标 = 退到[原因]
    if 状态 not in 档序 or 档序.index(状态) <= 档序.index(目标):
        return False, f"这张单现在是「{状态}」,不在「{目标}」之后 —— 没什么可退的", None
    return True, f"{原因}:订单从「{状态}」退回「{目标}」,运费公司承担;工厂要重新报这几步", 目标


