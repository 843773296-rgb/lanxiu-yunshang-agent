#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""购买喜好推荐的口径(用户 2026-10-10)。

用户原话:「顾客只买了红的,那么就默认红的是商机,上新红色时就可以推出是商机,可以进行推荐」;
随后:「商品归纳总结……这能力是购买喜好推荐的前提」。

所以喜好**不在这里另算一套**:把她买过的衣服交给商品归纳(knowledge/traits.py),归纳出来的「规律」
就是她的喜好 —— 颜色、纹样、面料、工艺、形制五个维度都算,判法同一个(方案 B:比全店买过的东西明显多,
至少 3 件、该值至少 2 件、2 倍以上,用户 10-10 确认)。上新的款只要对上她任意一条规律,就是一条待确认的商机。

这里只放「看多久」这一个推荐特有的数。门槛在 traits —— **两处各写一份,改了一处就漂**。
口径模块不取当前日期:今天由调用方传进来。
"""
import datetime as _dt

咬合 = [
    ("新款没对上她的规律也推", "新款一条都对不上 → 不推"),
]

回看月数 = 24        # 只看最近 24 个月买的(用户 10-10 确认的推荐值;拍脑袋的:口味会变)


def 窗口起点(今天):
    """最近 24 个月从哪天起(含)。按天数算,不按自然月 —— 月末那几天不会因为「2 月没有 30 号」算错。"""
    return 今天 - _dt.timedelta(days=round(回看月数 * 365.25 / 12))


def 对上的规律(她的规律, 新款属性):
    """她的规律(traits.归纳 的「规律」列表)里,哪几条这件新款也有。按倍数从高到低。"""
    return [x for x in 她的规律 if x["值"] in (新款属性.get(x["维度"]) or ())]


if __name__ == "__main__":
    坏 = 0
    ok = 窗口起点(_dt.date(2026, 10, 10)) == _dt.date(2024, 10, 10)
    坏 += not ok
    print(f"  {'✅' if ok else '❌'} 24 个月窗口从 2024-10-10 起")
    规 = [dict(维度="颜色", 值="红", 倍数=3.8), dict(维度="面料", 值="云锦", 倍数=8.0)]
    ok = [x["值"] for x in 对上的规律(规, {"颜色": ["红", "白"], "面料": ["真丝素罗"]})] == ["红"]
    坏 += not ok
    print(f"  {'✅' if ok else '❌'} 新款有红色、面料不是云锦 → 只对上「红」那一条")
    ok = 对上的规律(规, {"颜色": ["蓝"]}) == []
    坏 += not ok
    print(f"  {'✅' if ok else '❌'} 新款一条都对不上 → 不推")
    raise SystemExit(1 if 坏 else 0)
