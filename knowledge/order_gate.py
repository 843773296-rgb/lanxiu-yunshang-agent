# -*- coding: utf-8 -*-
"""下单前置条件的口径 —— **什么样的订单需要什么,以及什么时候判不了。**

判定写在这里,取数在 `backend/`。口径模块不碰数据库,也不取当前日期。

## 一、真正该拦的不是「没有接待任务」

交接文档里记的是「上门任务没完成也能下单」。照这个去做会**误伤每一个老客户**:
回头客本来就不用重新上门,用的是几个月前的量体数据
(实测 19 单「没有前置接待」的定制订单,客户全都有下单之前的量体记录)。

**接待任务只是取得量体数据的一种途径,不是目的。**
真正该拦的是:**定制订单,而量体数据不存在或已超期。**

`12-成长与生命周期.md` 第五节写得很硬:

> 超期的量体记录**不是「参考值」,是「无效值」** —— 下单前必须拦下。
> 「有个旧尺寸总比没有强」这个想法,正是返工的来源。

## 二、这条规则原来**执行不了**,不是没人执行

`knowledge/growth.py` 早就实现了复量周期和超期判定,
`get_wearer` 也会提示「下单前必须拦下」。但订单表上**没有着装人字段** ——
一个客户名下可以有本人和两个孩子,这一单是给谁做的,库里没记。

于是「这一单的量体过没过期」根本判不了。
**判据写在文档里,而库里没有字段承载它,那条规则就永远跑不到。**

第一次量的时候我还量错了:取「这个客户最近的量体」,
而那多半是**大人自己的**——孩子的量体停在 342 天前,被大人的新记录盖住了。

## 三、判不了要说判不了

补了 `ordr.wearer_id` 之后,仍有一部分订单填不上:
名下有多个着装人的(9 单)、查不到着装人的(10 单)。
**这些一律留空,并且单独报出来** —— 不许挑一个候选填进去。

猜一个着装人的代价是不对称的:猜对了没人知道,
猜错了这一单会拿着**另一个人的尺寸**去裁剪,而且报表上完全正常。

所以本模块的返回值有**三种**,不是两种:

    可以      前置条件齐了
    不可以    明确缺什么(没量体 / 超期)
    判不了    缺的是**判断的依据**本身(不知道给谁做)

**「判不了」不许当成「可以」。**
"""

# ── 一单是给谁做的:**商品自己说得出来** ──────────────────────────
#
# 商品有 `gender` 这一列,取值 男 / 女 / **童** / 通用。
# 这条线本来就在库里,只是没被用起来 —— 而不用它的代价是实打实的:
# 实测 560005 买的是**童装**,却挂在 32 岁的大人身上,
# 因为那个客户名下只登记了一个着装人,「名下唯一 → 直接填」就填上去了。
# 于是复量规则去查**大人**的量体,而衣服是给**孩子**做的。
# **规则跑得欢,查的是错的人。**
#
# ⚠️ 而且**一单可以给不止一个人做**(实测 7 单:两件童款加一件女款,
# 一家三口订同款)。所以着装人要挂在**订单行**上,挂在订单上表达不了。
童款 = "童"
分不出性别的 = ("通用", None, "")

# ── 品类树:比 `product.gender` 可靠,而且能回答一个更该问的问题 ──────
#
# `category` 是三级树:顶级 女装 / 男装 / **童装** / 配饰 / 面料部件,
# 二级 上装 / 裙装 / 外套。
#
# 原来只看 `product.gender`,于是「题字腰封」(配饰·腰封/腰带)报「通用款分不出」——
# **那是在用错的维度问问题**。该问的不是「给男的还是女的」,
# 是「**这件东西要不要按人裁**」。配饰和面料部件都不要:
# 腰封按长度、簪钗按款式,和三围没关系。
#
# ⚠️ 两条线会打架:实测**顶级=女装而 gender=男 的商品有 15 个**,反过来 2 个。
# **以树为准** —— 它是三级结构、有明确的 parent,而 gender 是一个平列字段,
# 填错了没有任何地方会报错。但打架的**要报出来**,不静默选一个。
不按人裁的顶级品类 = {"配饰": "按长度/款式做,和三围没关系",
                      "面料部件": "卖的是料子和绣片,不是成衣"}
顶级到性别 = {"女装": "女", "男装": "男", "童装": 童款}


def 要按人裁吗(顶级品类名):
    """这件商品要不要按着装人的尺寸裁。返回 (要不要, 理由)。"""
    why = 不按人裁的顶级品类.get(顶级品类名)
    return (why is None, why or f"「{顶级品类名}」要照着人的尺寸裁")


def 按品类定性别(顶级品类名):
    """顶级品类推出该给谁穿。认不出返回 None —— **认不出就说认不出**。"""
    return 顶级到性别.get(顶级品类名)


def 定位着装人(商品性别, 候选, 是成年, 顶级品类名=None):
    """把这一行定位到人。返回 (着装人 或 None, 理由)。

    **先看品类树,再看 `product.gender`。** 树认得出来就用树的结论,
    并且**拿 gender 交叉校验** —— 两条对不上时把这件事说出来,
    因为对不上意味着至少有一条是填错的,而填错的那条在别处也会出错。

    `候选` 是 [(id, name, gender, birthday), ...],`是成年` 是个函数(生日 → 真假)。
    判据两句话:
      · 童款  → 候选里的**未成年人**,唯一才定
      · 男/女款 → 候选里**同性别的成年人**,唯一才定
      · 通用款 → 分不出,不猜

    **唯一才定。** 两个人都对得上时返回 None —— 那是「判不了」,
    不是「挑一个」。猜错的代价不对称:这一行会拿着另一个人的尺寸去裁剪,
    而报表上完全正常。
    """
    if 顶级品类名:
        要裁, 为什么 = 要按人裁吗(顶级品类名)
        if not 要裁:
            return (None, f"「{顶级品类名}」**不按人裁** —— {为什么}。"
                          f"这一行不需要着装人,**这不是「判不了」**")
        树说 = 按品类定性别(顶级品类名)
        if 树说:
            打架 = (商品性别 not in 分不出性别的 and 商品性别 != 树说)
            商品性别 = 树说
            if 打架:
                # 不挡路,但要留痕 —— 调用方会把它报出来
                pass
    if 商品性别 in 分不出性别的:
        return (None, "品类树认不出、gender 也是通用 —— **两条线都分不出是给谁做的**")
    if 商品性别 == 童款:
        cand = [w for w in 候选 if not 是成年(w[3])]
        什么 = "未成年着装人"
    else:
        cand = [w for w in 候选 if 是成年(w[3]) and w[2] == 商品性别]
        什么 = f"{商品性别}性成年着装人"
    if len(cand) == 1:
        return (cand[0], f"{商品性别}款 → 名下唯一的{什么}")
    if not cand:
        return (None, f"{商品性别}款,但这个客户名下**没有登记{什么}** —— "
                      f"人没建档,这一行落不到任何人身上")
    return (None, f"{商品性别}款,名下有 {len(cand)} 个{什么} —— "
                  f"**唯一才定,两个都对得上就是判不了**")


需要量体的订单类型 = ("定制品订单",)
无需量体的订单类型 = ("标品订单",)   # 现货成衣,按尺码卖,不量体


def 需要量体吗(订单类型):
    """标品不需要。**写成白名单而不是「不是定制就不要」** ——
    以后新增一种订单类型时,默认落到「需要」这一边,
    **默认严比默认松安全**:漏拦一次是错尺寸,多拦一次只是多问一句。
    """
    return (订单类型 or "") not in 无需量体的订单类型


def 能不能下单(订单类型, 着装人, 量体记录, 超期判定):
    """返回 (结论, 理由)。结论是「可以」/「不可以」/「判不了」三者之一。

    参数都由调用方查好传进来 —— 这个模块不碰库:
      着装人      None 表示定位不到
      量体记录    None 表示这个着装人在下单前没有量体
      超期判定    `growth.measure_expired` 的返回值,或 None 表示算不出
    """
    if not 需要量体吗(订单类型):
        return ("可以", f"{订单类型}是现货成衣,按尺码卖,不需要量体")
    if not 着装人:
        return ("判不了", "**不知道这一单是给谁做的** —— 订单上没有着装人,"
                          "而这个客户名下不止一个人。"
                          "判不了就是判不了,**不许挑一个候选顶上** —— "
                          "猜错的话这一单会拿着另一个人的尺寸去裁剪,"
                          "而报表上完全正常")
    if not 量体记录:
        return ("不可以", f"{着装人} 在下单之前没有任何量体记录 —— "
                          f"定制不能凭空裁")
    if 超期判定 is None:
        return ("判不了", f"{着装人} 的复量周期算不出来(多半是缺生日或性别)—— "
                          f"缺的是判断的依据本身")
    if 超期判定.get("过期"):
        return ("不可以",
                f"{着装人} 的量体已过 {超期判定['已过天数']} 天,"
                f"允许 {超期判定['允许天数']} 天({超期判定['原因']})—— "
                f"**超期的记录不是参考值,是无效值**。"
                f"「有个旧尺寸总比没有强」正是返工的来源")
    return ("可以", f"{着装人} 的量体在有效期内"
                    f"({超期判定['已过天数']}/{超期判定['允许天数']} 天)")
