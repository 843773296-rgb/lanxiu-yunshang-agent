# -*- coding: utf-8 -*-
"""客户归属保护期 —— 跨店成交时整户转不转(用户 2026-11-11 拍,一张卡三问 + 开会前一张卡)。

用户原话 / 选项:
  · 保护期 **180 天**
  · 「还在维护」= **在原店消费,或原导购有跟进记录**;保护期从**最后一次维护**那天起算
  · 过了保护期、在别店成交 → **整户自动转给这一单的接待导购**,通知原导购和两家店长;有异议走「客户转移」审批转回
  · 接待导购为空 → 先不转,给新店店长派「指定导购」
  · **历史的先不管,继续原本导购维护** —— 只在上线以后的付款上判
  · 业内做法(给用户看过):业绩归成交店,归属**不随一次跨店消费转**,过保护期才转

同时定掉 09-20 预约分配决策清单 P11(长期没接触的归属要不要释放、保护期多长)。

**这里只判,不取今天、不读库**(规矩 ①:口径模块不自己取当前日期)。数据由 backend/ownership_transfer.py 取好传进来。
边界含端:最后维护后第 180 天成交仍在保护期(不转),第 181 天才转 —— 和生命周期「第 180 天仍是休眠」同一种含端写法。
"""
import datetime as _dt

保护期天 = 180


def _日(x):
    if x is None or x == "":
        return None
    if isinstance(x, _dt.datetime):
        return x.date()
    if isinstance(x, _dt.date):
        return x
    try:
        return _dt.date.fromisoformat(str(x)[:10])
    except ValueError:
        return None


def 最后维护日(原店付款日们=(), 原导购跟进日们=(), 原店到店日们=(), 建档日=None):
    """→ (日期 或 None, 来自哪一类)。三类里取最晚的;三类都没有 → 退回建档日(从没维护过,保护期从建档起算)。"""
    候 = [(d, 类) for 类, 们 in (("原店消费", 原店付款日们), ("原导购跟进", 原导购跟进日们), ("原店到店", 原店到店日们))
         for d in (_日(x) for x in 们) if d]
    if 候:
        d, 类 = max(候)
        return d, 类
    d = _日(建档日)
    return (d, "建档") if d else (None, "无")


def 该转吗(档案店, 成交店, 原导购, 接待导购, 最后维护, 成交日, 保护期天=保护期天):
    """→ dict(转: bool, 要指定导购: bool, 理由: str, 已过天数: int|None)。纯函数。
    · 同店成交 / 接待导购就是原导购 → 不转(不是跨店)
    · 还在保护期(成交日 − 最后维护 ≤ 保护期天)→ 不转,只是业绩归成交店
    · 过了保护期、有接待导购 → 转给接待导购
    · 过了保护期、没有接待导购 → 不转,要新店店长指定导购
    · 最后维护日判不出来 → **不转**(拿不准就不动别人的客户)"""
    成 = _日(成交日); 维 = _日(最后维护)
    if not 档案店 or not 成交店 or 档案店 == 成交店:
        return dict(转=False, 要指定导购=False, 理由="同店成交,不是跨店", 已过天数=None)
    if 接待导购 and 原导购 and 接待导购 == 原导购:
        return dict(转=False, 要指定导购=False, 理由="接待导购就是原导购", 已过天数=None)
    if not 成 or not 维:
        return dict(转=False, 要指定导购=False, 理由="最后一次维护的日子判不出来 —— 拿不准就不转", 已过天数=None)
    天 = (成 - 维).days
    if 天 <= 保护期天:
        return dict(转=False, 要指定导购=False, 已过天数=天,
                    理由=f"还在保护期(最后维护 {维},到成交 {天} 天 ≤ {保护期天} 天)—— 归属不转,业绩归成交店")
    if not 接待导购:
        return dict(转=False, 要指定导购=True, 已过天数=天,
                    理由=f"已过保护期({天} 天 > {保护期天} 天),但这一单没有接待导购 —— 要新店店长指定导购后再转")
    return dict(转=True, 要指定导购=False, 已过天数=天,
                理由=f"已过保护期(最后维护 {维},到成交 {天} 天 > {保护期天} 天)—— 整户转给这一单的接待导购")


# ── 长期没人接触 → 释放到公海(用户 2026-11-12 拍,台账第十四条)──────────────────────────
# 上面那条管「跨店成交过了保护期才转」;这条管**没有成交、只是长期没人接触**的客户:
#   · 最后一次接触(本店消费 / 原导购跟进 / 本店到店)后满 180 天 → 整户释放到本店公海,店长指派
#   · 释放前 7 天(第 173 天起)先知会原导购;原导购在这 7 天里联系了并登记跟进 → 最后接触日刷新,自然不放
#   · 判不出最后接触日 → 不放(拿不准就不动别人的客户,和上面同一个保守方向)
# 边界含端:第 180 天当天仍归原导购,第 181 天才放 —— 和保护期、生命周期同一种含端写法。
# 11-11 的说明里写「同时定掉 P11」—— 那次定的是保护期多长,**没定要不要自动释放**;11-12 用户在卡上选了「180 天释放、提前 7 天知会」,以这条为准。
释放天 = 180
知会提前天 = 7


def 该放吗(最后接触, 今天, 已知会日=None, 释放天=释放天, 知会提前天=知会提前天):
    """→ dict(动作: '不动' | '知会' | '释放', 已过天数: int|None, 理由: str)。纯函数,不取今天、不读库。
    已知会日:上次知会原导购的日子(没知会过 = None)。**没知会过的不许直接释放** —— 哪怕已经过了 180 天,
    也先知会、再等 7 天(上线第一天一大批「早过了 180 天」的客户不能一夜之间全被收走)。"""
    维 = _日(最后接触); 今 = _日(今天); 知 = _日(已知会日)
    if not 维 or not 今:
        return dict(动作="不动", 已过天数=None, 理由="最后一次接触的日子判不出来 —— 拿不准就不放")
    天 = (今 - 维).days
    if 天 < 释放天 - 知会提前天:
        return dict(动作="不动", 已过天数=天, 理由=f"最后接触 {维},才过 {天} 天(第 {释放天 - 知会提前天} 天起才知会)")
    if 知 is None or 知 < 维:
        return dict(动作="知会", 已过天数=天,
                    理由=f"最后接触 {维},已过 {天} 天 —— 先知会原导购:{知会提前天} 天内联系并登记跟进就保留,否则释放到公海")
    if (今 - 知).days < 知会提前天 or 天 <= 释放天:
        return dict(动作="不动", 已过天数=天, 理由=f"{知} 已知会原导购,等满 {知会提前天} 天且过第 {释放天} 天再放")
    return dict(动作="释放", 已过天数=天,
                理由=f"最后接触 {维} 已过 {天} 天,{知} 知会后 {知会提前天} 天内没有新接触 —— 整户释放到本店公海,店长指派")
