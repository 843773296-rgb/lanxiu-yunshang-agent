"""未成交挽回的口径 —— **哪些单该跟、按什么顺序跟,以及哪条线我不划。**

## 这是什么

库里压着两笔**算得出金额的流失**,而系统里没有任何东西在看:

    待付款订单   下了单没付钱
    预约未成行   约了没来(已取消 / 爽约 / 已过期)

它们在表上**只是一个状态,没有一个动作**。

## ⚠️ 「压几天算超时」这条线,我不划

定制品和标品的合理等待期**本来就不一样** ——
定制品要等方案确认、要等客户和家人商量一件几万块的衣服;
标品放三天不付多半就是不要了。

**编一个数出来,会把正常的单子也算成流失**,而那种错不会报错,
只会让顾问去催一个本来就该等的客户。

和这个项目其他几条「不替它猜」是同一条:会员积分门槛、特体修版量、
童装档差表、公差数值。**规则没定义清楚的地方,不许替它猜一个。**

所以这里**不划线,只排序**:把停留天数和金额摆出来,按「压着多少钱 × 压了多久」
排,让看的人自己决定从哪儿切一刀。

## 排序的依据:金额 × 停留天数

不是按单号,也不是单看金额或单看天数:

    只看金额   一单 5 万压了两天,排在一单 500 压了两个月前面 —— 而后者多半已经黄了
    只看天数   一单 500 压了两个月,排在一单 5 万压了三周前面 —— 而后者才是真的钱

**两个乘起来,量纲是「元·天」** —— 它读起来像「这笔钱被占了多久」,
而那正是要挽回的东西。

## 「已取消」和「爽约」不是一类

它们在预约表上都是一行,而**该做的事完全不同**:

    已取消   客户**主动说了不来** —— 他知道自己取消了,回访要问「是不是不合适」
    爽约     **没说就没来** —— 可能忘了、可能出事了,回访要先确认人没事
    已过期   **系统判的** —— 到点没动静,连客户自己都未必知道有这条预约

把三种混成「未到店」去发同一套话术,**第二种和第三种都会显得很唐突**。
"""

# ⚠️ **这条线要业务定,不许在这儿编一个数。**
# 定制品和标品的合理等待期不一样,而编出来的那个数**不会报错**,
# 只会让顾问去催一个本来就该等的客户。
超时天数 = None
超时天数_为什么是空的 = (
    "定制品要等方案确认、要等客户和家里商量一件几万块的衣服;"
    "标品放三天不付多半就是不要了 —— **两者的合理等待期本来就不一样**。"
    "这个数要业务按品类分别定,在那之前**只排序不划线**。")

# 三种未成行,各自该做什么 —— **不许混成一类**
未成行 = {
    "已取消": ("客户**主动说了不来**",
              "回访问「是不是时间不合适 / 方案不合适」—— 他知道自己取消过"),
    "爽约":   ("**没说就没来**",
              "**先确认人没事**,再问要不要重约 —— 上来就催会很唐突"),
    "已过期": ("**系统判的**,到点没动静",
              "客户自己可能都不知道有这条预约 —— 回访要先把这件事说清楚"),
}


def 紧要度(金额, 停留天数):
    """排序用的那个数:**元 · 天** —— 「这笔钱被占了多久」。

    只看金额会把「5 万压两天」排在「500 压两个月」前面(而后者多半已经黄了);
    只看天数会把「500 压两个月」排在「5 万压三周」前面(而后者才是真的钱)。
    """
    return round((金额 or 0) * max(停留天数 or 0, 0), 1)


def 停留(iso日期, 今天):
    """压了几天。**今天从外面传进来** —— 口径模块不取当前时间。

    和 `lifecycle.py` / `review.py` 同一个分层:谁负责判定,谁就不该同时负责取时间,
    否则同一批数据在不同时刻算出不同结果,真值对账没法复现。
    """
    import datetime as _dt
    if not iso日期: return None
    try:
        d = _dt.date.fromisoformat(str(iso日期)[:10])
    except ValueError:
        return None
    return (_dt.date.fromisoformat(str(今天)[:10]) - d).days


def 口径说明():
    return {
        "排序依据": "金额 × 停留天数(元·天)—— 「这笔钱被占了多久」",
        "⚠️ 没有划线": 超时天数_为什么是空的,
        "三种未成行不许混": {k: v[0] for k, v in 未成行.items()},
    }


