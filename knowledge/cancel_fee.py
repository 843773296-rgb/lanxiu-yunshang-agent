"""开裁后顾客不做了 —— 扣多少工钱(业务 2026-10-10 晚定,法规文档 ③)。

民法典 787:定作人在完成工作前可以**随时解除**,只赔已发生的损失。所以不设固定违约比例,
扣的是**已经发生的工钱**,按工单工日折钱:

    已完成的工单     工日 × 单价,全算
    做到一半的工单   已过天数 × 单价,**不超过这张工单的工日**
    没开始的工单     不扣(开工日还没到)
    扣的总额         **不超过顾客已付的钱**
    单价             普通工序 300 / 非遗级 800 元一工日(业务 09-24,和毛利同一个口径,取自 margin.py)

业务选的是「按工单工日折钱」,**没选**「按工序比例」(比如开裁算 20%、绣完算 60%)——
比例要有人定、而且顾客问「凭什么是 60%」答不上来;工日是工单上记着的、顾客看得懂。

「已过天数」= 今天 − 开工日(开工当天算 0 天)。**往顾客有利的那头取**:
当天开工当天取消,一天工也没做满,不扣。

逐道列给顾客确认:`明细` 里每道工序一行,写清是哪道、几个工日、怎么算的。
**这里只算工钱** —— 料的成本价由门店按采购单另列(确认书第三条),两样加起来再封顶。

工单数据缺了(没有工日 / 没有开工日)的那道 → 不猜,列进 `判不了`,整单要人工核。
"""
import datetime, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import margin as M

咬合 = [
    ("做到一半的按已过天数折,不超过该工单工日", "做到一半的按已过天数折,超过工日的封顶"),
    ("扣的总额不超过已付款", "扣的总额不超过已付款"),
]


def _日(x):
    try:
        return datetime.date.fromisoformat(str(x)[:10])
    except (TypeError, ValueError):
        return None


def 一道(工单, 今天, 非遗集):
    """工单 = dict(编号, 工艺, 工艺名, 工日, 开工日, 状态)。→ 一行明细。"""
    工日, 起 = 工单.get("工日"), _日(工单.get("开工日"))
    档 = M.档(工单.get("工艺"), 非遗集)
    价 = M.工时单价[档]
    名 = 工单.get("工艺名") or 工单.get("工艺") or "—"
    行 = dict(工单=工单.get("编号"), 工序=名, 档=档, 单价=价, 工日=工日, 状态=工单.get("状态"))
    if 工日 is None or 工日 < 0:
        return dict(行, 扣=None, 怎么算=f"工单没记工日,判不了")
    if 工单.get("状态") == "已完成":
        return dict(行, 扣=round(工日 * 价, 2), 计天=工日, 怎么算=f"已完成:{工日:g} 工日 × {价} 元")
    if 起 is None:
        return dict(行, 扣=None, 怎么算="工单没记开工日,判不了做了几天")
    过 = (今天 - 起).days
    if 过 <= 0:
        return dict(行, 扣=0.0, 计天=0, 怎么算=f"还没开工(开工日 {起}),不扣")
    天 = min(过, 工日)
    封 = "(封顶到这张工单的工日)" if 过 > 工日 else ""
    return dict(行, 扣=round(天 * 价, 2), 计天=天, 怎么算=f"做到一半:已过 {过} 天,按 {天:g} 天 × {价} 元{封}")


def 算(工单们, 今天, 已付, 非遗集, 料费=0.0):
    """→ dict(明细, 工钱, 料费, 合计, 封顶了, 退, 判不了, 说法)。

    料费 = 门店按采购单核的料的成本价(这里不算,只参与封顶)。
    判不了的那几道**不按 0 算** —— 按 0 算会少扣,而它在明细上和「没开工、不扣」长得一样。
    """
    今天 = _日(今天)
    明细 = [一道(w, 今天, 非遗集) for w in 工单们]
    判不了 = [x for x in 明细 if x["扣"] is None]
    工钱 = round(sum(x["扣"] for x in 明细 if x["扣"] is not None), 2)
    料费 = round(float(料费 or 0), 2)
    原 = round(工钱 + 料费, 2)
    已付 = round(float(已付 or 0), 2)
    合计 = min(原, 已付)
    出 = dict(明细=明细, 工钱=工钱, 料费=料费, 合计=合计, 封顶了=原 > 已付, 退=round(已付 - 合计, 2),
             判不了=[x["工单"] for x in 判不了])
    if 判不了:
        出["说法"] = f"有 {len(判不了)} 道工序的工单数据不全,这一单的扣款**先不报给顾客**,请生产补齐工单再算"
    else:
        出["说法"] = (f"已发生工钱 {工钱:,.2f} 元" + (f" + 料 {料费:,.2f} 元" if 料费 else "")
                    + (f",超过已付 {已付:,.2f} 元,按已付封顶" if 出["封顶了"] else "")
                    + f";扣 {合计:,.2f} 元,退 {出['退']:,.2f} 元。逐道明细请顾客确认后再退")
    return 出


def 从库(c, 订单号, 今天, 料费=0.0, 非遗集=None):
    """读这张单的工单(workorder.ref = 订单号)和已付(ordr.received)。"""
    o = c.execute("SELECT received, amount FROM ordr WHERE id=?", (订单号,)).fetchone()
    if not o:
        return dict(error=f"没有订单 {订单号}")
    工单们 = [dict(编号=i, 工艺=k, 工艺名=n, 工日=d, 开工日=s, 状态=st) for i, k, n, d, s, st in c.execute(
        "SELECT w.id, w.craft, cr.name, w.workdays, w.start_date, w.status FROM workorder w "
        "LEFT JOIN craft cr ON cr.code=w.craft WHERE w.ref=? ORDER BY w.start_date, w.id", (订单号,))]
    已付 = o[0] if o[0] is not None else o[1]
    出 = 算(工单们, 今天, 已付, 非遗集 if 非遗集 is not None else M.非遗工艺(), 料费)
    if not 工单们:
        出["说法"] = "这张单还没有工单 —— 还没开工,不扣工钱(料费按备料情况另算)"
    return dict(出, 订单=订单号, 已付=已付)


if __name__ == "__main__":
    遗 = {"KF01"}
    今 = "2026-10-10"
    W = lambda i, k, d, s, st: dict(编号=i, 工艺=k, 工艺名=k, 工日=d, 开工日=s, 状态=st)
    坏 = 0

    def ck(名, ok, 附=""):
        global 坏
        坏 += not ok
        print(f"  {'✅' if ok else '❌'} {名}" + (f"  {附}" if not ok and 附 else ""))

    r = 算([W("a", "KF11", 4, "2026-10-01", "已完成")], 今, 99999, 遗)
    ck("已完成的全算:普通 4 工日 × 300 = 1200", r["工钱"] == 1200, r)
    r = 算([W("a", "KF01", 4, "2026-10-01", "已完成")], 今, 99999, 遗)
    ck("非遗级按 800:缂丝 4 工日 = 3200", r["工钱"] == 3200, r)
    r = 算([W("a", "KF11", 10, "2026-10-07", "在制")], 今, 99999, 遗)
    ck("做到一半的按已过天数折:开工 3 天 × 300 = 900", r["工钱"] == 900, r)
    r = 算([W("a", "KF11", 2, "2026-10-01", "在制")], 今, 99999, 遗)
    ck("做到一半的按已过天数折,超过工日的封顶", r["工钱"] == 600, r)
    r = 算([W("a", "KF11", 5, "2026-10-14", "在制"), W("b", "KF11", 5, 今, "在制")], 今, 99999, 遗)
    ck("没开始的不扣(开工日在明天以后、今天刚开工都是 0)", r["工钱"] == 0, r)
    r = 算([W("a", "KF01", 20, "2026-09-01", "已完成")], 今, 5000, 遗, 料费=800)
    ck("扣的总额不超过已付款", r["合计"] == 5000 and r["退"] == 0 and r["封顶了"], r)
    r = 算([W("a", "KF11", None, "2026-10-01", "在制"), W("b", "KF11", 2, "2026-10-01", "已完成")], 今, 9999, 遗)
    ck("工日缺了不按 0 算,列进判不了、不报给顾客", r["判不了"] == ["a"] and "先不报" in r["说法"], r)
    r = 算([W("a", "KF11", 4, "2026-10-01", "已完成"), W("b", "KF01", 10, "2026-10-08", "在制")], 今, 99999, 遗)
    ck("逐道列明细:每道一行,写清怎么算", len(r["明细"]) == 2 and all(x["怎么算"] for x in r["明细"])
       and r["工钱"] == 1200 + 2 * 800, r)
    ck("单价和毛利同一个口径(margin.工时单价)", M.工时单价 == {"普通": 300, "非遗级": 800})
    raise SystemExit(1 if 坏 else 0)
