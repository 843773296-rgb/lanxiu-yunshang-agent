def 回测要遮吗(键名):
    """这个对外键名是不是在泄露人工怎么处置的。

    ⚠️ 返回 True 的键**必须**在 `回测要遮的字段` 里登记过 ——
    `backend/backtest_mask_check.py` 盯的就是这件事:
    以后给工具加一列 `处理人`,清单不跟着加,这条判据当场红。
    不盯的话,**清单会悄悄过期,而回测仍然显示很漂亮**。
    """
    名 = str(键名)
    return any(标 in 名 for 标 in 处置痕迹的标记) or 名 == "状态"


