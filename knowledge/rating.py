def 收下分项(分们):
    """分们 = {分项名: 星}。**选填**,不填的就是没评(None),不是 0 星。

    返回 (收不收, {列名: 星}, 一句话)。有一项不合法整份不收 —— 不挑能收的收一半。
    """
    出 = {}
    for 名, 星 in (分们 or {}).items():
        if 名 not in 分项:
            return False, {}, f"没有「{名}」这个分项 —— 只有 {'/'.join(分项)}(都是交付体验的一部分)"
        if 星 is None:
            continue
        收, n, 说 = 收下星级(星)
        if not 收:
            return False, {}, f"「{名}」{说}"
        出[分项[名]] = n
    return True, 出, f"收下 {len(出)} 个分项"


