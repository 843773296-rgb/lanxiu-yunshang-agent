# -*- coding: utf-8 -*-
"""签收后请顾客评价的口径 —— 何时能评 / 几星算差评 / 能不能改 / 差评怎么流转。

**业务定的(用户逐条拍板):**

  ① 渠道:签收后在**小程序**请顾客评价(2026-09-24)
  ② **签收当场就请**(2026-09-27)
  ③ **≤3 星算差评**,而且**自动进待处理清单** —— 不是躺在表里等人去翻(2026-09-27)
  ④ 评价**能对到顾问,但现在不进考核,只给店长看** → **所以现在不做防刷**(2026-09-27)

## 这个星级衡量的是「交付体验」,不是「衣服好不好」

⚠️ **这是业务知情并接受的代价,必须写在口径里,不能只写在会议记录里。**

「签收当场就请」意味着顾客是在**店里、导购面前、刚拿到衣服还没穿过**的时候评的。
于是这个数字:

  · 衡量的是**拿到手那一刻的体验**(准不准时、合不合身、导购怎么样、包装),
    **不是穿了两周之后衣服好不好** —— 后者那时候还没发生,顾客无从评起;
  · **会系统性偏高** —— 当面很难给差评。所以 4.8 分**不能**读成「95% 的人满意」,
    它的基线本来就比匿名事后评高。

**把这个星级当成「衣服质量」的证据是错的**,而这种错在页面上看不出来 ——
两种星级长得一模一样,都是 1-5 颗星。所以判据写成一个函数(`这个星级能说明什么`),
让它**可以被评测直接考**,而不是指望看文档的人记住。

## 「没签收不许评」的判据取自哪儿(这一条是设计,不是实现细节)

判据取 `fit_code.used_at`(那个 6 位码**被核验过了**)和 `pickup_item.fit_at`,
**不取订单状态**。因为:

  · 订单状态是**一个可以被人改的字段** —— 谁把 `status` 写成「已完成」,闸就开了;
  · 码核验过了是**一件发生过的事** —— 顾客本人在场拿手机点过、导购输入过、
    库里那一行的 `used_at` 有时间。

> 这是项目里反复出现的那条:**闸要架在事实上,不要架在别人算出来的字段上。**
> (同源:`order_spread_check` 里「已匿名化的客户名下没有订单」那一条 ——
> 重算 `order_cnt` 骗得过聚合,骗不过「订单在不在那儿」。)

## 粒度:**一个包裹一次**,不是一单一次

分批发货时签收落到包裹(一个包裹一个码,业务 2026-09-23)。评价紧跟签收动作,
所以也按包裹。一单一次会撞上「第一批到店时已经评过了,第二批拿到手没法评」——
而那两批的交付体验可能完全不同(一批准时一批晚了半个月)。

⚠️ **这一条是默认值,业务没逐条定**,用到时要说出去。
"""
import datetime

星最低, 星最高 = 1, 5
差评线 = 3               # ≤3 星算差评 —— **业务 2026-09-27 拍板**(不是常见的 ≤2)
进考核了吗 = False        # 业务 2026-09-27:现在不进顾问考核,只给店长看

# ── 下面这几个是**默认值,业务没逐条定** ─────────────────────────────
能评几天 = 7             # 签收后多少天内还能评。过期不再催:再往后评的就不是交付体验了
能改几小时 = 24          # 评完多久内能改
能改几次 = 1
最短处理记录 = 6      # 差评待办关闭时处理记录的最少字数 —— **判据只写这一处**
默认值_依据 = ("按包裹评、7 天内能评、24 小时内能改一次 —— 这几条是默认值,"
             "**业务只定了「签收当场就请」「≤3 星算差评且自动进待处理清单」"
             "「不进考核只给店长看」**;用到时要说出去")

# 为什么允许改:「签收当场就请」已经让星级偏高了(当面难给差评)。
# **一律不许改会把这个偏差焊死** —— 顾客回家发现问题,连修正的口子都没有。
# 但改的方向是不对称的,见 `改了之后清单怎么动()`。


def _t(s):
    return datetime.datetime.strptime(str(s)[:16], "%Y-%m-%d %H:%M")


def 签收于(件们):
    """这个包裹**什么时候签收的** —— 取最后一件签收合身的时刻,没有就是 None。

    件们  [{order_item_id, fit_result, fit_at}] —— 这个包裹里的件

    ⚠️ 判据是「**有件签收合身了**」,不是「整个包裹都签收完了」:
    一个包裹两件合身一件不合身时,合身那两件顾客当场拿走了(业务 09-23),
    交付体验已经发生 —— 要求整包裹齐全才能评,等于让不合身那一件把评价一起扣住。
    """
    好 = [x.get("fit_at") for x in (件们 or []) if x.get("fit_result") == "合身" and x.get("fit_at")]
    return max(好) if 好 else None


def 能不能评(件们, now, 评过了吗=False, 来源="顾客小程序"):
    """现在能不能请这位顾客评价。返回 (能不能, 一句人话)。

    件们      这个包裹里的件(见 `签收于`)
    评过了吗  这个包裹已经有评价了
    来源      「顾客小程序」以外的一律不认 —— **顾问不能替顾客评**
    """
    if 来源 != "顾客小程序":
        return False, (f"评价只认顾客自己在小程序上提交(这条来自「{来源}」)—— "
                       "顾问代评的星级不能用来衡量顾问自己")
    签 = 签收于(件们)
    if not 签:
        return False, ("这个包裹还没有任何一件签收(6 位码没核验过)—— "
                       "**没签收不许评**:顾客还没拿到手,评的是什么无从谈起")
    if 评过了吗:
        return False, "这个包裹已经评过了 —— 一个包裹一次"
    天 = (_t(now) - _t(签)).days
    if 天 < 0:
        return False, f"签收时间({签})在现在({now})之后 —— 数据有问题,先查,别放行"
    if 天 > 能评几天:
        return False, (f"签收已经 {天} 天,超过 {能评几天} 天不再请评 —— "
                       "业务定的是「签收当场就请」,这时候顾客评的已经不是交付体验了")
    return True, ("可以请评价" + ("(就是现在,签收当场)" if 天 == 0 else f"(签收后第 {天} 天)"))


def 收下星级(星):
    """把顾客提交的星级归一。返回 (收不收, 星或 None, 一句人话)。

    ⚠️ **不四舍五入、不夹到范围里** —— 6 星和 0 星是提交端出了问题,
    悄悄改成 5 星或 1 星会把 bug 存成数据。
    """
    try:
        n = int(星)
    except (TypeError, ValueError):
        return False, None, f"星级不是整数({星!r})—— 提交端出问题了,别收"
    if n != 星 and not isinstance(星, int) and float(星) != n:
        return False, None, f"星级不是整数({星!r})—— 半星这个产品没有"
    if not (星最低 <= n <= 星最高):
        return False, None, f"星级 {n} 不在 {星最低}-{星最高} 之间 —— **不夹到范围里**,提交端出问题了"
    return True, n, f"{n} 星" + ("(差评)" if 是差评(n) else "")


def 是差评(星):
    """≤3 星算差评 —— **业务 2026-09-27 拍板**。"""
    return int(星) <= 差评线


def 能不能改(评于, now, 改过几次=0):
    """顾客想改自己的评价。返回 (能不能, 一句人话)。"""
    if 改过几次 >= 能改几次:
        return False, f"已经改过 {改过几次} 次 —— 最多改 {能改几次} 次"
    小时 = (_t(now) - _t(评于)).total_seconds() / 3600
    if 小时 < 0:
        return False, "评价时间在现在之后 —— 数据有问题,先查"
    if 小时 > 能改几小时:
        return False, f"评完已经 {小时:.0f} 小时,超过 {能改几小时} 小时不能改"
    return True, f"评完 {小时:.0f} 小时内,可以改"


def 改了之后清单怎么动(原星, 新星, 已在清单吗):
    """改评价时,待处理清单怎么跟着动。返回 (动作, 一句人话)。

    动作:「进清单」/「更新星级」/「留在清单里」/「不动」。

    ⚠️ **方向不对称:好评改差评要进清单,差评改好评不撤出。**
    因为清单不是「当前状态的镜子」,是**一串待办**:店长看到差评已经去联系顾客了,
    把它撤掉等于把已经发生的事抹掉 —— 而且很可能正是店长联系过之后顾客才改的好评,
    撤掉就再也看不出「差评被处理好了」和「从来没有差评」的区别。
    """
    原差, 新差 = 是差评(原星), 是差评(新星)
    if 新差 and not 已在清单吗:
        return "进清单", f"{原星} 星改成 {新星} 星,成了差评 —— 进待处理清单"
    if 新差 and 已在清单吗:
        return "更新星级", f"还是差评({原星}→{新星} 星)—— 清单里那条更新星级"
    if 已在清单吗:
        return "留在清单里", (f"{原星} 星改成 {新星} 星,不是差评了,但**清单里那条不撤** —— "
                          "只标注「顾客后来改成 {} 星」。撤掉就看不出差评被处理好过".format(新星))
    return "不动", f"{原星}→{新星} 星,都不是差评"


def 差评待办(星, 评语, order_id, pkg_id, 评于, 顾问=None):
    """差评自动落待处理清单的那一行(业务 2026-09-27:**自动进**,不是躺在表里)。

    ⚠️ 顾问**记下来但不参与考核**(业务 09-27)。记的原因是店长要能查是哪一单谁经手的;
    一旦哪天要进考核,见 `进考核前要做什么()`。
    """
    if not 是差评(星):
        return None
    return dict(kind="评价差评", order_id=order_id, pkg_id=pkg_id, star=int(星),
                note=(str(评语 or "").strip() or "(顾客没写评语)"), rated_at=评于,
                advisor=顾问, owner="店长", status="待处理",
                why=f"{星} 星(≤{差评线} 算差评)—— 业务 2026-09-27 定:自动进待处理清单,店长跟")


def 待办能不能关(处理记录):
    """差评待办关闭的条件。返回 (能不能, 一句人话)。

    **必须写处理记录** —— 「看过了」不算处理完。不要求这条,清单三天之内就会被清空成绿的,
    而顾客那边什么都没发生。

    ⚠️ 判据**只有一处**(`最短处理记录`),两句人话共用它。
    第一版写成两道 `if`(先判空、再判太短),咬合当场抓到:**去掉第一道,第二道照样拦住空串**,
    于是「改坏了却没红」—— 同一个规矩写在两处,攻击哪一处都证明不了它在承重。
    """
    s = str(处理记录 or "").strip()
    if len(s) < 最短处理记录:
        return False, ("关闭差评要写处理记录(联系了顾客 / 怎么解决的)—— 「看过了」不算处理完"
                       if not s else
                       f"处理记录太短(「{s}」,不到 {最短处理记录} 字)—— 写清楚联系了没有、怎么处理的")
    return True, "写了处理记录,可以关"


def 这个星级能说明什么():
    """这个数字能下什么结论、不能下什么结论。**给评测和给页面文案用。**

    返回 (能说的, 不能说的)。
    """
    能说 = ["交付那一刻顾客的感受(准不准时、合不合身、导购怎么样、包装)",
           "不同门店 / 不同时间段的交付体验**互相比**(同一个偏差,比较仍然成立)",
           "哪些单当场就出了问题(差评进待处理清单)"]
    不能说 = [f"衣服好不好 / 面料工艺怎么样 —— 顾客还没穿过(签收当场就评)",
            "顾客的长期满意度 / 会不会复购 —— 这要事后回访,不是签收当场",
            "「4.8 分说明 95% 的人满意」—— 当面难给差评,这个分数**系统性偏高**,"
            "只能和它自己的历史比,不能和匿名评分的行业基线比",
            f"顾问的绩效 —— 业务 2026-09-27 定:{'' if 进考核了吗 else '现在不进考核,'}"
            "而且现在**没有防刷**"]
    return 能说, 不能说


def 进考核前要做什么(要进考核吗):
    """哪天要把评价接进顾问考核,先过这道。返回 (能不能进, 一句人话)。

    ⚠️ 这个函数存在的意义就是**拦住未来的自己**:业务 09-27 说「现在不进考核」,
    所以现在不做防刷 —— 这两件事是**捆在一起**的。哪天有人只改了前半句,
    这里会当场告诉他后半句是什么。
    """
    if not 要进考核吗:
        return True, "不进考核,只给店长看 —— 现在这样(业务 2026-09-27)"
    return False, ("要进顾问考核,**必须同时做防刷** —— 现在的评价没有任何防刷:"
                   "顾问陪着顾客在店里、当面拿着手机点,星级本来就偏高;"
                   "一旦和钱挂钩,顾问替顾客点、挑人请评、只请满意的顾客评,这个数很快不能信。"
                   "至少要有:一单一次的硬约束(已有)、**评价必须从顾客自己的手机提交**、"
                   "异常分布告警(某个顾问全是 5 星)、抽样电话复核")


# ── 咬合记录(改坏了必须有东西红)────────────────────────────────────────
# 六条都在 `tools/bite_specs.json` 里可重放,**全部真跑过三关**。
# 第一次跑挂了两条,两种不同的失效:
#   · 「没签收不许评」改坏后红的是 `ValueError` —— 闸后面的 `_t(签)` 直接崩,
#     **整个自测脚本崩掉,那一条 ❌ 没机会打印**。退出码非 0,看着像抓到了。
#     → 自测改成**延迟求值**(见 `ck`),崩了也落到具体那一条上。
#   · 「空记录也能关」**改坏了却没红** —— 同一个规矩写了两道 `if`,
#     去掉一道另一道照样拦。→ 判据合并成 `最短处理记录` 一处。
咬合 = [
    ("让 能不能评() 在没签收时也放行", "没签收不许评"),
    ("把 差评线 从 3 改成 2", "3 星算差评"),
    ("让 收下星级() 把 6 星夹成 5 星", "6 星不收,不夹到范围里"),
    ("让 改了之后清单怎么动() 在差评改好评时撤出清单", "差评改好评,清单里那条不撤"),
    ("把 最短处理记录 从 6 改成 0(空记录也能关)", "关差评要写处理记录"),
    ("让 能不能评() 接受来源「导购端」", "顾问不能替顾客评"),
]

if __name__ == "__main__":
    import sys, traceback
    bad = []

    def ck(名, 取):
        """⚠️ `取` 是个**函数**,不是求好的值 —— 这一条是咬合当场逼出来的。

        原来写成 `ck(名, 表达式)`:表达式在调用前就求值了,所以**被测代码一抛异常,
        整个自测脚本当场崩掉,那一条 ❌ 根本没机会打印出来**。
        退出码是非 0,看着像「抓到了」,其实是「崩了」——
        而咬合的第三关问的正是「红的是不是那一条」,那次它答不出来。
        (同源:项目栽过的「攻击自己跑不起来,于是任何异常都被读成被拦下」。)
        """
        try:
            ok = bool(取())
            说 = ""
        except Exception as e:
            ok, 说 = False, f"  ← **崩了**:{type(e).__name__}: {e}"
        print(f"  {'✅' if ok else '❌'} {名}{说}")
        if not ok: bad.append(名)

    print("评价口径 · 自测\n" + "=" * 74)
    签了 = [dict(order_item_id=1, fit_result="合身", fit_at="2026-09-27 15:00"),
           dict(order_item_id=2, fit_result="合身", fit_at="2026-09-27 15:04")]
    没签 = [dict(order_item_id=1, fit_result=None), dict(order_item_id=2, fit_result=None)]
    混 = [dict(order_item_id=1, fit_result="合身", fit_at="2026-09-27 15:00"),
         dict(order_item_id=2, fit_result="不合身")]

    # ── ① 何时能评 ──
    ck("签收那一刻取最后一件签收的时间", lambda: 签收于(签了) == "2026-09-27 15:04")
    ck("一件都没签收 → 没有签收时刻", lambda: 签收于(没签) is None)
    ck("不合身那件不算(取合身那件的时间)", lambda: 签收于(混) == "2026-09-27 15:00")
    ck("签收当场 → 可以请评价", lambda: 能不能评(签了, "2026-09-27 15:10")[0])
    ck("没签收不许评", lambda: not 能不能评(没签, "2026-09-27 15:10")[0])
    ck("两件合身一件不合身 → 那两件的交付已经发生,能评", lambda: 能不能评(混, "2026-09-27 15:10")[0])
    ck("已经评过 → 一个包裹一次", lambda: not 能不能评(签了, "2026-09-27 15:10", 评过了吗=True)[0])
    ck(f"签收满 {能评几天} 天还能评", lambda: 能不能评(签了, "2026-10-04 15:00")[0])
    ck(f"超过 {能评几天} 天不再请评", lambda: not 能不能评(签了, "2026-10-05 16:00")[0])
    ck("签收时间在未来 → 不放行,报数据有问题",
       lambda: not 能不能评(签了, "2026-09-26 10:00")[0] and "数据有问题" in 能不能评(签了, "2026-09-26 10:00")[1])
    ck("顾问不能替顾客评", lambda: not 能不能评(签了, "2026-09-27 15:10", 来源="导购端")[0])

    # ── ② 几星算差评 ──
    ck("3 星算差评", lambda: 是差评(3))
    ck("4 星不算差评", lambda: not 是差评(4))
    ck("1 星算差评", lambda: 是差评(1))
    ck("5 星收下", lambda: 收下星级(5)[:2] == (True, 5))
    ck("6 星不收,不夹到范围里", lambda: 收下星级(6)[0] is False and 收下星级(6)[1] is None)
    ck("0 星不收", lambda: not 收下星级(0)[0])
    ck("半星不收(4.5)", lambda: not 收下星级(4.5)[0])
