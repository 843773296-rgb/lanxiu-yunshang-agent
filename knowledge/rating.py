def 要不要第二个人(方式):
    """这个处理方式要不要第二个人批。返回 (要不要, 一句人话)。

    业务 2026-10-11:**钱要出门就要两个人,不出门就一个人定。**
    四类事项的「要不要双人复核」合成了这一条 —— 四个开关会各自漂,
    一条按后果分档的规则只有一处可以漂。
    """
    if 方式 in 出钱的处理方式:
        return True, f"「{方式}」要我方出钱 —— 业务 2026-10-11:钱要出门就要两个人"
    return False, f"「{方式}」不出钱,一个人定得了"


def 要填金额吗(方式):
    """这个处理方式要不要人填「退了多少钱」。返回 (要不要, 一句人话)。

    **只有「部分退款」要填** —— 全额退款的金额就是订单额,现算得出来,
    让人填等于多一个会填错的地方(而填错了没人看得出来:
    > 一个「退了订单额」和一个「手填的数恰好等于订单额」,**在那个数上长得一模一样**,
    > 但后者下次改了订单额就不跟着变)。
    不出钱的那几种填了金额要**拒**,不是忽略 —— 填了说明有人理解错了,
    而静默忽略会让他以为记上了。
    """
    if 方式 == "部分退款":
        return True, "「部分退款」要填退了多少钱 —— 不填就判不出要谁批"
    if 方式 == "全额退款":
        return False, "「全额退款」的金额 = 订单额,现算,不用填"
    return False, f"「{方式}」不出钱,没有金额可填"


def 这笔要谁批(金额):
    """这个金额要哪一级批。返回 (角色或 None, 一句人话)。

    None = 不限角色(照旧只要求「不是处理人自己」)。
    """
    if 金额 is not None and 金额 > 退款上升一级的线:
        return 上升一级要谁批, (f"退 {金额:.2f} 超过 {退款上升一级的线} —— "
                               f"业务拍的:超线要上升一级,{上升一级要谁批}批")
    return None, (f"退 {金额:.2f} 没超 {退款上升一级的线},店长批得了"
                  if 金额 is not None else "不出钱,不用管金额")


def 处理方式能不能用(方式, 批准人=None, 处理人=None,
                     金额=None, 订单额=None, 批准人角色=None):
    """关差评时这套参数合不合规。返回 (能不能, 一句人话)。

    ⚠️ **批准人是「店长」这件事是开发定的,业务没拍过。**
    业务 2026-10-11 只拍了「要给补偿或退款才要两个人」,**没说第二个人是谁**。
    这里照最近的先例定成店长(`api.decide_repair` 的我方支出 1000–5000 要总部批;
    差评补偿额度小、而店长本来就是跟客户的那个人,所以店长批是相称的)。
    **上线前要业务确认这一句。**
    > 这个标注不是客套:`ops.py` 里差评 72 小时那个数就是「开发定的、业务没拍过」,
    > 而 2026-10-11 清点时**唯一把它揪出来的就是一句同样的标注**。
    > 一个业务拍过的数和一个开发定的数,在报表上长得一模一样。

    ⚠️ **批准人不能是处理人自己** —— 照 `decide_repair` 那条
    「批准人不能是判责的店长自己」。一个人既处置又批准,双人复核就只剩一个人,
    **而记录上看起来两个字段都填了**。
    """
    方式 = str(方式 or "").strip()
    if not 方式:
        return False, (f"关差评要选处理方式({' / '.join(处理方式)})—— "
                       f"**不是备注里写一句**:「给没给钱」要判得出来,才知道要不要第二个人批")
    if 方式 not in 处理方式:
        return False, f"处理方式只能是 {' / '.join(处理方式)},收到「{方式}」"
    要, 话 = 要不要第二个人(方式)
    if not 要:
        # ⚠️ 不出钱的那几种**填了金额要拒,不是忽略** ——
        # 填了说明有人理解错了(比如把「免运费」当成退运费),
        # 而静默忽略会让他以为记上了,账上却什么都没有。
        if 金额 is not None:
            return False, (f"{话},所以**没有金额可记**,而这次填了 {金额} —— "
                           f"要记一笔钱出门就得选出钱的那几种"
                           f"({' / '.join(出钱的处理方式)})")
        return True, 话
    批 = str(批准人 or "").strip()
    if not 批:
        return False, f"{话} —— 填批准人(店长工号)"
    if 处理人 and 批 == str(处理人).strip():
        return False, (f"{话};而批准人填的是处理人自己({批})—— "
                       f"**一个人既处置又批准,双人复核就只剩一个人**,"
                       f"而记录上两个字段都填着")

    # ── 金额:要不要填、填得对不对、超线要谁批 ───────────────────────
    要填, 填话 = 要填金额吗(方式)
    if 要填 and 金额 is None:
        return False, f"{填话}"
    if 金额 is not None:
        try:
            金额 = float(金额)
        except (TypeError, ValueError):
            return False, f"退款金额得是个数,收到「{金额}」"
        if 金额 <= 0:
            return False, f"退款金额要大于 0,收到 {金额}"
        if 订单额 is not None and 金额 > float(订单额) + 0.005:
            return False, (f"退 {金额:.2f} 超过这一单的订单额 {float(订单额):.2f} —— "
                           f"**退得比收的多**,先核对单号")
        if 方式 == "全额退款" and 订单额 is not None \
                and abs(金额 - float(订单额)) > 0.005:
            return False, (f"「全额退款」的金额就是订单额 {float(订单额):.2f},"
                           f"而填的是 {金额:.2f} —— 要退这个数就选「部分退款」")
    # 全额退款没给金额时,金额 = 订单额(现算,不让人填)
    if 方式 == "全额退款" and 金额 is None and 订单额 is not None:
        金额 = float(订单额)

    要谁, 谁话 = 这笔要谁批(金额)
    if 要谁:
        if not 批准人角色:
            return False, (f"{谁话};而取不到批准人 {批} 的角色 —— "
                           f"**取不到就不放行**(放行等于这道闸没有)")
        if str(批准人角色).strip() != 要谁:
            return False, (f"{谁话};而批准人 {批} 是「{批准人角色}」—— "
                           f"**这一笔得 {要谁} 批**")
        return True, f"{话};{谁话};批准人 {批}({批准人角色})"
    return True, f"{话};批准人 {批}" + (f";{谁话}" if 金额 is not None else "")


