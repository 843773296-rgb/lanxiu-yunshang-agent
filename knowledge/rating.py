def 能不能追评(签收时刻, now, 追评过了吗=False):
    """追评:**穿过之后**的那句话。不带星,不改总星,不进差评清单。"""
    if 追评过了吗:
        return False, "已经追评过了 —— 一个包裹追评一次"
    if not 签收时刻:
        return False, "还没签收,没有「穿过之后」"
    天 = (_t(now) - _t(签收时刻)).total_seconds() / 86400
    if 天 < 0:
        return False, "签收时间在未来 —— 数据有问题"
    if 天 > 能追评几天:
        return False, f"签收已经 {int(天)} 天,超过 {能追评几天} 天不再收追评"
    return True, "可以追评(不带星级,不改原来的评分)"


