"""店里在推什么 —— 活动 / 内容「能不能推给客户」的口径(包四第二块,用户 2026-11-26 拍开工)。

只放判定,不取数、不取当前日期(CLAUDE.md 第 9 节 ①:判定的人不负责取时间)。工具 store_promotions 取数后调这里。

口径(我拟的,用户没逐条过 —— 挪口径只改这里):
- 活动能推 = 状态「进行中 / 未开始」**且**(全渠道 **或** 就是本店的门店活动)。别店的门店活动不推(客户到不了那家店参加)
- 内容能对客发 = 状态「已发布」。草稿是内部还没审完的东西,发出去等于替品牌说了没定稿的话
- 活动预算 / 花费 / 成交不在这里 —— 那是内部数,效果看活动复盘(activity_roi)
"""

能推的活动状态 = ("进行中", "未开始")
全渠道 = "全渠道"
能发的内容状态 = ("已发布",)


def 活动能推吗(状态, 活动门店码, 本店码):
    """→ (能不能, 一句为什么)。本店码 None = 跨店角色(总部 / 售后),只按状态判。"""
    if 状态 not in 能推的活动状态:
        return False, f"活动「{状态}」—— 只有{' / '.join(能推的活动状态)}的能推"
    if 活动门店码 in (None, "", 全渠道) or 本店码 is None or 活动门店码 == 本店码:
        return True, "可以推"
    return False, f"这是 {活动门店码} 的门店活动,本店客户去不了那家店参加 —— 不推"


def 内容能发吗(状态):
    if 状态 in 能发的内容状态:
        return True, "已发布,可以发给客户"
    return False, f"内容还是「{状态}」—— 没发布的不能发给客户"


# 咬合记录(规格在 tools/bite_specs.json)
咬合 = [
    ("把「能推的活动状态」加上「已结束」", "已结束的活动不能推"),
]


def _自测():
    assert 活动能推吗("进行中", "全渠道", "SH001")[0]
    assert 活动能推吗("未开始", "SH001", "SH001")[0]
    assert not 活动能推吗("进行中", "SH002", "SH001")[0]
    assert 活动能推吗("进行中", "SH002", None)[0], "跨店角色只按状态判"
    assert not 活动能推吗("已结束", "全渠道", "SH001")[0], "已结束的活动不能推"
    assert not 活动能推吗("已取消", "全渠道", None)[0]
    assert 内容能发吗("已发布")[0] and not 内容能发吗("草稿")[0]
    print("✅ promotions 自测过(状态 / 全渠道 / 本店 / 别店 / 跨店角色 / 草稿)")
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(_自测())
