"""周报口径(用户 2026-10-09 拍板)—— **口径在这里,取数在 backend/api.py**。

    业务周   周一 00:00 到周日 24:00(中国时间,按演示世界的日期)。「上周」= 上一个**完整**的周一到周日。
    营收     **实收减退款**:这一周实际收到的钱,减去这一周退出去的钱;
             **按付款日、退款日归周**,不是按下单日。
    进店客流 用实际预约到店(预约漏斗里的「真到店」),不另造客流数据。
    顾问排名 按归因成交(业务 09-22 的 W 型归因,和成交率同一套算法)。

⚠️ 这个模块**不取当前日期**(CLAUDE.md 第 9 节 ①:谁负责判定,谁就不该同时负责取时间)——
「今天」由调用方传进来。
"""
import datetime as _dt

周名 = "周一到周日"

咬合 = [
    ("业务周切成周日到周六(周日算成下一周的头一天)", "周日属于这一周(不是下一周)"),
]


def 周起止(某天):
    """某一天所在的那个业务周 → (周一, 周日)。接受 date 或 'YYYY-MM-DD'。"""
    d = 某天 if isinstance(某天, _dt.date) else _dt.date.fromisoformat(str(某天)[:10])
    一 = d - _dt.timedelta(days=d.weekday())
    return 一, 一 + _dt.timedelta(days=6)


def 上一完整周(今天):
    """「上周」= 今天所在那周的前一周。**今天是周日也一样** —— 本周还没过完,不算完整。"""
    一, _ = 周起止(今天)
    return 周起止(一 - _dt.timedelta(days=1))


# ── 报告期:日报 / 周报 / 月报共用一套(用户 2026-10-09:「周报-月报-日报」都要做)──
# 三种报告只差时间窗:日 = 那一天;周 = 周一到周日;月 = 自然月。不给日期就是「上一个完整的」那一期
# (日报 = 昨天,周报 = 上周,月报 = 上个月)—— 本期还没过完,不算完整。
报告期种类 = ("日", "周", "月")


def 月起止(某天):
    d = 某天 if isinstance(某天, _dt.date) else _dt.date.fromisoformat(str(某天)[:10])
    一 = d.replace(day=1)
    末 = (一.replace(year=一.year + (一.month == 12), month=一.month % 12 + 1) - _dt.timedelta(days=1))
    return 一, 末


def 报告期(种类, 某天=None, 今天=None):
    """→ (起, 止, 名字)。给了某天就是那一天所在的那一期;没给就是今天之前最近一个**完整**的那一期。"""
    if 种类 not in 报告期种类:
        raise ValueError(f"报告期只能是 {'/'.join(报告期种类)},给的是「{种类}」")
    if 某天 is None:
        今 = 今天 if isinstance(今天, _dt.date) else _dt.date.fromisoformat(str(今天)[:10])
        if 种类 == "日":
            某天 = 今 - _dt.timedelta(days=1)
        elif 种类 == "周":
            return (*上一完整周(今), "上周")
        else:
            某天 = 今.replace(day=1) - _dt.timedelta(days=1)
    if 种类 == "日":
        d = 某天 if isinstance(某天, _dt.date) else _dt.date.fromisoformat(str(某天)[:10])
        return d, d, f"{d}(日报)"
    if 种类 == "周":
        一, 日 = 周起止(某天)
        return 一, 日, f"{一} ~ {日}(周报,周一到周日)"
    一, 末 = 月起止(某天)
    return 一, 末, f"{一.year} 年 {一.month} 月(月报)"


# 退款:售后单里这两类、走完了的,才是真退出去的钱。
# ⚠️ 库里**没有单独的「退款完成时间」**,只有售后单的最后更新时间(updated)——
# 用它近似退款日,返回值里要写明是近似。
退款类 = ("退货退款", "仅退款")
退款完成 = "已完成"


def 营收(收款行, 退款行):
    """收款行:[(付款日, 实收)];退款行:[(退款日, 金额)] —— 都已经按周筛好。返回汇总。"""
    收 = round(sum(x or 0 for _, x in 收款行), 2)
    退 = round(sum(x or 0 for _, x in 退款行), 2)
    return {"实收": 收, "退款": 退, "营收": round(收 - 退, 2),
            "收款笔数": len(收款行), "退款笔数": len(退款行)}


