    def h(as_of, idle, o=3, a=8000, q=2, **kw):
        d = dict(customer_id="C1", as_of=as_of, idle_days=idle, orders_12m=o,
                 amount_12m=a, quarters_12m=q)
        # 闲置给 None 是为了测「判不了」那条路,而 decide() 吃不了 None ——
        # 这一列在那种情况下本来也无从填起,**留空比填个假的好**
        if idle is not None:
            d["lifecycle"] = lifecycle.decide(dict(d, order_cnt=1 if o else 0))["生命周期"]
        d.update(kw)
        return d

    # ── 活跃度轴的六个含端边界:**不许自己写数字,必须和 lifecycle 一致** ──
    for d, want in [(90, "活跃"), (91, "休眠"), (180, "休眠"),
                    (181, "潜在流失"), (365, "潜在流失"), (366, "流失")]:
        ck(f"活跃档 闲置 {d} 天", 活跃档(d), want)
    ck("闲置算不出就是 None(不是活跃)", 活跃档(None), None)

    # ── 🔑 判据本身:标签变两次,轴上只走一步 ────────────────────
    # 「忠诚→休眠」和「活跃→休眠」**走到哪一步完全一样**,差别只在有多可惜。
    忠诚掉 = 判([h("2026-03-01", 10, o=5, a=30000, q=3), h("2026-06-01", 120, o=0, a=0, q=0)])
    活跃掉 = 判([h("2026-03-01", 10, o=1, a=2000, q=1), h("2026-06-01", 120, o=0, a=0, q=0)])
    ck("忠诚掉成休眠:到了休眠", 忠诚掉["到"], "休眠")
    ck("活跃掉成休眠:到了休眠", 活跃掉["到"], "休眠")
    ck("忠诚掉成休眠算退了一步", 忠诚掉["退了几步"], 1)
    ck("两种掉法**走到哪一步一模一样**", 忠诚掉["退了几步"], 活跃掉["退了几步"])
    ck("忠诚过的更可惜(中)", 忠诚掉["严重程度"], "中")
    ck("没价值标签的不那么可惜(低)", 活跃掉["严重程度"], "低")
    ck("两种掉法都要预警", (忠诚掉["要不要预警"], 活跃掉["要不要预警"]), (True, True))

    # 忠诚过但标签已被压掉 —— **从那一列读不出来,从当时的事实能**
    ck("忠诚过但标签被压掉的,仍然算可惜", 忠诚掉["曾经是"], ["忠诚", "高价值"])
    ck("现在这个标签已经没了", 忠诚掉["现在还是"], [])
    ck("理由里要说出这个标签没了", "已经没了" in 忠诚掉["话"], True)
    ck("标签掉了的不许说「现在仍然是」", "现在仍然是" in 忠诚掉["话"], False)

    # 🔑 **标签还在的那一支** —— 活跃度退了,而忠诚/高价值都还在。
    # 这两条必须一起看:**同样是「曾经是忠诚」,一个还在一个没了,说法必须不同**。
    标签还在 = 判([h("2026-03-01", 10, o=5, a=30000, q=3),
                  h("2026-06-01", 120, o=5, a=30000, q=3)])
    ck("标签还在时,现在还是不为空", 标签还在["现在还是"], ["忠诚", "高价值"])
    ck("标签还在时要说「现在仍然是」", "现在仍然是" in 标签还在["话"], True)
    ck("标签还在时不许说「曾经是」", "曾经是" in 标签还在["话"], False)
    ck("两个价值标签列表都排过序",
       (标签还在["曾经是"], 标签还在["现在还是"]),
       (sorted(标签还在["曾经是"]), sorted(标签还在["现在还是"])))

    # ── 说不出来的,单独一个码 ────────────────────────────────
    ck("只有一条判定说不出在不在动", 判([h("2026-06-01", 120)])["码"], "NO_HISTORY")
    ck("只有一条**不叫没在流失**", 判([h("2026-06-01", 120)])["要不要预警"], False)
    ck("一条都没有也是说不出来", 判([])["码"], "NO_HISTORY")
    ck("最新那条没闲置天数:判不了不当没事",
       判([h("2026-03-01", 10), h("2026-06-01", None)])["码"], "NO_HISTORY")

    # ── 到底了:复盘不是预警 ──────────────────────────────────
    走了 = 判([h("2026-01-01", 10, o=5, a=30000, q=3), h("2026-06-01", 400, o=0, a=0, q=0)])
    ck("已经流失的不算预警算复盘", 走了["码"], "GONE")
    ck("复盘不进预警", 走了["要不要预警"], False)
    ck("复盘也要说她曾经多可惜", "更可惜" in 走了["话"], True)
    ck("366 天就到底(含端)", 判([h("2026-01-01", 10), h("2026-06-01", 366)])["码"], "GONE")
    ck("365 天还来得及", 判([h("2026-01-01", 10), h("2026-06-01", 365)])["码"], "SLIPPING")

    # ── 回升 vs 一直稳 vs 一直在退 ────────────────────────────
    回 = 判([h("2026-01-01", 10), h("2026-03-01", 200), h("2026-06-01", 20)])
    ck("退过又回来了是 RECOVERED", 回["码"], "RECOVERED")
    ck("回升不报预警", 回["要不要预警"], False)
    ck("回升要说清她一度退到哪", "一度退到「潜在流失」" in 回["话"], True)
    ck("一直在活跃就是 STABLE",
       判([h("2026-01-01", 10), h("2026-06-01", 20)])["码"], "STABLE")
    ck("一直在休眠也是 STABLE(没退)",
       判([h("2026-01-01", 120), h("2026-06-01", 150)])["码"], "STABLE")
    # 🔑 这两条必须一起看:**同样是「现在比最差时好」,一个有上次可查一个没有**
    ck("退过又回来才叫 RECOVERED", 回["码"], "RECOVERED")
    ck("一进视野就已经休眠、后来活跃起来,**不叫退过又回来**",
       判([h("2026-01-01", 120), h("2026-06-01", 20)])["码"], "IMPROVING")
    ck("没有「上次」可查的,理由里不许说一度退到哪",
       "一度退到" in 判([h("2026-01-01", 120), h("2026-06-01", 20)])["话"], False)

    # 🔑 和「她自己最好的那一格」比,不和上一条比
    # 退到潜在流失、又继续退 —— 上一条已经是掉下来之后的了
    连退 = 判([h("2026-01-01", 10, o=5, a=30000, q=3),
               h("2026-03-01", 120, o=0, a=0, q=0),
               h("2026-06-01", 200, o=0, a=0, q=0)])
    ck("退到底之后又退不算第一次下滑", 连退["退了几步"], 2)
    ck("连着退仍然是在往下走", 连退["码"], "SLIPPING")
    ck("退两步 + 曾经忠诚 = 高", 连退["严重程度"], "高")
    ck("退两步要在理由里点出来", "一共退了 2 步" in 连退["话"], True)

    # 🔑 这三条必须一起看:**同样是「一共退了 2 步」,一脚踩空和慢慢凉是两件事**
    踩空 = 判([h("2026-01-01", 10, o=5, a=30000, q=3),
               h("2026-06-01", 200, o=0, a=0, q=0)])
    ck("一脚踩空:一共退了 2 步", 踩空["退了几步"], 2)
    ck("慢慢凉:也是一共退了 2 步", 连退["退了几步"], 2)
    ck("**两者在「退了几步」上一模一样**", 踩空["退了几步"], 连退["退了几步"])
    ck("一脚踩空的单步退幅是 2", 踩空["单步最大退幅"], 2)
    ck("慢慢凉的单步退幅只有 1", 连退["单步最大退幅"], 1)
    ck("一脚踩空才说「一次判定之间」", "一次判定之间" in 踩空["话"], True)
    ck("慢慢凉不许说「一次判定之间」", "一次判定之间" in 连退["话"], False)
    ck("慢慢凉要说是一步一步退的", "一步一步" in 连退["话"], True)

    # 🔑 日期要用「她最后一次还在最好状态」那条,不是历史第一条
    前面都好 = 判([h("2026-01-01", 10, o=5, a=30000, q=3),
                  h("2026-02-01", 20, o=5, a=30000, q=3),
                  h("2026-08-01", 120, o=0, a=0, q=0)])
    ck("最好那天取的是最后一次还在最好状态", 前面都好["最好那天"], "2026-02-01")
    ck("理由里的日期也是那一天", "2026-02-01 还是「活跃」" in 前面都好["话"], True)
    ck("不是历史第一条那天", "2026-01-01" in 前面都好["话"], False)

    # 没有价值标签但退到潜在流失 —— 一个维度够不上「高」
    普退远 = 判([h("2026-01-01", 10, o=1, a=2000, q=1), h("2026-06-01", 200, o=0, a=0, q=0)])
    ck("退得远但不可惜 = 中", 普退远["严重程度"], "中")

    # ── 没下过单的不归这里管 ──────────────────────────────────
    ck("从没下过单的单独一个码",
       判([h("2026-01-01", 10, o=0, a=0, q=0), h("2026-06-01", 200, o=0, a=0, q=0)])["码"],
       "NEVER_BOUGHT")

    # ── 顺序不靠调用方 ───────────────────────────────────────
    乱 = [h("2026-06-01", 120, o=0, a=0, q=0), h("2026-03-01", 10, o=5, a=30000, q=3)]
    ck("历史乱序传进来结果一样", 判(乱)["码"], "SLIPPING")

    # ── 排名:只在同一档内部比 ────────────────────────────────
    预警们 = [dict(id=f"C{i}", 严重程度=lv, 要不要预警=True,
                  idle_days=d, orders_12m=o, amount_12m=a)
              for i, (lv, d, o, a) in enumerate(
                  [("高", 200, 5, 30000), ("高", 300, 1, 5000),
                   ("低", 100, 8, 50000), ("中", 190, 2, 9000)])]
    分组 = 排名(预警们)
    ck("排名按严重程度分组", sorted(分组), ["中", "低", "高"])
    ck("排名只在同一严重档内部比", [len(v) for v in (分组["高"], 分组["中"], 分组["低"])],
       [2, 1, 1])
    ck("高危里最该先联系的排第一", 分组["高"][0]["id"], "C0")
    # 🔑 **这一条才是「只在同档内部比」的判据。**
    # 低危那个 C2 金额最高、最近、最频 —— 混成一批打分它会拿到全局第 1,
