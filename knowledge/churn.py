def 活跃档(idle_days):
    """她多久没来 → 落在活跃度轴的哪一格。**算不出返回 None。**

    边界全部**复用** `lifecycle.match()` —— 这里一个数字都不写。
    理由:六个含端边界(90/91/180/181/365/366)手抄一遍就多一份会漂的口径,
    而 `>= 90` 抄成 `> 90` **错出来的答案看起来完全合理**。
    """
    if idle_days is None:
        return None
    # order_cnt=1 挡掉「潜在」,不给 days_since_first_order 挡掉「新客」,
    # 金额单数都给 0 挡掉价值标签 —— 剩下的命中必然**恰好一个**在轴上。
    命中 = [d for d in lifecycle.match({"idle_days": idle_days, "order_cnt": 1})
            if d in 活跃度轴]
    assert len(命中) == 1, f"idle_days={idle_days} 在活跃度轴上命中 {命中} —— 轴和口径对不上了"
    return 命中[0]


def _距离(档):
    """离「活跃」几步。算不出返回 None —— **「算不出」不是 0。**"""
    return 活跃度轴.index(档) if 档 in 活跃度轴 else None


def _那天的标签(条):
    """拿那天存下的四个事实重跑判定,返回**命中的全部**标签(不是单一主档)。

    ⚠️ 缺字段**当场抛**,不 try/except 兜底 ——
    2026-10-05 栽过:一个 `try: ... except: pass` 让下界形同虚设,
    23216 条历史的档位全是字符串 "None" 而所有检查都是绿的。
    """
    return lifecycle.match({
        "idle_days": 条["idle_days"],
        "orders_12m": 条["orders_12m"],
        "amount_12m": 条["amount_12m"],
        "quarters_12m": 条["quarters_12m"],
        "order_cnt": 1 if (条["orders_12m"] or 0) > 0 or (条["amount_12m"] or 0) > 0 else 0,
    })


def 判(档位历史):
    """她在不在往下走。返回 dict,**要不要预警 / 码 / 严重程度 / 人话**。

    `档位历史`:`lifecycle_history` 表的行,**键名逐字就是列名** ——
    customer_id / as_of / lifecycle / idle_days / orders_12m / amount_12m /
    quarters_12m。顺序不管,这里自己按 as_of 排。

    ⚠️ **键名一个字都不许改成别的**。2026-10-05 栽过:`decide()` 返回的键是
    「生命周期」而我写了 `.get("lifecycle")`,**静静返回 None**,
    而我的验证用的是同一个错读法,所以必然一致 ——
    **用同一个错读法去验,永远验不出这个错。**
    """
    行 = sorted(档位历史, key=lambda h: (h["as_of"], h.get("id") or 0))

    # ── 说不出来的两种,各自一个码 ────────────────────────────
    # ⚠️ 「只有一次判定」和「判了两次没变」**不是一回事**:
    # > 一个「还没有第二次判定」的客户,和一个「两次判定之间没动」的,
    # > **在「这次和上次一样」这句话上长得一模一样** —— 而前者压根没有上次。
    if len(行) < 2:
        return {"要不要预警": False, "码": "NO_HISTORY", "严重程度": None,
                "话": f"只有 {len(行)} 条判定记录 —— **说不出她在不在动**,"
                      f"这不叫「没在流失」,叫还看不出来",
                "从": None, "到": None, "退了几步": None}

    现在, 之前 = 行[-1], 行[:-1]
    到 = 活跃档(现在["idle_days"])
    if 到 is None:
        return {"要不要预警": False, "码": "NO_HISTORY", "严重程度": None,
                "话": "最新那条没有闲置天数 —— **判不了,不当没事**",
                "从": None, "到": None, "退了几步": None}

    # 她在这段历史里**最靠前过的那一格** —— 下滑要和「她自己的最好状态」比,
    # 不和上一条比:上一条可能已经是掉下来之后的了。
    历史档 = [活跃档(h["idle_days"]) for h in 行]
    有效 = [d for d in 历史档 if d is not None]
    最好 = min(有效, key=_距离)
    # **「她最后一次还在最好状态」那一条** —— 下滑是从那天之后开始的,
    # 不是从历史第一条开始的。她可能前三条都好好的,第四条才开始掉。
    最好那条 = 行[max(i for i, d in enumerate(历史档) if d == 最好)]
    从 = 活跃档(行[-2]["idle_days"])
    退了 = _距离(到) - _距离(最好)

    # ── 没下过单的,不归这里管(和 reactivate 的 NOT_YET 对齐) ──
    if all("潜在" in _那天的标签(h) for h in 行):
        return {"要不要预警": False, "码": "NEVER_BOUGHT", "严重程度": None,
                "话": "她从来没下过单 —— **她不是冷了,是还没热过**,这不归挽回管",
                "从": 从, "到": 到, "退了几步": 0}

    # ── 可惜程度:从**当时的事实**重跑,不读档位标签 ────────────
    曾有价值 = sorted({t for h in 行 for t in _那天的标签(h) if t in 价值标签})
    # ⚠️ **排序必须确定。** 不排的话次序跟着判定命中的顺序走,
    # 同一批数据今天明天可能不一样 —— 而数据一个字没变。
    # (`rfm.py` 那条「排序必须确定」说的是同一件事。)
    现有价值 = sorted({t for t in _那天的标签(现在) if t in 价值标签})

    def 收(码, 预警, 严重度, 话):
        序 = [_距离(d) for d in 历史档 if d is not None]
        return {"要不要预警": 预警, "码": 码, "严重程度": 严重度, "话": 话,
                "从": 从, "到": 到, "退了几步": max(退了, 0),
                # **单步最大退幅** —— 和「退了几步」是两个数,见下面那段注释
                "单步最大退幅": max((序[j] - 序[j - 1] for j in range(1, len(序))), default=0),
                "最好那天": 最好那条["as_of"], "最好时是": 最好,
                "曾经是": 曾有价值, "现在还是": 现有价值}

    # ── 已经到底了:不是预警,是复盘 ──────────────────────────
    # **预警的意思是还来得及。** 超过 365 天再报「预警」是自欺:
    # > 一条「来得及的预警」和一条「已经走完了的」,
    # > **在那行红色的提醒上长得一模一样** —— 而后者该做的事完全不同。
    if 到 == "流失":
        可 = f"(她曾经是{'、'.join(曾有价值)},**更可惜**)" if 曾有价值 else ""
        return 收("GONE", False, None,
                  f"她已经 {现在['idle_days']} 天没来 —— **超过一年,这不是预警是复盘**{可};"
                  f"要联系归召回,得先有由头(见促活口径)")

    # ── 退过又回来了:单独一个码,因为下一步完全不同 ────────────
    # ⚠️ **「我们看见她退下去」和「她一进视野就已经在下面」不是一回事。**
    # > 一个「退到休眠又回来」的客户,和一个「建档时就已经休眠、后来才活跃起来」的,
    # > **在「现在比最差的时候好」这句话上长得一模一样** ——
    # > 而前者有「上次我们做了什么」可查,后者**压根没有上次**。
    # 所以 RECOVERED 要求历史里真的出现过「比她自己早先的最好状态更差」那一步。
    序 = [_距离(d) for d in 历史档 if d is not None]
    退过 = any(序[j] > min(序[:j]) for j in range(1, len(序)))
    if 退了 <= 0 and 退过:
        最远 = max(有效, key=_距离)
        if _距离(最远) > _距离(到):
            return 收("RECOVERED", False, None,
                      f"她一度退到「{最远}」,现在回到「{到}」—— "
                      f"**这不是预警**,去看上次做了什么、能不能复用")

    if 退了 <= 0:
        if 从 and _距离(到) < _距离(从):
            return 收("IMPROVING", False, None, f"她从「{从}」回到「{到}」,在往回走")
        return 收("STABLE", False, None, f"活跃度一直在「{到}」,没退")

    # ── 在往下走 ────────────────────────────────────────────
    # 严重程度 = **走到哪一步** × **有多可惜**,两个维度,不合成一个分数。
    远 = _距离(到) >= _距离("潜在流失")
    if 曾有价值 and 远:   等级 = "高"
    elif 曾有价值 or 远:  等级 = "中"
    else:                 等级 = "低"

    # ⚠️ **「一脚踩空」和「慢慢凉」要分开量,不能用同一个减法说。**
    # 2026-10-05 真库跑出来的第一个高危客户就栽在这儿:她两条 as_of 差了快一年、
    # 中间还有三条记录,而我的理由写着「两次判定之间她就走掉了」。
    # > 一句「两次判定之间她就走掉了」和一句「这一年里她一步步退下来」,
    # > **在那个「退了 2 步」上长得一模一样** ——
    # > 而顾问照前一句会去翻那两个月,照后一句才会去看一整年的触点。
    # 所以:**总共退了几步**(和她最好时比)和**单步最大退幅**(相邻两条比)是两个数。
    序号 = [_距离(d) for d in 历史档 if d is not None]
    单步最大 = max((序号[j] - 序号[j - 1] for j in range(1, len(序号))), default=0)

    跨 = f"{最好那条['as_of']} 还是「{最好}」,{现在['as_of']} 已经是「{到}」"
    # ⚠️ **「曾经是」和「现在仍然是」不是同一句话。**
    # 2026-10-05 真跑工具时看见的:一个活跃度退了两步、而忠诚/高价值**都还在**的客户,
    # 理由里写着「她曾经是忠诚、高价值」。
    # > 一句「她曾经是忠诚」说给一个**现在仍然是**忠诚的客户,
    # > 和说给一个标签已经掉了的,**在那句话上长得一模一样** ——
    # > 而顾问照前一句会对她说错话(「您以前是我们的忠诚客户」)。
    # 69 条自测抓不到它:那个 fixture 恰好是「标签掉了」那一种,
    # **这条分支的措辞从来没被人读到过**。
    if not 曾有价值:
        可 = ""
    elif 现有价值:
        可 = f";她**现在仍然是**{'、'.join(现有价值)}(所以更可惜)"
    else:
        可 = f";她曾经是{'、'.join(曾有价值)}(**现在这个标签已经没了**)"
    if 单步最大 >= 2:
        跳 = f";**一次判定之间就退了 {单步最大} 步**,那一段里发生了什么要先查"
    elif 退了 >= 2:
        跳 = f";**是一步一步退下来的**(共 {退了} 步),不是哪一天突然走掉"
    else:
        跳 = ""
    return 收("SLIPPING", True, 等级,
              f"{跨} —— 在活跃度上一共退了 {退了} 步{可}{跳}。"
              f"**要不要现在联系要另算**(有没有由头,见促活口径)")


def 排名(预警们):
    """同一严重档内部排序。返回 {严重程度: [按先联系顺序排好的]}。

    ⚠️ **只在同一档内部比。** RFM 是五分位,分数取决于传进来的是哪一批人 ——
    把高危和低危混在一批里打分,高危里排最后的会比低危里排第一的分数低,
    而「谁先联系」这个结论就反了。
    (`rfm.py` 开头那段「分数只在这一批人内部可比」说的就是这件事。)
    """
    出 = {}
    for 等 in 严重:
        批 = [w for w in 预警们 if w.get("严重程度") == 等 and w.get("要不要预警")]
        if 批:
            出[等] = rfm.score(批)
    return 出


