    # > 一个改坏之后仍然成立的断言,和一个真能抓住这次破坏的,
    # > **在那份咬合清单上长得一模一样。**
    # (第一版我拿「分组人数是 [2,1,1]」和「低危第一名的顺序是 1」当判据,
    #  这两条混批之后照样绿 —— 写咬合规格的时候才发现。)
    ck("高危里的第一名,先联系顺序得是 1", 分组["高"][0]["先联系顺序"], 1)
    ck("每一档都各自从 1 开始编号",
       [分组[k][0]["先联系顺序"] for k in ("高", "中", "低")], [1, 1, 1])

    # ── 每个码都要说得出下一步 ───────────────────────────────
    for 条码 in 下一步:
        ck(f"{条码} 说得出下一步", bool(下一步[条码]), True)
