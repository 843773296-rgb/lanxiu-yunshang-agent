def 未到点(开始时间, 今天):
    """还没到预约时间 —— **既不算到店,也不算流失**,整条不进分母。

    今天从外面传。理由同 `review.py`:口径模块取了当前时间,
    同一批数据在不同时刻算出不同结果,真值对账没法复现。
    """
    return bool(开始时间) and 开始时间[:10] > 今天


def 环节转化(这一环, 上一环, 环名=""):
    """÷ 上一环 —— 回答「**这一环**漏了多少」。分母为零时不给数。"""
    if not 上一环:
        return (f"上一环就是 0 个人,{环名 or '这一环'}的转化率无从谈起", None)
    return (f"{这一环}/{上一环} = {这一环 * 100 // 上一环}%", round(这一环 / 上一环, 4))


def 整体转化(这一环, 总数, 环名=""):
    """÷ 总预约 —— 回答「一百个预约最后剩几个」。"""
    if not 总数:
        return ("一条预约都没有,转化率无从谈起", None)
    return (f"{这一环}/{总数} = {这一环 * 100 // 总数}%", round(这一环 / 总数, 4))


def 最窄的一环(各环):
    """哪一环漏得最狠 —— **按环节转化率找,不是按人数差找**。

    按人数差找会永远指向第一环:一百个人里漏掉四十个,和十个人里漏掉九个,
    前者人数差大,后者才是真的堵。**漏斗前宽后窄是天然的,不是问题。**

    各环:[(环名, 人数), ...] 按顺序。
    """
    worst, rate = None, None
    for i in range(1, len(各环)):
        名, n = 各环[i]
        上 = 各环[i - 1][1]
        if not 上:
            continue
        r = n / 上
        if rate is None or r < rate:
            worst, rate = (各环[i - 1][0], 名, n, 上), r
    if not worst:
        return None
    return (f"最窄的一环是「{worst[0]} → {worst[1]}」:"
            f"{worst[3]} 个只剩 {worst[2]} 个({int(rate * 100)}%)")
