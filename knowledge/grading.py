#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""推档口径 —— **1237 条尺码不是 1237 个数,是 12 条档差加一张基码表。**

## 这个模块存在的理由

`size_spec` 有 1237 条,全部是推出来的:`基码值 + 档差 × 尺码序号`。
让版师逐条核 1237 个数是不现实的,而他真正该核的只有两样:

    基码表   86 个版型 × 各自几个部位的基准值
    档差表   12 条(胸围 +4、肩宽 +1……)

**把「要核 1237 个」压成「要核 12 条」,这是这个模块干的全部事。**

## ⚠️ 一个「仅供参考」的数,和一个能用的数,在表上长得一模一样

知识库里写着一条特例:**马面裙的腰围不按档差推** ——
褶位是从腰围反推排布的,腰围变了褶位要重排,不是简单加 4cm。
所以那一格的 `+4` 只是**下单参考**,真正出货必须由版师按实际腰围重排。

而在 `size_spec` 里,PT04 的 M 码腰围是 `72.0`,PT01 的 M 码胸围是 `96.0` ——
**两个数长得一模一样,一个能直接用,一个不能。**
看表的人没有任何办法分辨,于是那条特例只存在于一份 md 的一个段落里。

这和这个项目反复撞的是同一件事:**估算 / 复核 / 版师 / BOM 是四种可信度,
不许长得一样。** 现在多一种:**「推得出但不作数」**。

## ⚠️ 特例按结构判,不按版型编码

md 里那条特例写的是「**PT04 / PT05**」。而库里有 **5 个**马面裙
(PT04、PT05,加上后来的 PT76–78 改良马面裙),**五个都有褶裥片、都有腰围**。

按编码写死的话,后三个的腰围会**静默地被当成能用的数** ——
而它们和前两个是同一个结构问题。所以判据是:

> **这个版型的裁片里有「褶裥片」⇒ 它的腰围是从褶位反推的 ⇒ 腰围只是下单参考。**

编码会随着新增版型而漏,结构不会。这和「判据贴着字面、不贴着含义」
是同一个坑的第 N 次 —— 只是这次它藏在一份 md 的表格里。

## 口径模块不碰数据库,也不取当前日期

和 `lifecycle.py` / `rfm.py` / `review.py` 同一个分层。
谁负责判定,谁就不该同时负责取数 —— 否则真值对账没法复现。
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
MD_PT = os.path.join(HERE, "10-版型库.md")

# 尺码序号,以 M 为 0。**和 derive_pattern.SIZE_NO 是同一件事** ——
# 那边是推档用的,这边是核档用的,两边必须一致,`grading_check` 会对一次。
尺码序号 = {"S": -1, "M": 0, "均码": 0, "L": 1, "XL": 2}

# ⚠️ **童款不在这套序号里,而这件事原来是静默的。**
#
# 推档那边写的是 `SIZE_NO.get(sz, 0)` —— 一个 `.get(x, 0)` 的默认值。
# 童款的尺码是**身高码**(110 / 120 / 130 / 140),一个都不在表里,
# 于是四个码的序号全是 0,**推出来四组一模一样的数**:
# 110 码和 140 码的孩子(身高差 30cm)拿到同一张尺码表。
#
# 它没有报过任何错。这是这个项目反复撞的那件事的又一个样本:
# **失败要有声音**,而 `.get(键, 0)` 恰恰是最安静的一种失败 ——
# 它把「查不到」变成了一个看起来完全正常的数。
#
# 童装的档差是**按身高分档**的,每档的各部位增量只有版师给得出来,
# 知识库里没有这张表。**所以不替它猜** —— 和「会员积分门槛没定义就不猜」
# 是同一条。现在的做法是把这 70 格全部标成「推得出但不作数」,
# 让它在每一个看得到尺码表的地方都自己说出来。
童款尺码体系未定义 = ("童款按**身高码**分档(110 / 120 / 130 / 140),"
                     "而档差表是成人 S/M/L/XL 的那一套 —— "
                     "**童装的档差知识库里没有**。"
                     "现在这几个码的尺寸是**同一组数**(序号都算成了 0),"
                     "不能直接拿去裁 —— 须由版师给出童装档差后重推")


def 序号(尺码):
    """尺码 → 序号。**认不出来返回 None,不返回 0。**

    返回 0 的话,「M 码」和「一个没见过的码」就变成同一件事 ——
    那正是童款那 70 格的来源。
    """
    return 尺码序号.get(str(尺码).strip())


def 尺码体系未定义(尺码表):
    """这一组尺码里有认不出来的吗?有就返回原因,没有返回 None。"""
    未知 = [s for s in (尺码表 or []) if 序号(s) is None]
    return 童款尺码体系未定义 if 未知 else None

# 判定「这个版型的这个部位只是下单参考」的结构条件。
# key = 部位名,value = (触发这条的裁片关键词, 为什么)
# ⚠️ **关键词是「褶裥」不是「褶裥片」。** 第一版写了「褶裥片」,
# 而明制曳撒的那一片叫「**下裳褶裥**」—— 它有马面、有褶裥,
# 腰围是同一个结构问题,却被关键词差的那一个字漏掉了,**而且不报错**。
# 这和「44 种裁片一个都不许静默丢」是同一条:
# **漏掉的那个不会举手,它只是安静地不在清单里。**
仅供参考 = {
    "腰围": ("褶裥",
             "褶位是从腰围反推排布的,腰围变了褶位要重排 —— 不是简单加 4cm。"
             "这一格是**下单参考**,出货必须由版师按实际腰围重排褶位"),
}


def 档差(md=None):
    """从 10-版型库.md 读档差表。**手抄一份的话,改 md 不改代码就开始漂。**"""
    t = md if md is not None else open(MD_PT, encoding="utf-8").read()
    out = {}
    for line in t.split("\n"):
        m = re.match(r"\|\s*([一-鿿]+)\s*\|\s*\+([\d.]+)\s*\|", line.strip())
        if m: out[m.group(1)] = float(m.group(2))
    return out


def 参考项(裁片名):
    """这个版型有哪些部位「推得出但不作数」。传裁片名的集合,返回 {部位: 理由}。

    **传裁片名而不是版型编码** —— 见文件头那条:编码会漏,结构不会。
    """
    有 = set(裁片名 or ())
    return {部位: 理由 for 部位, (关键词, 理由) in 仅供参考.items()
            if any(关键词 in n for n in 有)}


def 覆盖范围(基码值, 部位, 尺码表):
    """这个版型的这个部位,从最小码到最大码覆盖多宽。

    版师问的是「这个版型能做多大的人」,而尺码表答的是「M 码胸围 96」——
    **一个数答不了一个范围的问题。**
    """
    d = 档差().get(部位)
    if d is None or not 尺码表: return None
    ns = [尺码序号.get(s, 0) for s in 尺码表]
    return (round(基码值 + d * min(ns), 1), round(基码值 + d * max(ns), 1))


# 量纲常识 —— **每条都是定义性的或极宽的,不设「看起来合理」的阈值**。
#
# 上一次栽在这儿:裁片占比第一版把「单片 > 60%」一律当异常,
# 而一条马面裙的裙片占 90% 本来就正常。**一刀切的阈值会把对的判成错的**,
# 而那种误报比漏报更贵:它会让人去改一个本来对的数。
量纲 = [
    ("值必须为正",        lambda 部位, v: v > 0),
    ("领围必须小于胸围",   None),      # 跨部位,单独判
    ("马面宽必须小于腰围", None),
]

长度上限 = {"衣长": 200, "上襦衣长": 120, "裙长": 200, "裤长": 200, "通袖长": 300}


def 体检(部位值, 参考的部位=()):
    """一个版型一个尺码的量纲体检。`部位值` = {部位: 值},返回疑点列表。

    **返回空列表要能和「没扫到」分开** —— 调用方必须自己报样本量。
    """
    bad = []
    for 部位, v in 部位值.items():
        if v is None or v <= 0:
            bad.append(f"{部位}={v} —— 尺寸不可能是 0 或负数")
        if 部位 in 长度上限 and v and v > 长度上限[部位]:
            bad.append(f"{部位}={v}cm 超过 {长度上限[部位]}cm —— 多半是单位或小数点错了")
    领, 胸 = 部位值.get("领围"), 部位值.get("胸围")
    if 领 and 胸 and 领 >= 胸:
        bad.append(f"领围 {领} ≥ 胸围 {胸} —— 这件衣服套不进去")
    宽, 腰 = 部位值.get("马面宽"), 部位值.get("腰围")
    if 宽 and 腰 and 宽 >= 腰:
        bad.append(f"马面宽 {宽} ≥ 腰围 {腰} —— 马面是裙门,不可能比整圈腰还宽")
    return bad


def 核档(尺码到部位值, 参考的部位=()):
    """**核的是档差,不是 1237 个数。**

    传 {尺码: {部位: 值}},返回 {部位: {"档差": 实际算出来的, "一致": bool, ...}}。
    相邻码之间的差必须处处相等,而且等于档差表里那个数 —— 这是推档的**定义**,
    所以这条判据零误报:不一致就是真的有一格不对。
    """
    表, out = 档差(), {}
    体系未定义 = 尺码体系未定义(list(尺码到部位值))
    码 = sorted(尺码到部位值, key=lambda s: 序号(s) if 序号(s) is not None else 0)
    for 部位 in sorted({k for v in 尺码到部位值.values() for k in v}):
        vs = [(序号(s), 尺码到部位值[s].get(部位)) for s in 码]
        vs = [(n, v) for n, v in vs if v is not None and n is not None]
        差 = {round((v2 - v1) / (n2 - n1), 3)
              for (n1, v1), (n2, v2) in zip(vs, vs[1:]) if n2 != n1}
        应 = 表.get(部位)
        # **「算不出来」和「算出来不对」不是一回事** —— 而它们在输出上
        # 长得一模一样(都是一个「不一致」)。童款那四个版型第一次扫出来时
        # 报的就是「实际 [] ≠ 规则 4.0」:看着像档差错了,实际是**一个码都比不了**。
        # **红错理由比不红更费事**:照着那条去查档差是白费功夫。
        算不出 = (len(vs) < 2 or not 差)
        out[部位] = {
            "尺码数": len(vs),
            "实际档差": sorted(差) if 差 else [],
            "规则档差": 应,
            "算不出来": 算不出,
            "算不出来的原因": (体系未定义 if 算不出 and 体系未定义 else
                               ("只有一个码,没有相邻码可比" if 算不出 else None)),
            "处处相等": (not 算不出) and len(差) == 1,
            "和规则一致": (len(差) == 1 and 应 is not None
                          and abs(list(差)[0] - 应) < 1e-6),
            "有规则": 应 is not None,
            "仅供参考": 部位 in (参考的部位 or ()),
        }
    return out


