"""**部位** —— 客户看得见的地方,和裁片不是一回事。

## 为什么要单独有这一层

设计稿的「部件」配置是按部位分的(领口 / 裙摆),而库里原来只有
`product_custom.mt_opts = "云锦,真丝素罗"` —— **一个扁平字符串,没有部位**。
于是「领口能不能用织金缎」这个问题**根本表达不了**。

2026-09-14 业务确认:**门店接单时客户确实分部位选料,记在 pad 上。**
pad 上那份记录不进报价、不进 BOM、不进工单,也**和订单没有绑定关系** ——
客户说「我领口选的是织金缎」,系统里查不到。
**一个在 pad 上流转的字段,和一个不存在的字段,在系统里效果一样。**

## 部位从**裁片归并**而来,不是我编的

|        | 是什么 | 例子 | 给谁看 |
|--------|--------|------|--------|
| 裁片   | 版师**裁布的单位** | 上襦前片、大襟贴边、褶裥片 | 版房 / 车间 |
| 部位   | 客户**看得见的地方** | 领口、裙、袖 | 卖场 / 客户 |

直接拿裁片当部位,客户会在配置页上看到「**大襟贴边**」——
那是版房的话,不是卖场的话。所以归并一层。

**归并规则写在下面,是给业务核的** —— 它是一份推断,不是事实。
业务看过之后要么认,要么改这张表。

## 两条边界(摸底时确认的,能把改动范围压下来一大截)

**① 相容矩阵不加部位。** 现在 `工艺 × 材质` 2025 格;
乘上部位就是几万格,没人维护得了。而且没必要:
**「苏绣能不能做在真丝上」和做在哪个部位无关** —— 那是材质和工艺之间的物理性质。

**② 颜色不进 SKU。** 进了的话一件定制品会炸出 部位×材质×颜色 行 SKU,
而**颜色是配置项不是库存单位** —— 定制品本来就不备库存。

## ⚠️ 本期不按部位算料

用料现在按**版型整件**算(`pattern.fabric_base`)。分部位选料之后这些米数
要按裁片分摊,而 `pattern_piece` **没有面积、没有用料占比** ——
补那一列要 84 个版型 × 平均 5 个裁片 ≈ 400 个数,**只有版师给得出来**。

所以第一步:**报价按这个商品可选料里最贵的那种算**,宁可报高不可报低,
并且在报价上**显式写明这是上限**。见 `报价口径`。
"""

# ══════════════════════════════════════════════════════════════════════
# **这里是「部位」的唯一来源。** 任何地方要用部位词,从这儿取,不许自己写。
#
# ## 2026-09-14 的裁决:以这套为准
#
# 设计交互稿里部位的叫法**自己就不统一**:
#
#     pad 配置页的二级 tab    上身 / 袖子 / 内衬
#     工艺文档打印稿的「位置」 领口 / 裙摆
#
# 同一个系统的两个界面用两套词 —— 车间拿到工艺文档,**对不上 pad 上选的**。
# 业务裁决:**以这套(从裁片 + BOM 推出来的)为准**,交互稿按这套改。
#
# 还有一处同源的不统一:工艺文档那一列叫「**工艺**」,而值是「真丝」——
# 那是**面料**。库里 `craft` 表把「工艺」(45 条)和「材质」(45 条)分得很清,
# 混着叫会让车间不知道该看哪张表。所以工艺文档里这一列叫「**面料**」。
#
# ## 为什么要写在这儿,而不是写在文档里
#
# 写在文档里的裁决,下一个人照着设计稿改代码时**不会去翻文档**。
# 写在这儿,他改的时候就会看到;而 `part_check` 还会拦住
# 「别处自己写一套部位词」这件事 —— **单一来源不靠自觉,靠检查**。
# ══════════════════════════════════════════════════════════════════════

# 裁片 → 部位。**顺序有意义**:从上到下第一个命中的说了算。
# 例:「开衩贴边」里既有「贴边」也有「开衩」—— 开衩在下摆,不在门襟,
# 所以「下摆」那条要排在「门襟」前面。第一版排反了,把它归进了门襟。
归并规则 = [
    ("领口", ("领缘", "立领", "圆领", "方领", "竖领", "盘领", "坦领", "交领", "诃子")),
    ("袖",   ("大袖片", "短袖片", "袖片", "袖缘")),
    ("裙",   ("下裳", "裙头", "裙片", "裙腰", "裤腰", "褶裥", "马面")),
    ("横襕", ("横襕",)),
    ("系带", ("系带", "襳带", "绦")),
    ("下摆", ("开衩", "侧摆", "内摆", "摆片", "垂髾")),
    ("门襟", ("门襟", "大襟", "斜襟", "对襟", "拉链贴边", "补子位")),
    ("主身", ("前片", "后片", "衣身", "上襦", "背子", "腰接片")),
]

# ── 内衬:**它不在裁片里** ──────────────────────────────────────────
# 2026-09-14 业务指出漏了「内衬」(pad 配置页上的二级 tab 是「上身 / 袖子 / 内衬」)。
# 查下来它**结构上就推不出来**:
#
#   裁片里一条「里 / 衬」都没有 —— 裁片是**面料的裁法**,而里布是另一层
#   它在 **BOM 的备注**里:「上襦挂里」「褙子通身挂里」「长衫全挂里」
#                          「大袖易勾,加防勾内衬」
#   材料表里有 7 种里料 + 10 种衬料(真丝里布 ¥68/米、防勾内衬 ¥32/米 …)
#   **82 个版型里 37 个带挂里**
#
# 所以部位有**两个来源**,这件事必须写出来,否则下一个人还会漏:
#
#   从**裁片**来   领口 / 门襟 / 主身 / 袖 / 裙 / 下摆 / 横襕 / 系带
#   从**BOM**来    内衬          ← 面料之外的那一层
#   兜底           整件          ← 配饰,没有版型也没有裁片
#
# **一个只看一张表的归并,推不出另一张表里的东西** ——
# 而推不出来的表现是「配置页上少一个 tab」,不是报错。
# ⚠️ **只认「里料」,不认「衬料」。** 第一版把两者都算进去,
# 86 个版型里 82 个都冒出「内衬」这个部位 —— 那是错的:
#
#   里料  穿在里面那一层,**客户会选**
#         (真丝里布 ¥68/米 vs 棉质里布 ¥22/米,手感差很多)
#   衬料  定型用的(领衬 / 牵条、树脂衬、马尾衬、裙腰衬带),
#         **客户不选,版师定** —— 算成部位的话,配置页上会多出一个点不动的 tab
#
# 收紧之后是 58 / 86,那才是真的「这件衣服有可选内衬」。
内衬词 = ("挂里", "内衬")
内衬料类 = ("里料",)

# 配置页上的显示顺序 —— 从上到下,和人穿衣服的顺序一致;内衬在最后(它在里面)
部位顺序 = ["领口", "门襟", "主身", "袖", "腰", "裙", "下摆", "横襕", "系带",
            "内衬", "整件"]


def 归部位(裁片名):
    """一个裁片归到哪个部位。归不进去返回 None —— **不许静默丢**,
    调用方要把归不进去的报出来(`part_check` 盯着这条)。"""
    for 部, 词 in 归并规则:
        if any(k in (裁片名 or "") for k in 词):
            return 部
    return None


# **配饰没有部位之分。** 定制云肩、题字腰封这类:它们没有版型 ⇒ 没有裁片 ⇒
# 推不出部位,而它们**确实收定制加价**(实测云肩 ¥864、腰封 ¥396)。
# 硬给它们套成衣的部位(领口 / 裙摆)是编的 —— 云肩上没有「裙摆」。
# 它们的定制点是**整件的面料和工艺**,所以给一个明确的「整件」,
# 而不是让它们在「有钱没项」那一栏里挂着。
整件 = "整件"


def 形制的部位(conn, 版型码):
    """这个版型有哪些部位。**部位随形制变** —— 马面裙没有领口,立领长衫有。

    从它自己的裁片推,所以扩一个形制、加一个版型,部位自动就对。
    """
    if not 版型码:
        return [整件]               # 没有版型 ⇒ 配饰,整件定制
    ps = [r[0] for r in conn.execute(
        "SELECT name FROM pattern_piece WHERE pattern=?", (版型码,))]
    出 = {归部位(p) for p in ps} - {None}
    # **内衬走另一路:看 BOM,不看裁片。** 见上面 `内衬词` 那段说明。
    if conn.execute(
            "SELECT 1 FROM pattern_bom b LEFT JOIN material m ON m.code=b.material "
            "WHERE b.pattern=? AND (m.cat IN (" +
            ",".join("?" * len(内衬料类)) + ") OR " +
            " OR ".join(["b.note LIKE ?"] * len(内衬词)) + ") LIMIT 1",
            (版型码, *内衬料类, *[f"%{w}%" for w in 内衬词])).fetchone():
        出.add("内衬")
    return [b for b in 部位顺序 if b in 出] or [整件]


# 设计交互稿里出现过、但**不采用**的部位叫法。
# 留在这儿是为了让检查能认出「有人照交互稿写了一套」,
# 并且报错时说得出该用哪个词 —— **光说「不许用」,人还得自己猜用什么**。
交互稿旧称 = {"上身": "主身", "袖子": "袖", "裙摆": "裙", "衣身": "主身"}

# 一个部位上要配**两样**:用什么料、做什么工艺。
# 交互稿里这两样的叫法也不统一(和部位同一个毛病):
#
#     pad 一级 tab        面料选择 / **花型**选择
#     商品详情页设计稿    布料 / **花纹**
#     工艺文档那一列      「工艺」,而值是「真丝」—— 那其实是**面料**
#
# 库里 `craft` 表分得很清:`cat='材质'` 45 条、`cat='工艺'` 45 条。
# **以库里这套为准**:两个维度叫「面料」和「工艺」。
配置维度 = ("面料", "工艺")
维度旧称 = {"花型": "工艺", "花纹": "工艺", "布料": "面料"}

# ⚠️ **面料和工艺之间有相容矩阵**(2025 格,其中 441 对判「不可」)——
# 「妆花 × 香云纱」「缂丝 × 香云纱」这些组合做不出来。
# 所以同一个部位上选的面料和工艺**必须相容**,而这条
# 原来只在配置页拦,**订单上没人对过账**。
# 相容性和**部位无关**(苏绣能不能做在真丝上,跟做在领口还是裙摆没关系)——
# 这也是「相容矩阵不加部位维度」那条边界的由来。


# ── 哪个部位该给哪一类料 ──────────────────────────────────────────
# 2026-09-14 业务说「还没细分,你直接分配」。
# **分配不等于随便分** —— 有硬依据的只做那部分,其余维持「全部主料可选」。
#
# 依据是 **BOM 的备注**,那是版师写的「部位 → 用什么料」:
#
#     「上襦挂里」  → 真丝里布(里料)
#     「褙子通身挂里」→ 真丝里布(里料)
#     「马面部分挂里」→ 棉质里布(里料)
#     「裙头系带」  → 织带 / 系带(辅料)
#     「立领与门襟」 → 树脂衬(衬料)
#
# 所以按**材料类别**分层,而不是按我对某块料好不好看的判断:
#
#     内衬   里料      —— 现在铺的是主料(云锦),**那是错的:云锦不做里子**
#     系带   辅料      —— 织带 / 丝绦这类
#     其余   主料      —— 客户看得见的那一层
#
# ⚠️ **衬料不进来**:领衬 / 牵条 / 树脂衬是版师定型用的,客户不选
# (这也是「内衬」那个部位只认里料的同一条理由)。
#
# ✅ **外层部位不细分,这是 2026-09-14 拍过板的决定,不是待办。**
#
# 业务原话:「**维持可选,客户自己挑**」。
# 所以领口 / 门襟 / 主身 / 袖 / 裙 / 下摆一律给「这个商品的全部可选主料」,
# **由客户在配置页上自己挑**。
#
# ⚠️ **这和「还没细分」不是一回事,虽然数据长得一模一样。**
# 「还没细分」是欠着一件事,下一个人该去补;
# 「客户自己挑」是已经决定不做那件事,下一个人不该去补。
# **两种状态在代码里长得一样** —— 所以必须在这儿写明是哪一种,
# 否则会有人好心去编一套「领口适合织金缎、主身适合素缎」的细分出来。
#
# 为什么不细分:那种话是**审美和成本的判断,不是结构事实** ——
# 库里没有任何依据支持它(相容矩阵管的是面料 × 工艺,和部位无关;
# BOM 备注只写到「挂里用里布」这一层)。**编一个出来就是假装业务拍过板。**
部位料类 = {"内衬": ("里料",), "系带": ("辅料",)}
默认料类 = ("主料",)


def 部位可选料类(部位):
    """这个部位该从哪一类材料里选。见上面那段说明。"""
    return 部位料类.get(部位, 默认料类)


