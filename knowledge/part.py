"""**部位** —— 客户看得见的地方,和裁片不是一回事。

## 为什么要单独有这一层

设计稿的「部件」配置是按部位分的(领口 / 裙摆),而库里原来只有
`product_custom.mt_opts = "云锦,真丝素罗"` —— **一个扁平字符串,没有部位**。
于是「领口能不能用织金缎」这个问题**根本表达不了**。

2026-09-14 业务确认:**门店接单时客户确实分部位选料,记在 pad 上。**
pad 上那份记录不进报价、不进 BOM、不进工单,也**和订单没有绑定关系** ——
客户说「我领口选的是织金缎」,系统里查不到。
**一个在 pad 上流转的字段,和一个不存在的字段,在系统里效果一样。**

## 部位从**裁片归并**而来,不是我编的

|        | 是什么 | 例子 | 给谁看 |
|--------|--------|------|--------|
| 裁片   | 版师**裁布的单位** | 上襦前片、大襟贴边、褶裥片 | 版房 / 车间 |
| 部位   | 客户**看得见的地方** | 领口、裙、袖 | 卖场 / 客户 |

直接拿裁片当部位,客户会在配置页上看到「**大襟贴边**」——
那是版房的话,不是卖场的话。所以归并一层。

**归并规则写在下面,是给业务核的** —— 它是一份推断,不是事实。
业务看过之后要么认,要么改这张表。

## 两条边界(摸底时确认的,能把改动范围压下来一大截)

**① 相容矩阵不加部位。** 现在 `工艺 × 材质` 2025 格;
乘上部位就是几万格,没人维护得了。而且没必要:
**「苏绣能不能做在真丝上」和做在哪个部位无关** —— 那是材质和工艺之间的物理性质。

**② 颜色不进 SKU。** 进了的话一件定制品会炸出 部位×材质×颜色 行 SKU,
而**颜色是配置项不是库存单位** —— 定制品本来就不备库存。

## ⚠️ 本期不按部位算料

用料现在按**版型整件**算(`pattern.fabric_base`)。分部位选料之后这些米数
要按裁片分摊,而 `pattern_piece` **没有面积、没有用料占比** ——
补那一列要 84 个版型 × 平均 5 个裁片 ≈ 400 个数,**只有版师给得出来**。

所以第一步:**报价按这个商品可选料里最贵的那种算**,宁可报高不可报低,
并且在报价上**显式写明这是上限**。见 `报价口径`。
"""

# 裁片 → 部位。**顺序有意义**:从上到下第一个命中的说了算。
# 例:「开衩贴边」里既有「贴边」也有「开衩」—— 开衩在下摆,不在门襟,
# 所以「下摆」那条要排在「门襟」前面。第一版排反了,把它归进了门襟。
归并规则 = [
    ("领口", ("领缘", "立领", "圆领", "方领", "竖领", "盘领", "坦领", "交领", "诃子")),
    ("袖",   ("大袖片", "短袖片", "袖片", "袖缘")),
    ("裙",   ("下裳", "裙头", "裙片", "裙腰", "裤腰", "褶裥", "马面")),
    ("横襕", ("横襕",)),
    ("系带", ("系带", "襳带", "绦")),
    ("下摆", ("开衩", "侧摆", "内摆", "摆片", "垂髾")),
    ("门襟", ("门襟", "大襟", "斜襟", "对襟", "拉链贴边", "补子位")),
    ("主身", ("前片", "后片", "衣身", "上襦", "背子", "腰接片")),
]

# 配置页上的显示顺序 —— 从上到下,和人穿衣服的顺序一致
部位顺序 = ["领口", "门襟", "主身", "袖", "腰", "裙", "下摆", "横襕", "系带"]


def 归部位(裁片名):
    """一个裁片归到哪个部位。归不进去返回 None —— **不许静默丢**,
    调用方要把归不进去的报出来(`part_check` 盯着这条)。"""
    for 部, 词 in 归并规则:
        if any(k in (裁片名 or "") for k in 词):
            return 部
    return None


def 形制的部位(conn, 版型码):
    """这个版型有哪些部位。**部位随形制变** —— 马面裙没有领口,立领长衫有。

    从它自己的裁片推,所以扩一个形制、加一个版型,部位自动就对。
    """
    ps = [r[0] for r in conn.execute(
        "SELECT name FROM pattern_piece WHERE pattern=?", (版型码,))]
    出 = {归部位(p) for p in ps} - {None}
    return [b for b in 部位顺序 if b in 出]


