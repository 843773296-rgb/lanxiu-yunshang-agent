#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""来源等级的口径 —— **哪一条能对客户说,哪一条不能。**

## 这条规矩早就写着,而执行对不上

`README.md` 开头那句是这个库最重的一句:

> 知识库最怕的不是内容少,是**真假混在一起而读的人分不出来**。

档位也定好了三档(`public` / `scale` / `demo`),连「能不能对客户说」都写清了。
**问题出在没有任何东西去核它。** 2026-09-15 扫了一遍:

    public   29 条,**15 条连出处的名字都没有** —— 而这一档的定义是「给得出链接」
    scale    32 条,**31 条没有出处**
    demo      1 条**带着真实的非遗网链接** —— 它被低标了

也就是说:**46 条「能对客户说」的知识,溯不了源**;而一条溯得了源的被标成了不能说。

> **一个标着「公开可查、可溯源」却给不出出处的条目,比标着 demo 更糟。**
> 标 demo 的没人敢拿去承诺;标 public 的,顾问会照着它对客户说。

## 我**不替它编出处**

给不出出处的那 46 条,多半是从公开资料写的、只是没记链接 ——
**替它降成 demo 是说另一个方向的假话**(把真的公开知识说成虚构的),
而**替它编一个链接**更糟。

所以这里做的是第三件事:**让它自己说出来。**
查询返回里除了档位,还带一个**溯源状态** ——
「标着可溯源,但库里没有出处」会**跟着这一条一起被读到**,
模型没法再把它当成有出处的知识往外说。

**「补出处」是人的活,而「不许假装有出处」是代码的活。**

## 口径不手抄 —— 从 README 那张表读

档位的定义在 `README.md` 里,`knowledge/kb.py` 的正则也认这三个词。
这里**再抄一份**的话,改了 md 不改代码就开始漂,而漂了不报错。
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
MD = os.path.join(HERE, "README.md")

# 哪几档**必须给得出出处** —— 这是档位定义里那句「给得出链接」的执行面。
# `demo` 不要求:它本来就声明了自己是虚构的,**声明了就不算撒谎**。
要出处 = ("public", "scale")

# ⚠️ **这几个是占位符,不是出处。**
#
# 库里 106 条 demo 的 `src_name` 写着「演示数据」—— 那是在说「这里没有出处」,
# 而第一版判据看见「非空」就认成有出处了。
# **一个占位符和一个真值长得一模一样**,这个项目撞过好几次:
# 空白 ≠ 零分、没改动 ≠ 没记录、还没细分 ≠ 客户自己挑,现在是 **占位 ≠ 出处**。
#
# 后果不在 demo 上(它本来就不要求出处),而在**将来**:
# 哪天有人把一条 `public` 的 src_name 填成「演示数据」或「待补」,
# 判据会说它溯得了源。
非出处 = ("演示数据", "示例数据", "示例", "demo", "待补", "待确认", "无", "-", "—", "—")


def 是出处(x):
    """这串字是一个**能定位到东西**的出处,还是一个占位符?"""
    x = (x or "").strip()
    return bool(x) and x not in 非出处


def 档位(md=None):
    """从 README 那张表读:{档位: (含义, 能不能对客户说)}。"""
    t = md if md is not None else open(MD, encoding="utf-8").read()
    out = {}
    for line in t.split("\n"):
        m = re.match(r"\|\s*`(\w+)`\s*\|\s*(.+?)\s*\|\s*(.+?)\s*\|\s*$", line.strip())
        if m: out[m.group(1)] = (m.group(2), m.group(3))
    return out


def 对客口径(档):
    """这一档对客户能说到什么程度 —— **直接取 md 里那一列的原话**。"""
    d = 档位().get(档)
    return d[1] if d else "**未知来源等级**,按不能对外说处理"


def 溯源(档, 出处名=None, 出处链接=None):
    """这一条的溯源状态。返回 (齐不齐, 一句人话)。

    **齐不齐和档位是两件事**,而它们在表上长得一模一样:
    两条都写着 `public`,一条给得出链接、一条什么都没有,
    而读的人看到的是同一个词。
    """
    有 = 是出处(出处名) or 是出处(出处链接)
    if 档 not in 要出处:
        if 有:
            return (True, f"标着 `{档}`,**但库里其实有出处**"
                          f"({出处名 or 出处链接})—— 这一条**该升档**")
        return (True, None)
    if 有:
        return (True, None)
    return (False, f"标着 `{档}`(定义是「给得出链接」),**而库里没有出处** —— "
                   f"**不能当成可溯源的知识对客户说**,须先补出处或降档")


def 标注(档, 出处名=None, 出处链接=None):
    """给工具返回用的一小块:档位 + 对客口径 + 溯源状态。

    **三样一起给,缺一样都会被读成另一个意思**:
    只给档位,读的人以为标着 public 就有出处;
    只给出处,读的人不知道这一条能不能对外说。
    """
    齐, 话 = 溯源(档, 出处名, 出处链接)
    out = {"来源等级": 档, "对客户": 对客口径(档)}
    # **占位符不许当出处贴出去** —— 贴一个「演示数据」到「出处」那一栏,
    # 读的人会以为这一条有来源。
    名, 链 = (出处名 if 是出处(出处名) else None), (出处链接 if 是出处(出处链接) else None)
    if 名 or 链:
        out["出处"] = 名 or 链
        if 链: out["出处链接"] = 链
    if 话: out["⚠️ 溯源"] = 话
    return out


if __name__ == "__main__":
    d = 档位()
    print(f"从 README 读到 {len(d)} 档:")
    for k, (含义, 对客) in d.items():
        print(f"  {k:8} {含义[:30]:34} → 对客户:{对客[:30]}")
    print()
    print("自测:public 无出处 →", 溯源("public")[1][:40])
    print("自测:public 有出处 →", 溯源("public", "中国非物质文化遗产网")[1])
    print("自测:demo 有出处   →", 溯源("demo", None, "https://x")[1][:40])
