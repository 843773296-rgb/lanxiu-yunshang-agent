"""月度复盘的口径 —— **算什么、怎么算、什么时候不许给数**。

判定逻辑写在这里,`backend/api.py` 只负责取数和包装。
和 `lifecycle.py` / `rfm.py` 同一个分层:**口径模块不碰数据库,也不取当前日期** ——
谁负责判定,谁就不该同时负责取时间,否则同一批数据在不同时刻算出不同结果,
真值对账没法复现。

## 这份复盘和一张普通报表的区别

普通报表报「这个月完成了 46 条」。而这份要回答的是**三类不同的问题**:

    做得怎么样   完成率、逾期、平均耗时 —— 这些是**相对指标**,
                 只有和上个月比、和别的顾问比才有意义
    哪里不对劲   改派次数、逾期集中在谁身上 —— 这些是**信号**,
                 不是成绩单;报出来是让人去看,不是让人打分
    AI 有没有用  建议采纳率 —— **这是这套系统独有的数**,
                 别处拿不到:它记着「agent 建议了谁 / 人最后选了谁」

## 分母为零,不许给比率

这是这个项目第 10 版报告的主题:**没有分母的「没问题」不是信息**。

具体到这里:待分配池一直是空的(预约都自动派出去了),所以**一条分派都没发生过**。
这时候「采纳率」有三种写法,只有一种是对的:

    ❌ 0%          —— 会被读成「建议一次都没被采纳」
    ❌ 不显示这一行 —— 会被读成「这个月没问题」
    ✅ 「没发生过分派(0 次),所以采纳率无从谈起」

**「没有数据」和「数据是零」是两件事**,而它们在一张报表上长得一模一样。
"""

# 一条任务算不算「这个月的」——按**截止时间**归月,不按创建时间。
# 理由:复盘看的是「这个月该做完的做完了没有」,而不是「这个月新建了多少」。
# 一条 8 月建、9 月截止的任务,是 9 月的成绩。
归月字段 = "end_ts"
归月字段_人话 = "截止时间"

# 逾期的定义:**到了截止时间还是「有效」**。
# 已完结的不算逾期 —— 哪怕完成得晚。理由:复盘要区分「还没做」和「做晚了」,
# 前者是眼下的风险(客户还在等),后者是历史。做晚了另有一个指标(见下)。
逾期 = "截止时间已过,状态仍是「有效」"

# 三类指标,验法完全不同 —— **别混**(见 CLAUDE.md 第 9 节 ③)
指标分类 = {
    "绝对": ["总数", "完成数", "逾期数", "改派次数", "分派次数"],
    "相对": ["完成率", "采纳率", "平均耗时"],
    "信号": ["逾期集中在谁身上", "改派理由", "待分配积压"],
}


def rate(分子, 分母, 说明=""):
    """算一个比率。**分母为零时不给数,给一句话。**

    返回 (可读文本, 数值或 None)。数值为 None 表示「无从谈起」,
    调用方不许把它当 0 用。
    """
    if not 分母:
        return (f"没发生过{说明 or '这件事'}(0 次),比率无从谈起", None)
    return (f"{分子}/{分母} = {分子 * 100 // 分母}%", round(分子 / 分母, 4))


def 逾期判定(状态, 截止, 今天):
    """**今天从外面传进来** —— 口径模块不取当前时间。

    不取的理由和 lifecycle.py 一样:取了的话,同一批数据在不同时刻算出不同结果,
    真值对账没法复现,而且「昨天跑是 3 条、今天跑是 5 条」分不清是数据变了还是时间走了。
    """
    if 状态 != "有效":
        return False
    return bool(截止) and 截止[:10] < 今天


def 摘要(n):
    """把一堆数变成一句人话。**先说该管的,再说做得怎么样。**

    顺序是有意的:一份复盘先看「有没有东西要处理」,再看「做得怎么样」——
    反过来的话,一个 92% 的完成率会把 5 条逾期盖住。
    """
    急 = []
    if n.get("逾期数"):
        急.append(f"**{n['逾期数']} 条逾期**")
    if n.get("待分配"):
        急.append(f"**{n['待分配']} 条待分配没人管**")
    if n.get("改派次数", 0) >= 3:
        急.append(f"改派了 {n['改派次数']} 次(值得看看是不是排班有问题)")
    head = "先看这几件:" + "、".join(急) if 急 else "没有逾期、没有积压。"
    return head


