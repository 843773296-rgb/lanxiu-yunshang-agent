"""会员等级与积分的口径 —— **怎么判档、积分怎么对账、哪些动作要审批**。

判定写在这里,`backend/api.py` 只取数。口径模块不碰数据库,也不取当前日期。

## 一、等级按「滚动 12 个月」,不按累计

`level_cfg` 里写得明明白白:「**滚动 12 个月**实付 ≥5000 元 或 完成订单 ≥2 单」。
这两个字很容易被忽略,而忽略的代价是**看不见的**:

    按滚动 12 个月算  →  106 个客户全部对上
    按累计算          →  96 个对上、10 个错     ← **91%**

**一个错口径达到 91% 的一致率,是最危险的情况 —— 它看起来就是对的。**
那 10 个人会默默拿到错等级(多半是老客户:早年买得多,近一年没动静,
按累计仍是黑金,按滚动已经掉档),而没有任何地方会报错。

## 二、数据从快照字段来,不现算

判档用 `customer.amount_12m` / `orders_12m`,**不是去 `ordr` 表现算**。

理由不是图省事:库里的 `ordr` 只有 49 笔完成订单、涉及 33 个客户,
而客户有 106 个 —— **订单表是个样本,不是完整的历史**。
拿它现算,大部分客户会算出「0 单 0 元」,然后被判成普通。
第一版就是这么干的,报出「78% 的客户等级不对」这个吓人的假结论。

**和 `idle_days` 那次是同一个形状**(见 CLAUDE.md:我加的 C5 全库 100% 红,
是尺子错了)。**快照字段存在,往往就说明现算不可靠。**

## 三、门槛是「或」,不是「且」

「实付 ≥5000 **或** 完成订单 ≥2 单」—— 满足任一条就够。
写成「且」的话,一个买了一件三万元礼服的客户会被判成普通。

取**最高的够格档**:从黑金往下试,第一个够格的就是它的档。

## 四、`need_points` 不参与判档

`level_cfg` 里还有个 `need_points`(银卡 3000 / 金卡 10000 / 黑金 25000),
但 `note` 里的门槛描述**一个字都没提积分**。

**所以这里不拿它判档,并且明说「这一条没定义清楚」** ——
它可能是另一条兑换路径(攒够积分也能升),也可能只是展示用的。
两种的业务含义完全不同。**没定义清楚的规则,不许替它猜一个。**

## 五、积分:两个来源都留着,但要对账

`points_log` 每条带一个 `balance`(这一笔之后的余额),客户档案上另有一个 `points`。
**同一个事实两个来源,必然漂。**

这本账修过一次(`tools/migrate_points_balance.py`),值得把过程写下来,
因为**第一眼的结论是错的**:

    第一眼   「268 条流水里 30 处对不上」→ 像是两个来源在打架
    量准了   档案 points vs 流水**最后一条**余额 —— 86/86 **全对**
             断的只是**中间**那些余额(被 max(0,...) 截断了)

所以 `delta` 是真的、终点是真的,**只有中间那一段是假的**。
修法是从终点倒推重算中间,**delta 一个都不改** ——
交易记录是原始凭证,不许为了让链条好看去动它。

修完 0 处断点,而且终点仍然 86/86。

**但对账这件事不能取消。** 修过一次不等于以后不会再漂:
只要两个来源都还在(而它们都必须在 —— 字段是客户在小程序里看到的数,
流水是账务原始记录),就有再漂的可能。所以工具照旧两个都给、照旧对账,
只是现在正常情况下应该报「0 处」。

**期初为负不是错误,是事实。** 倒推之后 19 个客户的期初是负数,
说明第一条记录之前还有没入账的收支。**把它截断成 0 才是造假** ——
截断之后链条依然断,只是断在一个看起来更体面的地方。

## 六、哪些动作必须审批

状态机 `bk-approval`:待审批 → 已通过 / 已驳回 / 已撤回,
而且「待审批 → 已通过/已驳回」这两条边**只有总部运营能走**(`fsm.APPROVAL_ROLE`)。

    等级调整   人为改档,绕过了门槛规则       → 必须审批
    积分调整   凭空加减积分,等于发钱         → 必须审批
    客户转移   改的是归属,影响提成和隔离范围  → 必须审批

**共同点:它们都绕过了某条本该自动成立的规则。**
自动算出来的档不用审批,人手改的才要 —— 审批管的是「例外」,不是「日常」。
"""

# 等级判定用哪两个字段。**写在这儿是为了让「用快照不现算」这个决定有个落点** ——
# 散在工具里的话,下一个人写新查询时会很自然地去 join ordr。
金额字段 = "amount_12m"
单数字段 = "orders_12m"
窗口 = "滚动 12 个月"

# 必须审批的三种动作,以及**为什么**。
要审批的 = {
    "等级调整": "人为改档,绕过了门槛规则",
    "积分调整": "凭空加减积分,等于发钱",
    "客户转移": "改的是归属,影响提成和隔离范围",
}
审批角色 = "总部运营"      # 和 fsm.APPROVAL_ROLE 一致;那边是唯一判定处,这里只是说明


def 判档(实付, 单数, 档位表):
    """算这个人该是哪一档。

    档位表:[{name, amount, orders, sort}, ...],**从库里读,不在这儿硬编** ——
    门槛是运营会调的东西,硬编一份就是第二个来源。

    门槛是**或**:满足金额或单数任一条即可。取最高的够格档。
    """
    for g in sorted(档位表, key=lambda x: x.get("sort") or 0, reverse=True):
        amt, n = g.get("amount") or 0, g.get("orders") or 0
        if (amt > 0 and (实付 or 0) >= amt) or (n > 0 and (单数 or 0) >= n):
            return g["name"]
    return next((g["name"] for g in sorted(档位表, key=lambda x: x.get("sort") or 0)),
                "普通")


def 离下一档(实付, 单数, 当前档, 档位表):
    """离升档还差多少 —— **两条路各报各的,不合并成一个「还差多少」**。

    合并的话必须选一条报,而选哪条取决于「哪条更近」,
    那是替客户做决定:有人愿意再买一单,有人只想凑金额。
    """
    ups = [g for g in sorted(档位表, key=lambda x: x.get("sort") or 0)
           if (g.get("sort") or 0) > next((h.get("sort") or 0) for h in 档位表
                                          if h["name"] == 当前档)]
    if not ups:
        return None
    g = ups[0]
    差额 = max(0, (g.get("amount") or 0) - (实付 or 0))
    差单 = max(0, (g.get("orders") or 0) - (单数 or 0))
    return dict(下一档=g["name"],
                再消费=f"{差额:.0f} 元" if 差额 else "已够",
                或再完成=f"{差单} 单" if 差单 else "已够",
                说明="两条路满足**任一条**即可升档;"
                     "不合并成一个数,是因为选哪条该由客户决定")


def 积分对账(流水):
    """逐条验「上一条余额 + 本次增减 = 本条余额」,**返回断点**。

    流水按时间正序传进来。返回 [(上一条余额, 本次增减, 表上的余额, 行为, 时间), ...]。
    **不修数据,只指出来** —— 余额字段和流水哪个是对的,这里判断不了。
    """
    bad = []
    for i in range(1, len(流水)):
        prev, cur = 流水[i - 1], 流水[i]
        应得 = (prev.get("balance") or 0) + (cur.get("delta") or 0)
        if 应得 != (cur.get("balance") or 0):
            bad.append((prev.get("balance"), cur.get("delta"), cur.get("balance"),
                        cur.get("behavior"), cur.get("ts")))
    return bad
