def 条件有据吗(项, 取值, 原话):
    """用户这句话里有没有依据填这个条件值。→ (有据, 为什么不行 或 None, 哪一类 或 None)。

    ⚠️ **「哪一类」要带出来,而不是让调用方去嗅那句话的字眼。**
    调用方要按类排序报告(矛盾优先),而「判据贴着字面」正是这个项目栽过七次的那件事。

    三种结果,**一种都不许合并**:

        有据         → (True, None)
        原话没提这件事 → (False, "…没说…")   缺信息,回去问
        原话说的和口径矛盾 → (False, "…不能用…") **这一次量体不该记**,要重量

    ⚠️ 第二种和第三种的下一步动作不同:一个是补一句话,一个是重新量。
    合成一句「条件填错了」,这两件就分不开了。
    """
    说 = str(原话 or "")
    项 = str(项 or "")
    取值 = str(取值 or "").strip()
    if not 取值:
        return False, f"没记「{项}」—— 三个条件缺一件就等于没量", "没填"
    # 先看有没有和口径矛盾的说法 —— 这一支优先,它比「没提」更要紧
    for 坏 in 条件矛盾说法.get(项, ()):
        if 坏 in 说:
            return False, (f"用户说的是「{坏}」,而量体口径的「{项}」只认 "
                           f"{' / '.join(条件取值.get(项, ()))} —— "
                           f"**这一次量出来的不能用**,不是填哪个值的问题。"
                           f"回去告诉用户要按口径重量一次。"), "矛盾"
    形们 = 条件说法.get(项, {}).get(取值)
    if not 形们:
        return (False, f"「{项}」填的是「{取值}」,只认 {' / '.join(条件取值.get(项, ()))}",
                "取值不对")
    词 = 维度词.get(项, ())
    for f in 形们:
        i = 说.find(f)
        while i >= 0:
            # 自己就带维度词的说法(赤足 / 无内搭 / 平静呼气)直接算有据
            if any(w in f for w in 词):
                return True, None, None
            # 裸说法:要和维度词在同一个小句里(逗号级)
            a = b = i
            while a > 0 and 说[a - 1] not in 小句边界:
                a -= 1
            while b < len(说) and 说[b] not in 小句边界:
                b += 1
            if any(w in 说[a:b] for w in 词):
                return True, None, None
            i = 说.find(f, i + 1)
    return (False, (f"用户这句话里没说「{项}」是什么 —— 模型填了「{取值}」。"
                    f"**三个条件不许默认**:同一个人穿厚内搭和不穿,胸围差 3–4cm;"
                    f"没记条件的尺寸,返修时判断不了是量错了还是穿法变了。回去问用户。"),
            "没说")
