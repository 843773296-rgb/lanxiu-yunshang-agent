def 校验一次(方式, 条件, 值们):
    """一次量体能不能登记。返回 [问题…](空 = 能登)。**不改数、不猜单位。**

    条件  {"内搭":…, "鞋":…, "呼吸":…}
    值们  {量体项名: 数值}
    """
    坏 = []
    if 方式 not in 亲自服务的方式:
        坏.append(f"量体方式「{方式}」不算数 —— 业务 09-22:不准远程量体,只认"
                  f"{' / '.join(亲自服务的方式)}(顾问亲自服务,客户没时间就上门)")
    for 项, 可取 in 条件取值.items():
        v = (条件 or {}).get(项)
        if not v:
            坏.append(f"没记「{项}」—— 三个条件缺一件就等于没量:返修时判断不了是量错了还是穿法变了")
        elif v not in 可取:
            坏.append(f"「{项}」填的是「{v}」,只认 {' / '.join(可取)}")
    if not 值们:
        坏.append("一项尺寸都没有")
    for 名, v in (值们 or {}).items():
        if 名 not in 合理范围:
            坏.append(f"没有「{名}」这个量体项")
            continue
        try:
            x = float(v)
        except (TypeError, ValueError):
            坏.append(f"「{名}」的值「{v}」不是数"); continue
        lo, hi = 合理范围[名]
        if not (lo <= x <= hi):
            坏.append(f"「{名}」{x} 不在人体合理范围 {lo}–{hi} 里 —— 多半是录错了(单位?小数点?),"
                      f"**不替你改**,核对后重录")
    return 坏


def 场次(记录们):
    """把逐项记录按 (着装人, 时间, 量体人) 归成一次一次的量体。返回按时间排好的 [场次…]。

    记录  [{"着装人","时间","量体人","方式","项","值","订单行"(可空)}]
    场次  {"着装人","时间","量体人","方式","订单行","值们":{项:值}}
    """
    场 = {}
    for r in 记录们:
        k = (r.get("着装人"), r.get("时间"), r.get("量体人"))
        s = 场.setdefault(k, dict(着装人=k[0], 时间=k[1], 量体人=k[2], 方式=r.get("方式"),
                                  订单行=r.get("订单行"), 值们={}))
        s["值们"][r["项"]] = r["值"]
        if r.get("订单行") and not s["订单行"]:
            s["订单行"] = r["订单行"]
    return sorted(场.values(), key=lambda s: str(s["时间"] or ""))


def 以哪次为准(场次们, 订单行=None, 截止=None):
    """这件衣服(或这个人)以哪一次量体为准。返回 (场次 | None, 一句人话)。

    订单行  给了:**只认绑在这一行上的下单量体**(业务 09-22:签单时重新量,以这次为准);
            没绑就是没有 —— **不退回去用别的场次**(业务选了「没有就不许下单」)
    没给:取**最近一整次**亲自量的(截止到 `截止`,不含之后的),缺项不从旧场次拼
    """
    亲 = [s for s in 场次们 if s.get("方式") in 亲自服务的方式]
    if 订单行 is not None:
        绑 = [s for s in 亲 if s.get("订单行") == 订单行]
        if not 绑:
            return None, ("这一件**没有下单量体** —— 业务 09-22:签单时要按这件衣服重新量,"
                          "以这次为准,**没有就不许下单**(回头客也一样)")
        s = 绑[-1]
        return s, f"以这一件的下单量体为准:{s['时间']} 由 {s['量体人']} {s['方式']}量"
    if 截止:
        亲 = [s for s in 亲 if str(s["时间"] or "") <= str(截止)]
    if not 亲:
        return None, "没有顾问亲自量(到店 / 上门)的量体"
    s = 亲[-1]
    return s, (f"以最近一次为准:{s['时间']} 由 {s['量体人']} {s['方式']}量"
               f"(共 {len(s['值们'])} 项;**缺的项就是缺,不从更早的场次拼**)")


def 缺哪几项(场次, 需要的项):
    """这次量体够不够做这件衣服。返回缺的项(空 = 够)。"""
    有 = set((场次 or {}).get("值们") or {})
    return [x for x in 需要的项 if x not in 有]


