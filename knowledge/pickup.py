# -*- coding: utf-8 -*-
"""定制品交付签收的口径 —— 到店代收、取件、试穿合身核验、完成、不合身转返修。

**业务 2026-09-22 定(用户逐条拍板):**

  ① 定制品由工厂发货**到店**,顾问代收;顾问邀约顾客到店取,实在来不了才代为**转寄**
  ② **签收 = 顾客确认「试穿合身」**:顾客在手机端点「试穿合身」,拿到一个 **6 位码**交给导购,
     导购在导购端输入,核验通过才算签收。**到店取的也走这个码**(到店和转寄证据一样硬,
     判责时不用区分两种签收)
  ③ 签收后订单进「待完成」,**完成由顾客确认**;顾客一直不确认,由顾问**二次追认**
  ④ 试穿**不合身不算签收**,直接转返修。判责:商品和订单留存数据对得上、又没有别的瑕疵
     → **顾客承担主要责任**(返修 / 重做收费);导购或打版的问题 → **企业承担**(免费)

## 为什么签收要一个码,不是导购点一下

导购点一下「顾客确认合身」,证据就只有导购的一面之词 —— 而这一下是**责任转移点**:
签收之后出尺寸问题,判责方向就变了。一个只有顾客手机能拿到的码,是顾客本人在场认可的凭据。
(和白坯试衣签字是同一个道理:责任转移点要有对方的动作,不能只有我方的记录。)

## 码的规矩(这几条是默认,业务没逐条定,用到时要说出去)

  · 6 位数字,**只对这一单有效**,**只能用一次**,**24 小时内有效**
  · 输错 **5 次**作废,要顾客重新点一次拿新码(防猜:6 位码 10⁶ 种,5 次猜中的概率是 5×10⁻⁶)
  · 库里只存码的**哈希**,不存明文 —— 导购端和库都看不到顾客那个码
"""
import hashlib, hmac, secrets, datetime

码位数 = 6
码有效小时 = 24
码最多试 = 5
追认等几天 = 15          # 签收后多少天顾客还没确认完成,提醒顾问去跟进 / 允许追认
码_依据 = ("6 位码只对这一单、只能用一次、24 小时有效、输错 5 次作废 —— "
          "这几个数是默认值,**业务没逐条确认**;业务定的是「顾客手机端点试穿合身出码、导购输入核验」")
取件方式 = ("到店取", "转寄")


def _t(s):
    return datetime.datetime.strptime(str(s)[:16], "%Y-%m-%d %H:%M")


def _fmt(t):
    return t.strftime("%Y-%m-%d %H:%M")


def 码哈希(order_id, code):
    """库里只存这个。带上单号,同一个码换一单就对不上。"""
    return hashlib.sha256(f"fit:{order_id}:{code}".encode()).hexdigest()


def 出码(order_id, now, rng=None):
    """顾客在手机端点「试穿合身」时调。返回 (明文码, 要存的那一行)。**明文只给顾客,不入库。**"""
    n = rng.randrange(10 ** 码位数) if rng else secrets.randbelow(10 ** 码位数)   # 真用走 secrets,自测才给固定种子
    code = f"{n:0{码位数}d}"
    t = _t(now)
    return code, dict(order_id=order_id, code_hash=码哈希(order_id, code), issued_at=_fmt(t),
                      expires_at=_fmt(t + datetime.timedelta(hours=码有效小时)), used_at=None, tries=0)


def 核验(记录, order_id, 输入, now):
    """导购输入顾客给的码。返回 (结论, 一句人话, 要更新的字段)。

    结论:「通过」/「不对」/「作废」/「过期」/「用过了」/「没有码」。
    **输错也要记一次** —— 不记的话,「最多试 5 次」形同虚设。
    """
    if not 记录:
        return "没有码", "这一单顾客还没在手机上点「试穿合身」—— 请顾客点一下,把 6 位码告诉你", {}
    if 记录.get("used_at"):
        return "用过了", "这个码已经核验过了 —— 这一单已经签收", {}
    if (记录.get("tries") or 0) >= 码最多试:
        return "作废", f"这个码输错 {码最多试} 次已作废 —— 请顾客重新点一次拿新码", {}
    if _t(now) > _t(记录["expires_at"]):
        return "过期", f"码超过 {码有效小时} 小时已过期 —— 请顾客重新点一次拿新码", {}
    输 = "".join(ch for ch in str(输入 or "") if ch.isdigit())
    if len(输) != 码位数 or not hmac.compare_digest(码哈希(order_id, 输), 记录["code_hash"]):
        n = (记录.get("tries") or 0) + 1
        剩 = 码最多试 - n
        return ("作废" if 剩 <= 0 else "不对",
                "码不对" + (f",还能再试 {剩} 次" if 剩 > 0 else f" —— 已输错 {码最多试} 次,作废,请顾客重新拿码"),
                {"tries": n})
    return "通过", "核验通过:顾客本人确认试穿合身,这一单签收", {"used_at": _fmt(_t(now))}


def 能不能追认(签收于, now, 理由):
    """顾客一直不确认完成时,顾问二次追认。返回 (能不能, 一句人话)。"""
    if not 签收于:
        return False, "还没签收(试穿合身没核验过),谈不上完成"
    天 = (_t(now) - _t(签收于)).days
    if 天 < 追认等几天:
        return False, f"签收才 {天} 天 —— 满 {追认等几天} 天顾客还没确认,顾问才能追认;先请顾客自己确认"
    if not str(理由 or "").strip():
        return False, "追认要写理由(比如「已电话联系,顾客表示没问题」)—— 没有理由的追认等于替顾客点了完成"
    return True, f"签收已 {天} 天,顾问追认完成"


def 不合身判责(对得上留存数据, 有别的瑕疵, 我方问题=None):
    """试穿不合身,转返修时给一个**建议**的责任方。**结论由人确认**(售后判责一贯的规矩)。

    对得上留存数据  成衣和订单留存的数据(下单量体、选的码、配置)对得上吗:True / False / None(不知道)
    有别的瑕疵      除了不合身,有没有工艺 / 面料瑕疵:True / False / None
    我方问题        查出来是导购(量体 / 选码)或打版的问题:「导购」/「打版」/ None
    返回 (责任方, 处理, 一句人话)。责任方:「顾客」/「企业」/「判不了」。
    """
    if 我方问题 in ("导购", "打版"):
        return "企业", "免费返修或重做", f"是{我方问题}的问题 —— 业务 09-22 定:企业承担,免费"
    if 有别的瑕疵:
        return "企业", "免费返修或重做", "除了不合身还有别的瑕疵 —— 按工艺 / 面料瑕疵走,我方承担"
    if 对得上留存数据 is True and 有别的瑕疵 is False:
        return ("顾客", "返修或重做收费",
                "成衣和订单留存的数据对得上、没有别的瑕疵 —— 业务 09-22 定:顾客承担主要责任,返修或重做收费")
    return "判不了", "转人工", ("**判不了** —— " + ("没核过成衣和订单留存数据对不对得上" if 对得上留存数据 is None
                                                   else "成衣和订单留存数据对不上,要查是哪一环的问题")
                              + (";也没查有没有别的瑕疵" if 有别的瑕疵 is None else ""))


