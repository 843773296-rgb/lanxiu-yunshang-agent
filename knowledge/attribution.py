#!/usr/bin/env python3
"""成交归因的口径 —— **唯一源头**,不碰库、不取时间。

业务 2026-09-20:
> **成交率毕竟是一个长期一对一营销的结果,不能因为某一次就算在某人身上。**

这句话推翻了「按接待人算」这个简化 —— 它在业内叫**归因(attribution)**。

## 🔑 两种分成,校验规则**相反**

CRM 里(Salesforce 的 Opportunity Splits)这是两张不同的东西:

    收入分成  Revenue Split   —— **加起来必须 100%**。算提成,是**分蛋糕**
    影响力分成 Overlay Split  —— **可以超过 100%**。记贡献,**不是零和的**

一单 10 万可以同时是:
    收入   张三 70% · 李四 30%             (=100,这是钱)
    影响力 张三 100% · 李四 60% · 店长 40%  (=200,这是贡献)

**混在一起就全错了** —— 而它们在库里长得一模一样:都是「某人 + 某个百分比」。
所以 `kind` 必填,而且两种的校验**方向相反**:
一种总和必须 100,另一种**不许**拿 100 去要求它。

⚠️ 这一条最容易在重构里被写成同一个校验 —— 写成同一个之后,
**两份都跑得出数、都不报错**,只是影响力那一批会被判成「总和不对」而已。
下面的自测里两条专门钉它。

**「成交率」属于影响力那一类** —— 它衡量能力,不是分钱。

## 🔑 「人填的」和「算法算的」也要分开

三者算出来都是一个百分比,**长得一模一样**。所以 `source` 必填:
人工填 / 规则算 / 算法算(算法算还要写明是哪个算法、哪一版)。

不分开的后果:换了归因算法之后,**老数据和新数据混在一张表里,
而谁也说不清某一条是哪种算法的结果** —— 那时候整张表就废了。

## W 型归因的 30/30/30/10 是**行业惯例,不是算出来的**

换成 40/20/30/10 排序就可能变 —— 而两种算出来的数都叫「影响力」。
所以入库时 `method` 必须写明版本,换了参数就是另一个版本。
"""

收入分成, 影响力分成 = "收入分成", "影响力分成"

# 角色对应定制流程的节点 —— **W 型归因要用的就是这几个点**
# 2026-09-22 加「跟进」:W 型的「其余 10%」给的是中间的跟进/日程/预约,
# 原来的角色表里没有它 —— **记不进去的贡献,和没有贡献长得一样**。
角色 = ("首次接待", "量体", "方案确认", "成交", "售后", "跟进")
来源 = ("人工填", "规则算", "算法算")

# B2B 销售的标准模型:三个关键节点各 30%,其余触点平分 10%
W型权重 = {"首触": 30.0, "关键": 30.0, "成交": 30.0, "其余": 10.0}
关键节点类型 = "量体"      # 定制业务里的关键节点:后面所有事都建立在那组数据上

下一步 = {
    收入分成:   "这是分钱的那一份 —— 总和必须 100,算提成用它",
    影响力分成: "这是记贡献的那一份 —— 可以超过 100,衡量能力用它,**别拿它去分钱**",
}


def 校验一笔(kind, role, source, pct, method=None):
    """记一笔之前的校验。过了返回 None,不过返回一句人话(调用方去抛)。"""
    if kind not in (收入分成, 影响力分成):
        return (f"kind 必须是「{收入分成}」或「{影响力分成}」—— "
                f"**两者的校验规则相反,混了就全错**")
    if role not in 角色:
        return f"role 必须是 {角色} 之一"
    if source not in 来源:
        return f"source 必须是 {来源} 之一"
    if source == "算法算" and not method:
        # **换了算法之后,老数据和新数据混在一张表里谁也说不清** —— 所以必填
        return "source=算法算 时必须写明 method(算法名+版本)"
    if pct is None or pct <= 0 or pct > 100:
        return f"pct 要在 (0,100],给的是 {pct}"
    return None


def 总和该不该管(kind):
    """这一种分成,要不要拿 100 去要求它。

    ⚠️ **这个函数存在的唯一理由,就是把两种分成的校验方向分开。**
    写成同一个校验之后,两份都跑得出数、都不报错 ——
    只是影响力那一批会被整批判成「总和不对」,而那是**它本来就该有的样子**。
    """
    return kind == 收入分成


def 总和对不对(kind, 总和, 容差=0.01):
    """返回 (对不对, 人话)。影响力分成永远返回 True —— **它不是零和的**。"""
    if not 总和该不该管(kind):
        return True, (f"{kind}**不要求加起来是 100** —— 它记的是贡献不是分钱,"
                      f"现在是 {round(总和, 2)}")
    if abs(总和 - 100) <= 容差:
        return True, f"{kind} 加起来正好 100"
    return False, (f"{kind} 加起来是 {round(总和, 2)},**不是 100** —— "
                   f"这一份是分钱的,多一分少一分都有人吃亏")


def W型分配(旅程):
    """按 W 型算每个人的影响力。`旅程` 是 [{"类型":…, "经手人":…}, …],按时间排好。

    返回 [(工号, 百分比, 角色)],按百分比从大到小。

    **算不出来就返回空,不编** —— 没有触点的单子,
    「算出来大家都是 0」和「压根没有触点」长得一模一样。
    """
    有人的 = [x for x in (旅程 or []) if x.get("经手人")]
    if not 有人的:
        return []

    分 = {}

    def 给(who, pct, role):
        if not who:
            return
        cur = 分.get(who, [0.0, set()])
        cur[0] += pct
        cur[1].add(role)
        分[who] = cur

    给(有人的[0]["经手人"], W型权重["首触"], "首次接待")

    关键 = [x for x in 有人的 if x.get("类型") == 关键节点类型]
    if 关键:
        每人 = W型权重["关键"] / len(关键)
        for x in 关键:
            给(x["经手人"], 每人, "量体")
    else:
        # **没有量体这个节点时,那 30% 不许凭空分掉** —— 归给成交人,
        # 并在角色里留痕,否则「有量体」和「没量体」的分配看起来一样
        给(有人的[-1]["经手人"], W型权重["关键"], "成交(无量体节点)")

    给(有人的[-1]["经手人"], W型权重["成交"], "成交")

    中间 = [x for x in 有人的[1:-1] if x.get("类型") != 关键节点类型]
    if 中间:
        每人 = W型权重["其余"] / len(中间)
        for x in 中间:
            给(x["经手人"], 每人, x.get("类型") or "跟进")

    return sorted(((who, round(v[0], 1), "/".join(sorted(v[1])))
                   for who, v in 分.items()), key=lambda x: -x[1])


# ── 成交率(业务 2026-09-22 拍板的口径)──────────────────────────────
#
#   门店成交率 = 成交的客户数 ÷ 亲自接待过的客户数(每人只算一次)
#   顾问成交率 = 他在成交客户上的归因份额之和 ÷ 他亲自接待过的客户数
#
# 行业(服装零售 / 4S / 婚纱影楼)都按**客户**算,不按接待次数 ——
# 按次数算的话,一个客户来五次就是五次接待,**越用心跟的顾问分母越大、率越低**。
# 上一版按「单数 ÷ 接待次数」算出 141%–189%,就是分母分子不是同一种东西。
#
# ⚠️ 两个细节业务没定,先用行业默认:**不分周期**;**一个客户下多张单只算 1 个成交客户**。

def 客户份额(各单分成):
    """一个成交客户身上,每个人占几成。

    `各单分成` 是 [{工号: 百分比}, …],这个客户每张定制单一条(W 型结果)。
    **一个客户只算 1 个成交客户** —— 下了三张单也是 1,按每张单的份额取平均。
    W 型一张单加起来 ≤100(没有中间触点时是 90),所以每个客户分出去的**不超过 1**。
    """
    单 = [d for d in (各单分成 or []) if d]
    if not 单:
        return {}
    出 = {}
    for d in 单:
        for who, pct in d.items():
            出[who] = 出.get(who, 0.0) + pct / 100.0 / len(单)
    return 出


def 成交率(成交份额, 接待客户数):
    """返回 (率 或 None, 人话)。**分母为 0 不给率** ——
    「没接待过客户」和「成交率 0%」是两回事。"""
    if not 接待客户数:
        return None, "没有亲自接待过的客户 —— **没东西可算,不是 0%**"
    return 成交份额 / 接待客户数, f"{成交份额:.1f} ÷ {接待客户数} 个亲自接待过的客户"


# ── 统计周期:同期 / 队列 两种口径,可切换(业务 2026-09-22)──────────────
#
#   同期  这个月被亲自接待过的客户里,**这个月**下了定制单的占多少
#   队列  **首次**亲自接待在这个月的客户,首次接待后 **N 天内**下了定制单的占多少
#
# 长周期生意(4S / 家装 / 定制)基本都用队列:同期口径下,这个月接待、下个月才下单的
# 客户,这个月算没成交、下个月又不在分母里 —— **成交率被系统性压低**。
# N = 90,**业务 2026-09-22 确认**(原提议 30,改为 90)。依据:行业惯例让 N 覆盖约八成
# 最终成交(P80);演示数据里 30 天只覆盖 52%,
# 90 天覆盖 77%(P80 = 96 天)。⚠️ **演示数据,真实数据来了要按真实 P80 重定**。
默认N = 90


def 分期成交率(接待, 订单, 模式, 月, 截止, N=默认N):
    """返回 {"门店": (成交客户数, 分母), "顾问": {工号: (份额和, 分母)}, "未成熟": bool}。

    `接待` [(客户, 'YYYY-MM-DD', 工号)] —— **只放亲自接待的**(远程量体不算)
    `订单` [(客户, 'YYYY-MM-DD', {工号: pct})] —— 每张定制单的 W 型分成
    `截止` 数据截止日(世界的今天)—— 队列口径要知道这批客户够不够 N 天
    """
    import datetime as _d
    日 = lambda x: _d.date.fromisoformat(x[:10])
    if 模式 == "同期":
        在期 = lambda d: d[:7] == 月
        分母客户 = {c for c, d, w in 接待 if 在期(d)}
        顾问客户 = {}
        for c, d, w in 接待:
            if 在期(d):
                顾问客户.setdefault(w, set()).add(c)
        窗 = {c: (lambda d: 在期(d)) for c in 分母客户}
        未成熟 = False
    elif 模式 == "队列":
        首 = {}
        for c, d, w in 接待:
            if c not in 首 or d < 首[c]:
                首[c] = d
        分母客户 = {c for c, d in 首.items() if d[:7] == 月}
        止 = {c: 日(首[c]) + _d.timedelta(days=N) for c in 分母客户}
        窗 = {c: (lambda d, c=c: 日(首[c]) <= 日(d) <= 止[c]) for c in 分母客户}
        顾问客户 = {}
        for c, d, w in 接待:
            if c in 分母客户 and 窗[c](d):
                顾问客户.setdefault(w, set()).add(c)
        # **N 天还没过完的客户,率会偏低** —— 那不是没成交,是还没到时候
        未成熟 = any(止[c] > 日(截止) for c in 分母客户)
    else:
        raise ValueError(f"模式只能是「同期」或「队列」,给的是「{模式}」")
    各 = {}
    for c, d, 分 in 订单:
        if c in 窗 and 窗[c](d):
            各.setdefault(c, []).append(分)
    份额 = {c: 客户份额(v) for c, v in 各.items()}
    顾问 = {w: (sum(份额.get(c, {}).get(w, 0) for c in cs), len(cs)) for w, cs in 顾问客户.items()}
    return {"门店": (sum(1 for c in 分母客户 if 份额.get(c)), len(分母客户)),
            "顾问": 顾问, "未成熟": 未成熟}


