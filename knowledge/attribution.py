#!/usr/bin/env python3
"""成交归因的口径 —— **唯一源头**,不碰库、不取时间。

业务 2026-09-20:
> **成交率毕竟是一个长期一对一营销的结果,不能因为某一次就算在某人身上。**

这句话推翻了「按接待人算」这个简化 —— 它在业内叫**归因(attribution)**。

## 🔑 两种分成,校验规则**相反**

CRM 里(Salesforce 的 Opportunity Splits)这是两张不同的东西:

    收入分成  Revenue Split   —— **加起来必须 100%**。算提成,是**分蛋糕**
    影响力分成 Overlay Split  —— **可以超过 100%**。记贡献,**不是零和的**

一单 10 万可以同时是:
    收入   张三 70% · 李四 30%             (=100,这是钱)
    影响力 张三 100% · 李四 60% · 店长 40%  (=200,这是贡献)

**混在一起就全错了** —— 而它们在库里长得一模一样:都是「某人 + 某个百分比」。
所以 `kind` 必填,而且两种的校验**方向相反**:
一种总和必须 100,另一种**不许**拿 100 去要求它。

⚠️ 这一条最容易在重构里被写成同一个校验 —— 写成同一个之后,
**两份都跑得出数、都不报错**,只是影响力那一批会被判成「总和不对」而已。
下面的自测里两条专门钉它。

**「成交率」属于影响力那一类** —— 它衡量能力,不是分钱。

## 🔑 「人填的」和「算法算的」也要分开

三者算出来都是一个百分比,**长得一模一样**。所以 `source` 必填:
人工填 / 规则算 / 算法算(算法算还要写明是哪个算法、哪一版)。

不分开的后果:换了归因算法之后,**老数据和新数据混在一张表里,
而谁也说不清某一条是哪种算法的结果** —— 那时候整张表就废了。

## W 型归因的 30/30/30/10 是**行业惯例,不是算出来的**

换成 40/20/30/10 排序就可能变 —— 而两种算出来的数都叫「影响力」。
所以入库时 `method` 必须写明版本,换了参数就是另一个版本。
"""

收入分成, 影响力分成 = "收入分成", "影响力分成"

# 角色对应定制流程的节点 —— **W 型归因要用的就是这几个点**
# 2026-09-22 加「跟进」:W 型的「其余 10%」给的是中间的跟进/日程/预约,
# 原来的角色表里没有它 —— **记不进去的贡献,和没有贡献长得一样**。
角色 = ("首次接待", "量体", "方案确认", "成交", "售后", "跟进")
来源 = ("人工填", "规则算", "算法算")

# B2B 销售的标准模型:三个关键节点各 30%,其余触点平分 10%
W型权重 = {"首触": 30.0, "关键": 30.0, "成交": 30.0, "其余": 10.0}
关键节点类型 = "量体"      # 定制业务里的关键节点:后面所有事都建立在那组数据上

下一步 = {
    收入分成:   "这是分钱的那一份 —— 总和必须 100,算提成用它",
    影响力分成: "这是记贡献的那一份 —— 可以超过 100,衡量能力用它,**别拿它去分钱**",
}


def 校验一笔(kind, role, source, pct, method=None):
    """记一笔之前的校验。过了返回 None,不过返回一句人话(调用方去抛)。"""
    if kind not in (收入分成, 影响力分成):
        return (f"kind 必须是「{收入分成}」或「{影响力分成}」—— "
                f"**两者的校验规则相反,混了就全错**")
    if role not in 角色:
        return f"role 必须是 {角色} 之一"
    if source not in 来源:
        return f"source 必须是 {来源} 之一"
    if source == "算法算" and not method:
        # **换了算法之后,老数据和新数据混在一张表里谁也说不清** —— 所以必填
        return "source=算法算 时必须写明 method(算法名+版本)"
    if pct is None or pct <= 0 or pct > 100:
        return f"pct 要在 (0,100],给的是 {pct}"
    return None


def 总和该不该管(kind):
    """这一种分成,要不要拿 100 去要求它。

    ⚠️ **这个函数存在的唯一理由,就是把两种分成的校验方向分开。**
    写成同一个校验之后,两份都跑得出数、都不报错 ——
    只是影响力那一批会被整批判成「总和不对」,而那是**它本来就该有的样子**。
    """
    return kind == 收入分成


def 总和对不对(kind, 总和, 容差=0.01):
    """返回 (对不对, 人话)。影响力分成永远返回 True —— **它不是零和的**。"""
    if not 总和该不该管(kind):
        return True, (f"{kind}**不要求加起来是 100** —— 它记的是贡献不是分钱,"
                      f"现在是 {round(总和, 2)}")
    if abs(总和 - 100) <= 容差:
        return True, f"{kind} 加起来正好 100"
    return False, (f"{kind} 加起来是 {round(总和, 2)},**不是 100** —— "
                   f"这一份是分钱的,多一分少一分都有人吃亏")


def W型分配(旅程):
    """按 W 型算每个人的影响力。`旅程` 是 [{"类型":…, "经手人":…}, …],按时间排好。

    返回 [(工号, 百分比, 角色)],按百分比从大到小。

    **算不出来就返回空,不编** —— 没有触点的单子,
    「算出来大家都是 0」和「压根没有触点」长得一模一样。
    """
    有人的 = [x for x in (旅程 or []) if x.get("经手人")]
    if not 有人的:
        return []

    分 = {}

    def 给(who, pct, role):
        if not who:
            return
        cur = 分.get(who, [0.0, set()])
        cur[0] += pct
        cur[1].add(role)
        分[who] = cur

    给(有人的[0]["经手人"], W型权重["首触"], "首次接待")

    关键 = [x for x in 有人的 if x.get("类型") == 关键节点类型]
    if 关键:
        每人 = W型权重["关键"] / len(关键)
        for x in 关键:
            给(x["经手人"], 每人, "量体")
    else:
        # **没有量体这个节点时,那 30% 不许凭空分掉** —— 归给成交人,
        # 并在角色里留痕,否则「有量体」和「没量体」的分配看起来一样
        给(有人的[-1]["经手人"], W型权重["关键"], "成交(无量体节点)")

    给(有人的[-1]["经手人"], W型权重["成交"], "成交")

    中间 = [x for x in 有人的[1:-1] if x.get("类型") != 关键节点类型]
    if 中间:
        每人 = W型权重["其余"] / len(中间)
        for x in 中间:
            给(x["经手人"], 每人, x.get("类型") or "跟进")

    return sorted(((who, round(v[0], 1), "/".join(sorted(v[1])))
                   for who, v in 分.items()), key=lambda x: -x[1])


# ── 咬合记录 ────────────────────────────────────────────────────────
咬合 = [
    ("把两种分成的校验写成同一个(影响力也被要求加起来 100)", "影响力分成不许被要求等于 100"),
    ("让 source=算法算 不必写 method(换了算法之后老数据新数据分不开)", "算法算必须写 method"),
    ("没有量体节点时把那 30% 凭空分掉(有量体和没量体的分配看起来一样)", "没有量体节点时"),
    ("让没有触点的单子也算出一个分配(编一个出来)", "没有触点不编"),
]


def _自测():
    G, R, D = "\033[32m", "\033[31m", "\033[0m"
    坏 = []

    def ck(说, 得, want):
        if 得 != want:
            坏.append(f"{说}:要 {want!r},得 {得!r}")

    # ── 🔑 两种分成的校验方向相反 ────────────────────────────
    ck("收入分成要求等于 100", 总和该不该管(收入分成), True)
    ck("影响力分成不许被要求等于 100", 总和该不该管(影响力分成), False)
    ck("收入分成 100 → 对", 总和对不对(收入分成, 100.0)[0], True)
    ck("收入分成 99 → 不对", 总和对不对(收入分成, 99.0)[0], False)
    ck("收入分成 101 → 不对(多了也不行,多出来的那份没人出)",
       总和对不对(收入分成, 101.0)[0], False)
    ck("影响力 200 → 对(它不是零和的)", 总和对不对(影响力分成, 200.0)[0], True)
    ck("影响力 30 → 也对", 总和对不对(影响力分成, 30.0)[0], True)
    # 两种的说法不许一样 —— **同一句话就等于没分开**
    if 总和对不对(收入分成, 100.0)[1] == 总和对不对(影响力分成, 100.0)[1]:
        坏.append("两种分成在总和正好 100 时给了同一句话 —— **那就等于没分开**")

    # ── 记一笔的校验 ─────────────────────────────────────────
    ck("kind 写错", bool(校验一笔("随便", "量体", "人工填", 50)), True)
    ck("role 写错", bool(校验一笔(收入分成, "打杂", "人工填", 50)), True)
    ck("source 写错", bool(校验一笔(收入分成, "量体", "拍脑袋", 50)), True)
    ck("算法算必须写 method", bool(校验一笔(收入分成, "量体", "算法算", 50)), True)
    ck("算法算写了 method 就行",
       校验一笔(收入分成, "量体", "算法算", 50, method="W型归因 v1"), None)
    ck("pct 是 0 不行", bool(校验一笔(收入分成, "量体", "人工填", 0)), True)
    ck("pct 超 100 不行", bool(校验一笔(收入分成, "量体", "人工填", 100.1)), True)
    ck("pct 正好 100 可以", 校验一笔(收入分成, "量体", "人工填", 100), None)

    # ── W 型分配 ─────────────────────────────────────────────
    ck("没有触点不编", W型分配([]), [])
    ck("有触点但都没经手人,也不编",
       W型分配([{"类型": "量体", "经手人": None}]), [])

    旅 = [{"类型": "预约", "经手人": "A"}, {"类型": "量体", "经手人": "B"},
          {"类型": "跟进", "经手人": "C"}, {"类型": "下单", "经手人": "D"}]
    出 = dict((w, p) for w, p, _ in W型分配(旅))
    ck("首触 30", 出.get("A"), 30.0)
    ck("量体 30", 出.get("B"), 30.0)
    ck("中间那位分 10", 出.get("C"), 10.0)
    ck("成交 30", 出.get("D"), 30.0)
    ck("加起来正好 100", round(sum(出.values()), 1), 100.0)

    # 没有量体节点:那 30% 归成交人,而且**角色里要留痕**
    旅2 = [{"类型": "预约", "经手人": "A"}, {"类型": "下单", "经手人": "D"}]
    出2 = W型分配(旅2)
    角 = {w: r for w, p, r in 出2}
    ck("没有量体节点时,那 30% 归成交人", dict((w, p) for w, p, _ in 出2).get("D"), 60.0)
    ck("而且角色里留痕", "无量体节点" in 角.get("D", ""), True)
    ck("没有量体时也不凭空多出 10(中间没人)",
       round(sum(p for _, p, _ in 出2), 1), 90.0)

    # 同一个人身兼数职:百分比要累加,角色要都记下来
    旅3 = [{"类型": "预约", "经手人": "A"}, {"类型": "量体", "经手人": "A"},
           {"类型": "下单", "经手人": "A"}]
    出3 = W型分配(旅3)
    ck("一个人包办,百分比累加", 出3[0][1], 90.0)
    ck("而且三个角色都记下来", len(出3[0][2].split("/")), 3)

    if 坏:
        print(f"{R}❌ 归因口径自测 {len(坏)} 条不过{D}")
        for b in 坏:
            print(f"    ❌ {b}")
        return 1
    print(f"{G}✅ 归因口径自测 26 条全过{D}")
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(_自测())
