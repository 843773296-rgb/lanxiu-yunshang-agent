"""商品归纳总结的口径(用户 2026-10-10):给一套衣服,从花型(纹样)、材质 / 布料(面料)、工艺,
再加颜色、形制,归纳出规律;**没发现规律就说没有**。

用户原话:「这对商机、版型师、运营都有必要性」「这能力是购买喜好推荐的前提」。
所以购买喜好推荐(purchase_pref)就是它的一个用法:把顾客买过的衣服交给它归纳。

## 两件事

① **一件衣服是什么**(属性):五个维度,每个值都带**从哪来的**(结构化字段 / 商品名 / 推导)。
   认不出来的**明说认不出**,不填一个像样的词 —— 认不出的件数会报在「覆盖」里,
   结论只看认得出的那几件,并且说清只看了几件。

② **这一套有什么规律**(归纳):和颜色偏好同一个判法(用户 10-10 选的方案 B,同族沿用):
   一个值算「规律」,要同时满足 ——
       这一套至少 3 件(认得出这个维度的)· 这个值至少 2 件 · 占比是对照组的 2 倍以上
   **对照组**:归纳一套商品时比的是「全部在架商品」;归纳一位顾客买过的东西时比的是「全店买过的东西」。
   占比很高、但对照组里本来就这么高的(比如大部分衣服都是「无纹样」),**不叫规律,叫共性** —— 分开报。
   没有任何一个维度出规律 → 明说「没有发现规律」,并说是件数不够还是各维度都分散。

## 中文子串的坑(CLAUDE.md 第 7 节 ③)

「香云纱」里有「纱」、「真丝素罗」里有「素罗」—— 认料一律**最长的词先认,认到的那一段挖掉再认下一个**。
"""
import re

