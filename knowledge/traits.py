# 和颜色偏好同一组门槛(用户 2026-10-10 确认方案 B + 推荐参数;同族沿用,不另定一套)
最少件数 = 3
该值最少件数 = 2
倍数门槛 = 2.0
维度们 = ("颜色", "纹样", "面料", "工艺", "形制")


def 拆词(词们):
    """「绢 / 电力纺」「妆花缎 / 妆花纱」这种一条写了几个名字的,拆成几个别名,都指回原词。
    「真丝素罗 · 厚款(16 姆米)」这种带规格的,认名字只认点号前面那段。"""
    出 = {}
    for w in 词们:
        for 段 in re.split(r"\s*/\s*", w):
            段 = re.split(r"\s*[·((]", 段)[0].strip()
            if len(段) >= 1 and 段 not in 出:
                出[段] = w
    return 出


def 认词(文, 词表):
    """在一段文字里认出词表里的词。**最长的先认,认到的挖掉** —— 防「香云纱」被认成「纱」。返回 [原词]。"""
    别名 = 拆词(词表)
    剩, 出 = 文 or "", []
    for 名 in sorted(别名, key=len, reverse=True):
        if 名 and 名 in 剩:
            原 = 别名[名]
            if 原 not in 出:
                出.append(原)
            剩 = 剩.replace(名, "□" * len(名))
    return 出


def 属性(*, 名称, 形制=None, 色系们=(), 定制面料=None, 定制工艺=None, 主料词=(), 工艺词=(), 纹样推=None):
    """一件衣服 → {维度: [(值, 来源)]}。认不出的维度给 []。

    定制面料 / 定制工艺:定制品的可选项(product_custom 的 mt_opts / kf_opts,逗号分隔)——
    它们是「这款能做什么」,**名字里明写了的优先**(那是这一款的主打),名字里没写才用可选项的第一项。
    纹样推:knowledge/motif.推 —— 它自己会给「无纹样」(素料,确定)和「待业务核」(认不出);后者算认不出。
    """
    出 = {d: [] for d in 维度们}
    for f in dict.fromkeys(x for x in 色系们 if x):
        出["颜色"].append((f, "SKU 颜色 → 色系表"))
    if 形制:
        出["形制"].append((形制, "版型 / 定制配置"))
    料 = 认词(名称, 主料词)
    if 料:
        出["面料"] += [(x, "商品名") for x in 料]
    elif 定制面料:
        x = [y.strip() for y in 定制面料.split(",") if y.strip()]
        if x:
            出["面料"].append((x[0], "定制可选项第一项"))
    艺 = [x for x in 认词(名称, 工艺词) if x not in [y for y, _ in 出["面料"]]]
    if 艺:
        出["工艺"] += [(x, "商品名") for x in 艺]
    elif 定制工艺:
        出["工艺"] += [(y.strip(), "定制可选项") for y in 定制工艺.split(",")[:2] if y.strip()]
    if 纹样推:
        w, 来源, _ = 纹样推(名称, "、".join(x for x, _ in 出["面料"]), "、".join(x for x, _ in 出["工艺"]))
        if w and 来源 != "待业务核" and w != "待业务核":
            出["纹样"].append((w, 来源))
    return 出


def 归纳(件们, 对照占比, 维度=维度们):
    """件们:[{维度: [值, …]}](一件一个 dict,同一件里一个值只算一次);
    对照占比:{维度: {值: 0~1}}(对照组里「有这个值的件数 ÷ 认得出这个维度的件数」)。

    返回 {"规律": [...], "共性": [...], "覆盖": {维度: (认得出, 总)}, "结论": 一句话}。
    规律 / 共性的每一项:{维度, 值, 件数, 认得出, 占比, 对照, 倍数}。"""
    规律, 共性, 覆盖 = [], [], {}
    总 = len(件们)
    for d in 维度:
        有 = [set(x.get(d) or ()) for x in 件们]
        有 = [s for s in 有 if s]
        覆盖[d] = (len(有), 总)
        if len(有) < 最少件数:
            continue
        计 = {}
        for s in 有:
            for v in s:
                计[v] = 计.get(v, 0) + 1
        for v, k in 计.items():
            if k < 该值最少件数:
                continue
            占 = k / len(有)
            基 = (对照占比.get(d) or {}).get(v)
            项 = dict(维度=d, 值=v, 件数=k, 认得出=len(有), 占比=round(占, 3),
                     对照=round(基, 3) if 基 is not None else None,
                     倍数=round(占 / 基, 2) if 基 else None)
            if 基 and 占 / 基 >= 倍数门槛:
                规律.append(项)
            elif 占 >= 0.8:
                共性.append(项)       # 几乎都是,但对照组里本来就常见 —— 不叫规律
    规律.sort(key=lambda x: (-x["倍数"], -x["件数"], x["维度"], x["值"]))
    共性.sort(key=lambda x: (-x["占比"], x["维度"], x["值"]))
    够 = [d for d, (n, _) in 覆盖.items() if n >= 最少件数]
    if 规律:
        结论 = "发现了规律"
    elif not 够:
        结论 = f"没有发现规律:认得出的件数都不到 {最少件数} 件,样本太少,归纳不出东西"
    else:
        结论 = ("没有发现规律:" + "、".join(够) + " 这几个维度都比较分散,没有哪个值明显多于"
                + ("全店平均" if 对照占比 else "对照组"))
    return dict(规律=规律, 共性=共性, 覆盖=覆盖, 结论=结论)


def 一句话(项):
    """给人看的:「6 件里 4 件是云锦(这一套 67%,在架商品里 8%,约 8 倍)」。不出现公式。"""
    倍 = f",约 {项['倍数']:.0f} 倍" if 项.get("倍数") and 项["倍数"] >= 3 else (
        f",约 {项['倍数']:.1f} 倍" if 项.get("倍数") else "")
    对 = f",对照组里 {项['对照']:.0%}" if 项.get("对照") is not None else ""
    return f"{项['认得出']} 件里 {项['件数']} 件{项['维度']}是「{项['值']}」(这一套 {项['占比']:.0%}{对}{倍})"


