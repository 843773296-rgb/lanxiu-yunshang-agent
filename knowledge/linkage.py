#!/usr/bin/env python3
"""订单 ↔ 预约的链路口径 —— **唯一源头**,不碰库、不取时间。

业务 2026-09-20 要的是**成交率**。算率的前提是:
**这一单能追到是哪一次接待促成的。** 而现在追不到。

## 🔑 「没接上」和「没记过」是两件事,下一步完全相反

2026-09-21 查库:

    定制单 3511 张标着「未接入」
    其中下单前有过**到店接待**记录的 —— **14 张**
    全库「已到店 / 已完成」的预约 —— **7 条**
    581 个客户下过定制单,只有 55 个有任何预约记录

所以:**成交率算不出来,不是因为链路没接,是因为接待压根没记。**

    没接上   → 我写代码去接
    没记过   → 业务去改流程(到店接待要落一条记录)

把 3497 张没有任何依据的单硬接上去,**算出来的成交率看起来完全正常** ——
那是这个项目最怕的那一类错。

## 🔑 「推断出来的关联」不许和「记录下来的关联」长一样

    已关联    系统里本来就记着这一单来自哪次预约
    推断关联  我们按「下单前恰好一次到店接待」猜出来的

两者都能让成交率算出一个数,**而后者的可信度完全不同**。
所以是两种来路,不是一种。将来真实数据补上,可以把推断的那批重新核。

## 四种「接不上」,下一步各不相同

    AMBIGUOUS     下单前有**多次**到店接待 —— 不猜,等人工确认
    NO_VISIT      约过但**都没来**(取消/爽约/过期)—— 这单不是接待带来的
    NOT_RECORDED  一条预约记录都没有 —— **接待没记**,不是「他没预约」
    (已接上的那种是 INFERRED / RECORDED)
"""

来路 = ("未接入", "无预约", "已关联", "推断关联")
到店状态 = ("已到店", "已完成")

下一步 = {
    "RECORDED":     "本来就记着来自哪次预约 —— 可以直接用",
    "INFERRED":     "按「下单前恰好一次到店接待」推断的 —— **可信度低于记录的那种**,算率时要分开说",
    "AMBIGUOUS":    "下单前有多次到店接待,**不猜** —— 要人工确认是哪一次",
    "NO_VISIT":     "客户约过但都没来(取消/爽约/过期)—— 这一单不是接待带来的",
    "NOT_RECORDED": "一条预约记录都没有 —— **是接待没记,不是他没预约**;这要业务改流程,不是改代码",
}

# 接入率低于这个数就不给成交率。
# ⚠️ **这个 0.6 是拍的**,没有依据 —— 标出来,别让下游当成结论。
# 它要回答的是:一个建立在 0.4% 样本上的「成交率」,比没有这个数更糟,
# 因为**它看起来和一个真的成交率长得一模一样**。
接入率门槛 = 0.6
待校准 = ("接入率门槛",)


def 判(候选):
    """这一单能不能追到是哪次接待促成的。

    `候选` 是**下单之前**这个客户的预约列表 [{"id", "status"}, …]。
    返回 (来路, 码, 人话, 关联到哪一条或 None)。
    """
    到店 = [a for a in (候选 or []) if (a.get("status") or "") in 到店状态]
    if len(到店) == 1:
        a = 到店[0]
        return ("推断关联", "INFERRED",
                f"下单前**恰好一次**到店接待({a.get('id')})—— 按这个推断,"
                f"**但这是猜的,不是记录下来的**", a.get("id"))
    if len(到店) > 1:
        return ("未接入", "AMBIGUOUS",
                f"下单前有 {len(到店)} 次到店接待 —— **不猜是哪一次**,等人工确认", None)
    if 候选:
        状 = "、".join(sorted({(a.get("status") or "?") for a in 候选}))
        return ("未接入", "NO_VISIT",
                f"约过 {len(候选)} 次但**都没到店**({状})—— 这一单不是接待带来的", None)
    return ("未接入", "NOT_RECORDED",
            "一条预约记录都没有 —— **这是接待没记,不是他没预约**", None)


def 能不能算成交率(可用, 总数):
    """接入率够不够支撑一个成交率。返回 (能不能, 人话)。

    **「算出来是 3%」和「只有 3% 的单能算」是两回事** ——
    后者算出来的任何率都没有代表性,而它和一个真的率长得一模一样。
    """
    if not 总数:
        return False, "这个范围里一张定制单都没有 —— **没东西可算**,不是率低"
    率 = 可用 / 总数
    if 率 >= 接入率门槛:
        return True, f"{可用}/{总数} 的单追得到接待({率:.0%}),够算"
    return False, (f"只有 {可用}/{总数} 的单追得到是哪次接待促成的({率:.1%}),"
                   f"**低于 {接入率门槛:.0%} 这条线(这个门槛是拍的,待校准)** —— "
                   f"这时候给一个成交率,它和一个真的成交率长得一模一样,"
                   f"**而它建立在 {率:.1%} 的样本上**")


# ── 咬合记录 ────────────────────────────────────────────────────────
咬合 = [
    ("多个到店接待时挑第一个(把「不知道是哪次」变成一个确定的答案)", "多次到店不猜"),
    ("把推断出来的关联标成「已关联」(和记录下来的混成一种)", "推断关联不是已关联"),
    ("把「一条预约都没有」和「约过但没来」合成一个码", "一条预约都没有"),
    ("接入率再低也给成交率", "接入率太低不给率"),
]


def _自测():
    G, R, D = "\033[32m", "\033[31m", "\033[0m"
    坏 = []

    def ck(说, 得, want):
        if 得 != want:
            坏.append(f"{说}:要 {want!r},得 {得!r}")

    到 = lambda i: {"id": f"A{i}", "status": "已到店"}
    ck("恰好一次到店 → 推断关联", 判([到(1)])[0], "推断关联")
    ck("恰好一次到店 → 码是 INFERRED", 判([到(1)])[1], "INFERRED")
    ck("而且关联到那一条", 判([到(1)])[3], "A1")
    # 🔑 **推断关联不是已关联** —— 两者都能让率算出来,可信度完全不同
    ck("推断关联不是已关联", 判([到(1)])[0] == "已关联", False)

    ck("多次到店不猜", 判([到(1), 到(2)])[1], "AMBIGUOUS")
    ck("多次到店时不许关联到任何一条", 判([到(1), 到(2)])[3], None)
    ck("多次到店的来路仍是未接入", 判([到(1), 到(2)])[0], "未接入")

    ck("约过但都没来", 判([{"id": "A9", "status": "已取消"}])[1], "NO_VISIT")
    ck("爽约也算没来", 判([{"id": "A9", "status": "爽约"}])[1], "NO_VISIT")
    ck("待确认也算没来", 判([{"id": "A9", "status": "待确认"}])[1], "NO_VISIT")
    ck("一条预约都没有", 判([])[1], "NOT_RECORDED")
    ck("None 也算一条都没有", 判(None)[1], "NOT_RECORDED")
    # 有到店 + 有取消 → 按到店那次算(取消的不影响)
    ck("有一次到店、另有取消的,按到店那次算",
       判([到(1), {"id": "A9", "status": "已取消"}])[1], "INFERRED")

    # **四种说法不许一样** —— 一样就等于没分开
    说 = [判([到(1)])[2], 判([到(1), 到(2)])[2],
          判([{"id": "A9", "status": "已取消"}])[2], 判([])[2]]
    if len(set(说)) != 4:
        坏.append("四种情况给了重复的说法 —— **那它们就不该分成四种**")
    动作 = list(下一步.values())
    if len(set(动作)) != len(动作):
        坏.append("有两个码的下一步一模一样 —— **那它们就不该是两个码**")

    # ── 接入率门槛 ───────────────────────────────────────────
    ck("接入率太低不给率", 能不能算成交率(14, 3511)[0], False)
    ck("接入率够了给算", 能不能算成交率(80, 100)[0], True)
    ck("正好到门槛就给算", 能不能算成交率(60, 100)[0], True)
    ck("差一点就不给", 能不能算成交率(59, 100)[0], False)
    ck("一张单都没有,说的是「没东西可算」不是「率低」",
       "没东西可算" in 能不能算成交率(0, 0)[1], True)
    # 门槛是拍的,这件事要出现在说法里
    if "待校准" not in 能不能算成交率(14, 3511)[1]:
        坏.append("接入率不够的说法里没标「待校准」—— **一个拍脑袋的门槛和一个有出处的门槛长得一样**")

    if 坏:
        print(f"{R}❌ 链路口径自测 {len(坏)} 条不过{D}")
        for b in 坏:
            print(f"    ❌ {b}")
        return 1
    print(f"{G}✅ 链路口径自测 21 条全过{D}")
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(_自测())
