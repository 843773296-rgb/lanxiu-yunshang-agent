#!/usr/bin/env python3
"""订单 ↔ 接待的链路口径 —— **唯一源头**,不碰库、不取时间。

业务 2026-09-20 要的是**成交率**。算率的前提是:
**这一单能追到是哪一次接待促成的。**

## ⚠️ 2026-09-22 推翻了前一版的结论:**「接待」不等于「预约到店」**

前一版把接待定义成 `appointment` 里状态为「已到店/已完成」的那几条 ——
全库只有 **7 条**,于是算出「3511 张单追不到,缺的是接待记录,要业务改流程」。

**那个结论是错的,错在定义。** 业务 2026-09-22 说清楚了:

> 每次接待肯定都会有接待记录的,需要留下语音证据,如果有量体还需要留下量体数据,
> **客户的量体数据都是顾问接待留下来的数据,不以顾客自己上传的数据为准**,
> 还有**白坯试衣也是顾问接待的环节中比较靠后的环节**。

所以接待的证据是**量体 / 白坯试衣 / 预约到店**,而不是只有预约:

    量体场次    2026 场   (到店 1740 · 远程 255 · 上门 31,**全部由员工记录**)
    试衣场次     328 场
    预约到店       7 条

按这个定义,**3542 张定制单 100% 在下单前都有接待记录**。

**「接待没记」是用错了定义,不是业务缺流程。**
这件事值得单独记一笔:**一个定义错了的判断,和一个数据真的缺了的判断,
在结论上长得一模一样** —— 都是「追不到,得等业务」。

## 🔑 接待场次是**派生**的,不是一张表

    接待场次 = (客户, 日期, 经手人)

同一天同一个顾问给同一个客户量十几个尺寸,那是**一次**接待。
而同一天两个顾问各做一次,那是两次(实测 7450 场量体里有 97 场是多人的)。

⚠️ **录音是证据,但说不出是谁接待的** —— `call_audio` 没有经手人列。
所以录音不进链路判定,只能作为旁证。这是个数据缺口,记在这儿。

## 🔑 「挂哪次接待」和「谁促成的」是两个问题

链路回答前者:**下单前最近一次**接待(定制单成交通常紧跟最后一次量体/试衣)。

而**谁促成的**要看归因(W 型,见 `knowledge/attribution.py`)——
实测 **1939/3542(55%)的单,最近一次量体的经手人和订单上的顾问不是同一个人**。
**拿「最后接待人」当「促成人」会把 55% 的单算错人** ——
而算出来的成交率看起来完全正常。

## ⚠️ 两个待业务确认的判断

  ① **多次接待时取最近一次** —— 1971 张单下单前有不止一次接待(最多 12 次)。
     取最近一次是默认,不是业务拍的。
  ② **远程量体(255 场)算不算接待** —— 现在算。它由顾问操作、不是客户自传,
     但毕竟没见面。方式会在返回值里带出来,业务要排除随时能排除。
"""
来路 = ("未接入", "无预约", "已关联", "推断关联", "接待关联")
到店状态 = ("已到店", "已完成")          # 预约里算「真接待过」的那两种
接待证据 = ("量体", "白坯试衣", "预约到店")

下一步 = {
    "LINKED":       "下单前**只有一次**接待,挂它 —— 依据最硬的一种",
    "LINKED_LAST":  "下单前有多次接待,挂**最近一次**(定制单成交通常紧跟最后一次量体/试衣)"
                    " —— ⚠️ 这是默认,不是业务拍的",
    "NO_OWNER":     "有接待记录但**没记经手人** —— 这是数据缺口,不是没人接待",
    "NOT_RECORDED": "下单前**一条接待记录都没有** —— 量体/试衣/预约到店全没有;"
                    "定制单不该出现这种,出现了要去查是不是数据漏了",
}

# 接入率低于这个数就不给成交率。
# ⚠️ **这个 0.6 是拍的**,没有依据 —— 标出来,别让下游当成结论。
接入率门槛 = 0.6
待校准 = ("接入率门槛",)


def 判(接待):
    """这一单挂哪次接待。

    `接待` 是**下单之前**这个客户的接待场次,每条 {日期, 经手人, 证据, 方式?},
    **调用方按时间排好**(最早在前)。
    返回 (来路, 码, 人话, 挂到哪一次或 None)。

    ⚠️ **这里只回答「挂哪次」,不回答「谁促成的」** ——
    后者要看归因(W 型)。实测 55% 的单,最后接待人和订单顾问不是同一个人,
    **拿「最后接待人」当「促成人」会把一半以上的单算错人**。
    """
    有人的 = [x for x in (接待 or []) if (x.get("经手人") or "").strip()]
    if not 有人的:
        if 接待:
            return ("未接入", "NO_OWNER",
                    f"下单前有 {len(接待)} 次接待记录,但**一次都没记经手人** —— "
                    f"这是数据缺口,不是没人接待", None)
        return ("未接入", "NOT_RECORDED",
                "下单前**一条接待记录都没有**(量体/试衣/预约到店全没有)", None)
    末 = 有人的[-1]
    if len(有人的) == 1:
        return ("接待关联", "LINKED",
                f"下单前**只有一次**接待:{末.get('日期')} 由 {末.get('经手人')} "
                f"做的{末.get('证据') or '接待'}", 末)
    return ("接待关联", "LINKED_LAST",
            f"下单前有 **{len(有人的)} 次**接待,挂**最近一次**:{末.get('日期')} "
            f"由 {末.get('经手人')} 做的{末.get('证据') or '接待'} —— "
            f"⚠️ **「取最近一次」是默认,不是业务拍的**;"
            f"而**谁促成的**要看归因,不是看这一次", 末)


def 能不能算成交率(可用, 总数):
    """接入率够不够支撑一个成交率。返回 (能不能, 人话)。

    **「算出来是 3%」和「只有 3% 的单能算」是两回事** ——
    后者算出来的任何率都没有代表性,而它和一个真的率长得一模一样。
    """
    if not 总数:
        return False, "这个范围里一张定制单都没有 —— **没东西可算**,不是率低"
    率 = 可用 / 总数
    if 率 >= 接入率门槛:
        return True, (f"{可用}/{总数} 的单追得到接待({率:.0%}),够算。"
                      f"⚠️ **但「追得到哪次接待」不等于「知道谁促成的」** —— "
                      f"实测过半的单,最后接待人和订单上的顾问不是同一个人,"
                      f"**按接待人算和按归因算是两个数**")
    return False, (f"只有 {可用}/{总数} 的单追得到是哪次接待促成的({率:.1%}),"
                   f"**低于 {接入率门槛:.0%} 这条线(这个门槛是拍的,待校准)** —— "
                   f"这时候给一个成交率,它和一个真的成交率长得一模一样,"
                   f"**而它建立在 {率:.1%} 的样本上**")


# ── 咬合记录 ────────────────────────────────────────────────────────
咬合 = [
    ("把「只有一次接待」和「有多次挂最近一次」合成一个码(看不出是不是猜的)", "只有一次接待"),
    ("多次接待时挑**第一次**而不是最近一次(默认换了,而结论看起来一样)", "多次时挂最近一次"),
    ("把「有记录但没记经手人」当成「一条记录都没有」", "有接待但没记经手人"),
    ("接入率再低也给成交率", "接入率太低不给率"),
    ("算得出率的时候不再提醒「接待人≠促成人」", "够算时要提醒接待人不等于促成人"),
]


def _自测():
    G, R, D = "\033[32m", "\033[31m", "\033[0m"
    坏 = []

    def ck(说, 得, want):
        if 得 != want:
            坏.append(f"{说}:要 {want!r},得 {得!r}")

    一 = lambda d, who="S1", 证="量体": {"日期": d, "经手人": who, "证据": 证}

    # ── 挂哪次 ───────────────────────────────────────────────
    ck("只有一次接待", 判([一("2026-01-01")])[1], "LINKED")
    ck("只有一次时来路是接待关联", 判([一("2026-01-01")])[0], "接待关联")
    ck("挂到的就是那一次", 判([一("2026-01-01")])[3]["日期"], "2026-01-01")

    三次 = [一("2026-01-01", "A"), 一("2026-02-01", "B"), 一("2026-03-01", "C")]
    ck("多次时挂最近一次", 判(三次)[1], "LINKED_LAST")
    ck("挂的是最后那一次,不是第一次", 判(三次)[3]["经手人"], "C")
    # **「只有一次」和「多次挑一次」不许合成一个码** ——
    # 前者是确定的,后者是一个**默认**(业务没拍过)。混成一个就看不出哪些是猜的。
    if 判([一("2026-01-01")])[1] == 判(三次)[1]:
        坏.append("「只有一次」和「多次挂最近一次」用了同一个码 —— **看不出哪些是默认**")
    # 多次的时候必须把「这是默认不是业务拍的」说出来
    if "默认" not in 判(三次)[2]:
        坏.append("多次时没说明「取最近一次是默认」")
    # 而且要提醒「谁促成的」是另一个问题
    if "归因" not in 判(三次)[2]:
        坏.append("多次时没提醒「谁促成的要看归因」")

    # ── 没经手人 / 没记录 ────────────────────────────────────
    ck("有接待但没记经手人",
       判([{"日期": "2026-01-01", "经手人": "", "证据": "量体"}])[1], "NO_OWNER")
    ck("空白经手人也算没记",
       判([{"日期": "2026-01-01", "经手人": "   ", "证据": "量体"}])[1], "NO_OWNER")
    ck("一条记录都没有", 判([])[1], "NOT_RECORDED")
    ck("None 也算一条都没有", 判(None)[1], "NOT_RECORDED")
    # 没记经手人 ≠ 没有记录 —— 两者下一步不同(一个去补档案,一个去查数据漏没漏)
    if 判([{"日期": "x", "经手人": "", "证据": "量体"}])[2] == 判([])[2]:
        坏.append("「没记经手人」和「没有记录」给了同一句话 —— 那它们就不该分成两种")
    # 混着有人的和没人的,按有人的算
    ck("混着没经手人的记录,按有经手人的那次算",
       判([{"日期": "a", "经手人": "", "证据": "量体"}, 一("2026-05-01", "Z")])[1], "LINKED")

    # ── 接入率门槛 ───────────────────────────────────────────
    ck("接入率太低不给率", 能不能算成交率(14, 3511)[0], False)
    ck("接入率够了给算", 能不能算成交率(3542, 3542)[0], True)
    ck("正好到门槛就给算", 能不能算成交率(60, 100)[0], True)
    ck("差一点就不给", 能不能算成交率(59, 100)[0], False)
    ck("一张单都没有,说的是「没东西可算」不是「率低」",
       "没东西可算" in 能不能算成交率(0, 0)[1], True)
    if "待校准" not in 能不能算成交率(14, 3511)[1]:
        坏.append("接入率不够的说法里没标「待校准」")
    # 🔑 **算得出来的时候更要提醒**:追得到接待 ≠ 知道谁促成的
    if "够算时要提醒接待人不等于促成人" and "不等于" not in 能不能算成交率(3542, 3542)[1]:
        坏.append("够算时要提醒接待人不等于促成人 —— 实测 55% 的单两者不是同一个人")

    # 四种码都得说得出下一步,而且两两不同
    动作 = list(下一步.values())
    if len(set(动作)) != len(动作):
        坏.append("有两个码的下一步一模一样 —— **那它们就不该是两个码**")

    if 坏:
        print(f"{R}❌ 链路口径自测 {len(坏)} 条不过{D}")
        for b in 坏:
            print(f"    ❌ {b}")
        return 1
    print(f"{G}✅ 链路口径自测 22 条全过{D}")
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(_自测())
