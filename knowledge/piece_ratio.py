"""裁片用料占比 —— **估一个有依据的初值,而不是挂一个「等版师给」的待办。**

## 为什么不等

分部位选料上线之后,报价取「可选料里最贵的那种」当上限。
要变成实价,得知道**每个裁片吃多少布** —— 而 `pattern_piece` 只有
`pattern / name / qty / note`,没有面积。

补齐要 84 个版型 × 平均 5 个裁片 ≈ 400 个数,而**只有版师给得出来**。
于是它就成了一条**会一直挂着的待办** —— 而挂着的这段时间里,
报价一直按最贵的料算,客户一直被报高。

所以:**先估一个有依据的初值,标明它是估的,留复核位。**

## 估法:按裁片的几何面积

库里有基码尺寸(衣长 / 胸围 / 通袖长 / 裙长 / 领围 / 肩宽 / 马面宽),
够把每个裁片的面积估出来。**每条规则都写出依据,版师能逐条驳**:

    前片 / 后片   胸围/2 × 衣长          衣身按半胸围铺开
    袖片          (通袖长−肩宽)/2 × 袖肥  袖肥按胸围/4 估(常规放量)
    裙片          裙长 × 裙摆宽/片数      裙摆按胸围×1.6 估(A 字摆)
    马面          裙长 × 马面宽           库里有马面宽这一项
    领 / 领缘     领围 × 8cm             领条窄,按 8cm 宽估
    贴边 / 牵条   衣长 × 6cm             长条形
    摆片 / 侧摆   衣长/2 × 20cm          小片
    系带          120cm × 4cm            固定
    其余          衣长/2 × 胸围/4        兜底,按小片算

然后**归一化**:同一个版型所有裁片的占比之和 = 1,
再乘 `pattern.fabric_base` 就是每个裁片的米数。

## 2026-09-14 复核:改了一条规则,结论是「可用,待版师核」

业务说「没有细分数据,需要你来核」。**我不是版师,所以核的方式不是逐条拍板**,
是**拿独立的依据去验**,把明显不对的挑出来:

  · **同形制变体之间**结构应该一致(标准 / 加长 / 改良通勤只差总量)
  · **量纲常识写成性质**:纯上装衣身该占大头、领条该很小
  · **BOM 里的实际米数**能交叉验

复核抓到一条真错:**裙片占到 83%**。规则写的是「裙长 × 胸围×1.6 / 3」
(硬写死 3 片),外面**又乘了 `qty`** —— PT28 有 6 片时面积算成了 2 倍。
**分母写死 3、又乘实际片数,同一件事算了两遍。**
修法见下面「按整幅」那一栏。

修完之后的分布是健康的:

    纯上装    49 个版型,最大一片最高 61.7%(衣身)
    上下两件  27 个,最高 89.0%
    纯裙装    10 个,最高 93.4%(布几乎全在裙片上,**这是对的**)

⚠️ 第一版我把「单片 > 60%」一律当异常,**那个阈值一刀切了** ——
一条马面裙的裙片占 90% 本来就正常。判据要按**衣服类型**分档,不是一个数。

所以来源标 **`复核`**,不是 `版师` —— **我核的是「规则有没有算错」,
版师核的是「这个数对不对」,那是两件事。**

## ⚠️ 估出来的和版师给的不许长得一样

`ratio_src` 记来源:`估算`(机器估的)/ `复核`(核过规则,没核过数)/
`版师`(人核过数)/ `BOM`(明写的用量)。**三种可信度,不许长得一样。**
**版师改过的不许被重新估覆盖** —— 那是这条最容易出的错:
下次重跑估算脚本,把人工核过的数悄悄盖回去,而**没有任何地方会报**。

报价用估算值时,**必须在页面上说明它是估的** ——
一个标着「实价」的估算值,比一个标着「上限」的估算值糟得多。
"""

# 每条规则:(匹配词, 面积函数, 依据, 按整幅?)。**顺序有意义**,第一个命中的说了算。
# 面积函数拿一份基码尺寸 d(cm),返回面积(cm²)。
#
# ⚠️ **「按整幅」这一栏是核出来的,第一版没有。**
# 复核时发现裙片占到 **83%**:规则写的是「裙长 × 胸围×1.6 / 3」(硬写死 3 片),
# 然后外面**又乘了 `qty`** —— PT28 有 6 片时面积被算成 6/3 = **2 倍**。
# **分母写死 3、又乘实际片数,同一件事算了两遍。**
#
# 正确的是:**裙摆总宽是固定的(胸围×1.6),片数只决定怎么分,不决定总量** ——
# 一条裙子裁 3 片还是 6 片,用布一样多。
# 所以这类裁片标 `按整幅=True`,函数直接返回**整幅面积**,外面不再乘 qty。
#
# 同一个毛病的另一面:衣身的前片/后片是**真的每片都要一份布**(前片 ×2 就是两片),
# 那类仍然要乘 qty。**区别在于「片数是拆出来的」还是「片数是叠加的」。**
规则 = [
    (("上襦前片", "上襦后片"),
     lambda d: d.get("胸围", 100) / 2 * d.get("上襦衣长", d.get("衣长", 100) * .45),
     "上襦衣身按半胸围 × 上襦衣长", False),
    (("前片", "后片", "衣身", "袄前片", "袄后片", "上身前片", "上身后片",
      "裤前片", "裤后片", "背子"),
     lambda d: d.get("胸围", 100) / 2 * d.get("衣长", 100),
     "衣身按半胸围铺开 × 衣长", False),
    (("大袖片",),
     lambda d: (d.get("通袖长", 180) - d.get("肩宽", 40)) / 2 * d.get("胸围", 100) / 2,
     "大袖袖肥按半胸围估(大袖衫袖幅极阔)", False),
    (("袖片", "短袖片"),
     lambda d: (d.get("通袖长", 180) - d.get("肩宽", 40)) / 2 * d.get("胸围", 100) / 4,
     "袖肥按胸围/4 估(常规放量)", False),
    (("马面",),
     lambda d: d.get("裙长", 95) * d.get("马面宽", 32),
     "库里有马面宽这一项,直接用", True),
    # **整幅**:裙摆总宽固定,裁几片只决定怎么分,不决定总量 —— 不再乘 qty
    (("裙片", "褶裥片", "下裳褶裥", "下裳"),
     lambda d: d.get("裙长", 95) * d.get("胸围", 100) * 1.6,
     "裙摆总宽按胸围×1.6 估(A 字摆)。**整幅** —— 裁几片用布一样多", True),
    (("裙腰", "裙头"),
     lambda d: d.get("裙腰围", d.get("腰围", 70)) * 10,
     "裙腰是一条窄带,按腰围 × 10cm 估。**整幅**", True),
    (("领缘", "立领", "圆领", "方领", "竖领", "坦领", "诃子", "袖缘"),
     lambda d: d.get("领围", 38) * 8,
     "领条 / 袖缘窄,按 8cm 宽估", False),
    (("贴边", "牵条", "门襟"),
     lambda d: d.get("衣长", 100) * 6,
     "贴边是长条形,按 6cm 宽估", False),
    (("摆片", "侧摆", "内摆", "开衩", "垂髾", "横襕", "腰接片"),
     lambda d: d.get("衣长", 100) / 2 * 20,
     "小片,按半衣长 × 20cm 估", False),
    (("系带", "襳带", "绦"),
     lambda d: 120 * 4,
     "系带固定按 120×4cm 估", False),
]
兜底依据 = "没有匹配到的裁片,按半衣长 × 胸围/4 当小片估"


def 片面积(裁片名, 基码):
    """这个裁片的估算面积(cm²)。返回 (面积, 依据, 按整幅)。

    **按整幅 = True 时,外面不要再乘片数** —— 见文件顶上那段说明。
    """
    for 词, fn, why, 整幅 in 规则:
        if any(k in (裁片名 or "") for k in 词):
            try:
                return max(1.0, float(fn(基码))), why, 整幅
            except Exception:
                break
    return (max(1.0, 基码.get("衣长", 100) / 2 * 基码.get("胸围", 100) / 4),
            兜底依据, False)


def 版型占比(conn, 版型码):
    """一个版型每个裁片的用料占比。返回 [(裁片, 数量, 占比, 依据)],占比之和 = 1。

    **归一化是有意的**:我们估得出各片的相对大小,估不准绝对用布
    (排料、损耗、门幅都会影响)。而 `pattern.fabric_base` 是有的 ——
    **用可信的总量 × 估算的相对占比,比两个都估要稳。**
    """
    d = {r[0]: r[1] for r in conn.execute(
        "SELECT item,value FROM size_spec WHERE pattern=? AND size='M'", (版型码,))}
    if not d:
        d = {r[0]: r[1] for r in conn.execute(
            "SELECT item,value FROM size_spec WHERE pattern=?", (版型码,))}
    ps = [(r[0], r[1]) for r in conn.execute(
        "SELECT name,qty FROM pattern_piece WHERE pattern=?", (版型码,))]
    if not ps:
        return []
    行 = []
    for nm, qty in ps:
        a, why, 整幅 = 片面积(nm, d)
        行.append([nm, qty or 1, a if 整幅 else a * (qty or 1), why])
    总 = sum(x[2] for x in 行) or 1.0
    return [(nm, qty, round(area / 总, 4), why) for nm, qty, area, why in 行]
