"""白坯试衣的口径 —— **哪些单该试、试了签没签,以及签字在判责里算什么。**

知识库 08 号文件第五节那句话分量很重:

> **白坯试衣是重工订单唯一的后悔药。** 云锦缂丝一旦裁下去就没有回头路,
> 花几百块做一件白坯,能挡掉几万块的返工。

而系统里原来只做到了**一半**:

    已经有的                          完全没有的
    工期算进去了(重工档自动加 7–12 天)  **没有表** —— 试没试、谁陪的,一条记录都没有
    预约类型里有「到店试衣」            **没有状态** —— 订单流程里没有这一节
    知识库写清了三种试衣的分工          **没有签字** —— 而这一条最值钱

## ⚠️ 最要紧的不是记录,是**它在判责里算什么**

行业里试穿确认是**责任转移点**。而我们现在判尺寸争议**只有量体记录一张底牌** ——
09 号文件第五节就两行:「记录完整 → 客方收费改 / 记录不全 → **我方免费改**」。

补上试衣签字,等于给重工订单加**第二张底牌,而且是更硬的那张**:

    量体记录说的是  「**我们**量得对不对」
    试衣签字说的是  「**他本人穿过**并且认可了」

这两句话在判责时的分量完全不同。

## 「该试而没试」要往我方判,不是往客方

新增的判据**不是只往一个方向走**:

    该试 + 试了 + 签了字   → **客方**(他穿过并认可了)
    该试 + **没试**        → **我方**(我们没走该走的流程)
    该试 + 试了 + 没签字   → 回落到量体记录那两行

只写第一条的话,这个字段就变成了一个**单向对我方有利**的东西 ——
而一条只会往有利方向走的判据,业务不会信,也不该信。
"""
