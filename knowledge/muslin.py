def 该试衣(装饰最慢, crafts=(), 工时表=None):
    """这一单该不该做白坯试衣。返回 (该不该, 一句人话)。

    ⚠️ 判据见上面 `门槛_依据`(业务 2026-09-22 确认)。
    返回的那句话里带着「凭什么」,不许只返回一个 True/False 就完事 ——
    顾问要拿这句话跟客户解释为什么要多跑一趟。
    """
    if 工时表 is None:
        import leadtime
        工时表 = leadtime.craft_days()
    久 = (装饰最慢 or 0) >= 装饰最慢门槛
    单 = [k for k in (crafts or ())
          if (工时表.get(k) or (0,))[0] >= 单项工艺门槛]
    if not (久 or 单):
        return False, f"装饰工序最慢 {装饰最慢} 天,没有单项工艺超过 {单项工艺门槛} 天"
    why = []
    if 久: why.append(f"装饰工序最慢 {装饰最慢} 天(≥{装饰最慢门槛})")
    if 单: why.append(f"单项工艺 {'、'.join(单)} 起步就要 ≥{单项工艺门槛} 天")
    return True, ("**该做白坯试衣** —— " + "、".join(why)
                  + "(重工门槛业务 09-22 确认)")


