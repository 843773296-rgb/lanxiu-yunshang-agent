# **新规挂在「开裁」这个动作上,不挂在日期上。**
#
# 业务定新规时,库里已经有大量订单裁下去了 —— 那些是在旧规矩下裁的,
# **不能倒回去按新规矩判我方**(一条会追溯惩罚的规矩,业务不会信)。
# 所以按「这一单是怎么开裁的」分:
#
#     还没开裁                  → 新规(三类)—— 从现在起开裁都要过这道闸
#     经系统开裁(有开裁记录)    → 新规 —— 它是过了闸才裁的
#     系统接管开裁之前就裁了    → 旧规(只看重工)—— 那时候规矩就是这样
#
# 不用「生效日」的理由:演示世界的「今天」和真实日期不是一回事,
# 挑哪一天都会让一边的数据全落在另一边。**动作是确定的,日期不是。**
def 适用新规(开裁了吗, 系统开裁=False):
    """这一单按新规(三类)还是旧规(只看重工)判。**不知道开没开裁就返回 None。**"""
    if 开裁了吗 is None:
        return None
    return (not 开裁了吗) or bool(系统开裁)


def 必试(重工, 档位=None, 婚服=None, 新规=True):
    """这一件该不该**必须**做白坯试衣。返回 (结论, 一句人话, 命中了哪几类)。

    结论:True 必试 / False 不必 / None 判不了。
    重工  `该试衣()` 的结论(None = 判不了)
    档位  量体判出的档位:「标准码」「调号」「全定制」;None 或「需补量」= 判不了
    婚服  True / False / None(判不了)
    新规  False 时只看重工(系统接管开裁之前裁的单,见 `适用新规`)
    """
    if not 新规:
        if 重工 is None:
            return None, "**判不了** —— 这一单在系统接管开裁之前就裁了,按旧规只看重工,而重工判不出", []
        return (bool(重工),
                "按旧规(系统接管开裁之前裁的单只看重工):" + ("重工,该试" if 重工 else "不是重工,不必试"),
                ["重工"] if 重工 else [])
    中, 不明 = [], []
    for 名, 值 in (("重工", 重工),
                   ("全定制", None if 档位 in (None, "需补量") else 档位 == "全定制"),
                   ("婚服", 婚服)):
        if 值 is None: 不明.append(名)
        elif 值: 中.append(名)
    if 中:
        return True, f"**必须做白坯试衣** —— 属于{'、'.join(中)}(业务 09-22 定的三类命中任一即必试)", 中
    if 不明:
        return None, (f"**判不了** —— {'、'.join(不明)}这一类判不出。"
                      "**判不了不等于不必试**:不知道体型标不标准,和体型标准是两件事"), []
    return False, "不是重工、不是全定制、不是婚服 —— 按业务 09-22 定的范围不必试", []


