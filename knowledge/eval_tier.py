#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""评测集频率分层 —— **口径的唯一出口**。

规则逐字来自 `knowledge/17-评测集频率分层.md`(用户 2026-11-10 拍的板)。

## 为什么这个模块里一个常数都不手抄

三层的门槛(95% / 85% / 不设)、目标占比(60/30/10)、样本量下限(20)、
每个场景属哪一层 —— **全部现读那份 md**。

这个项目为「同一个事实两个来源」栽过:生命周期口径曾有两份手抄件
(`seed.py` 和 `server.py` 各写一份优先级列表),漂了不报错 ——
页面上印「优先级 3」,实际按第 4 位算,没有任何迹象。
分层比那个更容易漂:**改频率的人会去改 md(那是给人读的),
不会想到还有一份常数躺在 py 里**。

## 这个模块不判「一道题难不难」

层名是**频率语义**(日常/偶发/罕见),不是难度。用户最初说的是
「主流/困难/极端」,而他选的标准是「按出现频率」—— 这两个不是一回事。
**别拿这三个层名去推断难度**,也别在这里加「难度」字段:
要难度就另开一轴,和频率分开报。

## 「没打标」和「打不了标」是两件事

`层()` 返回 `None` 有两种含义,调用方**必须分开处理**:

    套在「不打频率标」名单里   → 它是另一个维度的题(角色边界 / 早期负向),
                                 照常报分、单列一行,**不是缺陷**
    套压根不在这份口径里       → **这是缺陷**:新加了题集却没打标,
                                 判据要判红(见 tools/eval_tier_check.py)

所以这里给两个口:`层()` 只回答层名,`认得这套吗()` 回答它是不是登记过的。
少了后者,「新套漏打标」会被静默当成「不打标的套」—— 而那两件事
在一个 `None` 上长得一模一样。
"""
import io
import os
import re

这里 = os.path.dirname(os.path.abspath(__file__))
真相源 = os.path.join(这里, "17-评测集频率分层.md")
层名 = ("日常", "偶发", "罕见")


def _读():
    return io.open(真相源, encoding="utf-8").read()


def _表行(段文):
    """一张 markdown 表里的数据行(去掉表头和分隔行)。"""
    出 = []
    for l in 段文.split("\n"):
        l = l.strip()
        if not l.startswith("|"):
            continue
        格 = [c.strip() for c in l.strip("|").split("|")]
        if not 格 or set("".join(格)) <= set("-: "):
            continue
        if 格[0].strip("*") in ("套", "层"):
            continue
        出.append(格)
    return 出


def _段(文, 标题, 下一个标题前缀="#"):
    i = 文.find(标题)
    assert i >= 0, f"真相源里找不到「{标题}」这一节 —— 口径和模块对不上了"
    j = 文.find("\n" + 下一个标题前缀, i + len(标题))
    return 文[i:j if j > 0 else len(文)]


def 分层表():
    """`{(套, 前缀 or None): 层}`。前缀 None = 整套一个场景。"""
    文 = _读()
    出 = {}
    for 层 in 层名:
        for 格 in _表行(_段(文, f"### {层}(")):
            套, 场景 = 格[0], 格[1]
            m = re.match(r"^([A-Z]{1,3})\s", 场景)
            出[(套, m.group(1) if m else None)] = 层
    return 出


def 不打标的套():
    """`{套: 为什么}` —— 它们是**另一个维度**的题,不是漏打标。"""
    出 = {}
    for 格 in _表行(_段(文 := _读(), "## 不打频率标的")):
        if len(格) >= 3:
            出[格[0]] = 格[2]
    assert 出, "真相源里「不打频率标」那张表读空了"
    return 出


def 门槛():
    """`{层: 通过率下限}`;不设门槛的层值是 `None`(**不是 0**)。

    ⚠️ `None` 和 `0` 必须分开:`0` 会让「任何分数都达标」被读成达标,
    而 `None` 的意思是**这一层不参与放行判定**。
    """
    出 = {}
    for 格 in _表行(_段(_读(), "## 三层的定义")):
        层 = 格[0].strip("*")
        if 层 not in 层名:
            continue
        m = re.search(r"≥\s*(\d+)\s*%", 格[-1])
        出[层] = int(m.group(1)) / 100 if m else None
    assert set(出) == set(层名), f"三层的定义只读出 {sorted(出)}"
    return 出


def 目标占比():
    """`{层: 占比}`,现读那张目标分布表(用户拍的 60/30/10)。"""
    出 = {}
    for 格 in _表行(_段(_读(), "## 目标分布")):
        层 = 格[0].strip("*")
        if 层 not in 层名:
            continue
        m = re.search(r"(\d+)\s*%", 格[1])
        assert m, f"{层} 那一行读不出目标占比"
        出[层] = int(m.group(1)) / 100
    assert set(出) == set(层名), f"目标分布只读出 {sorted(出)}"
    s = sum(出.values())
    assert abs(s - 1.0) < 1e-9, f"目标占比加起来是 {s},不是 1"
    return 出


def 样本量下限():
    m = re.search(r"≥\s*(\d+)\s*题才报门槛判定", _读())
    assert m, "读不出样本量下限 —— 真相源最后那节的写法变了"
    return int(m.group(1))


def 范围外的套():
    """**不是题集**的结果文件 —— 不打标也不算漏打标。

    和「不打频率标的套」分开:后者是题、只是另一个维度;
    这里的压根不是一套题(比如 V1 那条链跑出来的产物)。
    合成一个名单会让「漏打标」藏在「本来就不用打标」里。
    """
    出 = {}
    for 格 in _表行(_段(_读(), "### 不是题集")):
        if len(格) >= 2:
            出[格[0]] = 格[1]
    assert 出, "真相源里「不是题集」那张表读空了"
    return 出


def 认得这套吗(套):
    return (套 in {s for s, _ in 分层表()}
            or 套 in 不打标的套() or 套 in 范围外的套())


def 层(套, 题号, 表=None):
    """这道题属哪一层;不打频率标的套、以及登记过但对不上前缀的,返回 `None`。

    **先试前缀,再退整套** —— 运维那一大套一套混了 14 个场景,
    而其余套整套一个场景。
    """
    表 = 分层表() if 表 is None else 表
    m = re.match(r"^([A-Za-z]{1,3})", str(题号) or "")
    if m and (套, m.group(1).upper()) in 表:
        return 表[(套, m.group(1).upper())]
    return 表.get((套, None))


def 分布(题们):
    """`题们` = `[(套, 题号), …]` → `({层: 条数}, 不打标的, 范围外的, 认不出来的)`。

    **四样分开返回,一样都不许合并。** 它们是四件事:

        某一层 0 题      → 那一层的通过率说明不了什么(空集合上性质全成立)
        这套不打频率标   → 它是**另一个维度**的题(角色边界 / 抗压),正常
        这套不是题集     → 它压根不是题(V1 跑出来的产物),正常
        这套认不出来     → **缺陷**:新加了题集没人打标

    合成一个「没打标的数」之后,**漏打标就藏在「本来就不用打标」里面** ——
    而这正是这份判据存在的理由。
    """
    表, 不打, 外 = 分层表(), 不打标的套(), 范围外的套()
    计 = {x: 0 for x in 层名}
    标外, 范围外, 不认得 = 0, 0, []
    for 套, 题号 in 题们:
        if 套 in 不打:
            标外 += 1
            continue
        if 套 in 外:
            范围外 += 1
            continue
        t = 层(套, 题号, 表)
        if t is None:
            不认得.append((套, 题号))
        else:
            计[t] += 1
    return 计, 标外, 范围外, 不认得


def 自测():
    坏 = []
    表 = 分层表()
    if len(表) < 20:
        坏.append(f"分层表只读出 {len(表)} 条,真相源那三张表没读全")
    # 门槛:罕见必须是 None(不设门槛),另两层必须是数
    g = 门槛()
    if g.get("罕见") is not None:
        坏.append("罕见层读出了一个门槛数 —— 口径里它是「只报分,不设门槛」")
    if not (g.get("日常") and g.get("偶发")):
        坏.append(f"日常/偶发的门槛没读出来:{g}")
    if g.get("日常") and g.get("偶发") and g["日常"] <= g["偶发"]:
        坏.append("日常的门槛没有比偶发高 —— 口径里日常更严")
    # 目标占比
    z = 目标占比()
    if z != {"日常": 0.6, "偶发": 0.3, "罕见": 0.1}:
        坏.append(f"目标占比读出来是 {z},口径里是 60/30/10")
    # 前缀优先于整套:运维那一大套必须按前缀分得开
    if 层("ops", "T01") == 层("ops", "R01"):
        坏.append("运维那套的两个不同频率场景被判成同一层 —— 前缀没起作用")
    if 层("ops", "C1") != "罕见":
        坏.append(f"渠道对比应是罕见,读出来是 {层('ops', 'C1')}")
    if 层("chat", "P01") != "日常":
        坏.append(f"工艺问答应是日常,读出来是 {层('chat', 'P01')}")
    # 不打标的套:层() 要给 None,而「认得」要是 True —— 这两件必须分得开
    if 层("role", "A01") is not None:
        坏.append("角色边界题不该有频率层")
    if not 认得这套吗("role"):
        坏.append("角色边界题是登记过的「不打标」,不是没登记")
    if 认得这套吗("压根没有这套_自测"):
        坏.append("一个没登记的套被认成登记过的 —— 新套漏打标就查不出来了")
    # 分布:三样必须分开
    计, 标外, 范围外, 不认得 = 分布([("ops", "R01"), ("ops", "T01"), ("role", "A01"),
                                   ("v1", "D2000"), ("没登记的套", "X1")])
    if not (计["日常"] == 1 and 计["罕见"] == 1 and 标外 == 1
            and 范围外 == 1 and len(不认得) == 1):
        坏.append(f"分布把四件事混了:{计} 标外={标外} 范围外={范围外} 不认得={不认得}")
    if 样本量下限() < 10:
        坏.append(f"样本量下限 {样本量下限()} 太低,地板守不住空集合")
    return 坏


if __name__ == "__main__":
    import sys
    坏 = 自测()
    表 = 分层表()
    print(f"评测集频率分层 · 口径自测(读 {os.path.basename(真相源)})")
    print(f"  分层表 {len(表)} 条 · 门槛 {门槛()} · 目标 {目标占比()} · 下限 {样本量下限()}")
    print(f"  不打频率标的套:{', '.join(不打标的套())}")
    for x in 坏:
        print(f"  ❌ {x}")
    print("  ✅ 口径自测全过" if not 坏 else f"\n❌ {len(坏)} 条不符合口径")
    sys.exit(1 if 坏 else 0)
