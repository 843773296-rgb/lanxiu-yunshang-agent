#
# 这个判断不是随便定的,按代价方向推:
# · 地址不明 → 按兜底收 28:客户可能被多收(他其实在江浙沪)→ 他会问,**可逆**;
# · 地址不明 → 算 0 免邮:我方少收一笔运费 → 钱没收就是没收,**不可逆**。
#
# 但**收了要说出来**:返回里带一句「这是按兜底算的,不是按地址算的」,
# 并把 `要人确认` 置 True。否则它和一个真的按地址算出来的 28 元
# **在那张单子上长得一模一样**。
