# **按长度从长到短** —— 顺序由长度决定,不由手顺决定(理由见 `规范省份` 的注释)
省份后缀 = tuple(sorted(
    ("省", "市", "自治区", "特别行政区", "维吾尔自治区", "壮族自治区", "回族自治区"),
    key=len, reverse=True))


def 规范省份(省):
    """「上海」和「上海市」是同一个省份。只做最小归一,不猜。

    ⚠️ **不做模糊匹配**:「江苏」vs「江苏省」要认成一个,
    但「黑龙江」里也有「江」—— 所以只去掉结尾的那几个后缀,不做子串包含。

    ⚠️⚠️ **后缀必须按长度从长到短试。** 第一版照手顺写成
    `("省","市","自治区","特别行政区","维吾尔自治区",...)`,于是
    「新疆维吾尔自治区」**先命中短的「自治区」**,剥成「新疆维吾尔」——
    和区域表里登记的「新疆」对不上,整个偏远区从 48 元掉回兜底 28 元。
    长的那几条后缀**一条都没机会用上**,而它们明明写在表里。
    > 一张「写了但永远匹配不到」的后缀表,和一张没写的,**在代码里长得一模一样。**
    所以这儿 `sorted(..., key=len, reverse=True)`,**让顺序由长度决定,不由手顺决定**。
    """
    s = str(省 or "").strip()
    for 尾 in 省份后缀:
        if s.endswith(尾) and len(s) > len(尾):
            s = s[:-len(尾)]
            break
    return s


def 省份清单(文本):
    """区域表里那一列(「上海,浙江,江苏」)拆成规范化的集合。"""
    out = []
    for x in str(文本 or "").replace("、", ",").replace("，", ",").split(","):
        x = 规范省份(x)
        if x:
            out.append(x)
    return out


def 查区域表(区域表):
    """区域表本身合不合格。返回 (行不行, 一句人话)。

    ⚠️ **空表不许当「都免邮」。** 这个项目的规矩:空集合上所有性质都成立 ——
    一张空的区域表会让每一单都算不出区,而「算不出来」要是回落到 0,
    就是**整店静默免邮**,而报表上完全正常。
    """
    if not 区域表:
        return False, ("运费区域表是空的 —— **这不叫「都免邮」,叫表还没配**。"
                       "去运营后台配区域")
    兜底 = [z for z in 区域表 if z.get("兜底")]
    if not 兜底:
        return False, ("区域表里没有**兜底区** —— 那么一个没登记的省份就算不出运费,"
                       "而算不出来要是回落到 0,就是静默免邮。"
                       "把「其他」那一档标成兜底")
    if len(兜底) > 1:
        return False, (f"有 {len(兜底)} 个区都标了兜底({'、'.join(z['区域'] for z in 兜底)})"
                       f"—— 兜底只能有一个,不然命中哪个看顺序,而顺序会漂")
    撞 = {}
    for z in 区域表:
        for p in 省份清单(z.get("省份")):
            撞.setdefault(p, []).append(z.get("区域"))
    重 = {p: v for p, v in 撞.items() if len(v) > 1}
    if 重:
        return False, ("同一个省份登记在两个区里:"
                       + "；".join(f"{p} 在 {' / '.join(v)}" for p, v in list(重.items())[:3])
                       + " —— 命中哪个要看顺序,**而顺序会漂**")
    坏 = [z.get("区域") for z in 区域表
          if not isinstance(z.get("运费"), (int, float)) or z.get("运费") < 0]
    if 坏:
        return False, f"这几个区的运费不是一个非负的数:{'、'.join(map(str, 坏))}"
    return True, f"{len(区域表)} 个区,兜底是「{兜底[0]['区域']}」"


def 找区(省, 区域表):
    """这个省份落在哪个区。返回 (那一行, 怎么落进去的)。

    怎么落进去的,**三种,不是两种**:
      "命中"    这个省明确登记在某个区里
      "兜底"    这个省有值,但没登记在任何区 —— **兜底区就是为它准备的,这是正常的**
      "没省份"  省份是空的 —— **这才是异常**:不知道寄到哪

    ⚠️ 第一版把后两种合成了一种(都算「靠兜底」、都要人确认),于是
    **安徽 / 广东 / 北京这些正常省份全被标成要人确认** —— 实测 1437 位客户。
    > 一个「兜底区接住了它该接的省份」和一个「根本不知道寄到哪」,
    > **在「落进了兜底区」这件事上长得一模一样** —— 而只有后者该让人停下来看。
    把前者也标成要人确认,结果是**这个标记在 1437 个正常单上响**,
    那它在真正该响的那一单上就没人看了。
    """
    兜底 = next((z for z in 区域表 if z.get("兜底")), None)
    p = 规范省份(省)
    if not p:
        return 兜底, "没省份"
    for z in 区域表:
        if z.get("兜底"):
            continue              # 兜底区不靠省份命中,它是最后那一档
        if p in 省份清单(z.get("省份")):
            return z, "命中"
    return 兜底, "兜底"


def 算运费(省, 货品金额, 区域表, 满额免邮门槛):
    """这一单收多少运费。返回一个 dict,**算不出来时不返回 0**。

    货品金额  **必须是货品金额(`ordr.goods_amount`),不是含运费的合计。**
        ⚠️ 用含运费的合计会绕回自己:运费加上去刚好够门槛 → 免运费 →
        又不够门槛 → 再加运费……**而它不会报错,只会在边界上给出两个都说得通的答案**。
        这一条写在这儿,是因为参数名叫「金额」的时候两者长得一模一样。
    """
    行, 话 = 查区域表(区域表)
    if not 行:
        return dict(运费=None, 算得出来=False, 依据=话, 要人确认=True, 区域=None)
    try:
        货 = float(货品金额)
    except (TypeError, ValueError):
        return dict(运费=None, 算得出来=False, 要人确认=True, 区域=None,
                    依据=f"货品金额给的是「{货品金额}」,不是一个数 —— "
                         f"**算不出来,不是免邮**")
    if 货 < 0:
        return dict(运费=None, 算得出来=False, 要人确认=True, 区域=None,
                    依据=f"货品金额是负数({货})—— 算不出来,不是免邮")
    try:
        门 = float(满额免邮门槛)
    except (TypeError, ValueError):
        return dict(运费=None, 算得出来=False, 要人确认=True, 区域=None,
                    依据=f"满额免邮门槛给的是「{满额免邮门槛}」,不是一个数")

    区, 怎么落的 = 找区(省, 区域表)
    if 货 >= 门:
        return dict(运费=0.0, 算得出来=True, 要人确认=False, 区域=区["区域"],
                    怎么落的=怎么落的,
                    依据=f"货品金额 {货:.2f} ≥ 满额免邮门槛 {门:.2f} → 免运费",
                    免邮原因="满额")
    出 = dict(运费=float(区["运费"]), 算得出来=True, 区域=区["区域"], 怎么落的=怎么落的,
              免邮原因=("区域免邮" if float(区["运费"]) == 0 else None))
    if 怎么落的 == "没省份":
        # **只有这一种要人确认** —— 见 `找区` 上面那段:
        # 把正常落兜底的也标上,这个标记就会在一千多个正常单上响
        出.update(要人确认=True,
                  依据=(f"**没有收货省份** → 按兜底区「{区['区域']}」"
                        f"收 {区['运费']:.2f}。{地址不明怎么办}"))
    elif 怎么落的 == "兜底":
        出.update(要人确认=False,
                  依据=(f"{省} 没单独登记 → 落兜底区「{区['区域']}」→ {区['运费']:.2f}"
                        + ("(这个区免邮)" if float(区["运费"]) == 0 else "")
                        + " —— 兜底区就是为没单独登记的省份准备的,这是正常的"))
    else:
        出.update(要人确认=False,
                  依据=(f"{省} 在「{区['区域']}」区 → {区['运费']:.2f}"
                        + ("(这个区免邮)" if float(区["运费"]) == 0 else "")))
    return 出


