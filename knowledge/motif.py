    print("  扫库:" + 说明)
    for b in 坏:
        print("  ❌", b)
    print(f"  {'❌ %d 条不过' % len(坏) if 坏 else '✅ 8 例全过(含 2 例「不许猜」和 1 例雅名不是纹样)'}")
    raise SystemExit(1 if 坏 else 0)
