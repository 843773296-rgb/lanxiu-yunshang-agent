def 花色来自工艺(工艺=""):
    """这件衣服的花色是不是**工艺染 / 印出来的**(而不是绣上去的具象纹样)。
    返回命中的那门工艺名,没有返回 None。给出图提示词这类「怎么描述这件衣服」的地方用。"""
    return next((k for k in 染缬 if k in (工艺 or "")), None)


def 词表(本期=False):
    """本期=True 只给现在库里应该有的那些词(预留词排除)"""
    return tuple(w for w in 词 if not 本期 or w not in 预留)


def 归一(w):
    """商品名里的写法 → 词表里的词"""
    return 别名.get(w, w if w in 词 else None)


def 从名字(名):
    """名字里明写了纹样就直接用它。**附上抽自哪一段** ——
    「照水」是雅名不是纹样,没有证据的抽取一定会错,而错了不会报错。"""
    for w in sorted(list(别名) + list(词), key=len, reverse=True):
        if w in (名 or "") and 归一(w):
            return 归一(w), f"商品名里的「{w}」"
    return None, None


def 推(名, 面料="", 工艺=""):
    """→ (纹样, 来源, 证据)。来源:商品名 / 面料推导 / 工艺推导 / 素面料 / 待业务核"""
    文 = " ".join(x or "" for x in (名, 面料, 工艺))
    # ① 补子:品级制度,不许猜(这一条必须排在最前面 —— 排在推导之后就永远轮不到它)
    if "补子" in 文:
        return 待核, 待核, "04-配饰.md:纹样有品级制度,用错等同于礼制错误 —— 补子按品级定,不推"
    # ② 名字里明写的
    w, ev = 从名字(名)
    if w:
        return w, "商品名", ev
    # ③ 面料织花的,花是织进去的
    for k, (ws, src) in 面料纹.items():
        if k in 文:
            return ws[0], "面料推导", f"{k} → {'、'.join(ws)};{src}"
    # ④ 工艺上花的
    for keys, ws, src in 工艺纹:
        if any(k in 文 for k in keys) and not any(k in 文 for k in 针法 if k not in keys):
            return ws[0], "工艺推导", f"{'、'.join(k for k in keys if k in 文)} → {ws[0]};{src}"
    # ⑤ 素织的料:没有花就是没有花,这是答案不是空白
    if any(k in 文 for k in 素织):
        return "无纹样", "素面料", f"{next(k for k in 素织 if k in 文)} 是素织,花要另外绣或染上去"
    return 待核, 待核, "面料和工艺都推不出来 —— **不猜**"


def 自检():
    """同源谬误提醒:这些期望值是**手写**的,不是拿本模块现算的。"""
    例 = [
        ("「缂丝团花」唐制半臂", "缂丝", "缂丝", "团花", "商品名"),
        ("「照水」素缎明制马面裙·阔褶", "素缎", "", "无纹样", "素面料"),      # 雅名不是纹样
        ("「金襕」织金缎马面裙(现货)", "织金缎", "", "缠枝", "面料推导"),
        ("「霜序」提花明制立领长袄", "提花暗纹缎", "", "暗花", "面料推导"),
        ("「山鸣」真丝素罗明制贴里", "真丝素罗", "苏绣", "折枝", "工艺推导"),  # 素料 + 绣 → 绣的花
        ("明制圆领袍(带补子)", "云锦", "补子", 待核, 待核),                   # 品级,不许猜
        ("「青黛」蓝印花布交领襦裙", "高支纯棉", "蓝印花布", "无纹样", "工艺推导"),
        # 「无纹样」= 没有**具象**纹样,不等于这件衣服素面 —— 染缬类的花是工艺染出来的(09-24 出图清单踩到)
        ("手工盘扣 花型(六颗装)", "", "盘扣", 待核, 待核),                    # 推不出来就说推不出来
    ]
    坏 = []
    for 名, m, k, 期望, 期望源 in 例:
        w, src, ev = 推(名, m, k)
        if (w, src) != (期望, 期望源):
            坏.append(f"{名}:推出 {w}/{src},应为 {期望}/{期望源}")
        if not ev:
            坏.append(f"{名}:没给证据")
    # 「四合如意」是云肩的形制,不是纹样 —— 抽错过一次,钉在这里
    w, src, _ = 推("盘金绣 云肩(四合如意)", "", "盘金绣")
    if w == "柿蒂":
        坏.append("「云肩(四合如意)」被当成柿蒂纹 —— 那是云肩的形制,不是它上面的花")
    # 词表是闭集:推出来的东西必须在词表里(或者是「待业务核」)
    for 名, m, k, *_ in 例:
        w, _, _ = 推(名, m, k)
        if w not in 词 and w != 待核:
            坏.append(f"{名}:推出了词表外的「{w}」")
    return 坏


def 扫库(db=None):
    """拿这份口径扫一遍商品库:**本期在用的词一个都不许命中 0。**
    命中 0 的两种可能 ——「库里真没有」和「抽取规则坏了」—— 在数据上长得一模一样,
    所以预留词单独标出来,剩下的命中 0 就是故障,不是正常。"""
    import os, sqlite3
    db = db or os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                            "backend", "lanxiu.db")
    if not os.path.exists(db):
        return None, "库不在(跳过)"
    c = sqlite3.connect(db)
    n = {}
    for 名, mt, kf in c.execute("SELECT p.name, pc.mt_opts, pc.kf_opts FROM product p "
                                "LEFT JOIN product_custom pc ON pc.spu=p.spu"):
        w, _, _ = 推(名, mt or "", kf or "")
        n[w] = n.get(w, 0) + 1
    总 = sum(n.values())
    零 = [w for w in 词表(本期=True) if not n.get(w)]
    return 零, f"{总} 件商品 · " + " ".join(f"{k}{v}" for k, v in sorted(n.items(), key=lambda x: -x[1]))


