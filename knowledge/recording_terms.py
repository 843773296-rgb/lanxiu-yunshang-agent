"""录音同意的口径 —— 业务 2026-09-20 定的三条(待决策清单 一·3、一·4、D9):

    ① 录音同意**写进应用说明(服务条款)**,不二次确认;电话 / 上门**默认同意录音**
    ② 录音同意**不能撤回**
    ③ 由 ② 推出来的两件事(D9):
       (a) 不能撤回,就**不许在任何界面显示撤回入口** —— 否则界面在骗人
       (b) **不进 `consent` 表**。那张表是「可撤回的、逐着装人的授权」(都带 revoked_at),
           录音同意是**条款接受** —— 硬塞进去会多出一档 revoked_at 永远为 NULL 的记录,
           和另外几档长得一模一样、语义却相反。→ 单独记「条款版本 + 客户接受时间」

所以这里**不判「能不能录」**(业务定了默认同意,不设闸),只回答一件事:
**这一通录音,同意的依据是什么** —— 客户接受过含录音条款的版本,还是按业务规定默认同意。
两者都合规,但它们**不是一回事**:前者客户点过「同意」,后者是规定。混成一个「已同意」,
哪天要拿出证据时分不开。

不碰库、不取当前日期。
"""
import re

条款文档 = "服务条款"
# ⚠️ **演示假设**:录音条款从服务条款 v2.3 起写入。业务只定了「写进应用说明」,没说哪一版 ——
# 库里账户的条款版本只有 v2.1 / v2.3 两种,取较新那版。上线前以法务实际发布的版本为准
录音条款起始版本 = "v2.3"
# ⚠️ **demo 草稿**,不是法务定稿。写在这儿是为了让「条款里到底写了什么」有一处能查,而不是空着
录音条款草稿 = ("为保证服务质量和您的需求被准确记录,门店顾问与您的电话沟通、上门及到店沟通可能会被录音,"
              "录音仅用于整理沟通内容、跟进您的需求和服务质量检查,不对外提供。")
默认同意依据 = "电话 / 上门 / 到店默认同意录音(业务 2026-09-20 定:写进应用说明,不二次确认)"

咬合 = []


def _版本号(v):
    m = re.match(r"v?(\d+)(?:\.(\d+))?", str(v or ""))
    return (int(m.group(1)), int(m.group(2) or 0)) if m else None


def 含录音条款吗(版本):
    """这一版服务条款里有没有录音条款。版本认不出来 → False(说不清就不算接受过)。"""
    a, b = _版本号(版本), _版本号(录音条款起始版本)
    return bool(a and a >= b)


def 依据(最近接受):
    """最近接受 = (版本, 接受时间) 或 None。返回 (类别, 一句人话)。类别:条款接受 / 默认同意。

    **不返回「不同意」** —— 业务定了不能撤回、默认同意,没有这一档。
    """
    if 最近接受 and 含录音条款吗(最近接受[0]):
        return "条款接受", f"客户 {str(最近接受[1])[:10]} 接受了{条款文档} {最近接受[0]}(含录音条款)"
    if 最近接受:
        return "默认同意", (f"客户接受过的{条款文档}是 {最近接受[0]},早于录音条款({录音条款起始版本} 起)—— "
                          f"按{默认同意依据}")
    return "默认同意", f"客户没有在小程序上接受过{条款文档}(没注册账户)—— 按{默认同意依据}"
