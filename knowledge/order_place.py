def 逐件判(类型, 着装人, 开单时间, 场次们, 订单行, 需要的项):
    """一件能不能随整单确认下单。返回 (结论, 一句人话)。结论:可以 / 不可以 / 判不了。

    类型      「定制品」/「标品」
    场次们    这个着装人的全部量体场次(measure.场次 的结果)
    需要的项  这件衣服的版型要比对的量体项;None = 不知道(→ 判不了)
    """
    if 类型 != "定制品":
        return "可以", "标品按尺码卖,不用下单量体"
    if not 着装人:
        return "判不了", ("**这一件还没定给谁做** —— 下单量体量的必须是穿这件的人,"
                          "先定着装人,再量")
    s, 话 = measure.以哪次为准(场次们, 订单行=订单行)
    if s is None:
        return "不可以", 话
    if str(s["时间"] or "") < str(开单时间 or ""):
        return "不可以", (f"这一件绑的下单量体是 {s['时间']} 量的,**早于开单**({开单时间})—— "
                          "那不是为这一件重新量的。业务 09-22:签单时按这件衣服重新量,以这次为准")
    if 需要的项 is None:
        return "判不了", "**不知道这个版型要比对哪几项**(没挂尺码表)—— 判不了够不够,不许当成够"
    缺 = measure.缺哪几项(s, 需要的项)
    if 缺:
        return "不可以", f"这次下单量体缺 {'、'.join(缺)} —— 做这件衣服要用,补量后再确认(缺项不从别的场次拼)"
    return "可以", 话


# 业务 09-22:开单时衣服和穿的人要对得上(「肯定要」);成人款最低 14 周岁,业务 09-22 确认
成人款最小周岁 = 14
童款最大周岁 = 17


def 穿的人对不对(商品性别, 顶级品类名, 着装人性别, 着装人周岁):
    """这件衣服能不能开给这个人。返回 (结论, 一句人话)。结论:可以 / 不可以 / 判不了。

    **先看品类树,再看商品性别**(和 order_gate.定位着装人 同一个顺序:树比 gender 可靠)。
      女 / 男款   性别要对上;不满 14 周岁的不行 —— 该开童款
      童款        要未成年(不满 18 周岁)
      通用 / 不按人裁的(面料部件)/ 配饰这类分不出性别的  不查
    着装人性别或生日没登记 → **判不了**,开单时当拦(判不了不等于可以)。
    """
    import order_gate as OG
    if 顶级品类名 and not OG.要按人裁吗(顶级品类名)[0]:
        return "可以", f"「{顶级品类名}」不按人裁,不用对人"
    该 = (OG.按品类定性别(顶级品类名) if 顶级品类名 else None) or 商品性别
    if 该 in OG.分不出性别的:
        return "可以", "通用款,不分男女"
    if 该 == OG.童款:
        if 着装人周岁 is None:
            return "判不了", "这是童款,**着装人没登记生日** —— 判不了是不是孩子,先补生日"
        if 着装人周岁 > 童款最大周岁:
            return "不可以", f"这是童款,着装人 {着装人周岁} 岁 —— 童款只开给未成年人,大人请换成人款"
        return "可以", "童款,着装人是孩子"
    if not 着装人性别:
        return "判不了", f"这是{该}款,**着装人没登记性别** —— 先补"
    if 着装人性别 != 该:
        return "不可以", f"这是{该}款,着装人是{着装人性别}性 —— 衣服和穿的人对不上,请换款或换着装人"
    if 着装人周岁 is None:
        return "判不了", f"这是{该}款成人衣,**着装人没登记生日** —— 判不了是不是孩子,先补生日"
    if 着装人周岁 < 成人款最小周岁:
        return "不可以", f"这是{该}款成人衣,着装人才 {着装人周岁} 岁 —— 不满 {成人款最小周岁} 岁请开童款"
    return "可以", f"{该}款,着装人对得上"


def 整单(各件):
    """各件 [(结论, 话)] → (整单结论, 一句人话)。"""
    if not 各件:
        return "判不了", "这张单一件商品都没有"
    不 = [w for g, w in 各件 if g == "不可以"]
    疑 = [w for g, w in 各件 if g == "判不了"]
    if 不:
        return "不可以", f"有 {len(不)} 件过不了:" + ";".join(不[:3])
    if 疑:
        return "判不了", f"有 {len(疑)} 件判不了:" + ";".join(疑[:3]) + " —— **判不了不等于可以**"
    return "可以", "每一件都有为它重新量的下单量体,可以确认下单"


