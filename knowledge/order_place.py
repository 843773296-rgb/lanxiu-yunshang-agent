"""下单的口径 —— **先开单 → 再量 → 量完绑到这一件 → 确认下单。** 唯一源头,不碰库、不取今天。

## 业务 2026-09-22 拍板

  · 「每一个订单都需要有绑定的下单量体数据」—— 没有就不许下单,回头客也一样
  · 签单时按这件衣服的要求重新量,**这一件以这次为准**
  · 顺序:**先开单(订单里有这一件)→ 再量 → 量完绑到这一件 → 确认下单**

  · **付款默认在确认下单时已经完成**(业务 09-22)—— 定制单确认后**跳过「待付款」**,直接进「待审核」;
    开单后、确认前停在新状态「待确认」(不进业绩、不催付款、可直接取消)。标品流程不变。

所以下单拆成两个动作:

    开单      订单和订单行先建出来(还没生效)—— 下单量体要绑的那一件得先存在
    确认下单  逐件过闸:定制的每一件都有绑在它上面的、开单之后量的、够做这件衣服的下单量体

## 确认下单逐件判什么

  标品              不量体,按尺码卖 —— 直接过
  定制,着装人没定   **判不了** —— 下单量体量的必须是穿这件的人,不知道是谁就没法量
  没有下单量体      不可以 —— 业务的硬规矩
  下单量体早于开单  不可以 —— 那不是为这一件重新量的(是拿旧量体顶上的)
  缺这件要用的项    不可以 —— 列出缺哪几项(缺项不从别的场次拼,见 measure.py)
  版型要哪几项不知道 **判不了** —— 不许当成「不缺」放行

**整单**:有一件不可以 → 不可以;没有不可以但有判不了 → 判不了;全过 → 可以。
**判不了不等于可以** —— 和 order_gate / muslin 同一条。
"""
