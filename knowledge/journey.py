#!/usr/bin/env python3
"""客户旅程的口径 —— **唯一源头**,不碰库、不取时间。

归因算法(W 型 / Shapley)要的输入是**客户旅程**:一个客户从第一次接触到下单,
中间经过了哪些点、每个点是谁经手的。这些点库里本来就有,只是散在五张表里
(预约 / 跟进 / 日程 / 量体 / 下单),**没有一处把它们连起来**。

## 🔑 触点不是「记录」,是「谁在什么时候做了什么」

同一张表里的记录,**不一定都是触点**:

    量体 10624 条,但**一个客户一次量体会产生十几条记录**(每个测量项一条)——
    那是**一次**触点,不是十几次。

不去重的话,量体那一类会以 10:1 的比例淹没其他触点,
**而归因算出来的「量体贡献最大」只是因为它的行数最多** ——
那不是发现,是**计数方式**。

ℹ 查过:7450 场量体里有 **97 场是多人的**(最多 8 人),占 1.3%。
  按 (日期, 经手人) 去重会把那 97 场算成多个触点 —— **对归因来说这是对的**
  (确实多人参与),所以不再往下合并。

## 🔑 「没有触点」和「触点不够算」要分开

    没有任何触点        → 这个客户在库里没有留下过程,**不是「没人管他」**
    只有下单这一个点    → 算不出谁促成的(前面的过程没记)
    有两个以上有人的点  → 能算

三种都会让归因返回空,**而它们在一张空结果里长得一模一样**。
"""

# **顺序即业务流程的典型顺序** —— 但真实旅程不一定按这个顺序走。
# 它只用来给同一时刻的触点排个先后,不作为「应该这样走」的判据。
类型 = ["预约", "跟进", "日程", "量体", "下单"]

# 这一类的多条记录,其实是**一次**触点 —— 按 (日期, 经手人) 合并。
一次多行的类型 = {"量体"}

下一步 = {
    "OK":          "可以算归因",
    "NO_TOUCH":    "这个客户在库里没有留下任何过程 —— **不是「没人管他」**,是没记过",
    "ONLY_ORDER":  "只有下单这一个点,前面的过程没记 —— 算不出谁促成的",
    "NO_OWNER":    "有触点但都没记经手人 —— **这是数据缺口**,不是没人参与",
}


def 去重(触点):
    """把「一次多行」的那几类合并成一次。

    `触点` 是 [{类型, 时间, 经手人, 对象, 备注}, …]。
    合并键是 (类型, 日期, 经手人) —— **时间取那天最早的一条**,
    备注里记上合并了几条。
    """
    出, 合 = [], {}
    for t in 触点 or []:
        if t.get("类型") not in 一次多行的类型:
            出.append(dict(t))
            continue
        键 = (t.get("类型"), (t.get("时间") or "")[:10], t.get("经手人"))
        if 键 not in 合:
            合[键] = dict(t, 条数=1)
        else:
            c = 合[键]
            c["条数"] += 1
            if (t.get("时间") or "") < (c.get("时间") or "9999"):
                c["时间"] = t.get("时间")
                c["对象"] = t.get("对象")
    for c in 合.values():
        n = c.pop("条数")
        c["备注"] = f"{n} 个测量项" if n > 1 else (c.get("备注") or "1 个测量项")
        出.append(c)
    return 出


def 排序(触点):
    """按时间排;同一时刻的按业务流程的典型顺序。

    ⚠️ 时间为空的排在最前面而不是被丢掉 —— **「没有时间」和「很早」不是一回事**,
    丢掉的话那条触点就从旅程里消失了,而旅程看起来还是完整的。
    """
    def 键(x):
        t = x.get("类型")
        return (x.get("时间") or "", 类型.index(t) if t in 类型 else len(类型))
    return sorted(触点 or [], key=键)


def 归一(触点):
    """去重 + 排序 —— 给归因用的那一份。"""
    return 排序(去重(触点))


def 够不够算(旅程):
    """这条旅程能不能拿去算归因。返回 (能不能, 码, 人话)。

    **三种「算不了」的下一步不同**,所以不能合成一个空结果。
    """
    旅 = 旅程 or []
    if not 旅:
        return False, "NO_TOUCH", ("这个客户在库里**没有留下任何过程** —— "
                                   "不是「没人管他」,是**没记过**")
    有人的 = [x for x in 旅 if x.get("经手人")]
    if not 有人的:
        return False, "NO_OWNER", (f"有 {len(旅)} 个触点,但**一个都没记经手人** —— "
                                   f"这是数据缺口,不是没人参与")
    非下单 = [x for x in 有人的 if x.get("类型") != "下单"]
    if not 非下单:
        return False, "ONLY_ORDER", ("只有**下单**这一个点,前面的过程一条都没记 —— "
                                     "算不出是谁促成的")
    return True, "OK", f"{len(有人的)} 个有经手人的触点,能算"


# ── 咬合记录 ────────────────────────────────────────────────────────
咬合 = [
    ("不再给量体去重(一次量体十几条记录被当成十几次触点)", "一次量体算一个触点"),
    ("把「一个触点都没有」和「只有下单」合成一个码", "只有下单算不出"),
    ("排序时把没有时间的触点丢掉(旅程看起来还是完整的)", "没有时间的不许丢"),
]


def _自测():
    G, R, D = "\033[32m", "\033[31m", "\033[0m"
    坏 = []

    def ck(说, 得, want):
        if 得 != want:
            坏.append(f"{说}:要 {want!r},得 {得!r}")

    # ── 🔑 量体去重 ──────────────────────────────────────────
    量 = [dict(类型="量体", 时间=f"2026-09-01 10:0{i}", 经手人="A", 对象=i, 备注="")
          for i in range(9)]
    ck("一次量体算一个触点", len(去重(量)), 1)
    ck("合并之后时间取最早那条", 去重(量)[0]["时间"], "2026-09-01 10:00")
    ck("备注里记上合并了几条", 去重(量)[0]["备注"], "9 个测量项")
    # 同一天**两个人**各量一次 —— 那是两次触点(97 场多人量体就是这种)
    两人 = 量 + [dict(类型="量体", 时间="2026-09-01 11:00", 经手人="B", 对象=99, 备注="")]
    ck("同一天两个人各量一次,算两个触点", len(去重(两人)), 2)
    # 同一个人**两天**各量一次 —— 也是两次
    两天 = 量 + [dict(类型="量体", 时间="2026-09-02 10:00", 经手人="A", 对象=98, 备注="")]
    ck("同一个人两天各量一次,算两个触点", len(去重(两天)), 2)
    # 别的类型不合并 —— 一天打三通跟进就是三次触点
    跟 = [dict(类型="跟进", 时间="2026-09-01 1%d:00" % i, 经手人="A", 对象=i, 备注="")
          for i in range(3)]
    ck("跟进不合并(一天三通就是三次)", len(去重(跟)), 3)

    # ── 排序 ─────────────────────────────────────────────────
    乱 = [dict(类型="下单", 时间="2026-09-03", 经手人="A"),
          dict(类型="预约", 时间="2026-09-01", 经手人="A"),
          dict(类型="量体", 时间="2026-09-02", 经手人="A")]
    ck("按时间排", [x["类型"] for x in 排序(乱)], ["预约", "量体", "下单"])
    同时 = [dict(类型="下单", 时间="2026-09-01", 经手人="A"),
            dict(类型="预约", 时间="2026-09-01", 经手人="A")]
    ck("同一时刻按业务流程顺序", [x["类型"] for x in 排序(同时)], ["预约", "下单"])
    缺 = [dict(类型="跟进", 时间=None, 经手人="A"),
          dict(类型="预约", 时间="2026-09-01", 经手人="A")]
    ck("没有时间的不许丢", len(排序(缺)), 2)
    ck("没有时间的排在最前(不是当成很晚)", 排序(缺)[0]["类型"], "跟进")

    # ── 够不够算 ─────────────────────────────────────────────
    码 = lambda 旅: 够不够算(旅)[1]
    ck("一个触点都没有", 码([]), "NO_TOUCH")
    ck("有触点但都没经手人", 码([dict(类型="预约", 时间="x", 经手人=None)]), "NO_OWNER")
    ck("只有下单算不出", 码([dict(类型="下单", 时间="x", 经手人="A")]), "ONLY_ORDER")
    ck("有预约有下单就能算",
       码([dict(类型="预约", 时间="x", 经手人="A"), dict(类型="下单", 时间="y", 经手人="B")]),
       "OK")
    # **三种「算不了」的说法不许一样** —— 一样就等于没分开
    说 = [够不够算([])[2],
          够不够算([dict(类型="预约", 时间="x", 经手人=None)])[2],
          够不够算([dict(类型="下单", 时间="x", 经手人="A")])[2]]
    if len(set(说)) != 3:
        坏.append("三种「算不了」给了同一句话 —— **那它们就不该分成三种**")
    动作 = list(下一步.values())
    if len(set(动作)) != len(动作):
        坏.append("有两个码的下一步一模一样 —— **那它们就不该是两个码**")

    if 坏:
        print(f"{R}❌ 旅程口径自测 {len(坏)} 条不过{D}")
        for b in 坏:
            print(f"    ❌ {b}")
        return 1
    print(f"{G}✅ 旅程口径自测 16 条全过{D}")
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(_自测())
