# -*- coding: utf-8 -*-
"""订单交付风险分档 —— **全用规则,模型只写建议**(用户 2026-10-25 拍,方案文档工作流三)。

一笔订单 → 已结束 / 不适用 / 无法判断 / 已延期 / 需关注 / 暂无已识别风险。按下面的顺序判,先命中先算:

  ① 标品单                                 → 不适用(标品不走生产,没有交付风险这件事)
  ② 已完成 / 已关闭 / 待收货(工厂已发出)     → 已结束(不派跟踪任务)
  ③ 方案确认中 / 待付款(还没进生产)          → 无法判断,缺「还没进生产,没有承诺完工日」
  ④ 在产,但没有承诺完工日(工厂没回接单 …)   → 无法判断,缺「承诺完工日」—— **不压成低风险**
  ⑤ 今天已过承诺完工日、还没发出            → 已延期(事实,不是预测)
  ⑥ 离承诺完工日 ≤ 临近天数,或在「该催」里   → 需关注
  ⑦ 其余                                   → 暂无已识别风险 —— **不等于保证准时**(方案原话)

临近天数默认 3(方案文档「建议试点:距承诺日期 ≤ 3 个自然日」),**由调用方传**,不写死在这里。
**不自己取当天日期**(CLAUDE.md §9 ①):谁负责判定,谁就不该同时负责取时间,否则同一批数据不同时刻判出两样。
输入是 api.get_order 的返回里用到的那几样(调用方摘出来传),这里不取数。
"""
import datetime as _d

档们 = ("不适用", "已结束", "无法判断", "已延期", "需关注", "暂无已识别风险")
要跟踪的档 = ("已延期", "需关注")      # 只有这两档才可能派「订单跟踪」任务


def 分档(类型, 状态, 承诺完工日, 该催, 今天, 临近天数=3, 该催理由=None):
    """→ {"档", "依据": [...], "缺": [...], "离承诺完工日天数"}。

    类型:订单类型(定制品订单 / 标品订单);状态:PRD 状态(方案确认中 / 待付款 / 待发货 / 待收货 / 已完成 / 已关闭);
    承诺完工日:工厂回传接单时报的那一天(YYYY-MM-DD…),没有就 None;该催:factory_feed.该催 算出的布尔;
    今天:演示世界的今天(YYYY-MM-DD),由调用方给。"""
    依据, 缺 = [], []
    出 = lambda 档, 天=None: {"档": 档, "依据": 依据, "缺": 缺, "离承诺完工日天数": 天}
    if 类型 != "定制品订单":
        依据.append(f"这是{类型 or '未知类型'},不走生产")
        return 出("不适用")
    if 状态 in ("已完成", "已关闭", "待收货"):
        依据.append(f"订单状态是「{状态}」" + (",工厂已经发出" if 状态 == "待收货" else ""))
        return 出("已结束")
    if 状态 in ("方案确认中", "待付款"):
        缺.append(f"订单还在「{状态}」,没进生产,没有承诺完工日")
        return 出("无法判断")
    if 该催 and 该催理由:
        依据.append(f"在「该催工厂」里:{该催理由}")
    if not 承诺完工日:
        缺.append("承诺完工日(工厂还没回接单,或接单时没报日期)")
        return 出("无法判断")
    天 = (_d.date.fromisoformat(str(承诺完工日)[:10]) - _d.date.fromisoformat(str(今天)[:10])).days
    if 天 < 0:
        依据.append(f"承诺完工日 {str(承诺完工日)[:10]} 已经过了 {-天} 天,订单还没发出")
        return 出("已延期", 天)
    if 天 <= int(临近天数) or 该催:
        if 天 <= int(临近天数):
            依据.append(f"离承诺完工日 {str(承诺完工日)[:10]} 还有 {天} 天(临近线 {临近天数} 天)")
        return 出("需关注", 天)
    依据.append(f"离承诺完工日 {str(承诺完工日)[:10]} 还有 {天} 天,没在该催里 —— 这不等于保证准时")
    return 出("暂无已识别风险", 天)
