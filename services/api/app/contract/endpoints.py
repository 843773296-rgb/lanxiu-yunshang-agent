_键 = {(a["方法"], a["路径"]): a for a in 接口表}


def 找(方法, 路径):
    k = (方法, 路径)
    if k not in _键:
        raise KeyError(f"没登记这条接口:{方法} {路径}")
    return _键[k]


def 校验():
    """契约自检:返回问题清单。**空清单才算过。**"""
    坏 = []
    for a in 接口表:
        if a["权限"] not in PM.能力们:
            坏.append(f"{a['方法']} {a['路径']}:点了一条不存在的能力 {a['权限']!r}")
        for c in a["字段权限"]:
            if c not in PM.能力们:
                坏.append(f"{a['方法']} {a['路径']}:字段权限点了不存在的能力 {c!r}")
        if a["形态"] == 异步 and not a["幂等"]:
            # 异步动作几乎都有外部副作用,而超时重发是常态
            坏.append(f"{a['方法']} {a['路径']}:异步动作必须要 Idempotency-Key")
        if a["方法"] == "PATCH" and not a["乐观锁"]:
            坏.append(f"{a['方法']} {a['路径']}:PATCH 必须要 If-Match / expected_revision")
        if a["列表"] and a["方法"] != "GET":
            坏.append(f"{a['方法']} {a['路径']}:只有 GET 能标列表")
        if a["形态"] == 读 and a["审计"]:
            # 审计每一次读会把审计表淹掉,而淹掉的审计等于没有审计
            坏.append(f"{a['方法']} {a['路径']}:读操作不该逐次写审计")
    # ── 闭环:权限矩阵里每条能力都必须被至少一条接口引用 ────────────
    # **一条没有任何地方引用的能力,和一条没实现的能力,在代码上长得一模一样。**
    用过 = {a["权限"] for a in 接口表} | {c for a in 接口表 for c in a["字段权限"]}
    for c in PM.能力们:
        if c not in 用过:
            坏.append(f"能力「{c}」没有任何接口引用它 —— 那就没有任何东西在执行它")
    return 坏
