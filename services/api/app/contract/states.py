# 「我不知道」类状态:**不是终态**,必须能查回真实状态。
不确定状态 = ["状态待核实"]


def 找(名):
    if 名 not in _按名:
        raise KeyError(f"没有这个状态机:{名} —— 现有 {list(_按名)}")
    return _按名[名]


def 能不能走(名, 从, 到):
    """能不能从一个状态走到另一个。**认不出的状态当场抛**,不返回 False ——
    返回 False 的话,拼错一个状态名就等于「这条路不通」,而那是另一回事。"""
    m = 找(名)
    for x in (从, 到):
        if x not in m["状态"]:
            raise ValueError(f"{名} 没有这个状态:{x!r} —— 现有 {m['状态']}")
    return 到 in m["流转"].get(从, [])
