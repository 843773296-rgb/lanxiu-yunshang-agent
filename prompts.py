def assemble(role, have):
    """按调用方**实际挂了哪些工具/能力**装配提示词。

    have:工具名集合,外加能力标记(目前只有「图片」)。
    返回 (提示词文本, [装上的稳定编号])。
    """
    head, rules, foot = ROLES[role]
    have = set(have)
    picked = [r for r in rules
              if all(n in have for n in r.needs) and not any(n in have for n in r.avoid)]
    laws = [r for r in picked if r.scope == "铁律"]
    tips = [r for r in picked if r.scope == "工具"]
    body = "\n\n".join(f"{i}. {r.text}" for i, r in enumerate(laws, 1))
    out = head + "\n" + body + "\n"
    if tips:
        # 工具用法**贴着工具写**,按工具名分组 —— 模型找「这个工具怎么用」时,
        # 落点是工具名,不是「第几条铁律」。
        out += "\n## 手上这几个工具的用法\n\n" + "\n\n".join(
            f"**`{r.needs[0]}`** —— {r.text}" for r in tips) + "\n"
    return out + foot, [r.id for r in picked]


def all_rules(unique=False):
    """unique=True 按对象去重 —— 一条规矩被多个角色复用是**设计**,不是重复。
    编号唯一性要用去重版;覆盖检查要用全量版。"""
    out = [(role, r) for role, (_, rs, _) in ROLES.items() for r in rs]
    if not unique: return out
    seen, uniq = set(), []
    for role, r in out:
        if id(r) in seen: continue
        seen.add(id(r)); uniq.append((role, r))
    return uniq


