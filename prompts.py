#!/usr/bin/env python3
"""提示词的**唯一源头**。

为什么要单独一个文件:同一个「汉服工艺顾问」角色,原来有两份提示词 ——
`agent/chat.py` 里 6 条铁律(后台 8760 的聊天在用),
`agentsite/sdk.py` 里 14 条(工作站 8770 的智能体在用)。
两份手抄件必然漂,而且漂的方向很坏:

  · 评测跑的是 chat.py 那份,**给出的分数评的不是产品**;
  · 后来加的那些铁律(kb_bom 是成本不是售价、kb_fit 不许猜码、版型裁不出来 …)
    只进了长的那份,而这些规矩对两条路径**同样成立**;
  · 反过来,短的那份里有些更细的措辞(hit=0、相容矩阵只录了 6%、
    「仙气」是关键词不是工艺名)长的那份反而丢了。

**同一个事实两个来源,必然漂** —— 这和 `数据规范.md` 里 D1 是同一条教训。

## 为什么不是「把长的那份抄过去」

因为 chat.py 只挂了 10 个 kb_* 工具,没有 get_wearer / get_order / 图片。
把「先用 get_wearer 找到那个孩子」发给一个没有 get_wearer 的模型,
等于让它承诺一件它做不到的事 —— 它会开始编。

所以每条铁律都声明它**依赖哪个工具**(`needs`),
装配时按调用方**实际挂了哪些工具**过滤。工具变了,提示词自动跟着变。

## 编号

对外引用一律用**稳定编号** TL01–TL15,不要用「铁律 3」这种位置编号 ——
位置会随装配变,而且已经乱过一次(sdk.py 里一度是 …11 → 20 → 12 → 13)。
发给模型的文本里仍然重新编成 1…N,因为模型看的是那一份的顺序。
"""

class Rule:
    """一条铁律。

    needs:装了这些工具才发这条 —— 让模型去调一个它没有的工具,它会开始编。
    avoid:装了这些工具就**不**发这条 —— 同一件事换了机制,说法就得换。
          例:V1 用 submit_finding 交结构化结果,V3 出纯文本,
          「按四段写草稿」对前者是错的指令。
    scope:"铁律" 或 "工具"。

      **「这个工具怎么用」不该混在铁律列表里。** 一条规矩如果只在讲某个工具的
      用法(kb_bom 返回的是成本不是售价、kb_fit 判需补量时不许猜码),
      它就该贴在那个工具旁边,而不是当成第 7 条通用戒律 ——
      铁律列表越长,每一条被稀释得越厉害,而工具用法本来就有天然的落点。

      拆解 Accio 时看到的同一个做法:它的 `tool-registry.jsonc` 有个 `notes` 字段,
      内容("Shopify 域内写操作必须先读对应 SKILL.md")会被运行时**注入进工具清单**,
      和工具列表一起给模型看,不进系统提示词的戒律段。

      ⚠️ 诚实说明:这是**结构上的改进,不是已验证的效果改进**。
      现有 20 题评测在 6 道负向题上单跑一遍的波动就有 ±2,分辨不出这种量级的差别。
      改它的理由是「规矩该放在它管的东西旁边」,不是「实测涨分」。
    """
    __slots__ = ("id", "needs", "avoid", "text", "scope")
    def __init__(self, id, needs, text, avoid=(), scope="铁律"):
        self.id, self.needs, self.avoid = id, tuple(needs), tuple(avoid)
        self.text, self.scope = text.strip(), scope


