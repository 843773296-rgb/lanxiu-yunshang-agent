def _reuse(rid):
    """按编号引用已有的规矩对象 —— **复用,不是复制一份**。
    同一条规矩被多个角色装上是设计;抄两份才是隐患(改一份漏一份)。"""
    for _rs in (KB_RULES, TASK_RULES):
        for r in _rs:
            if r.id == rid: return r
    raise KeyError(rid)


